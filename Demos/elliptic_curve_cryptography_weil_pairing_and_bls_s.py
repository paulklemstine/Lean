#!/usr/bin/env python3
"""Numerical demonstrations of bilinear BLS identities in an exponent model.

This is an educational finite-group model, not production cryptography. Source
points are represented by exponents modulo R, while pairing values live in the
order-R subgroup generated by TARGET_GENERATOR modulo TARGET_MODULUS.
"""

from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from typing import Iterable, Sequence

R = 11
TARGET_MODULUS = 23
TARGET_GENERATOR = 2  # has multiplicative order 11 modulo 23
SOURCE_GENERATOR = 1


def source_add(left: int, right: int) -> int:
    """Add two source-group representatives."""
    return (left + right) % R


def scalar_multiply(scalar: int, point: int) -> int:
    """Multiply a source point by a scalar."""
    return (scalar * point) % R


def pairing(left: int, right: int) -> int:
    """Evaluate e(P,Q)=g^(P Q) in the toy target group."""
    exponent = (left * right) % R
    return pow(TARGET_GENERATOR, exponent, TARGET_MODULUS)


def hash_to_source(message: str) -> int:
    """Deterministically map text to a nonzero toy source point."""
    digest = int.from_bytes(sha256(message.encode("utf-8")).digest(), "big")
    return 1 + digest % (R - 1)


@dataclass(frozen=True)
class KeyPair:
    secret: int
    public: int


def keygen(secret: int) -> KeyPair:
    """Construct a toy key pair from a nonzero scalar."""
    normalized = secret % R
    if normalized == 0:
        raise ValueError("the toy secret must be nonzero modulo R")
    return KeyPair(normalized, scalar_multiply(normalized, SOURCE_GENERATOR))


def sign(secret: int, message: str) -> int:
    """Sign a message in the hash-to-source abstraction."""
    return scalar_multiply(secret, hash_to_source(message))


def verify(public_key: int, message: str, signature: int) -> bool:
    """Check e(signature,G)=e(H(message),public_key)."""
    return pairing(signature, SOURCE_GENERATOR) == pairing(
        hash_to_source(message), public_key
    )


def aggregate(signatures: Iterable[int]) -> int:
    """Add any finite family of source-group signatures."""
    total = 0
    for signature in signatures:
        total = source_add(total, signature)
    return total


def aggregate_verify(
    aggregate_signature: int, messages: Sequence[str], public_keys: Sequence[int]
) -> bool:
    """Check the product pairing law for an aggregate signature."""
    if len(messages) != len(public_keys):
        raise ValueError("messages and public keys must have equal lengths")
    right = 1
    for message, public_key in zip(messages, public_keys):
        right = (
            right * pairing(hash_to_source(message), public_key)
        ) % TARGET_MODULUS
    return pairing(aggregate_signature, SOURCE_GENERATOR) == right


def demonstrate_bilinearity() -> None:
    """Exhaustively check e(aP,bQ)=e(P,Q)^(ab) in the toy group."""
    checks = 0
    for a in range(R):
        for b in range(R):
            for point in range(R):
                for other in range(R):
                    left = pairing(
                        scalar_multiply(a, point), scalar_multiply(b, other)
                    )
                    right = pow(pairing(point, other), a * b, TARGET_MODULUS)
                    assert left == right
                    checks += 1
    print(f"Bilinearity: {checks:,} identities checked successfully.")


def demonstrate_signature_and_cdh_extraction() -> None:
    """Show correctness, uniqueness, and fresh-forgery CDH extraction."""
    key = keygen(7)
    message = "fresh checkpoint"
    hash_point = hash_to_source(message)
    signature = sign(key.secret, message)
    assert verify(key.public, message, signature)

    accepted = [candidate for candidate in range(R) if verify(key.public, message, candidate)]
    assert accepted == [signature]

    # Program the fresh message hash as challenge point B. A valid signature is xB.
    challenge_b = hash_point
    cdh_target = scalar_multiply(key.secret, challenge_b)
    assert signature == cdh_target
    print(
        "Signature/CDH: H(m)=%d, public=%d, unique signature=%d=xB."
        % (hash_point, key.public, signature)
    )


def demonstrate_aggregation() -> None:
    """Aggregate several signatures and verify one point against all terms."""
    messages = ["north sensor", "south sensor", "consensus block", "release tag"]
    keys = [keygen(secret) for secret in (3, 8, 6, 9)]
    signatures = [sign(key.secret, message) for key, message in zip(keys, messages)]
    sigma = aggregate(signatures)
    assert all(
        verify(key.public, message, signature)
        for key, message, signature in zip(keys, messages, signatures)
    )
    assert aggregate_verify(sigma, messages, [key.public for key in keys])
    print(f"Aggregation: {len(signatures)} signatures {signatures} -> one point {sigma}.")


def main() -> None:
    demonstrate_bilinearity()
    demonstrate_signature_and_cdh_extraction()
    demonstrate_aggregation()
    print("All educational pairing and BLS demonstrations passed.")


if __name__ == "__main__":
    main()
