#!/usr/bin/env python3
"""
algorithms.py — Core algorithms for analyzing the adjacent-transposition-plus-cycle walk.

Implements:
1. Transition matrix construction for the hybrid walk on S_n
2. Spectral gap computation via eigenvalue decomposition
3. Total variation distance profile computation
4. Observable (cycle displacement) decay tracking
5. Canonical path congestion estimation

Keywords: cutoff phenomenon, symmetric group, Cayley graph, spectral gap,
canonical paths, total variation mixing, sparse matrix computation
"""

import numpy as np
from itertools import permutations
from math import factorial, log, sqrt, pi, cos
from typing import List, Tuple, Dict, Optional


class SymmetricGroupWalk:
    """
    Represents the random walk on S_n generated by adjacent transpositions
    and the long cycle.

    The measure μ_n assigns weight 1/(n+1) to each of:
    - (n-1) adjacent transpositions (i, i+1) for 0 ≤ i < n-1
    - the long cycle (0 1 2 ... n-1)
    - the inverse long cycle (n-1 n-2 ... 1 0)

    Attributes:
        n: Size of the symmetric group S_n
        generators: List of generator permutations (as tuples)
        all_perms: All permutations of {0, ..., n-1}
        perm_to_idx: Dict mapping permutation tuple to index
        transition_matrix: The transition matrix P of the walk
    """

    def __init__(self, n: int):
        """Initialize the walk on S_n.

        Args:
            n: Size of the permutation group. Must be ≥ 2.

        Raises:
            ValueError: If n < 2.

        Complexity:
            Time: O(n! · n) for building the transition matrix
            Space: O(n!²) for storing the transition matrix
        """
        if n < 2:
            raise ValueError(f"n must be at least 2, got {n}")
        self.n = n
        self.N = factorial(n)
        self.generators = self._build_generators()
        self.all_perms = list(permutations(range(n)))
        self.perm_to_idx = {p: i for i, p in enumerate(self.all_perms)}
        self.transition_matrix = self._build_transition_matrix()

    def _build_generators(self) -> List[Tuple[int, ...]]:
        """Build the generator set: adjacent transpositions + long cycle ± inverse.

        Returns:
            List of n+1 generator permutations.

        Complexity: O(n)
        """
        gens = []
        n = self.n
        # Adjacent transpositions
        for i in range(n - 1):
            p = list(range(n))
            p[i], p[i + 1] = p[i + 1], p[i]
            gens.append(tuple(p))
        # Long cycle: i ↦ i+1 mod n
        gens.append(tuple((i + 1) % n for i in range(n)))
        # Inverse: i ↦ i-1 mod n
        gens.append(tuple((i - 1) % n for i in range(n)))
        return gens

    @staticmethod
    def compose(sigma: Tuple[int, ...], tau: Tuple[int, ...]) -> Tuple[int, ...]:
        """Compose permutations: (sigma ∘ tau)(i) = sigma(tau(i)).

        Complexity: O(n)
        """
        return tuple(sigma[tau[i]] for i in range(len(sigma)))

    def _build_transition_matrix(self) -> np.ndarray:
        """Build the N×N transition matrix.

        P[i,j] = μ({g : g·σ_i = σ_j}) where σ_i, σ_j are permutations.

        Complexity: O(n! · (n+1) · n) time, O(n!²) space
        """
        N = self.N
        num_gens = len(self.generators)
        P = np.zeros((N, N))
        for i, sigma in enumerate(self.all_perms):
            for g in self.generators:
                result = self.compose(g, sigma)
                j = self.perm_to_idx[result]
                P[i, j] += 1.0 / num_gens
        return P

    def spectral_data(self) -> Dict[str, float]:
        """Compute spectral data of the transition matrix.

        Returns:
            Dict with keys: 'gap' (spectral gap), 'second_eigenvalue',
            'all_eigenvalues' (sorted descending).

        Complexity: O(n!³) for full eigendecomposition
        """
        eigenvalues = np.sort(np.linalg.eigvalsh(self.transition_matrix))[::-1]
        gap = 1.0 - eigenvalues[1]
        return {
            'gap': gap,
            'second_eigenvalue': eigenvalues[1],
            'all_eigenvalues': eigenvalues.tolist()
        }

    def tv_profile(self, max_steps: Optional[int] = None) -> List[float]:
        """Compute the total variation distance profile from identity.

        Args:
            max_steps: Maximum number of steps. Default: 3n² log n + 10.

        Returns:
            List of TV distances d(t) for t = 0, 1, ..., max_steps.

        Complexity: O(max_steps · n!²) for matrix-vector products
        """
        if max_steps is None:
            max_steps = int(3 * self.n ** 2 * log(max(self.n, 2)) + 10)

        identity = tuple(range(self.n))
        dist = np.zeros(self.N)
        dist[self.perm_to_idx[identity]] = 1.0
        uniform = 1.0 / self.N

        tv_distances = []
        for t in range(max_steps + 1):
            tv = 0.5 * np.sum(np.abs(dist - uniform))
            tv_distances.append(tv)
            dist = dist @ self.transition_matrix
        return tv_distances

    def observable_decay(self, max_steps: Optional[int] = None) -> List[float]:
        """Compute the cycle displacement observable expectation over time.

        F_n(σ) = Σ_j cos(2π(σ(j) - j)/n)

        Args:
            max_steps: Maximum number of steps.

        Returns:
            List of E[F_n(X_t)] for t = 0, 1, ..., max_steps.

        Complexity: O(max_steps · n!²)
        """
        if max_steps is None:
            max_steps = int(3 * self.n ** 2 * log(max(self.n, 2)) + 10)

        n = self.n
        identity = tuple(range(n))
        dist = np.zeros(self.N)
        dist[self.perm_to_idx[identity]] = 1.0

        # Precompute observable values
        obs_values = np.array([
            sum(cos(2 * pi * (sigma[j] - j) / n) for j in range(n))
            for sigma in self.all_perms
        ])

        expectations = []
        for t in range(max_steps + 1):
            expectations.append(float(dist @ obs_values))
            dist = dist @ self.transition_matrix
        return expectations

    def mixing_time(self, epsilon: float = 0.25) -> int:
        """Find the mixing time t_mix(ε).

        Args:
            epsilon: TV distance threshold.

        Returns:
            Smallest t such that d(t) < epsilon.
        """
        tv = self.tv_profile()
        for t, d in enumerate(tv):
            if d < epsilon:
                return t
        return len(tv)

    def canonical_path_length_estimate(self) -> float:
        """Estimate the maximum canonical path length.

        For the hybrid walk, canonical paths use O(n) generators:
        use the long cycle for global repositioning and adjacent
        transpositions for local sorting.

        Returns:
            Estimated maximum path length.
        """
        return 2 * self.n  # O(n) from hybrid strategy

    def canonical_path_congestion_estimate(self) -> float:
        """Estimate the edge congestion of canonical paths.

        Returns:
            Estimated maximum edge congestion.
        """
        return self.n * self.n  # O(n²) from counting overlaps


def analyze_walk(n: int) -> Dict:
    """Complete analysis of the walk on S_n.

    Args:
        n: Size of the symmetric group.

    Returns:
        Dict with spectral data, mixing times, and scaling estimates.
    """
    walk = SymmetricGroupWalk(n)
    spectral = walk.spectral_data()
    tv = walk.tv_profile()
    obs = walk.observable_decay()

    t_mix_25 = next((t for t, d in enumerate(tv) if d < 0.25), len(tv))
    t_mix_50 = next((t for t, d in enumerate(tv) if d < 0.50), len(tv))
    t_mix_75 = next((t for t, d in enumerate(tv) if d < 0.75), len(tv))

    n2_log_n = n * n * log(max(n, 2))

    return {
        'n': n,
        'group_size': walk.N,
        'num_generators': len(walk.generators),
        'spectral_gap': spectral['gap'],
        'gap_times_n_sq': spectral['gap'] * n * n,
        'relaxation_time': 1.0 / spectral['gap'],
        't_mix_25': t_mix_25,
        't_mix_50': t_mix_50,
        't_mix_75': t_mix_75,
        'ratio_25': t_mix_25 / n2_log_n if n >= 2 else float('inf'),
        'ratio_50': t_mix_50 / n2_log_n if n >= 2 else float('inf'),
        'window': (t_mix_25 - t_mix_75) / (n * n) if t_mix_25 > t_mix_75 else 0,
        'tv_profile': tv,
        'observable_decay': obs,
    }


if __name__ == "__main__":
    print("Hybrid Walk Analysis")
    print("=" * 70)
    print(f"{'n':>3} {'|S_n|':>7} {'gap':>10} {'gap·n²':>8} "
          f"{'t_25':>6} {'t_50':>6} {'ratio':>8} {'window':>8}")
    print("-" * 70)

    for n in range(3, 7):
        r = analyze_walk(n)
        print(f"{r['n']:3d} {r['group_size']:7d} {r['spectral_gap']:10.6f} "
              f"{r['gap_times_n_sq']:8.4f} {r['t_mix_25']:6d} {r['t_mix_50']:6d} "
              f"{r['ratio_25']:8.4f} {r['window']:8.4f}")
