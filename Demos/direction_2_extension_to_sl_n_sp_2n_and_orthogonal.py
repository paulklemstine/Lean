def estimate_entangling_power(n: int, p: int, num_samples: int = 500) -> dict:
    """
    Estimate the "entangling power" of random elements in SL_n(F_p).

    The entangling power of a linear map A on F_p^n is measured by
    the number of independent vectors generated by iterating A:
    rank({v, Av, A²v, ..., A^{n-1}v}).

    Certified elements (irreducible charpoly) always achieve rank n
    (the maximum), as proven by the orbit spanning theorem.

    Args:
        n: Matrix dimension
        p: Prime
        num_samples: Number of samples

    Returns:
        Dictionary with entangling power statistics
    """
    np.random.seed(42)
    certified_ranks = []
    uncertified_ranks = []

    for _ in range(num_samples):
        A = sample_random_sl(n, p)
        # Compute rank of [v, Av, A²v, ..., A^{n-1}v] for random v
        v = np.random.randint(0, p, n)
        if np.all(v == 0):
            v[0] = 1

        orbit_matrix = np.zeros((n, n), dtype=int)
        current = v.copy()
        for k in range(n):
            orbit_matrix[:, k] = current % p
            current = mat_mul(A, current.reshape(-1, 1), p).flatten()

        # Compute rank over F_p via row reduction
        rank = _matrix_rank_fp(orbit_matrix, p)

        is_cert = sl_certificate(A, p)
        if is_cert:
            certified_ranks.append(rank)
        else:
            uncertified_ranks.append(rank)

    return {
        "dimension": n,
        "field_size": p,
        "certified_count": len(certified_ranks),
        "uncertified_count": len(uncertified_ranks),
        "certified_avg_rank": (np.mean(certified_ranks) if certified_ranks
                                else None),
        "uncertified_avg_rank": (np.mean(uncertified_ranks) if uncertified_ranks
                                  else None),
        "certified_all_maximal": (all(r == n for r in certified_ranks)
                                   if certified_ranks else None),
        "explanation": (
            f"Certified elements always achieve rank {n} (maximum), "
            f"confirming the orbit spanning theorem."
        )
    }


def _matrix_rank_fp(M: np.ndarray, p: int) -> int:
    """Compute rank of matrix M over F_p."""
    m, n = M.shape
    A = M.copy() % p
    rank = 0
    for col in range(n):
        # Find pivot
        pivot = -1
        for row in range(rank, m):
            if A[row, col] % p != 0:
                pivot = row
                break
        if pivot == -1:
            continue
        A[[rank, pivot]] = A[[pivot, rank]]
        inv = mod_inv(int(A[rank, col]) % p, p)
        A[rank] = (A[rank] * inv) % p
        for row in range(m):
            if row != rank and A[row, col] % p != 0:
                A[row] = (A[row] - A[row, col] * A[rank]) % p
        rank += 1
    return rank


