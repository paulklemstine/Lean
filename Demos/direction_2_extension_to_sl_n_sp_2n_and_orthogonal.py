# Application 3: Classical Group Recognition
# ============================================================

def recognize_group(generators: list, n: int, p: int,
                    num_random: int = 50) -> dict:
    """
    Attempt to recognize if a group generated by given matrices
    is the full SL_n(F_p), using the certificate framework.

    Strategy:
    1. Generate random products of generators
    2. Check if any has irreducible characteristic polynomial
    3. If a certified element is found, the group likely contains SL_n(F_p)

    Args:
        generators: List of n×n matrices over F_p
        n: Matrix dimension
        p: Prime
        num_random: Number of random products to test

    Returns:
        Dictionary with recognition results
    """
    np.random.seed(42)
    certified_found = False
    elements_tested = 0

    for _ in range(num_random):
        # Generate random word in generators
        word_length = np.random.randint(2, 10)
        M = np.eye(n, dtype=int)
        for _ in range(word_length):
            idx = np.random.randint(len(generators))
            M = mat_mul(M, np.array(generators[idx]), p)

        elements_tested += 1
        if mat_det(M, p) == 1 and sl_certificate(M, p):
            certified_found = True
            break

    return {
        "certified_element_found": certified_found,
        "elements_tested": elements_tested,
        "likely_full_group": certified_found,
        "confidence": "high" if certified_found else "inconclusive",
        "explanation": (
            "A certified element (irreducible charpoly) was found, "
            "suggesting the group contains SL_n(F_p) as a subgroup."
            if certified_found else
            "No certified element found in the sample. "
            "The group may be a proper subgroup of SL_n(F_p)."
        )
    }


