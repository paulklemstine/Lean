# Application 2: Cryptographic Verifiable Randomness
# ============================================================

def verifiable_random_element(n: int, p: int) -> dict:
    """
    Generate a verifiably random element of SL_n(F_p) with certificate.

    The certificate (irreducible charpoly) proves that the element
    is "generically placed" in the group — not in any proper subgroup
    that preserves a nontrivial subspace.

    This is useful in cryptographic protocols where a participant must
    prove their random group element is "honestly random."

    Args:
        n: Matrix dimension
        p: Prime field size

    Returns:
        Dictionary with the element and its certificate
    """
    A = sample_certified_sl(n, p, max_attempts=500)
    if A is None:
        return {"success": False, "reason": "No certified element found"}

    cp = _charpoly_direct(A, p)

    return {
        "success": True,
        "matrix": A.tolist(),
        "determinant": mat_det(A, p),
        "charpoly": cp,
        "is_irreducible": is_irreducible(cp, p),
        "dimension": n,
        "field_size": p,
        "certificate_type": "SL_n irreducible charpoly"
    }


