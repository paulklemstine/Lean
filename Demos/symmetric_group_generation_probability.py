"""
Numerical demonstration of the Index-Two Generation Ceiling.

This self-contained script verifies, by exact enumeration, the central result:

    For a finite group G with a proper subgroup H of index two (|G| = 2|H|),
    the number g of ordered pairs (a, b) that generate G satisfies

            4 * g <= 3 * |G|^2,     equivalently   g / |G|^2 <= 3/4.

For the symmetric group S_n the canonical index-two subgroup is the alternating
group A_n (the even permutations, kernel of the sign map). A pair of even
permutations generates only even permutations, so a quarter of all ordered
pairs are doomed -- this is the parity obstruction.

The script:
  1. Builds S_n explicitly as tuples (one-line notation).
  2. Computes the subgroup generated by a set of permutations via orbit closure.
  3. Counts exact generating pairs for small n and prints P(S_n) = g / (n!)^2.
  4. Verifies the both-even obstruction has size exactly (n!)^2 / 4.
  5. Confirms the 3/4 ceiling holds (with equality at n = 2).

All functions use type hints and are inlined; no external dependencies.
"""

from __future__ import annotations

from fractions import Fraction
from itertools import permutations
from math import factorial
from typing import Dict, List, Tuple

Perm = Tuple[int, ...]  # one-line notation: image of (0, 1, ..., n-1)


def identity(n: int) -> Perm:
    """The identity permutation on {0, ..., n-1}."""
    return tuple(range(n))


def compose(p: Perm, q: Perm) -> Perm:
    """Compose permutations: (p . q)(i) = p(q(i))."""
    return tuple(p[q[i]] for i in range(len(p)))


def inverse(p: Perm) -> Perm:
    """The inverse permutation of p."""
    n = len(p)
    inv = [0] * n
    for i in range(n):
        inv[p[i]] = i
    return tuple(inv)


def sign(p: Perm) -> int:
    """Sign of a permutation: +1 if even, -1 if odd (via inversion count)."""
    n = len(p)
    inversions = sum(1 for i in range(n) for j in range(i + 1, n) if p[i] > p[j])
    return 1 if inversions % 2 == 0 else -1


def generated_subgroup(generators: List[Perm], n: int) -> frozenset[Perm]:
    """
    Compute the subgroup of S_n generated by `generators` via breadth-first
    orbit closure: start from the identity, repeatedly multiply by generators
    (and their inverses) until the set stabilizes.
    """
    e = identity(n)
    closure: set[Perm] = {e}
    # Seed with generators and their inverses.
    gens = list(generators) + [inverse(g) for g in generators]
    frontier: List[Perm] = [e]
    while frontier:
        new_frontier: List[Perm] = []
        for x in frontier:
            for g in gens:
                y = compose(g, x)
                if y not in closure:
                    closure.add(y)
                    new_frontier.append(y)
        frontier = new_frontier
    return frozenset(closure)


def count_generating_pairs(n: int) -> int:
    """Count ordered pairs (a, b) in S_n that generate all of S_n."""
    full_size = factorial(n)
    elements: List[Perm] = list(permutations(range(n)))
    g = 0
    for a in elements:
        for b in elements:
            if len(generated_subgroup([a, b], n)) == full_size:
                g += 1
    return g


def count_both_even_pairs(n: int) -> int:
    """Count ordered pairs (a, b) with both a and b even (the parity trap)."""
    elements: List[Perm] = list(permutations(range(n)))
    evens = [p for p in elements if sign(p) == 1]
    return len(evens) ** 2


def generation_report(n: int) -> Dict[str, object]:
    """Assemble the exact generation statistics for S_n."""
    order = factorial(n)
    total_pairs = order * order
    g = count_generating_pairs(n)
    both_even = count_both_even_pairs(n)
    prob = Fraction(g, total_pairs)
    return {
        "n": n,
        "order": order,
        "total_pairs": total_pairs,
        "generating_pairs": g,
        "both_even_pairs": both_even,
        "P": prob,
        "P_float": float(prob),
        "ceiling_ok": 4 * g <= 3 * total_pairs,
        "obstruction_is_quarter": 4 * both_even == total_pairs,
    }


def main() -> None:
    print("=" * 74)
    print("  THE INDEX-TWO GENERATION CEILING:  P(S_n) <= 3/4")
    print("=" * 74)
    header = f"{'n':>2} | {'|S_n|':>6} | {'gen pairs':>10} | {'P(S_n)':>10} | {'P':>7} | 3/4?"
    print(header)
    print("-" * len(header))

    for n in range(2, 6):
        r = generation_report(n)
        p_frac = r["P"]
        print(
            f"{r['n']:>2} | {r['order']:>6} | {r['generating_pairs']:>10} | "
            f"{str(p_frac):>10} | {r['P_float']:>7.4f} | "
            f"{'YES' if r['ceiling_ok'] else 'NO!'}"
        )
        assert r["ceiling_ok"], "Ceiling violated -- mathematics is broken!"
        assert r["obstruction_is_quarter"], "Parity trap is not exactly a quarter!"

    print("-" * len(header))
    print("All ceilings verified.  Equality (P = 3/4) occurs exactly at n = 2.")
    print()
    print("Parity obstruction check:  both-even pairs = (n!)^2 / 4 in every case.")
    for n in range(2, 6):
        be = count_both_even_pairs(n)
        tot = factorial(n) ** 2
        print(f"  n = {n}:  both-even = {be:>7}  vs  (n!)^2/4 = {tot // 4:>7}  "
              f"-> {'match' if be == tot // 4 else 'MISMATCH'}")

    print()
    print("Interpretation:")
    print("  A quarter of all ordered pairs are 'both even' and trapped in A_n,")
    print("  so they can never generate S_n.  Hence at most 3/4 of pairs generate.")


if __name__ == "__main__":
    main()
