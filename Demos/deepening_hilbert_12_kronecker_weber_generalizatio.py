"""
Numerical demonstration of the atomicity theorem for prime-class-number
Hilbert class fields.

Main theorem (in plain mathematical terms):
    Let K be a number field with Hilbert class field H (the maximal unramified
    abelian extension of K). Artin reciprocity gives a canonical isomorphism
        Gal(H/K)  ~=  Cl(O_K)      (the ideal class group),
    hence [H:K] = h_K, the class number. If h_K is PRIME, then H/K has no proper
    intermediate fields: every field L with K <= L <= H equals K or H.

The subfield lattice of H/K is (as an order dual) exactly the subgroup lattice
of the class group Cl(O_K). This file demonstrates the theorem entirely at the
level of finite abelian groups: we model class groups by their invariant
factors, enumerate the subgroup lattice, and confirm that the number of
intermediate fields equals the number of subgroups -- and that this number is 2
(atomic) precisely when the class number is prime and the group is cyclic.

All functions are self-contained; only the Python standard library is used.
"""

from __future__ import annotations

from itertools import product
from math import gcd
from typing import Dict, List, Tuple


# ---------------------------------------------------------------------------
# Primality
# ---------------------------------------------------------------------------
def is_prime(n: int) -> bool:
    """Return True iff n is a prime number (trial division)."""
    if n < 2:
        return False
    i = 2
    while i * i <= n:
        if n % i == 0:
            return False
        i += 1
    return True


# ---------------------------------------------------------------------------
# Finite abelian groups modelling class groups Cl(O_K)
# ---------------------------------------------------------------------------
# A finite abelian group is represented by its invariant factors, e.g.
#   Z/2            -> (2,)
#   Z/4            -> (4,)
#   Z/2 x Z/2      -> (2, 2)
#   Z/2 x Z/6      -> (2, 6)
# Elements are tuples (x_0, ..., x_{k-1}) with 0 <= x_i < factor_i, added
# componentwise modulo the respective factor.
Group = Tuple[int, ...]
Element = Tuple[int, ...]


def group_elements(factors: Group) -> List[Element]:
    """All elements of the abelian group Z/factors[0] x ... x Z/factors[k-1]."""
    ranges = [range(f) for f in factors]
    return [tuple(e) for e in product(*ranges)]


def add(a: Element, b: Element, factors: Group) -> Element:
    """Group addition modulo the invariant factors."""
    return tuple((x + y) % f for x, y, f in zip(a, b, factors))


def subgroup_generated(gens: List[Element], factors: Group) -> frozenset:
    """The subgroup generated by a list of elements (closure under +)."""
    identity = tuple(0 for _ in factors)
    elems = {identity}
    frontier = list(elems)
    while frontier:
        new_frontier = []
        for x in frontier:
            for g in gens:
                y = add(x, g, factors)
                if y not in elems:
                    elems.add(y)
                    new_frontier.append(y)
        frontier = new_frontier
    return frozenset(elems)


def all_subgroups(factors: Group) -> List[frozenset]:
    """Enumerate every subgroup of the finite abelian group (small groups)."""
    elems = group_elements(factors)
    seen = set()
    subgroups: List[frozenset] = []
    # Generate subgroups as closures of subsets of generators. For small groups
    # it suffices to close every subset of elements; we do this incrementally by
    # closing single elements then merging, which stays cheap for |G| small.
    # Start with the trivial subgroup.
    trivial = subgroup_generated([], factors)
    subgroups.append(trivial)
    seen.add(trivial)
    # Grow: repeatedly adjoin one element to each known subgroup.
    changed = True
    while changed:
        changed = False
        for H in list(subgroups):
            for g in elems:
                gens = list(H) + [g]
                new = subgroup_generated(gens, factors)
                if new not in seen:
                    seen.add(new)
                    subgroups.append(new)
                    changed = True
    return subgroups


# ---------------------------------------------------------------------------
# Algorithm A: atomicity decision
# ---------------------------------------------------------------------------
def is_atomic(class_number: int) -> bool:
    """
    Decide whether the Hilbert class field H/K is atomic (no proper
    intermediate fields), given only the class number h_K = [H:K].

    By the main theorem this is equivalent to h_K being prime.
    """
    return is_prime(class_number)


# ---------------------------------------------------------------------------
# Algorithm B: intermediate-field lattice via the class group
# ---------------------------------------------------------------------------
def num_intermediate_fields(factors: Group) -> int:
    """
    Number of intermediate fields of H/K (including K and H), which equals the
    number of subgroups of the class group Cl(O_K) via the Galois correspondence.
    """
    return len(all_subgroups(factors))


def group_order(factors: Group) -> int:
    """Order of the abelian group = class number h_K."""
    n = 1
    for f in factors:
        n *= f
    return n


def is_cyclic(factors: Group) -> bool:
    """A product Z/f_0 x ... is cyclic iff the factors are pairwise coprime."""
    for i in range(len(factors)):
        for j in range(i + 1, len(factors)):
            if gcd(factors[i], factors[j]) != 1:
                return False
    return True


# ---------------------------------------------------------------------------
# Worked examples: imaginary quadratic fields K = Q(sqrt(d))
# ---------------------------------------------------------------------------
# (discriminant/field label, class group invariant factors) from classical tables.
IMAGINARY_QUADRATIC: Dict[str, Group] = {
    "Q(sqrt(-1))": (1,),          # h = 1  (trivial group)
    "Q(sqrt(-5))": (2,),          # h = 2  prime -> atomic
    "Q(sqrt(-6))": (2,),          # h = 2  prime -> atomic
    "Q(sqrt(-23))": (3,),         # h = 3  prime -> atomic (cyclic cubic)
    "Q(sqrt(-31))": (3,),         # h = 3  prime -> atomic
    "Q(sqrt(-14))": (4,),         # h = 4  cyclic Z/4 -> one intermediate field
    "Q(sqrt(-21))": (2, 2),       # h = 4  Z/2 x Z/2 -> genus layering
    "Q(sqrt(-47))": (5,),         # h = 5  prime -> atomic
}


def describe_field(label: str, factors: Group) -> str:
    """Human-readable one-line summary of a field's class-field structure."""
    h = group_order(factors)
    n_sub = num_intermediate_fields(factors)
    n_proper = n_sub - 2  # exclude K and H
    atomic = is_atomic(h)
    grp = "trivial" if h == 1 else " x ".join(f"Z/{f}" for f in factors)
    verdict = (
        "H = K (nothing to extend)" if h == 1
        else "ATOMIC: no intermediate fields" if atomic
        else f"{n_proper} proper intermediate field(s)"
    )
    return (
        f"{label:16s} h_K={h:<2d} Cl(O_K)={grp:14s} "
        f"subgroups={n_sub:<2d}  ->  {verdict}"
    )


def main() -> None:
    print("=" * 78)
    print("Atomicity of prime-class-number Hilbert class fields")
    print("=" * 78)
    print()
    print("Theorem: h_K prime  <=>  H/K has NO proper intermediate fields.")
    print("The intermediate-field lattice of H/K mirrors the subgroup lattice")
    print("of the class group Cl(O_K) (Artin reciprocity + Galois correspondence).")
    print()

    print("-" * 78)
    print("Worked examples over imaginary quadratic fields:")
    print("-" * 78)
    for label, factors in IMAGINARY_QUADRATIC.items():
        print(describe_field(label, factors))
    print()

    print("-" * 78)
    print("Cross-check: prime order  <=>  exactly 2 subgroups  <=>  atomic")
    print("-" * 78)
    for factors in [(2,), (3,), (5,), (7,), (4,), (6,), (9,), (2, 2), (3, 3)]:
        h = group_order(factors)
        n_sub = num_intermediate_fields(factors)
        atomic_by_theorem = is_atomic(h)
        atomic_by_lattice = (n_sub == 2)
        cyclic = is_cyclic(factors)
        assert atomic_by_theorem == atomic_by_lattice, "theorem/lattice mismatch!"
        grp = " x ".join(f"Z/{f}" for f in factors)
        print(
            f"Cl={grp:12s} h={h:<3d} #subgroups={n_sub:<2d} "
            f"cyclic={str(cyclic):5s} atomic={atomic_by_lattice}"
        )
    print()

    print("-" * 78)
    print("Subgroup counts for standard shapes (sanity):")
    print("-" * 78)
    print(f"  Z/p        -> {num_intermediate_fields((5,))} subgroups (expected 2)")
    print(f"  Z/p^2      -> {num_intermediate_fields((9,))} subgroups (expected 3)")
    print(f"  Z/p x Z/p  -> {num_intermediate_fields((3, 3))} subgroups "
          f"(expected p+3 = 6)")
    print()
    print("All assertions passed: prime class number is exactly atomicity.")


if __name__ == "__main__":
    main()
