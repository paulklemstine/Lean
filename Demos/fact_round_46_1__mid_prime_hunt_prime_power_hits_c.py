from __future__ import annotations

import math
from collections import Counter
from itertools import combinations, product
from typing import Dict, Iterable, List, Sequence, Tuple

# --------------------------------------------------------------------------
# Basic arithmetic primitives (all inlined, no external dependencies)
# --------------------------------------------------------------------------


def primes_upto(n: int) -> List[int]:
    """All primes p with p <= n, by a simple sieve of Eratosthenes."""
    if n < 2:
        return []
    sieve = bytearray([1]) * (n + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return [i for i in range(n + 1) if sieve[i]]


def factorize(v: int) -> Dict[int, int]:
    """Prime factorization of v >= 1 as {prime: exponent}."""
    assert v >= 1
    out: Dict[int, int] = {}
    d = 2
    while d * d <= v:
        while v % d == 0:
            out[d] = out.get(d, 0) + 1
            v //= d
        d += 1 if d == 2 else 2
    if v > 1:
        out[v] = out.get(v, 0) + 1
    return out


def big_omega(v: int) -> int:
    """Omega(v): number of prime factors of v counted with multiplicity."""
    return sum(factorize(v).values())


def valuation(v: int, p: int) -> int:
    """The p-adic valuation v_p(v) for v >= 1."""
    assert v >= 1 and p >= 2
    e = 0
    while v % p == 0:
        v //= p
        e += 1
    return e


def is_smooth(B: int, v: int) -> bool:
    """v is B-smooth: every prime factor of v is at most B.  (v >= 1.)"""
    return all(p <= B for p in factorize(v))


def smooth_pool(B: int, x: int) -> List[int]:
    """All B-smooth v with 1 <= v <= x."""
    return [v for v in range(1, x + 1) if is_smooth(B, v)]


def psi(B: int, x: int) -> int:
    """Psi_B(x): the number of B-smooth integers in [1, x]."""
    if x < 1:
        return 0
    return len(smooth_pool(B, x))


def hit_count(B: int, m: int, x: int) -> int:
    """#{v <= x : v is B-smooth and m | v}."""
    return sum(1 for v in smooth_pool(B, x) if v % m == 0)


def primorial(B: int) -> int:
    """P_B = product of all primes <= B."""
    out = 1
    for p in primes_upto(B):
        out *= p
    return out


def sqf_hits(B: int, v: int) -> Tuple[int, ...]:
    """Squarefree hit vector: the factor-base primes dividing v."""
    return tuple(p for p in primes_upto(B) if v % p == 0)


def pow_hits(B: int, v: int) -> Tuple[int, ...]:
    """Prime-power hit vector: the factor-base primes p with p^2 | v."""
    return tuple(p for p in primes_upto(B) if v % (p * p) == 0)


def hit_profile(B: int, v: int, jmax: int) -> Tuple[Tuple[int, int], ...]:
    """The prime-power hit profile of v, truncated at layer jmax."""
    return tuple(
        (p, j)
        for p in primes_upto(B)
        for j in range(1, jmax + 1)
        if v % (p**j) == 0
    )


def is_perfect_square(n: int) -> bool:
    r = math.isqrt(n)
    return r * r == n


def u_param(B: int, x: int) -> float:
    """The smoothness parameter u = log x / log B."""
    return math.log(x) / math.log(B)


