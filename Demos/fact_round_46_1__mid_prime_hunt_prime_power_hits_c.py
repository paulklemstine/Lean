#!/usr/bin/env python3
"""
Algorithm 1 -- Rescaled Hit-Count Evaluation via the Exact Smoothness Bijection.

Computes  hit_B(m; x) = #{v <= x : v is B-smooth and m | v}  WITHOUT enumerating
the hit set, by invoking the exact rescaling identity

        hit_B(m; x) = Psi_B(floor(x / m))          (m > 0 and B-smooth).

The identity is a bijection v <-> v/m, valid because smoothness passes to
divisors (forward map) and is multiplicative (backward map).  The smoothness
hypothesis on m is checked and enforced: for a non-smooth modulus the identity
is FALSE (B = 5, m = 7, x = 100 gives 0 != 10).

Complexity.  Enumerating the pool below y costs O(Psi_B(y) * pi(B)) with the
multiplicative closure generator, and Psi_B(y) is polynomial in log y of degree
pi(B).  Rescaling therefore reduces the work by the factor
Psi_B(x)/Psi_B(x/m) -- and, when a whole family of moduli is queried, memoizing
Psi_B collapses the family to a handful of distinct rescaled bounds.
"""

from __future__ import annotations

from functools import lru_cache
from typing import Dict, List, Tuple


def primes_upto(n: int) -> List[int]:
    """All primes p <= n."""
    if n < 2:
        return []
    sieve = bytearray([1]) * (n + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return [i for i in range(n + 1) if sieve[i]]


def smooth_pool(B: int, x: int) -> List[int]:
    """All B-smooth v in [1, x], generated by closing {1} under the factor base."""
    if x < 1:
        return []
    pool: List[int] = [1]
    for p in primes_upto(B):
        nxt: List[int] = []
        for v in pool:
            w = v
            while w <= x:
                nxt.append(w)
                w *= p
        pool = nxt
    return sorted(pool)


@lru_cache(maxsize=None)
def psi(B: int, x: int) -> int:
    """Psi_B(x): the number of B-smooth integers in [1, x].  Memoized."""
    return len(smooth_pool(B, x))


def is_smooth(B: int, m: int) -> bool:
    """Test B-smoothness of m >= 1 by stripping factor-base primes."""
    if m < 1:
        return False
    for p in primes_upto(B):
        while m % p == 0:
            m //= p
    return m == 1


def hit_count_rescaled(B: int, m: int, x: int) -> int:
    """
    hit_B(m; x) via the exact rescaling identity.

    Raises ValueError if m is not a positive B-smooth modulus, because the
    identity genuinely fails there -- the guard is part of the algorithm.
    """
    if m <= 0:
        raise ValueError("modulus must be positive")
    if not is_smooth(B, m):
        raise ValueError(
            f"modulus {m} is not {B}-smooth; the rescaling identity does not "
            f"apply (e.g. B=5, m=7, x=100 gives 0 != 10)"
        )
    return psi(B, x // m)


def hit_count_bruteforce(B: int, m: int, x: int) -> int:
    """Reference implementation: enumerate the pool and filter.  Slow."""
    return sum(1 for v in smooth_pool(B, x) if v % m == 0)


def hit_table(B: int, x: int, jmax: int = 6) -> Dict[Tuple[int, int], int]:
    """
    The whole prime-power hit table {(p, j) -> hit_B(p^j; x)} for p <= B.
    Every entry is one memoized Psi_B lookup at a rescaled bound.
    """
    out: Dict[Tuple[int, int], int] = {}
    for p in primes_upto(B):
        for j in range(1, jmax + 1):
            m = p**j
            if m > x:
                break
            out[(p, j)] = hit_count_rescaled(B, m, x)
    return out


if __name__ == "__main__":
    B, x = 13, 40000
    print(f"B = {B}, x = {x}, pool size Psi_B(x) = {psi(B, x)}\n")
    print(f"{'p':>3} {'j':>3} {'p^j':>8} {'rescaled':>10} {'brute force':>12}  match")
    print("-" * 56)
    for (p, j), val in sorted(hit_table(B, x, jmax=4).items()):
        ref = hit_count_bruteforce(B, p**j, x)
        print(f"{p:>3} {j:>3} {p**j:>8} {val:>10} {ref:>12}  {'OK' if val == ref else 'FAIL'}")
    print()
    try:
        hit_count_rescaled(5, 7, 100)
    except ValueError as e:
        print("guard fired as required:", e)


#!/usr/bin/env python3
"""
Algorithm 2 -- Telescoping Reconstruction of the Graded Valuation Spectrum.

For a factor-base prime p, computes the FULL multiplicity histogram

        N_j = #{v <= x : v is B-smooth and v_p(v) = j},   j = 0, 1, 2, ...

without factoring a single pool element, using the telescoping identity

        N_j = Psi_B(floor(x / p^j)) - Psi_B(floor(x / p^(j+1))).

The identity follows from the exact rescaling theorem plus the observation that
{v : p^j | v} is a nested decreasing family whose successive differences are
exactly the strata of constant valuation.

Complexity.  The histogram needs only floor(log_p x) + 2 evaluations of Psi_B,
each at a geometrically shrinking bound.  Since Psi_B(x/p^j) shrinks rapidly in
j, the total work is dominated by the single evaluation at j = 0, i.e. it costs
essentially the same as computing Psi_B(x) once -- versus O(Psi_B(x) log x)
for the naive factor-everything approach.

The routine also returns the mean valuation and the total p-adic contribution
sum_v v_p(v), which by the budget decomposition is exactly sum_{j>=1} hit(p^j).
"""

from __future__ import annotations

import math
from functools import lru_cache
from typing import Dict, List, Tuple


def primes_upto(n: int) -> List[int]:
    if n < 2:
        return []
    sieve = bytearray([1]) * (n + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return [i for i in range(n + 1) if sieve[i]]


def smooth_pool(B: int, x: int) -> List[int]:
    if x < 1:
        return []
    pool: List[int] = [1]
    for p in primes_upto(B):
        nxt: List[int] = []
        for v in pool:
            w = v
            while w <= x:
                nxt.append(w)
                w *= p
        pool = nxt
    return sorted(pool)


@lru_cache(maxsize=None)
def psi(B: int, x: int) -> int:
    return len(smooth_pool(B, x))


def graded_spectrum(B: int, p: int, x: int) -> Dict[int, int]:
    """
    The exact valuation histogram {j -> #{v <= x smooth : v_p(v) = j}},
    computed by telescoping rescaled smooth counts.
    """
    if p > B:
        raise ValueError(f"{p} is not in the factor base for B = {B}")
    jmax = int(math.log(x, p)) + 1 if x >= p else 0
    out: Dict[int, int] = {}
    prev = psi(B, x)                     # Psi_B(x / p^0)
    for j in range(0, jmax + 1):
        nxt = psi(B, x // p ** (j + 1))  # Psi_B(x / p^(j+1))
        out[j] = prev - nxt
        prev = nxt
    return out


def spectrum_summary(B: int, p: int, x: int) -> Tuple[Dict[int, int], float, int]:
    """Return (histogram, mean valuation, total p-adic budget sum_v v_p(v))."""
    hist = graded_spectrum(B, p, x)
    pool_size = sum(hist.values())
    total = sum(j * n for j, n in hist.items())
    mean = total / pool_size if pool_size else 0.0
    return hist, mean, total


def verify_against_bruteforce(B: int, p: int, x: int) -> bool:
    """Independent check by direct factorization of every pool element."""
    from collections import Counter

    def val(v: int, q: int) -> int:
        e = 0
        while v % q == 0:
            v //= q
            e += 1
        return e

    ref = Counter(val(v, p) for v in smooth_pool(B, x))
    hist = graded_spectrum(B, p, x)
    keys = set(ref) | set(hist)
    return all(ref.get(k, 0) == hist.get(k, 0) for k in keys)


if __name__ == "__main__":
    B, x = 13, 60000
    for p in (2, 3, 5, 13):
        hist, mean, total = spectrum_summary(B, p, x)
        ok = verify_against_bruteforce(B, p, x)
        shown = ", ".join(f"{j}:{n}" for j, n in sorted(hist.items()) if n)
        print(f"p = {p:>2}  mean v_p = {mean:5.3f}   total p-adic budget = {total:>6}"
              f"   verified: {ok}")
        print(f"        histogram  {shown}")
    # the total p-adic budget summed over p is the whole smoothness budget
    grand = sum(spectrum_summary(B, p, x)[2] for p in primes_upto(B))
    print(f"\nsum over p <= B of the p-adic budget = {grand}"
          "   (= sum over the pool of Omega(v), by the budget decomposition)")


#!/usr/bin/env python3
"""
Algorithm 3 -- Budget Decomposition Audit and Layer Attribution.

The budget decomposition theorem states that, over the B-smooth pool below x,

    sum_{v <= x, v B-smooth} Omega(v)
        = sum_{p <= B} sum_{j = 1}^{floor(log2 x)} hit_B(p^j; x)
        = sum_{p <= B} sum_{j = 1}^{floor(log2 x)} Psi_B(floor(x / p^j)).

This gives a SELF-CHECKING computation of the aggregate smoothness budget by two
independent routes, and -- more usefully -- an exact attribution of the budget
to the graded layers j = 1, 2, 3, ...  The layer j = 1 is precisely what the
squarefree hit features can see; layers j >= 2 are provably invisible to them,
which is the structural reason a prime-power feature adds out-of-sample signal.

Complexity.
  * Direct route: O(Psi_B(x) * pi(B)) integer divisions (factor every element).
  * Rescaled route: pi(B) * floor(log2 x) evaluations of Psi_B at geometrically
    shrinking bounds; with memoization the cost is dominated by the single
    evaluation at the top bound.
Agreement of the two routes is guaranteed by the theorem; any disagreement
localises an implementation bug to a specific (p, j) cell.
"""

from __future__ import annotations

import math
from functools import lru_cache
from typing import Dict, List, NamedTuple, Tuple


def primes_upto(n: int) -> List[int]:
    if n < 2:
        return []
    sieve = bytearray([1]) * (n + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return [i for i in range(n + 1) if sieve[i]]


def smooth_pool(B: int, x: int) -> List[int]:
    if x < 1:
        return []
    pool: List[int] = [1]
    for p in primes_upto(B):
        nxt: List[int] = []
        for v in pool:
            w = v
            while w <= x:
                nxt.append(w)
                w *= p
        pool = nxt
    return sorted(pool)


@lru_cache(maxsize=None)
def psi(B: int, x: int) -> int:
    return len(smooth_pool(B, x))


def valuation(v: int, p: int) -> int:
    e = 0
    while v % p == 0:
        v //= p
        e += 1
    return e


class BudgetAudit(NamedTuple):
    pool_size: int
    budget_direct: int          # sum_v Omega(v), by direct factorization
    budget_rescaled: int        # sum_{p,j} Psi_B(x / p^j)
    layers: Dict[int, int]      # j -> hits contributed at layer j
    cells: Dict[Tuple[int, int], int]   # (p, j) -> hit count
    agrees: bool


def budget_audit(B: int, x: int) -> BudgetAudit:
    """Compute the aggregate budget by both routes and attribute it to layers."""
    ps = primes_upto(B)
    pool = smooth_pool(B, x)

    # route 1: direct factorization of every pool element
    direct = sum(sum(valuation(v, p) for p in ps) for v in pool)

    # route 2: rescaled smooth counts, layer by layer
    J = max(1, int(math.log2(x))) if x >= 2 else 0
    cells: Dict[Tuple[int, int], int] = {}
    layers: Dict[int, int] = {}
    rescaled = 0
    for j in range(1, J + 1):
        layer_total = 0
        for p in ps:
            m = p**j
            if m > x:
                continue
            c = psi(B, x // m)
            cells[(p, j)] = c
            layer_total += c
        if layer_total:
            layers[j] = layer_total
        rescaled += layer_total

    return BudgetAudit(
        pool_size=len(pool),
        budget_direct=direct,
        budget_rescaled=rescaled,
        layers=layers,
        cells=cells,
        agrees=direct == rescaled,
    )


def layer_shares(audit: BudgetAudit) -> Dict[int, float]:
    """Fraction of the total budget attributable to each graded layer."""
    tot = audit.budget_direct
    return {j: c / tot for j, c in audit.layers.items()} if tot else {}


if __name__ == "__main__":
    for B, x in ((5, 20000), (11, 60000), (13, 120000)):
        a = budget_audit(B, x)
        shares = layer_shares(a)
        vis = shares.get(1, 0.0)
        print(f"B = {B:>2}, x = {x:>7}   pool {a.pool_size:>6}   "
              f"budget(direct) {a.budget_direct:>7}   "
              f"budget(rescaled) {a.budget_rescaled:>7}   "
              f"agree: {a.agrees}")
        print(f"    layer j=1 (all the squarefree features see): {vis:6.1%}"
              f"   layers j>=2 (invisible to them): {1 - vis:6.1%}")
        top = ", ".join(f"j={j}:{s:.1%}" for j, s in sorted(shares.items())[:6])
        print(f"    layer shares  {top}\n")


