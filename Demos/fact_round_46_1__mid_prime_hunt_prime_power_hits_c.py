        tot_var = sum((o - mean) ** 2 for o in omegas) / len(omegas)

        def residual_variance(key) -> float:
            groups: Dict[object, List[int]] = {}
            for v in pool:
                groups.setdefault(key(v), []).append(big_omega(v))
            s = 0.0
            for vals in groups.values():
                mu = sum(vals) / len(vals)
                s += sum((o - mu) ** 2 for o in vals)
            return s / len(pool)

        r_sqf = residual_variance(lambda v: sqf_hits(B, v))
        r_pow = residual_variance(lambda v: (sqf_hits(B, v), pow_hits(B, v)))
