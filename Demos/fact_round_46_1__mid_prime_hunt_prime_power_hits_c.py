#!/usr/bin/env python3
"""
The hit fraction as a local logarithmic derivative: a numerical study of the
Dickman-ratio conjecture.

Because a divisibility feature is an exact rescaling,

        hit_B(p^2; x) / Psi_B(x)  =  Psi_B(floor(x/p^2)) / Psi_B(x),

every question about the predictive content of a prime-power feature reduces
to a question about the smooth-counting function Psi_B at two nearby arguments.
The conjecture is that, for fixed B and x -> infinity, this ratio tends to 1
with the sharp second-order rate

        1 - pi(B) * (2 log p) / log x + O((log x)^-2),

which is exactly what the two-sided abundance bracket

        (m+1)^pi(B) <= Psi_B(x) <= (floor(log2 x) + 1)^pi(B)

predicts: the pool grows like c_B (log x)^pi(B), so replacing log x by
log x - 2 log p multiplies the count by (1 - 2 log p / log x)^pi(B).

This script measures the true ratio by brute force and compares it with both
the first-order prediction and the exact power-law surrogate.  No fitting is
performed: the predictions have no free parameters.
"""

from __future__ import annotations

import math
from functools import lru_cache
from typing import List, Tuple


def primes_upto(n: int) -> List[int]:
    if n < 2:
        return []
    sieve = bytearray([1]) * (n + 1)
    sieve[0] = sieve[1] = 0
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return [i for i in range(n + 1) if sieve[i]]


def smooth_pool(B: int, x: int) -> List[int]:
    if x < 1:
        return []
    pool: List[int] = [1]
    for p in primes_upto(B):
        nxt: List[int] = []
        for v in pool:
            w = v
            while w <= x:
                nxt.append(w)
                w *= p
        pool = nxt
    return sorted(pool)


@lru_cache(maxsize=None)
def psi(B: int, x: int) -> int:
    return len(smooth_pool(B, x))


def hit_fraction(B: int, p: int, x: int) -> float:
    """The exact p^2-hit fraction, via the rescaling identity."""
    return psi(B, x // (p * p)) / psi(B, x)


def first_order_prediction(B: int, p: int, x: int) -> float:
    """1 - pi(B) * 2 log p / log x."""
    return 1.0 - len(primes_upto(B)) * 2 * math.log(p) / math.log(x)


def power_law_prediction(B: int, p: int, x: int) -> float:
    """(1 - 2 log p / log x)^pi(B): the exact power-law surrogate."""
    k = len(primes_upto(B))
    base = 1.0 - 2 * math.log(p) / math.log(x)
    return base**k if base > 0 else 0.0


def toll(B: int, p: int) -> float:
    """The budget toll 2 log p / log B, in units of the smoothness parameter u."""
    return 2 * math.log(p) / math.log(B)


def study(B: int, p: int, xs: List[int]) -> None:
    k = len(primes_upto(B))
    print(f"\nB = {B}  (pi(B) = {k}),  p = {p},  budget toll = {toll(B, p):.4f} "
          f"units of u")
    print(f"{'x':>10} {'u':>7} {'Psi_B(x)':>10} {'hit frac':>10} "
          f"{'power law':>11} {'first order':>12} {'|err| pl':>10}")
    print("-" * 78)
    for x in xs:
        f = hit_fraction(B, p, x)
        pl = power_law_prediction(B, p, x)
        fo = first_order_prediction(B, p, x)
        u = math.log(x) / math.log(B)
        print(f"{x:>10} {u:>7.3f} {psi(B, x):>10} {f:>10.4f} {pl:>11.4f} "
              f"{fo:>12.4f} {abs(f - pl):>10.4f}")


def main() -> None:
    print(__doc__)
    xs = [10**3, 10**4, 10**5, 10**6, 10**7]
    for B, p in ((5, 2), (7, 2), (13, 2), (13, 3), (13, 13)):
        study(B, p, xs)

    print("\n" + "=" * 78)
    print("THE TIGHT-u MECHANISM IN ONE TABLE")
    print("=" * 78)
    print("The toll 2 log p / log B is antitone in B, so the SAME p^2-hit removes")
    print("a larger share of the smoothness budget at a smaller factor base.\n")
    print(f"{'B':>10} {'pi(B)':>6} " + "".join(f"{'toll p=' + str(q):>12}"
                                               for q in (2, 3, 5, 7, 13)))
    print("-" * 78)
    for B in (13, 50, 200, 1000, 10**4, 10**6):
        row = "".join(f"{toll(B, q):>12.4f}" for q in (2, 3, 5, 7, 13))
        print(f"{B:>10} {len(primes_upto(B)):>6} {row}")
    print("\nAt B = 13 a 4-hit costs 0.54 units of u; at B = 10^6 it costs 0.10.")
    print("Since the smooth density decays super-exponentially in u, the feature")
    print("carries first-order information only in the tight-u regime.")

    print("\n" + "=" * 78)
    print("SANITY CHECK: THE RATIO IS AN EXACT COUNT, NOT AN ESTIMATE")
    print("=" * 78)
    ok = True
    for B in (5, 7, 11, 13):
        for p in primes_upto(B):
            for x in (5000, 50000):
                lhs = sum(1 for v in smooth_pool(B, x) if v % (p * p) == 0)
                rhs = psi(B, x // (p * p))
                ok &= lhs == rhs
    print(f"brute-force hit counts equal rescaled smooth counts in every case: {ok}")
    print("\nNote on interpretation.  The rescaling identity above is exact and")
    print("unconditional.  The two predicted columns are the CONJECTURED asymptotic")
    print("behaviour, and at the modest x reachable by brute force the O((log x)^-2)")
    print("remainder is still clearly visible -- the power-law surrogate tracks the")
    print("true ratio's shape and improves monotonically with x, while the bare")
    print("first-order form is unusable for large pi(B) at small x.  Establishing")
    print("the asymptotic rigorously requires an asymptotic for Psi_B itself.")


if __name__ == "__main__":
    main()


