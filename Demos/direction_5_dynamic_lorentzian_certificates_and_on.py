def enumerate_spanning_trees(n_vertices, edges):
    """Enumerate all spanning trees of a graph (brute force for small graphs)."""
    trees = []
    need = n_vertices - 1
    for combo in combinations(range(len(edges)), need):
        # Check if this edge set forms a spanning tree
        adj = defaultdict(set)
        for idx in combo:
            u, v = edges[idx]
            adj[u].add(v)
            adj[v].add(u)
        # BFS to check connectivity
        if not adj:
            continue
        visited = set()
        stack = [0]
        while stack:
            node = stack.pop()
            if node in visited:
                continue
            visited.add(node)
            for nb in adj[node]:
                if nb not in visited:
                    stack.append(nb)
        if len(visited) == n_vertices:
            trees.append(combo)
    return trees


