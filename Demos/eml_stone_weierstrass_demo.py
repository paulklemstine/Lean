print("\n" + "=" * 60)
print("Demo 5: Convergence as network size increases")
print("=" * 60)

sizes = [2, 4, 8, 16, 32]
errors = []
for size in sizes:
    pred, _ = fit_eml_network(
        Phi_circle, target_circle, n_exp=size, n_log=size, lr=0.005, steps=2000
    )
    err = np.max(np.abs(pred - target_circle))
    errors.append(err)
    print(f"  {size:2d} exp + {size:2d} log generators: max error = {err:.6f}")

fig2, ax = plt.subplots(figsize=(8, 5))
ax.semilogy(sizes, errors, 'bo-', linewidth=2, markersize=8)
ax.set_xlabel('Number of generators (each type)', fontsize=12)
ax.set_ylabel('Max approximation error', fontsize=12)
ax.set_title('EML Convergence on S¹: Error vs. Network Size', fontsize=13, fontweight='bold')
ax.grid(True, alpha=0.3)
plt.savefig('demos/eml_convergence.png', dpi=150, bbox_inches='tight')
