"""
EML Stone–Weierstrass Theorem: Demonstration on Compact Hausdorff Spaces

This demo illustrates the EML universal approximation theorem by showing that
EML networks (built from exponential and logistic generators composed with
continuous point-separating features) can approximate arbitrary continuous
functions on compact spaces.

We demonstrate on:
  1. The circle S¹ (a compact manifold, not a subset of ℝ)
  2. The 2-sphere S² (a compact surface)
  3. A torus T² (product of circles)

In each case, we choose a continuous point-separating family Φ and show that
the EML subalgebra generated by {exp(w·Φ+b), σ(w·Φ+b)} approximates target
functions to arbitrary precision.
"""

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec

# --- EML building blocks ---

def logistic(x):
    """Logistic activation σ(x) = 1/(1+exp(-x))."""
    return 1.0 / (1.0 + np.exp(-np.clip(x, -500, 500)))

def eml_exp_gen(Phi, w, b):
    """Exponential generator: exp(∑ wᵢ Φᵢ(x) + b)."""
    return np.exp(np.clip(Phi @ w + b, -500, 500))

def eml_logistic_gen(Phi, w, b):
    """Logistic generator: σ(∑ wᵢ Φᵢ(x) + b)."""
    return logistic(Phi @ w + b)


def fit_eml_network(Phi, target, n_exp=8, n_log=8, lr=0.01, steps=2000):
    """
    Fit an EML network to a target function by gradient descent.
    Uses a simple architecture: sum of weighted exp and logistic generators.
    """
    n_features = Phi.shape[1]
    np.random.seed(42)

    # Initialize parameters
    w_exp = np.random.randn(n_exp, n_features) * 0.3
    b_exp = np.random.randn(n_exp) * 0.3
    c_exp = np.random.randn(n_exp) * 0.1

    w_log = np.random.randn(n_log, n_features) * 1.0
    b_log = np.random.randn(n_log) * 0.5
    c_log = np.random.randn(n_log) * 0.1

    bias = 0.0

    for step in range(steps):
        # Forward pass
        pred = np.zeros(len(target)) + bias
        exp_gens = []
        log_gens = []
        for k in range(n_exp):
            g = eml_exp_gen(Phi, w_exp[k], b_exp[k])
            exp_gens.append(g)
            pred += c_exp[k] * g
        for k in range(n_log):
            g = eml_logistic_gen(Phi, w_log[k], b_log[k])
            log_gens.append(g)
            pred += c_log[k] * g

        residual = pred - target
        loss = np.mean(residual**2)

        # Gradient descent
        n = len(target)
        grad_bias = 2 * np.mean(residual)
        bias -= lr * grad_bias

        for k in range(n_exp):
            g = exp_gens[k]
            dc = 2 * np.mean(residual * g)
            c_exp[k] -= lr * dc
            dg = residual * c_exp[k] * g
            dw = 2 * np.mean(dg[:, None] * Phi, axis=0)
            db = 2 * np.mean(dg)
            w_exp[k] -= lr * 0.1 * dw
            b_exp[k] -= lr * 0.1 * db

        for k in range(n_log):
            g = log_gens[k]
            sig_deriv = g * (1 - g)
            dc = 2 * np.mean(residual * g)
            c_log[k] -= lr * dc
            dg = residual * c_log[k] * sig_deriv
            dw = 2 * np.mean(dg[:, None] * Phi, axis=0)
            db = 2 * np.mean(dg)
            w_log[k] -= lr * dw
            b_log[k] -= lr * db

        if step % 500 == 0:
            print(f"  Step {step:4d}: loss = {loss:.6f}")

    # Final prediction
    pred = np.zeros(len(target)) + bias
    for k in range(n_exp):
        pred += c_exp[k] * eml_exp_gen(Phi, w_exp[k], b_exp[k])
    for k in range(n_log):
        pred += c_log[k] * eml_logistic_gen(Phi, w_log[k], b_log[k])

    return pred, loss


# ============================================================
# Demo 1: Approximation on the circle S¹
# ============================================================
print("=" * 60)
print("Demo 1: EML approximation on the circle S¹")
print("=" * 60)

N = 500
theta = np.linspace(0, 2*np.pi, N, endpoint=False)

# Point-separating features: Φ = (cos θ, sin θ)
Phi_circle = np.column_stack([np.cos(theta), np.sin(theta)])

# Target: a non-trivial continuous function on S¹
target_circle = np.cos(3*theta) + 0.5 * np.sin(5*theta) + np.cos(theta)**2

print("Fitting EML network to f(θ) = cos(3θ) + 0.5·sin(5θ) + cos²(θ) on S¹...")
pred_circle, loss_circle = fit_eml_network(
    Phi_circle, target_circle, n_exp=12, n_log=12, lr=0.005, steps=3000
)
print(f"  Final L² error: {np.sqrt(np.mean((pred_circle - target_circle)**2)):.6f}")
print(f"  Max error: {np.max(np.abs(pred_circle - target_circle)):.6f}")

# ============================================================
# Demo 2: Approximation on the 2-sphere S²
# ============================================================
print("\n" + "=" * 60)
print("Demo 2: EML approximation on the 2-sphere S²")
print("=" * 60)

N_sphere = 800
indices = np.arange(0, N_sphere) + 0.5
phi_s = np.arccos(1 - 2 * indices / N_sphere)
theta_s = np.pi * (1 + 5**0.5) * indices

x_s = np.sin(phi_s) * np.cos(theta_s)
y_s = np.sin(phi_s) * np.sin(theta_s)
z_s = np.cos(phi_s)

# Point-separating features: Φ = (x, y, z)
Phi_sphere = np.column_stack([x_s, y_s, z_s])

# Target: spherical harmonic Y₂₀ ∝ 3z² - 1
target_sphere = 3 * z_s**2 - 1

print("Fitting EML network to Y₂₀(x,y,z) = 3z² - 1 on S²...")
pred_sphere, loss_sphere = fit_eml_network(
    Phi_sphere, target_sphere, n_exp=15, n_log=15, lr=0.003, steps=3000
)
print(f"  Final L² error: {np.sqrt(np.mean((pred_sphere - target_sphere)**2)):.6f}")
print(f"  Max error: {np.max(np.abs(pred_sphere - target_sphere)):.6f}")

# ============================================================
# Demo 3: Approximation on the torus T²
# ============================================================
print("\n" + "=" * 60)
print("Demo 3: EML approximation on the torus T² = S¹ × S¹")
print("=" * 60)

N_torus = 40
u_grid = np.linspace(0, 2*np.pi, N_torus, endpoint=False)
v_grid = np.linspace(0, 2*np.pi, N_torus, endpoint=False)
U, V = np.meshgrid(u_grid, v_grid)
u_flat = U.flatten()
v_flat = V.flatten()

Phi_torus = np.column_stack([
    np.cos(u_flat), np.sin(u_flat),
    np.cos(v_flat), np.sin(v_flat)
])

target_torus = np.cos(u_flat) * np.sin(v_flat) + np.cos(2*u_flat - v_flat)

print("Fitting EML network to f(u,v) = cos(u)sin(v) + cos(2u-v) on T²...")
pred_torus, loss_torus = fit_eml_network(
    Phi_torus, target_torus, n_exp=15, n_log=15, lr=0.003, steps=3000
)
print(f"  Final L² error: {np.sqrt(np.mean((pred_torus - target_torus)**2)):.6f}")
print(f"  Max error: {np.max(np.abs(pred_torus - target_torus)):.6f}")

# ============================================================
# Point Separation Demonstration
# ============================================================
print("\n" + "=" * 60)
print("Demo 4: Point separation by EML generators")
print("=" * 60)

print("\nShowing exp generators separate points on S¹:")
pairs = [(0.3, 1.7), (np.pi/4, 3*np.pi/4), (0.0, np.pi)]
for t1, t2 in pairs:
    phi1 = np.array([np.cos(t1), np.sin(t1)])
    phi2 = np.array([np.cos(t2), np.sin(t2)])
    w = np.array([1.0, 0.0])
    val1 = np.exp(w @ phi1)
    val2 = np.exp(w @ phi2)
    print(f"  θ₁={t1:.2f}, θ₂={t2:.2f}: exp(cos θ₁)={val1:.6f}, exp(cos θ₂)={val2:.6f}, "
          f"separated={'Yes' if abs(val1-val2) > 1e-10 else 'No'}")

