#!/usr/bin/env python3
"""Numerical demonstrations for additive Steiner completion on (Z/3Z)^2.

The program uses only the Python standard library.  It enumerates the twelve
Steiner blocks, verifies unique pair completion and translation covariance,
and checks that every 2-by-2 linear map over Z/3Z preserves completion.
"""

from __future__ import annotations

from itertools import combinations, product
from typing import Callable, Dict, Iterable, List, Set, Tuple

Point = Tuple[int, int]
Block = Tuple[Point, Point, Point]
Matrix = Tuple[Tuple[int, int], Tuple[int, int]]
MODULUS = 3
POINTS: Tuple[Point, ...] = tuple(product(range(MODULUS), repeat=2))


def add(x: Point, y: Point) -> Point:
    """Add two points coordinatewise modulo three."""
    return ((x[0] + y[0]) % MODULUS, (x[1] + y[1]) % MODULUS)


def neg(x: Point) -> Point:
    """Return the additive inverse of a point."""
    return ((-x[0]) % MODULUS, (-x[1]) % MODULUS)


def third(x: Point, y: Point) -> Point:
    """Return the canonical third point T(x,y)=-(x+y)."""
    return neg(add(x, y))


def translate(x: Point, t: Point) -> Point:
    """Translate x by t."""
    return add(x, t)


def canonical_block(x: Point, y: Point) -> Block:
    """Return a sorted, hashable representation of the completed block."""
    values = sorted((x, y, third(x, y)))
    return (values[0], values[1], values[2])


def enumerate_blocks() -> Set[Block]:
    """Enumerate all distinct blocks generated by pairs of distinct points."""
    return {canonical_block(x, y) for x, y in combinations(POINTS, 2)}


def pair_multiplicities(blocks: Iterable[Block]) -> Dict[Tuple[Point, Point], int]:
    """Count how often each unordered pair occurs among the supplied blocks."""
    counts: Dict[Tuple[Point, Point], int] = {}
    for block in blocks:
        for x, y in combinations(block, 2):
            pair = tuple(sorted((x, y)))
            counts[pair] = counts.get(pair, 0) + 1
    return counts


def apply_matrix(matrix: Matrix, x: Point) -> Point:
    """Apply a 2-by-2 matrix over Z/3Z to x."""
    return (
        (matrix[0][0] * x[0] + matrix[0][1] * x[1]) % MODULUS,
        (matrix[1][0] * x[0] + matrix[1][1] * x[1]) % MODULUS,
    )


def all_matrices() -> Iterable[Matrix]:
    """Generate all 81 two-by-two matrices over Z/3Z."""
    for a, b, c, d in product(range(MODULUS), repeat=4):
        yield ((a, b), (c, d))


def verify_steiner_system() -> None:
    """Check unique completion, nondegeneracy, and the twelve-block count."""
    blocks = enumerate_blocks()
    assert len(blocks) == 12
    counts = pair_multiplicities(blocks)
    assert len(counts) == 36
    assert all(multiplicity == 1 for multiplicity in counts.values())
    for x, y in combinations(POINTS, 2):
        z = third(x, y)
        assert len({x, y, z}) == 3
        assert add(add(x, y), z) == (0, 0)


def verify_translation_covariance() -> None:
    """Check T(x+t,y+t)=T(x,y)+t for every one of 729 triples."""
    for x, y, t in product(POINTS, repeat=3):
        left = third(translate(x, t), translate(y, t))
        right = translate(third(x, y), t)
        assert left == right


def verify_linear_preservation() -> None:
    """Check completion preservation for all 81 linear maps and 81 pairs."""
    for matrix in all_matrices():
        f: Callable[[Point], Point] = lambda x, m=matrix: apply_matrix(m, x)
        for x, y in product(POINTS, repeat=2):
            assert f(third(x, y)) == third(f(x), f(y))


def print_block_table(blocks: Iterable[Block]) -> None:
    """Print blocks in a stable human-readable order."""
    print("The 12 additive Steiner blocks on (Z/3Z)^2:")
    for index, block in enumerate(sorted(blocks), start=1):
        print(f"  {index:2d}: {block}")


def main() -> None:
    verify_steiner_system()
    verify_translation_covariance()
    verify_linear_preservation()
    blocks = enumerate_blocks()
    print_block_table(blocks)
    print("\nChecks completed:")
    print("  - 9 points and 12 distinct blocks")
    print("  - every one of 36 unordered pairs occurs exactly once")
    print("  - translation covariance holds in all 729 cases")
    print("  - all 81 linear maps preserve completion for all 81 ordered pairs")


if __name__ == "__main__":
    main()
