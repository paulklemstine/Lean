"""
demo.py — Numerical demonstrations for
"EML Universal Approximation on the Unit Cube: Density of Coordinate-Exponential
Algebras and Depth Compression of Monomials".

This script is fully self-contained (standard library only, plus the ubiquitous
NumPy) and illustrates the four headline results:

  1. eml_dense_unitCube / eml_approx_unitCube — exponential-polynomial features
     {x -> exp(<k, x>)} approximate continuous targets on [0,1]^n uniformly, with
     error shrinking as the feature set is enriched.
  2. coordExp_bounds_unitCube — each shallow feature exp(x_i) lies in [1, e].
  3. monoNaive vs monoExpLog — two exact representations of x^n: depth n vs depth 3.
  4. eml_depth_compression / eml_depth_unbounded_gap — the depth gap n - 3 grows
     without bound while both representations agree on (0, infinity).

Run:  python demo.py
"""

from __future__ import annotations

import itertools
import math
from typing import Callable, Iterable, List, Sequence, Tuple

import numpy as np


# ----------------------------------------------------------------------------- #
# 1. Coordinate exponential features and exponential-polynomial approximation   #
# ----------------------------------------------------------------------------- #
def exp_poly_features(X: np.ndarray, multi_indices: Sequence[Tuple[int, ...]]) -> np.ndarray:
    """Design matrix of exponential-monomial features.

    For each sample x (a row of X) and each multi-index k, the feature is
        Phi[x, k] = exp(<k, x>) = prod_i exp(k_i * x_i).
    These span the EML subalgebra generated by {x -> exp(x_i)} (Definition 2.5).

    Args:
        X: array of shape (m, n); m sample points in the cube [0,1]^n.
        multi_indices: finite set S subset of N^n indexing the features.

    Returns:
        Phi: array of shape (m, |S|).
    """
    K = np.asarray(multi_indices, dtype=float)          # (|S|, n)
    return np.exp(X @ K.T)                               # exp(<k, x>) for all k


def fit_exp_poly(
    f: Callable[[np.ndarray], np.ndarray],
    n: int,
    max_degree: int,
    grid_per_axis: int = 11,
) -> Tuple[np.ndarray, List[Tuple[int, ...]], float]:
    """Least-squares exponential-polynomial fit of f on a grid over [0,1]^n.

    Realizes the constructive content of eml_approx_unitCube: solve
    min_c || Phi c - f ||_2 over the exponential-monomial features.

    Args:
        f: target function, mapping (m, n) -> (m,).
        n: input dimension.
        max_degree: include all multi-indices k with sum(k) <= max_degree.
        grid_per_axis: number of grid points per coordinate.

    Returns:
        (coeffs, multi_indices, max_abs_error) where max_abs_error is the
        sup-norm residual measured on the grid.
    """
    axis = np.linspace(0.0, 1.0, grid_per_axis)
    X = np.array(list(itertools.product(axis, repeat=n)), dtype=float)  # (m, n)
    y = f(X)

    multi_indices = [
        k
        for k in itertools.product(range(max_degree + 1), repeat=n)
        if sum(k) <= max_degree
    ]
    Phi = exp_poly_features(X, multi_indices)
    coeffs, *_ = np.linalg.lstsq(Phi, y, rcond=None)
    residual = Phi @ coeffs - y
    return coeffs, multi_indices, float(np.max(np.abs(residual)))


def demo_density() -> None:
    print("=" * 72)
    print("1. Density: exponential-polynomial approximation on [0,1]^n")
    print("=" * 72)

    # A genuinely nonlinear 2-D target on the unit square.
    def target(X: np.ndarray) -> np.ndarray:
        return np.sin(3.0 * X[:, 0]) * (X[:, 1] ** 2) + np.cos(2.0 * X[:, 0] * X[:, 1])

    print(f"{'max_degree':>11} | {'#features':>9} | {'sup-norm error':>15}")
    print("-" * 42)
    for d in range(1, 7):
        _, idx, err = fit_exp_poly(target, n=2, max_degree=d, grid_per_axis=15)
        print(f"{d:>11} | {len(idx):>9} | {err:>15.3e}")
    print("Uniform error decreases as the feature set grows -> density.\n")


# ----------------------------------------------------------------------------- #
# 2. Shallow-feature range bound  1 <= exp(x_i) <= e                             #
# ----------------------------------------------------------------------------- #
def demo_feature_bounds() -> None:
    print("=" * 72)
    print("2. Shallow-feature bounds: exp(x_i) in [1, e] for x_i in [0,1]")
    print("=" * 72)
    samples = np.random.default_rng(0).uniform(0.0, 1.0, size=(100_000,))
    vals = np.exp(samples)
    print(f"min exp(x_i) observed = {vals.min():.6f}  (lower bound 1)")
    print(f"max exp(x_i) observed = {vals.max():.6f}  (upper bound e = {math.e:.6f})")
    assert vals.min() >= 1.0 - 1e-12 and vals.max() <= math.e + 1e-12
    print("All shallow features confined to [1, e] as proven.\n")


# ----------------------------------------------------------------------------- #
# 3 & 4. Depth: naive monomial (depth n) vs exp/log monomial (depth 3)          #
# ----------------------------------------------------------------------------- #
def mono_naive_eval(x: float, n: int) -> float:
    """Naive representation x^n = x * x * ... * x (n factors)."""
    acc = 1.0
    for _ in range(n):
        acc *= x
    return acc


def mono_naive_depth(n: int) -> int:
    """Depth of the right-nested product of n copies of x."""
    return n


def mono_explog_eval(x: float, n: int) -> float:
    """exp/log representation x^n = exp(n * log x) on (0, infinity)."""
    return math.exp(n * math.log(x))


def mono_explog_depth(n: int) -> int:
    """Depth of exp(n * log x): the constant 3, independent of n."""
    return 3


def demo_depth() -> None:
    print("=" * 72)
    print("3 & 4. Depth compression of monomials x^n on (0, infinity)")
    print("=" * 72)
    rng = np.random.default_rng(1)
    xs = rng.uniform(0.1, 3.0, size=5)
    print("Agreement check (both equal x^n):")
    for x in xs:
        for n in (4, 7, 12):
            a = mono_naive_eval(float(x), n)
            b = mono_explog_eval(float(x), n)
            assert math.isclose(a, b, rel_tol=1e-9), (x, n, a, b)
    print("  naive == exp/log == x^n verified for sampled (x, n).\n")

    print(f"{'degree n':>9} | {'depth naive':>12} | {'depth exp/log':>14} | {'gap n-3':>8}")
    print("-" * 52)
    for n in (4, 8, 16, 32, 64, 128):
        dn, de = mono_naive_depth(n), mono_explog_depth(n)
        print(f"{n:>9} | {dn:>12} | {de:>14} | {dn - de:>8}")
    print("exp/log depth stays at 3; the gap n-3 grows without bound.\n")


def main() -> None:
    demo_density()
    demo_feature_bounds()
    demo_depth()
    print("All demonstrations completed successfully.")


if __name__ == "__main__":
    main()
