#!/usr/bin/env python3
"""
The Galois/Frobenius side channel: numerical demonstrations.

Every quantity below is an *exact* Shannon quantity on a finite, uniformly weighted
sample space (a finite Galois group, or a product of copies of it).  Groups are
realised as permutation groups, so the "splitting type" of a prime is the cycle
type of its Frobenius element acting on the roots of a defining polynomial.

Sections
  1. The abelianization cap      I(residue ; type) <= log2 [G : G']
  2. Data processing             post-processing never increases a channel
  3. The Frobenius one-time pad  readouts of sigma_p sigma_q say nothing about sigma_p
  4. Posterior = prior, and the pad breaking once the cofactor is revealed
  5. The which-factor wall       exactly one hidden bit, exactly zero leaked
  6. The multi-prime wall        log2(m+1) hidden bits, zero leaked
  7. The semiprime ledger        pure synergy in the S4 and D4 quartic fields

Run:  python3 demo.py
"""
from __future__ import annotations

import random
from collections import Counter
from fractions import Fraction
from itertools import permutations, product
from math import log2
from typing import Callable, Dict, Hashable, Iterable, List, Sequence, Set, Tuple, TypeVar

Perm = Tuple[int, ...]
T = TypeVar("T")

# ---------------------------------------------------------------------------
# Permutation groups
# ---------------------------------------------------------------------------


def mul(a: Perm, b: Perm) -> Perm:
    """Composition a o b (apply b first)."""
    return tuple(a[b[i]] for i in range(len(b)))


def inv(a: Perm) -> Perm:
    r = [0] * len(a)
    for i, x in enumerate(a):
        r[x] = i
    return tuple(r)


def identity(n: int) -> Perm:
    return tuple(range(n))


def generate(gens: Sequence[Perm]) -> Set[Perm]:
    """Subgroup generated by gens (closure under right multiplication)."""
    e = identity(len(gens[0]))
    group: Set[Perm] = {e}
    frontier: List[Perm] = [e]
    while frontier:
        new: List[Perm] = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in group:
                    group.add(y)
                    new.append(y)
        frontier = new
    return group


def derived_subgroup(G: Set[Perm]) -> Set[Perm]:
    n = len(next(iter(G)))
    comms = [mul(mul(a, b), mul(inv(a), inv(b))) for a in G for b in G]
    return generate(comms) if comms else {identity(n)}


def cycle_type(p: Perm) -> Tuple[int, ...]:
    """Splitting type of a prime with Frobenius p: the multiset of cycle lengths."""
    seen: Set[int] = set()
    lengths: List[int] = []
    for i in range(len(p)):
        if i in seen:
            continue
        j, length = i, 0
        while j not in seen:
            seen.add(j)
            j = p[j]
            length += 1
        lengths.append(length)
    return tuple(sorted(lengths))


def coset_readout(N: Set[Perm]) -> Callable[[Perm], Perm]:
    """Residue readout: g -> canonical representative of the coset gN."""
    return lambda g: min(mul(g, n) for n in N)


def conj_class_readout(G: Set[Perm]) -> Callable[[Perm], Perm]:
    """Artin-symbol readout: g -> canonical representative of its G-conjugacy class."""
    return lambda g: min(mul(mul(h, g), inv(h)) for h in G)


# Standard Galois groups of low-degree fields, as permutation groups.
S3: Set[Perm] = set(permutations(range(3)))
S4: Set[Perm] = set(permutations(range(4)))
A4: Set[Perm] = derived_subgroup(S4)
D4: Set[Perm] = generate([(1, 2, 3, 0), (2, 1, 0, 3)])
V4: Set[Perm] = generate([(1, 0, 3, 2), (2, 3, 0, 1)])
C4: Set[Perm] = generate([(1, 2, 3, 0)])
GROUPS: Dict[str, Set[Perm]] = {"S3": S3, "S4": S4, "A4": A4, "D4": D4, "V4": V4, "C4": C4}

# ---------------------------------------------------------------------------
# Finite Shannon calculus on a uniform sample space
# ---------------------------------------------------------------------------


def entropy(values: Iterable[Hashable]) -> float:
    vals = list(values)
    n = len(vals)
    return -sum((c / n) * log2(c / n) for c in Counter(vals).values())


def mutual_info(space: Sequence[T], f: Callable[[T], Hashable], g: Callable[[T], Hashable]) -> float:
    """I(f ; g) = H(f) + H(g) - H(f, g) under the uniform law on `space`."""
    fs = [f(w) for w in space]
    gs = [g(w) for w in space]
    return entropy(fs) + entropy(gs) - entropy(list(zip(fs, gs)))


def cells_factor(space: Sequence[T], f: Callable[[T], Hashable], g: Callable[[T], Hashable]) -> bool:
    """Exact integer test of the independence law: #{f=a,g=b}*|S| == #{f=a}*#{g=b}."""
    joint = Counter((f(w), g(w)) for w in space)
    cf = Counter(f(w) for w in space)
    cg = Counter(g(w) for w in space)
    n = len(space)
    return all(joint.get((a, b), 0) * n == cf[a] * cg[b] for a in cf for b in cg)


def fmt(x: float) -> str:
    return f"{0.0 if abs(x) < 1e-12 else x:.6f}"


# ---------------------------------------------------------------------------
# 1. The abelianization cap
# ---------------------------------------------------------------------------


def demo_cap() -> None:
    print("=" * 78)
    print("1. THE ABELIANIZATION CAP   I(residue ; type) <= log2 [G : G']")
    print("=" * 78)
    idx_hdr = "[G:G']"
    print(f"{'G':>3} {'|G|':>4} {idx_hdr:>6} {'cap':>9} {'I(c;cycle type)':>16} {'I(c;Artin class)':>17}")
    for name, G in GROUPS.items():
        space = sorted(G)
        N = derived_subgroup(G)
        c = coset_readout(N)
        index = len(G) // len(N)
        cap = log2(index)
        i_type = mutual_info(space, c, cycle_type)
        i_class = mutual_info(space, c, conj_class_readout(G))
        assert i_type <= cap + 1e-12 and i_class <= cap + 1e-12
        print(f"{name:>3} {len(G):>4} {index:>6} {fmt(cap):>9} {fmt(i_type):>16} {fmt(i_class):>17}")
    print("  The cap is attained exactly when the readout determines the residue class:")
    print("  the Artin class always does (cosets of G' are unions of classes); the cycle")
    print("  type does in S3 and S4 but not in A4 or D4.  An S4 quartic field, with five")
    print("  splitting types, still pushes at most ONE bit through the residue channel.\n")


# ---------------------------------------------------------------------------
# 2. Data processing
# ---------------------------------------------------------------------------


def demo_data_processing() -> None:
    print("=" * 78)
    print("2. DATA PROCESSING   I(psi o f ; phi o g) <= I(f ; g)")
    print("=" * 78)
    rng = random.Random(1)
    space = sorted(D4)
    c = coset_readout(derived_subgroup(D4))
    base = mutual_info(space, c, cycle_type)
    reps = sorted({c(g) for g in space})
    types = sorted({cycle_type(g) for g in space})
    worst = 0.0
    for _ in range(200):
        psi = {r: rng.randrange(3) for r in reps}
        phi = {t: rng.randrange(3) for t in types}
        val = mutual_info(space, lambda g: psi[c(g)], lambda g: phi[cycle_type(g)])
        worst = max(worst, val)
        assert val <= base + 1e-12
    print(f"  D4: I(c ; T) = {fmt(base)};  max over 200 random coarsenings psi, phi = {fmt(worst)}")
    print("  No post-processing of the residue or of the type ever beats the cap.\n")


# ---------------------------------------------------------------------------
# 3-4. The Frobenius one-time pad
# ---------------------------------------------------------------------------


def demo_one_time_pad() -> None:
    print("=" * 78)
    print("3. THE FROBENIUS ONE-TIME PAD   I(F(sigma_p) ; H(sigma_p sigma_q)) = 0")
    print("=" * 78)
    rng = random.Random(7)
    G = S4
    elems = sorted(G)
    readouts_H: Dict[str, Callable[[Perm], Hashable]] = {
        "cycle type of sigma_N": cycle_type,
        "Artin class of sigma_N": conj_class_readout(G),
        "residue of N": coset_readout(derived_subgroup(G)),
        "sigma_N itself": lambda g: g,
    }
    for trial in range(3):
        A = rng.sample(elems, rng.randint(2, 9))
        space = [(x, y) for x in A for y in elems]
        print(f"  trial {trial}: candidate set A for sigma_p has |A| = {len(A)}  (non-abelian S4)")
        for hname, Hf in readouts_H.items():
            for fname, Ff in {"type of sigma_p": cycle_type, "sigma_p itself": lambda g: g}.items():
                val = mutual_info(space, lambda z: Ff(z[0]), lambda z: Hf(mul(z[0], z[1])))
                ok = cells_factor(space, lambda z: Ff(z[0]), lambda z: Hf(mul(z[0], z[1])))
                assert abs(val) < 1e-9 and ok
            print(f"     I(any readout of sigma_p ; {hname:<24}) = 0   (cell counts factor exactly)")
    print()

    print("=" * 78)
    print("4. POSTERIOR = PRIOR, AND THE PAD BREAKS WHEN THE COFACTOR IS REVEALED")
    print("=" * 78)
    A = [g for g in elems if cycle_type(g) in [(1, 1, 2), (4,), (1, 3)]][:7]
    space = [(x, y) for x in A for y in elems]
    prior = Counter(cycle_type(x) for x, _ in space)
    obs = Counter(cycle_type(mul(x, y)) for x, y in space)
    print(f"  |A| = {len(A)}; prior law of type(sigma_p):",
          {k: str(Fraction(v, len(space))) for k, v in sorted(prior.items())})
    for b in sorted(obs):
        fib = [(x, y) for x, y in space if cycle_type(mul(x, y)) == b]
        post = Counter(cycle_type(x) for x, _ in fib)
        same = all(Fraction(post[k], len(fib)) == Fraction(prior[k], len(space)) for k in prior)
        assert same
        print(f"     observe type(sigma_N) = {str(b):<12} -> posterior equals prior: {same}")
    full = mutual_info(space, lambda z: z[0], lambda z: (mul(z[0], z[1]), z[1]))
    print(f"  Reveal sigma_q too:  I(sigma_p ; (sigma_N, sigma_q)) = {fmt(full)} = log2 |A| = {fmt(log2(len(A)))}")
    # no-pruning (support form): every class of sigma_p remains possible
    sigma = elems[5]
    compensators = [inv(p) for p in elems]  # q = p^{-1} sigma
    assert all(mul(p, mul(inv(p), sigma)) == sigma for p in elems)
    print(f"  No pruning: for a fixed target sigma_N, every p has the compensating q = p^-1 sigma"
          f" ({len(compensators)} of {len(elems)} candidates survive).\n")


# ---------------------------------------------------------------------------
# 5. The which-factor wall
# ---------------------------------------------------------------------------


def demo_which_factor() -> None:
    print("=" * 78)
    print("5. THE WHICH-FACTOR WALL   H(bit) = 1 and I(bit ; k) = 0 for swap-invariant k")
    print("=" * 78)
    for name in ["S3", "S4", "D4", "A4"]:
        G = GROUPS[name]
        elems = sorted(G)
        space = [(x, y) for x in elems for y in elems if cycle_type(x) != cycle_type(y)]
        bit = lambda z: cycle_type(z[0]) < cycle_type(z[1])
        c = coset_readout(derived_subgroup(G))
        cls = conj_class_readout(G)
        k_res = lambda z: (c(mul(z[0], z[1])), min(cycle_type(z[0]), cycle_type(z[1])),
                           max(cycle_type(z[0]), cycle_type(z[1])))
        k_art = lambda z: (cls(mul(z[0], z[1])), min(cycle_type(z[0]), cycle_type(z[1])),
                           max(cycle_type(z[0]), cycle_type(z[1])))
        h = entropy([bit(z) for z in space])
        i_res = mutual_info(space, bit, k_res)
        i_art = mutual_info(space, bit, k_art)
        i_ord = mutual_info(space, bit, lambda z: (cycle_type(z[0]), cycle_type(z[1])))
        assert abs(h - 1) < 1e-12 and abs(i_res) < 1e-12 and abs(i_art) < 1e-12
        print(f"  {name}: H(bit)={fmt(h)}  I(bit; residue+unordered types)={fmt(i_res)}"
              f"  I(bit; Artin+unordered)={fmt(i_art)}  I(bit; ORDERED types)={fmt(i_ord)}")
    print("  The zero is exact, and the ordered readout shows the bit is really there.\n")


# ---------------------------------------------------------------------------
# 6. The multi-prime wall
# ---------------------------------------------------------------------------


def demo_multi_prime() -> None:
    print("=" * 78)
    print("6. THE MULTI-PRIME WALL   N = p0 p1 ... pm,  H(label) = log2(m+1),  I = 0")
    print("=" * 78)
    G = S4
    elems = sorted(G)
    c = coset_readout(derived_subgroup(G))
    for m in [1, 2]:
        space = [x for x in product(elems, repeat=m + 1)
                 if len({cycle_type(g) for g in x}) == m + 1]
        label = lambda x: min(range(m + 1), key=lambda i: cycle_type(x[i]))

        def k_sym(x: Tuple[Perm, ...]) -> Hashable:
            prod_coset = c(x[0])
            for g in x[1:]:
                prod_coset = c(mul(prod_coset, g))
            return (prod_coset, tuple(sorted(cycle_type(g) for g in x)))

        h = entropy([label(x) for x in space])
        i0 = mutual_info(space, label, k_sym)
        i_ord = mutual_info(space, label, lambda x: tuple(cycle_type(g) for g in x))
        assert abs(h - log2(m + 1)) < 1e-12 and abs(i0) < 1e-12
        print(f"  m+1={m+1} factors, |space|={len(space)}: H(label)={fmt(h)} = log2({m+1});"
              f" I(label; residue+multiset of types)={fmt(i0)}; ordered={fmt(i_ord)}")
    print()


# ---------------------------------------------------------------------------
# 7. The semiprime ledger
# ---------------------------------------------------------------------------


def demo_ledger() -> None:
    print("=" * 78)
    print("7. THE SEMIPRIME LEDGER: PURE SYNERGY")
    print("=" * 78)
    for name in ["S4", "D4"]:
        G = GROUPS[name]
        elems = sorted(G)
        space = [(x, y) for x in elems for y in elems]
        c = coset_readout(derived_subgroup(G))
        res = lambda z: c(mul(z[0], z[1]))
        h_res = entropy([res(z) for z in space])
        i_p = mutual_info(space, res, lambda z: cycle_type(z[0]))
        i_q = mutual_info(space, res, lambda z: cycle_type(z[1]))
        i_uno = mutual_info(space, res, lambda z: tuple(sorted([cycle_type(z[0]), cycle_type(z[1])])))
        i_ord = mutual_info(space, res, lambda z: (cycle_type(z[0]), cycle_type(z[1])))
        print(f"  {name}: H(residue of N)={fmt(h_res)} = log2[G:G']")
        print(f"      I(res ; type p)={fmt(i_p)}  I(res ; type q)={fmt(i_q)}"
              f"  I(res ; {{Tp,Tq}})={fmt(i_uno)}  I(res ; (Tp,Tq))={fmt(i_ord)}")
        assert abs(i_p) < 1e-12 and abs(i_q) < 1e-12 and abs(i_uno - i_ord) < 1e-12
    closed = 39 / 16 - 0.75 * log2(3) + 5 / 64 * log2(5)
    print(f"  D4 closed form 39/16 - (3/4)log2 3 + (5/64)log2 5 = {fmt(closed)}  (> 1, <= 2)")
    print("  Zero bits about each factor alone, yet positive bits about the pair:")
    print("  every bit the residue of N leaks is synergistic, and ordered = unordered.\n")


if __name__ == "__main__":
    demo_cap()
    demo_data_processing()
    demo_one_time_pad()
    demo_which_factor()
    demo_multi_prime()
    demo_ledger()
    print("All assertions passed.")
