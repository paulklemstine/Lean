    # Quick demonstrations
    print("Valley Detection:")
    for alpha in [3.0, 4.0, 5.0, 8.0]:
        result = valley_detect(lambda r, a=alpha: valley_model(a, r))
        print(f"  α={alpha}: {'Valley at r={:.4f}'.format(result[0]) if result else 'No valley'}")

    print("\nAlpha Estimation from synthetic data:")
