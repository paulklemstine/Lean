#!/usr/bin/env python3
"""Numerical demonstrations for Bergman fans of finite circuit presentations.

The script uses exact integer and rational arithmetic.  A matroid is supplied by
its ground-set size and a list of circuits; no external packages are required.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from typing import Iterable, Sequence, TypeVar

Number = TypeVar("Number", int, float, Fraction)
Circuit = tuple[int, ...]


def minimizers_on_circuit(weights: Sequence[Number], circuit: Circuit) -> tuple[int, ...]:
    """Return all circuit elements attaining the minimum weight."""
    if not circuit:
        raise ValueError("A circuit must be nonempty.")
    minimum = min(weights[e] for e in circuit)
    return tuple(e for e in circuit if weights[e] == minimum)


def repeated_minimum(weights: Sequence[Number], circuit: Circuit) -> bool:
    """Test whether the minimum on one circuit has at least two witnesses."""
    return len(minimizers_on_circuit(weights, circuit)) >= 2


def in_bergman_fan(weights: Sequence[Number], circuits: Sequence[Circuit]) -> bool:
    """Test all circuit equations, hence Bergman and tropical-space membership."""
    return all(repeated_minimum(weights, circuit) for circuit in circuits)


def translate(weights: Sequence[Number], constant: Number) -> tuple[Number, ...]:
    """Add the same scalar to every coordinate."""
    return tuple(value + constant for value in weights)


def nonnegative_dilate(weights: Sequence[Number], scalar: Number) -> tuple[Number, ...]:
    """Multiply every coordinate by a nonnegative scalar."""
    if scalar < 0:
        raise ValueError("The Bergman closure theorem requires a nonnegative scalar.")
    return tuple(scalar * value for value in weights)


def orbit_point(
    weights: Sequence[Fraction], c0: Fraction, c1: Fraction, t: Fraction
) -> tuple[Fraction, ...]:
    """Evaluate the straight path between two points on a translation orbit."""
    if not Fraction(0) <= t <= Fraction(1):
        raise ValueError("The path parameter t must lie in [0, 1].")
    constant = (Fraction(1) - t) * c0 + t * c1
    return translate(weights, constant)


@dataclass
class DisjointSet:
    """Disjoint-set union structure for computing circuit components."""

    parent: list[int]
    rank: list[int]

    @classmethod
    def create(cls, size: int) -> "DisjointSet":
        return cls(list(range(size)), [0] * size)

    def find(self, item: int) -> int:
        if self.parent[item] != item:
            self.parent[item] = self.find(self.parent[item])
        return self.parent[item]

    def union(self, left: int, right: int) -> None:
        root_left, root_right = self.find(left), self.find(right)
        if root_left == root_right:
            return
        if self.rank[root_left] < self.rank[root_right]:
            root_left, root_right = root_right, root_left
        self.parent[root_right] = root_left
        if self.rank[root_left] == self.rank[root_right]:
            self.rank[root_left] += 1


def circuit_components(size: int, circuits: Sequence[Circuit]) -> tuple[tuple[int, ...], ...]:
    """Compute components generated by common membership in a circuit."""
    dsu = DisjointSet.create(size)
    for circuit in circuits:
        if not circuit:
            raise ValueError("A circuit must be nonempty.")
        representative = circuit[0]
        for element in circuit[1:]:
            dsu.union(representative, element)
    groups: dict[int, list[int]] = {}
    for element in range(size):
        groups.setdefault(dsu.find(element), []).append(element)
    return tuple(tuple(group) for group in sorted(groups.values(), key=lambda g: g[0]))


def in_bergman_lineality(
    weights: Sequence[Number], size: int, circuits: Sequence[Circuit]
) -> bool:
    """Test the equivalent condition that weights are constant on components."""
    for component in circuit_components(size, circuits):
        first = weights[component[0]]
        if any(weights[element] != first for element in component[1:]):
            return False
    return True


def describe_circuit_tests(weights: Sequence[Number], circuits: Sequence[Circuit]) -> None:
    for circuit in circuits:
        minimizers = minimizers_on_circuit(weights, circuit)
        print(f"  circuit {circuit}: minimizers {minimizers}; "
              f"{'PASS' if len(minimizers) >= 2 else 'FAIL'}")


def main() -> None:
    circuits: tuple[Circuit, ...] = ((0, 1, 2), (1, 2, 3))
    weight = (Fraction(0), Fraction(0), Fraction(2), Fraction(0))

    print("Overlapping-circuit example")
    print("circuits:", circuits)
    print("weight:", weight)
    describe_circuit_tests(weight, circuits)
    print("Bergman/tropical-linear-space member:", in_bergman_fan(weight, circuits))

    print("\nTranslation and dilation symmetries")
    for constant in (Fraction(-3), Fraction(0), Fraction(5, 2)):
        shifted = translate(weight, constant)
        print(f"  c={constant}: {shifted}, member={in_bergman_fan(shifted, circuits)}")
    for scalar in (Fraction(0), Fraction(1, 2), Fraction(3)):
        dilated = nonnegative_dilate(weight, scalar)
        print(f"  a={scalar}: {dilated}, member={in_bergman_fan(dilated, circuits)}")

    print("\nA path inside one translation orbit")
    for t in (Fraction(0), Fraction(1, 4), Fraction(1, 2), Fraction(3, 4), Fraction(1)):
        point = orbit_point(weight, Fraction(-2), Fraction(3), t)
        print(f"  t={t}: {point}, member={in_bergman_fan(point, circuits)}")

    components = circuit_components(4, circuits)
    print("\nCircuit components:", components)
    for candidate in ((7, 7, 7, 7), (1, 1, 1, 2)):
        print(f"  lineality candidate {candidate}: "
              f"{in_bergman_lineality(candidate, 4, circuits)}")

    print("\nNonconvexity of the three-element tropical line")
    one_circuit: tuple[Circuit, ...] = ((0, 1, 2),)
    left = (Fraction(0), Fraction(0), Fraction(2))
    right = (Fraction(0), Fraction(2), Fraction(0))
    midpoint = tuple((x + y) / 2 for x, y in zip(left, right))
    print("  endpoints:", left, right)
    print("  endpoint membership:", in_bergman_fan(left, one_circuit),
          in_bergman_fan(right, one_circuit))
    print("  midpoint:", midpoint, "membership:", in_bergman_fan(midpoint, one_circuit))


if __name__ == "__main__":
    main()
