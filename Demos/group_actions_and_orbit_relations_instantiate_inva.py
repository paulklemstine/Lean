#!/usr/bin/env python3
"""
Orbit capacity of symmetry-invariant patterns: numerical demonstrations.
=======================================================================

This self-contained script verifies, by brute-force enumeration, every closed
form established in the accompanying paper:

  * Orbit Capacity Theorem   : #invariant patterns = 2^(#orbits)
  * Burnside Capacity Formula: #orbits = (1/|G|) * sum_g |Fix(g)|
  * Ostinato capacity        : 2^q
  * Point-reflection capacity: 2^((p q + tau(p) tau(q)) / 2)
  * Quarter-turn capacity    : 2^((p^2 + 2 tau(p) + tau(p)^2) / 4)
  * Glide capacity           : 2^(p q / 2)
  * Descent dichotomy        : swapping point-group elements need p = q
  * Realizability            : every subgroup is some pattern's symmetry group
  * Canon onset spectrum     : achievable onsets = multiples of ord(g) up to p q
  * Maximum-entropy ceiling  : H(P) <= m bits, equality iff uniform
  * Orbit-Bernoulli entropy  : H(P_theta) = m * H2(theta)
  * Per-orbit deficit        : m - H(P_theta) = m * (1 - H2(theta))

Everything is done with exact integer arithmetic where possible; the entropy
checks use floating point with an explicit tolerance.

Run:  python3 demo.py
"""

from __future__ import annotations

from itertools import product
from math import gcd, log2
from typing import Callable, Dict, Iterable, List, Sequence, Set, Tuple

Cell = Tuple[int, int]
Pattern = Tuple[bool, ...]
Action = Callable[[Cell], Cell]

TOL = 1e-9


# ----------------------------------------------------------------------------
# Core machinery: cells, orbits, invariant patterns, Burnside
# ----------------------------------------------------------------------------


def torus_cells(p: int, q: int) -> List[Cell]:
    """All cells of the p x q time-pitch torus, in a fixed order."""
    return [(t, n) for t in range(p) for n in range(q)]


def orbits(cells: Sequence[Cell], group: Sequence[Action]) -> List[List[Cell]]:
    """Orbit partition of `cells` under the finite list of maps `group`.

    Uses a simple union-find (Algorithm B of the paper).
    """
    index: Dict[Cell, int] = {c: i for i, c in enumerate(cells)}
    parent: List[int] = list(range(len(cells)))

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x: int, y: int) -> None:
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[max(rx, ry)] = min(rx, ry)

    for g in group:
        for c in cells:
            union(index[c], index[g(c)])

    buckets: Dict[int, List[Cell]] = {}
    for c in cells:
        buckets.setdefault(find(index[c]), []).append(c)
    return list(buckets.values())


def orbit_count(cells: Sequence[Cell], group: Sequence[Action]) -> int:
    """Number of orbits, by direct enumeration."""
    return len(orbits(cells, group))


def fixed_count(cells: Sequence[Cell], g: Action) -> int:
    """|Fix(g)| — the number of cells left in place by g."""
    return sum(1 for c in cells if g(c) == c)


def burnside_orbit_count(cells: Sequence[Cell], group: Sequence[Action]) -> int:
    """Orbit count via Burnside's lemma (Algorithm A of the paper).

    Requires `group` to be the *full* group, not merely a generating set.
    """
    total = sum(fixed_count(cells, g) for g in group)
    assert total % len(group) == 0, "Burnside sum must be divisible by |G|"
    return total // len(group)


def invariant_patterns(
    cells: Sequence[Cell], group: Sequence[Action]
) -> List[Pattern]:
    """Brute-force enumeration of all G-invariant binary patterns.

    A pattern is a tuple of booleans indexed in the order of `cells`.
    Only feasible for small grids; used purely as ground truth.
    """
    index = {c: i for i, c in enumerate(cells)}
    out: List[Pattern] = []
    for bits in product([False, True], repeat=len(cells)):
        if all(bits[index[g(c)]] == bits[index[c]] for g in group for c in cells):
            out.append(bits)
    return out


def two_torsion_card(n: int) -> int:
    """tau(n): the number of x in Z_n with -x = x (2 if n even, else 1)."""
    return 2 if n % 2 == 0 else 1


# ----------------------------------------------------------------------------
# The four crystallographic generators as group actions on a torus
# ----------------------------------------------------------------------------


def shift_group(p: int, q: int) -> List[Action]:
    """The full cyclic group of time shifts (t, n) -> (t + s, n)."""
    return [(lambda c, s=s: ((c[0] + s) % p, c[1])) for s in range(p)]


def shift_subgroup(p: int, q: int, g: int) -> List[Action]:
    """The cyclic subgroup generated by the shift by g."""
    d = p // gcd(p, g)
    return [(lambda c, j=j: ((c[0] + j * g) % p, c[1])) for j in range(d)]


def point_reflection_group(p: int, q: int) -> List[Action]:
    """{identity, (t, n) -> (-t, -n)} — retrograde-inversion."""
    return [lambda c: c, lambda c: ((-c[0]) % p, (-c[1]) % q)]


def quarter_turn_group(p: int) -> List[Action]:
    """The order-four group generated by (t, n) -> (-n, t) on a square torus."""

    def kappa(c: Cell) -> Cell:
        return ((-c[1]) % p, c[0] % p)

    def iterate(c: Cell, k: int) -> Cell:
        for _ in range(k):
            c = kappa(c)
        return c

    return [(lambda c, k=k: iterate(c, k)) for k in range(4)]


def glide_group(p: int, q: int) -> List[Action]:
    """{identity, (t, n) -> (t + p/2, -n)} for even p."""
    assert p % 2 == 0, "a toroidal glide needs an even time period"
    return [lambda c: c, lambda c: ((c[0] + p // 2) % p, (-c[1]) % q)]


# ----------------------------------------------------------------------------
# Symmetry groups of a single pattern, and realizability
# ----------------------------------------------------------------------------


def symmetry_shifts(p: int, q: int, onsets: Set[Cell]) -> List[int]:
    """The shifts s in Z_p that preserve the given onset set."""
    out: List[int] = []
    for s in range(p):
        if all(((t + s) % p, n) in onsets for (t, n) in onsets):
            out.append(s)
    return out


def cyclic_subgroups(p: int) -> List[List[int]]:
    """All subgroups of Z_p, as sorted lists of residues (one per divisor)."""
    subs: List[List[int]] = []
    for d in range(1, p + 1):
        if p % d == 0:
            subs.append(sorted((p // d * j) % p for j in range(d)))
    return subs


def subgroup_pattern(p: int, q: int, H: Sequence[int]) -> Set[Cell]:
    """The indicator pattern of a subgroup H of the shift group."""
    Hs = set(H)
    return {(t, n) for t in range(p) for n in range(q) if t in Hs}


# ----------------------------------------------------------------------------
# Canons
# ----------------------------------------------------------------------------


def is_canon_at(p: int, q: int, onsets: Set[Cell], g: int) -> bool:
    """Does shifting every cell forward in time by g reproduce the pattern?"""
    return all((((t + g) % p, n) in onsets) == ((t, n) in onsets)
               for t in range(p) for n in range(q))


def canon_with_onsets(p: int, q: int, g: int, k: int) -> Set[Cell] | None:
    """Algorithm C: build a canon at distance g with exactly k onsets, or None."""
    d = p // gcd(p, g)
    if k % d != 0 or k > p * q:
        return None
    j = k // d
    orbs = orbits(torus_cells(p, q), shift_subgroup(p, q, g))
    chosen: Set[Cell] = set()
    for orb in orbs[:j]:
        chosen.update(orb)
    return chosen


def achievable_onset_counts(p: int, q: int, g: int) -> List[int]:
    """Brute force: all onset counts realized by some canon at distance g."""
    cells = torus_cells(p, q)
    found: Set[int] = set()
    for bits in product([False, True], repeat=len(cells)):
        onsets = {c for c, b in zip(cells, bits) if b}
        if is_canon_at(p, q, onsets, g):
            found.add(len(onsets))
    return sorted(found)


# ----------------------------------------------------------------------------
# Entropy
# ----------------------------------------------------------------------------


def entropy_bits(dist: Iterable[float]) -> float:
    """Shannon entropy in bits of a probability vector."""
    return sum(-x * log2(x) for x in dist if x > 0.0)


def binary_entropy_bits(theta: float) -> float:
    """H2(theta) = -theta log2 theta - (1-theta) log2 (1-theta)."""
    return entropy_bits([theta, 1.0 - theta])


def orbit_bernoulli_distribution(m: int, theta: float) -> List[float]:
    """The orbit-Bernoulli distribution over all 2^m invariant patterns."""
    out: List[float] = []
    for cfg in product([0, 1], repeat=m):
        w = 1.0
        for bit in cfg:
            w *= theta if bit else (1.0 - theta)
        out.append(w)
    return out


# ----------------------------------------------------------------------------
# Demonstrations
# ----------------------------------------------------------------------------


def banner(title: str) -> None:
    print()
    print("=" * 74)
    print(title)
    print("=" * 74)


def demo_capacity_and_burnside() -> None:
    banner("1. Orbit Capacity Theorem and Burnside's lemma")
    print("  For each action: enumerate invariant patterns, compare with 2^m,")
    print("  and compare the enumerated orbit count with the Burnside average.")
    print()
    header = f"  {'action':<26}{'cells':>7}{'orbits':>8}{'burnside':>10}" \
             f"{'2^m':>8}{'brute':>8}"
    print(header)
    print("  " + "-" * (len(header) - 2))

    cases: List[Tuple[str, int, int, List[Action]]] = [
        ("full shifts 4x3", 4, 3, shift_group(4, 3)),
        ("full shifts 3x2", 3, 2, shift_group(3, 2)),
        ("point reflection 3x3", 3, 3, point_reflection_group(3, 3)),
        ("point reflection 4x3", 4, 3, point_reflection_group(4, 3)),
        ("glide 4x3", 4, 3, glide_group(4, 3)),
        ("glide 2x2", 2, 2, glide_group(2, 2)),
    ]
    for name, p, q, grp in cases:
        cells = torus_cells(p, q)
        m = orbit_count(cells, grp)
        mb = burnside_orbit_count(cells, grp)
        pats = len(invariant_patterns(cells, grp))
        assert m == mb, (name, m, mb)
        assert pats == 2 ** m, (name, pats, m)
        print(f"  {name:<26}{p*q:>7}{m:>8}{mb:>10}{2**m:>8}{pats:>8}")

    # quarter turns on a square torus, separately (needs p = q)
    for p in (2, 3):
        cells = torus_cells(p, p)
        grp = quarter_turn_group(p)
        m = orbit_count(cells, grp)
        mb = burnside_orbit_count(cells, grp)
        pats = len(invariant_patterns(cells, grp))
        assert m == mb and pats == 2 ** m
        print(f"  {'quarter turn %dx%d' % (p, p):<26}{p*p:>7}{m:>8}{mb:>10}"
              f"{2**m:>8}{pats:>8}")
    print("\n  All capacities agree with 2^(#orbits), and Burnside agrees "
          "with enumeration.")


def demo_closed_forms() -> None:
    banner("2. The four closed-form capacities")

    print("\n  (a) Ostinato capacity  2^q  (invariance under every time shift)")
    print(f"      {'p':>3}{'q':>3}{'orbits':>9}{'2^q':>10}")
    for p, q in [(2, 2), (3, 2), (4, 3), (5, 4), (12, 5)]:
        m = burnside_orbit_count(torus_cells(p, q), shift_group(p, q))
        assert m == q and 2 ** m == 2 ** q
        print(f"      {p:>3}{q:>3}{m:>9}{2**q:>10}")

    print("\n  (b) Point-reflection capacity  2^((p q + tau(p) tau(q)) / 2)")
    print(f"      {'p':>3}{'q':>3}{'tau p':>7}{'tau q':>7}{'orbits':>9}"
          f"{'capacity':>12}")
    for p, q in [(3, 3), (4, 3), (5, 5), (6, 4), (2, 2)]:
        m = burnside_orbit_count(torus_cells(p, q), point_reflection_group(p, q))
        tp, tq = two_torsion_card(p), two_torsion_card(q)
        pred = (p * q + tp * tq) // 2
        assert m == pred, (p, q, m, pred)
        print(f"      {p:>3}{q:>3}{tp:>7}{tq:>7}{m:>9}{2**m:>12}")

    print("\n  (c) Quarter-turn capacity  2^((p^2 + 2 tau + tau^2) / 4)")
    print(f"      {'p':>3}{'tau':>5}{'orbits':>9}{'capacity':>12}{'formula':>26}")
    for p in [2, 3, 4, 5, 6, 7]:
        m = burnside_orbit_count(torus_cells(p, p), quarter_turn_group(p))
        t = two_torsion_card(p)
        pred = (p * p + 2 * t + t * t) // 4
        assert m == pred, (p, m, pred)
        alt = (p * p + 3) // 4 if p % 2 else (p * p + 8) // 4
        assert alt == pred
        label = f"(p^2+3)/4" if p % 2 else "(p^2+8)/4"
        print(f"      {p:>3}{t:>5}{m:>9}{2**m:>12}{label:>26}")

    print("\n  (d) Glide capacity  2^(p q / 2)   (p even; the glide fixes "
          "nothing)")
    print(f"      {'p':>3}{'q':>3}{'|Fix(glide)|':>14}{'orbits':>9}"
          f"{'capacity':>12}")
    for p, q in [(2, 2), (4, 3), (4, 4), (6, 5)]:
        cells = torus_cells(p, q)
        grp = glide_group(p, q)
        nfix = fixed_count(cells, grp[1])
        m = burnside_orbit_count(cells, grp)
        assert nfix == 0 and m == p * q // 2
        print(f"      {p:>3}{q:>3}{nfix:>14}{m:>9}{2**m:>12}")


def demo_descent() -> None:
    banner("3. Descent dichotomy for the point group of the square lattice")
    print("  A signed permutation of the plane descends to the p x q torus iff")
    print("  it preserves the sublattice p Z x q Z.  Diagonal elements always")
    print("  do; swapping elements do so iff p = q.")
    print()

    def diagonal_preserves(p: int, q: int, e1: int, e2: int) -> bool:
        # test on the generators (p, 0) and (0, q) of the sublattice
        for v in [(p, 0), (0, q)]:
            w = (e1 * v[0], e2 * v[1])
            if w[0] % p or w[1] % q:
                return False
        return True

    def swap_preserves(p: int, q: int, e1: int, e2: int) -> bool:
        for v in [(p, 0), (0, q)]:
            w = (e1 * v[1], e2 * v[0])
            if w[0] % p or w[1] % q:
                return False
        return True

    print(f"  {'p':>3}{'q':>3}{'diagonal elts descending':>28}"
          f"{'swapping elts descending':>28}")
    for p, q in [(3, 3), (4, 4), (4, 3), (6, 2), (5, 5), (2, 6)]:
        nd = sum(1 for e1 in (1, -1) for e2 in (1, -1)
                 if diagonal_preserves(p, q, e1, e2))
        ns = sum(1 for e1 in (1, -1) for e2 in (1, -1)
                 if swap_preserves(p, q, e1, e2))
        assert nd == 4
        assert ns == (4 if p == q else 0)
        print(f"  {p:>3}{q:>3}{nd:>28}{ns:>28}")
    print("\n  Total descending point group: 8 when p = q, otherwise 4.")


def demo_monotonicity() -> None:
    banner("4. Capacity is antitone in the symmetry group — strictly when "
           "orbits fuse")
    p, q = 6, 2
    cells = torus_cells(p, q)
    print(f"  Torus {p}x{q}; the shift subgroups of Z_{p} ordered by inclusion.")
    print()
    print(f"  {'subgroup of Z_6':<22}{'|H|':>5}{'orbits':>9}{'capacity':>12}")
    for H in cyclic_subgroups(p):
        grp = [(lambda c, s=s: ((c[0] + s) % p, c[1])) for s in H]
        m = burnside_orbit_count(cells, grp)
        print(f"  {str(H):<22}{len(H):>5}{m:>9}{2**m:>12}")
    print("\n  Each inclusion of subgroups weakly decreases capacity, and")
    print("  strictly decreases it whenever the larger group merges two cells")
    print("  that the smaller keeps apart.")


def demo_realizability() -> None:
    banner("5. Every symmetry type is realized by an explicit pattern")
    p, q = 6, 1
    print(f"  Torus {p}x{q}: for each subgroup H of the shift group, the")
    print("  indicator pattern of H has symmetry group exactly H.")
    print()
    print(f"  {'H':<22}{'onsets of the pattern':<28}{'its symmetry group':<22}")
    for H in cyclic_subgroups(p):
        pat = subgroup_pattern(p, q, H)
        sym = symmetry_shifts(p, q, pat)
        assert sym == sorted(H), (H, sym)
        onsets = sorted(t for (t, _) in pat)
        print(f"  {str(H):<22}{str(onsets):<28}{str(sym):<22}")
    print("\n  No symmetry type is missing: the full subgroup lattice occurs.")

    print("\n  The backbeat (4 beats, 1 instrument, onsets at t = 0 and 2):")
    back = {(0, 0), (2, 0)}
    sym = symmetry_shifts(4, 1, back)
    print(f"    symmetry group = {sym}  -> proper (misses shift 1) and "
          f"nontrivial (contains shift 2)")
    assert sym == [0, 2]


def demo_canons() -> None:
    banner("6. The complete onset spectrum of canons")
    print("  Theory: k is achievable at distance g iff ord(g) | k and k <= p q.")
    print()
    print(f"  {'p':>3}{'q':>3}{'g':>3}{'ord(g)':>8}  "
          f"{'predicted spectrum':<26}{'brute force':<26}")
    for p, q, g in [(4, 1, 2), (4, 1, 1), (4, 1, 0), (6, 1, 3), (3, 2, 1)]:
        d = p // gcd(p, g) if g else 1
        pred = [k for k in range(p * q + 1) if k % d == 0]
        brute = achievable_onset_counts(p, q, g)
        assert pred == brute, (p, q, g, pred, brute)
        print(f"  {p:>3}{q:>3}{g:>3}{d:>8}  {str(pred):<26}{str(brute):<26}")

    print("\n  Synthesis (Algorithm C) on the 6x2 torus at distance g = 2 "
          "(ord = 3):")
    for k in [0, 3, 6, 9, 12, 5]:
        built = canon_with_onsets(6, 2, 2, k)
        if built is None:
            print(f"    k = {k:>2}: impossible (3 does not divide {k})")
        else:
            ok = is_canon_at(6, 2, built, 2) and len(built) == k
            assert ok
            print(f"    k = {k:>2}: built a canon with onsets "
                  f"{sorted(built)}")


def demo_entropy() -> None:
    banner("7. Entropy: the ceiling, the orbit-Bernoulli model, the deficit")

    print("  (a) Maximum-entropy ceiling on invariant patterns.")
    p, q = 4, 3
    cells = torus_cells(p, q)
    grp = glide_group(p, q)
    m = burnside_orbit_count(cells, grp)
    n_pat = 2 ** m
    uniform = [1.0 / n_pat] * n_pat
    h_uniform = entropy_bits(uniform)
    print(f"      glide on the {p}x{q} torus: m = {m} orbits, "
          f"{n_pat} invariant patterns")
    print(f"      H(uniform) = {h_uniform:.6f} bits   (ceiling m = {m})")
    assert abs(h_uniform - m) < TOL

    # a deliberately skewed distribution has strictly lower entropy
    skew = [0.5] + [0.5 / (n_pat - 1)] * (n_pat - 1)
    h_skew = entropy_bits(skew)
    print(f"      H(skewed)  = {h_skew:.6f} bits   -> strictly below the "
          f"ceiling")
    assert h_skew < m - TOL

    print("\n  (b) Orbit-Bernoulli entropy: H(P_theta) = m * H2(theta).")
    print(f"      {'theta':>7}{'H2(theta)':>12}{'m H2':>12}"
          f"{'H(P) enumerated':>18}{'deficit m(1-H2)':>18}")
    m_small = 6  # enumerate all 2^6 = 64 invariant patterns explicitly
    for theta in [0.05, 0.1, 0.2, 0.3, 0.5, 0.7, 0.9]:
        dist = orbit_bernoulli_distribution(m_small, theta)
        assert abs(sum(dist) - 1.0) < TOL
        h = entropy_bits(dist)
        h2 = binary_entropy_bits(theta)
        pred = m_small * h2
        deficit = m_small * (1.0 - h2)
        assert abs(h - pred) < 1e-9
        assert abs((m_small - h) - deficit) < 1e-9
        print(f"      {theta:>7.2f}{h2:>12.6f}{pred:>12.6f}{h:>18.6f}"
              f"{deficit:>18.6f}")

    print("\n  (c) The deficit is exactly m bits times a per-orbit cost that")
    print("      depends only on theta — geometry and taste factor apart.")
    theta = 0.2
    h2 = binary_entropy_bits(theta)
    print(f"      theta = {theta}:  per-orbit cost = 1 - H2 = "
          f"{1.0 - h2:.6f} bits")
    print(f"      {'symmetry group':<28}{'orbits m':>10}"
          f"{'capacity':>12}{'total deficit':>16}")
    rows = [
        ("none (16x4 grid)", 16 * 4),
        ("glide, 16x4 grid", 16 * 4 // 2),
        ("point reflection, 16x4", (16 * 4 + 2 * 2) // 2),
        ("all time shifts, 16x4", 4),
    ]
    for name, mm in rows:
        print(f"      {name:<28}{mm:>10}{'2^' + str(mm):>12}"
              f"{mm * (1.0 - h2):>16.4f}")
    print("\n      Halving the orbit count halves the absolute cost of the "
          "same taste.")


