"""
Numerical demonstrations of the subgroup-index telescope.

Ground-truth theorems (formally verified):

  relIndex_prod_telescope
      product over a monotone chain H_0 <= ... <= H_n of the relative indices
      [H_{i+1} : H_i]  equals  [H_n : H_0].

  prod_relIndex_eq_card_of_bot_top
      if H_0 = {e} and H_n = G, the product of relative indices equals |G|.

  Corollary (no isotopes)
      |G| = product of orders of the composition factors of G, hence two finite
      groups with the same multiset of composition factors have the same order.

This script implements just enough finite-group machinery (permutation groups via
subgroup closure) to exhibit these identities on concrete groups. It is fully
self-contained: standard library only.
"""

from __future__ import annotations

from itertools import permutations
from math import prod
from typing import Dict, FrozenSet, List, Sequence, Tuple

# A permutation of {0, ..., n-1} is encoded as a tuple `p` with p[i] = image of i.
Perm = Tuple[int, ...]


def compose(p: Perm, q: Perm) -> Perm:
    """Return the composition (p after q): (p ∘ q)(i) = p[q[i]]."""
    return tuple(p[q[i]] for i in range(len(q)))


def identity(n: int) -> Perm:
    """The identity permutation of degree n."""
    return tuple(range(n))


def closure(generators: Sequence[Perm], n: int) -> FrozenSet[Perm]:
    """Generate the subgroup of S_n spanned by `generators` via orbit closure."""
    elems: set[Perm] = {identity(n)}
    frontier: List[Perm] = [identity(n)]
    gens = list(generators) if generators else [identity(n)]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = compose(g, x)
            if y not in elems:
                elems.add(y)
                frontier.append(y)
    return frozenset(elems)


def symmetric_group(n: int) -> FrozenSet[Perm]:
    """The full symmetric group S_n as a set of permutations."""
    return frozenset(permutations(range(n)))


def is_subgroup(h: FrozenSet[Perm], g: FrozenSet[Perm]) -> bool:
    """Test whether h is a subset of g (chain membership check)."""
    return h <= g


def relative_index(h_small: FrozenSet[Perm], h_big: FrozenSet[Perm]) -> int:
    """The relative index [H_big : H_small] = |H_big| / |H_small|."""
    assert h_small <= h_big, "h_small must be contained in h_big"
    assert len(h_big) % len(h_small) == 0, "Lagrange must hold"
    return len(h_big) // len(h_small)


def telescope_check(chain: Sequence[FrozenSet[Perm]]) -> Dict[str, object]:
    """
    Verify relIndex_prod_telescope on an explicit monotone chain
    H_0 <= H_1 <= ... <= H_n: product of relative indices equals [H_n : H_0].
    """
    for a, b in zip(chain, chain[1:]):
        assert is_subgroup(a, b), "chain must be monotone (each H_i <= H_{i+1})"
    rel = [relative_index(chain[i], chain[i + 1]) for i in range(len(chain) - 1)]
    product = prod(rel)
    endpoint = relative_index(chain[0], chain[-1])
    return {
        "relative_indices": rel,
        "product_of_relative_indices": product,
        "endpoint_index_[H_n:H_0]": endpoint,
        "telescope_holds": product == endpoint,
    }


def cyclic_divisor_chain(n: int) -> List[FrozenSet[Perm]]:
    """
    Realize Z_n as the cyclic group <c> in S_n (c = the n-cycle) and build the
    full subgroup chain through its divisor lattice along one maximal flag.
    Returns a chain from the trivial subgroup up to the whole group.
    """
    cycle: Perm = tuple((i + 1) % n for i in range(n))
    whole = closure([cycle], n)

    def prime_factor_flag(m: int) -> List[int]:
        """Maximal divisor flag 1 | d_1 | ... | m via prime factorization."""
        flag = [1]
        cur = 1
        rem = m
        d = 2
        while rem > 1:
            while rem % d == 0:
                cur *= d
                flag.append(cur)
                rem //= d
            d += 1
        return flag

    chain: List[FrozenSet[Perm]] = []
    for d in prime_factor_flag(n):
        # subgroup of order d is generated by cycle^(n//d)
        e = n // d
        acc = identity(n)
        for _ in range(e):
            acc = compose(cycle, acc)
        chain.append(closure([acc], n))
    chain[-1] = whole
    return chain


def demo_s4_composition_series() -> None:
    """Composition series of S_4: 1 < <(12)(34)> < V4 < A4 < S4."""
    print("=" * 70)
    print("Composition series of S_4  (the 24 shuffles of four objects)")
    print("=" * 70)
    s4 = symmetric_group(4)
    # double transpositions generating the Klein four-group V4
    a = (1, 0, 3, 2)  # (0 1)(2 3)
    b = (2, 3, 0, 1)  # (0 2)(1 3)
    triv = closure([], 4)
    z2 = closure([a], 4)
    v4 = closure([a, b], 4)
    # A4: even permutations
    a4 = frozenset(p for p in s4 if _sign(p) == 1)
    chain = [triv, z2, v4, a4, s4]
    result = telescope_check(chain)
    print(f"orders along chain : {[len(h) for h in chain]}")
    print(f"relative indices   : {result['relative_indices']}   (the factor orders)")
    print(f"product            : {result['product_of_relative_indices']}")
    print(f"|S_4|              : {len(s4)}")
    print(f"telescope holds    : {result['telescope_holds']}")
    print(f"factors as 'formula': Z2 * Z2 * Z3 * Z2  ->  product 24\n")


def _sign(p: Perm) -> int:
    """Sign of a permutation (+1 even, -1 odd) via inversion count."""
    n = len(p)
    inversions = sum(1 for i in range(n) for j in range(i + 1, n) if p[i] > p[j])
    return 1 if inversions % 2 == 0 else -1


def demo_cyclic() -> None:
    """Telescope on cyclic groups Z_n through a maximal divisor flag."""
    print("=" * 70)
    print("Cyclic groups Z_n: order = product of relative indices")
    print("=" * 70)
    for n in (6, 12, 30):
        chain = cyclic_divisor_chain(n)
        result = telescope_check(chain)
        print(f"Z_{n:<3} flag orders {[len(h) for h in chain]}")
        print(f"        relative indices {result['relative_indices']} "
              f"-> product {result['product_of_relative_indices']} = {n} "
              f"({'OK' if result['product_of_relative_indices'] == n else 'FAIL'})")
    print()


def demo_no_isotopes() -> None:
    """
    'No isotopes': a group's order is the product of its composition-factor
    orders, so the multiset of factors determines the order.
    """
    print("=" * 70)
    print("The 'no isotopes' law: factor multiset determines the order")
    print("=" * 70)
    samples: Dict[str, List[int]] = {
        "Z_12          ": [2, 2, 3],       # Z2, Z2, Z3
        "Z_2 x Z_6     ": [2, 2, 3],       # same factor multiset as Z_12
        "S_4           ": [2, 2, 3, 2],    # Z2, Z2, Z3, Z2
        "S_5 (order120)": [2, 60],         # Z2, A5  (A5 simple, order 60)
        "A_5  (order60)": [60],            # A5 simple
    }
    for name, factors in samples.items():
        order = prod(factors)
        print(f"{name}: factor orders {factors:} -> |G| = {order}")
    print("\nZ_12 and Z_2 x Z_6 share the multiset {2,2,3}; both have order 12.")
    print("No finite group can share a factor multiset yet differ in order.\n")


def main() -> None:
    demo_s4_composition_series()
    demo_cyclic()
    demo_no_isotopes()


if __name__ == "__main__":
    main()
