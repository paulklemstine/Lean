    for n in range(2, 8):
        r = support(one_loop_cycle(n))
        exp = primitivity_exponent(r, cutoff)
        bound = 2 * (n - 1)
        print(f"    N = {n}:  measured exponent = {exp} <= 2(N-1) = {bound}: {exp is not None and exp <= bound}")
    print()


