"""
Numerical demonstrations of the symmetry dichotomy for attention architectures.

The mathematics being illustrated
---------------------------------
A *sequence* is an n-by-d real table x, with x[i][a] the a-th feature of token i.
A token permutation sigma acts by  (sigma . x)[i] = x[sigma(i)].

A *readout* with weight table w is the linear functional

        R_w(x) = sum_i sum_a w[i][a] * x[i][a],

which is exactly a softmax attention head whose scores are all equal (uniform
attention), up to the factor 1/n absorbed into w.  The *attention algebra* A is
the algebra of real polynomials in readouts: sums model multi-head attention,
products model the multiplicative interaction generated by stacking layers.

The results demonstrated below:

  D1  Uniform-score softmax heads ARE readouts.
  D2  Position-reading barrier: any permutation-invariant model errs by >= 1/2
      when asked to report an absolute coordinate.
  D3  Orbit barrier equality: the optimal invariant error on an orbit is
      EXACTLY half the orbit oscillation, attained by the orbit midpoint.
  D4  Averaging is free: symmetrizing an approximant of an invariant target
      never increases the uniform error (and usually decreases it).
  D5  Symmetric universality: invariant elements of the attention algebra
      approximate an invariant target to any accuracy, with error decreasing
      as the polynomial degree grows.
  D6  Positional repair: the one-hot encoding admits a permutation-INVARIANT
      quadratic decoder that inverts it, so invariant models regain the ability
      to read absolute positions.
  D7  Equivariance = marked invariance: the marked functional of an equivariant
      map is invariant and reproduces the map exactly.

Requires only the Python standard library and NumPy.
"""

from __future__ import annotations

import itertools
from typing import Callable, Iterable, List, Sequence, Tuple

import numpy as np

Array = np.ndarray
Perm = Tuple[int, ...]


# ----------------------------------------------------------------------------
# Core objects: the token action, readouts, softmax heads
# ----------------------------------------------------------------------------

def act(sigma: Perm, x: Array) -> Array:
    """Token action: (sigma . x)[i] = x[sigma(i)].  x has shape (n, d)."""
    return x[list(sigma), :]


def all_perms(n: int) -> List[Perm]:
    """The full symmetric group on {0, ..., n-1}."""
    return list(itertools.permutations(range(n)))


def cyclic_group(n: int) -> List[Perm]:
    """The cyclic shift group generated by i -> i+1 mod n."""
    return [tuple((i + k) % n for i in range(n)) for k in range(n)]


def readout(w: Array, x: Array) -> float:
    """R_w(x) = sum_i sum_a w[i,a] x[i,a]."""
    return float(np.sum(w * x))


def softmax_head(scores: Array, w: Array, x: Array) -> float:
    """A genuine softmax attention head: softmax(scores) . (row-wise w-values)."""
    e = np.exp(scores - np.max(scores))
    alpha = e / np.sum(e)
    values = np.sum(w * x, axis=1)
    return float(np.dot(alpha, values))


def demo_1_heads_are_readouts() -> None:
    print("D1  Uniform-score softmax heads are exactly readouts")
    rng = np.random.default_rng(0)
    n, d = 4, 3
    w = rng.normal(size=(n, d))
    x = rng.normal(size=(n, d))
    lhs = softmax_head(np.zeros(n), w, x)
    rhs = readout(w / n, x)
    print(f"    softmax head with zero scores : {lhs: .10f}")
    print(f"    readout with weights w/n      : {rhs: .10f}")
    print(f"    agree to 1e-12                : {abs(lhs - rhs) < 1e-12}")
    print()


# ----------------------------------------------------------------------------
# D2 / D3: the sharp barrier
# ----------------------------------------------------------------------------

def orbit(group: Sequence[Perm], x: Array) -> List[Array]:
    return [act(s, x) for s in group]


def orbit_barrier(target: Callable[[Array], float],
                  x: Array,
                  group: Sequence[Perm]) -> Tuple[float, float]:
    """Return (optimal invariant error on the orbit of x, optimal model value).

    Theory: an invariant model is constant on the orbit, so the best it can do
    is the midpoint of the range of the target over the orbit, and the error is
    exactly half the oscillation.
    """
    vals = [target(y) for y in orbit(group, x)]
    hi, lo = max(vals), min(vals)
    return (hi - lo) / 2.0, (hi + lo) / 2.0


def demo_2_position_barrier() -> None:
    print("D2  Position-reading barrier: reading token 0 costs at least 1/2")
    n, d = 2, 1
    group = all_perms(n)
    target = lambda y: float(y[0, 0])          # "report the first coordinate"

    # The witness from the proof: the one-hot table u with u[0,0] = 1.
    u = np.zeros((n, d))
    u[0, 0] = 1.0
    err, best = orbit_barrier(target, u, group)
    print(f"    orbit of the one-hot witness : "
          f"{[float(t[0, 0]) for t in orbit(group, u)]}")
    print(f"    best invariant constant      : {best:.4f}")
    print(f"    optimal error                : {err:.4f}   (theory: 0.5)")

    # Brute-force check over a rich family of invariant models: every symmetric
    # polynomial of degree <= 3 in the two coordinates, fitted by least squares.
    grid = np.linspace(-1.0, 1.0, 41)
    pts = np.array([[p, q] for p in grid for q in grid])
    feats = np.stack([
        np.ones(len(pts)),
        pts[:, 0] + pts[:, 1],
        pts[:, 0] * pts[:, 1],
        pts[:, 0] ** 2 + pts[:, 1] ** 2,
        (pts[:, 0] + pts[:, 1]) ** 3,
        pts[:, 0] ** 2 * pts[:, 1] + pts[:, 0] * pts[:, 1] ** 2,
    ], axis=1)                                  # all columns are symmetric
    y = pts[:, 0]                               # target = first coordinate
    coef, *_ = np.linalg.lstsq(feats, y, rcond=None)
    sup_err = float(np.max(np.abs(feats @ coef - y)))
    print(f"    best symmetric cubic fit, sup error on the grid : {sup_err:.4f}")
    print(f"    exceeds the 1/2 barrier                         : {sup_err >= 0.5 - 1e-9}")
    print()


def demo_3_orbit_equality() -> None:
    print("D3  Orbit barrier is an EQUALITY: optimal error = oscillation / 2")
    rng = np.random.default_rng(7)
    n, d = 3, 2
    group = all_perms(n)
    # A deliberately order-sensitive target.
    target = lambda y: float(y[0, 0] + 2.0 * y[1, 1] - y[2, 0] ** 2)

    for trial in range(3):
        x = rng.normal(size=(n, d))
        err, best = orbit_barrier(target, x, group)
        vals = [target(y) for y in orbit(group, x)]
        osc = max(vals) - min(vals)
        # Achievability: the constant midpoint model, evaluated on the orbit.
        attained = max(abs(best - v) for v in vals)
        # Lower bound: no invariant model (i.e. no constant on the orbit) beats it.
        sweep = min(max(abs(c - v) for v in vals)
                    for c in np.linspace(min(vals) - 1, max(vals) + 1, 20001))
        print(f"    trial {trial}: osc/2 = {osc / 2:.6f} | midpoint attains "
              f"{attained:.6f} | best over all constants {sweep:.6f}")
    print("    -> lower bound and achievability coincide.")
    print()


# ----------------------------------------------------------------------------
# D4 / D5: the positive half
# ----------------------------------------------------------------------------

def monomial_exponents(n_feats: int, degree: int) -> List[Tuple[int, ...]]:
    """All exponent vectors of total degree <= `degree` over `n_feats` readouts."""
    out: List[Tuple[int, ...]] = []
    for total in range(degree + 1):
        for combo in itertools.combinations_with_replacement(range(n_feats), total):
            e = [0] * n_feats
            for c in combo:
                e[c] += 1
            out.append(tuple(e))
    return out


def attention_features(x: Array, weights: Sequence[Array],
                       exps: Sequence[Tuple[int, ...]]) -> Array:
    """Evaluate the monomials in the readouts R_{w_1}, ..., R_{w_m} at x.

    Each returned coordinate is an element of the attention algebra.
    """
    base = np.array([readout(w, x) for w in weights])
    return np.array([float(np.prod(base ** np.array(e))) for e in exps])


def symmetrize(model: Callable[[Array], float],
               group: Sequence[Perm]) -> Callable[[Array], float]:
    """Group averaging: S_G f (x) = (1/|G|) sum_g f(g . x)."""
    def averaged(x: Array) -> float:
        return float(np.mean([model(act(s, x)) for s in group]))
    return averaged


def demo_4_averaging_is_free() -> None:
    print("D4  Averaging is free: symmetrizing never hurts on an invariant target")
    rng = np.random.default_rng(3)
    n, d = 3, 2
    group = all_perms(n)
    # An invariant target: a symmetric function of the tokens.
    target = lambda y: float(np.sum(np.sum(y, axis=1) ** 2))

    weights = [rng.normal(size=(n, d)) for _ in range(4)]
    exps = monomial_exponents(len(weights), degree=2)

    # A deliberately ASYMMETRIC fit: train only on unsaturated samples.
    train = [rng.normal(size=(n, d)) for _ in range(400)]
    A = np.stack([attention_features(x, weights, exps) for x in train])
    b = np.array([target(x) for x in train])
    coef, *_ = np.linalg.lstsq(A, b, rcond=None)
    raw = lambda x: float(np.dot(coef, attention_features(x, weights, exps)))
    sym = symmetrize(raw, group)

    test = [rng.normal(size=(n, d)) for _ in range(300)]
    saturated = [act(s, x) for x in test for s in group]
    e_raw = max(abs(raw(x) - target(x)) for x in saturated)
    e_sym = max(abs(sym(x) - target(x)) for x in saturated)
    print(f"    sup error, unsymmetrized model : {e_raw:.6f}")
    print(f"    sup error, symmetrized model   : {e_sym:.6f}")
    print(f"    symmetrization did not hurt    : {e_sym <= e_raw + 1e-9}")
    print(f"    symmetrized model is invariant : "
          f"{max(abs(sym(act(s, test[0])) - sym(test[0])) for s in group) < 1e-9}")
    print()


def demo_5_symmetric_universality() -> None:
    print("D5  Symmetric universality: error shrinks as the algebra degree grows")
    rng = np.random.default_rng(11)
    n, d = 3, 2
    group = all_perms(n)
    # Invariant, genuinely nonlinear target: a multisymmetric power sum mixture.
    def target(y: Array) -> float:
        return float(np.sum(y[:, 0] ** 2 * y[:, 1]) + np.sum(np.tanh(y[:, 1])))

    # Coordinate readouts span all linear functionals; symmetrized monomials in
    # them span the invariant part of the attention algebra degree by degree.
    weights: List[Array] = []
    for i in range(n):
        for a in range(d):
            w = np.zeros((n, d))
            w[i, a] = 1.0
            weights.append(w)

    train = [rng.normal(scale=0.5, size=(n, d)) for _ in range(2000)]
    test = [rng.normal(scale=0.5, size=(n, d)) for _ in range(300)]

    for degree in (1, 2, 3, 4, 5):
        exps = monomial_exponents(len(weights), degree)
        def feats(x: Array, exps: Sequence[Tuple[int, ...]] = exps) -> Array:
            # symmetrized features: average the monomials over the group
            return np.mean([attention_features(act(s, x), weights, exps)
                            for s in group], axis=0)
        A = np.stack([feats(x) for x in train])
        b = np.array([target(x) for x in train])
        # Column rescaling keeps the (badly conditioned) monomial basis usable.
        scale = np.maximum(np.sqrt(np.mean(A ** 2, axis=0)), 1e-12)
        coef, *_ = np.linalg.lstsq(A / scale, b, rcond=1e-10)
        errs = [abs(float(np.dot(coef, feats(x) / scale)) - target(x))
                for x in test]
        rms = float(np.sqrt(np.mean(np.square(errs))))
        print(f"    degree {degree}: #invariant features = {len(exps):4d} | "
              f"sup error = {max(errs):.6f} | rms error = {rms:.6f}")
    print("    -> density of the invariant part of the attention algebra.")
    print()


# ----------------------------------------------------------------------------
# D6: positional encoding and the invariant decoder
# ----------------------------------------------------------------------------

def pos_encode(x: Array) -> Array:
    """One-hot positional encoding: append the indicator of the token's index."""
    n, _ = x.shape
    return np.concatenate([x, np.eye(n)], axis=1)


def invariant_decode(z: Array, n_feats: int) -> Array:
    """dec(z)[i,a] = sum_j z[j, pos(i)] * z[j, feat(a)] -- one attention pattern.

    This is a sum over tokens, hence permutation-invariant, yet it inverts the
    one-hot positional encoding exactly.
    """
    feats = z[:, :n_feats]
    tags = z[:, n_feats:]
    return tags.T @ feats


def demo_6_positional_repair() -> None:
    print("D6  Positional repair: an invariant quadratic decoder inverts the encoding")
    rng = np.random.default_rng(5)
    n, d = 4, 3
    x = rng.normal(size=(n, d))
    z = pos_encode(x)
    print(f"    ||dec(enc(x)) - x||_inf                    : "
          f"{np.max(np.abs(invariant_decode(z, d) - x)):.2e}")
    worst = 0.0
    for s in all_perms(n):
        worst = max(worst, float(np.max(np.abs(
            invariant_decode(act(s, z), d) - invariant_decode(z, d)))))
    print(f"    max change of dec under all n! permutations: {worst:.2e}")
    print("    -> the decoder is exactly permutation-invariant AND inverts enc,")
    print("       so invariant models on encoded input read absolute positions.")

    # Concretely: an invariant model on encoded input recovers x[0,0] exactly,
    # which by D2 is impossible without the encoding.
    read_first = lambda zz: float(invariant_decode(zz, d)[0, 0])
    errs = [abs(read_first(act(s, z)) - x[0, 0]) for s in all_perms(n)]
    print(f"    invariant read of x[0,0] on encoded input, max error over the")
    print(f"    whole orbit: {max(errs):.2e}   (barrier without encoding: 0.5)")
    print()


# ----------------------------------------------------------------------------
# D7: equivariance = marked invariance
# ----------------------------------------------------------------------------

def mark_at(i: int, x: Array) -> Array:
    """Marked-token encoding: append a single feature flagging position i."""
    n, _ = x.shape
    flag = np.zeros((n, 1))
    flag[i, 0] = 1.0
    return np.concatenate([x, flag], axis=1)


def marked_functional(F: Callable[[Array], Array], a: int, z: Array) -> float:
    """G_a(z) = sum_i F(feat(z))[i,a] * mark(z)[i]."""
    feats = z[:, :-1]
    mark = z[:, -1]
    return float(np.dot(F(feats)[:, a], mark))


def demo_7_equivariance_is_marked_invariance() -> None:
    print("D7  Equivariance = invariance, seen through the marked-token window")
    rng = np.random.default_rng(13)
    n, d = 3, 2
    group = all_perms(n)

    # A permutation-equivariant sequence-to-sequence map: each token's output
    # depends on its own features and on order-free statistics of the whole set.
    def F(x: Array) -> Array:
        pooled = np.sum(x, axis=0, keepdims=True)
        return np.tanh(x) + 0.3 * x * pooled

    x = rng.normal(size=(n, d))

    # (a) F really is equivariant.
    eq = max(float(np.max(np.abs(F(act(s, x)) - act(s, F(x))))) for s in group)
    print(f"    equivariance defect of F                : {eq:.2e}")

    # (b) The marked functional is invariant ...
    z = mark_at(1, x)
    inv = max(abs(marked_functional(F, 0, act(s, z)) - marked_functional(F, 0, z))
              for s in group)
    print(f"    invariance defect of the marked functional: {inv:.2e}")

    # (c) ... and reproduces F exactly on marked sequences.
    rep = max(abs(marked_functional(F, a, mark_at(i, x)) - F(x)[i, a])
              for i in range(n) for a in range(d))
    print(f"    ||G_a(mark_i(x)) - F(x)[i,a]||_inf        : {rep:.2e}")

    # (d) The induced head family is EXACTLY equivariant, not approximately.
    head_defect = max(
        abs(marked_functional(F, a, mark_at(i, act(s, x)))
            - marked_functional(F, a, mark_at(s[i], x)))
        for s in group for i in range(n) for a in range(d))
    print(f"    exact equivariance of the head family     : {head_defect:.2e}")
    print()


# ----------------------------------------------------------------------------
# Bonus: the cyclic (relative-encoding) regime inherits the same barrier
# ----------------------------------------------------------------------------

def demo_8_relative_encoding_barrier() -> None:
    print("D8  Relative (cyclic) symmetry inherits the 1/2 absolute-position barrier")
    n, d = 5, 1
    group = cyclic_group(n)
    u = np.zeros((n, d))
    u[0, 0] = 1.0
    target = lambda y: float(y[0, 0])
    err, best = orbit_barrier(target, u, group)
    print(f"    cyclic orbit values of 'read token 0' : "
          f"{[float(t[0, 0]) for t in orbit(group, u)]}")
    print(f"    optimal shift-invariant error         : {err:.4f}  (theory: 0.5)")

    # But a SHIFT-INVARIANT target is approximated perfectly by a shift-invariant
    # model: the barrier is exactly the failure of invariance, nothing more.
    rng = np.random.default_rng(21)
    x = rng.normal(size=(n, d))
    shift_inv_target = lambda y: float(np.sum(y[:, 0] * np.roll(y[:, 0], 1)))
    err2, _ = orbit_barrier(shift_inv_target, x, group)
    print(f"    optimal error for a shift-INVARIANT target: {err2:.2e}")
    print()


