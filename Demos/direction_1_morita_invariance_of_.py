def green_j_classes(elements, mult):
    """
    Compute approximate J-equivalence classes for a finite monoid.

    Two elements a, b are J-equivalent if MaM = MbM (same principal
    two-sided ideal).
    """
    n = len(elements)

    def ideal(a):
        """Compute the two-sided ideal MaM."""
        result = set()
        for m1 in elements:
            for m2 in elements:
                result.add(mult[(m1, mult[(a, m2)])])
        return frozenset(result)

    # Group by ideal
    classes = defaultdict(list)
    for a in elements:
        classes[ideal(a)].append(a)

    return dict(classes)


