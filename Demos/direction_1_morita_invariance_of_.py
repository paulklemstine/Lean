# Probe complexity computation
# ─────────────────────────────────────────────────────────────────

def has_nontrivial_parallel_morphisms(cat):
    """Check if there exist distinct parallel morphisms."""
    for (X, Y), morphisms in cat.hom.items():
        if len(morphisms) > 1:
            return True
    return False


def probe_family_separates(cat, probe_set):
    """Check if a set of probe objects separates all parallel morphisms."""
    for (X, Y), morphisms in cat.hom.items():
        for i, f in enumerate(morphisms):
            for g in morphisms[i+1:]:
                # Check if probes separate f from g
                separated = False
                for Z in probe_set:
                    for h in cat.hom.get((Z, X), []):
                        hf = cat.comp.get((h, f))
                        hg = cat.comp.get((h, g))
                        if hf != hg:
                            separated = True
                            break
                    if separated:
                        break
                if not separated:
                    return False
    return True


def compute_kappa(cat):
    """
    Compute κ(C) = minimum cardinality of a separating probe family.

    Uses brute-force search over all subsets of objects, starting from
    smallest cardinality.
    """
    if not has_nontrivial_parallel_morphisms(cat):
        return 0

    objects = cat.objects
    n = len(objects)

    # Try subsets of increasing size
    for size in range(1, n + 1):
        # Generate all subsets of given size
        for subset in _subsets_of_size(objects, size):
            if probe_family_separates(cat, subset):
                return size

    return n  # Total family always works


def _subsets_of_size(lst, k):
    """Generate all subsets of size k from lst."""
    if k == 0:
        yield []
        return
    if k > len(lst):
        return
    for i in range(len(lst)):
        for rest in _subsets_of_size(lst[i+1:], k - 1):
            yield [lst[i]] + rest


