"""
Demonstration: Morita Invariance of Probe Complexity (κ)

This script constructs explicit finite categories, computes their Karoubi
envelopes (idempotent completions), and verifies that probe complexity κ
is preserved — illustrating the formally verified theorem κ(C) = κ(Kar(C)).

Examples include:
  1. A two-object discrete category (control case, κ = 0)
  2. A monoid with a nontrivial idempotent
  3. A two-object category with nontrivial hom-sets
  4. A poset category (thin, κ = 0)
"""

from itertools import product
from collections import defaultdict


# ─────────────────────────────────────────────────────────────────
# Core data structures
# ─────────────────────────────────────────────────────────────────

class FiniteCategory:
    """
    A finite category specified by:
      - objects: list of object names
      - hom: dict mapping (X, Y) -> list of morphism names
      - comp: dict mapping (f, g) -> h for composable pairs
      - identity: dict mapping X -> id_X
    """
    def __init__(self, name, objects, hom, comp, identity):
        self.name = name
        self.objects = objects
        self.hom = hom  # (X,Y) -> [f1, f2, ...]
        self.comp = comp  # (f, g) -> h  where f: X->Y, g: Y->Z
        self.identity = identity  # X -> id_X

    def __repr__(self):
        n_obj = len(self.objects)
        n_mor = sum(len(v) for v in self.hom.values())
        return f"Category({self.name}, {n_obj} objects, {n_mor} morphisms)"


class KaroubiObject:
    """An object (X, p) of the Karoubi envelope where p : X -> X is idempotent."""
    def __init__(self, X, p):
        self.X = X
        self.p = p

    def __repr__(self):
        return f"({self.X}, {self.p})"

    def __eq__(self, other):
        return self.X == other.X and self.p == other.p

    def __hash__(self):
        return hash((self.X, self.p))


# ─────────────────────────────────────────────────────────────────
# Karoubi envelope construction
# ─────────────────────────────────────────────────────────────────

def find_idempotents(cat):
    """Find all idempotent endomorphisms p : X -> X with p ∘ p = p."""
    idempotents = {}  # X -> list of idempotent morphisms
    for X in cat.objects:
        idemps = []
        for p in cat.hom.get((X, X), []):
            if cat.comp.get((p, p)) == p:
                idemps.append(p)
        idempotents[X] = idemps
    return idempotents


def build_karoubi_envelope(cat):
    """
    Construct the Karoubi envelope Kar(C).

    Objects: pairs (X, p) where p : X -> X is idempotent.
    Morphisms (X,p) -> (Y,q): morphisms f : X -> Y with p ∘ f ∘ q = f,
        equivalently p ∘ f = f and f ∘ q = f.
    """
    idempotents = find_idempotents(cat)

    # Objects of Kar(C)
    kar_objects = []
    for X in cat.objects:
        for p in idempotents[X]:
            kar_objects.append(KaroubiObject(X, p))

    # Morphisms of Kar(C)
    kar_hom = {}
    for obj_s in kar_objects:
        for obj_t in kar_objects:
            morphisms = []
            for f in cat.hom.get((obj_s.X, obj_t.X), []):
                # Check: p ∘ f ∘ q = f
                pf = cat.comp.get((obj_s.p, f))
                if pf is not None:
                    pfq = cat.comp.get((pf, obj_t.p))
                    if pfq == f:
                        morphisms.append(f)
            kar_hom[(repr(obj_s), repr(obj_t))] = morphisms

    # Build composition table
    kar_comp = {}
    for obj_a in kar_objects:
        for obj_b in kar_objects:
            for obj_c in kar_objects:
                for f in kar_hom.get((repr(obj_a), repr(obj_b)), []):
                    for g in kar_hom.get((repr(obj_b), repr(obj_c)), []):
                        fg = cat.comp.get((f, g))
                        if fg is not None:
                            kar_comp[(f, g)] = fg

    # Build identity table (identity on (X,p) is p itself)
    kar_identity = {}
    for obj in kar_objects:
        kar_identity[repr(obj)] = obj.p

    kar_obj_names = [repr(o) for o in kar_objects]
    return FiniteCategory(
        name=f"Kar({cat.name})",
        objects=kar_obj_names,
        hom=kar_hom,
        comp=kar_comp,
        identity=kar_identity
    ), kar_objects


