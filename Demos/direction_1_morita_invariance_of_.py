class DeterministicAutomaton:
    """
    A deterministic finite automaton (DFA) viewed as a category.

    States are objects, and for each input symbol a, the transition
    δ(s, a) gives a morphism. The category has one morphism per
    word in the free monoid on the alphabet (up to identification
    by the transition function).
    """
    def __init__(self, name: str, states: List[str],
                 alphabet: List[str],
                 transitions: Dict[Tuple[str, str], str]):
        """
        Args:
            name: Name of the automaton
            states: List of state names
            alphabet: List of input symbols
            transitions: Maps (state, symbol) to next state
        """
        self.name = name
        self.states = states
        self.alphabet = alphabet
        self.transitions = transitions

    def transition_monoid_category(self):
        """
        Convert to the transition monoid viewed as a one-object category.

        Each element of the transition monoid is a function States → States
        induced by a word. We compute the monoid generated by the
        individual symbol transitions.
        """
        n = len(self.states)
        state_idx = {s: i for i, s in enumerate(self.states)}

        # Each symbol induces a function on states
        def symbol_func(a):
            return tuple(state_idx[self.transitions[(s, a)]]
                         for s in self.states)

        # Generate monoid by closure under composition
        identity = tuple(range(n))
        elements = {identity}
        generators = [symbol_func(a) for a in self.alphabet]

        queue = list(generators)
        for g in generators:
            elements.add(g)

        while queue:
            f = queue.pop(0)
            for g in list(elements):
                # Compose f then g
                fg = tuple(g[f[i]] for i in range(n))
                if fg not in elements:
                    elements.add(fg)
                    queue.append(fg)
                # Compose g then f
                gf = tuple(f[g[i]] for i in range(n))
                if gf not in elements:
                    elements.add(gf)
                    queue.append(gf)

        # Build multiplication table
        elem_list = sorted(elements)
        elem_names = {e: f"m{i}" for i, e in enumerate(elem_list)}
        elem_names[identity] = "id"

        mult = {}
        for f in elem_list:
            for g in elem_list:
                fg = tuple(g[f[i]] for i in range(n))
                mult[(elem_names[f], elem_names[g])] = elem_names[fg]

        return {
            'name': f"TransMon({self.name})",
            'elements': [elem_names[e] for e in elem_list],
            'multiplication': mult,
            'identity': "id",
            'size': len(elements),
            'generators': {a: elem_names[symbol_func(a)] for a in self.alphabet},
        }

    def observational_complexity(self):
        """
        Compute the observational complexity = κ of the transition monoid.

        This measures how many "test inputs" are needed to distinguish
        all state transformations.
        """
        mon = self.transition_monoid_category()
        elements = mon['elements']
        mult = mon['multiplication']

        # κ for a one-object category with monoid M:
        # A probe family is just {⋆} or ∅.
        # If |M| > 1, κ = 1 (the single object probes via identity).
        # If |M| = 1, κ = 0.

        if len(elements) <= 1:
            return 0
        return 1


