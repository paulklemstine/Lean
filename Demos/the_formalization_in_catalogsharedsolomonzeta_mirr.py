def demo_fundamental_identity() -> None:
    banner("1.  #Surj(M, X) = sum_{Y <= X} mu(Y, X) #Hom(M, Y)")
    cases = [
        ((0, 0), [2, 2], "M = Z^2,      X = (Z/2)^2"),
        ((0,), [4], "M = Z,        X = Z/4"),
        ((0, 0), [2, 4], "M = Z^2,      X = Z/2 x Z/4"),
        ((2, 4), [2, 2], "M = Z/2 x Z/4, X = (Z/2)^2"),
        ((0, 0, 0), [3, 3], "M = Z^3,      X = (Z/3)^2"),
    ]
    print(f"{'case':<24}{'Moebius weight':>16}{'#Surj':>10}{'match':>8}")
    for src, dst, label in cases:
        w = moebius_weight(src, dst)
        s = sum(1 for f in homs(src, dst, frozenset(elements(dst))) if is_surjective(dst, f, frozenset(elements(dst))))
        print(f"{label:<24}{w:>16}{s:>10}{'  OK' if w == s else '  FAIL':>8}")
        assert w == s


def demo_hall_formula() -> None:
    banner("2.  Hall's formula:  #Aut(X) * #{N <= Z^n : Z^n/N =~ X} = "
           "(prod_{i<d}(p^n - p^i)) |pX|^n")
    print(f"{'p':>3}{'lambda':>12}{'n':>4}{'#Aut(X)':>10}{'#Surj (brute)':>16}"
          f"{'formula':>12}{'#sublattices':>14}")
    for p, lam, n in [
        (2, (1,), 1), (2, (1,), 2), (2, (1, 1), 2), (2, (2,), 2),
        (2, (2, 1), 2), (3, (1,), 2), (3, (1, 1), 2), (2, (1, 1), 3),
    ]:
        mods = [p ** a for a in lam]
        brute = count_surj([0] * n, mods)
        d, card_pX = p_group_data(p, lam)
        formula = free_weight_local(p, n, d, card_pX)
        A, count = quotient_count(p, lam, n)
        assert brute == formula
        print(f"{p:>3}{str(lam):>12}{n:>4}{A:>10}{brute:>16}{formula:>12}{count:>14}")
    print("\nEvery brute-force surjection count agrees with the closed formula,")
    print("and the number of sublattices is the quotient by #Aut(X).")


def demo_gaussian_binomial() -> None:
    banner("3.  Elementary abelian quotients: the Gaussian binomial")
    print("#{N <= Z^n : Z^n/N =~ (Z/p)^d} = (prod_{i<d}(p^n - p^i)) / |GL_d(F_p)|")
    print(f"{'p':>3}{'n':>4}{'d':>4}{'#GL_d(F_p)':>14}{'#Surj':>10}{'count':>8}"
          f"{'Gaussian binom.':>18}")
    for p, n, d in [(2, 2, 1), (2, 2, 2), (2, 3, 2), (3, 3, 2), (2, 4, 3)]:
        gl = 1
        for i in range(d):
            gl *= p ** d - p ** i
        surj = free_weight_local(p, n, d, 1)
        count = surj // gl
        # Gaussian binomial [n choose d]_p
        num, den = 1, 1
        for i in range(d):
            num *= p ** (n - i) - 1
            den *= p ** (d - i) - 1
        gauss = num // den
        assert count == gauss
        print(f"{p:>3}{n:>4}{d:>4}{gl:>14}{surj:>10}{count:>8}{gauss:>18}")


def demo_group_ring() -> None:
    banner("4.  The order Lambda = Z_p[Z/pZ] is local: the free Solomon coefficients")
    p, e = 2, 2
    ring = lam_elements(p, e)
    print(f"working in Lambda_e = (Z/{p**e})[x]/(x^{p} - 1),  |Lambda_e| = {len(ring)}")
    print("(a finite quotient of Z_p[Z/pZ]; the maximal ideal is the set of")
    print(" elements whose coefficient sum is divisible by p)")
    zero = tuple(0 for _ in range(p))
    x_minus_1 = tuple([-1 % (p ** e), 1] + [0] * (p - 2))
    ideals = {
        "0        (X = Lambda)": frozenset({zero}),
        "(x-1)    (X = Lambda/(x-1))": lam_submodule_generated(p, e, [x_minus_1]),
        "(p, x-1) (X = residue field F_p)": lam_submodule_generated(
            p, e, [tuple([p] + [0] * (p - 1)), x_minus_1]),
    }
    print()
    print(f"{'quotient type X':<36}{'|X|':>6}{'d':>4}{'|mX|':>7}{'n':>4}"
          f"{'#Surj':>9}{'formula':>10}")
    for label, I in ideals.items():
        d, card_mX, reps = lam_quotient_data(p, e, I)
        for n in (1, 2):
            brute = lam_count_surj_onto_quotient(p, e, I, n)
            formula = free_weight_local(p, n, d, card_mX)
            assert brute == formula, (label, n, brute, formula)
            print(f"{label:<36}{len(reps):>6}{d:>4}{card_mX:>7}{n:>4}"
                  f"{brute:>9}{formula:>10}")
    print("\nThe same closed formula as over the maximal order Z_p, although")
    print("Lambda is not maximal and (for p > 1) not even a domain.")


def demo_direct_sums() -> None:
    banner("5.  Hom-counts are multiplicative along direct sums")
    print(f"{'M1':>10}{'M2':>10}{'Y':>14}{'#Hom(M1+M2,Y)':>16}"
          f"{'#Hom(M1,Y)*#Hom(M2,Y)':>24}")
    for m1, m2, Ymods in [((2,), (4,), [4]), ((0,), (2,), [2, 2]), ((3,), (9,), [9])]:
        full = frozenset(elements(Ymods))
        both = count_hom(tuple(list(m1) + list(m2)), Ymods, full)
        prod = count_hom(m1, Ymods, full) * count_hom(m2, Ymods, full)
        assert both == prod
        print(f"{str(m1):>10}{str(m2):>10}{str(Ymods):>14}{both:>16}{prod:>24}")
    print("\nConsequently the Moebius weight of M depends on M only through the")
    print("function Y -> #Hom(M, Y) on the submodule lattice of X.")


def demo_freeness_criterion() -> None:
    banner("6.  Moebius weights detect freeness -- and one test space is not enough")
    p, n = 2, 1
    print("Over Z_p, compare the free lattice Z_p (rank 1) with M = F_p = Z/p.")
    print("Finite quotient types of Z_p-modules are finite abelian p-groups, and")
    print("Hom(Z_p, Y) = Y, so the weight of Z_p at X is #Surj(Z, X).\n")
    print(f"{'X':<18}{'d':>3}{'|pX|':>7}{'free weight':>14}"
          f"{'weight of Z/p':>16}{'equal?':>9}")
    tests = [[2], [4], [2, 2], [2, 4]]
    for Xmods in tests:
        lam = []
        for m in Xmods:
            k = 0
            while p ** (k + 1) <= m:
                k += 1
            lam.append(k)
        d, card_pX = p_group_data(p, tuple(lam))
        free_w = free_weight_local(p, n, d, card_pX)
        w_M = moebius_weight((p,), Xmods)
        print(f"{str(Xmods):<18}{d:>3}{card_pX:>7}{free_w:>14}{w_M:>16}"
              f"{('yes' if free_w == w_M else 'NO'):>9}")
    print()
    print("At the single residual test space X = (Z/p)^2 both weights vanish:")
    print(f"  free weight of rank 1 at (Z/p)^2 = {free_weight_local(p, 1, 2, 1)}")
    print(f"  weight of Z/p at (Z/p)^2         = {moebius_weight((p,), [p, p])}")
    print("so that space alone cannot separate Z/p from the free lattice Z_p.")
    print("The space X = Z/p^2 does:  free weight "
          f"{free_weight_local(p, 1, 1, p)} vs weight {moebius_weight((p,), [p * p])}.")
    print("\nThis is exactly the sharpness statement: the whole family of finite")
    print("quotient types is needed, but the family does characterise freeness.")


def demo_zeta_series() -> None:
    banner("7.  The Solomon zeta function of Z_p^n (first terms)")
    p, N = 2, 4
    print(f"zeta_{{Z_{p}^n}}(s) = sum_{{k>=0}} a_k(n) {p}^{{-ks}},  "
          f"a_k(n) = #{{N <= Z_p^n : index {p}^k}}")
    print("computed as sum over partitions lambda of k of Hall's counts:")
    print(f"{'n':>3}" + "".join(f"{'a_' + str(k):>10}" for k in range(N + 1))
          + f"{'  Euler product check':>24}")
    for n in (1, 2, 3):
        coeffs = []
        for k in range(N + 1):
            total = 0
            for lam in partitions(k):
                if len(lam) > n:
                    continue
                A, cnt = quotient_count(p, tuple(lam), n)
                total += cnt
            coeffs.append(total)
        # Euler product prediction: prod_{i=0}^{n-1} 1/(1 - p^i T)
        pred = [0] * (N + 1)
        pred[0] = 1
        series = [1] + [0] * N
        for i in range(n):
            new = [0] * (N + 1)
            for k in range(N + 1):
                acc = 0
                j = 0
                while j <= k:
                    acc += series[k - j] * (p ** i) ** j
                    j += 1
                new[k] = acc
            series = new
        ok = all(coeffs[k] == series[k] for k in range(N + 1))
        print(f"{n:>3}" + "".join(f"{c:>10}" for c in coeffs)
              + f"{('  matches prod 1/(1-p^i T)' if ok else '  MISMATCH'):>24}")
        assert ok


def partitions(k: int, maxpart: int | None = None) -> List[List[int]]:
    """All partitions of k as weakly decreasing lists (empty list for k = 0)."""
    if maxpart is None:
        maxpart = k
    if k == 0:
        return [[]]
    out: List[List[int]] = []
    for first in range(min(k, maxpart), 0, -1):
        for rest in partitions(k - first, first):
            out.append([first] + rest)
    return out


