"""
Solomon zeta coefficients over arithmetic orders: numerical demonstrations.
==========================================================================

This self-contained script illustrates, by explicit enumeration on small
examples, the results of the accompanying paper:

  (1)  The fundamental counting identity

           #Aut(X) * #{ N <= M : M/N =~ X }  =  #Surj(M, X)
                                             =  sum_{Y <= X} mu(Y, X) * #Hom(M, Y),

       where mu is the Moebius function of the submodule lattice of X.

  (2)  Hall's formula over Z (equivalently over Z_p): for a finite abelian
       p-group X of type lambda with d = #parts(lambda),

           #Surj(Z^n, X) = (prod_{i<d} (p^n - p^i)) * |pX|^n .

  (3)  The local formula over a commutative local ring R with residue field
       of size q:

           #Surj(R^n, X) = (prod_{i<d} (q^n - q^i)) * |mX|^n,
           d = dim_k X/mX,

       verified for R = Z_p (via its finite quotients) and for the *group
       ring* order Lambda = Z_p[Z/pZ] (via its finite quotients
       (Z/p^e)[x]/(x^p - 1)), which is a local ring with residue field F_p
       even though it is neither maximal nor a domain.

  (4)  Multiplicativity of Hom-counts along direct sums, hence the
       dependence of the Moebius weight on M only through Y -> #Hom(M, Y).

  (5)  The Moebius-weight characterisation of freeness, and the explicit
       counterexample showing that a single test space of residual
       dimension n+1 does not suffice.

Everything is computed by brute-force enumeration on small objects; no
external libraries are required.
"""

from __future__ import annotations

from functools import lru_cache
from itertools import product
from typing import Dict, FrozenSet, Iterable, List, Sequence, Tuple

Elt = Tuple[int, ...]  # element of a finite abelian group  prod_i Z/m_i


# ----------------------------------------------------------------------
# 1. Finite abelian groups  A = prod_i Z/m_i
# ----------------------------------------------------------------------


def elements(mods: Sequence[int]) -> List[Elt]:
    """All elements of prod_i Z/mods[i]."""
    return [tuple(t) for t in product(*[range(m) for m in mods])]


def add(mods: Sequence[int], a: Elt, b: Elt) -> Elt:
    return tuple((x + y) % m for x, y, m in zip(a, b, mods))


def smul(mods: Sequence[int], c: int, a: Elt) -> Elt:
    return tuple((c * x) % m for x, m in zip(a, mods))


def subgroup_generated(mods: Sequence[int], gens: Iterable[Elt]) -> FrozenSet[Elt]:
    """The subgroup of prod Z/m_i generated by `gens` (closure under addition)."""
    zero: Elt = tuple(0 for _ in mods)
    seen = {zero}
    frontier = [zero]
    gens = list(gens)
    while frontier:
        cur = frontier.pop()
        for g in gens:
            nxt = add(mods, cur, g)
            if nxt not in seen:
                seen.add(nxt)
                frontier.append(nxt)
    return frozenset(seen)


def all_subgroups(mods: Sequence[int]) -> List[FrozenSet[Elt]]:
    """Every subgroup of prod_i Z/m_i, found by saturating generating sets."""
    zero: Elt = tuple(0 for _ in mods)
    found = {frozenset({zero})}
    frontier = [frozenset({zero})]
    els = elements(mods)
    while frontier:
        H = frontier.pop()
        for g in els:
            if g in H:
                continue
            K = subgroup_generated(mods, list(H) + [g])
            if K not in found:
                found.add(K)
                frontier.append(K)
    return sorted(found, key=lambda H: (len(H), sorted(H)))


def moebius_lattice(subs: List[FrozenSet[Elt]]) -> Dict[Tuple[int, int], int]:
    """Moebius function mu(Y, Z) of the subgroup lattice, indexed by positions."""
    order = sorted(range(len(subs)), key=lambda i: len(subs[i]))
    mu: Dict[Tuple[int, int], int] = {}
    for zi in order:
        Z = subs[zi]
        for yi in order:
            Y = subs[yi]
            if not Y <= Z:
                continue
            if Y == Z:
                mu[(yi, zi)] = 1
            else:
                mu[(yi, zi)] = -sum(
                    mu[(yi, wi)]
                    for wi in range(len(subs))
                    if Y <= subs[wi] < Z and (yi, wi) in mu
                )
    return mu


# ----------------------------------------------------------------------
# 2. Hom- and surjection-counts between finite abelian groups
# ----------------------------------------------------------------------


def homs(src: Sequence[int], dst_mods: Sequence[int], dst: FrozenSet[Elt]) -> List[Tuple[Elt, ...]]:
    """
    All homomorphisms prod_i Z/src[i] -> (subgroup `dst` of prod Z/dst_mods).

    A hom is the tuple of images of the standard generators e_i; the only
    constraint is src[i] * image(e_i) = 0.  Use src[i] = 0 for a free factor Z.
    """
    choices = []
    for m in src:
        ok = [y for y in dst if m == 0 or smul(dst_mods, m, y) == tuple(0 for _ in dst_mods)]
        choices.append(ok)
    return [tuple(t) for t in product(*choices)]


def is_surjective(mods: Sequence[int], images: Sequence[Elt], target: FrozenSet[Elt]) -> bool:
    return subgroup_generated(mods, images) == target


def count_hom(src: Sequence[int], dst_mods: Sequence[int], dst: FrozenSet[Elt]) -> int:
    return len(homs(src, dst_mods, dst))


def count_surj(src: Sequence[int], dst_mods: Sequence[int]) -> int:
    full = frozenset(elements(dst_mods))
    return sum(1 for f in homs(src, dst_mods, full) if is_surjective(dst_mods, f, full))


def aut_card(mods: Sequence[int]) -> int:
    """|Aut(X)| for X = prod Z/mods[i] (brute force: surjective endomorphisms)."""
    return count_surj(mods, mods)


# ----------------------------------------------------------------------
# 3. The fundamental identity and Hall's formula
# ----------------------------------------------------------------------


def moebius_weight(src: Sequence[int], dst_mods: Sequence[int]) -> int:
    """sum_{Y <= X} mu(Y, X) * #Hom(M, Y) for M = prod Z/src[i], X = prod Z/dst_mods."""
    subs = all_subgroups(dst_mods)
    mu = moebius_lattice(subs)
    top = len(subs) - 1
    assert subs[top] == frozenset(elements(dst_mods))
    return sum(mu[(yi, top)] * count_hom(src, dst_mods, subs[yi]) for yi in range(len(subs)) if (yi, top) in mu)


def free_weight_local(q: int, n: int, d: int, card_mX: int) -> int:
    """(prod_{i<d} (q^n - q^i)) * |mX|^n."""
    prod = 1
    for i in range(d):
        prod *= q ** n - q ** i
    return prod * card_mX ** n


def p_group_data(p: int, lam: Sequence[int]) -> Tuple[int, int]:
    """For X of type lambda: (d, |pX|) with d = #parts, |pX| = p^(|lam| - d)."""
    d = len(lam)
    return d, p ** (sum(lam) - d)


def quotient_count(p: int, lam: Sequence[int], n: int) -> Tuple[int, int]:
    """
    Return (#Aut(X), #{N <= Z^n : Z^n/N =~ X}) for X of type lambda,
    the second entry computed from Hall's formula.
    """
    mods = [p ** a for a in lam]
    A = aut_card(mods)
    d, card_pX = p_group_data(p, lam)
    surj = free_weight_local(p, n, d, card_pX)
    assert surj % A == 0
    return A, surj // A


# ----------------------------------------------------------------------
# 4. The order Lambda_e = (Z/p^e)[x]/(x^p - 1), a finite quotient of Z_p[Z/pZ]
# ----------------------------------------------------------------------

LElt = Tuple[int, ...]  # coefficient vector of length p, entries mod p^e


def lam_elements(p: int, e: int) -> List[LElt]:
    return [tuple(t) for t in product(range(p ** e), repeat=p)]


def lam_add(p: int, e: int, a: LElt, b: LElt) -> LElt:
    m = p ** e
    return tuple((x + y) % m for x, y in zip(a, b))


def lam_mul(p: int, e: int, a: LElt, b: LElt) -> LElt:
    """Cyclic convolution: multiplication in (Z/p^e)[x]/(x^p - 1)."""
    m = p ** e
    out = [0] * p
    for i, ai in enumerate(a):
        if ai == 0:
            continue
        for j, bj in enumerate(b):
            out[(i + j) % p] = (out[(i + j) % p] + ai * bj) % m
    return tuple(out)


def lam_in_maximal(p: int, a: LElt) -> bool:
    """The maximal ideal of Lambda is the preimage of pZ_p under the augmentation."""
    return sum(a) % p == 0


def lam_submodule_generated(p: int, e: int, gens: Iterable[LElt]) -> FrozenSet[LElt]:
    """Lambda-submodule of Lambda^1 (i.e. ideal) generated by `gens`."""
    ring = lam_elements(p, e)
    zero = tuple(0 for _ in range(p))
    seen = {zero}
    frontier = [zero]
    gens = list(gens)
    while frontier:
        cur = frontier.pop()
        for g in gens:
            for r in ring:
                nxt = lam_add(p, e, cur, lam_mul(p, e, r, g))
                if nxt not in seen:
                    seen.add(nxt)
                    frontier.append(nxt)
    return frozenset(seen)


def lam_quotient_data(p: int, e: int, I: FrozenSet[LElt]) -> Tuple[int, int, List[LElt]]:
    """
    For X = Lambda/I return (d, |mX|, coset representatives), with
    d = dim_{F_p} X/mX and mX the image of the maximal ideal.
    """
    ring = lam_elements(p, e)
    # canonical representative of a coset: the lexicographically smallest element
    rep: Dict[LElt, LElt] = {}
    for a in ring:
        coset = frozenset(lam_add(p, e, a, i) for i in I)
        rep[a] = min(coset)
    reps = sorted(set(rep.values()))
    # mX = image of the maximal ideal m of Lambda
    max_ideal = [a for a in ring if lam_in_maximal(p, a)]
    mX = set()
    for a in max_ideal:
        mX.add(rep[a])
    card_X = len(reps)
    card_mX = len(mX)
    # X/mX is an F_p-vector space of size card_X / card_mX
    quot = card_X // card_mX
    d = 0
    while p ** d < quot:
        d += 1
    assert p ** d == quot
    return d, card_mX, reps


def lam_count_surj_onto_quotient(p: int, e: int, I: FrozenSet[LElt], n: int) -> int:
    """
    #Surj(Lambda^n, Lambda/I): a hom is an n-tuple of elements of Lambda/I, and
    it is onto iff the corresponding elements generate Lambda/I over Lambda,
    i.e. iff the ideal they generate together with I is all of Lambda.
    """
    ring = lam_elements(p, e)
    rep: Dict[LElt, LElt] = {}
    for a in ring:
        rep[a] = min(frozenset(lam_add(p, e, a, i) for i in I))
    reps = sorted(set(rep.values()))
    total = 0
    for tup in product(reps, repeat=n):
        gen = lam_submodule_generated(p, e, list(tup) + list(I))
        if len(gen) == len(ring):
            total += 1
    return total


