def demo_embedding() -> None:
    print("=" * 78)
    print("1.  The exact embedding: a semiprime is a Pythagorean tree node")
    print("=" * 78)
    for p, q in [(3, 5), (7, 11), (13, 101), (65537, 1299709)]:
        node = fermat_pair(p, q)
        N = p * q
        tri = pythagorean_triple(node)
        assert n_of(node) == N and is_fermat_pair(node)
        addr = address(node)
        assert eval_word(addr) == node
        shown = "".join(addr) if len(addr) <= 40 else "".join(addr[:37]) + "..."
        print(f"  N = {p} * {q} = {N}")
        print(f"      node (m,n) = {node}   triple = {tri}")
        print(f"      depth = {len(addr):<6d} address (node->root) = {shown}")
    print()


def demo_skeleton(trials: int = 20000, seed: int = 20260916) -> None:
    print("=" * 78)
    print("2.  The skeleton theorem, and its identity with the trace")
    print("=" * 78)
    print("    N = 1 (mod 3) <=> 3|n ;  N = 2 (mod 3) <=> 3|m ;  N = 0 <=> 3 divides neither")
    rng = random.Random(seed)
    ok = 0
    for _ in range(trials):
        m = rng.randrange(2, 10**6)
        n = rng.randrange(1, m)
        if math.gcd(m, n) != 1:
            continue
        r = n_of((m, n)) % 3
        good = (
            (r == 1) == (n % 3 == 0)
            and (r == 2) == (m % 3 == 0)
            and (r == 0) == (m % 3 != 0 and n % 3 != 0)
        )
        assert good
        ok += 1
    print(f"    coprime pairs tested: {ok}/{ok} in agreement (100%)")

    rng = random.Random(seed + 1)
    checked = 0
    for _ in range(400):
        p, q = random_semiprime(16, 24, rng)
        m, n = fermat_pair(p, q)
        N = p * q
        assert (n % 3 == 0) == (p % 3 == q % 3)
        assert (N % 3 == 1) == (n % 3 == 0)
        assert (N % 3 == 1) == (p % 3 == q % 3 and p % 3 != 0)
        checked += 1
    print(f"    semiprimes tested:    {checked}/{checked}   3|n  <=>  p = q (mod 3)  <=>  N = 1 (mod 3)")
    print("    => the skeleton channel restates N mod 3 exactly; zero extra information.")
    print()


def demo_parent_law(trials: int = 400, seed: int = 4242) -> None:
    print("=" * 78)
    print("3.  The parent-interval law and exactness of the descent")
    print("=" * 78)
    rng = random.Random(seed)
    steps = 0
    for _ in range(trials):
        p, q = random_semiprime(10, 16, rng)
        cur = fermat_pair(p, q)
        while cur != ROOT:
            g, par = letter_of(cur), parent_pair(cur)
            assert apply_gen(g, par) == cur, "parent-interval law failed"
            assert is_fermat_pair(par) or par == ROOT
            assert sum(par) < sum(cur), "descent must strictly decrease m+n"
            cur = par
            steps += 1
    print(f"    {trials}/{trials} descents terminated exactly at the root (2,1)")
    print(f"    {steps} descent steps verified: band-decided parent + child-map reconstruction exact")
    print("    (the ratio m/n alone decides the step: (1,2)->A, (2,3)->B, (3,oo)->C)")
    print()


def demo_letter_is_balance(trials: int = 3000, seed: int = 99) -> None:
    print("=" * 78)
    print("4.  The first letter IS the balance band of the factorisation")
    print("=" * 78)
    print("    A <=> q > 3p     B <=> 2p < q <= 3p     C <=> q <= 2p")
    rng = random.Random(seed)
    tally: Counter = Counter()
    for _ in range(trials):
        p, q = random_semiprime(10, 20, rng)
        L = letter_of(fermat_pair(p, q))
        expect = "A" if q > 3 * p else ("B" if 2 * p < q <= 3 * p else "C")
        assert L == expect, (p, q, L, expect)
        tally[L] += 1
    print(f"    {trials}/{trials} semiprimes agree.  Observed letters: "
          f"A={tally['A']}  B={tally['B']}  C={tally['C']}")
    print("    Reading this letter would reveal how balanced the factorisation is")
    print("    -- exactly what governs whether Fermat-style search is cheap.")
    print()


def demo_seal(moduli: Optional[List[int]] = None) -> None:
    print("=" * 78)
    print("5.  The seal: all three letters inside ONE residue class of N")
    print("=" * 78)
    if moduli is None:
        moduli = [3, 9, 27, 81, 243, 729, 2187, 5, 7, 101]
    print("    odd witnesses  (M+1,M), (3M-1,M), (3M+1,M):")
    for M in moduli:
        w = witnesses_odd(M)
        assert all(is_fermat_pair(v) for v in w.values())
        assert all(letter_of(v) == k for k, v in w.items())
        res = {n_of(v) % M for v in w.values()}
        assert res == {1 % M}
        print(f"      M = {M:<6d} N mod M = {res.pop():<3d} for letters A, B, C  -> sealed")

    print("    proper witnesses (4M-1,2M), (4M+1,2M), (6M+1,2M) — every M >= 2, nontrivial factors:")
    for M in [2, 3, 4, 9, 10, 27, 81, 1000]:
        w = witnesses_proper(M)
        assert all(is_fermat_pair(v) for v in w.values())
        assert all(letter_of(v) == k for k, v in w.items())
        assert {n_of(v) % M for v in w.values()} == {1 % M}
        facs = {k: (v[0] - v[1], v[0] + v[1]) for k, v in w.items()}
        assert all(f[0] >= 2 * M - 1 for f in facs.values())
        print(f"      M = {M:<5d} A: N={n_of(w['A'])}={facs['A'][0]}*{facs['A'][1]}   "
              f"C: N={n_of(w['C'])}={facs['C'][0]}*{facs['C'][1]}   both N = 1 (mod {M})")
    print("    A is unbalanced (3(m-n) < m+n), C is balanced (m+n <= 2(m-n)):")
    M = 27
    wa, wc = witnesses_proper(M)["A"], witnesses_proper(M)["C"]
    assert 3 * (wa[0] - wa[1]) < wa[0] + wa[1] and wc[0] + wc[1] <= 2 * (wc[0] - wc[1])
    print(f"      M = {M}: N={n_of(wa)} unbalanced and N={n_of(wc)} balanced, congruent mod {M}")
    print("    => no function of N mod M can output the letter, or the balance band.")
    print()


def demo_positionwise_seal(moduli: Optional[List[int]] = None,
                           depths: Optional[List[int]] = None) -> None:
    print("=" * 78)
    print("6.  Positionwise seal: sealed at depth t even given all shallower letters")
    print("=" * 78)
    if moduli is None:
        moduli = [2, 3, 9, 27, 100]
    if depths is None:
        depths = [0, 1, 2, 5, 9]
    for M in moduli:
        for t in depths:
            nodes = {k: node_family(M, k, t) for k in (1, 2, 3)}
            assert all(is_fermat_pair(v) for v in nodes.values())
            assert {n_of(v) % M for v in nodes.values()} == {1 % M}
            for k, v in nodes.items():
                for s in range(t):
                    assert letter_at(s, v) == "C"
            got = "".join(letter_at(t, nodes[k]) for k in (1, 2, 3))
            assert got == "ABC", got
            print(f"      M = {M:<4d} t = {t:<2d}  prefix = {'C'*t or '(empty)':<10s} "
                  f"letters at depth t = {got},  all with N = 1 (mod {M})")
    print("    => even with the entire shallower path given away, the next letter is free.")
    print()


def demo_depth_bound(max_depth: int = 12) -> None:
    print("=" * 78)
    print("7.  The channel is too big: 2*depth + 3 <= m + n <= N, saturated by the C-spine")
    print("=" * 78)
    for d in [1, 2, 3, 5, 8, max_depth]:
        node = spine(d)
        assert eval_word(["C"] * d) == node
        assert 2 * d + 3 == node[0] + node[1]
        print(f"      depth {d:<3d} spine node {str(node):<12s} m+n = {node[0]+node[1]:<5d} "
              f"N = {n_of(node):<7d} = {node[0]-node[1]} * {node[0]+node[1]}")
    print("      depth grows linearly in N, hence EXPONENTIALLY in the bit length of N:")
    for bits in (16, 64, 256, 2048):
        print(f"        a {bits}-bit N admits addresses of length up to about 2^{bits-1}")
    print("    Depth blindness: spine depths 1 and 1+j*M share a residue class mod M.")
    for M in (3, 9, 27):
        for j in (1, 2):
            assert (n_of(spine(1 + j * M)) - n_of(spine(1))) % M == 0
        print(f"      M = {M:<4d} depths 1, {1+M}, {1+2*M}, ... all give N = 15 (mod {M})")
    print()


def demo_information(samples: int = 6000, shuffles: int = 200, seed: int = 7) -> None:
    print("=" * 78)
    print("8.  Empirical channel measurement: blindness, with two live positive controls")
    print("=" * 78)
    rng = random.Random(seed)
    letters: List[int] = []
    residues: Dict[int, List[int]] = {k: [] for k in range(1, 7)}
    sum_mod3: List[int] = []
    n_mod3: List[int] = []
    bands: List[int] = []
    log_depth: List[float] = []
    log_gap: List[float] = []
    code = {"A": 0, "B": 1, "C": 2}
    for _ in range(samples):
        p, q = random_semiprime(16, 24, rng)
        node = fermat_pair(p, q)
        N = p * q
        letters.append(code[letter_of(node)])
        for k in range(1, 7):
            residues[k].append(N % (3**k))
        n_mod3.append(N % 3)
        sum_mod3.append((p + q) % 3)
        bands.append(code[letter_of(node)])  # the band, recoded identically
        # depth of the node: descend (cheap here because p, q are moderate)
        d = len(address(node))
        log_depth.append(math.log(d + 1))
        log_gap.append(math.log(q - p))

    print(f"    sample: {samples} semiprimes, p,q uniform primes in [2^16, 2^24)")
    print("    channel                                  I (bits)    null mean    z")
    for k in range(1, 7):
        mi = mutual_information(residues[k], letters)
        mu, sd = permutation_null(residues[k], letters, shuffles, rng)
        z = (mi - mu) / sd if sd > 0 else 0.0
        print(f"    I(N mod 3^{k}; first letter)            {mi:10.5f} {mu:12.5f} {z:+7.2f}")

    mi_trace = mutual_information(n_mod3, sum_mod3)
    print(f"    CONTROL  I(N mod 3; (p+q) mod 3)        {mi_trace:10.5f}   "
          f"(the visible trace channel: saturating)")
    mi_band = mutual_information(bands, letters)
    h_letter = entropy(letters)
    print(f"    CONTROL  I(ratio band; first letter)    {mi_band:10.5f}   "
          f"= H(letter) = {h_letter:.5f}  (deterministic)")

    mean_d = sum(log_depth) / len(log_depth)
    mean_g = sum(log_gap) / len(log_gap)
    cov = sum((a - mean_d) * (b - mean_g) for a, b in zip(log_depth, log_gap))
    sd_d = math.sqrt(sum((a - mean_d) ** 2 for a in log_depth))
    sd_g = math.sqrt(sum((b - mean_g) ** 2 for b in log_gap))
    print(f"    DIAGNOSTIC  corr(log depth, log gap)    {cov / (sd_d * sd_g):+10.4f}   "
          f"(the tree does feel the factorisation)")
    print()
    print("    Reading: residue channels sit at the permutation null (no signal), while")
    print("    the band control saturates the letter entropy.  The apparatus can detect a")
    print("    channel when one exists; there is none from N's residues to the letters.")
    print()


def main() -> None:
    print()
    print("THE TREE POSITION OF A SEMIPRIME IS ADICALLY SEALED — demonstrations")
    print()
    demo_embedding()
    demo_skeleton()
    demo_parent_law()
    demo_letter_is_balance()
    demo_seal()
    demo_positionwise_seal()
    demo_depth_bound()
    demo_information()
    print("All assertions passed.")


if __name__ == "__main__":
    main()
