"""
Numerical demonstrations of the well-quasi-order finite-basis engine.

Central principle (proved in the accompanying paper):

    In any well-quasi-order (WQO), every upward-closed set U is generated by
    its FINITELY many minimal elements Min(U):

        x in U  <=>  exists g in Min(U) with g <= x.

    Dually, every downward-closed (minor-closed) set S is cut out by the
    finitely many minimal elements of its complement -- the "forbidden set":

        x in S  <=>  for all b in B, not (b <= x).

This file specializes the principle to two concrete well-quasi-orders:

  * (N, <=)          -- initial segments and single forbidden numbers.
  * (N^k, <=coord)   -- Dickson's lemma: monomial ideals are finitely generated.

Everything is self-contained (standard library only) and type-hinted.
"""

from __future__ import annotations

from itertools import product
from typing import Callable, Iterable, List, Sequence, Set, Tuple

# A point of N^k is represented as a tuple of nonnegative ints.
Vec = Tuple[int, ...]


# ---------------------------------------------------------------------------
# Coordinatewise order on N^k (= monomial divisibility)
# ---------------------------------------------------------------------------
def leq_coord(a: Vec, b: Vec) -> bool:
    """Return True iff a <= b coordinatewise (equivalently, monomial a divides b)."""
    return len(a) == len(b) and all(ai <= bi for ai, bi in zip(a, b))


def lt_coord(a: Vec, b: Vec) -> bool:
    """Strict coordinatewise order: a <= b and a != b."""
    return leq_coord(a, b) and a != b


# ---------------------------------------------------------------------------
# The abstract engine, made concrete for a finite sample of a set.
# ---------------------------------------------------------------------------
def minimal_elements(
    points: Iterable[Vec], leq: Callable[[Vec, Vec], bool]
) -> List[Vec]:
    """
    Compute the minimal elements Min(points) with respect to the order `leq`.

    An element x is minimal if no *distinct* element y of the set satisfies y < x.
    In a WQO this set is guaranteed finite; here `points` is already finite so we
    simply filter.
    """
    pts: List[Vec] = list(dict.fromkeys(points))  # dedupe, keep order
    result: List[Vec] = []
    for x in pts:
        if not any(y != x and leq(y, x) for y in pts):
            result.append(x)
    return sorted(result)


def generated_upper_set(
    generators: Sequence[Vec], box: int, dim: int
) -> Set[Vec]:
    """
    The upper set generated by `generators`, intersected with the finite box
    {0, ..., box}^dim.  A vector x is in the set iff some generator divides it.
    """
    out: Set[Vec] = set()
    for x in product(range(box + 1), repeat=dim):
        if any(leq_coord(g, x) for g in generators):
            out.add(x)
    return out


# ---------------------------------------------------------------------------
# Demonstration 1: Dickson's lemma / monomial-ideal finite generation on N^2.
# ---------------------------------------------------------------------------
def demo_dickson_finite_generation() -> None:
    print("=" * 70)
    print("DEMO 1: Dickson's lemma -- finite generation of a monomial ideal")
    print("=" * 70)

    # Build an upper set U in N^2 as the divisibility-up-closure of a *redundant*
    # generating list.  The engine predicts a unique finite minimal generating
    # set Min(U); redundant generators should be pruned automatically.
    box, dim = 8, 2
    redundant_gens: List[Vec] = [
        (2, 3),  # minimal
        (4, 1),  # minimal
        (1, 5),  # minimal
        (5, 6),  # redundant: divisible by (2,3)
        (4, 4),  # redundant: divisible by (4,1)
        (3, 7),  # redundant: divisible by (1,5)
    ]
    U = generated_upper_set(redundant_gens, box, dim)
    mins = minimal_elements(U, leq_coord)

    print(f"Redundant generator list : {redundant_gens}")
    print(f"Minimal generators Min(U): {mins}")
    print(f"|U cap box|              : {len(U)} vectors in {{0..{box}}}^2")

    # Verify the generation identity on the whole box:
    #   x in U  <=>  some minimal generator divides x.
    ok = all(
        (x in U) == any(leq_coord(g, x) for g in mins)
        for x in product(range(box + 1), repeat=dim)
    )
    print(f"Generation identity holds on the box: {ok}")
    print(f"Minimal set is finite (as WQO guarantees): {len(mins)} elements")
    print()


# ---------------------------------------------------------------------------
# Demonstration 2: forbidden-set characterization of a lower set in N.
# ---------------------------------------------------------------------------
def forbidden_set_nat(in_S: Callable[[int], bool], bound: int) -> List[int]:
    """
    Given a lower set S of naturals (via membership test `in_S`) sampled on
    {0, ..., bound}, return the finite forbidden set B = Min(complement).
    """
    complement = [(n,) for n in range(bound + 1) if not in_S(n)]
    # minimal elements of complement under the usual order = least excluded number
    return [t[0] for t in minimal_elements(complement, leq_coord)]


def demo_forbidden_set_nat() -> None:
    print("=" * 70)
    print("DEMO 2: forbidden set of an initial segment of N")
    print("=" * 70)

    bound = 20
    for n in (0, 1, 5, 12):
        # S = {0, ..., n-1} is a lower set.
        in_S = lambda x, n=n: x < n
        B = forbidden_set_nat(in_S, bound)
        # Reconstruct S from B: x in S iff no b in B has b <= x.
        reconstructed = [x for x in range(bound + 1) if all(not (b <= x) for b in B)]
        expected = [x for x in range(bound + 1) if in_S(x)]
        print(
            f"S = {{0..{n-1}}}: forbidden set B = {B}; "
            f"reconstruction correct = {reconstructed == expected}"
        )
    # S = all of N (on the sample): empty forbidden set.
    B_all = forbidden_set_nat(lambda x: True, bound)
    print(f"S = N (sampled): forbidden set B = {B_all} (empty, as predicted)")
    print()


# ---------------------------------------------------------------------------
# Demonstration 3: membership decision via a finite obstruction family.
# ---------------------------------------------------------------------------
def decides_membership(x: Vec, forbidden: Sequence[Vec]) -> bool:
    """
    Decide membership of x in a minor-closed set S given its finite forbidden
    family: x in S iff no forbidden obstruction divides (is <= to) x.
    """
    return not any(leq_coord(b, x) for b in forbidden)


def demo_obstruction_membership() -> None:
    print("=" * 70)
    print("DEMO 3: minor-closed membership via a finite forbidden family (N^2)")
    print("=" * 70)

    # Take S = downward-closed set avoiding any vector that is >= a forbidden one.
    # Forbidden family (two obstructions), analogous to Wagner's {K5, K3,3}.
    forbidden: List[Vec] = [(2, 2), (0, 4)]
    print(f"Forbidden family (obstructions): {forbidden}")
    tests: List[Vec] = [(1, 1), (2, 2), (3, 0), (1, 4), (0, 3), (2, 1)]
    for x in tests:
        verdict = decides_membership(x, forbidden)
        print(f"  x = {x}:  in S = {verdict}")

    # Cross-check that S really is downward closed on a box.
    box = 6
    S = {x for x in product(range(box + 1), repeat=2) if decides_membership(x, forbidden)}
    downward_closed = all(
        (y in S)
        for x in S
        for y in product(range(box + 1), repeat=2)
        if leq_coord(y, x)
    )
    print(f"S is downward-closed on {{0..{box}}}^2: {downward_closed}")
    print()


def main() -> None:
    demo_dickson_finite_generation()
    demo_forbidden_set_nat()
    demo_obstruction_membership()
    print("All demonstrations complete.")


if __name__ == "__main__":
    main()
