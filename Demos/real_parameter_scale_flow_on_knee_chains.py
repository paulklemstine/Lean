#!/usr/bin/env python3
"""
Real-Parameter Scale Flow on Knee Chains — numerical demonstration.

This script is a self-contained, dependency-free (standard library only)
verification of every quantitative claim in the accompanying paper:

  1. The measured knee table is generated by a single base chain translated
     by one context octave per octave of model scale.
  2. Truncated subtraction on the naturals and the clamp max(x - y, 0) on the
     nonnegative reals are the *same* operation, so the octave shift extends
     from an action of (N, +) to an action of (R>=0, +).
  3. The extended flow restricts cell-for-cell to the measured table.
  4. Continuous rigidity: the exchange law plus base-context inertia determine
     the whole two-variable table from its base profile.
  5. Monotone interpolation through the measured cells exists iff the chain is
     monotone, but is NOT unique: the ramp and staircase interpolants disagree
     by four keys at the half-octave.
  6. Adding stationary increments forces affinity (generator theorem), pinning
     the canonical table k*(s, t) = k0 + delta * max(t - s, 0).
  7. The generator is the keys-per-octave rate, and the table satisfies the
     transport equation d/ds k + d/dt k = 0.
  8. The 3B sweep: an unmeasured 3B model sits at scale index ~1.44997, with a
     knee of ~18.20 keys at 2048 tokens (deployable budget 19) — a value no
     integer scale index can produce.
  9. Rate identifiability: base knee, rate and offset are jointly identifiable.
 10. The budget adjunction and the exact staircase-vs-triangle defect S/2.
 11. The tropical reading: the table is a tropical binomial whose corner locus
     is exactly the diagonal t = sigma.

Run:  python3 demo.py
"""

from __future__ import annotations

import math
from typing import Callable, Dict, List, Sequence, Tuple

# ----------------------------------------------------------------------------
# Measured data (the reference family)
# ----------------------------------------------------------------------------

BASE_CTX: int = 512                 # context length of octave 0
K0_BASE: float = 16.0               # base knee, in keys
DELTA: float = 4.0                  # keys per octave

# Measured knee table: rows are scale indices 0, 1, 2 (0.5B, 1.5B, 7B),
# columns are context octaves 0..3 (512, 1024, 2048, 4096 tokens).
MEASURED_TABLE: Dict[int, List[int]] = {
    0: [16, 20, 24, 28],
    1: [16, 16, 20, 24],
    2: [16, 16, 16, 20],
}

MODEL_ANCHORS: Dict[float, int] = {1.5: 1, 7.0: 2}   # billions of params -> index


# ----------------------------------------------------------------------------
# 1. Ordered subtraction, in both monoids
# ----------------------------------------------------------------------------

def nat_tsub(j: int, s: int) -> int:
    """Truncated subtraction in (N, +): j - s clamped at 0."""
    return j - s if j >= s else 0


def real_tsub(t: float, s: float) -> float:
    """Ordered subtraction in (R>=0, +): exactly the clamp max(t - s, 0)."""
    return max(t - s, 0.0)


def base_chain(j: int) -> int:
    """The measured base chain K(j) = 16 + 4j (the 0.5B row)."""
    return 16 + 4 * j


def shift(chain: Callable[[int], int], s: int) -> Callable[[int], int]:
    """The discrete octave shift: (shift K s)(j) = K(j - s), truncated."""
    return lambda j: chain(nat_tsub(j, s))


# ----------------------------------------------------------------------------
# 2. The canonical real table
# ----------------------------------------------------------------------------

def kstar(k0: float, delta: float, sigma: float, t: float) -> float:
    """k*(sigma, t) = k0 + delta * (t - sigma)^+  — the canonical real table."""
    return k0 + delta * real_tsub(t, sigma)


def kstar_tropical(k0: float, delta: float, sigma: float, t: float) -> float:
    """Tropical binomial form: max-plus sum of monomials k0 and k0 + d t - d s."""
    return max(k0, k0 + delta * t - delta * sigma)


# ----------------------------------------------------------------------------
# 3. Interpolants of a measured chain
# ----------------------------------------------------------------------------

def ramp(x: float) -> float:
    """Unit ramp: 0 below 0, linear on [0, 1], 1 above 1."""
    return min(1.0, max(x, 0.0))


def pl_interp(chain: Callable[[int], int], t: float) -> float:
    """Ramp-basis (piecewise-linear) interpolant of a measured chain.

    PL_K(t) = K(0) + sum_{i < ceil(t)} (K(i+1) - K(i)) * ramp(t - i).
    Monotone whenever K is, because every coefficient is nonnegative and every
    basis function is monotone.
    """
    total = float(chain(0))
    for i in range(math.ceil(t)):
        total += (chain(i + 1) - chain(i)) * ramp(t - i)
    return total


def ceil_interp(chain: Callable[[int], int], t: float) -> float:
    """Staircase interpolant: round the context octave up to the next measured one."""
    return float(chain(math.ceil(t)))


def affine_interp(k0: float, delta: float, t: float) -> float:
    """The affine profile k0 + delta * t (unique monotone stationary interpolant)."""
    return k0 + delta * t


# ----------------------------------------------------------------------------
# 4. Scale-axis calibration
# ----------------------------------------------------------------------------

def scale_index(n_billion: float) -> float:
    """Log-linear scale index, anchored at 1.5B -> 1 and 7B -> 2."""
    return 1.0 + math.log(n_billion / 1.5) / math.log(14.0 / 3.0)


def deployable_budget(n_billion: float, ctx_tokens: int,
                      k0: float = K0_BASE, delta: float = DELTA) -> int:
    """Interpolated, deployable (integer) key budget for any model size / context."""
    sigma = scale_index(n_billion)
    t = math.log2(ctx_tokens / BASE_CTX)
    return math.ceil(kstar(k0, delta, sigma, t))


# ----------------------------------------------------------------------------
# 5. Budget reach and served region
# ----------------------------------------------------------------------------

def reach(k0: float, delta: float, b: float) -> float:
    """Reach of a budget: the number of context octaves above base it buys."""
    return (b - k0) / delta


def served_cells(k0: float, delta: float, b: float, S: int, J: int) -> int:
    """Number of served cells of the DISCRETE table over scale rows 0..S-1."""
    count = 0
    for s in range(S):
        for j in range(J + 1):
            if kstar(k0, delta, float(s), float(j)) <= b + 1e-12:
                count += 1
    return count


def served_area(k0: float, delta: float, b: float, S: float) -> float:
    """Area under the CONTINUOUS served boundary t = sigma + reach over [0, S]."""
    r = reach(k0, delta, b)
    # integral_0^S (sigma + r) dsigma  =  S^2/2 + r*S ; with r = 0 this is S^2/2.
    return S * S / 2.0 + r * S


