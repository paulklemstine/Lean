def demo_octave_shift_law() -> bool:
    header("1. The discrete octave shift law: one chain, translated")
    print("  Measured table (rows = scale index, cols = context octave 0..3):")
    for s, row in MEASURED_TABLE.items():
        print(f"    sigma = {s} : {row}")
    print()
    print("  Claim: every cell equals K(j - s) with K(j) = 16 + 4j, truncated.")
    ok = True
    for s, row in MEASURED_TABLE.items():
        shifted = [shift(base_chain, s)(j) for j in range(len(row))]
        ok &= check(f"row sigma = {s} is the base chain shifted by {s}",
                    shifted == row, f"{shifted}")
    return ok


def demo_monoid_action() -> bool:
    header("2. The shift extends to an action of (R>=0, +)")
    print("  rho_s K(t) = K(max(t - s, 0)).  Check rho_0 = id and")
    print("  rho_b o rho_a = rho_{a+b} at many random-ish sample points.")
    profile = lambda x: affine_interp(K0_BASE, DELTA, x)
    ok = True
    samples = [0.0, 0.25, 0.5, 1.0, 1.3333, 2.0, 2.7, 3.5, 5.0]
    ok &= check("rho_0 is the identity",
                all(abs(profile(real_tsub(t, 0.0)) - profile(t)) < 1e-12
                    for t in samples))
    pairs = [(0.3, 0.7), (1.0, 1.0), (0.45, 2.2), (1.44997, 0.55003)]
    good = True
    for a, b in pairs:
        for t in samples:
            lhs = profile(real_tsub(real_tsub(t, a), b))
            rhs = profile(real_tsub(t, a + b))
            good &= abs(lhs - rhs) < 1e-12
    ok &= check("rho_b o rho_a = rho_{a+b} (associativity of the action)", good)

    # exchange law
    good = all(
        abs(profile(real_tsub(t + a, s + a)) - profile(real_tsub(t, s))) < 1e-12
        for s in samples for t in samples for a in (0.0, 0.5, 1.7)
    )
    ok &= check("exchange law: a octaves of scale buy a octaves of context", good)
    return ok


def demo_restriction() -> bool:
    header("3. The real flow restricts to the measured cells")
    ok = True
    for s, row in MEASURED_TABLE.items():
        vals = [kstar(K0_BASE, DELTA, float(s), float(j)) for j in range(len(row))]
        ok &= check(f"k*({s}, j) reproduces the sigma = {s} row",
                    all(abs(v - m) < 1e-12 for v, m in zip(vals, row)),
                    f"{[round(v, 3) for v in vals]}")
    print()
    print("  Also: the tropical binomial form agrees everywhere.")
    good = all(
        abs(kstar(K0_BASE, DELTA, s, t) - kstar_tropical(K0_BASE, DELTA, s, t)) < 1e-12
        for s in (0.0, 0.5, 1.44997, 2.0, 3.3) for t in (0.0, 0.5, 1.0, 2.0, 4.0)
    )
    ok &= check("k* = max(k0, k0 + delta*t - delta*sigma)", good)
    return ok


def demo_rigidity() -> bool:
    header("4. Continuous rigidity: two local laws determine the whole plane")
    print("  Build a table only from the base profile and the two laws, then")
    print("  check it agrees with the closed form k*(s, t) = k0 + d*(t-s)^+.")

    base = lambda x: affine_interp(K0_BASE, DELTA, x)

    def table_from_laws(sigma: float, t: float) -> float:
        # Transport (sigma, t) to the base row / base-context edge, exactly as
        # in the proof of the rigidity theorem.
        if t <= sigma:
            return base(0.0)          # base-context inertia
        return base(t - sigma)        # slide down the flow direction (1,1)

    ok = all(
        abs(table_from_laws(s, t) - kstar(K0_BASE, DELTA, s, t)) < 1e-12
        for s in (0.0, 0.37, 1.0, 1.44997, 2.0, 5.0)
        for t in (0.0, 0.37, 1.0, 2.0, 3.5, 7.0)
    )
    return check("rigidity reconstruction matches the closed form", ok)


def demo_lipschitz() -> bool:
    header("5. Lipschitz transport in scale: no cliffs between measured rows")
    worst = 0.0
    for t in (0.0, 0.5, 1.0, 2.0, 3.0, 5.0):
        for s in (0.0, 0.5, 1.0, 1.5, 2.0):
            for h in (0.01, 0.1, 0.5, 1.0):
                gap = abs(kstar(K0_BASE, DELTA, s, t) - kstar(K0_BASE, DELTA, s + h, t))
                worst = max(worst, gap - DELTA * h)
    return check("|k*(s,t) - k*(s+h,t)| <= delta*h everywhere sampled",
                 worst <= 1e-12, f"max excess = {worst:.3e}")


def demo_interpolation_nonuniqueness() -> bool:
    header("6. Monotone interpolation exists — but is NOT unique")
    ok = True
    print("  Both interpolants hit every measured cell:")
    good_pl = all(abs(pl_interp(base_chain, float(n)) - base_chain(n)) < 1e-12
                  for n in range(6))
    good_st = all(abs(ceil_interp(base_chain, float(n)) - base_chain(n)) < 1e-12
                  for n in range(6))
    ok &= check("ramp-basis interpolant passes through every cell", good_pl)
    ok &= check("staircase interpolant passes through every cell", good_st)

    print("  Both are monotone:")
    grid = [i / 20.0 for i in range(101)]
    mono_pl = all(pl_interp(base_chain, a) <= pl_interp(base_chain, b) + 1e-12
                  for a, b in zip(grid, grid[1:]))
    mono_st = all(ceil_interp(base_chain, a) <= ceil_interp(base_chain, b) + 1e-12
                  for a, b in zip(grid, grid[1:]))
    ok &= check("ramp-basis interpolant is monotone", mono_pl)
    ok &= check("staircase interpolant is monotone", mono_st)

    print("  Yet they disagree at the half-octave:")
    pl_half = pl_interp(base_chain, 0.5)
    st_half = ceil_interp(base_chain, 0.5)
    ok &= check("PL(1/2) = 18 and ST(1/2) = 20 — a four-key gap",
                abs(pl_half - 18.0) < 1e-12 and abs(st_half - 20.0) < 1e-12,
                f"PL = {pl_half}, ST = {st_half}, gap = {st_half - pl_half}")
    return ok


def demo_generator_theorem() -> bool:
    header("7. Stationary increments force affinity (generator theorem)")
    print("  The staircase interpolant is monotone and interpolating, but its")
    print("  increments are NOT stationary; the ramp interpolant of an")
    print("  arithmetic chain is affine and its increments ARE stationary.")

    def stationarity_defect(f: Callable[[float], float]) -> float:
        worst = 0.0
        for t in (0.0, 0.25, 0.5, 1.0, 1.75, 2.5):
            for u in (0.0, 0.25, 0.5, 1.0, 1.75):
                lhs = f(t + u) - f(t)
                rhs = f(u) - f(0.0)
                worst = max(worst, abs(lhs - rhs))
        return worst

    d_pl = stationarity_defect(lambda x: pl_interp(base_chain, x))
    d_st = stationarity_defect(lambda x: ceil_interp(base_chain, x))
    ok = True
    ok &= check("ramp interpolant has stationary increments",
                d_pl < 1e-12, f"defect = {d_pl:.3e}")
    ok &= check("staircase interpolant does NOT",
                d_st > 0.5, f"defect = {d_st:.3f} keys")
    print()
    print("  Generator theorem: monotone + stationary  =>  K0(t) = K0(0) + delta*t")
    slope = pl_interp(base_chain, 1.0) - pl_interp(base_chain, 0.0)
    good = all(abs(pl_interp(base_chain, t)
                   - (pl_interp(base_chain, 0.0) + slope * t)) < 1e-12
               for t in [i / 8.0 for i in range(40)])
    ok &= check("the unique stationary monotone interpolant is 16 + 4t",
                good and abs(slope - DELTA) < 1e-12,
                f"delta = K0(1) - K0(0) = {slope}")
    return ok


def demo_transport_equation() -> bool:
    header("8. The generator is the keys-per-octave rate; transport equation")
    h = 1e-6
    ok = True
    for sigma, t in ((1.0, 2.0), (0.5, 3.0), (1.44997, 2.0)):
        d_sigma = (kstar(K0_BASE, DELTA, sigma + h, t)
                   - kstar(K0_BASE, DELTA, sigma - h, t)) / (2 * h)
        d_t = (kstar(K0_BASE, DELTA, sigma, t + h)
               - kstar(K0_BASE, DELTA, sigma, t - h)) / (2 * h)
        ok &= check(f"at (sigma, t) = ({sigma}, {t}):  d/dsigma = -delta, d/dt = +delta,"
                    f" sum = 0",
                    abs(d_sigma + DELTA) < 1e-5 and abs(d_t - DELTA) < 1e-5
                    and abs(d_sigma + d_t) < 1e-6,
                    f"({d_sigma:+.4f}, {d_t:+.4f}) -> {d_sigma + d_t:+.2e}")
    return ok


def demo_3B_sweep() -> bool:
    header("9. The 3B sweep: filling in the row nobody measured")
    s3 = scale_index(3.0)
    ok = True
    ok &= check("scaleIndex(1.5) = 1", abs(scale_index(1.5) - 1.0) < 1e-12)
    ok &= check("scaleIndex(7) = 2", abs(scale_index(7.0) - 2.0) < 1e-12)
    ok &= check("7/5 < scaleIndex(3) < 3/2  (strictly fractional offset)",
                1.4 < s3 < 1.5, f"scaleIndex(3) = {s3:.6f}")
    print()
    print("  Predicted knee chain (ctx tokens -> exact value -> deployable budget):")
    ctxs = [512, 1024, 2048, 4096]
    for ctx in ctxs:
        t = math.log2(ctx / BASE_CTX)
        val = kstar(K0_BASE, DELTA, s3, t)
        print(f"    ctx = {ctx:5d} : k* = {val:7.4f}  ->  budget {math.ceil(val):3d}")
    print()
    k2 = kstar(K0_BASE, DELTA, s3, 2.0)
    k3 = kstar(K0_BASE, DELTA, s3, 3.0)
    ok &= check("3B at 512 and 1024 is still flat at 16 keys",
                abs(kstar(K0_BASE, DELTA, s3, 0.0) - 16.0) < 1e-12
                and abs(kstar(K0_BASE, DELTA, s3, 1.0) - 16.0) < 1e-12)
    ok &= check("18 < k*(3B, 2048) < 18.4  and  ceil = 19",
                18.0 < k2 < 18.4 and math.ceil(k2) == 19, f"k* = {k2:.6f}")
    ok &= check("22 < k*(3B, 4096) < 22.4  and  ceil = 23",
                22.0 < k3 < 22.4 and math.ceil(k3) == 23, f"k* = {k3:.6f}")
    ok &= check("bracketed strictly by the 7B and 1.5B cells at 2048",
                kstar(K0_BASE, DELTA, 2.0, 2.0) < k2 < kstar(K0_BASE, DELTA, 1.0, 2.0),
                f"16 < {k2:.4f} < 20")
    ok &= check("no integer scale index reproduces it (falsifiable prediction)",
                all(abs(kstar(K0_BASE, DELTA, float(s), 2.0) - k2) > 1e-6
                    for s in range(0, 12)))
    print()
    print("  Full interpolated deployment table:")
    print(f"    {'model':>8} | " + " | ".join(f"{c:>5}" for c in ctxs))
    print("    " + "-" * (10 + 8 * len(ctxs)))
    for n in (0.5, 1.0, 1.5, 2.0, 3.0, 5.0, 7.0, 13.0):
        row = " | ".join(f"{deployable_budget(n, c):5d}" for c in ctxs)
        print(f"    {n:6.1f}B | {row}")
    print()
    print("  NOTE.  The calibration is anchored on the two CONSECUTIVE rows")
    print("  1.5B -> 1 and 7B -> 2.  The measured ladder is not geometric")
    print("  (1.5/0.5 = 3 but 7/1.5 = 14/3), so the third row is over-determined:")
    print(f"  this calibration places 0.5B at sigma = {scale_index(0.5):.4f}, not 0, and")
    print("  its interpolated row (16, 19, 23, 27) undershoots the measured")
    print("  (16, 20, 24, 28) by one key.  The knee table itself is exact at every")
    print("  integer scale index; the residual is in the size-to-index calibration,")
    print("  and it is precisely the kind of deviation a third anchor can test.")
    return ok


def demo_identifiability() -> bool:
    header("10. The rate is data, not a fitting convention")
    print("  If two clamped-affine tables agree at every real context, their")
    print("  base knee, rate and offset must all agree.  Perturb any one of")
    print("  them and the tables separate:")
    ok = True
    ref = lambda t: kstar(K0_BASE, DELTA, 1.0, t)
    grid = [i / 4.0 for i in range(0, 25)]
    for label, f in (
        ("perturbed rate    (delta 4 -> 4.5)", lambda t: kstar(K0_BASE, 4.5, 1.0, t)),
        ("perturbed base    (k0 16 -> 16.5)", lambda t: kstar(16.5, DELTA, 1.0, t)),
        ("perturbed offset  (sigma 1 -> 1.1)", lambda t: kstar(K0_BASE, DELTA, 1.1, t)),
    ):
        sep = max(abs(ref(t) - f(t)) for t in grid)
        ok &= check(f"{label} separates the tables", sep > 1e-9,
                    f"max |diff| = {sep:.4f} keys")
    print()
    print("  And the measured cells force (k0, delta) = (16, 4):")
    k0_forced = kstar(K0_BASE, DELTA, 0.0, 0.0)                       # clamp active
    delta_forced = kstar(K0_BASE, DELTA, 0.0, 1.0) - k0_forced        # clamp inactive
    ok &= check("k0 = 16 and delta = 4 are forced by the 0.5B row",
                abs(k0_forced - 16.0) < 1e-12 and abs(delta_forced - 4.0) < 1e-12,
                f"(k0, delta) = ({k0_forced}, {delta_forced})")
    return ok


def demo_reach_and_defect() -> bool:
    header("11. Budget reach, the served region, and the exact S/2 defect")
    ok = True
    print("  Budget adjunction:  k*(sigma, t) <= b   <=>   t <= sigma + reach(b).")
    for b in (16.0, 20.0, 24.0, 28.0):
        r = reach(K0_BASE, DELTA, b)
        good = True
        for sigma in (0.0, 0.5, 1.0, 1.44997, 2.0, 3.0):
            for t in [i / 4.0 for i in range(0, 33)]:
                lhs = kstar(K0_BASE, DELTA, sigma, t) <= b + 1e-12
                rhs = t <= sigma + r + 1e-12
                good &= (lhs == rhs)
        ok &= check(f"budget b = {b:.0f} keys has reach {r:.1f} octaves; adjunction holds",
                    good)
    print()
    print("  Continuous budget law: the served boundary is a line of slope 1.")
    r16 = reach(K0_BASE, DELTA, 16.0)
    ok &= check("a 16-key budget has reach 0 (boundary is the diagonal t = sigma)",
                abs(r16) < 1e-12)
    print()
    print("  Staircase (discrete cells) vs triangle (continuous area):")
    print(f"    {'S':>3} | {'cells':>7} | {'area':>8} | {'defect':>8} | {'S/2':>6}")
    print("    " + "-" * 44)
    for S in range(0, 9):
        J = max(S, 1) + 4
        cells = served_cells(K0_BASE, DELTA, 16.0, S, J)
        area = served_area(K0_BASE, DELTA, 16.0, float(S))
        defect = cells - area
        print(f"    {S:3d} | {cells:7d} | {area:8.2f} | {defect:8.2f} | {S / 2:6.2f}")
        ok &= abs(defect - S / 2.0) < 1e-12
    ok = check("discrete served cells - continuous served area = S/2, exactly", ok)
    return ok


def demo_tropical_corner() -> bool:
    header("12. The tropical corner: one knee per model, on the diagonal")
    ok = True
    sigma = 1.44997
    h = 1e-7

    def one_sided(t: float, side: int) -> float:
        if side > 0:
            return (kstar(K0_BASE, DELTA, sigma, t + h)
                    - kstar(K0_BASE, DELTA, sigma, t)) / h
        return (kstar(K0_BASE, DELTA, sigma, t)
                - kstar(K0_BASE, DELTA, sigma, t - h)) / h

    left = one_sided(sigma, -1)
    right = one_sided(sigma, +1)
    ok &= check("at t = sigma the one-sided slopes are 0 (left) and delta (right)",
                abs(left) < 1e-5 and abs(right - DELTA) < 1e-5,
                f"left = {left:.6f}, right = {right:.6f}")
    print("  Away from the diagonal the two one-sided slopes agree (smooth):")
    for t in (sigma - 0.6, sigma + 0.6, sigma + 2.0):
        l, r = one_sided(t, -1), one_sided(t, +1)
        ok &= check(f"t = {t:.4f} is a smooth point", abs(l - r) < 1e-5,
                    f"slopes {l:.4f} / {r:.4f}")
    print()
    print("  Corner locus is invariant under the flow direction (1, 1):")
    good = True
    for a in (0.0, 0.5, 1.3, 2.7):
        # corner of the shifted table sits at sigma + a
        s2 = sigma + a
        lf = (kstar(K0_BASE, DELTA, s2, s2) - kstar(K0_BASE, DELTA, s2, s2 - h)) / h
        rt = (kstar(K0_BASE, DELTA, s2, s2 + h) - kstar(K0_BASE, DELTA, s2, s2)) / h
        good &= abs(lf) < 1e-5 and abs(rt - DELTA) < 1e-5
    ok &= check("shifting scale by a shifts the corner by a", good)
    print()
    print("  Convexity (diminishing returns) along both axes:")
    def convex_on(f: Callable[[float], float], xs: Sequence[float]) -> bool:
        return all(f((a + c) / 2) <= (f(a) + f(c)) / 2 + 1e-12
                   for a in xs for c in xs)
    xs = [i / 4.0 for i in range(-8, 25)]
    ok &= check("convex in context",
                convex_on(lambda t: kstar(K0_BASE, DELTA, 1.0, t), xs))
    ok &= check("convex in scale",
                convex_on(lambda s: kstar(K0_BASE, DELTA, s, 3.0), xs))
    return ok


