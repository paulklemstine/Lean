#!/usr/bin/env python3
"""Numerical demonstrations of parity Fourier analysis for integer-graded data."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Iterable, Mapping, Tuple

VSpace = Dict[int, int]


@dataclass(frozen=True)
class Invariants:
    """The even, odd, total, and Euler measurements of graded data."""

    even: int
    odd: int
    total: int
    euler: int


def normalize(space: Mapping[int, int]) -> VSpace:
    """Remove zero coefficients and copy graded data into a plain dictionary."""
    return {degree: coefficient for degree, coefficient in space.items() if coefficient != 0}


def invariants(space: Mapping[int, int]) -> Invariants:
    """Compute parity-sector masses and their two character evaluations."""
    even = sum(coefficient for degree, coefficient in space.items() if degree % 2 == 0)
    odd = sum(coefficient for degree, coefficient in space.items() if degree % 2 != 0)
    total = sum(space.values())
    euler = sum((1 if degree % 2 == 0 else -1) * coefficient
                for degree, coefficient in space.items())
    result = Invariants(even, odd, total, euler)
    assert total + euler == 2 * even
    assert total - euler == 2 * odd
    return result


def reconstruct(total: int, euler: int) -> Tuple[int, int]:
    """Recover even and odd masses from compatible Fourier coordinates."""
    if (total - euler) % 2 != 0:
        raise ValueError("total mass and Euler characteristic must have matching parity")
    return (total + euler) // 2, (total - euler) // 2


def reflect(space: Mapping[int, int]) -> VSpace:
    """Reflect every degree d to -d."""
    return normalize({-degree: coefficient for degree, coefficient in space.items()})


def convolve(left: Mapping[int, int], right: Mapping[int, int]) -> VSpace:
    """Multiply virtual cellular spaces by adding degrees and coefficients."""
    output: VSpace = {}
    for left_degree, left_coefficient in left.items():
        for right_degree, right_coefficient in right.items():
            degree = left_degree + right_degree
            output[degree] = output.get(degree, 0) + left_coefficient * right_coefficient
    return normalize(output)


def character_evaluation(space: Mapping[int, int], generator_sign: int) -> int:
    """Evaluate the character generated by +1 or -1 on integer dimensions."""
    if generator_sign not in (-1, 1):
        raise ValueError("an integral unit character must be generated by +1 or -1")
    if generator_sign == 1:
        return sum(space.values())
    return sum((1 if degree % 2 == 0 else -1) * coefficient
               for degree, coefficient in space.items())


def display(name: str, space: Mapping[int, int]) -> None:
    """Print a compact report and verify all identities."""
    data = invariants(space)
    recovered = reconstruct(data.total, data.euler)
    print(f"{name}: {dict(sorted(space.items()))}")
    print(f"  even={data.even}, odd={data.odd}, total={data.total}, euler={data.euler}")
    print(f"  reconstruction={recovered}; reflection euler={invariants(reflect(space)).euler}")
    print(f"  character values: trivial={character_evaluation(space, 1)}, "
          f"parity={character_evaluation(space, -1)}")


def main() -> None:
    """Run mixed-degree, reflection, and convolution demonstrations."""
    sample = {-2: 3, -1: 5, 0: 7, 3: 11}
    virtual = {-4: 9, 2: -4, 5: 6}
    factor_a = {0: 2, 1: 3}
    factor_b = {0: 5, 1: -1}

    display("Mixed positive and negative dimensions", sample)
    display("Virtual coefficients with cancellation", virtual)
    product = convolve(factor_a, factor_b)
    display("Convolution product", product)

    a, b, product_data = invariants(factor_a), invariants(factor_b), invariants(product)
    assert product_data.total == a.total * b.total
    assert product_data.euler == a.euler * b.euler
    print("Product check: total and Euler coordinates multiply componentwise.")


if __name__ == "__main__":
    main()
