# --------------------------------------------------------------------------
# 4.  Rational lines, alignment classes, the square-discriminant dichotomy
# --------------------------------------------------------------------------


def rat_step(a: int, b: int, s: int, u: int, p: Seed) -> Seed:
    m, n = p
    return (s * m + b * u * n, b * u * m + (s - a * u) * n)


def find_unit(a: int, b: int, bound: int = 4_000_000) -> Tuple[int, int] | None:
    """Smallest positive solution of s^2 - a s u - b^2 u^2 = 1 (brute force)."""
    for u in range(1, bound):
        disc = (a * u) ** 2 + 4 * (b * b * u * u + 1)
        r = isqrt(disc)
        if r * r != disc:
            continue
        if (a * u + r) % 2 == 0:
            s = (a * u + r) // 2
            if s > 0:
                return (s, u)
    return None


def demo_rational_lines() -> None:
    print("=" * 72)
    print("10. RATIONAL LINES  b m^2 - a m n - b n^2 = b  AND THEIR AUTOMORPHISMS")
    print("=" * 72)
    for (a, b), start in [((1, 1), (2, 1)), ((2, 3), (3, 2)), ((1, 2), (4, 3)),
                          ((2, 1), (5, 2)), ((1, 3), (6, 5))]:
        unit = find_unit(a, b)
        assert unit is not None
        s, u = unit
        step = math.acosh(s - a * u / 2)
        pts = [start]
        for _ in range(3):
            pts.append(rat_step(a, b, s, u, pts[-1]))
        seeds = [p for p in pts if is_seed(*p)]
        print(f"  rho = {a}/{b}:  disc a^2+4b^2 = {a * a + 4 * b * b}"
              f"   unit (s,u) = ({s},{u})   step = arcosh({s - Fraction(a * u, 2)})"
              f" = {step:.6f}")
        print(f"        orbit of {start}: {pts}")
        print(f"        radial invariants: "
              + ", ".join(str(radial(*p)) for p in pts))
        print(f"        genuine Euclid seeds among them: {seeds}")
    print()


def demo_alignment_classes() -> None:
    print("=" * 72)
    print("11. ALIGNMENT CLASSES:  same radial invariant  <=>  exactly collinear with i")
    print("=" * 72)
    classes: Dict[Fraction, List[Seed]] = {}
    for m in range(2, 1200):
        for n in range(1, m):
            if is_seed(m, n):
                classes.setdefault(radial(m, n), []).append((m, n))
    top = sorted(classes.items(), key=lambda kv: (-len(kv[1]), kv[0]))[:6]
    for rho, members in top:
        a, b = rho.numerator, rho.denominator
        print(f"  rho = {str(rho):>5}  disc = {a * a + 4 * b * b:>6}"
              f"  members with m < 1200: {members}")
        if len(members) >= 3:
            p, q, r = members[0], members[1], members[2]
            d1, d2, d3 = hyp_dist(*p, *q), hyp_dist(*q, *r), hyp_dist(*p, *r)
            print(f"        collinearity check on {p},{q},{r}: "
                  f"d1 + d2 - d3 = {d1 + d2 - d3:+.2e},  Delta = "
                  f"{seed_det(*p, *q, *r)}")
    print()


def demo_square_discriminant() -> None:
    print("=" * 72)
    print("12. SQUARE-DISCRIMINANT DICHOTOMY")
    print("=" * 72)
    print("   Claim: for 0 < n < m the number (m^2 - n^2 - 1)^2 + (2 m n)^2 is never a square.")
    hits = 0
    tested = 0
    for m in range(2, 700):
        for n in range(1, m):
            tested += 1
            v = (m * m - n * n - 1) ** 2 + (2 * m * n) ** 2
            r = isqrt(v)
            if r * r == v:
                hits += 1
                print(f"        counterexample at ({m},{n})!")
    print(f"   pairs tested: {tested};  square discriminants found: {hits}")
    print("   Empty square-discriminant lines (the conic factors into two linear forms):")
    for a, b, e, f in [(0, 1, 1, 1), (3, 2, 1, 2), (8, 3, 1, 3), (5, 6, 2, 3), (16, 15, 3, 5)]:
        sols = [(m, n) for m in range(1, 400) for n in range(1, 400)
                if b * m * m - a * m * n - b * n * n == b]
        print(f"        rho = {a}/{b}: disc = {a * a + 4 * b * b} = {isqrt(a * a + 4 * b * b)}^2,"
              f"  ({e} m - {f} n)({f} m + {e} n) = {e * f},"
              f"  positive solutions with m,n < 400: {len(sols)}")
    print()


