def dist_to_vline(m: float, n: float, a: float) -> float:
    """Distance from z(m,n) to the vertical geodesic Re = a: arsinh(|x-a|/y)."""
    return math.asinh(abs(n / m - a) * m)


def demo_hypercycles() -> None:
    print("=" * 72)
    print("13. HYPERCYCLES:  A n + B m + C = 0  =>  constant distance arsinh|C/A|")
    print("=" * 72)
    print("   right spine (n fixed): distance to Re = 0 is arsinh(n)")
    for n in (1, 2, 3):
        row = [(m, dist_to_vline(m, n, 0.0)) for m in range(n + 1, n + 20, 2)]
        vals = {round(d, 12) for _, d in row}
        print(f"        n = {n}: arsinh(n) = {math.asinh(n):.9f}, "
              f"distinct measured values: {len(vals)} -> {next(iter(vals)):.9f}")
    print("   left spine (m, m-1): distance to Re = 1 is arsinh(1) = "
          f"{math.asinh(1):.9f}")
    for m in range(2, 8):
        print(f"        (m,n) = ({m},{m - 1}): {dist_to_vline(m, m - 1, 1.0):.9f}")
    print()


