def demo_dihedral_censuses() -> None:
    print("=" * 78)
    print("1.  Three censuses on the dihedral group D3 (order 6)")
    print("=" * 78)
    D3 = dihedral(3)
    rot = [("r", 1), ("r", 2)]                       # a full conjugacy class
    refl = [("s", 0), ("s", 1), ("s", 2)]            # the reflection class
    mix = [("r", 1), ("r", 2), ("s", 0)]             # inversion closed, not normal
    show_table(D3, rot, 5, "Rotation class S = {r, r^2}:")
    show_table(D3, refl, 4, "Reflection class S = {s, sr, sr^2}:")
    show_table(D3, mix, 5, "Mixed set S = {r, r^2, s}:")

    print("\n  Orbits of <inversion, Aut(G,S)> for the mixed set:")
    for orb in census_orbits(D3, mix):
        print("    {" + ", ".join(label(g) for g in orb) + "}")
    print("  Distinct census rows (lengths 0..8):")
    for lev in census_level_sets(D3, mix, 8):
        print("    {" + ", ".join(label(g) for g in lev) + "}")
    n_orb = len(census_orbits(D3, mix))
    n_lev = len(census_level_sets(D3, mix, 8))
    print(f"  orbit count = {n_orb},  distinct rows = {n_lev}   "
          f"(bound rows <= orbits: {n_lev <= n_orb}; here it is sharp)")


def demo_invariances() -> None:
    print("\n" + "=" * 78)
    print("2.  The invariance theorems, checked entry by entry")
    print("=" * 78)
    D3 = dihedral(3)
    mix = [("r", 1), ("r", 2), ("s", 0)]
    nmax = 9
    tab = census_table(D3, mix, nmax)

    ok_inv = all(tab[n][D3.index[g]] == tab[n][D3.index[D3.inv(g)]]
                 for n in range(nmax + 1) for g in D3.elements)
    print(f"  inversion invariance  W(n, g^-1) = W(n, g):           {ok_inv}")

    auts = preserving_automorphisms(D3, mix)
    ok_aut = all(tab[n][D3.index[g]] == tab[n][D3.index[sig[g]]]
                 for sig in auts for n in range(nmax + 1) for g in D3.elements)
    print(f"  {len(auts)} S-preserving automorphism(s); invariance holds: {ok_aut}")

    refl = [("s", 0), ("s", 1), ("s", 2)]
    tabr = census_table(D3, refl, nmax)
    ok_cls = all(tabr[n][D3.index[g]]
                 == tabr[n][D3.index[D3.mul(D3.mul(a, g), D3.inv(a))]]
                 for n in range(nmax + 1) for g in D3.elements for a in D3.elements)
    print(f"  class-function property for the normal set {{s,sr,sr^2}}: {ok_cls}")

    total_ok = all(sum(tab[n]) == len(mix) ** n for n in range(nmax + 1))
    print(f"  total mass  sum_g W(n, g) = |S|^n:                    {total_ok}")


def demo_return_dominance() -> None:
    print("\n" + "=" * 78)
    print("3.  Return dominance at even lengths (and its failure at odd lengths)")
    print("=" * 78)
    D3 = dihedral(3)
    rot = [("r", 1), ("r", 2)]
    tab = census_table(D3, rot, 8)
    for n in range(0, 9):
        row = tab[n]
        at_one = row[D3.index[D3.identity]]
        mx = max(row)
        flag = "max at identity" if at_one == mx else "IDENTITY NOT MAXIMAL"
        print(f"  n = {n:2d}  W(n,1) = {at_one:5d}   max_g W(n,g) = {mx:5d}   "
              f"[{'even' if n % 2 == 0 else 'odd '}]  {flag}")

    print("\n  Second-moment identity  W(2n, 1) = sum_h W(n, h)^2:")
    for n in range(0, 5):
        lhs = census_table(D3, rot, 2 * n)[2 * n][D3.index[D3.identity]]
        rowh = census_table(D3, rot, n)[n]
        rhs = sum(v * v for v in rowh)
        print(f"    n = {n}:  W({2*n}, 1) = {lhs:5d}   sum_h W({n},h)^2 = {rhs:5d}   "
              f"{'OK' if lhs == rhs else 'MISMATCH'}")


def demo_support() -> None:
    print("\n" + "=" * 78)
    print("4.  Support of the census = subgroup generated by S")
    print("=" * 78)
    D3 = dihedral(3)
    rot = [("r", 1), ("r", 2)]
    reached = set()
    for n in range(0, 13):
        for g, c in walk_count_row(D3, rot, n).items():
            if c > 0:
                reached.add(g)
    gen = set(generated_subgroup(D3, rot))
    print("  S = {r, r^2}:  reached = {" + ", ".join(sorted(label(g) for g in reached))
          + "},  <S> = {" + ", ".join(sorted(label(g) for g in gen)) + "}")
    print(f"  equal: {reached == gen};  <S> = G: {gen == set(D3.elements)}"
          "  (so the Cayley graph is disconnected)")

    mix = [("r", 1), ("r", 2), ("s", 0)]
    reached2 = set()
    for n in range(0, 13):
        for g, c in walk_count_row(D3, mix, n).items():
            if c > 0:
                reached2.add(g)
    print(f"  S = {{r, r^2, s}}:  <S> = G: {set(generated_subgroup(D3, mix)) == set(D3.elements)}"
          f",  every element reached: {reached2 == set(D3.elements)}")


def demo_directed_failure() -> None:
    print("\n" + "=" * 78)
    print("5.  Sharpness: inversion invariance fails for a directed connection set")
    print("=" * 78)
    D3 = dihedral(3)
    dir_set = [("r", 1)]
    print(f"  S = {{r}} is inversion closed: {is_inversion_closed(D3, dir_set)}")
    row1 = walk_count_row(D3, dir_set, 1)
    print(f"  W(1, r)   = {row1[('r', 1)]}")
    print(f"  W(1, r^-1)= {row1[D3.inv(('r', 1))]}   -> the two differ, "
          "so inversion invariance genuinely needs S = S^{-1}")


def demo_k44_converse() -> None:
    print("\n" + "=" * 78)
    print("6.  The converse fails: K_{4,4} as a Cayley graph on Z/8")
    print("=" * 78)
    Z8 = cyclic(8)
    odd = [1, 3, 5, 7]
    show_table(Z8, odd, 4, "Z/8 with the four odd residues:")
    print("\n  Orbits of <inversion, Aut(G,S)>:")
    for orb in census_orbits(Z8, odd):
        print("    {" + ", ".join(str(g) for g in sorted(orb)) + "}")
    print("  Distinct census rows (lengths 0..10):")
    for lev in census_level_sets(Z8, odd, 10):
        print("    {" + ", ".join(str(g) for g in sorted(lev)) + "}")
    same = census_vector(Z8, odd, 2, 10) == census_vector(Z8, odd, 4, 10)
    print(f"\n  census(2) = census(4): {same}")
    print(f"  order of 2 = {Z8.element_order(2)}, order of 4 = {Z8.element_order(4)}"
          "  ->  4 is an involution, 2 is not, so no automorphism and no")
    print("      inversion can carry 2 to 4: they are NOT census-equivalent.")
    print("  The coincidence is caused by the transposition (2 4), a graph")
    print("  automorphism of K_{4,4} fixing 0 that is not a group automorphism.")


def demo_adjacency_bridge() -> None:
    print("\n" + "=" * 78)
    print("7.  Adjacency powers and the trace formula")
    print("=" * 78)
    D3 = dihedral(3)
    mix = [("r", 1), ("r", 2), ("s", 0)]
    els = D3.elements
    N = len(els)
    A = [[1 if D3.mul(D3.inv(x), y) in mix else 0 for y in els] for x in els]
    symm = all(A[i][j] == A[j][i] for i in range(N) for j in range(N))
    print(f"  adjacency matrix symmetric (equivalently S = S^-1): {symm}")

    def matmul(X, Y):
        return [[sum(X[i][k] * Y[k][j] for k in range(N)) for j in range(N)]
                for i in range(N)]

    P = [[1 if i == j else 0 for j in range(N)] for i in range(N)]
    for n in range(0, 7):
        row = walk_count_row(D3, mix, n)
        entries_ok = all(P[i][j] == row[D3.mul(D3.inv(els[i]), els[j])]
                         for i in range(N) for j in range(N))
        tr = sum(P[i][i] for i in range(N))
        print(f"  n = {n}:  (A^n)_{{x,y}} = W(n, x^-1 y): {entries_ok};  "
              f"tr(A^n) = {tr:6d} = |G| * W(n,1) = {N * row[D3.identity]:6d}")
        P = matmul(P, A)


def main() -> None:
    demo_dihedral_censuses()
    demo_invariances()
    demo_return_dominance()
    demo_support()
    demo_directed_failure()
    demo_k44_converse()
    demo_adjacency_bridge()
    print("\nAll demonstrations completed.")


if __name__ == "__main__":
    main()
