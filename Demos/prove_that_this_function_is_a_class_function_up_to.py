"""
Cayley Walk Censuses: numerical demonstrations
==============================================

For a finite group G and a "connection set" S subset of G, the *walk census* is

    W(S, n, g) = #{ (s_1, ..., s_n) in S^n : s_1 * s_2 * ... * s_n = g },

the number of walks of length n from the identity to g in the Cayley graph
Cay(G, S).  This script demonstrates, on explicit finite groups, the results of
the accompanying paper:

  1.  Inversion invariance:  W(S, n, g^{-1}) = W(S, n, g) when S = S^{-1}.
  2.  Automorphism invariance: W(S, n, sigma g) = W(S, n, g) for every
      automorphism sigma of G with sigma(S) = S.
  3.  The class-function property when S is a union of conjugacy classes.
  4.  The orbit bound: the number of distinct census rows is at most the number
      of orbits of the group generated by inversion and Aut(G, S).
  5.  Return dominance at even lengths: W(S, 2n, g) <= W(S, 2n, 1), together
      with the failure of the statement at odd lengths.
  6.  The support theorem: W(S, n, g) > 0 for some n iff g lies in the subgroup
      generated by S.
  7.  Sharpness: inversion invariance fails for directed connection sets, and
      the converse of the orbit theorem fails for the complete bipartite graph
      K_{4,4} realised as a Cayley graph on Z/8.

Everything is self-contained: groups are represented as explicit multiplication
tables over a list of element labels.
"""

from __future__ import annotations

from itertools import product
from typing import Callable, Dict, Iterable, List, Sequence, Tuple

# ---------------------------------------------------------------------------
# A tiny finite-group toolkit
# ---------------------------------------------------------------------------


class FiniteGroup:
    """A finite group given by a list of elements and a multiplication rule."""

    def __init__(self, elements: Sequence, mul: Callable[[object, object], object],
                 name: str = "G") -> None:
        self.elements: List = list(elements)
        self.mul = mul
        self.name = name
        self.index: Dict[object, int] = {g: i for i, g in enumerate(self.elements)}
        self.identity = self._find_identity()
        self._inv: Dict[object, object] = {g: self._find_inverse(g) for g in self.elements}

    def _find_identity(self):
        for e in self.elements:
            if all(self.mul(e, g) == g and self.mul(g, e) == g for g in self.elements):
                return e
        raise ValueError("no identity element found")

    def _find_inverse(self, g):
        for h in self.elements:
            if self.mul(g, h) == self.identity:
                return h
        raise ValueError(f"no inverse for {g}")

    def inv(self, g):
        return self._inv[g]

    def order(self) -> int:
        return len(self.elements)

    def element_order(self, g) -> int:
        n, x = 1, g
        while x != self.identity:
            x = self.mul(x, g)
            n += 1
        return n

    def automorphisms(self) -> List[Dict[object, object]]:
        """All automorphisms, found by brute force over images of a generating set."""
        gens = self.generating_set()
        candidates: List[Dict[object, object]] = []
        for images in product(self.elements, repeat=len(gens)):
            sigma = self._extend(dict(zip(gens, images)))
            if sigma is not None and sigma not in candidates:
                candidates.append(sigma)
        return candidates

    def generating_set(self) -> List:
        """A small generating set, found greedily."""
        gens: List = []
        for g in self.elements:
            if g == self.identity:
                continue
            if len(self.subgroup_closure(gens)) < self.order():
                if g not in self.subgroup_closure(gens):
                    gens.append(g)
        return gens

    def subgroup_closure(self, gens: Iterable) -> List:
        """The subgroup generated by `gens` (closed under products and inverses)."""
        gens = list(gens)
        closure = {self.identity}
        frontier = [self.identity]
        gens_full = list(gens) + [self.inv(g) for g in gens]
        while frontier:
            x = frontier.pop()
            for s in gens_full:
                y = self.mul(x, s)
                if y not in closure:
                    closure.add(y)
                    frontier.append(y)
        return [g for g in self.elements if g in closure]

    def _extend(self, partial: Dict[object, object]):
        """Extend a map on generators to an automorphism, or return None."""
        sigma: Dict[object, object] = {self.identity: self.identity}
        sigma.update(partial)
        changed = True
        while changed:
            changed = False
            for a, b in product(list(sigma.keys()), repeat=2):
                ab = self.mul(a, b)
                image = self.mul(sigma[a], sigma[b])
                if ab in sigma:
                    if sigma[ab] != image:
                        return None
                else:
                    sigma[ab] = image
                    changed = True
        if len(sigma) != self.order():
            return None
        if len(set(sigma.values())) != self.order():
            return None
        for a, b in product(self.elements, repeat=2):
            if sigma[self.mul(a, b)] != self.mul(sigma[a], sigma[b]):
                return None
        return sigma


# ---------------------------------------------------------------------------
# The census
# ---------------------------------------------------------------------------


def walk_count_row(G: FiniteGroup, S: Sequence, n: int) -> Dict[object, int]:
    """W(S, n, .) for all g, computed by n convolutions.  Cost O(n |G| |S|)."""
    row: Dict[object, int] = {g: 0 for g in G.elements}
    row[G.identity] = 1
    for _ in range(n):
        new: Dict[object, int] = {g: 0 for g in G.elements}
        for g, c in row.items():
            if c:
                for s in S:
                    new[G.mul(g, s)] += c
        row = new
    return row


def census_table(G: FiniteGroup, S: Sequence, nmax: int) -> List[List[int]]:
    """Rows indexed by length n = 0..nmax, columns by the elements of G."""
    table: List[List[int]] = []
    row: Dict[object, int] = {g: 0 for g in G.elements}
    row[G.identity] = 1
    for _ in range(nmax + 1):
        table.append([row[g] for g in G.elements])
        new: Dict[object, int] = {g: 0 for g in G.elements}
        for g, c in row.items():
            if c:
                for s in S:
                    new[G.mul(g, s)] += c
        row = new
    return table


def census_vector(G: FiniteGroup, S: Sequence, g, nmax: int) -> Tuple[int, ...]:
    """The census row of a single element g, truncated at length nmax."""
    return tuple(census_table(G, S, nmax)[n][G.index[g]] for n in range(nmax + 1))


def is_inversion_closed(G: FiniteGroup, S: Sequence) -> bool:
    return all(G.inv(s) in S for s in S)


def preserving_automorphisms(G: FiniteGroup, S: Sequence) -> List[Dict[object, object]]:
    Sset = set(S)
    return [sig for sig in G.automorphisms() if {sig[s] for s in Sset} == Sset]


def census_orbits(G: FiniteGroup, S: Sequence) -> List[List]:
    """Orbits of the group generated by inversion and the S-preserving automorphisms."""
    auts = preserving_automorphisms(G, S)
    parent = {g: g for g in G.elements}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x, y):
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[rx] = ry

    for g in G.elements:
        union(g, G.inv(g))
        for sig in auts:
            union(g, sig[g])
    buckets: Dict[object, List] = {}
    for g in G.elements:
        buckets.setdefault(find(g), []).append(g)
    return list(buckets.values())


def census_level_sets(G: FiniteGroup, S: Sequence, nmax: int) -> List[List]:
    table = census_table(G, S, nmax)
    buckets: Dict[Tuple[int, ...], List] = {}
    for j, g in enumerate(G.elements):
        key = tuple(table[n][j] for n in range(nmax + 1))
        buckets.setdefault(key, []).append(g)
    return list(buckets.values())


def generated_subgroup(G: FiniteGroup, S: Sequence) -> List:
    return G.subgroup_closure(S)


# ---------------------------------------------------------------------------
# Two concrete groups
# ---------------------------------------------------------------------------


def dihedral(n: int) -> FiniteGroup:
    """D_n of order 2n.  Elements ('r', i) (rotations) and ('s', i) (reflections),
    with the multiplication rules
        r_i r_j = r_{i+j},  r_i s_j = s_{j-i},  s_i r_j = s_{i+j},  s_i s_j = r_{j-i}.
    """
    els = [("r", i) for i in range(n)] + [("s", i) for i in range(n)]

    def mul(a, b):
        (ta, ia), (tb, ib) = a, b
        if ta == "r" and tb == "r":
            return ("r", (ia + ib) % n)
        if ta == "r" and tb == "s":
            return ("s", (ib - ia) % n)
        if ta == "s" and tb == "r":
            return ("s", (ia + ib) % n)
        return ("r", (ib - ia) % n)

    return FiniteGroup(els, mul, name=f"D{n}")


def cyclic(n: int) -> FiniteGroup:
    """Z/n, written multiplicatively as integers mod n under addition."""
    return FiniteGroup(list(range(n)), lambda a, b: (a + b) % n, name=f"Z{n}")


def label(g) -> str:
    if isinstance(g, tuple):
        t, i = g
        return f"{'r' if t == 'r' else 'sr'}{i}"
    return str(g)


def show_table(G: FiniteGroup, S: Sequence, nmax: int, title: str) -> None:
    print(f"\n{title}")
    print("  connection set S = {" + ", ".join(label(s) for s in S) + "}"
          + ("   (inversion closed)" if is_inversion_closed(G, S)
             else "   (NOT inversion closed)"))
    header = "  n |" + "".join(f"{label(g):>8}" for g in G.elements)
    print(header)
    print("  " + "-" * (len(header) - 2))
    for n, row in enumerate(census_table(G, S, nmax)):
        print(f"  {n} |" + "".join(f"{v:>8}" for v in row))


