# 3.  Empirical verification on real primes
# ---------------------------------------------------------------------------

def primes_up_to(limit: int) -> List[int]:
    sieve = bytearray([1]) * (limit + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(limit ** 0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = bytearray(len(sieve[i * i::i]))
    return [i for i in range(limit + 1) if sieve[i]]


def count_roots_mod_p(coeffs: Sequence[int], p: int) -> int:
    """Number of x in F_p with sum coeffs[i] x^i = 0 (coeffs in ascending degree)."""
    total = 0
    for x in range(p):
        acc = 0
        xp = 1
        for c in coeffs:
            acc = (acc + c * xp) % p
            xp = (xp * x) % p
        if acc == 0:
            total += 1
    return total


def demo_primes(limit: int = 60000) -> None:
    print()
    print("=" * 78)
    print(f"3.  EMPIRICAL VERIFICATION ON PRIMES UP TO {limit}")
    print("=" * 78)
    ps = [p for p in primes_up_to(limit) if p > 5]

    # (a) cyclic cubic of conductor 7 : x^3 + x^2 - 2x - 1
    f1 = (-1, -2, 1, 1)
    good = [p for p in ps if p % 7 != 0]
    split = [count_roots_mod_p(f1, p) == 3 for p in good]
    residue = [p % 7 for p in good]
    rule = [r in (1, 6) for r in residue]
    exceptions = sum(1 for a, b in zip(split, rule) if a != b)
    print("\n (a) x^3 + x^2 - 2x - 1  (cyclic cubic, conductor 7)")
    print(f"     primes tested: {len(good)}")
    print(f"     'splits completely  <=>  p = +-1 mod 7' exceptions: {exceptions}")
    print(f"     density of totally split: {sum(split)/len(split):.6f}  (predicted 1/3)")
    print(f"     I(p mod 7 ; fork)  = {bits(mutual_information(residue, split)):.6f} bits"
          f"   (theory {bits(math.log(3) - (2/3)*LOG2):.6f})")
    control = [p % 5 for p in good]
    print(f"     I(p mod 5 ; fork)  = {bits(mutual_information(control, split)):.6f} bits"
          f"   (coprime control: predicted 0, small positive = finite-sample bias)")
    types = {}
    for p in good:
        r = count_roots_mod_p(f1, p)
        types[r] = types.get(r, 0) + 1
    print(f"     root-count histogram: {dict(sorted(types.items()))}"
          f"   (Galois cubic: only 0 or 3 roots, never exactly 1)")

    # (b) S3 cubic : x^3 + x + 1, discriminant -31
    f2 = (1, 1, 0, 1)
    good2 = [p for p in ps if p % 31 != 0]
    split2 = [count_roots_mod_p(f2, p) == 3 for p in good2]
    res31 = [p % 31 for p in good2]
    # the sign of the Frobenius = Legendre symbol of the discriminant -31
    legendre = [pow((-31) % p, (p - 1) // 2, p) == 1 for p in good2]
    print("\n (b) x^3 + x + 1  (S3 closure, discriminant -31), G^ab = C2")
    print(f"     density of totally split: {sum(split2)/len(split2):.6f}  (predicted 1/6)")
    i_sign = mutual_information(legendre, split2)
    i_mod = mutual_information(res31, split2)
    theory_s3 = (4 / 3) * LOG2 + 0.5 * math.log(3) - (5 / 6) * math.log(5)
    print(f"     I(sign ; fork)     = {bits(i_sign):.6f} bits   (theory {bits(theory_s3):.6f})")
    print(f"     I(p mod 31 ; fork) = {bits(i_mod):.6f} bits   (excess over the sign is"
          f" finite-sample bias: {bits(i_mod - i_sign):+.6f})")
    qr = [i for i, s in enumerate(legendre) if s]
    face = [split2[i] for i in qr]
    print(f"     on the quadratic-residue face, density of [1,1,1] ="
          f" {sum(face)/len(face):.6f}  (predicted 1/3, and the face fork is flat)")

    # (c) S4 quartic : x^4 - x - 1, discriminant -283
    f3 = (-1, -1, 0, 0, 1)
    good3 = [p for p in ps if p % 283 != 0]
    nroots = [count_roots_mod_p(f3, p) for p in good3]
    hist = {k: nroots.count(k) for k in (0, 1, 2, 4)}
    m = len(good3)
    print("\n (c) x^4 - x - 1  (S4 closure, discriminant -283)")
    print("     root-count densities  (predicted 4:2:1:0 = 1/24 : 6/24 : 8/24 : 9/24)")
    for k, pred in [(4, 1 / 24), (2, 6 / 24), (1, 8 / 24), (0, 9 / 24)]:
        print(f"       {k} roots: measured {hist[k]/m:.5f}   predicted {pred:.5f}")
    hasroot = [r > 0 for r in nroots]
    legendre3 = [pow((-283) % p, (p - 1) // 2, p) == 1 for p in good3]
    theory_s4 = 1.5 * LOG2 - (5 / 8) * math.log(5)
    print(f"     I(sign ; has root) = {bits(mutual_information(legendre3, hasroot)):.6f} bits"
          f"   (theory {bits(theory_s4):.6f})")
    even = [i for i, s in enumerate(legendre3) if s]
    face4 = [nroots[i] for i in even]
    d1 = sum(1 for r in face4 if r == 4) / len(face4)
    d2 = sum(1 for r in face4 if r == 0) / len(face4)
    d3 = sum(1 for r in face4 if r == 1) / len(face4)
    print(f"     even-face densities [1,1,1,1] / [2,2] / [1,3] ="
          f" {d1:.4f} / {d2:.4f} / {d3:.4f}   (predicted 1/12, 3/12, 8/12)")


