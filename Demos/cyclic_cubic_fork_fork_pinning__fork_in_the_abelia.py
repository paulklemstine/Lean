# 1-2.  Exact values for C3, S3, S4, A5
# ---------------------------------------------------------------------------

def demo_galois_groups() -> None:
    print("=" * 78)
    print("1-2.  EXACT FORK INFORMATION IN THE CHEBOTAREV MODEL")
    print("=" * 78)

    # (a) cyclic cubic: G = C3, realised as the 3-cycles acting on 3 points.
    c3: List[Perm] = [(0, 1, 2), (1, 2, 0), (2, 0, 1)]
    closed_c3 = math.log(3) - (2 / 3) * LOG2
    print("\n (a) Cyclic cubic field, G = C3  (e.g. x^3 + x^2 - 2x - 1, conductor 7)")
    fork_report("fork [1,1,1] (Frobenius trivial), observable = full residue class",
                c3, lambda g: g, lambda g: g == (0, 1, 2), closed_c3)

    # (b) S3 cubic: only the sign is visible.
    s3 = symmetric_group(3)
    closed_s3 = (4 / 3) * LOG2 + 0.5 * math.log(3) - (5 / 6) * math.log(5)
    print("\n (b) S3 cubic  (e.g. x^3 + x + 1, discriminant -31), G^ab = C2")
    fork_report("fork [1,1,1], observable = sign",
                s3, sign, lambda g: g == (0, 1, 2), closed_s3)
    identity_deficit = entropy([g == (0, 1, 2) for g in s3]) - 0.5 * closed_c3
    print(f"     structural identity  I = H(fork) - H(1/3)/2 :"
          f" {bits(identity_deficit):.6f} bits  vs  {bits(closed_s3):.6f} bits")

    # the A3 face is exactly flat
    a3 = alternating_group(3)
    flat = mutual_information([sign(g) for g in a3], [g == (0, 1, 2) for g in a3])
    print(f"     A3-face fork (restrict to even permutations): I = {bits(flat):.6f} bits")

    # (c) S4 quartic
    s4 = symmetric_group(4)
    closed_s4 = 1.5 * LOG2 - (5 / 8) * math.log(5)
    print("\n (c) S4 quartic  (e.g. x^4 - x - 1, discriminant -283)")
    counts = {k: 0 for k in range(5)}
    for g in s4:
        counts[sum(1 for i in range(4) if g[i] == i)] += 1
    print(f"     fixed-point counts 4:2:1:0 = {counts[4]}:{counts[2]}:{counts[1]}:{counts[0]}"
          f" out of 24   (predicted 1:6:8:9)")
    fork_report("fork 'has a root', observable = sign",
                s4, sign, lambda g: any(g[i] == i for i in range(4)), closed_s4)
    a4 = alternating_group(4)
    for label, f in [("[1,1,1,1] vs rest (even face)", lambda g: g == (0, 1, 2, 3)),
                     ("[2,2] vs rest (even face)", lambda g: cycle_type(g) == (2, 2)),
                     ("[1,3] vs rest (even face)", lambda g: cycle_type(g) == (1, 3))]:
        val = mutual_information([sign(g) for g in a4], [f(g) for g in a4])
        print(f"     within-face fork {label:32s} I = {bits(val):.6f} bits")

    # (d) A5 is congruence-blind
    a5 = alternating_group(5)
    comm5 = commutator_subgroup(a5)
    print("\n (d) A5 closure: perfect group")
    print(f"     |[A5,A5]| = {len(comm5)} = |A5| = {len(a5)}  => abelianization trivial")
    for label, f in [("has a fixed point", lambda g: any(g[i] == i for i in range(5))),
                     ("is a 5-cycle", lambda g: cycle_type(g) == (5,)),
                     ("is the identity", lambda g: g == (0, 1, 2, 3, 4))]:
        val = mutual_information([sign(g) for g in a5], [f(g) for g in a5])
        print(f"     fork '{label:20s}'  I(any abelian character) = {bits(val):.6f} bits")


