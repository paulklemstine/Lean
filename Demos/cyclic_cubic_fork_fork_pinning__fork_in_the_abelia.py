"""
Fork-Pinning: numerical demonstrations
======================================

Self-contained numerical companion to "Fork-Pinning: An Information-Theoretic
Criterion for Congruence Determination of Prime Splitting".

Everything here is elementary and dependency-free (standard library only).

What is demonstrated
--------------------
1.  The Chebotarev model: exact fork information for the Galois groups
    C3, S3, S4 and A5, compared with the closed forms
        cyclic cubic   I = H = log 3 - (2/3) log 2        = 0.9183 bits
        S3 cubic       I = (4/3)log2 + (1/2)log3 - (5/6)log5 = 0.1909 bits
        S4 quartic     I = (3/2)log2 - (5/8)log5          = 0.0488 bits
        A5             I = 0 for every fork
2.  The fork-pinning criterion: pinned  <=>  invariant under commutators
    <=>  factors through the abelianization.  Decided by direct enumeration.
3.  Empirical verification on real primes:
        x^3 + x^2 - 2x - 1 splits completely  <=>  p = +-1 mod 7   (exact)
        x^3 + x + 1        has no congruence rule; only the sign is visible
        x^4 - x - 1        root counts 4:2:1:0 in ratio 1:6:8:9 out of 24
4.  Capacity: I <= log 2 for any binary fork, attained exactly at balanced
    pinned forks; in S_n only by the sign and its negation.
5.  The coset profile  Phi(d) = h(d) - h(2d)/2: sharp bound for an
    index-two conductor, strictly increasing, Phi(d)/d -> log 2,
    Phi(d)/h(d) -> 0.
6.  The semiprime barrier: universal dial D(n), the quadratic collapse
    n^2 D(n) -> 1 - log 2 = 0.30685, and the exactly-zero which-factor wall.

Run:  python3 demo.py
"""

from __future__ import annotations

import itertools
import math
from typing import Callable, Dict, Iterable, List, Sequence, Tuple

Perm = Tuple[int, ...]

LOG2 = math.log(2.0)


# ---------------------------------------------------------------------------
# Information theory on a finite uniform space
# ---------------------------------------------------------------------------

def eta(t: float) -> float:
    """-t log t, with eta(0) = 0."""
    return 0.0 if t <= 0.0 else -t * math.log(t)


def entropy(values: Sequence[object]) -> float:
    """Entropy (nats) of the empirical law of a list of outcomes."""
    n = len(values)
    counts: Dict[object, int] = {}
    for v in values:
        counts[v] = counts.get(v, 0) + 1
    return sum(eta(c / n) for c in counts.values())


def mutual_information(xs: Sequence[object], ys: Sequence[object]) -> float:
    """I(X;Y) = H(X) + H(Y) - H(X,Y) in nats, for paired samples."""
    return entropy(xs) + entropy(ys) - entropy(list(zip(xs, ys)))


def bits(nats: float) -> float:
    return nats / LOG2


def binary_entropy(d: float) -> float:
    return eta(d) + eta(1.0 - d)


# ---------------------------------------------------------------------------
# Permutation groups as explicit lists of tuples
# ---------------------------------------------------------------------------

def symmetric_group(n: int) -> List[Perm]:
    return [tuple(p) for p in itertools.permutations(range(n))]


def compose(a: Perm, b: Perm) -> Perm:
    """(a*b)(i) = a(b(i))."""
    return tuple(a[b[i]] for i in range(len(a)))


def inverse(a: Perm) -> Perm:
    out = [0] * len(a)
    for i, ai in enumerate(a):
        out[ai] = i
    return tuple(out)


def sign(a: Perm) -> int:
    """+1 or -1, computed from the parity of the number of transpositions."""
    seen = [False] * len(a)
    parity = 0
    for i in range(len(a)):
        if not seen[i]:
            j, length = i, 0
            while not seen[j]:
                seen[j] = True
                j = a[j]
                length += 1
            parity += length - 1
    return 1 if parity % 2 == 0 else -1


def alternating_group(n: int) -> List[Perm]:
    return [p for p in symmetric_group(n) if sign(p) == 1]


def cycle_type(a: Perm) -> Tuple[int, ...]:
    seen = [False] * len(a)
    parts: List[int] = []
    for i in range(len(a)):
        if not seen[i]:
            j, length = i, 0
            while not seen[j]:
                seen[j] = True
                j = a[j]
                length += 1
            parts.append(length)
    return tuple(sorted(parts))


def commutator_subgroup(group: Sequence[Perm]) -> List[Perm]:
    """Subgroup generated by all commutators [g,h] = g h g^-1 h^-1."""
    gens = {compose(compose(g, h), compose(inverse(g), inverse(h)))
            for g in group for h in group}
    identity = tuple(range(len(group[0])))
    closure = {identity}
    frontier = [identity]
    while frontier:
        x = frontier.pop()
        for s in gens:
            y = compose(x, s)
            if y not in closure:
                closure.add(y)
                frontier.append(y)
    return sorted(closure)


# ---------------------------------------------------------------------------
# The fork-pinning criterion, decided by enumeration
# ---------------------------------------------------------------------------

def is_commutator_invariant(group: Sequence[Perm],
                            fork: Callable[[Perm], bool]
                            ) -> Tuple[bool, Tuple[Perm, Perm] | None]:
    """Test Y(g c) = Y(g) for all g in G, c in [G,G]; return a witness if not."""
    comm = commutator_subgroup(group)
    for g in group:
        for c in comm:
            if fork(compose(g, c)) != fork(g):
                return False, (g, c)
    return True, None


def fork_report(name: str,
                group: Sequence[Perm],
                observable: Callable[[Perm], object],
                fork: Callable[[Perm], bool],
                closed_form: float | None = None) -> None:
    xs = [observable(g) for g in group]
    ys = [fork(g) for g in group]
    h_y = entropy(ys)
    info = mutual_information(xs, ys)
    pinned_fraction = info / h_y if h_y > 0 else float("nan")
    invariant, witness = is_commutator_invariant(group, fork)
    print(f"  {name}")
    print(f"     P[fork] = {sum(ys)}/{len(ys)} = {sum(ys)/len(ys):.6f}")
    print(f"     H(fork) = {bits(h_y):.6f} bits")
    print(f"     I(obs;fork) = {bits(info):.6f} bits", end="")
    if closed_form is not None:
        print(f"   (closed form {bits(closed_form):.6f} bits,"
              f" |diff| = {abs(bits(info) - bits(closed_form)):.2e})")
    else:
        print()
    print(f"     pinned fraction I/H = {pinned_fraction:.6f}")
    print(f"     commutator-invariant (=> pinnable): {invariant}"
          + ("" if invariant else f"   witness g,c with Y(gc) != Y(g): {witness}"))


