# 4.  Capacity of a binary fork
# ---------------------------------------------------------------------------

def demo_capacity() -> None:
    print()
    print("=" * 78)
    print("4.  CAPACITY OF A BINARY FORK:  I <= log 2, attained iff determined + balanced")
    print("=" * 78)
    for n in (2, 3, 4):
        group = symmetric_group(n)
        attaining: List[str] = []
        # enumerate all forks of S_n that are measurable w.r.t. the sign
        for label, fork in [("sign", lambda g: sign(g) == 1),
                            ("not sign", lambda g: sign(g) == -1),
                            ("constant true", lambda g: True),
                            ("constant false", lambda g: False),
                            ("is identity", lambda g: g == tuple(range(len(g)))),
                            ("has a fixed point",
                             lambda g: any(g[i] == i for i in range(len(g))))]:
            xs = [sign(g) for g in group]
            ys = [fork(g) for g in group]
            info = mutual_information(xs, ys)
            tag = "  <-- attains capacity" if abs(info - LOG2) < 1e-12 else ""
            if tag:
                attaining.append(label)
            print(f"   S{n}: fork {label:20s} I(sign;fork) = {bits(info):.6f} bits{tag}")
        print(f"   S{n}: forks attaining log 2 among those tested: {attaining}")
        print(f"       P[sign = +1] = {sum(1 for g in group if sign(g) == 1)/len(group):.4f}"
              f"  (balanced, as required)\n")


# ---------------------------------------------------------------------------
# 5.  The coset profile of an index-two conductor
# ---------------------------------------------------------------------------

def coset_profile(d: float) -> float:
    """Phi(d) = h(d) - h(2d)/2, the sharp bound for a balanced observable."""
    return binary_entropy(d) - binary_entropy(2 * d) / 2


def demo_profile() -> None:
    print("=" * 78)
    print("5.  THE EXTREMAL COSET PROFILE  Phi(d) = h(d) - h(2d)/2")
    print("=" * 78)
    print("     d        Phi(d) [bits]   Phi(d)/d      Phi(d)/h(d)   |Phi - d log2| <= 4d^2")
    for d in (0.001, 0.005, 0.01, 0.05, 0.1, 0.2, 0.3, 0.4, 0.49, 0.5):
        phi = coset_profile(d)
        frac = phi / binary_entropy(d) if d > 0 else 0.0
        err = abs(phi - d * LOG2)
        ok = "ok" if d > 0.25 or err <= 4 * d * d + 1e-15 else "FAIL"
        print(f"   {d:6.3f}   {bits(phi):12.6f}   {phi/d:10.6f}   {frac:11.6f}   {ok}")
    print(f"     Phi(1/2) = {bits(coset_profile(0.5)):.6f} bits = log 2 : capacity reached")
    print("     strictly increasing on [0, 1/2]: "
          f"{all(coset_profile(d) < coset_profile(d + 0.001) for d in [i/1000 for i in range(0, 499)])}")

    # Sharpness: a single-coset fork attains the profile exactly.
    s4 = symmetric_group(4)
    xs = [sign(g) for g in s4]
    for label, fork in [("identity only (single coset, d = 1/24)",
                         lambda g: g == (0, 1, 2, 3)),
                        ("double transpositions (single coset, d = 3/24)",
                         lambda g: cycle_type(g) == (2, 2)),
                        ("transpositions (single coset, d = 6/24)",
                         lambda g: cycle_type(g) == (1, 1, 2))]:
        ys = [fork(g) for g in s4]
        d = sum(ys) / len(ys)
        print(f"   {label:48s} I = {bits(mutual_information(xs, ys)):.6f}"
              f"  Phi(d) = {bits(coset_profile(d)):.6f}")


# ---------------------------------------------------------------------------
# 6.  The semiprime barrier
# ---------------------------------------------------------------------------

def semiprime_dial(n: float) -> float:
    """Closed form D(n) of the semiprime-level mutual information (nats)."""
    return math.log(n) + (
        -(2 * n - 1) * math.log(2 * n - 1)
        + (n - 1) * (3 - 2 * n) * math.log(n - 1)
        + 2 * (n - 1) * LOG2
        + ((n - 1) * (n - 2) * math.log(n - 2) if n > 2 else 0.0)
    ) / (n * n)


def demo_semiprime() -> None:
    print()
    print("=" * 78)
    print("6.  THE SEMIPRIME BARRIER")
    print("=" * 78)

    # Brute-force check of the closed form on C3 x C3 and on S3 x S3.
    for name, group, mul, ident in [
        ("C3", [0, 1, 2], lambda a, b: (a + b) % 3, 0),
        ("S3", symmetric_group(3), compose, (0, 1, 2)),
        ("C4", [0, 1, 2, 3], lambda a, b: (a + b) % 4, 0),
        ("S4", symmetric_group(4), compose, (0, 1, 2, 3)),
    ]:
        pairs = [(a, b) for a in group for b in group]
        classes = [mul(a, b) for a, b in pairs]
        or_fork = [a == ident or b == ident for a, b in pairs]
        first = [a for a, _ in pairs]
        n = len(group)
        i_or = mutual_information(classes, or_fork)
        i_which = mutual_information(classes, first)
        print(f"\n   G = {name}, n = {n}")
        print(f"     I(class of N ; [p splits OR q splits]) = {bits(i_or):.6f} bits"
              f"   closed form {bits(semiprime_dial(n)):.6f}")
        print(f"     P[OR] = {sum(or_fork)}/{n*n} = {(2*n-1)}/{n*n}")
        print(f"     collapse bound 1/((2n-1)(n-1)) = "
              f"{bits(1/((2*n-1)*(n-1))):.6f} bits   (satisfied: {i_or <= 1/((2*n-1)*(n-1))})")
        print(f"     WHICH-FACTOR WALL  I(class of N ; first factor) = {bits(i_which):.3e} bits"
              f"   (exactly 0)")

    print("\n   Universal dial and the sharp constant  n^2 D(n) -> 1 - log 2 = "
          f"{1 - LOG2:.6f}")
    print("     n        D(n) [bits]      n^2 D(n) [nats]   |n^2 D - (1-log2)|")
    for n in (2, 3, 4, 5, 10, 24, 60, 120, 1000, 10 ** 5):
        d = semiprime_dial(float(n))
        print(f"   {n:7d}   {bits(d):13.8f}   {n*n*d:15.8f}   {abs(n*n*d - (1-LOG2)):.6f}")
    print(f"     exact value at n = 2 : 4 D(2) = 3 log(4/3) = {3*math.log(4/3):.6f}"
          f"  (computed {4*semiprime_dial(2.0):.6f})")
    print("     budget n^2 D(n) < 1 for all n: "
          f"{all(n*n*semiprime_dial(float(n)) < 1 for n in range(2, 500))}")

    # The k-factor wall.
    print("\n   k-factor wall (products of k+1 uniform elements of C3):")
    g = [0, 1, 2]
    for k in (1, 2, 3):
        tuples = list(itertools.product(g, repeat=k + 1))
        prod = [sum(t) % 3 for t in tuples]
        stat = [any(x == 0 for x in t[:k]) for t in tuples]
        print(f"     k = {k}:  I(class of the product ; 'some of the first {k} splits')"
              f" = {bits(mutual_information(prod, stat)):.3e} bits")


def main() -> None:
    demo_galois_groups()
    demo_primes()
    demo_capacity()
    demo_profile()
    demo_semiprime()
    print()
    print("=" * 78)
    print("All demonstrations complete.")
    print("=" * 78)


