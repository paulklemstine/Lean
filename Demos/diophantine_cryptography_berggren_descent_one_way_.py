# The three Berggren generators (matching the Lean formalization)
BERGGREN_MATRICES = {
    0: np.array([[1, -2, 2], [2, -1, 2], [2, -2, 3]]),  # U (left)
    1: np.array([[1, 2, 2], [2, 1, 2], [2, 2, 3]]),      # A (middle)
    2: np.array([[-1, 2, 2], [-2, 1, 2], [-2, 2, 3]]),   # D (right)
}

ROOT_TRIPLE = np.array([3, 4, 5])

MINKOWSKI_METRIC = np.diag([1, 1, -1])


def berggren_word_matrix(word: List[int]) -> np.ndarray:
    """Compute the matrix product U_w for a Berggren word w."""
    result = np.eye(3, dtype=int)
    for i in word:
        result = BERGGREN_MATRICES[i] @ result
    return result


def berggren_word_triple(word: List[int]) -> np.ndarray:
    """Compute the Pythagorean triple generated by word w."""
    return berggren_word_matrix(word) @ ROOT_TRIPLE


def minkowski_form(v: np.ndarray) -> int:
    """Compute Q(a,b,c) = a² + b² - c²."""
    return int(v[0]**2 + v[1]**2 - v[2]**2)


def berggren_hash(word: List[int], p: int) -> Tuple[int, int, int]:
    """Compute H_p(w) = U_w · (3,4,5)^T mod p."""
    triple = berggren_word_triple(word)
    return tuple(int(x) % p for x in triple)


