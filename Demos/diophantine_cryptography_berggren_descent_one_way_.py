def create_visualization():
    """Create a visualization of the Berggren tree and hash function."""
    fig, axes = plt.subplots(2, 2, figsize=(14, 12))

    # Plot 1: Berggren tree (first 3 levels)
    ax = axes[0, 0]
    ax.set_title("Berggren Tree of Pythagorean Triples", fontsize=12, fontweight='bold')

    def draw_tree(ax, word, x, y, dx, level_max=3):
        triple = berggren_word_triple(word)
        label = f"({triple[0]},{triple[1]},{triple[2]})"
        ax.annotate(label, (x, y), ha='center', va='center',
                    bbox=dict(boxstyle='round,pad=0.3', facecolor='lightblue',
                              edgecolor='navy', alpha=0.8),
                    fontsize=7)
        if len(word) < level_max:
            for i, color in enumerate(['#e74c3c', '#2ecc71', '#3498db']):
                child_x = x + (i - 1) * dx
                child_y = y - 1
                ax.plot([x, child_x], [y - 0.3, child_y + 0.3], color=color,
                        linewidth=1.5, alpha=0.7)
                draw_tree(ax, word + [i], child_x, child_y, dx / 3, level_max)

    draw_tree(ax, [], 0, 3, 3, level_max=3)
    ax.set_xlim(-5, 5)
    ax.set_ylim(-1, 4)
    ax.axis('off')

    # Plot 2: Hypotenuse growth with depth
    ax = axes[0, 1]
    ax.set_title("Hypotenuse Growth vs. Tree Depth", fontsize=12, fontweight='bold')

    import random
    random.seed(42)
    depths = list(range(12))
    min_hyps = []
    avg_hyps = []
    max_hyps = []

    for d in depths:
        hyps = []
        for _ in range(min(200, 3**d)):
            word = [random.randint(0, 2) for _ in range(d)]
            triple = berggren_word_triple(word)
            hyps.append(int(triple[2]))
        min_hyps.append(min(hyps))
        avg_hyps.append(np.mean(hyps))
        max_hyps.append(max(hyps))

    ax.fill_between(depths, min_hyps, max_hyps, alpha=0.2, color='blue', label='Range')
    ax.plot(depths, avg_hyps, 'b-o', markersize=4, label='Mean hypotenuse')
    ax.plot(depths, [5 + 2*d for d in depths], 'r--', label='Bound: 5 + 2k')
    ax.set_xlabel("Word length k")
    ax.set_ylabel("Hypotenuse c")
    ax.set_yscale('log')
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)

    # Plot 3: Modular hash distribution
    ax = axes[1, 0]
    ax.set_title("Hash Distribution mod p=31", fontsize=12, fontweight='bold')

    p = 31
    from itertools import product as iproduct
    hash_counts = np.zeros((p, p))
    for length in range(4):
        for word_tuple in iproduct(range(3), repeat=length):
            word = list(word_tuple)
            h = berggren_hash(word, p)
            hash_counts[h[0] % p, h[1] % p] += 1

    im = ax.imshow(hash_counts, cmap='YlOrRd', aspect='auto')
    ax.set_xlabel("a mod 31")
    ax.set_ylabel("b mod 31")
    plt.colorbar(im, ax=ax, label="# of words")

    # Plot 4: Collision resistance
    ax = axes[1, 1]
    ax.set_title("Collision Resistance: Distinct Triples vs. Words", fontsize=12,
                 fontweight='bold')

    lengths = list(range(1, 7))
    total_words = [3**k for k in lengths]
    distinct_triples_int = []
    distinct_triples_mod = []

    for k in lengths:
        triples_z = set()
        triples_mod = set()
        p = 97
        for word_tuple in iproduct(range(3), repeat=k):
            word = list(word_tuple)
            t = tuple(berggren_word_triple(word))
            triples_z.add(t)
            triples_mod.add(berggren_hash(word, p))
        distinct_triples_int.append(len(triples_z))
        distinct_triples_mod.append(len(triples_mod))

    ax.plot(lengths, total_words, 'k-^', label='Total words (3^k)', markersize=6)
    ax.plot(lengths, distinct_triples_int, 'b-o', label='Distinct triples (ℤ)',
            markersize=6)
    ax.plot(lengths, distinct_triples_mod, 'r-s', label=f'Distinct hashes (mod {p})',
            markersize=6)
    ax.set_xlabel("Word length k")
    ax.set_ylabel("Count")
    ax.set_yscale('log')
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('diagram.svg', format='svg', bbox_inches='tight')
    plt.savefig('berggren_crypto_demo.png', dpi=150, bbox_inches='tight')
    print("  Saved diagram.svg and berggren_crypto_demo.png")


