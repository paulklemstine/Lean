"""Degree monoids of transition systems: numerical demonstrations.

This self-contained script illustrates, by direct computation, the results of
the accompanying paper:

    D(R, a) = { n : a returns to a in exactly n R-steps }

* D(R, a) is an additive submonoid of N (0 in D, closed under +).
* Realisation: the chain machine of a set S of loop lengths has degree monoid
  exactly <S>, the submonoid generated by S.
* Product law: synchronous products intersect degree monoids;
  periods take least common multiples.
* Rescaling law: the k-step machine has degree monoid { n : k*n in D }.
* Determinism: a deterministic machine has D = d*N -- no gaps; hence a gap
  certifies nondeterminism, and <2,3> is unrealisable deterministically.
* Frobenius / Sylvester: the two-loop machine of coprime p, q > 1 has largest
  gap p*q - p - q and exactly (p-1)(q-1)/2 gaps in total.

Run with:  python3 demo.py
No third-party dependencies.
"""

from __future__ import annotations

from itertools import product
from math import gcd
from typing import Dict, Iterable, List, Sequence, Set, Tuple

State = int
Relation = Dict[State, Set[State]]  # successor sets


# --------------------------------------------------------------------------
# Core: exact-length reachability and the degree monoid
# --------------------------------------------------------------------------
def step_set(rel: Relation, current: Set[State]) -> Set[State]:
    """One synchronous step of the subset construction."""
    out: Set[State] = set()
    for s in current:
        out |= rel.get(s, set())
    return out


def degree_spectrum(rel: Relation, base: State, horizon: int) -> List[int]:
    """Return the sorted list of n <= horizon with base -->^n base.

    Complexity: O(horizon * |states| * out-degree) via the subset construction.
    """
    lengths: List[int] = []
    frontier: Set[State] = {base}
    for n in range(horizon + 1):
        if base in frontier:
            lengths.append(n)
        frontier = step_set(rel, frontier)
        if not frontier:
            break
    return lengths


def is_submonoid_prefix(lengths: Sequence[int], horizon: int) -> bool:
    """Check 0 in D and closure under addition, as far as the horizon allows."""
    members = set(lengths)
    if 0 not in members:
        return False
    for m, n in product(lengths, repeat=2):
        if m + n <= horizon and (m + n) not in members:
            return False
    return True


def period(lengths: Iterable[int]) -> int:
    """gcd of the closed-computation lengths (0 for the dead state)."""
    d = 0
    for n in lengths:
        d = gcd(d, n)
    return d


def gaps(lengths: Sequence[int], horizon: int) -> List[int]:
    """Multiples of the period, up to the horizon, that are not realised."""
    d = period(lengths)
    members = set(lengths)
    if d == 0:
        return []
    return [m for m in range(0, horizon + 1, d) if m not in members]


# --------------------------------------------------------------------------
# Machine constructions
# --------------------------------------------------------------------------
def chain_machine(generators: Sequence[int], top: int | None = None) -> Relation:
    """The chain machine of a set S of loop lengths.

    States 0..B where B = max(S) (or `top`). A positive state i steps to i-1;
    the base 0 may jump to s-1 for each nonzero s in S. Jump-then-descend is a
    closed computation at 0 of length exactly s.
    """
    pos = [s for s in generators if s > 0]
    bound = top if top is not None else (max(pos) if pos else 0)
    rel: Relation = {i: set() for i in range(bound + 1)}
    for i in range(1, bound + 1):
        rel[i].add(i - 1)
    for s in pos:
        rel[0].add(s - 1)
    return rel


def cycle_machine(n: int) -> Relation:
    """A single deterministic cycle of length n >= 1."""
    return {i: {(i + 1) % n} for i in range(n)}


def synchronous_product(r1: Relation, r2: Relation) -> Tuple[Relation, Dict[Tuple[int, int], int]]:
    """Synchronous product; returns the relation and the state encoding."""
    states = [(a, b) for a in r1 for b in r2]
    code = {p: i for i, p in enumerate(states)}
    rel: Relation = {code[p]: set() for p in states}
    for (a, b) in states:
        for a2 in r1.get(a, set()):
            for b2 in r2.get(b, set()):
                rel[code[(a, b)]].add(code[(a2, b2)])
    return rel, code


def rescale(rel: Relation, k: int) -> Relation:
    """The k-step machine: one new tick = k old steps."""
    out: Relation = {}
    for s in rel:
        frontier: Set[State] = {s}
        for _ in range(k):
            frontier = step_set(rel, frontier)
        out[s] = frontier
    return out


def is_deterministic(rel: Relation) -> bool:
    return all(len(succ) <= 1 for succ in rel.values())


# --------------------------------------------------------------------------
# Numerical semigroup utilities
# --------------------------------------------------------------------------
def in_two_generator_semigroup(p: int, q: int, n: int) -> bool:
    """Residue criterion: with b = q^{-1} n mod p, membership iff b*q <= n."""
    b = (pow(q, -1, p) * n) % p
    return b * q <= n


def frobenius_number(p: int, q: int) -> int:
    return p * q - p - q


def sylvester_gap_count(p: int, q: int) -> int:
    return (p - 1) * (q - 1) // 2


def brute_force_gaps(p: int, q: int) -> List[int]:
    limit = frobenius_number(p, q) + 1
    return [n for n in range(limit + 1) if not in_two_generator_semigroup(p, q, n)]


# --------------------------------------------------------------------------
# Demonstrations
# --------------------------------------------------------------------------
def banner(title: str) -> None:
    print("\n" + "=" * 74)
    print(title)
    print("=" * 74)


def demo_monoid_law(horizon: int = 40) -> None:
    banner("1. The degree monoid is an additive submonoid of N")
    catalogue = {
        "dead state (no transitions)": {0: set()},
        "self-loop": {0: {0}},
        "4-cycle": cycle_machine(4),
        "two loops of lengths 2 and 3": chain_machine([2, 3]),
        "three loops of lengths 4, 6, 9": chain_machine([4, 6, 9]),
    }
    for name, rel in catalogue.items():
        spec = degree_spectrum(rel, 0, horizon)
        print(f"{name:32s} D = {spec[:12]}{' ...' if len(spec) > 12 else ''}")
        assert is_submonoid_prefix(spec, horizon), name
        print(f"{'':32s} period = {period(spec)}, gaps = {gaps(spec, horizon)}")
    print("\nAll listed spectra contain 0 and are closed under addition.")


def demo_realisation(horizon: int = 60) -> None:
    banner("2. Realisation: the chain machine of S realises <S>")

    def generated_prefix(gens: Sequence[int], horizon: int) -> List[int]:
        reachable = [False] * (horizon + 1)
        reachable[0] = True
        for n in range(horizon + 1):
            if reachable[n]:
                for g in gens:
                    if g > 0 and n + g <= horizon:
                        reachable[n + g] = True
        return [n for n in range(horizon + 1) if reachable[n]]

    for gens in ([], [1], [5], [2, 3], [3, 5], [4, 6, 9], [6, 10, 15]):
        rel = chain_machine(gens)
        observed = degree_spectrum(rel, 0, horizon)
        expected = generated_prefix(gens, horizon)
        ok = observed == expected
        print(f"S = {str(gens):14s} states = {len(rel):3d}  matches <S>: {ok}")
        assert ok
        print(f"{'':17s}D = {observed[:14]}{' ...' if len(observed) > 14 else ''}")


def demo_products(horizon: int = 80) -> None:
    banner("3. Product law: intersection of monoids, lcm of periods")
    for m, n in ((4, 6), (3, 5), (6, 10), (2, 3)):
        r1, r2 = cycle_machine(m), cycle_machine(n)
        prod, code = synchronous_product(r1, r2)
        spec_prod = degree_spectrum(prod, code[(0, 0)], horizon)
        s1 = set(degree_spectrum(r1, 0, horizon))
        s2 = set(degree_spectrum(r2, 0, horizon))
        inter = sorted(s1 & s2)
        L = m * n // gcd(m, n)
        print(f"cycles {m} x {n}: D(product) = {spec_prod[:8]}"
              f"  intersection = {inter[:8]}  lcm = {L}  period = {period(spec_prod)}")
        assert spec_prod == inter
        assert period(spec_prod) == L


def demo_rescaling(horizon: int = 40) -> None:
    banner("4. Rescaling law: D(R^[k], a) = { n : k*n in D(R,a) }")
    for gens, k in (([2, 3], 2), ([3, 5], 3), ([6], 2), ([4, 6, 9], 2)):
        rel = chain_machine(gens)
        base_spec = set(degree_spectrum(rel, 0, k * horizon))
        fast = rescale(rel, k)
        observed = degree_spectrum(fast, 0, horizon)
        expected = [n for n in range(horizon + 1) if k * n in base_spec]
        print(f"S = {str(gens):12s} k = {k}:  D = {observed[:10]}   predicted = {expected[:10]}")
        assert observed == expected
        print(f"{'':20s} gaps before rescaling: {gaps(sorted(base_spec), 20)}, "
              f"after: {gaps(observed, 20)}")


def demo_determinism(horizon: int = 60) -> None:
    banner("5. Determinism <=> gaplessness")
    examples = {
        "5-cycle (deterministic)": cycle_machine(5),
        "chain machine of {6} (deterministic loop)": chain_machine([6]),
        "two loops 2,3 (nondeterministic)": chain_machine([2, 3]),
        "two loops 3,5 (nondeterministic)": chain_machine([3, 5]),
    }
    for name, rel in examples.items():
        spec = degree_spectrum(rel, 0, horizon)
        d = period(spec)
        g = gaps(spec, horizon)
        det = is_deterministic(rel)
        print(f"{name:44s} deterministic = {str(det):5s} period = {d}  gaps = {g}")
        if det:
            assert g == [], "a deterministic machine must be gapless"
        if g:
            assert not det, "a gap certifies nondeterminism"
    print("\nSeparation: <2,3> = {0,2,3,4,...} has the gap 1 at period 1,")
    print("so no deterministic machine on any state space realises it.")


def demo_frobenius_sylvester() -> None:
    banner("6. Frobenius number and Sylvester's gap count")
    print(f"{'(p,q)':>10} {'F = pq-p-q':>12} {'#gaps':>8} {'(p-1)(q-1)/2':>14}   gaps")
    for p, q in ((2, 3), (3, 5), (4, 7), (5, 7), (7, 11), (5, 12)):
        if gcd(p, q) != 1:
            continue
        g = brute_force_gaps(p, q)
        F = frobenius_number(p, q)
        assert max(g) == F
        assert len(g) == sylvester_gap_count(p, q)
        shown = g if len(g) <= 10 else g[:10] + ["..."]
        print(f"{str((p, q)):>10} {F:>12} {len(g):>8} {sylvester_gap_count(p, q):>14}   {shown}")

    print("\nSymmetry check: for 0 <= n <= F exactly one of n, F-n is realisable.")
    for p, q in ((3, 5), (5, 7), (7, 11)):
        F = frobenius_number(p, q)
        ok = all(in_two_generator_semigroup(p, q, n)
                 != in_two_generator_semigroup(p, q, F - n) for n in range(F + 1))
        print(f"  (p,q) = ({p},{q}), F = {F}: involution n -> F-n swaps gaps and non-gaps: {ok}")
        assert ok


def demo_machine_vs_criterion(horizon: int = 80) -> None:
    banner("7. Machine simulation agrees with the residue criterion")
    for p, q in ((2, 3), (3, 5), (5, 7)):
        rel = chain_machine([p, q])
        spec = set(degree_spectrum(rel, 0, horizon))
        predicted = {n for n in range(horizon + 1) if in_two_generator_semigroup(p, q, n)}
        print(f"(p,q) = ({p},{q}): simulated spectrum equals residue criterion: {spec == predicted}")
        assert spec == predicted


def demo_finite_state_bound() -> None:
    banner("8. Finite-state realisation and the deterministic period bound")
    for gens in ([2, 3], [3, 5], [4, 6, 9], [5, 12]):
        rel = chain_machine(gens)
        print(f"S = {str(gens):12s} realised by a machine with {len(rel)} states "
              f"(max generator + 1 = {max(gens) + 1})")
        assert len(rel) == max(gens) + 1
    print("\nDeterministic machines on N states have period <= N:")
    for n in (3, 5, 8):
        rel = cycle_machine(n)
        spec = degree_spectrum(rel, 0, 3 * n)
        print(f"  {n}-cycle: states = {len(rel)}, period = {period(spec)} <= {len(rel)}")
        assert period(spec) <= len(rel)


def main() -> None:
    demo_monoid_law()
    demo_realisation()
    demo_products()
    demo_rescaling()
    demo_determinism()
    demo_frobenius_sylvester()
    demo_machine_vs_criterion()
    demo_finite_state_bound()
    print("\nAll demonstrations completed successfully.")


if __name__ == "__main__":
    main()
