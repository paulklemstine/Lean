"""
Chain Invariants Demo: Divisibility Chains and the Anti-Escher Property

Demonstrates the three key results:
1. Exponential growth in strict divisibility chains
2. BigOmega (Ω) as chain rank
3. The Anti-Escher property for ℤ
"""

from math import log2
from collections import Counter
from typing import List, Tuple


def prime_factorization(n: int) -> List[int]:
    """Return the list of prime factors with multiplicity."""
    if n <= 1:
        return []
    factors = []
    d = 2
    while d * d <= n:
        while n % d == 0:
            factors.append(d)
            n //= d
        d += 1
    if n > 1:
        factors.append(n)
    return factors


def big_omega(n: int) -> int:
    """Ω(n) = number of prime factors with multiplicity."""
    return len(prime_factorization(n))


def divisors(n: int) -> List[int]:
    """Return all divisors of n in sorted order."""
    divs = []
    for i in range(1, int(n**0.5) + 1):
        if n % i == 0:
            divs.append(i)
            if i != n // i:
                divs.append(n // i)
    return sorted(divs)


def find_all_maximal_chains(n: int) -> List[List[int]]:
    """Find all divisibility chains from 1 to n of maximal length Ω(n)."""
    target_len = big_omega(n) + 1  # +1 because chain includes both endpoints
    
    def dfs(current: int, chain: List[int]) -> List[List[int]]:
        if current == n:
            if len(chain) == target_len:
                return [chain[:]]
            return []
        if len(chain) >= target_len:
            return []
        results = []
        for d in divisors(n):
            if d > current and current != d and d % current == 0 and d <= n:
                # d must be a multiple of current
                if d != current:
                    chain.append(d)
                    results.extend(dfs(d, chain))
                    chain.pop()
        return results
    
    return dfs(1, [1])


def chain_spectrum(chain: List[int]) -> List[int]:
    """Compute the spectrum (quotient sizes) of a divisibility chain."""
    return [chain[i+1] // chain[i] for i in range(len(chain) - 1)]


