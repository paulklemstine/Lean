def verify_anti_escher():
    """Demonstrate the Anti-Escher property for ℤ."""
    print("=" * 60)
    print("THEOREM 3: Anti-Escher Property for ℤ")
    print("=" * 60)
    print()
    print("Every strictly descending chain of nonzero principal ideals in ℤ")
    print("has trivial (zero) intersection.")
    print()
    
    # Example: chain generated by 2, 4, 8, 16, ...
    print("  Example 1: Chain (2) ⊃ (4) ⊃ (8) ⊃ (16) ⊃ ...")
    print("  Generators grow exponentially: |aₙ| = 2^(n+1)")
    print("  For any nonzero x, eventually |aₙ| > |x|, so aₙ ∤ x.")
    print("  ⟹ Intersection = {0}  ✓")
    print()
    
    # Example: chain generated by 6, 12, 60, 420, ...
    chain = [6]
    for _ in range(7):
        # Each step: multiply by smallest prime not already a factor, or by 2
        last = chain[-1]
        for p in [2, 3, 5, 7, 11, 13, 17]:
            candidate = last * p
            if candidate != last:
                chain.append(candidate)
                break
    
    print(f"  Example 2: Chain {' → '.join(str(c) for c in chain[:6])} → ...")
    print(f"  Generators: {chain[:6]}")
    print(f"  Growth ratios: {[chain[i+1]//chain[i] for i in range(min(5, len(chain)-1))]}")
    
    # Check intersection
    test_values = [1, 2, 3, 6, 12, 100, 1000]
    print(f"  Testing divisibility of various x:")
    for x in test_values:
        max_divides = 0
        for i, a in enumerate(chain):
            if x % a == 0:
                max_divides = i
            else:
                break
        print(f"    x = {x:>4}: divisible by first {max_divides + 1} generators, "
              f"fails at a[{max_divides + 1}] = {chain[max_divides + 1] if max_divides + 1 < len(chain) else '...'}")
    
    print()
    print("  Key insight: |aₙ| ≥ 2ⁿ · |a₀| → ∞, so no nonzero x survives.")


def spectrum_sum_conjecture_test():
    """Test the spectrum sum minimality conjecture for small n."""
    print()
    print("=" * 60)
    print("CONJECTURE: Spectrum Sum Minimality")
    print("=" * 60)
    print()
    print("For any maximal-length chain from 1 to n, the spectrum sum ≥ sopfr(n).")
    print()
    
    results = []
    for n in range(2, 101):
        factors = prime_factorization(n)
        sopfr = sum(factors)
        chains = find_all_maximal_chains(n)
        
        if chains:
            sums = [sum(chain_spectrum(c)) for c in chains]
            min_sum = min(sums)
            max_sum = max(sums)
            holds = min_sum >= sopfr
            results.append((n, sopfr, min_sum, max_sum, len(chains), holds))
            
            if not holds:
                print(f"  ✗ COUNTEREXAMPLE at n = {n}: sopfr = {sopfr}, min_sum = {min_sum}")
    
    if all(r[5] for r in results):
        print(f"  Conjecture holds for all n in [2, 100]  ✓")
        print()
        # Show interesting cases
        print("  Interesting cases (where spectrum sum varies):")
        for n, sopfr, min_s, max_s, count, _ in results:
            if min_s != max_s:
                print(f"    n = {n:>3}: sopfr = {sopfr:>3}, "
                      f"spectrum sums in [{min_s}, {max_s}], "
                      f"{count} maximal chains")


