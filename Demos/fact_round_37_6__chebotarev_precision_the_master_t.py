def section_controls(groups: dict[str, list[Perm]]) -> None:
    print("\n" + "=" * 72)
    print("6. CONTROLS: thickening, coprime flatness, simultaneous measurement")
    print("=" * 72)
    s3, d4 = groups["S3"], groups["D4"]
    c3, c4 = coset_readout(s3), coset_readout(d4)
    thick = [(g, j) for g in s3 for j in range(17)]
    print(f"  thickening S3 x 17 copies: change in channel = "
          f"{channel(thick, lambda w: c3(w[0]), lambda w: split_readout(w[0])) - law(s3):+.2e}")
    joint = [(a, b) for a in s3 for b in d4]
    print(f"  joint population S3 x D4 ({len(joint)} Frobenius pairs):")
    print(f"    I(cosetA; typeA) = {channel(joint, lambda w: c3(w[0]), lambda w: split_readout(w[0])):.6f}")
    print(f"    I(cosetB; typeB) = {channel(joint, lambda w: c4(w[1]), lambda w: split_readout(w[1])):.6f}")
    print(f"    I(cosetA; typeB) = {channel(joint, lambda w: c3(w[0]), lambda w: split_readout(w[1])):+.2e}")
    print(f"    I(cosetB; typeA) = {channel(joint, lambda w: c4(w[1]), lambda w: split_readout(w[0])):+.2e}")


