# 7. Real primes for x^3 - x - 1
# ---------------------------------------------------------------------------


def primes_below(n: int) -> list[int]:
    sieve = bytearray([1]) * n
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(n**0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = bytearray(len(sieve[i * i::i]))
    return [i for i in range(n) if sieve[i]]


def root_count(p: int) -> int:
    """Number of roots of x^3 - x - 1 modulo p."""
    return sum(1 for x in range(p) if (x * x * x - x - 1) % p == 0)


def section_real_primes() -> None:
    print("\n" + "=" * 72)
    print("7. REAL PRIMES: x^3 - x - 1 (discriminant -23, Galois group S3)")
    print("=" * 72)
    ps = [p for p in primes_below(20000) if p != 23]
    squares = {(x * x) % 23 for x in range(1, 23)}
    rc = {p: root_count(p) for p in ps}
    shapes_ok = all(rc[p] in (0, 1, 3) for p in ps)
    dict_ok = all((rc[p] == 1) == (p % 23 not in squares) for p in ps)
    print(f"  {len(ps)} unramified primes < 20000: shapes in {{0,1,3}} roots: {shapes_ok};"
          f" '1 root <=> non-residue mod 23': {dict_ok}")
    print(f"  root counts 2,5,59 -> {rc[2]}, {rc[5]}, {rc[59]}  (inert, 1+2, split)")
    sample = [2, 5, 59]
    v = mutual_info([p % 23 for p in sample], [rc[p] for p in sample])
    print(f"  three-prime sample: plug-in I = {v:.6f} = log2 3 = {log2(3):.6f}  > law 1  > 1.0078")
    print("  plug-in channel of the 22-class dial (p mod 23) on the first n primes:")
    for n in (10, 30, 100, 300, 1000, len(ps)):
        sub = ps[:n]
        val = mutual_info([p % 23 for p in sub], [rc[p] for p in sub])
        print(f"    n = {n:5d}:  I_hat = {val:.4f}   (law 1.0000)")


# ---------------------------------------------------------------------------
# 8. Plug-in bias in the Chebotarev model
# ---------------------------------------------------------------------------


def section_bias(groups: dict[str, list[Perm]], seed: int = 20260821) -> None:
    print("\n" + "=" * 72)
    print("8. PLUG-IN BIAS: the law is dial-independent, the estimator is not")
    print("=" * 72)
    rng = random.Random(seed)
    s3 = groups["S3"]
    c = coset_readout(s3)
    pops = {}
    for q in (23, 229):
        pops[q] = fibre_product(s3, list(range(1, q)), c, legendre_dial(q, c, s3))
    trials = 40
    print(f"  mean plug-in I over {trials} samples of n iid Chebotarev pairs (law = 1 bit for both dials)")
    for n in (1000, 10000, 100000):
        row = []
        for q in (23, 229):
            pop = pops[q]
            tot = 0.0
            for _ in range(trials):
                smp = [rng.choice(pop) for _ in range(n)]
                tot += mutual_info([w[1] for w in smp], [split_readout(w[0]) for w in smp])
            mean = tot / trials
            # first-order (Miller-Madow style) prediction: effective-cell count
            K = q - 1
            cells = len({(w[1], split_readout(w[0])) for w in pop})
            pred = (cells - K - 3 + 1) / (2 * n * 0.6931471805599453)
            row.append(f"{K:3d} classes: bias {mean-1:+.5f} (pred {pred:+.5f})")
        print(f"    n = {n:6d}:  " + " | ".join(row))


def main() -> None:
    groups = build_groups()
    section_master_table(groups)
    section_catches(groups)
    section_fine_dial(groups)
    section_controls(groups)
    section_real_primes()
    section_bias(groups)


if __name__ == "__main__":
    main()
