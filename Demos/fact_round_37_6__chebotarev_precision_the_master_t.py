#!/usr/bin/env python3
"""
Chebotarev precision: numerical companion.

Everything is computed from scratch (explicit permutation groups, explicit
primes); no external packages beyond the Python standard library are needed.

Sections
  1. Entropy / mutual information on finite populations.
  2. Permutation groups: closure, derived subgroup, coset and type readouts.
  3. The master table of type-channel laws, recomputed from explicit groups,
     with the rigorous log2(3) enclosure and the six-decimal check.
  4. The two "catches": the D4 generator closing to S4, and F20 seeded as C5.
  5. The fine-dial reduction theorem on fibre-product populations
     (22-class and 228-class dials over S3, a dial over D4, coprime padding).
  6. Thickening invariance, coprime flatness, simultaneous measurement.
  7. Real primes: x^3 - x - 1, its mod-23 Artin dial, the class-field dictionary,
     the three-prime overshoot to log2(3), and convergence of the plug-in channel.
  8. Plug-in bias on Chebotarev-model samples: the bias depends on the dial,
     the law does not.
"""
from __future__ import annotations

import random
from collections import Counter
from math import log2
from typing import Callable, Hashable, Iterable, Sequence, TypeVar

T_ = TypeVar("T_")
Perm = tuple[int, ...]

# ---------------------------------------------------------------------------
# 1. Information on finite populations (uniform measure on a finite list)
# ---------------------------------------------------------------------------


def entropy(xs: Sequence[Hashable]) -> float:
    """Shannon entropy (bits) of the empirical law of xs."""
    n = len(xs)
    if n == 0:
        return 0.0
    return -sum((c / n) * log2(c / n) for c in Counter(xs).values())


def mutual_info(a: Sequence[Hashable], b: Sequence[Hashable]) -> float:
    """I(A;B) = H(A) + H(B) - H(A,B) in bits."""
    return entropy(a) + entropy(b) - entropy(list(zip(a, b)))


def channel(pop: Sequence[T_], f: Callable[[T_], Hashable], g: Callable[[T_], Hashable]) -> float:
    """Channel between two readouts of a population."""
    return mutual_info([f(w) for w in pop], [g(w) for w in pop])


# ---------------------------------------------------------------------------
# 2. Permutation groups
# ---------------------------------------------------------------------------


def compose(p: Perm, q: Perm) -> Perm:
    """(p*q)(i) = p(q(i))."""
    return tuple(p[q[i]] for i in range(len(p)))


def inverse(p: Perm) -> Perm:
    inv = [0] * len(p)
    for i, j in enumerate(p):
        inv[j] = i
    return tuple(inv)


def closure(gens: Iterable[Perm]) -> list[Perm]:
    """Subgroup generated by gens (breadth-first)."""
    gens = list(gens)
    n = len(gens[0])
    ident = tuple(range(n))
    seen = {ident}
    frontier = [ident]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = compose(g, x)
                if y not in seen:
                    seen.add(y)
                    new.append(y)
        frontier = new
    return sorted(seen)


def derived_subgroup(group: Sequence[Perm]) -> list[Perm]:
    comms = {compose(compose(a, b), compose(inverse(a), inverse(b))) for a in group for b in group}
    return closure(comms)


def coset_readout(group: Sequence[Perm]) -> Callable[[Perm], Hashable]:
    """g -> g G' (canonical label = smallest element of the coset)."""
    dsub = derived_subgroup(group)
    label = {g: min(compose(g, h) for h in dsub) for g in group}
    return lambda g: label[g]


def cycle_type(p: Perm) -> tuple[int, ...]:
    seen: set[int] = set()
    cyc: list[int] = []
    for i in range(len(p)):
        if i in seen:
            continue
        j, length = i, 0
        while j not in seen:
            seen.add(j)
            j = p[j]
            length += 1
        cyc.append(length)
    return tuple(sorted(cyc))


def split_readout(p: Perm) -> tuple[int, int]:
    """Coarse splitting type: (#roots in F_p, #roots in F_{p^2} not in F_p)
    = (#fixed points, #points on 2-cycles)."""
    ct = cycle_type(p)
    return (ct.count(1), 2 * ct.count(2))


def cyc(n: int, *cycles: Sequence[int]) -> Perm:
    """Permutation of {0..n-1} from disjoint cycles."""
    p = list(range(n))
    for c in cycles:
        for k in range(len(c)):
            p[c[k]] = c[(k + 1) % len(c)]
    return tuple(p)


def law(group: Sequence[Perm], typ: Callable[[Perm], Hashable] = split_readout) -> float:
    """Type-channel law value I(coset ; type) under the uniform (Chebotarev) law."""
    c = coset_readout(group)
    return channel(group, c, typ)


def build_groups() -> dict[str, list[Perm]]:
    aff = [tuple((a * x + b) % 5 for x in range(5)) for a in range(1, 5) for b in range(5)]
    return {
        "S3": closure([cyc(3, (0, 1, 2)), cyc(3, (0, 1))]),
        "S4": closure([cyc(4, (0, 1, 2, 3)), cyc(4, (0, 1))]),
        "A4": closure([cyc(4, (0, 1, 2)), cyc(4, (0, 1), (2, 3))]),
        "D4": closure([cyc(4, (0, 1, 2, 3)), cyc(4, (0, 2))]),
        "V4": closure([cyc(4, (0, 1), (2, 3)), cyc(4, (0, 2), (1, 3))]),
        "C4": closure([cyc(4, (0, 1, 2, 3))]),
        "C5": closure([cyc(5, (0, 1, 2, 3, 4))]),
        "D6": closure([cyc(6, (0, 1, 2, 3, 4, 5)), cyc(6, (1, 5), (2, 4))]),
        "S3reg": closure([cyc(6, (0, 1, 2), (3, 4, 5)), cyc(6, (0, 3), (1, 5), (2, 4))]),
        "F20": sorted(set(aff)),
    }


# ---------------------------------------------------------------------------
# 3. The master table
# ---------------------------------------------------------------------------

RECORDED: list[tuple[str, str, float]] = [
    ("S3", "split", 1.0),
    ("S4", "split", 1.0),
    ("A4", "split", 0.918296),
    ("D4", "split", 1.655639),
    ("V4", "split", 0.811278),
    ("C4", "split", 1.5),
    ("D6", "cycle", 1.729574),
    ("D6", "split", 1.396241),
    ("S3reg", "cycle", 1.0),
    ("F20", "split", 1.5),
]


def section_master_table(groups: dict[str, list[Perm]]) -> None:
    print("=" * 72)
    print("3. MASTER TABLE: law values recomputed from explicit permutation groups")
    print("=" * 72)
    # rigorous enclosure of log2 3 from two integer inequalities
    lo_ok = 2**1054 < 3**665
    hi_ok = 3**2301 < 2**3647
    print(f"  2^1054 < 3^665 : {lo_ok}    3^2301 < 2^3647 : {hi_ok}")
    print(f"  => {1054/665:.9f} < log2 3 < {3647/2301:.9f}  (width {3647/2301-1054/665:.2e})")
    worst = 0.0
    print(f"  {'group':6s} {'|G|':>4s} {'[G:Gp]':>6s} {'readout':7s} {'law (fresh)':>12s} {'recorded':>9s} {'|dev|':>9s}")
    for name, kind, rec in RECORDED:
        g = groups[name]
        typ = split_readout if kind == "split" else cycle_type
        val = law(g, typ)
        idx = len(g) // len(derived_subgroup(g))
        dev = abs(val - rec)
        worst = max(worst, dev)
        print(f"  {name:6s} {len(g):4d} {idx:6d} {kind:7s} {val:12.6f} {rec:9.6f} {dev:9.1e}")
    print(f"  max deviation fresh vs recorded constants: {worst:.1e}  (< 5e-7: {worst < 5e-7})")
    print(f"  closed forms: A4 = log2 3 - 2/3 = {log2(3)-2/3:.6f},  D4 = 9/4 - (3/8)log2 3 = {9/4-3/8*log2(3):.6f}")
    print(f"  C5 law = log2 5 - 8/5 = {law(groups['C5']):.6f}")
    f20 = law(groups["F20"])
    c4 = law(groups["C4"])
    print(f"  LAW COLLISION: F20 (order 20, nonabelian) = {f20:.6f} = C4 (order 4) = {c4:.6f}")
    print(f"  F20 loss = log2[G:G'] - I = {2 - f20:.6f} bit (the two order-4 cosets look alike)")


