def section_catches(groups: dict[str, list[Perm]]) -> None:
    print("\n" + "=" * 72)
    print("4. THE CATCHES (errors exposed by hand-derived constants)")
    print("=" * 72)
    four = cyc(4, (0, 1, 2, 3))
    wrong = closure([four, cyc(4, (0, 1))])
    right = closure([four, cyc(4, (0, 2))])
    print(f"  <4-cycle, (0 1)> has order {len(wrong)}  -> law {law(wrong):.6f}  (that is S4!)")
    print(f"  <4-cycle, (0 2)> has order {len(right)}   -> law {law(right):.6f}  (true D4)")
    print(f"  gap = {law(right)-law(wrong):.6f} bit > 1/2  (50x the 0.01 budget)")
    c5, f20 = law(groups["C5"]), law(groups["F20"])
    print(f"  F20 seeded as C5: C5 law {c5:.6f} vs F20 law {f20:.6f}; gap {f20-c5:.6f} > 3/4 bit")


# ---------------------------------------------------------------------------
# 5. Fine-dial reduction
# ---------------------------------------------------------------------------


def fibre_product(group: Sequence[Perm], residues: Sequence[Hashable],
                  c: Callable[[Perm], Hashable], phi: Callable[[Hashable], Hashable]) -> list[tuple[Perm, Hashable]]:
    """Chebotarev / class-field population {(g, r) : c(g) = phi(r)}."""
    return [(g, r) for g in group for r in residues if c(g) == phi(r)]


def is_uniform_dial(group: Sequence[Perm], residues: Sequence[Hashable],
                    c: Callable[[Perm], Hashable], phi: Callable[[Hashable], Hashable]) -> bool:
    sizes = {k: sum(1 for r in residues if phi(r) == k) for k in {c(g) for g in group}}
    return len(set(sizes.values())) == 1 and min(sizes.values()) > 0


def legendre_dial(q: int, sign: Callable[[Perm], Hashable], group: Sequence[Perm]) -> Callable[[int], Hashable]:
    """Map a nonzero residue mod q to the S3 coset: squares -> even coset, non-squares -> odd coset."""
    squares = {(x * x) % q for x in range(1, q)}
    even = sign(tuple(range(len(group[0]))))
    odd = next(sign(g) for g in group if sign(g) != even)
    return lambda r: even if r in squares else odd


def section_fine_dial(groups: dict[str, list[Perm]]) -> None:
    print("\n" + "=" * 72)
    print("5. FINE-DIAL REDUCTION: I(residue ; type) = I(coset ; type) for every uniform dial")
    print("=" * 72)
    s3 = groups["S3"]
    c = coset_readout(s3)
    target = channel(s3, c, split_readout)
    for q in (23, 229):
        res = list(range(1, q))
        phi = legendre_dial(q, c, s3)
        pop = fibre_product(s3, res, c, phi)
        val = channel(pop, lambda w: w[1], lambda w: split_readout(w[0]))
        print(f"  S3, {q-1:3d}-class dial mod {q:3d}: uniform={is_uniform_dial(s3, res, c, phi)}, "
              f"|pop|={len(pop):4d}, I(r;T) = {val:.12f}  vs coset law {target:.12f}")
    # D4 with a dial of 4*7 = 28 classes, residues labelled (coset, j)
    d4 = groups["D4"]
    cd = coset_readout(d4)
    cosets = sorted({cd(g) for g in d4})
    res = [(k, j) for k in range(len(cosets)) for j in range(7)]
    phi = lambda r: cosets[r[0]]
    pop = fibre_product(d4, res, cd, phi)
    val = channel(pop, lambda w: w[1], lambda w: split_readout(w[0]))
    print(f"  D4, 28-class dial: I(r;T) = {val:.12f}  vs coset law {law(d4):.12f}")
    # coprime padding: append an independent residue q in Z/5
    res2 = [(r, q) for r in res for q in range(5)]
    pop2 = fibre_product(d4, res2, cd, lambda x: phi(x[0]))
    val2 = channel(pop2, lambda w: w[1], lambda w: split_readout(w[0]))
    print(f"  D4, dial padded by a coprime residue (140 classes): I = {val2:.12f}  (adds nothing)")
    cap = log2(len(cosets))
    print(f"  cap log2[G:G'] = {cap:.6f} >= law {law(d4):.6f}")


