def _charpoly_small(M, q):
    """Characteristic polynomial for small matrices."""
    n = M.shape[0]; M = M.astype(int) % q
    if n == 0: return np.array([1])
    elif n == 1: return np.array([(-M[0,0]) % q, 1])
    elif n == 2:
        tr = int(np.trace(M)) % q
        det = int(M[0,0]*M[1,1] - M[0,1]*M[1,0]) % q
        return np.array([det, (-tr) % q, 1])
    elif n == 3:
        a,b,c = M[0]; d,e,f = M[1]; g,h,k = M[2]
        tr = (a+e+k) % q
        cs = (a*e - b*d + a*k - c*g + e*k - f*h) % q
        det = (a*(e*k-f*h) - b*(d*k-f*g) + c*(d*h-e*g)) % q
        return np.array([(-det)%q, cs%q, (-tr)%q, 1]) % q
    return np.array([1])  # fallback


def is_irreducible_mod(poly, q):
    """Test irreducibility over F_q."""
    n = len(poly) - 1
    if n <= 0: return False
    if n == 1: return True
    for x in range(q):
        val = sum(int(poly[i]) * pow(x, i, q) for i in range(n+1)) % q
        if val == 0: return False
    if n <= 3: return True
    return True  # simplified for demo


def random_invertible_matrix(n, q):
    """Random invertible matrix in GL(n, F_q)."""
    while True:
        M = np.random.randint(0, q, size=(n, n))
        if int(round(np.linalg.det(M))) % q != 0:
            return M % q


