def assess_prg_quality(g: np.ndarray, h: np.ndarray, q: int, 
                       num_steps: int = 100) -> dict:
    """Assess the quality of a matrix-group pseudorandom generator.
    
    A good PRG based on matrix groups requires that the generators
    produce rapid mixing in the Cayley graph. Certificate-complete
    pairs are necessary (though not sufficient) for this.
    
    The Cayley graph Cay(GL(n,q), {g,h,g⁻¹,h⁻¹}) has good expansion
    when ⟪g,h⟫ = GL(n,q), which our certificates help verify.
    """
    n = g.shape[0]
    
    # Check certificates
    cp_g = _charpoly_small(g, q)
    irr_g = is_irreducible_mod(cp_g, q)
    
    gh = (g @ h) % q
    cp_gh = _charpoly_small(gh, q)
    irr_gh = is_irreducible_mod(cp_gh, q)
    
    # Simulate random walk
    current = np.eye(n, dtype=int)
    visited_traces = set()
    
    for step in range(num_steps):
        if np.random.random() < 0.5:
            current = (current @ g) % q
        else:
            current = (current @ h) % q
        tr = int(np.trace(current)) % q
        visited_traces.add(tr)
    
    return {
        "certificate_passed": irr_g and irr_gh,
        "distinct_traces": len(visited_traces),
        "max_possible_traces": q,
        "trace_coverage": len(visited_traces) / q,
        "assessment": (
            "GOOD: High trace diversity suggests rapid mixing"
            if len(visited_traces) > q * 0.5 else
            "POOR: Low trace diversity suggests slow mixing"
        )
    }


