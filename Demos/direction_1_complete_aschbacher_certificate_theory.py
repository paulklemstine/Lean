def validate_matrix_group_key(g: np.ndarray, h: np.ndarray, q: int) -> dict:
    """Validate that a matrix group key pair generates a large subgroup.
    
    In matrix-group-based cryptographic protocols, the security relies on
    the group generated by the public generators being large. This function
    uses Aschbacher certificates to efficiently verify this property.
    
    Args:
        g, h: Generator matrices in GL(n, F_q)
        q: Field size (must be prime)
    
    Returns:
        Dictionary with validation results and security assessment.
    """
    n = g.shape[0]
    gh = (g @ h) % q
    
    cp_g = _charpoly_small(g, q)
    cp_h = _charpoly_small(h, q)
    cp_gh = _charpoly_small(gh, q)
    
    irr_g = is_irreducible_mod(cp_g, q)
    irr_h = is_irreducible_mod(cp_h, q)
    irr_gh = is_irreducible_mod(cp_gh, q)
    
    security_level = sum([irr_g, irr_h, irr_gh])
    
    return {
        "dimension": n,
        "field_size": q,
        "charpoly_g_irreducible": irr_g,
        "charpoly_h_irreducible": irr_h,
        "charpoly_gh_irreducible": irr_gh,
        "triple_irreducibility": irr_g and irr_h and irr_gh,
        "security_level": ["WEAK", "LOW", "MEDIUM", "HIGH"][security_level],
        "recommendation": (
            "ACCEPT: Generators certified to produce large subgroup"
            if security_level == 3 else
            f"REVIEW: Only {security_level}/3 irreducibility conditions met"
        )
    }


