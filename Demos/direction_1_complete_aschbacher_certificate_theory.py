def format_matrix(M, name="M"):
    """Pretty-print a matrix."""
    n = M.shape[0]
    lines = [f"{name} ="]
    for i in range(n):
        row = " ".join(f"{int(M[i,j]):3d}" for j in range(n))
        bracket = "⎡" if i == 0 else ("⎣" if i == n-1 else "⎢")
        bracket_r = "⎤" if i == 0 else ("⎦" if i == n-1 else "⎥")
        lines.append(f"  {bracket} {row} {bracket_r}")
    return "\n".join(lines)


def format_poly(coeffs, q):
    """Format a polynomial from its coefficients."""
    n = len(coeffs) - 1
    terms = []
    for i in range(n, -1, -1):
        c = int(coeffs[i]) % q
        if c == 0 and i < n:
            continue
        if i == n:
            if c == 1:
                terms.append(f"x^{i}" if i > 1 else ("x" if i == 1 else "1"))
            else:
                terms.append(f"{c}x^{i}" if i > 1 else (f"{c}x" if i == 1 else f"{c}"))
        elif i == 0:
            terms.append(f"{c}")
        elif i == 1:
            terms.append(f"{c}x" if c != 1 else "x")
        else:
            terms.append(f"{c}x^{i}" if c != 1 else f"x^{i}")
    return " + ".join(terms) if terms else "0"


