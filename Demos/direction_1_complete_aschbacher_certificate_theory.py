def detect_subgroup_confinement(g: np.ndarray, h: np.ndarray, q: int) -> dict:
    """Detect if a pair (g, h) is confined to a known maximal subgroup.
    
    Uses certificate failures to identify the specific Aschbacher class
    containing the generated subgroup.
    """
    n = g.shape[0]
    
    diagnostics = {}
    
    # Check C₁: reducible?
    cp_g = _charpoly_small(g, q)
    if not is_irreducible_mod(cp_g, q):
        # Find a root = eigenvalue
        for lam in range(q):
            val = sum(int(cp_g[i]) * pow(lam, i, q) for i in range(len(cp_g))) % q
            if val == 0:
                diagnostics["C1_eigenvalue"] = lam
                diagnostics["confined_to"] = "C₁ (reducible)"
                diagnostics["explanation"] = (
                    f"g has eigenvalue {lam} over F_{q}, "
                    f"so the eigenspace is a g-invariant subspace"
                )
                break
        return diagnostics
    
    # Check C₂: imprimitive?
    cp_h = _charpoly_small(h, q)
    cp_gh = _charpoly_small((g @ h) % q, q)
    
    irr_h = is_irreducible_mod(cp_h, q)
    irr_gh = is_irreducible_mod(cp_gh, q)
    
    if not (irr_h and irr_gh):
        diagnostics["confined_to"] = "Possibly C₂ (imprimitive) or other"
        if not irr_h:
            diagnostics["reason"] = "charpoly(h) is reducible"
        else:
            diagnostics["reason"] = "charpoly(g*h) is reducible"
        return diagnostics
    
    # Check C₃ and C₄ for composite dimensions
    if n > 1 and not all(n % d != 0 for d in range(2, n)):
        diagnostics["note"] = f"Dimension {n} is composite; C₃/C₄ checks needed"
    
    diagnostics["confined_to"] = "NONE DETECTED"
    diagnostics["certificates_passed"] = "C₁, C₂, C₃, C₄"
    return diagnostics


