def poly_mul_mod(p1, p2, q):
    result = np.convolve(p1.astype(np.int64), p2.astype(np.int64)) % q
    return result.astype(int)

def _charpoly_small(M, q):
    n = M.shape[0]
    M = M.astype(int) % q
    if n == 0:
        return np.array([1])
    elif n == 1:
        return np.array([(-M[0,0]) % q, 1])
    elif n == 2:
        tr = int(np.trace(M)) % q
        det = int(M[0,0]*M[1,1] - M[0,1]*M[1,0]) % q
        return np.array([det, (-tr) % q, 1])
    elif n == 3:
        a,b,c = M[0]; d,e,f = M[1]; g,h,k = M[2]
        tr = (a+e+k) % q
        cofactor_sum = (a*e - b*d + a*k - c*g + e*k - f*h) % q
        det = (a*(e*k - f*h) - b*(d*k - f*g) + c*(d*h - e*g)) % q
        return np.array([(-det) % q, cofactor_sum % q, (-tr) % q, 1]) % q
    elif n == 4:
        return _berkowitz_charpoly(M, q)
    else:
        return _berkowitz_charpoly(M, q)

def _berkowitz_charpoly(M, q):
    n = M.shape[0]
    M = M.astype(np.int64) % q
    if n == 0:
        return np.array([1])
    if n == 1:
        return np.array([(-M[0,0]) % q, 1])
    a = M[0,0]; r = M[0,1:]; c = M[1:,0]; B = M[1:,1:]
    m = n - 1
    S = np.zeros(n+1, dtype=np.int64)
    S[0] = 1; S[1] = (-a) % q
    power = np.eye(m, dtype=np.int64)
    for k in range(2, n+1):
        if k == 2:
            val = (r @ c) % q
        else:
            power = (power @ B) % q
            val = (r @ power @ c) % q
        S[k] = (-val) % q
    cpB = _berkowitz_charpoly(B, q)
    result = poly_mul_mod(S[:n+1], cpB, q)[:n+1]
    return result % q

def _poly_divmod(f, g, q):
    f = f.astype(np.int64).copy()
    g = g.astype(np.int64)
    n = len(f) - 1; m = len(g) - 1
    if n < m:
        return np.array([0]), f % q
    quotient = np.zeros(n - m + 1, dtype=np.int64)
    g_lead_inv = pow(int(g[m]), q - 2, q)
    for i in range(n, m - 1, -1):
        if i < len(f):
            coeff = (f[i] * g_lead_inv) % q
            quotient[i - m] = coeff
            for j in range(m + 1):
                f[i - m + j] = (f[i - m + j] - coeff * g[j]) % q
    return quotient % q, f[:m] % q

def _prime_divisors(n):
    divisors = []; d = 2; temp = n
    while d * d <= temp:
        if temp % d == 0:
            divisors.append(d)
            while temp % d == 0: temp //= d
        d += 1
    if temp > 1: divisors.append(temp)
    return divisors

def _poly_gcd(f, g, q):
    f = f.astype(np.int64) % q
    g = g.astype(np.int64) % q
    while len(f) > 1 and f[-1] % q == 0: f = f[:-1]
    while len(g) > 1 and g[-1] % q == 0: g = g[:-1]
    while len(g) > 1 or (len(g) == 1 and g[0] % q != 0):
        _, r = _poly_divmod(f, g, q)
        while len(r) > 1 and r[-1] % q == 0: r = r[:-1]
        f = g; g = r % q
    if len(g) == 1 and g[0] % q != 0: return np.array([1])
    return f

def is_irreducible_mod(poly, q):
    n = len(poly) - 1
    if n <= 0: return False
    if n == 1: return True
    for x in range(q):
        val = 0
        for i in range(n + 1):
            val = (val + int(poly[i]) * pow(x, i, q)) % q
        if val == 0:
            return False
    if n <= 3: return True
    # Rabin test for higher degrees
    def poly_powmod(base, exp, modpoly, q):
        result = np.array([1], dtype=np.int64)
        base = base.copy()
        while exp > 0:
            if exp % 2 == 1:
                result = poly_mul_mod(result, base, q)
                _, result = _poly_divmod(result, modpoly, q)
            base = poly_mul_mod(base, base, q)
            _, base = _poly_divmod(base, modpoly, q)
            exp //= 2
        return result % q
    x = np.array([0, 1], dtype=np.int64)
    xqn = x.copy()
    for _ in range(n):
        xqn = poly_powmod(xqn, q, poly, q)
    diff = np.zeros(max(len(xqn), 2), dtype=np.int64)
    diff[:len(xqn)] = xqn
    diff[1] = (diff[1] - 1) % q
    _, rem = _poly_divmod(diff, poly, q)
    if any(r % q != 0 for r in rem): return False
    primes = _prime_divisors(n)
    for p in primes:
        k = n // p
        xqk = x.copy()
        for _ in range(k):
            xqk = poly_powmod(xqk, q, poly, q)
        diff2 = np.zeros(max(len(xqk), 2), dtype=np.int64)
        diff2[:len(xqk)] = xqk
        diff2[1] = (diff2[1] - 1) % q
        g = _poly_gcd(diff2, poly, q)
        if len(g) > 1 or (len(g) == 1 and g[0] % q != 1): return False
    return True

def _is_prime(n):
    if n < 2: return False
    for d in range(2, int(n**0.5) + 1):
        if n % d == 0: return False
    return True

