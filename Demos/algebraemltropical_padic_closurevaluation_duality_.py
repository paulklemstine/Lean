# §5. Ultrametric Information Distance
# ============================================================

def ultrametric_dist(cl_op: ClosureOperator, v: ClosureCapacity,
                     s: FrozenSet, t: FrozenSet) -> float:
    """Ultrametric information distance: d(s,t) = cap(cl(s ∪ t))."""
    return v.cap(cl_op.cl(s | t))


def verify_ultrametric_triangle(cl_op: ClosureOperator, v: ClosureCapacity):
    """Verify the ultrametric triangle inequality."""
    ground = cl_op.ground
    violations = 0
    for s in powerset(ground):
        for t in powerset(ground):
            for u in powerset(ground):
                d_su = ultrametric_dist(cl_op, v, s, u)
                d_st = ultrametric_dist(cl_op, v, s, t)
                d_tu = ultrametric_dist(cl_op, v, t, u)
                if d_su > max(d_st, d_tu) + 1e-10:
                    violations += 1
    return violations


