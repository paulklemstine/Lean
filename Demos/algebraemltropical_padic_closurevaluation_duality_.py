# §3. Tropical Dominance
# ============================================================

def is_tropically_dominated(v: ClosureCapacity, x: int, X: FrozenSet) -> bool:
    """Check if x is tropically dominated by X: cap({x}) ≤ cap(X)."""
    return v.cap(frozenset({x})) <= v.cap(X) + 1e-10


def check_dependency_dominance(cl_op: ClosureOperator, v: ClosureCapacity):
    """Verify: x ∈ cl(X) ⟹ cap({x}) ≤ cap(X) for all x, X."""
    ground = cl_op.ground
    violations = 0
    confirmations = 0
    for X in powerset(ground):
        clX = cl_op.cl(X)
        for x in ground:
            if x in clX and x not in X:
                if is_tropically_dominated(v, x, X):
                    confirmations += 1
                else:
                    violations += 1
                    print(f"  VIOLATION: {x} ∈ cl({set(X)}) but cap({{{x}}}) > cap({set(X)})")
    return confirmations, violations


