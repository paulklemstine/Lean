from itertools import combinations
from typing import Callable, Dict, FrozenSet, List, Set, Tuple

# Type aliases
Element = int
FinSet = frozenset


def powerset(s: set) -> list:
    """Return all subsets of s."""
    elems = list(s)
    result = []
    for r in range(len(elems) + 1):
        for combo in combinations(elems, r):
            result.append(frozenset(combo))
    return result


# ============================================================
# §1. Closure Operators
# ============================================================

class ClosureOperator:
    """A closure operator on a finite ground set."""

    def __init__(self, ground: set, cl: Callable[[FrozenSet], FrozenSet]):
        self.ground = frozenset(ground)
        self._cl = cl
        self._verify_axioms()

    def cl(self, s: FrozenSet) -> FrozenSet:
        return self._cl(frozenset(s))

    def _verify_axioms(self):
        """Verify extensive, monotone, idempotent."""
        for s in powerset(self.ground):
            cls = self.cl(s)
            # Extensive
            assert s <= cls, f"Extensivity failed: {s} ⊄ cl({s}) = {cls}"
            # Idempotent
            assert self.cl(cls) == cls, f"Idempotency failed: cl(cl({s})) ≠ cl({s})"
        # Monotone (spot check)
        for s in powerset(self.ground):
            for t in powerset(self.ground):
                if s <= t:
                    assert self.cl(s) <= self.cl(t), \
                        f"Monotonicity failed: {s} ⊆ {t} but cl({s}) ⊄ cl({t})"

    def closed_sets(self) -> list:
        """Return all closed sets."""
        return [s for s in powerset(self.ground) if self.cl(s) == s]

    def is_closed(self, s: FrozenSet) -> bool:
        return self.cl(frozenset(s)) == frozenset(s)


# ============================================================
# §2. Closure Capacity
# ============================================================

class ClosureCapacity:
    """An ultrametric closure capacity."""

    def __init__(self, cl_op: ClosureOperator,
                 cap: Callable[[FrozenSet], float]):
        self.cl_op = cl_op
        self._cap = cap
        self._verify_axioms()

    def cap(self, s) -> float:
        return self._cap(frozenset(s))

    def _verify_axioms(self):
        ground = self.cl_op.ground
        # Normalized
        assert self.cap(frozenset()) == 0, "Normalization failed"
        # Closed invariant
        for s in powerset(ground):
            assert abs(self.cap(self.cl_op.cl(s)) - self.cap(s)) < 1e-10, \
                f"Closure invariance failed for {s}"
        # Monotone
        for s in powerset(ground):
            for t in powerset(ground):
                if s <= t:
                    assert self.cap(s) <= self.cap(t) + 1e-10, \
                        f"Monotonicity failed: cap({s})={self.cap(s)} > cap({t})={self.cap(t)}"
        # Ultrametric
        for s in powerset(ground):
            for t in powerset(ground):
                lhs = self.cap(self.cl_op.cl(s | t))
                rhs = max(self.cap(s), self.cap(t))
                assert lhs <= rhs + 1e-10, \
                    f"Ultrametric failed: cap(cl({s}∪{t}))={lhs} > max(cap({s}),cap({t}))={rhs}"


