def feature_selection_demo():
    """
    Feature selection via tropical dominance.

    Scenario: 6 features where some are derivable from others.
    Features 4 and 5 are redundant given features {0,1,2,3}.
    """
    print("\n" + "=" * 60)
    print("APPLICATION 2: Feature Selection via Tropical Dominance")
    print("=" * 60)

    features = set(range(6))

    # Feature dependency closure:
    # Feature 4 = f(feature 0, feature 1)
    # Feature 5 = f(feature 2, feature 3)
    def feature_cl(s):
        s = frozenset(s)
        result = set(s)
        if 0 in result and 1 in result:
            result.add(4)
        if 2 in result and 3 in result:
            result.add(5)
        return frozenset(result)

    def feature_cap(s):
        return 0 if len(frozenset(s)) == 0 else 1

    print(f"\nFeatures: {features}")

    # Check which features are redundant
    print("\n--- Feature Redundancy Analysis ---")
    for x in sorted(features):
        others = features - {x}
        if x in feature_cl(frozenset(others)):
            # Find minimal generating set
            for size in range(1, len(others) + 1):
                for combo in combinations(sorted(others), size):
                    if x in feature_cl(frozenset(combo)):
                        print(f"  Feature {x}: REDUNDANT "
                              f"(generated by {set(combo)})")
                        break
                else:
                    continue
                break
        else:
            print(f"  Feature {x}: ESSENTIAL")

    # Find skeleton
    G = set(features)
    full_cl = feature_cl(frozenset(G))
    changed = True
    while changed:
        changed = False
        for g in sorted(G):
            if feature_cl(frozenset(G - {g})) == full_cl:
                G.remove(g)
                changed = True
                break

    print(f"\nSelected features (skeleton): {sorted(G)}")
    print(f"Dimension reduction: {len(features)} → {len(G)}")


