# §4. Canonical Skeleton
# ============================================================

def find_canonical_skeleton(cl_op: ClosureOperator) -> FrozenSet:
    """Find the canonical skeleton: minimal generating set."""
    G = set(cl_op.ground)
    full_closure = cl_op.cl(frozenset(G))

    changed = True
    while changed:
        changed = False
        for g in list(G):
            reduced = frozenset(G - {g})
            if cl_op.cl(reduced) == full_closure:
                G.remove(g)
                changed = True
                break

    return frozenset(G)


def verify_skeleton_minimality(cl_op: ClosureOperator, skeleton: FrozenSet) -> bool:
    """Verify that no element can be removed from the skeleton."""
    full_closure = cl_op.cl(skeleton)
    for g in skeleton:
        reduced = skeleton - {g}
        if cl_op.cl(reduced) == full_closure:
            return False
    return True


