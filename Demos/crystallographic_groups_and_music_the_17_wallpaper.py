#!/usr/bin/env python3
"""Numerical demonstrations of symmetry quotients for binary rhythmic grids.

The script uses only the Python standard library. It computes equivalence classes,
enumerates symmetry-invariant patterns, checks the count 2^m, and reports concrete
one- and two-dimensional musical examples.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import product
from typing import Callable, Iterable, Iterator, Sequence

Cell = tuple[int, int]
Pattern = tuple[int, ...]


class DisjointSet:
    """Union-find data structure with path compression and union by rank."""

    def __init__(self, size: int) -> None:
        self.parent = list(range(size))
        self.rank = [0] * size

    def find(self, item: int) -> int:
        if self.parent[item] != item:
            self.parent[item] = self.find(self.parent[item])
        return self.parent[item]

    def union(self, left: int, right: int) -> None:
        root_left, root_right = self.find(left), self.find(right)
        if root_left == root_right:
            return
        if self.rank[root_left] < self.rank[root_right]:
            root_left, root_right = root_right, root_left
        self.parent[root_right] = root_left
        if self.rank[root_left] == self.rank[root_right]:
            self.rank[root_left] += 1

    def classes(self) -> list[list[int]]:
        grouped: dict[int, list[int]] = {}
        for item in range(len(self.parent)):
            grouped.setdefault(self.find(item), []).append(item)
        return sorted(grouped.values(), key=lambda group: group[0])


def quotient_classes(size: int, identifications: Iterable[tuple[int, int]]) -> list[list[int]]:
    """Return equivalence classes generated by the supplied cell pairs."""
    dsu = DisjointSet(size)
    for left, right in identifications:
        if not (0 <= left < size and 0 <= right < size):
            raise ValueError("identification index lies outside the cell set")
        dsu.union(left, right)
    return dsu.classes()


def expand_labels(size: int, classes: Sequence[Sequence[int]], labels: Sequence[int]) -> Pattern:
    """Pull a binary quotient labeling back to the original cell set."""
    if len(classes) != len(labels) or any(bit not in (0, 1) for bit in labels):
        raise ValueError("one binary label is required for each quotient class")
    values = [0] * size
    for group, bit in zip(classes, labels):
        for cell in group:
            values[cell] = bit
    return tuple(values)


def invariant_patterns(size: int, classes: Sequence[Sequence[int]]) -> Iterator[Pattern]:
    """Enumerate all 2^m patterns, where m is the number of classes."""
    for labels in product((0, 1), repeat=len(classes)):
        yield expand_labels(size, classes, labels)


def is_invariant(pattern: Sequence[int], classes: Sequence[Sequence[int]]) -> bool:
    """Check that every class is constant."""
    return all(not group or all(pattern[cell] == pattern[group[0]] for cell in group) for group in classes)


def render_loop(pattern: Sequence[int]) -> str:
    """Render zero as a rest and one as an onset."""
    return " ".join("●" if bit else "·" for bit in pattern)


def render_grid(pattern: Sequence[int], rows: int, columns: int) -> str:
    return "\n".join(render_loop(pattern[r * columns : (r + 1) * columns]) for r in range(rows))


@dataclass(frozen=True)
class ExampleResult:
    name: str
    cells: int
    classes: int
    predicted_patterns: int
    enumerated_patterns: int


def analyze(name: str, size: int, pairs: Iterable[tuple[int, int]]) -> tuple[ExampleResult, list[list[int]], list[Pattern]]:
    classes = quotient_classes(size, pairs)
    patterns = list(invariant_patterns(size, classes))
    assert len(set(patterns)) == 2 ** len(classes)
    assert all(is_invariant(pattern, classes) for pattern in patterns)
    return (
        ExampleResult(name, size, len(classes), 2 ** len(classes), len(patterns)),
        classes,
        patterns,
    )


def reflection_pairs(length: int) -> list[tuple[int, int]]:
    return [(i, length - 1 - i) for i in range(length)]


def half_turn_pairs(rows: int, columns: int) -> list[tuple[int, int]]:
    def index(row: int, column: int) -> int:
        return row * columns + column
    return [
        (index(r, c), index((-r) % rows, (-c) % columns))
        for r in range(rows)
        for c in range(columns)
    ]


def maximal_pairs(size: int) -> list[tuple[int, int]]:
    return [(0, i) for i in range(size)] if size else []


def main() -> None:
    examples = [
        analyze("Eight-step unconstrained loop", 8, []),
        analyze("Sixteen-step mirror rhythm", 16, reflection_pairs(16)),
        analyze("4 × 4 toroidal half-turn rhythm", 16, half_turn_pairs(4, 4)),
        analyze("Maximally symmetric twelve-cell rhythm", 12, maximal_pairs(12)),
    ]

    print("SYMMETRY–ENTROPY NUMERICAL DEMONSTRATION")
    print("=" * 50)
    for result, classes, patterns in examples:
        print(f"\n{result.name}")
        print(f"  cells: {result.cells}")
        print(f"  quotient classes: {result.classes}")
        print(f"  predicted count 2^m: {result.predicted_patterns}")
        print(f"  enumerated count: {result.enumerated_patterns}")
        print(f"  uniform capacity: {result.classes} bits")
        print(f"  class sizes: {[len(group) for group in classes]}")
        print(f"  sample: {render_loop(patterns[min(1, len(patterns) - 1)])}")

    _, _, half_turn_patterns = examples[2]
    print("\nA sample 4 × 4 half-turn-invariant grid:")
    print(render_grid(half_turn_patterns[137], 4, 4))

    maximal = examples[3][2]
    assert maximal == [(0,) * 12, (1,) * 12]
    print("\nMaximal symmetry leaves exactly:")
    for pattern in maximal:
        print(" ", render_loop(pattern))


if __name__ == "__main__":
    main()
