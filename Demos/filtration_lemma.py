"""
Clock-and-Switch Worlds: numerical demonstrations.

This script is fully self-contained (standard library only) and illustrates,
by explicit computation on small finite orders, the results of the paper
"Clock-and-Switch Worlds: A Sharp Filtration Theorem for Finite Preorders".

A clock-and-switch world CW(n, m) is the set of pairs (clock, switches) with
clock in {0, ..., n-1} and switches a subset of {0, ..., m-1}, ordered by

    (c, S) <= (c', S')   iff   c <= c'  and  S subset of S'.

A bounded morphism f : X -> Y of preorders satisfies
    (forth)  x <= y  implies  f(x) <= f(y),
    (back)   f(x) <= q  implies  there is y >= x with f(y) = q.

Demonstrations performed below:

  1. Cardinality  |CW(n, m)| = n * 2^m  and  |CW_c(n, m)| = n * 2^m * c.
  2. The greedy climb realises every finite rooted directed poset as a
     surjective bounded morphic image of CW(1, |P| - 1).
  3. The naive greedy climb (without the "jump to the top" clause) is NOT
     monotone on the diamond -- the counterexample that motivates the clause.
  4. The two lower bounds: |P| <= n * 2^m and height(P) <= n + m - 1.
  5. Exact switch count for chains: the (l+1)-chain needs exactly l switches.
  6. Antisymmetry is inherited: the two-element cluster is unrepresentable
     (verified by exhaustive search over all maps from small worlds).
  7. Phase-augmented worlds repair this: every finite rooted directed
     preorder is an image of CW_c(1, m) with c the maximal cluster size and
     m the number of clusters -- and c cannot be lowered.
"""

from __future__ import annotations

from itertools import combinations, product
from typing import Callable, Dict, FrozenSet, List, Optional, Sequence, Set, Tuple

# ---------------------------------------------------------------------------
# Finite preorders
# ---------------------------------------------------------------------------

Preorder = Tuple[Tuple[int, ...], Set[Tuple[int, int]]]
"""A finite preorder: the tuple of its elements and its <= relation as pairs."""


def transitive_reflexive_closure(
    elements: Sequence[int], edges: Sequence[Tuple[int, int]]
) -> Set[Tuple[int, int]]:
    """Reflexive-transitive closure of `edges` on `elements` (Floyd-Warshall)."""
    rel: Set[Tuple[int, int]] = {(x, x) for x in elements}
    rel |= set(edges)
    changed = True
    while changed:
        changed = False
        for a, b in list(rel):
            for c, d in list(rel):
                if b == c and (a, d) not in rel:
                    rel.add((a, d))
                    changed = True
    return rel


def make_preorder(n: int, edges: Sequence[Tuple[int, int]]) -> Preorder:
    """Build the preorder on {0,...,n-1} generated by `edges`."""
    elements = tuple(range(n))
    return elements, transitive_reflexive_closure(elements, edges)


def leq(P: Preorder) -> Callable[[int, int], bool]:
    """The order relation of `P` as a predicate."""
    _, rel = P
    return lambda x, y: (x, y) in rel


def is_rooted(P: Preorder) -> Optional[int]:
    """Return a root of `P` (a point below everything) or None."""
    elements, rel = P
    for r in elements:
        if all((r, p) in rel for p in elements):
            return r
    return None


def is_directed(P: Preorder) -> bool:
    """True iff every pair of points of `P` has a common upper bound."""
    elements, rel = P
    return all(
        any((x, z) in rel and (y, z) in rel for z in elements)
        for x in elements
        for y in elements
    )


def top_element(P: Preorder) -> Optional[int]:
    """Return a greatest element of `P` (exists when finite, nonempty, directed)."""
    elements, rel = P
    for t in elements:
        if all((p, t) in rel for p in elements):
            return t
    return None


def is_antisymmetric(P: Preorder) -> bool:
    """True iff `P` is a partial order."""
    elements, rel = P
    return all(
        not ((x, y) in rel and (y, x) in rel and x != y)
        for x in elements
        for y in elements
    )


def cluster_of(P: Preorder, p0: int) -> FrozenSet[int]:
    """The cluster of `p0`: all points mutually accessible with `p0`."""
    elements, rel = P
    return frozenset(p for p in elements if (p, p0) in rel and (p0, p) in rel)


def clusters(P: Preorder) -> List[FrozenSet[int]]:
    """The clusters of `P`, i.e. the fibres of the antisymmetrisation."""
    elements, _ = P
    seen: List[FrozenSet[int]] = []
    for p in elements:
        c = cluster_of(P, p)
        if c not in seen:
            seen.append(c)
    return seen


def height(P: Preorder) -> int:
    """The largest l with a strictly increasing chain c_0 < ... < c_l."""
    elements, rel = P

    def strict(x: int, y: int) -> bool:
        return (x, y) in rel and (y, x) not in rel

    best: Dict[int, int] = {}

    def longest_from(x: int) -> int:
        if x in best:
            return best[x]
        best[x] = 0  # guards against clusters (strict is irreflexive)
        value = 0
        for y in elements:
            if strict(x, y):
                value = max(value, 1 + longest_from(y))
        best[x] = value
        return value

    return max((longest_from(x) for x in elements), default=0)


def linear_extension(P: Preorder) -> List[int]:
    """A listing t_0, ..., t_{k-1} of a finite poset with t_i <= t_j => i <= j."""
    elements, rel = P
    remaining = list(elements)
    out: List[int] = []
    while remaining:
        for x in remaining:
            if all((y, x) not in rel or y == x or y in out for y in remaining):
                out.append(x)
                remaining.remove(x)
                break
        else:  # pragma: no cover - impossible for a finite poset
            raise ValueError("not a partial order")
    return out


# ---------------------------------------------------------------------------
# Clock-and-switch worlds
# ---------------------------------------------------------------------------

World = Tuple[int, FrozenSet[int]]
"""A clock-and-switch world: a clock reading and the set of switches that are on."""


def cworld(n: int, m: int) -> List[World]:
    """All n * 2^m states of CW(n, m)."""
    out: List[World] = []
    for c in range(n):
        for bits in product([False, True], repeat=m):
            out.append((c, frozenset(i for i, b in enumerate(bits) if b)))
    return out


def world_leq(w: World, v: World) -> bool:
    """Accessibility in CW(n, m): the clock advances, switches only turn on."""
    return w[0] <= v[0] and w[1] <= v[1]


def rank(w: World) -> int:
    """The rank grading: clock reading plus number of switches that are on."""
    return w[0] + len(w[1])


# ---------------------------------------------------------------------------
# Checking bounded morphisms
# ---------------------------------------------------------------------------

def check_bounded_morphism(
    source: Sequence[World],
    src_leq: Callable[[World, World], bool],
    P: Preorder,
    f: Callable[[World], int],
) -> Tuple[bool, bool, bool]:
    """Return (forth, back, surjective) for the candidate morphism `f`."""
    elements, _ = P
    le = leq(P)
    forth = all(le(f(x), f(y)) for x in source for y in source if src_leq(x, y))
    back = all(
        any(src_leq(x, y) and f(y) == q for y in source)
        for x in source
        for q in elements
        if le(f(x), q)
    )
    surjective = {f(x) for x in source} == set(elements)
    return forth, back, surjective


# ---------------------------------------------------------------------------
# The greedy climb
# ---------------------------------------------------------------------------

def greedy_climb(P: Preorder, drop_root_switch: bool = True) -> Tuple[int, Callable[[World], int]]:
    """The greedy climb morphism from CW(1, m) onto a rooted directed poset `P`.

    Returns the number of switches m and the map itself.  With
    `drop_root_switch` the root's (no-op) switch is removed, giving m = |P| - 1.
    """
    root = is_rooted(P)
    top = top_element(P)
    if root is None or top is None:
        raise ValueError("P must be rooted and directed")
    order = linear_extension(P)
    if drop_root_switch:
        order = order[1:]  # the root always comes first, and its switch is a no-op
    le = leq(P)
    m = len(order)

    def climb(w: World) -> int:
        pos = root
        for i, target in enumerate(order):
            if i in w[1]:
                pos = target if le(pos, target) else top
        return pos

    return m, climb


def naive_climb(P: Preorder) -> Tuple[int, Callable[[World], int]]:
    """The greedy climb WITHOUT the 'jump to the top' repair clause."""
    root = is_rooted(P)
    if root is None:
        raise ValueError("P must be rooted")
    order = linear_extension(P)
    le = leq(P)

    def climb(w: World) -> int:
        pos = root
        for i, target in enumerate(order):
            if i in w[1] and le(pos, target):
                pos = target
        return pos

    return len(order), climb


# ---------------------------------------------------------------------------
# Exhaustive search for the minimal switch number
# ---------------------------------------------------------------------------

def exists_morphism_from_cube(P: Preorder, m: int) -> Optional[Dict[World, int]]:
    """Search for a surjective bounded morphism CW(1, m) -> P, or return None.

    Vertices of the cube are assigned in order of increasing popcount, so that
    monotonicity can be checked against already-assigned predecessors and the
    search tree pruned as early as possible.
    """
    elements, _ = P
    le = leq(P)
    worlds = sorted(cworld(1, m), key=lambda w: (len(w[1]), sorted(w[1])))
    assignment: Dict[World, int] = {}

    def predecessors(w: World) -> List[World]:
        return [v for v in assignment if world_leq(v, w)]

    def complete_ok() -> bool:
        f = assignment.__getitem__
        forth, back, surj = check_bounded_morphism(worlds, world_leq, P, f)
        return forth and back and surj

    def recurse(index: int) -> bool:
        if index == len(worlds):
            return complete_ok()
        w = worlds[index]
        preds = predecessors(w)
        for value in elements:
            if all(le(assignment[v], value) for v in preds):
                assignment[w] = value
                if recurse(index + 1):
                    return True
                del assignment[w]
        return False

    return dict(assignment) if recurse(0) else None


def switch_number(P: Preorder, max_switches: int = 6) -> Optional[int]:
    """The least m with a surjective bounded morphism CW(1, m) -> P."""
    for m in range(max_switches + 1):
        if 2 ** m < len(P[0]):
            continue  # cardinality bound
        if m < height(P):
            continue  # height bound (one clock tick)
        if exists_morphism_from_cube(P, m) is not None:
            return m
    return None


# ---------------------------------------------------------------------------
# Phase-augmented worlds
# ---------------------------------------------------------------------------

PWorld = Tuple[World, int]
"""A phase-augmented world: a base world together with an order-invisible phase."""


def cworld_phase(n: int, m: int, c: int) -> List[PWorld]:
    """All n * 2^m * c states of CW_c(n, m)."""
    return [(w, j) for w in cworld(n, m) for j in range(c)]


def pworld_leq(w: PWorld, v: PWorld) -> bool:
    """Accessibility in CW_c(n, m): the phase is invisible to the order."""
    return world_leq(w[0], v[0])


def phase_representation(P: Preorder) -> Tuple[int, int, Callable[[PWorld], int]]:
    """The phase-augmented representation of a finite rooted directed preorder.

    Returns (m, c, F) where m is the number of clusters, c the maximal cluster
    size, and F : CW_c(1, m) -> P a surjective bounded morphism.  The map is
    "greedy climb on the antisymmetrisation, then read the phase as a choice of
    element inside the cluster reached".
    """
    cls = clusters(P)
    c = max(len(x) for x in cls)
    reps = [min(x) for x in cls]
    index_of = {p: i for i, x in enumerate(cls) for p in x}
    le = leq(P)

    # the antisymmetrisation Q, a rooted directed poset on the clusters
    q_edges = [
        (i, j)
        for i in range(len(cls))
        for j in range(len(cls))
        if le(reps[i], reps[j])
    ]
    Q = make_preorder(len(cls), q_edges)
    m, f = greedy_climb(Q, drop_root_switch=False)

    # a fibre-surjective choice function pick(q, j)
    enumerated = [sorted(x) for x in cls]

    def pick(q: int, j: int) -> int:
        members = enumerated[q]
        return members[j] if j < len(members) else members[0]

    def F(w: PWorld) -> int:
        return pick(f(w[0]), w[1])

    return m, c, F


def check_phase_morphism(
    P: Preorder, m: int, c: int, F: Callable[[PWorld], int]
) -> Tuple[bool, bool, bool]:
    """Return (forth, back, surjective) for a candidate map out of CW_c(1, m)."""
    source = cworld_phase(1, m, c)
    elements, _ = P
    le = leq(P)
    forth = all(le(F(x), F(y)) for x in source for y in source if pworld_leq(x, y))
    back = all(
        any(pworld_leq(x, y) and F(y) == q for y in source)
        for x in source
        for q in elements
        if le(F(x), q)
    )
    surjective = {F(x) for x in source} == set(elements)
    return forth, back, surjective


# ---------------------------------------------------------------------------
# Example orders
# ---------------------------------------------------------------------------

def chain(k: int) -> Preorder:
    """The k-element chain 0 < 1 < ... < k-1."""
    return make_preorder(k, [(i, i + 1) for i in range(k - 1)])


def diamond() -> Preorder:
    """The diamond 0 < a, b < 1 with a = 1, b = 2 incomparable, top = 3."""
    return make_preorder(4, [(0, 1), (0, 2), (1, 3), (2, 3)])


def boolean_lattice(d: int) -> Preorder:
    """The Boolean lattice of subsets of a d-element set, as a poset on 2^d points."""
    subsets = [frozenset(s) for r in range(d + 1) for s in combinations(range(d), r)]
    index = {s: i for i, s in enumerate(subsets)}
    edges = [(index[s], index[t]) for s in subsets for t in subsets if s <= t]
    return make_preorder(len(subsets), edges)


def six_point_poset() -> Preorder:
    """A six-point bounded poset of height 3 with two incomparable mid-levels."""
    # 0 = bottom, 1 and 2 incomparable, 3 and 4 incomparable above them, 5 = top
    return make_preorder(
        6, [(0, 1), (0, 2), (1, 3), (1, 4), (2, 3), (2, 4), (3, 5), (4, 5)]
    )


def two_element_cluster() -> Preorder:
    """The two-element cluster: distinct points, each accessible from the other."""
    return make_preorder(2, [(0, 1), (1, 0)])


def clustered_preorder() -> Preorder:
    """Bottom, then a three-element cluster, then a top: clusters of sizes 1, 3, 1."""
    edges = [(0, 1), (0, 2), (0, 3), (1, 2), (2, 1), (1, 3), (3, 1), (2, 3), (3, 2)]
    edges += [(1, 4), (2, 4), (3, 4)]
    return make_preorder(5, edges)


# ---------------------------------------------------------------------------
# Demonstrations
# ---------------------------------------------------------------------------

def demo_cardinality() -> None:
    print("=" * 72)
    print("1. Cardinality of clock-and-switch worlds")
    print("=" * 72)
    for n, m in [(1, 0), (1, 3), (3, 2), (4, 4)]:
        size = len(cworld(n, m))
        print(f"  |CW({n},{m})| = {size:5d}   predicted n*2^m = {n * 2 ** m}")
        assert size == n * 2 ** m
    for n, m, c in [(1, 2, 3), (2, 3, 2)]:
        size = len(cworld_phase(n, m, c))
        print(f"  |CW_{c}({n},{m})| = {size:5d}   predicted n*2^m*c = {n * 2 ** m * c}")
        assert size == n * 2 ** m * c
    print()


def demo_greedy_climb() -> None:
    print("=" * 72)
    print("2. The greedy climb represents finite rooted directed posets")
    print("=" * 72)
    examples = [
        ("3-chain", chain(3)),
        ("5-chain", chain(5)),
        ("diamond", diamond()),
        ("Boolean lattice B_2", boolean_lattice(2)),
        ("Boolean lattice B_3", boolean_lattice(3)),
        ("6-point poset", six_point_poset()),
    ]
    for name, P in examples:
        m, f = greedy_climb(P)
        forth, back, surj = check_bounded_morphism(cworld(1, m), world_leq, P, f)
        print(
            f"  {name:22s} |P| = {len(P[0]):2d}  switches used = {m:2d}  "
            f"forth={forth}  back={back}  onto={surj}"
        )
        assert forth and back and surj
        assert m == len(P[0]) - 1
    print()


def demo_naive_climb_fails() -> None:
    print("=" * 72)
    print("3. Without 'jump to the top' the climb is not monotone (diamond)")
    print("=" * 72)
    P = diamond()
    order = linear_extension(P)
    print(f"  linear extension of the diamond: {order}")
    m, f = naive_climb(P)
    witnesses = [
        (w, v)
        for w in cworld(1, m)
        for v in cworld(1, m)
        if world_leq(w, v) and not leq(P)(f(w), f(v))
    ]
    w, v = witnesses[0]
    print(f"  switches {sorted(w[1])} climb to {f(w)}, "
          f"switches {sorted(v[1])} climb to {f(v)}")
    print(f"  but {f(w)} <= {f(v)} is {leq(P)(f(w), f(v))}: monotonicity fails.")
    m2, f2 = greedy_climb(P, drop_root_switch=False)
    forth, _, _ = check_bounded_morphism(cworld(1, m2), world_leq, P, f2)
    print(f"  with the repair clause, forth holds: {forth}")
    assert witnesses and forth
    print()


def demo_lower_bounds() -> None:
    print("=" * 72)
    print("4. The two lower bounds: cardinality and height")
    print("=" * 72)
    examples = [
        ("3-chain", chain(3)),
        ("6-chain", chain(6)),
        ("diamond", diamond()),
        ("Boolean lattice B_3", boolean_lattice(3)),
        ("6-point poset", six_point_poset()),
    ]
    print(f"  {'order':22s} {'|P|':>4s} {'height':>7s} {'log2|P|':>9s} "
          f"{'switches used':>14s}")
    for name, P in examples:
        m, f = greedy_climb(P)
        h = height(P)
        log2 = max(0, (len(P[0]) - 1).bit_length())
        print(f"  {name:22s} {len(P[0]):4d} {h:7d} {log2:9d} {m:14d}")
        # both bounds hold for the constructed representation with n = 1
        assert len(P[0]) <= 1 * 2 ** m
        assert h <= 1 + m - 1
    print()


def demo_chain_switch_count() -> None:
    print("=" * 72)
    print("5. Exact switch count for chains: the (l+1)-chain needs exactly l")
    print("=" * 72)
    for ell in range(1, 4):
        P = chain(ell + 1)
        found = switch_number(P, max_switches=ell + 1)
        print(f"  ({ell + 1})-chain: minimal number of switches = {found} "
              f"(theory: {ell})")
        assert found == ell
    print()


def demo_cluster_obstruction() -> None:
    print("=" * 72)
    print("6. Antisymmetry is inherited: the two-element cluster is unreachable")
    print("=" * 72)
    K = two_element_cluster()
    print(f"  rooted: {is_rooted(K) is not None}   directed: {is_directed(K)}   "
          f"antisymmetric: {is_antisymmetric(K)}")
    for m in range(4):
        found = exists_morphism_from_cube(K, m)
        print(f"  surjective bounded morphism from CW(1,{m}) onto the cluster: "
              f"{'YES' if found else 'none'}")
        assert found is None
    print("  (the theory says no CW(n,m) works, for any n and m)")
    print()


def demo_phase_repair() -> None:
    print("=" * 72)
    print("7. Phase-augmented worlds: the filtration lemma for preorders")
    print("=" * 72)
    examples = [
        ("two-element cluster", two_element_cluster()),
        ("bottom + 3-cluster + top", clustered_preorder()),
        ("diamond (a poset)", diamond()),
    ]
    for name, P in examples:
        sizes = sorted(len(x) for x in clusters(P))
        m, c, F = phase_representation(P)
        forth, back, surj = check_phase_morphism(P, m, c, F)
        print(f"  {name:26s} cluster sizes {sizes}  ->  CW_{c}(1,{m})  "
              f"forth={forth} back={back} onto={surj}")
        assert forth and back and surj
        assert c == max(sizes)
        assert m == len(clusters(P))
    print()
    print("  Sharpness: the number of phases can never be less than the maximal")
    print("  cluster size, since every cluster of an image of CW_c(n,m) injects")
    print("  into the c phases.  Checking the failure directly for c = 1:")
    K = two_element_cluster()
    found = any(exists_morphism_from_cube(K, m) is not None for m in range(4))
    print(f"    one phase (i.e. an ordinary world) onto the 2-cluster: "
          f"{'YES' if found else 'impossible'}")
    assert not found
    print()


def main() -> None:
    demo_cardinality()
    demo_greedy_climb()
    demo_naive_climb_fails()
    demo_lower_bounds()
    demo_chain_switch_count()
    demo_cluster_obstruction()
    demo_phase_repair()
    print("All demonstrations completed successfully.")


if __name__ == "__main__":
    main()
