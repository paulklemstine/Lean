"""
Numerical demonstrations for:

    "The Incoherence Index as an Arithmetic Invariant:
     An Order Formula and the Realizable Spectrum"

Model recap
-----------
A *frame* on n social states is a finite set F of residues in Z/nZ ("atoms").
A *perfectly balanced sequence* is a non-empty multiset of atoms summing to 0
mod n. The *incoherence index* of F is the length of the shortest such sequence
(0 if none exists).

Theorems exercised here:
  * incoherenceIndex_singleton:        incoherenceIndex({a}) = addOrderOf(a) = n/gcd(n,a)
  * incoherenceIndex_singleton_one':   incoherenceIndex({1}) = n
  * incoherenceIndex_antitone:         F ⊆ G  ⟹  index(G) ≤ index(F)   (F incoherent)
  * every_index_realized_maximal:      every d ≥ 2 is the index of a maximal frame
  * divisor_index_realized:            every divisor d ≥ 2 of n is a singleton index
  * incoherenceIndex_oneTwo_zmod5:     index({1,2} ⊆ Z/5Z) = 3   (3 ∤ 5)

This script is self-contained: only the standard library is used.
"""

from __future__ import annotations

from collections import deque
from math import gcd
from typing import Iterable, List, Optional, Set, Tuple


# ---------------------------------------------------------------------------
# Core computations
# ---------------------------------------------------------------------------

def additive_order(a: int, n: int) -> int:
    """Additive order of `a` in Z/nZ, i.e. the least m ≥ 1 with m*a ≡ 0 (mod n).

    Closed form: n / gcd(n, a)  (and n for a ≡ 0, where gcd(n,0)=n gives 1; we
    special-case the identity 0 to return its true order 1).
    """
    a %= n
    if a == 0:
        return 1
    return n // gcd(n, a)


def incoherence_index_bfs(atoms: Iterable[int], n: int) -> int:
    """Shortest non-empty zero-sum length over `atoms` in Z/nZ (0 if none).

    Breadth-first search on partial sums (Algorithm B). State = current residue;
    from residue r we may step to (r + a) % n for each atom a. We seek the least
    number of steps (≥ 1) returning to residue 0. Terminates within n levels.
    """
    F: Set[int] = {a % n for a in atoms}
    if not F:
        return 0
    # frontier of residues reachable using exactly `level` atoms
    frontier: Set[int] = {0}
    visited_after_step: Set[int] = set()
    for level in range(1, n + 1):
        nxt: Set[int] = set()
        for r in frontier:
            for a in F:
                nxt.add((r + a) % n)
        if 0 in nxt:
            return level
        # prune residues we have already produced (shortest distance is monotone)
        nxt -= visited_after_step
        visited_after_step |= nxt
        if not nxt:
            return 0
        frontier = nxt
    return 0


def shortest_balanced_sequence(atoms: Iterable[int], n: int) -> Optional[List[int]]:
    """Return one explicit shortest balanced sequence (witness), or None."""
    F: List[int] = sorted({a % n for a in atoms})
    if not F:
        return None
    # BFS storing a back-pointer path of atoms used
    start: Tuple[int, Tuple[int, ...]] = (0, ())
    queue: deque[Tuple[int, Tuple[int, ...]]] = deque([start])
    seen: Set[int] = set()
    while queue:
        r, path = queue.popleft()
        for a in F:
            nr = (r + a) % n
            npath = path + (a,)
            if nr == 0:
                return list(npath)
            if nr not in seen:
                seen.add(nr)
                queue.append((nr, npath))
    return None


def generated_subgroup(atoms: Iterable[int], n: int) -> Set[int]:
    """The additive subgroup of Z/nZ generated by `atoms`."""
    F: Set[int] = {a % n for a in atoms}
    closure: Set[int] = {0}
    changed = True
    while changed:
        changed = False
        for r in list(closure):
            for a in F:
                s = (r + a) % n
                if s not in closure:
                    closure.add(s)
                    changed = True
    return closure


def is_maximal(atoms: Iterable[int], n: int) -> bool:
    """True iff the atoms generate all of Z/nZ."""
    return len(generated_subgroup(atoms, n)) == n


# ---------------------------------------------------------------------------
# Demonstrations
# ---------------------------------------------------------------------------

def demo_order_formula() -> None:
    """Theorem 1: incoherenceIndex({a}) = additive order of a = n/gcd(n,a)."""
    print("=" * 68)
    print("Theorem 1 (Order Formula): index({a}) = addOrderOf(a) = n/gcd(n,a)")
    print("=" * 68)
    for n in (4, 5, 6, 12):
        print(f"\n  n = {n}:")
        for a in range(1, n):
            idx = incoherence_index_bfs([a], n)
            order = additive_order(a, n)
            ok = "OK" if idx == order == n // gcd(n, a) else "MISMATCH"
            wit = shortest_balanced_sequence([a], n)
            print(f"    a={a}: index={idx}  order={order}  n/gcd={n//gcd(n,a)}  "
                  f"[{ok}]  witness={wit}")


def demo_unit_frame() -> None:
    """Corollary 1: incoherenceIndex({1}) = n (maximal, maximally robust)."""
    print("\n" + "=" * 68)
    print("Corollary 1 (Unit frame): index({1}) = n, and {1} is maximal")
    print("=" * 68)
    for n in (2, 3, 7, 10, 13):
        idx = incoherence_index_bfs([1], n)
        print(f"  n={n:>2}: index({{1}})={idx:>2}  maximal={is_maximal([1], n)}  "
              f"[{'OK' if idx == n else 'MISMATCH'}]")


def demo_saturation_law() -> None:
    """Theorem 2: F ⊆ G with F incoherent ⟹ index(G) ≤ index(F)."""
    print("\n" + "=" * 68)
    print("Theorem 2 (Saturation Law): adding atoms can only shorten the index")
    print("=" * 68)
    cases: List[Tuple[int, List[int], List[int]]] = [
        (4, [1], [1, 3]),
        (6, [1], [1, 2, 3]),
        (12, [1], [1, 4, 6]),
        (5, [1], [1, 2]),
    ]
    for n, F, G in cases:
        iF = incoherence_index_bfs(F, n)
        iG = incoherence_index_bfs(G, n)
        ok = "OK" if iG <= iF else "VIOLATION"
        print(f"  Z/{n}Z: index({F})={iF}  ⊇  index({G})={iG}   "
              f"({iG} ≤ {iF}) [{ok}]")


def demo_divisor_realization() -> None:
    """Theorem 4: every divisor d ≥ 2 of n is a singleton index (a = n/d)."""
    print("\n" + "=" * 68)
    print("Theorem 4 (Divisor realization): divisor d of n via atom a = n/d")
    print("=" * 68)
    for n in (12, 30):
        divisors = [d for d in range(2, n + 1) if n % d == 0]
        print(f"\n  n={n}, divisors ≥ 2: {divisors}")
        for d in divisors:
            a = n // d
            idx = incoherence_index_bfs([a], n)
            print(f"    d={d:>2}: atom a={a:>2}  index={idx:>2}  "
                  f"[{'OK' if idx == d else 'MISMATCH'}]")


def demo_full_realization() -> None:
    """Theorem 3: every d ≥ 2 is the index of a maximal frame ({1} ⊆ Z/dZ)."""
    print("\n" + "=" * 68)
    print("Theorem 3 (Full realization): every d ≥ 2 by a maximal frame {1}⊆Z/dZ")
    print("=" * 68)
    for d in range(2, 14):
        idx = incoherence_index_bfs([1], d)
        print(f"  d={d:>2}: frame {{1}}⊆Z/{d}Z  index={idx:>2}  "
              f"maximal={is_maximal([1], d)}  [{'OK' if idx == d else 'MISMATCH'}]")


def demo_escape_divisor_lattice() -> None:
    """Theorem 5: index({1,2} ⊆ Z/5Z) = 3, a non-divisor of 5."""
    print("\n" + "=" * 68)
    print("Theorem 5 (Escape): index({1,2} ⊆ Z/5Z) = 3, and 3 does NOT divide 5")
    print("=" * 68)
    n = 5
    idx = incoherence_index_bfs([1, 2], n)
    wit = shortest_balanced_sequence([1, 2], n)
    singleton_indices = sorted({incoherence_index_bfs([a], n) for a in range(1, n)})
    print(f"  index({{1,2}} ⊆ Z/5Z) = {idx}   witness = {wit}  "
          f"(sum = {sum(wit) if wit else 0} ≡ 0 mod 5)")
    print(f"  3 divides 5? {5 % 3 == 0}")
    print(f"  achievable singleton indices on Z/5Z: {singleton_indices} "
          f"(only divisors of 5)")
    print(f"  maximal({{1,2}} ⊆ Z/5Z) = {is_maximal([1, 2], n)}")
    # Brute-force confirmation that no length-1 or length-2 balanced sequence exists
    atoms = [1, 2]
    has_len1 = any(a % n == 0 for a in atoms)
    has_len2 = any((a + b) % n == 0 for a in atoms for b in atoms)
    print(f"  length-1 violation exists? {has_len1}   "
          f"length-2 violation exists? {has_len2}")


def main() -> None:
    demo_order_formula()
    demo_unit_frame()
    demo_saturation_law()
    demo_divisor_realization()
    demo_full_realization()
    demo_escape_divisor_lattice()
    print("\nAll demonstrations completed.")


if __name__ == "__main__":
    main()
