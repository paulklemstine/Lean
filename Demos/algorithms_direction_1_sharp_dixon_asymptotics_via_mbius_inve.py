#!/usr/bin/env python3
"""
Algorithms for Subgroup Lattice Möbius Inversion

This module implements the core algorithms for computing:
1. Subgroup lattices of symmetric groups
2. Möbius function values on the subgroup lattice
3. Generating pair counts via Möbius inversion
4. Asymptotic approximations

Time complexity:
  - Subgroup lattice of S_n: O(n!² · n) (pair-closure enumeration)
  - Möbius function: O(|Sub(G)|²) where |Sub(G)| is the number of subgroups
  - Generating pairs (brute force): O(n!² · n!)
  - Generating pairs (Möbius): O(|Sub(G)|) after lattice is computed

Space complexity: O(|Sub(G)| · n!) for storing subgroups
"""

import itertools
import math
from fractions import Fraction
from collections import defaultdict
from typing import Dict, FrozenSet, List, Set, Tuple, Optional


# ─────────────────────────────────────────────────────────────
# Permutation arithmetic
# ─────────────────────────────────────────────────────────────

def compose(p: Tuple[int, ...], q: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compose two permutations: (p ∘ q)(i) = p(q(i)).

    Args:
        p: First permutation as a tuple.
        q: Second permutation as a tuple.

    Returns:
        The composition p ∘ q.

    Example:
        >>> compose((1, 0, 2), (0, 2, 1))
        (1, 2, 0)
    """
    return tuple(p[q[i]] for i in range(len(p)))


def inverse(p: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compute the inverse of a permutation.

    Example:
        >>> inverse((1, 2, 0))
        (2, 0, 1)
    """
    n = len(p)
    inv = [0] * n
    for i in range(n):
        inv[p[i]] = i
    return tuple(inv)


def identity(n: int) -> Tuple[int, ...]:
    """The identity permutation of degree n."""
    return tuple(range(n))


def perm_sign(p: Tuple[int, ...]) -> int:
    """Compute the sign of a permutation (+1 for even, -1 for odd).

    Example:
        >>> perm_sign((1, 0, 2))
        -1
    """
    n = len(p)
    visited = [False] * n
    sign = 1
    for i in range(n):
        if not visited[i]:
            j = i
            cycle_len = 0
            while not visited[j]:
                visited[j] = True
                j = p[j]
                cycle_len += 1
            if cycle_len % 2 == 0:
                sign *= -1
    return sign


# ─────────────────────────────────────────────────────────────
# Subgroup generation
# ─────────────────────────────────────────────────────────────

def generated_subgroup(generators: List[Tuple[int, ...]], n: int) -> FrozenSet[Tuple[int, ...]]:
    """Compute the subgroup generated by a set of permutations.

    Uses BFS to find the closure under composition and inversion.

    Args:
        generators: List of generating permutations.
        n: Degree of the symmetric group.

    Returns:
        The generated subgroup as a frozenset.

    Complexity: O(|⟨gens⟩|² · n) in the worst case.

    Example:
        >>> sorted(generated_subgroup([(1, 0, 2)], 3))
        [(0, 1, 2), (1, 0, 2)]
    """
    e = identity(n)
    subgroup = {e}
    queue = []
    for g in generators:
        if g not in subgroup:
            subgroup.add(g)
            queue.append(g)

    while queue:
        g = queue.pop(0)
        for h in list(subgroup):
            for new in [compose(g, h), compose(h, g), inverse(g)]:
                if new not in subgroup:
                    subgroup.add(new)
                    queue.append(new)
    return frozenset(subgroup)


# ─────────────────────────────────────────────────────────────
# Subgroup lattice computation
# ─────────────────────────────────────────────────────────────

def compute_subgroup_lattice(n: int) -> Set[FrozenSet[Tuple[int, ...]]]:
    """Compute the subgroup lattice of S_n by pair-closure enumeration.

    For each pair (σ, τ) of permutations, compute ⟨σ, τ⟩ and collect
    all distinct subgroups. This is guaranteed to find all subgroups
    because every subgroup of S_n can be generated by at most n-1
    elements (and for the lattice, pairs suffice for most purposes).

    Note: This is not guaranteed to find ALL subgroups for n > 3,
    since some subgroups require more than 2 generators. For a
    complete lattice, one would need to also check closures of
    triples and beyond. However, for the Möbius formula applied
    to generating pairs, only 2-generated subgroups matter.

    Args:
        n: Degree of the symmetric group.

    Returns:
        Set of all discovered subgroups.

    Complexity: O(n!² · |max subgroup| · n) for pair enumeration.
    """
    perms = list(itertools.permutations(range(n)))
    subgroups: Set[FrozenSet[Tuple[int, ...]]] = set()

    # Always include trivial and full group
    subgroups.add(frozenset([identity(n)]))
    subgroups.add(frozenset(perms))

    # Single-generator subgroups
    for p in perms:
        subgroups.add(generated_subgroup([p], n))

    # Two-generator subgroups
    for p in perms:
        for q in perms:
            subgroups.add(generated_subgroup([p, q], n))

    return subgroups


def compute_subgroup_lattice_complete(n: int) -> Set[FrozenSet[Tuple[int, ...]]]:
    """Compute a more complete subgroup lattice using intersection closure.

    After finding pair-generated subgroups, takes pairwise intersections
    to discover subgroups that might not be 2-generated.

    Args:
        n: Degree of the symmetric group.

    Returns:
        More complete set of subgroups.
    """
    subgroups = compute_subgroup_lattice(n)

    # Intersection closure (a few rounds)
    for _ in range(3):
        new_sgs: Set[FrozenSet[Tuple[int, ...]]] = set()
        sg_list = list(subgroups)
        for i in range(len(sg_list)):
            for j in range(i + 1, len(sg_list)):
                inter = sg_list[i] & sg_list[j]
                # Check if intersection is a subgroup
                e = identity(n)
                if e in inter:
                    # Compute closure
                    sg = generated_subgroup(list(inter), n)
                    if sg == inter:
                        new_sgs.add(inter)
        if not (new_sgs - subgroups):
            break
        subgroups |= new_sgs

    return subgroups


# ─────────────────────────────────────────────────────────────
# Möbius function
# ─────────────────────────────────────────────────────────────

def compute_moebius_to_top(
    subgroups: Set[FrozenSet[Tuple[int, ...]]],
    n: int
) -> Dict[FrozenSet[Tuple[int, ...]], int]:
    """Compute μ(H, S_n) for all subgroups H using the recursive definition.

    The Möbius function on the subgroup lattice satisfies:
      μ(G, G) = 1
      μ(H, G) = -Σ_{K: H < K ≤ G} μ(K, G)  for H < G

    This is computed bottom-up (from G downward by size).

    Args:
        subgroups: Set of subgroups of S_n.
        n: Degree.

    Returns:
        Dictionary mapping each subgroup to its Möbius value μ(H, S_n).

    Complexity: O(|Sub|² · n!) for subset checking.
    """
    full = frozenset(itertools.permutations(range(n)))
    sorted_sgs = sorted(subgroups, key=lambda s: -len(s))

    mu: Dict[FrozenSet[Tuple[int, ...]], int] = {}
    mu[full] = 1

    for sg in sorted_sgs:
        if sg == full:
            continue
        mu_val = 0
        for larger in subgroups:
            if sg < larger:  # strict subset
                mu_val -= mu.get(larger, 0)
        mu[sg] = mu_val

    return mu


def moebius_generating_pair_count(
    subgroups: Set[FrozenSet[Tuple[int, ...]]],
    mu: Dict[FrozenSet[Tuple[int, ...]], int]
) -> int:
    """Compute the generating pair count using the Möbius formula.

    f(G) = Σ_{H ≤ G} μ(H, G) · |H|²

    This avoids enumerating all n!² pairs.

    Args:
        subgroups: Set of subgroups.
        mu: Möbius function values.

    Returns:
        Number of generating pairs.

    Complexity: O(|Sub|) after Möbius values are computed.
    """
    return sum(mu.get(sg, 0) * len(sg) ** 2 for sg in subgroups)


# ─────────────────────────────────────────────────────────────
# Brute-force verification
# ─────────────────────────────────────────────────────────────

def brute_force_generating_pairs(n: int) -> int:
    """Count generating pairs by brute force.

    Enumerate all n!² pairs and check if each generates S_n.

    Args:
        n: Degree.

    Returns:
        Number of generating pairs.

    Complexity: O(n!³ · n) — very slow for n ≥ 5.
    """
    perms = list(itertools.permutations(range(n)))
    target = len(perms)
    count = 0
    for p in perms:
        for q in perms:
            if len(generated_subgroup([p, q], n)) == target:
                count += 1
    return count


# ─────────────────────────────────────────────────────────────
# Asymptotic analysis
# ─────────────────────────────────────────────────────────────

def generating_pair_probability(n: int, gen_count: Optional[int] = None) -> Fraction:
    """Compute P_n = #{generating pairs} / n!².

    Args:
        n: Degree.
        gen_count: Pre-computed generating pair count (avoids recomputation).

    Returns:
        Exact probability as a Fraction.
    """
    if gen_count is None:
        gen_count = brute_force_generating_pairs(n)
    return Fraction(gen_count, math.factorial(n) ** 2)


def asymptotic_residuals(n: int, prob: Fraction) -> dict:
    """Compute residuals between exact P_n and asymptotic approximations.

    Returns a dict with:
      'order_0': |P_n - 3/4|       (Dixon limit)
      'order_1': |P_n - (1-1/n)|   (first correction)
      'order_2': |P_n - (1-1/n-1/n²)| (second correction)

    Args:
        n: Degree.
        prob: Exact probability.
    """
    result = {
        'order_0': abs(prob - Fraction(3, 4)),
        'order_1': abs(prob - (1 - Fraction(1, n))),
    }
    if n >= 3:
        result['order_2'] = abs(prob - (1 - Fraction(1, n) - Fraction(1, n**2)))
    return result


# ─────────────────────────────────────────────────────────────
# Main driver
# ─────────────────────────────────────────────────────────────

def full_analysis(n: int) -> dict:
    """Complete analysis of S_n.

    Computes:
      - Brute-force generating pair count
      - Subgroup lattice
      - Möbius function values
      - Möbius formula verification
      - Asymptotic comparisons

    Returns:
        Dictionary with all results.

    Example:
        >>> r = full_analysis(3)
        >>> r['gen_count']
        18
        >>> r['verified']
        True
    """
    gen_count = brute_force_generating_pairs(n)
    subgroups = compute_subgroup_lattice(n)
    mu = compute_moebius_to_top(subgroups, n)
    moebius_count = moebius_generating_pair_count(subgroups, mu)
    prob = generating_pair_probability(n, gen_count)

    return {
        'n': n,
        'group_order': math.factorial(n),
        'gen_count': gen_count,
        'total_pairs': math.factorial(n) ** 2,
        'probability': prob,
        'probability_float': float(prob),
        'num_subgroups': len(subgroups),
        'moebius_count': moebius_count,
        'verified': moebius_count == gen_count,
        'moebius_values': {len(sg): mu.get(sg, 0) for sg in subgroups},
        'residuals': asymptotic_residuals(n, prob)
    }


if __name__ == '__main__':
    print("Subgroup Lattice Möbius Inversion — Algorithm Module")
    print("=" * 50)
    for n in range(2, 5):
        r = full_analysis(n)
        print(f"\nS_{n}: P_{n} = {r['probability']} ≈ {r['probability_float']:.6f}")
        print(f"  Subgroups: {r['num_subgroups']}, Möbius verified: {r['verified']}")
        print(f"  Residuals: {r['residuals']}")
