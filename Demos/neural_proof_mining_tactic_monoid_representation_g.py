def demo_depth_stratification():
    """Demonstrate Theorems 19–25: depth stratification and search bounds."""
    print("=" * 60)
    print("DEMO 4: Depth Stratification & Search Bounds")
    print("=" * 60)

    # Create proof depth assignment
    np.random.seed(123)
    n_goals = 100
    max_depth = 5
    depths = np.random.choice(range(max_depth + 1), size=n_goals,
                               p=[0.05, 0.15, 0.25, 0.30, 0.18, 0.07])

    # Theorem 19: Stratum membership
    strata = defaultdict(list)
    for g in range(n_goals):
        strata[depths[g]].append(g)
    print(f"\nDepth stratification of {n_goals} goals (max depth {max_depth}):")
    for k in range(max_depth + 1):
        print(f"  Level {k}: {len(strata[k])} goals")

    # Theorem 20: Disjointness
    for j in range(max_depth + 1):
        for k in range(j + 1, max_depth + 1):
            overlap = set(strata[j]) & set(strata[k])
            assert len(overlap) == 0, f"Strata {j} and {k} overlap!"
    print(f"\nTheorem 20: All strata are disjoint ✓")

    # Theorem 21: Size bound
    for k in range(max_depth + 1):
        assert len(strata[k]) <= n_goals
    print(f"Theorem 21: All strata have ≤ {n_goals} elements ✓")

    # Theorem 23: Geometric search bound
    print(f"\nTheorem 23 (Geometric Search Bound):")
    for b in [2, 3, 5]:
        for d in [3, 5, 8]:
            geom_sum = sum(b**i for i in range(d + 1))
            upper = b**(d + 1)
            print(f"  b={b}, d={d}: Σb^i = {geom_sum:>10} ≤ b^(d+1) = {upper:>10} → {'✓' if geom_sum <= upper else '✗'}")

    # Theorem 24: Pigeonhole tradeoff
    D = max_depth
    n = n_goals
    min_stratum = min(len(strata[k]) for k in range(D + 1))
    pigeonhole_bound = n // (D + 1)
    print(f"\nTheorem 24 (Pigeonhole Tradeoff):")
    print(f"  n={n}, D+1={D+1}")
    print(f"  Smallest stratum has {min_stratum} goals")
    print(f"  Pigeonhole bound: ⌊n/(D+1)⌋ = {pigeonhole_bound}")
    print(f"  min ≤ bound? {min_stratum <= pigeonhole_bound} ✓")

    print("\n✓ Depth stratification verified!\n")


