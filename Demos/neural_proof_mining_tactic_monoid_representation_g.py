@dataclass
class NeuralProverConfig:
    """Configuration for a Lipschitz-certified neural prover.

    The Lipschitz constant L determines the certified robustness radius:
    adversarial perturbations of norm < δ can only affect goals within
    proof distance δ/L [Theorem 14].
    """
    n_layers: int
    layer_lipschitz: List[float]
    embedding_dim: int

    @property
    def total_lipschitz(self) -> float:
        """Overall Lipschitz constant: product of layer constants [Theorem 17]."""
        result = 1.0
        for L in self.layer_lipschitz:
            result *= L
        return result

    def robustness_radius(self, perturbation_norm: float) -> float:
        """Certified robustness radius [Theorem 14].

        Args:
            perturbation_norm: Maximum adversarial perturbation δ

        Returns:
            Minimum proof distance that can be affected: δ / ∏Lᵢ
        """
        L = self.total_lipschitz
        return perturbation_norm / L if L > 0 else float('inf')

    def robustness_report(self, perturbation_budget: float = 1.0) -> Dict:
        """Generate a certified robustness report.

        Returns:
            Dictionary with robustness metrics
        """
        L = self.total_lipschitz
        radius = self.robustness_radius(perturbation_budget)
        return {
            "n_layers": self.n_layers,
            "per_layer_lipschitz": self.layer_lipschitz,
            "total_lipschitz": L,
            "perturbation_budget": perturbation_budget,
            "certified_robustness_radius": radius,
            "embedding_dimension": self.embedding_dim,
            "robustness_class": (
                "STRONG" if radius > 5.0 else
                "MODERATE" if radius > 1.0 else
                "WEAK" if radius > 0.1 else
                "FRAGILE"
            )
        }


