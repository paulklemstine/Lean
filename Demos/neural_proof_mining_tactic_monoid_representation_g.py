class TacticShape:
    """A tactic shape with an identifier and arity."""
    def __init__(self, id: int, arity: int):
        self.id = id
        self.arity = arity

    def __repr__(self):
        return f"T({self.id}, arity={self.arity})"

    def __eq__(self, other):
        return self.id == other.id and self.arity == other.arity

    def __hash__(self):
        return hash((self.id, self.arity))


class TacticTrace:
    """A tactic trace: sequence of tactic shapes forming a monoid element."""
    def __init__(self, steps=None):
        self.steps = list(steps) if steps else []

    @property
    def depth(self):
        return len(self.steps)

    @property
    def total_arity(self):
        return sum(s.arity for s in self.steps)

    def __mul__(self, other):
        return TacticTrace(self.steps + other.steps)

    def __pow__(self, n):
        result = TacticTrace()
        for _ in range(n):
            result = result * self
        return result

    def __repr__(self):
        if not self.steps:
            return "ε"
        return " · ".join(str(s) for s in self.steps)

    def __eq__(self, other):
        return self.steps == other.steps

    def __hash__(self):
        return hash(tuple(self.steps))


def identity():
    """The identity element of the tactic trace monoid."""
    return TacticTrace()


