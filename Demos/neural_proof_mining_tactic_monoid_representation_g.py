@dataclass(frozen=True)
class TacticShape:
    """A tactic shape with identifier and arity.

    Attributes:
        id: Unique identifier for the tactic type
        arity: Number of subgoals generated by this tactic
    """
    id: int
    arity: int


@dataclass
class TacticTrace:
    """A tactic trace: element of the free monoid on TacticShape.

    Supports monoid operations (composition via concatenation).

    Attributes:
        steps: Ordered sequence of tactic shapes
    """
    steps: Tuple[TacticShape, ...] = ()

    @property
    def depth(self) -> int:
        """Depth of the trace (number of tactic applications).

        Satisfies depth(t1 * t2) = depth(t1) + depth(t2) [Theorem 2].
        """
        return len(self.steps)

    @property
    def total_arity(self) -> int:
        """Total arity: sum of arities of all shapes.

        Satisfies totalArity(t1 * t2) = totalArity(t1) + totalArity(t2) [Theorem 4].
        Bounded by depth * max_arity [Theorem 5].
        """
        return sum(s.arity for s in self.steps)

    def compose(self, other: 'TacticTrace') -> 'TacticTrace':
        """Monoid multiplication: sequential composition of traces."""
        return TacticTrace(self.steps + other.steps)

    def power(self, n: int) -> 'TacticTrace':
        """Monoid powering: t^n has depth n * depth(t) [Theorem 3]."""
        result = TacticTrace()
        for _ in range(n):
            result = result.compose(self)
        return result

    def factorize(self) -> List['TacticTrace']:
        """Factor into unit-depth traces [Theorem 25].

        Returns:
            List of d unit-depth traces where d = self.depth
        """
        return [TacticTrace((s,)) for s in self.steps]

    def __hash__(self):
        return hash(self.steps)

    def __eq__(self, other):
        return self.steps == other.steps


def construct_tactic_monoid(
    tactics: List[TacticShape],
    max_depth: int
) -> List[TacticTrace]:
    """Construct all tactic traces up to a given depth.

    Algorithm from Section 4.1 of the paper.

    Args:
        tactics: Set of available tactic shapes
        max_depth: Maximum trace depth to enumerate

    Returns:
        List of all traces of depth ≤ max_depth

    Complexity:
        O(|tactics|^max_depth) time and space

    >>> tactics = [TacticShape(0, 1), TacticShape(1, 2)]
    >>> traces = construct_tactic_monoid(tactics, 2)
    >>> len(traces)  # 1 + 2 + 4 = 7
    7
    """
    traces = [TacticTrace()]  # identity element

    current_level = [TacticTrace()]
    for d in range(max_depth):
        next_level = []
        for trace in current_level:
            for tactic in tactics:
                new_trace = trace.compose(TacticTrace((tactic,)))
                next_level.append(new_trace)
        traces.extend(next_level)
        current_level = next_level

    return traces


def compute_regular_representation(
    elements: List[TacticTrace],
    element_to_idx: Dict[TacticTrace, int]
) -> Dict[TacticTrace, np.ndarray]:
    """Compute the left regular representation of a finite monoid.

    For each element m, ρ(m) is the matrix where ρ(m)_{i,j} = 1
    if m * elements[j] = elements[i], else 0.

    Faithfulness is guaranteed by Cayley's theorem [Theorem 6].

    Args:
        elements: List of monoid elements
        element_to_idx: Mapping from elements to indices

    Returns:
        Dictionary mapping each element to its representation matrix

    Complexity:
        O(|M|^2) per element, O(|M|^3) total
    """
    n = len(elements)
    representations = {}

    for m in elements:
        mat = np.zeros((n, n), dtype=int)
        for j, ej in enumerate(elements):
            product = m.compose(ej)
            if product in element_to_idx:
                i = element_to_idx[product]
                mat[i, j] = 1
        representations[m] = mat

    return representations


def verify_faithfulness(
    representations: Dict[TacticTrace, np.ndarray]
) -> Tuple[bool, Optional[Tuple[TacticTrace, TacticTrace]]]:
    """Verify that a representation is faithful [Theorem 6].

    A faithful representation maps distinct elements to distinct matrices.

    Args:
        representations: Dictionary of representation matrices

    Returns:
        (True, None) if faithful, (False, (a, b)) if a ≠ b but ρ(a) = ρ(b)

    Complexity:
        O(|M|^2 · n^2) where n is the matrix dimension
    """
    elements = list(representations.keys())
    for i, a in enumerate(elements):
        for j in range(i + 1, len(elements)):
            b = elements[j]
            if np.array_equal(representations[a], representations[b]):
                return False, (a, b)
    return True, None


def lipschitz_goal_embedding(
    proof_distances: np.ndarray,
    lipschitz_const: float = 1.0
) -> Tuple[np.ndarray, float]:
    """Construct a Lipschitz goal embedding from proof distances.

    Algorithm from Section 4.2 of the paper.

    Uses the distance profile embedding: φ(g) = L * d(g, ·).
    This satisfies ‖φ(g₁) - φ(g₂)‖ ≤ L · d(g₁, g₂) [Theorem 13].

    Args:
        proof_distances: n×n matrix of pairwise proof distances
        lipschitz_const: Desired Lipschitz constant L

    Returns:
        Tuple of (embedding matrix n×n, verified Lipschitz constant)

    Complexity:
        O(n^2) for embedding, O(n^3) for verification
    """
    n = proof_distances.shape[0]
    embedding = lipschitz_const * proof_distances

    # Verify Lipschitz condition
    max_ratio = 0.0
    for i in range(n):
        for j in range(i + 1, n):
            embed_dist = np.linalg.norm(embedding[i] - embedding[j])
            proof_dist = proof_distances[i, j]
            if proof_dist > 1e-10:
                ratio = embed_dist / (lipschitz_const * proof_dist)
                max_ratio = max(max_ratio, ratio)

    return embedding, max_ratio


def certified_robustness_radius(
    lipschitz_const: float,
    perturbation_norm: float
) -> float:
    """Compute the certified robustness radius [Theorem 14].

    If ‖perturbation‖ < δ and the embedding has Lipschitz constant L,
    then only goals within proof distance δ/L can be affected.

    Args:
        lipschitz_const: Lipschitz constant L of the embedding
        perturbation_norm: Norm of the adversarial perturbation δ

    Returns:
        Certified robustness radius δ/L

    >>> certified_robustness_radius(2.0, 1.0)
    0.5
    """
    if lipschitz_const <= 0:
        return float('inf')
    return perturbation_norm / lipschitz_const


def depth_stratification(
    depths: np.ndarray
) -> Dict[int, List[int]]:
    """Compute the depth stratification of a goal set [Theorems 19-21].

    Partitions goals into disjoint strata by proof depth.

    Args:
        depths: Array of proof depths for each goal

    Returns:
        Dictionary mapping depth level k to list of goal indices in S_k

    Complexity:
        O(n) time and space
    """
    strata = defaultdict(list)
    for g, d in enumerate(depths):
        strata[int(d)].append(g)
    return dict(strata)


def verify_pigeonhole_tradeoff(
    strata: Dict[int, List[int]],
    n_goals: int
) -> Tuple[int, int, bool]:
    """Verify the depth-complexity tradeoff [Theorem 24].

    For n goals across D+1 depth levels, some level has ≤ ⌊n/(D+1)⌋ goals.

    Args:
        strata: Depth stratification
        n_goals: Total number of goals

    Returns:
        Tuple of (min_stratum_size, pigeonhole_bound, satisfied)
    """
    if not strata:
        return 0, 0, True

    n_levels = max(strata.keys()) + 1
    min_size = min(len(goals) for goals in strata.values())
    bound = n_goals // n_levels

    return min_size, bound, min_size <= bound


def geometric_search_bound(b: int, d: int) -> Tuple[int, int]:
    """Compute the geometric search bound [Theorem 23].

    For branching factor b ≥ 2 and depth d, the total number of
    traces of depth ≤ d is at most b^(d+1).

    Args:
        b: Branching factor (number of tactics)
        d: Maximum search depth

    Returns:
        Tuple of (actual geometric sum, upper bound b^(d+1))

    >>> geometric_search_bound(2, 3)
    (15, 16)
    """
    geom_sum = sum(b**i for i in range(d + 1))
    upper_bound = b**(d + 1)
    return geom_sum, upper_bound


def proof_search_bfs(
    start_goal: int,
    target_goal: int,
    adjacency: np.ndarray
) -> Optional[List[int]]:
    """Breadth-first proof search in the goal graph.

    Finds the shortest proof (minimum-depth tactic trace)
    from start_goal to target_goal.

    Args:
        start_goal: Starting goal index
        target_goal: Target goal index
        adjacency: n×n adjacency matrix of the goal graph

    Returns:
        List of goal indices forming the shortest path, or None

    Complexity:
        O(|V| + |E|) = O(n^2) in the worst case
    """
    n = adjacency.shape[0]
    visited = set()
    queue = [(start_goal, [start_goal])]
    visited.add(start_goal)

    while queue:
        current, path = queue.pop(0)
        if current == target_goal:
            return path

        for neighbor in range(n):
            if adjacency[current, neighbor] and neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, path + [neighbor]))

    return None


