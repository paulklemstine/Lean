# Section 3: Resolvent Certificate Generation
# =============================================================================

class ResolventCertificate:
    """
    A certificate packaging arithmetic evidence for Galois group identification.
    
    Corresponds to the formal ResolventCertificate structure in our Lean development.
    
    Attributes:
        polynomial: The polynomial coefficients
        prime_irred: Prime where f is irreducible mod p (5-cycle evidence)
        prime_trans: Prime where f factors as (2,1,1,1) mod p (transposition evidence)
        discriminant: The discriminant of f
        disc_is_square: Whether the discriminant is a perfect square
    """
    
    def __init__(self, coeffs: List[int]):
        self.coeffs = coeffs
        self.degree = len(coeffs) - 1
        self.prime_irred: Optional[int] = None
        self.prime_trans: Optional[int] = None
        self.pattern_irred: Optional[List[int]] = None
        self.pattern_trans: Optional[List[int]] = None
        self.discriminant: Optional[int] = None
        self.disc_is_square: Optional[bool] = None
        self.all_patterns: Dict[int, List[int]] = {}
    
    def compute(self, max_prime: int = 200) -> 'ResolventCertificate':
        """
        Compute the resolvent certificate by analyzing modular factorizations.
        
        Searches through primes up to max_prime to find Frobenius evidence.
        
        Complexity: O(π(max_prime) · n² · log(p)) where π is the prime counting function
        """
        # Compute discriminant
        poly = Poly(sum(c * x**(self.degree - i) for i, c in enumerate(self.coeffs)),
                   x, domain=ZZ)
        self.discriminant = int(poly.discriminant())
        r = int(abs(self.discriminant) ** 0.5)
        self.disc_is_square = any((r + d) ** 2 == abs(self.discriminant) for d in [-1, 0, 1])
        
        primes = [p for p in range(2, max_prime) if sympy.isprime(p)]
        
        for p in primes:
            if self.coeffs[0] % p == 0:
                continue
            
            try:
                fp = Poly(sum(c * x**(self.degree - i)
                             for i, c in enumerate(self.coeffs)), x, domain=GF(p))
                if fp.degree() < self.degree:
                    continue
                
                factors = fp.factor_list()[1]
                pattern = sorted([f[0].degree() * f[1] for f in factors])
                
                if sum(pattern) != self.degree:
                    continue
                
                self.all_patterns[p] = pattern
                
                if pattern == [self.degree] and self.prime_irred is None:
                    self.prime_irred = p
                    self.pattern_irred = pattern
                
                if self.degree == 5 and sorted(pattern) == [1, 1, 1, 2]:
                    if self.prime_trans is None:
                        self.prime_trans = p
                        self.pattern_trans = pattern
            except Exception:
                continue
        
        return self
    
    def is_complete(self) -> bool:
        """Check if the certificate has enough evidence for S₅ identification."""
        return (self.prime_irred is not None and
                self.prime_trans is not None and
                self.degree == 5)
    
    def verdict(self) -> str:
        """Return a human-readable verdict."""
        if not self.is_complete():
            return "INCOMPLETE: Insufficient modular evidence"
        return "CERTIFIED: Galois group is S₅ — polynomial NOT solvable by radicals"
    
    def __repr__(self) -> str:
        lines = [
            f"ResolventCertificate(degree={self.degree})",
            f"  Discriminant: {self.discriminant}",
            f"  Disc is square: {self.disc_is_square}",
            f"  5-cycle prime: {self.prime_irred} (pattern: {self.pattern_irred})",
            f"  Transposition prime: {self.prime_trans} (pattern: {self.pattern_trans})",
            f"  Verdict: {self.verdict()}",
        ]
        return "\n".join(lines)


