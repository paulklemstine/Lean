# Section 2: Derived Series Computation
# =============================================================================

def generate_group(generators: List[Tuple[int, ...]], n: int) -> Set[Tuple[int, ...]]:
    """
    Generate a permutation group from generators using BFS.
    
    Args:
        generators: List of generating permutations
        n: Degree of the symmetric group
        
    Returns:
        Set of all group elements
    
    Complexity: O(|G|² · n) where |G| is the group order
    """
    identity = tuple(range(n))
    group = {identity}
    queue = list(generators)
    
    while queue:
        g = queue.pop(0)
        if g in group:
            continue
        # Add products with all existing elements
        new_elements = set()
        for h in group:
            for prod in [compose_perms(g, h), compose_perms(h, g),
                        compose_perms(invert_perm(g), h)]:
                if prod not in group:
                    new_elements.add(prod)
        group.add(g)
        group.update(new_elements)
        queue.extend(new_elements)
    
    # Close under multiplication
    changed = True
    while changed:
        changed = False
        new = set()
        for g in group:
            for h in group:
                p = compose_perms(g, h)
                if p not in group:
                    new.add(p)
                    changed = True
        group.update(new)
    
    return group


def commutator_subgroup(group: Set[Tuple[int, ...]], n: int) -> Set[Tuple[int, ...]]:
    """
    Compute the commutator (derived) subgroup [G, G].
    
    The commutator subgroup is generated by all elements [a,b] = a⁻¹b⁻¹ab
    where a, b ∈ G. This is the first step in computing the derived series.
    
    Complexity: O(|G|³ · n)
    """
    commutators = []
    for a in group:
        for b in group:
            c = commutator(a, b)
            commutators.append(c)
    
    return generate_group(commutators, n)


def derived_series(group: Set[Tuple[int, ...]], n: int, max_depth: int = 20) -> List[Set[Tuple[int, ...]]]:
    """
    Compute the derived series G ⊃ G' ⊃ G'' ⊃ ...
    
    The derived series is defined by:
    - G⁽⁰⁾ = G
    - G⁽ⁿ⁺¹⁾ = [G⁽ⁿ⁾, G⁽ⁿ⁾]
    
    A group is solvable if and only if the derived series reaches {e}
    in finitely many steps.
    
    Args:
        group: The permutation group
        n: Degree of the symmetric group
        max_depth: Maximum number of derived subgroups to compute
        
    Returns:
        List of subgroups in the derived series
        
    Complexity: O(d · |G|³ · n) where d is the derived length
    """
    series = [group]
    current = group
    
    for i in range(max_depth):
        next_group = commutator_subgroup(current, n)
        series.append(next_group)
        
        if len(next_group) == 1:  # Reached {e}
            break
        if len(next_group) == len(current):  # Stabilized (not solvable)
            break
        current = next_group
    
    return series


def is_solvable(group: Set[Tuple[int, ...]], n: int) -> Tuple[bool, List[int]]:
    """
    Determine if a permutation group is solvable by computing its derived series.
    
    Returns:
        (is_solvable, series_orders) where series_orders is the list of orders
        of successive derived subgroups.
        
    This implements the RadicalSolvable predicate from our formal development.
    """
    series = derived_series(group, n)
    orders = [len(g) for g in series]
    
    # Solvable iff last group is trivial
    solvable = len(series[-1]) == 1
    return solvable, orders


