def demonstrate_derived_series():
    """
    Demonstrate the derived series computation on S₃, S₄, and S₅.
    
    S₃ is solvable: S₃ ⊃ A₃ ⊃ {e}
    S₄ is solvable: S₄ ⊃ A₄ ⊃ V₄ ⊃ {e}
    S₅ is NOT solvable: S₅ ⊃ A₅ = A₅ = ...
    """
    print("\n" + "="*60)
    print("  Derived Series of Symmetric Groups")
    print("="*60)
    
    for n in [3, 4, 5]:
        print(f"\n  S_{n} (order {__import__('math').factorial(n)}):")
        
        # Generate S_n
        identity = tuple(range(n))
        all_perms = set(permutations(range(n)))
        
        solvable, orders = is_solvable(all_perms, n)
        
        for i, order in enumerate(orders):
            marker = " = {e} ✓" if order == 1 else ""
            if i > 0 and order == orders[i-1] and order > 1:
                marker = " (stabilized — NOT solvable ✗)"
                print(f"    G⁽{i}⁾ has order {order}{marker}")
                break
            print(f"    G⁽{i}⁾ has order {order}{marker}")
        
        status = "SOLVABLE ✓" if solvable else "NOT SOLVABLE ✗"
        print(f"    → {status}")
        if solvable:
            print(f"    → RadicalSolvable certificate: depth = {len(orders) - 1}")


