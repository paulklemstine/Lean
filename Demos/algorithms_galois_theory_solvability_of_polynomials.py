# Section 1: Permutation Group Arithmetic
# =============================================================================

def compose_perms(p: Tuple[int, ...], q: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compose two permutations: (p ∘ q)(i) = p(q(i))."""
    return tuple(p[q[i]] for i in range(len(p)))


def invert_perm(p: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compute the inverse of a permutation."""
    inv = [0] * len(p)
    for i, v in enumerate(p):
        inv[v] = i
    return tuple(inv)


def commutator(a: Tuple[int, ...], b: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compute the group commutator [a, b] = a⁻¹ b⁻¹ a b."""
    a_inv = invert_perm(a)
    b_inv = invert_perm(b)
    return compose_perms(compose_perms(a_inv, b_inv), compose_perms(a, b))


def cycle_type(p: Tuple[int, ...]) -> Tuple[int, ...]:
    """
    Compute the cycle type of a permutation.
    Returns a sorted tuple of cycle lengths (descending).
    """
    n = len(p)
    visited = [False] * n
    cycles = []
    for i in range(n):
        if not visited[i]:
            length = 0
            j = i
            while not visited[j]:
                visited[j] = True
                j = p[j]
                length += 1
            cycles.append(length)
    return tuple(sorted(cycles, reverse=True))


def perm_order(p: Tuple[int, ...]) -> int:
    """Compute the order of a permutation."""
    ct = cycle_type(p)
    from math import gcd
    lcm = ct[0]
    for c in ct[1:]:
        lcm = lcm * c // gcd(lcm, c)
    return lcm


