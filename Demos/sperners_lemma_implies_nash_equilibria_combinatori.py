"""
Sperner's Lemma => Brouwer => Nash : numerical demonstrations.

This self-contained script illustrates the chain of results developed in the
accompanying paper:

    1.  Sperner's lemma on a triangulated 2-simplex: any *proper* 3-coloring of
        a subdivided triangle contains an odd (hence nonzero) number of fully
        colored ("rainbow") cells.

    2.  The descent coloring: for a continuous self-map f of the standard
        n-simplex, every vertex carries a "descent coordinate" i with v_i > 0
        and f(v)_i <= v_i.  Coloring lattice vertices by a descent coordinate
        yields a proper Sperner coloring, and the rainbow cell localizes a
        fixed point of f (Theorem `sperner_implies_brouwer`).

    3.  Nash equilibria as fixed points: Nash's best-response improvement map on
        the product of strategy simplices is a continuous self-map; its fixed
        points are exactly the mixed Nash equilibria.  We recover the mixed
        equilibrium of Matching Pennies, a game with no pure equilibrium.

Everything is implemented from scratch with only the standard library.
"""

from __future__ import annotations

from itertools import product
from typing import Callable, Dict, List, Tuple

Vector = Tuple[float, ...]
Lattice = Tuple[int, ...]


# ----------------------------------------------------------------------------
# 1.  Sperner's lemma on a subdivided triangle (n = 2)
# ----------------------------------------------------------------------------

def lattice_points(n: int, m: int) -> List[Lattice]:
    """All lattice points k in N^{n+1} with sum(k) = m (vertices of the
    m-th subdivision of the standard n-simplex)."""
    out: List[Lattice] = []
    for combo in product(range(m + 1), repeat=n + 1):
        if sum(combo) == m:
            out.append(combo)
    return out


def upward_cells_2d(m: int) -> List[Tuple[Lattice, Lattice, Lattice]]:
    """The 'upward' small triangles of the standard subdivision of the
    2-simplex at level m.  A cell is generated by adding +1 to one coordinate
    and -1 to another, starting from an interior anchor."""
    cells: List[Tuple[Lattice, Lattice, Lattice]] = []
    for a in range(m + 1):
        for b in range(m + 1 - a):
            c = m - a - b
            if c >= 1 and a >= 0 and b >= 0:
                # anchor (a, b, c); the standard 'up' triangle:
                v0 = (a + 1, b, c - 1)
                v1 = (a, b + 1, c - 1)
                v2 = (a, b, c)
                if min(v0) >= 0 and min(v1) >= 0 and min(v2) >= 0:
                    cells.append((v0, v1, v2))
    return cells


def is_proper_coloring(coloring: Dict[Lattice, int]) -> bool:
    """A coloring L is proper iff k[L(k)] != 0 for every lattice point k."""
    return all(k[c] != 0 for k, c in coloring.items())


def count_rainbow_cells(
    cells: List[Tuple[Lattice, ...]], coloring: Dict[Lattice, int], n: int
) -> int:
    """Number of cells whose vertex colors cover all n+1 colors."""
    target = set(range(n + 1))
    count = 0
    for cell in cells:
        if {coloring[v] for v in cell} == target:
            count += 1
    return count


def demo_sperner(m: int = 6) -> None:
    """Verify Sperner's lemma: a proper coloring of the level-m 2-simplex has
    an odd number of rainbow triangles."""
    print("=" * 70)
    print(f"1.  SPERNER'S LEMMA on the 2-simplex, subdivision level m = {m}")
    print("=" * 70)
    pts = lattice_points(2, m)
    cells = upward_cells_2d(m)

    # Build a proper coloring: color k by the *largest* coordinate index that
    # is nonzero (a deterministic but nontrivial proper rule).
    coloring: Dict[Lattice, int] = {}
    for k in pts:
        coloring[k] = max(i for i in range(3) if k[i] != 0)

    assert is_proper_coloring(coloring), "coloring must be proper"
    rainbow = count_rainbow_cells(cells, coloring, 2)
    print(f"  lattice vertices : {len(pts)}")
    print(f"  upward cells     : {len(cells)}")
    print(f"  rainbow cells    : {rainbow}  (Sperner guarantees odd >= 1)")
    print(f"  parity check     : {'ODD (OK)' if rainbow % 2 == 1 else 'EVEN (?)'}")
    print()


# ----------------------------------------------------------------------------
# 2.  Descent coloring and Brouwer fixed points on the n-simplex
# ----------------------------------------------------------------------------

def lattice_vertex(m: int, k: Lattice) -> Vector:
    """latticeVertex(m, k) = (k_0/m, ..., k_n/m)."""
    return tuple(ki / m for ki in k)


def descent_coordinate(f: Callable[[Vector], Vector], v: Vector) -> int:
    """A descent coordinate i: v_i > 0 and f(v)_i <= v_i (Lemma label_exists).
    Guaranteed to exist for any self-map of the simplex."""
    fv = f(v)
    for i, vi in enumerate(v):
        if vi > 1e-15 and fv[i] <= vi + 1e-12:
            return i
    # Fallback (should not happen for a genuine self-map): largest coordinate.
    return max(range(len(v)), key=lambda i: v[i])


def approximate_fixed_point(
    f: Callable[[Vector], Vector], n: int, m: int
) -> Tuple[Vector, float]:
    """Scan the level-m subdivision, color each vertex by a descent coordinate,
    and return the barycenter of a rainbow cell as an approximate fixed point.
    Returns (point, residual) where residual = max_i |f(x)_i - x_i|."""
    pts = lattice_points(n, m)
    coloring = {k: descent_coordinate(f, lattice_vertex(m, k)) for k in pts}

    best_pt: Vector = lattice_vertex(m, pts[0])
    best_res = float("inf")
    # For n == 2 use genuine cells; otherwise fall back to per-vertex residual.
    cells = upward_cells_2d(m) if n == 2 else [(k,) for k in pts]
    target = set(range(n + 1))
    for cell in cells:
        colors = {coloring[v] for v in cell}
        if n == 2 and colors != target:
            continue
        center = tuple(
            sum(lattice_vertex(m, v)[i] for v in cell) / len(cell)
            for i in range(n + 1)
        )
        fc = f(center)
        res = max(abs(fc[i] - center[i]) for i in range(n + 1))
        if res < best_res:
            best_res, best_pt = res, center
    return best_pt, best_res


def demo_brouwer() -> None:
    """Find a fixed point of an explicit continuous self-map of the 2-simplex
    by refining the subdivision (descent coloring + rainbow cell)."""
    print("=" * 70)
    print("2.  BROUWER FIXED POINT via descent coloring (2-simplex)")
    print("=" * 70)

    def normalize(w: Vector) -> Vector:
        s = sum(w)
        return tuple(wi / s for wi in w)

    # A continuous self-map: pull each point toward the fixed target (1/2,1/3,1/6)
    target = (1 / 2, 1 / 3, 1 / 6)

    def f(v: Vector) -> Vector:
        # weighted average toward target, then renormalize onto the simplex
        w = tuple(0.5 * v[i] + 0.5 * target[i] for i in range(3))
        return normalize(w)

    print(f"  map f has unique fixed point at {tuple(round(t, 4) for t in target)}")
    for m in (8, 16, 32, 64):
        x, res = approximate_fixed_point(f, 2, m)
        print(
            f"  m = {m:3d}:  x ~ {tuple(round(xi, 4) for xi in x)}"
            f"   residual |f(x)-x|_inf = {res:.5f}"
        )
    print()


# ----------------------------------------------------------------------------
# 3.  Nash equilibria as fixed points of the best-response improvement map
# ----------------------------------------------------------------------------

Strategy = Tuple[float, float]   # mixed strategy over 2 pure actions
Profile = Tuple[Strategy, Strategy]


def expected_payoffs(
    A: List[List[float]], B: List[List[float]], p: Strategy, q: Strategy
) -> Tuple[float, float]:
    """Expected payoffs (u1, u2) for the 2x2 bimatrix game (A, B)."""
    u1 = sum(A[i][j] * p[i] * q[j] for i in range(2) for j in range(2))
    u2 = sum(B[i][j] * p[i] * q[j] for i in range(2) for j in range(2))
    return u1, u2


def nash_improvement_step(
    A: List[List[float]], B: List[List[float]], profile: Profile
) -> Profile:
    """One step of Nash's continuous improvement map g.  Fixed points of g are
    exactly the mixed Nash equilibria (Theorem: Nash existence via Brouwer)."""
    p, q = profile
    u1, u2 = expected_payoffs(A, B, p, q)

    # Player 1: gain of pure action i = max(0, payoff(i vs q) - u1)
    gain1 = [max(0.0, sum(A[i][j] * q[j] for j in range(2)) - u1) for i in range(2)]
    gain2 = [max(0.0, sum(B[i][j] * p[i] for i in range(2)) - u2) for j in range(2)]

    new_p = tuple((p[i] + gain1[i]) / (1 + sum(gain1)) for i in range(2))
    new_q = tuple((q[j] + gain2[j]) / (1 + sum(gain2)) for j in range(2))
    return (new_p, new_q)  # type: ignore[return-value]


def find_nash(
    A: List[List[float]],
    B: List[List[float]],
    grid: int = 200,
) -> Profile:
    """Locate a mixed Nash equilibrium of a 2x2 game by minimizing the maximum
    unilateral regret over a fine grid of the strategy square -- the
    simplicial/Sperner search in spirit.  At a true equilibrium the regret
    of the improvement map vanishes, so the minimizer is an (approximate) NE.
    """
    best_profile: Profile = ((1.0, 0.0), (1.0, 0.0))
    best_regret = float("inf")
    for a in range(grid + 1):
        p: Strategy = (a / grid, 1 - a / grid)
        for b in range(grid + 1):
            q: Strategy = (b / grid, 1 - b / grid)
            r = max_regret(A, B, (p, q))
            if r < best_regret:
                best_regret, best_profile = r, (p, q)
    return best_profile


def max_regret(A: List[List[float]], B: List[List[float]], profile: Profile) -> float:
    """Largest unilateral improvement available to any player (0 at a true NE)."""
    p, q = profile
    u1, u2 = expected_payoffs(A, B, p, q)
    r1 = max(sum(A[i][j] * q[j] for j in range(2)) - u1 for i in range(2))
    r2 = max(sum(B[i][j] * p[i] for i in range(2)) - u2 for j in range(2))
    return max(r1, r2)


def demo_nash() -> None:
    """Compute mixed Nash equilibria of two 2x2 games as fixed points."""
    print("=" * 70)
    print("3.  NASH EQUILIBRIA as fixed points of the improvement map")
    print("=" * 70)

    # Matching Pennies: zero-sum, NO pure equilibrium.
    #   player 1 wins (+1) on a match, player 2 wins on a mismatch.
    A_mp = [[1.0, -1.0], [-1.0, 1.0]]
    B_mp = [[-1.0, 1.0], [1.0, -1.0]]
    ne = find_nash(A_mp, B_mp)
    print("  Matching Pennies (no pure equilibrium):")
    print(f"    mixed NE  p = {tuple(round(x, 4) for x in ne[0])},"
          f"  q = {tuple(round(x, 4) for x in ne[1])}")
    print(f"    (theory:  (0.5, 0.5), (0.5, 0.5))")
    print(f"    max regret = {max_regret(A_mp, B_mp, ne):.2e}  (0 at equilibrium)")
    print()

    # Coordination game: pure equilibria exist; the map converges to one.
    A_co = [[2.0, 0.0], [0.0, 1.0]]
    B_co = [[2.0, 0.0], [0.0, 1.0]]
    ne2 = find_nash(A_co, B_co)
    print("  Coordination game:")
    print(f"    NE  p = {tuple(round(x, 4) for x in ne2[0])},"
          f"  q = {tuple(round(x, 4) for x in ne2[1])}")
    print(f"    max regret = {max_regret(A_co, B_co, ne2):.2e}")
    print()


# ----------------------------------------------------------------------------

def main() -> None:
    demo_sperner(m=6)
    demo_brouwer()
    demo_nash()
    print("All demonstrations complete:  Sperner => Brouwer => Nash.")


if __name__ == "__main__":
    main()


"""
Visualization: a Sperner-colored subdivision of the 2-simplex, with the
guaranteed rainbow (fully colored) triangle highlighted.

The triangle is the standard 2-simplex with corners colored 0 (red), 1 (green),
2 (blue).  Interior lattice vertices are colored by a proper rule; Sperner's
lemma guarantees at least one small triangle whose three corners show all three
colors.  That cell is outlined in black.

Run:  python visualize_sperner.py   (writes sperner_simplex.png)
"""

from __future__ import annotations

from itertools import product
from typing import Dict, List, Tuple

import matplotlib.pyplot as plt

Lattice = Tuple[int, int, int]
COLORS = ["#e6194B", "#3cb44b", "#4363d8"]  # red, green, blue


def lattice_points(m: int) -> List[Lattice]:
    return [(a, b, m - a - b) for a in range(m + 1) for b in range(m + 1 - a)]


def bary_to_xy(k: Lattice, m: int) -> Tuple[float, float]:
    """Map barycentric (k0,k1,k2)/m to 2D plane coordinates."""
    corners = [(0.0, 0.0), (1.0, 0.0), (0.5, 0.866)]
    x = sum(corners[i][0] * k[i] / m for i in range(3))
    y = sum(corners[i][1] * k[i] / m for i in range(3))
    return x, y


def upward_cells(m: int) -> List[Tuple[Lattice, Lattice, Lattice]]:
    cells = []
    for a in range(m + 1):
        for b in range(m + 1 - a):
            c = m - a - b
            if c >= 1:
                cells.append(((a + 1, b, c - 1), (a, b + 1, c - 1), (a, b, c)))
    return cells


def main(m: int = 8) -> None:
    pts = lattice_points(m)
    coloring: Dict[Lattice, int] = {
        k: max(i for i in range(3) if k[i] != 0) for k in pts
    }
    cells = upward_cells(m)
    rainbow = [c for c in cells if {coloring[v] for v in c} == {0, 1, 2}]

    fig, ax = plt.subplots(figsize=(7, 6.5))
    # draw subdivision edges faintly
    for cell in cells:
        xy = [bary_to_xy(v, m) for v in cell] + [bary_to_xy(cell[0], m)]
        ax.plot([p[0] for p in xy], [p[1] for p in xy], color="0.85", lw=0.6, zorder=1)
    # draw colored vertices
    for k in pts:
        x, y = bary_to_xy(k, m)
        ax.scatter([x], [y], color=COLORS[coloring[k]], s=70, zorder=3,
                   edgecolors="k", linewidths=0.4)
    # highlight rainbow cells
    for cell in rainbow:
        xy = [bary_to_xy(v, m) for v in cell] + [bary_to_xy(cell[0], m)]
        ax.plot([p[0] for p in xy], [p[1] for p in xy], color="k", lw=2.5, zorder=4)
        cx = sum(bary_to_xy(v, m)[0] for v in cell) / 3
        cy = sum(bary_to_xy(v, m)[1] for v in cell) / 3
        ax.annotate("rainbow", (cx, cy), fontsize=9, ha="center",
                    fontweight="bold", zorder=5)

    ax.set_title(f"Sperner coloring of the 2-simplex (m={m}): "
                 f"{len(rainbow)} rainbow cell(s)")
    ax.set_aspect("equal")
    ax.axis("off")
    fig.tight_layout()
    fig.savefig("sperner_simplex.png", dpi=150)
    print("wrote sperner_simplex.png")


if __name__ == "__main__":
    main()
