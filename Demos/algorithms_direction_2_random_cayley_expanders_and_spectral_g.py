if __name__ == '__main__':
    n = 5
    print(f"Algorithms demo for S_{n}")
    print(f"|S_{n}| = {factorial(n)}")

    # Standard generators
    tau = tuple((i + 1) % n for i in range(n))  # long cycle
    sigma = list(range(n)); sigma[0], sigma[1] = sigma[1], sigma[0]
    sigma = tuple(sigma)  # swap (0 1)

    print(f"\nGenerators: σ={sigma}, τ={tau}")
    print(f"Generates S_{n}: {generates_symmetric_group(sigma, tau)}")

    # Build Cayley graph
    A, elems, idx = cayley_adjacency_matrix([sigma, tau], n)
    print(f"\nAdjacency matrix shape: {A.shape}")

    # Spectrum
    eigs = compute_spectrum(A)
    gap = spectral_gap(A)
    print(f"Spectral gap: {gap:.6f}")
    print(f"Top 10 eigenvalues: {eigs[:10].round(4)}")

    # Alon-Boppana
    ab = alon_boppana_bound(4)
    print(f"Alon-Boppana gap bound: {ab:.6f}")

    # Dirichlet energy
    f = np.random.randn(len(elems))
    E = dirichlet_energy(f, A, elems, [sigma, tau], n)
    print(f"\nDirichlet energy of random f: {E:.4f}")

    # L² contraction
    norms = verify_l2_contraction(A, f, 20)
    print(f"L² norms (first 10 steps): {[f'{x:.4f}' for x in norms[:10]]}")
    print(f"Contraction ratio (step 1): {norms[1]/norms[0]:.6f}")
    print(f"Expected ratio from gap: {(1-gap)**2:.6f}")

    # Trace method
    for k in [2, 3, 4]:
        excess = closed_walk_excess(A, k)
        print(f"Closed walk excess k={k}: {excess:.6f}")
