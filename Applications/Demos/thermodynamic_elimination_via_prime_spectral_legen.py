"""
Thermodynamic Elimination via Prime-Spectral Legendre Duality
=============================================================

This demo illustrates the main theorem: elimination of a variable in a
polynomial ring is governed by a variational principle over the prime spectrum.

The key insight:
  a ∈ √(I) ∩ R  ⟺  ∀ P ∈ Spec(R[X]), I ≤ P → C(a) ∈ P

Equivalently, a constant polynomial C(a) is in the radical of I if and only if
it belongs to every prime ideal containing I. The "thermodynamic" interpretation:
each prime is an "equilibrium state", the energy is 0 or 1 depending on membership,
and elimination = vanishing energy at all compatible states.
"""

