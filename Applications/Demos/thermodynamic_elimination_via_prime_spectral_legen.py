def separation_visualization():
    """
    Visualize the prime witness extraction: when a ∉ radicalElim(I),
    there exists a prime with positive energy.
    """
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # Scenario: I = (2X - 6) in Z[X]
    # radicalElim(I) = {a ∈ Z | ∃n: C(a^n) ∈ (2X - 6)}
    # C(a^n) = a^n ∈ (2X - 6) requires (2X-6) | a^n.
    # Since a^n is constant, this means a^n = 0, so a = 0.
    # Actually, a ∈ radicalElim iff C(a) ∈ √(2X-6).
    # √(2X-6) = √(2)·√(X-3)... over Z[X], the radical is harder.
    # Let's simplify: use I = (X-3) instead.
    
    # I = (X-3): radicalElim = {0} (only 0 is derivable)
    # For a = 5 ∉ radicalElim: which prime separates?
    # Any prime containing (X-3) but not containing C(5) = 5.
    # P = (X-3): 5 ∉ (X-3) since 5 is a nonzero constant. ✓
    
    elements = list(range(-5, 6))
    in_elim = [a == 0 for a in elements]
    
    colors = ['green' if ie else 'red' for ie in in_elim]
    bars = ax.bar(elements, [1]*len(elements), color=colors, alpha=0.6,
                 edgecolor='black', linewidth=0.5)
    
    # Annotate
    for i, a in enumerate(elements):
        status = "∈ radicalElim" if in_elim[i] else "∉ radicalElim"
        ax.text(a, 1.05, status, ha='center', va='bottom', fontsize=7, rotation=45)
        if not in_elim[i]:
            ax.text(a, 0.5, f'Witness:\nP=(X-3)\nenergy=1',
                   ha='center', va='center', fontsize=6, color='darkred')
    
    ax.set_xlabel('Element a ∈ Z', fontsize=12)
    ax.set_title('Prime Witness Extraction for I = (X-3) in Z[X]\n'
                'Green = eliminated, Red = separated by prime witness',
                fontsize=12)
    ax.set_ylim(0, 1.8)
    ax.set_yticks([])
    
    # Legend
    green_patch = mpatches.Patch(color='green', alpha=0.6, label='a ∈ radicalElim(I)')
    red_patch = mpatches.Patch(color='red', alpha=0.6, label='a ∉ radicalElim(I) → ∃ prime witness')
    ax.legend(handles=[green_patch, red_patch], loc='upper right', fontsize=10)
    
    plt.tight_layout()
    plt.savefig('demos/separation_theorem.png', dpi=150, bbox_inches='tight')
    print("Saved: demos/separation_theorem.png")
    plt.close()

