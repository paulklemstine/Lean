def example_elimination_ZX():
    """
    Consider R = Z and the ideal I = (X^2 - 4) ⊆ Z[X].
    
    The elimination ideal: eliminationIdeal(I) = I ∩ Z = {0}
    (no nonzero constant is in (X^2 - 4))
    
    The radical elimination ideal: radicalElim(I) = √I ∩ Z
    Since √(X^2 - 4) = √((X-2)(X+2)), and X^2 - 4 is already square-free
    in Z[X], we get √I = (X-2) ∩ (X+2) over Z[X].
    
    For a ∈ Z: C(a) = a ∈ √I iff a^n ∈ (X^2 - 4) for some n.
    Since C(a)^n = a^n (constant polynomial), a^n ∈ (X^2 - 4) only if a^n = 0,
    i.e., a = 0.
    
    The spectral characterization: for each prime P of Z[X] containing (X^2-4),
    we check if C(a) ∈ P.
    
    Key primes containing (X^2 - 4):
    - (X - 2, p) for various primes p dividing gcd stuff
    - (X + 2, p) 
    - (X^2 - 4, p) for primes p
    """
    print("=" * 70)
    print("Example 1: Elimination in Z[X] with I = (X² - 4)")
    print("=" * 70)
    
    # The polynomial X^2 - 4 = (X-2)(X+2)
    # Evaluation at any integer s: s^2 - 4
    
    # Elimination ideal: {a ∈ Z | C(a) ∈ I} = {a | a ∈ (X^2 - 4)} = {0}
    print("\nElimination ideal (I ∩ Z):")
    print("  eliminationIdeal(I) = {0}")
    print("  (Only a=0 satisfies: the constant 0 = 0·(X² - 4) ∈ I)")
    
    # Radical elimination: {a ∈ Z | C(a) ∈ √I}
    print("\nRadical elimination ideal (√I ∩ Z):")
    print("  radicalElim(I) = {0}")
    print("  (For a≠0, no power a^n is in (X² - 4) since a^n is constant)")
    
    # Spectral characterization
    print("\nSpectral characterization:")
    print("  Some primes of Z[X] containing (X² - 4):")
    print("  - P₁ = (X - 2, 0) = (X - 2)  [prime since Z[X]/(X-2) ≅ Z]")
    print("  - P₂ = (X + 2, 0) = (X + 2)  [prime since Z[X]/(X+2) ≅ Z]")
    print("  - P₃ = (X - 2, 3) [prime ideal]")
    print("  - P₄ = (X + 2, 3) [prime ideal]")
    
    print("\n  For a = 3:")
    print("    C(3) = 3 ∉ (X - 2) since 3 ≠ 0 in Z[X]/(X-2) ≅ Z")
    print("    → Energy at P₁ = 1  (positive pressure!)")
    print("    → 3 ∉ spectralElim(I) ✓")
    
    print("\n  For a = 0:")
    print("    C(0) = 0 ∈ every prime (0 is in every ideal)")
    print("    → Energy at every prime = 0")
    print("    → 0 ∈ spectralElim(I) ✓")
    
    return

