    # I = (X^2 - a, X^3 - b) in Q[a,b][X]
    # Elimination of X gives the relation b^2 = a^3
    
    print("\nConsider I = (X² - a, X³ - b) in Q[a,b][X]")
    print("Goal: Find which polynomial relations in a,b follow from I")
    print()
    
    # By substitution: X² = a, X³ = b
    # So X³ = X · X² = X · a, hence b = Xa, and X = b/a (when a ≠ 0)
    # Then X² = (b/a)² = b²/a² = a, so b² = a³
    
    print("Algebraic elimination:")
    print("  From X² = a and X³ = b:")
    print("  X³ = X · X² = X · a")
    print("  So b = X · a, giving X = b/a")
    print("  Then a = X² = (b/a)² = b²/a²")
    print("  Hence a³ = b²")
    print()
    print("  eliminationIdeal(I) ∩ Q[a,b] contains (b² - a³)")
    print()
    
    # Spectral verification: check at various primes
    print("Spectral verification:")
    print("  For any prime P of Q[a,b][X] containing I:")
    print("  - P contains X² - a and X³ - b")
    print("  - In the quotient, X² = a and X³ = b")
    print("  - So b² = (X³)² = X⁶ = (X²)³ = a³")
    print("  - Hence b² - a³ = 0 in the quotient")
    print("  - Therefore C(b² - a³) ∈ P")
    print()
    print("  ✓ b² - a³ passes ALL prime spectral tests")
    print("  ✓ This confirms b² - a³ ∈ spectralElim(I)")
    
    # Numerical verification
    print("\nNumerical verification (evaluation at X = s):")
