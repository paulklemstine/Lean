"""
=============================================================================
PYTHAGOREAN TRIPLE TREE FACTORING: CORE THEORY & EXPERIMENTS
=============================================================================

Given a number n to factor, we construct the Pythagorean triple (n, b, c)
where n² + b² = c². Since (c-b)(c+b) = n², every factorization of n²
corresponds to a unique triple --- and vice versa.

We then climb the Berggren ternary tree of primitive Pythagorean triples
from (n, b, c) back to the root (3, 4, 5), extracting factoring information
from the tree path.

KEY INSIGHT: The tree path encodes the arithmetic structure of n.
Different factorizations of n produce triples in different subtrees,
and the branching pattern reveals the factors.
"""

