# The three Berggren matrices that generate all primitive triples from (3,4,5)
# Each matrix M applied to column vector [a,b,c]^T gives a child triple.

def mat_mul(M, v):
    """Multiply 3x3 matrix by 3-vector."""
    return tuple(sum(M[i][j] * v[j] for j in range(3)) for i in range(3))

# Berggren matrices
A = [[ 1, -2,  2], [ 2, -1,  2], [ 2, -2,  3]]
B = [[ 1,  2,  2], [ 2,  1,  2], [ 2,  2,  3]]
C = [[-1,  2,  2], [-2,  1,  2], [-2,  2,  3]]

# Inverse matrices (for climbing UP the tree)
A_inv = [[ 1,  2,  2], [-2, -1, -2], [ 2,  2,  3]]  # Modified signs
B_inv = [[ 1, -2,  2], [ 2, -1, -2], [ 2, -2,  3]]
C_inv = [[-1,  2,  2], [ 2,  1, -2], [-2, -2,  3]]  # Actually need to recompute

def berggren_children(triple):
    """Generate three children of a primitive Pythagorean triple."""
    return [mat_mul(A, triple), mat_mul(B, triple), mat_mul(C, triple)]


def normalize_triple(triple):
    """Ensure a < b < c and all positive. Return sorted (a, b, c)."""
    a, b, c = sorted([abs(triple[0]), abs(triple[1])]) 
    return (a, b, abs(triple[2]))


def find_parent(triple):
    """
    Find the parent of a primitive Pythagorean triple in the Berggren tree.
    
    The inverse Berggren matrices are:
    A⁻¹ = [[ 1, -2,  2], [ 2, -1,  2], [ 2, -2,  3]]  (with sign adjustments)
    
    We use the UAD (Up-Across-Down) parameterization.
    For a primitive triple (a, b, c) with a odd, b even:
    - If a > b: apply U⁻¹ (was generated by A)
    - If a < b and a + b > c... etc.
    
    Actually, the standard inverse is:
    Parent = one of {A⁻¹·v, B⁻¹·v, C⁻¹·v} that gives all positive entries.
    """
    a, b, c = triple
    # Ensure a is odd, b is even
    if a % 2 == 0:
        a, b = b, a
    
    # The inverse matrices (Berggren)
    # For (a_odd, b_even, c):
    candidates = [
        ( a - 2*b + 2*c,  2*a - b + 2*c,  2*a - 2*b + 3*c),  # A⁻¹
        ( a + 2*b + 2*c,  2*a + b + 2*c,  2*a + 2*b + 3*c),   # B⁻¹ -- this always increases
        (-a + 2*b + 2*c, -2*a + b + 2*c, -2*a + 2*b + 3*c),   # C⁻¹
    ]
    
    # The correct inverse formulas (Price 2008):
    # To go UP in the tree, exactly one of three inverse matrices gives
    # a triple with smaller hypotenuse.
    inv_A = ( a - 2*b + 2*c,  2*a - b + 2*c,  2*a - 2*b + 3*c)
    inv_B = ( a + 2*b + 2*c,  2*a + b + 2*c,  2*a + 2*b + 3*c)
    inv_C = (-a + 2*b + 2*c, -2*a + b + 2*c, -2*a + 2*b + 3*c)
    
    for label, candidate in [('A', inv_A), ('B', inv_B), ('C', inv_C)]:
        p, q, r = candidate
        if p > 0 and q > 0 and r > 0 and r < c:
            # Normalize: odd leg first
            if p % 2 == 0:
                p, q = q, p
            return label, (p, q, r)
    
    return None, None  # This IS the root


def climb_to_root(triple):
    """
    Climb from a primitive triple to the root (3, 4, 5).
    Returns the path as a sequence of branch labels.
    """
    path = []
    current = triple
    
    # Normalize: odd first
    a, b, c = current
    if a % 2 == 0:
        a, b = b, a
    current = (a, b, c)
    
    max_steps = 1000
    for _ in range(max_steps):
        if sorted(current[:2]) == [3, 4] and current[2] == 5:
            break
        label, parent = find_parent(current)
        if parent is None:
            break
        path.append(label)
        current = parent
    
    return path, current


