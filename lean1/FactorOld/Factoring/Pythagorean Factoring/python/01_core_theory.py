# PART 1: Pythagorean Triples from a Single Leg
# ==========================================================================

def triples_from_leg(n: int) -> List[Tuple[int, int, int]]:
    """
    Given leg n, find ALL Pythagorean triples (a, b, c) with a = n.
    
    Since n² + b² = c², we need (c-b)(c+b) = n².
    For each factorization n² = d * e with d < e and d ≡ e (mod 2):
        b = (e - d) / 2
        c = (e + d) / 2
    """
    n_sq = n * n
    triples = []
    
    for d in range(1, int(math.isqrt(n_sq)) + 1):
        if n_sq % d != 0:
            continue
        e = n_sq // d
        if d >= e:
            continue
        if (d + e) % 2 != 0:  # same parity required
            continue
        b = (e - d) // 2
        c = (e + d) // 2
        if b > 0:
            triples.append((n, b, c))
    
    return triples


def factorizations_from_triples(n: int) -> dict:
    """
    Show how each triple reveals a factorization of n².
    Returns mapping: triple -> (d, e) where d * e = n².
    """
    result = {}
    for triple in triples_from_leg(n):
        a, b, c = triple
        d = c - b
        e = c + b
        result[triple] = (d, e)
    return result


