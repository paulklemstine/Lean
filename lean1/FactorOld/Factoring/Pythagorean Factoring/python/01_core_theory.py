def make_primitive(triple):
    """Reduce a triple to its primitive form by dividing by GCD."""
    a, b, c = triple
    g = math.gcd(math.gcd(abs(a), abs(b)), abs(c))
    return (a // g, b // g, c // g), g


def factor_via_pythagorean(n: int) -> dict:
    """
    Factor n using the Pythagorean triple tree.
    
    Strategy:
    1. Generate all triples with leg n
    2. For each triple, reduce to primitive form
    3. Climb the tree to root, recording the path
    4. The GCD reduction reveals factors
    5. The tree path encodes the multiplicative structure
    """
    results = {
        'n': n,
        'triples': [],
        'factorizations': [],
        'tree_paths': [],
    }
    
    triples = triples_from_leg(n)
    
    for triple in triples:
        a, b, c = triple
        d, e = c - b, c + b  # d * e = n²
        prim, g = make_primitive(triple)
        
        # Normalize primitive triple
        pa, pb, pc = prim
        if pa % 2 == 0:
            pa, pb = pb, pa
        prim = (pa, pb, pc)
        
        path, root = climb_to_root(prim)
        
        results['triples'].append({
            'triple': triple,
            'factorization': (d, e),
            'gcd': g,
            'primitive': prim,
            'tree_path': ''.join(path),
            'path_length': len(path),
            'reached_root': sorted(root[:2]) == [3, 4] and root[2] == 5,
        })
    
    return results


