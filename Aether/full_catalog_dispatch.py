#!/usr/bin/env python3
"""Full Catalog Dispatch: Submit the entire catalog as context to Aristotle.

Unlike domain-focused daemon cycles, this sends the full Catalog/ tree
as project context so Aristotle can see cross-domain connections.

Usage:
    python3 full_catalog_dispatch.py --concept "Gravitational Factoring"
    python3 full_catalog_dispatch.py --auto-concept
    python3 full_catalog_dispatch.py --dry-run
"""

import argparse
import asyncio
import difflib
import json
import shutil
import sys
import tarfile
import textwrap
import time
import uuid
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

from pi_agent_client import PiAgentClient, ResearchConcept
from prompt_engine import PromptEngine, ArtifactRequests
from aristotle_sdk_client import AristotleSDKClient
from telemetry import ExperimentRecord, TelemetryLogger


class FullCatalogDispatcher:
    """Dispatch a research concept to Aristotle with full catalog context."""

    def __init__(self, config: dict, domains_config: dict):
        self.config = config
        self.domains = domains_config.get("domains", [])
        self.global_settings = domains_config.get("global_settings", {})

        self.catalog_root = Path(config.get("catalog", {}).get("root_dir", "../Catalog")).resolve()
        if not self.catalog_root.exists() or self.catalog_root.name != "Catalog":
            if (self.catalog_root / "Catalog").exists():
                self.catalog_root = self.catalog_root / "Catalog"
            else:
                self.catalog_root = (Path(__file__).parent.parent / "Catalog").resolve()

        self.output_dir = Path("./output").resolve()
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.changes_dir = self.output_dir / "changes"
        self.changes_dir.mkdir(parents=True, exist_ok=True)
        self.artifacts_dir = self.output_dir / "artifacts"
        self.artifacts_dir.mkdir(parents=True, exist_ok=True)

        self.pi_agent = PiAgentClient(
            model=config.get("pi_agent", {}).get("model", "fingpt-7b:latest"),
        ) if self.global_settings.get("pi_agent_enabled", True) else None

        self.prompt_engine = PromptEngine(config.get("prompts", {}))
        self.aristotle = AristotleSDKClient(config.get("aristotle", {}))
        self.telemetry = TelemetryLogger(config.get("telemetry", {}))

    def _generate_lean_source(self, concept: ResearchConcept) -> str:
        """Generate a Lean 4 source file from a concept."""
        exp_id = str(uuid.uuid4())[:8]
        novelty = concept.novelty_estimate

        header = textwrap.dedent(f"""\
            import Mathlib

            /-! # CatalogBuild.Speculative.AutoResearch.{concept.title}

            Auto-generated by AETHER Full-Catalog Dispatch.
            Experiment: {exp_id}
            Date: {datetime.utcnow().isoformat()}
            -/

            /-
            {concept.concept_description}

            Mathematical Concept: {concept.mathematical_framing}
            -/
        """)

        lean_body = concept.lean_guess.strip()
        if not lean_body or lean_body == "" or "..." in lean_body or "theorem" not in lean_body:
            lean_body = textwrap.dedent(f"""\
                theorem {concept.title.lower().replace(' ', '_')}_breakthrough
                    {{X : Type*}} [Inhabited X] :
                    True := by
                  sorry
            """)

        if "sorry" not in lean_body:
            lean_body += "\n  sorry\n"

        return header + "\n" + lean_body

    def _extract_changed_files(
        self,
        result_dir: Path,
        original_root: Path,
    ) -> List[Tuple[Path, Path, str]]:
        """Compare result .lean files against originals and return changed ones.

        Returns list of (relative_path, result_path, diff_summary).
        """
        changed: List[Tuple[Path, Path, str]] = []
        lean_files = list(result_dir.rglob("*.lean"))

        for result_file in lean_files:
            # Compute relative path from result_dir
            rel_path = result_file.relative_to(result_dir)
            original_file = original_root / rel_path

            if not original_file.exists():
                # New file
                changed.append((rel_path, result_file, "new file"))
                continue

            original_text = original_file.read_text(encoding="utf-8")
            result_text = result_file.read_text(encoding="utf-8")

            if original_text != result_text:
                # Compute a simple diff summary
                diff = list(difflib.unified_diff(
                    original_text.splitlines(keepends=True),
                    result_text.splitlines(keepends=True),
                    fromfile=str(rel_path),
                    tofile=str(rel_path),
                    lineterm="",
                ))
                added = sum(1 for line in diff if line.startswith("+"))
                removed = sum(1 for line in diff if line.startswith("-"))
                summary = f"+{added}/-{removed} lines"
                changed.append((rel_path, result_file, summary))

        return changed

    def _save_changed_files(
        self,
        changed: List[Tuple[Path, Path, str]],
        exp_id: str,
    ) -> Path:
        """Save changed files to output/changes/{exp_id}/ and write a manifest."""
        changes_out = self.changes_dir / exp_id
        changes_out.mkdir(parents=True, exist_ok=True)

        manifest = {
            "experiment_id": exp_id,
            "timestamp": datetime.utcnow().isoformat(),
            "changed_files": [],
        }

        for rel_path, result_path, summary in changed:
            dest = changes_out / rel_path
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(result_path, dest)
            manifest["changed_files"].append({
                "path": str(rel_path),
                "summary": summary,
            })

        manifest_path = changes_out / "manifest.json"
        manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        print(f"[CHANGES] {len(changed)} changed files saved to {changes_out}")
        return changes_out

    def _extract_artifacts(self, project_dir: Path, exp_id: str) -> Dict[str, Path]:
        """Extract research report, demo, SVG, and discussion from result."""
        artifacts: Dict[str, Path] = {}
        result_dir = project_dir / "result_extracted"
        if not result_dir.exists():
            return artifacts

        patterns = {
            "research_report": ["RESEARCH_REPORT.md", "report.md", "*report*.md"],
            "python_demo": ["demo.py", "*demo*.py"],
            "svg_demo": ["diagram.svg", "*.svg"],
            "sciam_discussion": ["DISCUSSION.md", "discussion.md", "*discussion*.md"],
        }

        exp_artifacts_dir = self.artifacts_dir / exp_id
        exp_artifacts_dir.mkdir(parents=True, exist_ok=True)

        for artifact_type, filenames in patterns.items():
            for pattern in filenames:
                matches = list(result_dir.rglob(pattern))
                if matches:
                    src = matches[0]
                    dest = exp_artifacts_dir / src.name
                    shutil.copy2(src, dest)
                    artifacts[artifact_type] = dest
                    break

        return artifacts

    async def dispatch(self, concept: Optional[ResearchConcept] = None, dry_run: bool = False) -> bool:
        """Run one full-catalog dispatch cycle."""
        print("=" * 70)
        print("AETHER FULL-CATALOG DISPATCH")
        print("=" * 70)

        # Generate or use provided concept
        if concept is None:
            if self.pi_agent:
                domain = self.domains[0] if self.domains else {"id": "general", "name": "General", "seed_concepts": []}
                concept = self.pi_agent.generate_breakthrough_concept(
                    domain=domain["id"],
                    seed_concepts=domain.get("seed_concepts", []),
                    target="theorem",
                )
            else:
                concept = ResearchConcept(
                    title="auto_concept_full_catalog",
                    domain="general",
                    concept_description="Full catalog context dispatch.",
                    mathematical_framing="TBD",
                )

        exp_id = str(uuid.uuid4())[:8]
        print(f"[Concept] {concept.title} (novelty={concept.novelty_estimate:.2f})")

        # Build prompt
        prompt = self.prompt_engine.build_prompt(
            title=concept.title,
            domain="full_catalog",
            concept_description=concept.concept_description,
            mathematical_framing=concept.mathematical_framing,
            lean_guess=concept.lean_guess,
            difficulty="master",
            artifacts=ArtifactRequests(
                research_report=True,
                python_demo=True,
                svg_demo=True,
                sciam_discussion=True,
                lean_proof=True,
            ),
        )
        print(f"[Prompt] {len(prompt.prompt_text)} chars")

        # Generate Lean source
        lean_source = self._generate_lean_source(concept)
        print(f"[Lean] {len(lean_source)} chars generated")

        if dry_run:
            print("\n[DRY RUN] Skipping Aristotle dispatch.")
            print(f"\n--- PROMPT ---\n{prompt.prompt_text[:2000]}...")
            return True

        # Dispatch with FULL catalog context (domain="")
        project_dir = self.output_dir / f"job_{exp_id}"
        project_dir.mkdir(parents=True, exist_ok=True)

        print(f"[Dispatch] Submitting to Aristotle with full catalog context...")
        start_time = time.time()
        result = await self.aristotle.submit_with_catalog_context(
            lean_source=lean_source,
            catalog_root=self.catalog_root,
            project_dir=project_dir,
            prompt=prompt.prompt_text,
            domain="",  # Empty domain = full catalog copy
        )
        elapsed = time.time() - start_time
        print(f"[Dispatch] Aristotle result: {result.status} ({elapsed:.1f}s)")
        if result.error_message:
            print(f"[Dispatch] Error: {result.error_message}")

        # Process results
        if result.lean_source:
            # Extract changed files (not just Main.lean)
            result_dir = project_dir / "result_extracted"
            if result_dir.exists():
                changed = self._extract_changed_files(result_dir, self.catalog_root)
                print(f"[Extract] {len(changed)} changed/new files found")
                for rel, _, summary in changed:
                    print(f"  - {rel}: {summary}")

                if changed:
                    changes_out = self._save_changed_files(changed, exp_id)
            else:
                print("[Extract] No result_extracted directory")
                changed = []

            # Extract artifacts
            artifacts = self._extract_artifacts(project_dir, exp_id)
            print(f"[Artifacts] {list(artifacts.keys())}")

            # Save main lean source as pending
            pending_dir = self.catalog_root / "Speculative" / "AutoResearch"
            pending_dir.mkdir(parents=True, exist_ok=True)
            pending_file = pending_dir / f"PENDING_full_catalog_{exp_id}.lean"
            pending_file.write_text(result.lean_source, encoding="utf-8")
            print(f"[Pending] Saved to {pending_file}")

            # Log experiment
            record = ExperimentRecord(
                experiment_id=exp_id,
                arc_id="full_catalog",
                arc_name="Full Catalog Dispatch",
                domain="full_catalog",
                file_path=str(pending_file),
                difficulty="master",
                hypothesis_text=lean_source[:500],
                concept_combination=["full_catalog"],
                generation_latency_ms=elapsed * 1000,
                aristotle_job_id=result.project_id,
                status="proven" if result.status in ("complete", "COMPLETE", "COMPLETE_WITH_ERRORS") else result.status.lower(),
                proof_length_lines=len(result.lean_source.splitlines()),
                novelty_score=concept.novelty_estimate,
                epicness_score=concept.breakthrough_potential,
            )
            self.telemetry.log_experiment(record)

            # Write summary
            summary_path = self.output_dir / f"SUMMARY_{exp_id}.json"
            summary = {
                "experiment_id": exp_id,
                "status": result.status,
                "project_id": result.project_id,
                "elapsed_seconds": elapsed,
                "changed_files_count": len(changed),
                "artifacts": {k: str(v) for k, v in artifacts.items()},
                "pending_file": str(pending_file),
            }
            summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
            print(f"[Summary] Saved to {summary_path}")

            return True
        else:
            print(f"[Result] No proof returned. Status: {result.status}")
            return False


async def main():
    parser = argparse.ArgumentParser(description="Full Catalog Dispatch to Aristotle")
    parser.add_argument("--config", default="config.yaml", help="Path to config.yaml")
    parser.add_argument("--domains", default="research_domains.json", help="Path to research_domains.json")
    parser.add_argument("--concept", help="Use a specific concept title (skips Pi-Agent)")
    parser.add_argument("--auto-concept", action="store_true", help="Auto-generate a concept")
    parser.add_argument("--dry-run", action="store_true", help="Generate concept + prompt but do not dispatch")

    args = parser.parse_args()

    import yaml
    config_path = Path(args.config)
    config = yaml.safe_load(config_path.read_text(encoding="utf-8")) if config_path.exists() else {}

    domains_path = Path(args.domains)
    domains_config = json.loads(domains_path.read_text(encoding="utf-8")) if domains_path.exists() else {}

    dispatcher = FullCatalogDispatcher(config=config, domains_config=domains_config)

    concept = None
    if args.concept:
        concept = ResearchConcept(
            title=args.concept,
            domain="full_catalog",
            concept_description="User-specified full-catalog dispatch concept.",
            mathematical_framing="TBD",
        )

    success = await dispatcher.dispatch(concept=concept, dry_run=args.dry_run)
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    asyncio.run(main())
