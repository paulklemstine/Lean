from itertools import combinations
from typing import FrozenSet, Iterable, Sequence, Set

Point = int
OpenSet = FrozenSet[Point]
Topology = FrozenSet[OpenSet]


def generate_topology(ground: FrozenSet[Point], subbasis: Iterable[OpenSet]) -> Topology:
    basis: Set[OpenSet] = {frozenset(), ground}
    for s in subbasis:
        basis.add(frozenset(s) & ground)
    changed = True
    while changed:
        changed = False
        for u in list(basis):
            for v in list(basis):
                w = u & v
                if w not in basis:
                    basis.add(w)
                    changed = True
    opens: Set[OpenSet] = {frozenset(), ground}
    for r in range(1, len(basis) + 1):
        for combo in combinations(basis, r):
            opens.add(frozenset().union(*combo))
    return frozenset(opens)


def possibility(ground: FrozenSet[Point], topologies: Sequence[Topology]) -> Topology:
    """Possibility (infimum in the lattice of topologies).

    The possibility topology is generated by the UNION of all observers' opens:
    pool every set open for some observer, then close under finite intersections
    and arbitrary unions.
    """
    union_opens: Set[OpenSet] = set()
    for t in topologies:
        union_opens |= set(t)
    return generate_topology(ground, union_opens)
