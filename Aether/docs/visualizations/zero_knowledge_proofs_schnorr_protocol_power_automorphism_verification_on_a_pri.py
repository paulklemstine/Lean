from __future__ import annotations
from typing import List


def power_map_image(p: int, q: int, g: int, k: int) -> List[int]:
    """Apply the power map x -> x^k to every element of the order-q subgroup of
    (Z/pZ)^* generated by g, returning the sorted image multiset (as a list)."""
    subgroup = sorted({pow(g, e, p) for e in range(q)})
    return sorted(pow(x, k % q, p) for x in subgroup)


def is_automorphism(p: int, q: int, g: int, k: int) -> bool:
    """True iff x -> x^k is a bijection of the subgroup, i.e. k != 0 (mod q)."""
    image = power_map_image(p, q, g, k)
    return len(set(image)) == q
