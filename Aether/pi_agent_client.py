class PiAgentClient:
    """v3 Pi-Agent client: glm-5.1:cloud via ollama HTTP API.

    The brain of Aether v3. Handles:
    - Research direction selection
    - Dynamic prompt writing
    - Result quality evaluation
    - File classification and placement
    """

    OLLAMA_BASE_URL = "http://127.0.0.1:11434"

    def __init__(
        self,
        model: str = "glm-5.1:cloud",
        memory: Optional[ResearchMemory] = None,
        catalog_root: Optional[Path] = None,
        timeout: int = 300,
        compact: bool = False,
    ):
        self.model = model
        self.memory = memory
        self.catalog_root = Path(catalog_root) if catalog_root else None
        self.timeout = timeout
        self.compact = compact
        # Use max timeout for client connection, use per-request timeouts for operations
        self.client = httpx.Client(timeout=httpx.Timeout(connect=30.0, read=300.0, write=30.0, pool=30.0))

        # CatalogAnalyzer for reference selection
        self.catalog_analyzer: Optional[CatalogAnalyzer] = None
        if self.catalog_root and self.catalog_root.exists():
            self.catalog_analyzer = CatalogAnalyzer(self.catalog_root)

    def _call_ollama(self, system: str, user: str, timeout: Optional[int] = None) -> str:
        """Call ollama HTTP API with system + user prompts. Returns raw text.

        Args:
            system: System prompt
            user: User prompt
            timeout: Override timeout in seconds (uses self.timeout if None)
        """
        request_timeout = timeout or self.timeout

        # In compact mode, truncate to keep total under ~6K chars
        # Cloud reasoning models need shorter context for timely responses
        if self.compact:
            max_system = 4000
            max_user = 2000
            if len(system) > max_system:
                system = system[:max_system] + "\n[...system prompt truncated for model efficiency...]"
            if len(user) > max_user:
                user = user[:max_user] + "\n[...context truncated for model efficiency...]"

        # Log the request
        system_preview = system[:200].replace('\n', ' ')
        user_preview = user[:500].replace('\n', ' ')
        print(f"[Pi-Agent] → ollama request (model={self.model}, timeout={request_timeout}s)")
        print(f"[Pi-Agent]   system: {system_preview}...")
        print(f"[Pi-Agent]   user: {user_preview}...")

        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            "stream": False,
            "options": {
                "temperature": 0.85,
                "top_p": 0.92,
                "num_predict": 4096,
            },
        }
        try:
            response = self.client.post(
                f"{self.OLLAMA_BASE_URL}/api/chat",
                json=payload,
                timeout=request_timeout,
            )
            response.raise_for_status()
            data = response.json()
            content = data.get("message", {}).get("content", "")
            if not content:
                content = data.get("response", "")
            
            # kimi-k2 reasoning models put reasoning in 'thinking' field
            # and final answer in 'content'. If content is empty, the model
            # may have put the answer in thinking instead. Try to extract it.
            thinking = data.get("message", {}).get("thinking", "")
            if not content and thinking:
                # Model put answer in thinking field - try to extract JSON or useful content
                content = thinking
                print(f"[Pi-Agent] Content was empty, using thinking field ({len(thinking)} chars)")

            # Log the response
            response_preview = content[:500].replace('\n', ' ')
            print(f"[Pi-Agent] ← ollama response ({len(content)} chars)")
            print(f"[Pi-Agent]   {response_preview}...")

            return content
        except httpx.TimeoutException:
            print(f"[Pi-Agent] ← ollama TIMEOUT after {request_timeout}s")
            return f"[OLLAMA_TIMEOUT: Request timed out after {self.timeout}s]"
        except httpx.HTTPStatusError as e:
            print(f"[Pi-Agent] ← ollama HTTP error: {e.response.status_code}")
            return f"[OLLAMA_HTTP_ERROR: {e.response.status_code} {e.response.text[:200]}]"
        except Exception as e:
            print(f"[Pi-Agent] ← ollama error: {type(e).__name__}: {e}")
            return f"[OLLAMA_ERROR: {e}]"

    def _parse_json_response(self, raw: str) -> Optional[Dict[str, Any]]:
        """Try to extract JSON from an LLM response.
        
        Handles: pure JSON, markdown-wrapped JSON, reasoning text with JSON at end,
        and plain reasoning text (domain + concept extraction heuristic).
        """
        # Try direct parse
        try:
            return json.loads(raw.strip())
        except json.JSONDecodeError:
            pass

        # Try to find JSON in markdown code block
        json_match = re.search(r'```(?:json)?\s*\n?(.*?)\n?```', raw, re.DOTALL)
        if json_match:
            try:
                return json.loads(json_match.group(1).strip())
            except json.JSONDecodeError:
                pass

        # Try to find JSON object anywhere in the text
        json_match = re.search(r'\{[^{}]*(?:\{[^{}]*\}[^{}]*)*\}', raw, re.DOTALL)
        if json_match:
            try:
                result = json.loads(json_match.group())
                # Validate it looks like a concept or quality response
                if isinstance(result, dict) and len(result) >= 2:
                    return result
            except json.JSONDecodeError:
                pass

        # HEURISTIC: Extract concept from reasoning text when no JSON found
        # kimi-k2.6:cloud often returns reasoning without JSON wrapper
        import re as _re
        
        # Try to extract a domain name
        domain_patterns = [
            (r'(?:domain|Domain|DOMAIN)[:\s]+["\']?(\w+)["\'\s,]', 'domain'),
            (r'Select\s+(?:the\s+)?(?:best|most\s+promising)\s+(?:research\s+)?(?:direction|domain)[^.]*?\b(\w+)\b', 'domain'),
        ]
        known_domains = {'algebra', 'bridges', 'computation', 'cryptography', 'eml', 
                         'geometry', 'logic', 'machinelearning', 'physics', 
                         'pythagorean', 'shared', 'speculative', 'tropical',
                         'tropical_langlands', 'tropical_neural', 'carmichael',
                         'niven', 'dilithium', 'spb'}
        
        extracted = {}
        # Find domain mentions in the text
        lower_raw = raw.lower()
        for d in known_domains:
            if d in lower_raw:
                extracted['domain'] = d
                break
        
        # Try to find concept_title or title
        title_match = _re.search(r'(?:concept_title|title|Title)[:\s]+["\']([^"\'\n]+)["\'\s,]', raw)
        if not title_match:
            # Find bold/coded title like **tropical_langlands_gl2** or `tropical_langlands_gl2`
            title_match = _re.search(r'[**`]+([a-z_]+[a-z0-9_]+)[**`]+', raw)
        if title_match:
            extracted['concept_title'] = title_match.group(1).strip()
        
        # Try to find novelty and breakthrough scores
        novelty_match = _re.search(r'novelty[^0-9]*([0-9.]+)', raw)
        if novelty_match:
            try:
                extracted['novelty_estimate'] = float(novelty_match.group(1))
            except ValueError:
                pass
        breakthrough_match = _re.search(r'breakthrough[^0-9]*([0-9.]+)', raw)
        if breakthrough_match:
            try:
                extracted['breakthrough_potential'] = float(breakthrough_match.group(1))
            except ValueError:
                pass
        
        # If we extracted enough info, return it as a partial concept
        if extracted.get('domain') or extracted.get('concept_title'):
            # Extract mathematical framing from reasoning text
            # Look for mathematical statements or LaTeX in the reasoning
            math_patterns = [
                r'(?:prove|show|formalize|proving)[^.!]*?([A-Z][^.!]{10,200})',  # First sentence after prove/show
                r'(?:theorem|lemma)[^.!]*?([^.!]{10,200})',  # Theorem statements
                r'\$\$(.+?)\$\$',  # LaTeX display math
                r'\$(.+?)\$',    # LaTeX inline math
            ]
            for pat in math_patterns:
                match = _re.search(pat, raw)
                if match:
                    extracted['mathematical_framing'] = match.group(1).strip()[:300]
                    break
            
            # Extract description from reasoning
            desc_match = _re.search(r'(?:Justification|Rationale|Description):\s*(.{20,500})', raw, _re.DOTALL)
            if desc_match:
                extracted['concept_description'] = desc_match.group(1).strip()[:400]
            
            print(f"[Pi-Agent] Extracted concept from reasoning text: {extracted}")
            return extracted
        
        return None

