    def write_aristotle_prompt(
        self,
        concept: ResearchConcept,
        catalog_references: Optional[List[str]] = None,
        catalog_context: str = "",
        recent_successes: Optional[List[Dict]] = None,
        recent_failures: Optional[List[Dict]] = None,
        theorem_context: str = "",
    ) -> str:
        """Dynamically write the full Aristotle prompt.

        Composes a prompt that is sent DIRECTLY to Aristotle (the theorem prover).
        This is NOT a meta-instruction asking someone to write a brief — it is
        the actual task description Aristotle receives.

        Strategy:
        1. Build a complete direct-to-Aristotle prompt with all context
        2. Ask the LLM (Pi-Agent) to enrich it with deeper mathematical insight
        3. Strip any LLM preamble/echo before returning
        4. Fall back to the direct prompt (never a meta-instruction) if LLM fails

        Args:
            theorem_context: Previously proved theorems from ResearchContext,
                           so Aristotle can build on existing results.
        """
        refs = catalog_references or concept.catalog_references or []

        # Build reference section
        ref_section = ""
        if refs and self.catalog_analyzer:
            ref_section = self.catalog_analyzer.build_catalog_context_string(refs)
        elif catalog_context:
            ref_section = catalog_context

        # Research mode instructions (addressed directly to Aristotle)
        mode_instructions = {
            "prove": textwrap.dedent("""\
                Research Mode: PROVE

                Discover and prove a new theorem. Start from the mathematical
                context provided and find an interesting, non-trivial result
                that can be formally proven in Lean 4. The theorem should be
                specific enough to prove, but general enough to be mathematically
                interesting. Avoid trivial tautologies.
            """),
            "formalize": textwrap.dedent("""\
                Research Mode: FORMALIZE

                You are given informal mathematical ideas, notes, or a paper excerpt.
                Formalize these ideas in Lean 4. Translate the informal mathematics
                into precise definitions and theorem statements, then prove what you
                can. If some parts require new axioms, declare them clearly and prove
                consequences.
            """),
            "counterexample": textwrap.dedent("""\
                Research Mode: COUNTEREXAMPLE

                Find a counterexample to a stated conjecture. If the conjecture is
                false, provide a specific counterexample formalized in Lean 4 and
                prove that it contradicts the conjecture. If the conjecture is
                actually true, prove it instead.
            """),
            "sorry_fill": textwrap.dedent("""\
                Research Mode: SORRY_FILL

                You are given Lean 4 files that contain `sorry` placeholders.
                Your task is CRITICALLY IMPORTANT: fill ALL `sorry` placeholders
                with complete, rigorous proofs. This closes known open problems.

                ## Strategy for sorry_fill

                1. READ the surrounding context. The theorem statement, imports,
                   and nearby lemmas contain CRITICAL HINTS about proof strategy.

                2. DO NOT change the theorem statement — only fill the `sorry`.

                3. For HARD targets (Carmichael, Fibonacci, etc.), break the proof
                   into helper lemmas first, then use them to fill the original sorry.

                4. If you cannot complete the full proof, reduce the sorry count
                   by replacing some with partial progress. This is still valuable.

                5. Priority targets with known strategies:
                   - CarmichaelComposite: Use entry-point theory + growth bounds
                   - Fib_gcd_identity: Zsigmondy-type argument + entry point divides n
                   - CarmichaelComputational: Same as CarmichaelComposite approach

                6. Make sure your proof typechecks. A proof that compiles with
                   fewer sorries is better than an ambitious proof that doesn't compile.
            """),
        }

        mode_instruction = mode_instructions.get(concept.research_mode, mode_instructions["prove"])

        # Build history section
        history_section = ""
        if recent_successes:
            success_titles = [s.get("concept_title", s.get("title", "?")) for s in recent_successes[:5]]
            history_section += f"\nRecent successful concepts: {', '.join(success_titles)}\n"
        if recent_failures:
            failure_titles = [f.get("concept_title", f.get("title", "?")) for f in recent_failures[:5]]
            failure_reasons = [f.get("reason", "unknown") for f in recent_failures[:5]]
            history_section += f"\nRecent failures (avoid these approaches): "
            for title, reason in zip(failure_titles, failure_reasons):
                history_section += f"\n  - {title}: {reason}"

        # ---- DIRECT ARISTOTLE PROMPT ----
        # This is the prompt sent directly to Aristotle. It addresses Aristotle
        # as the theorem prover, not as a brief-writer intermediary.
        direct_prompt = textwrap.dedent(f"""\
            ## Research Task: {concept.title}

            {mode_instruction}

            ### Mathematical Objective
            {concept.concept_description}

            ### Precise Mathematical Framing
            {concept.mathematical_framing}

            {"### Lean 4 Sketch\\n" + concept.lean_guess if concept.lean_guess else ""}

            ### Proof Strategy
            This result is significant because it advances the {concept.domain} domain.
            {"The goal is to fill existing `sorry` placeholders — do not change theorem statements." if concept.research_mode == "sorry_fill" else "Produce novel, non-trivial theorems with complete Lean 4 proofs."}

            ### Catalog Context
            The theorem catalog has these relevant files that you should study as
            context. They contain existing theorems, definitions, and structures
            that you can build upon:

            {ref_section if ref_section else "No specific files referenced. Use Mathlib and general knowledge."}

            {history_section if history_section else ""}

            {"### Previously Proved Theorems (build on these)\\n" + theorem_context if theorem_context else ""}

            ### Expected Deliverables
            - Complete Lean 4 file with imports, definitions, and proofs
            - RESEARCH_REPORT.md explaining significance
            - demo.py with concrete numerical examples
            - diagram.svg visualizing the main concept
            - DISCUSSION.md in Scientific American style
        """)

        # ---- LLM ENRICHMENT ----
        # Ask Pi-Agent to enrich the direct prompt with deeper mathematical insight.
        # The output must still be a direct-to-Aristotle prompt, not a meta-instruction.
        # Create a summary of the direct prompt for the enrichment step.
        # The full direct prompt can be 50K+ chars with catalog references,
        # which is too long for the LLM. We only send the task portion
        # (first ~3000 chars, before the catalog context) to the LLM.
        prompt_summary = direct_prompt[:3000]
        if len(direct_prompt) > 3000:
            prompt_summary += "\n\n[... catalog context omitted for brevity ...]"

        enrichment_request = textwrap.dedent(f"""\
            Below is a research prompt that will be sent directly to Aristotle (a
            Lean 4 theorem prover). Your job is to ENRICH it with deeper mathematical
            insight, specific proof strategy hints, and precise Lean 4 type signatures.
            Do NOT add meta-instructions like "Write a brief" — the output goes
            directly to Aristotle, who is a theorem prover, not a person.

            Add depth to:
            - The precise theorem statement (give exact Lean 4 type signature)
            - The proof strategy (add 3-5 concrete proof steps with key lemmas)
            - The significance (explain why this matters to the research program)

            ---
            {prompt_summary}
            ---

            Output the enriched TASK SECTIONS ONLY (no catalog references needed).
            No preamble, no "Here is the enriched prompt:", just the task content.
        """)

        # For compact/cloud mode, skip enrichment entirely - it always times out
        # The direct prompt is well-structured for Aristotle already
        if self.compact:
            print(f"[Pi-Agent] Using direct prompt (compact mode, enrichment skipped)")
            return direct_prompt

        raw = self._call_ollama(_PROMPT_WRITING_SYSTEM_PROMPT, enrichment_request, timeout=60)

        # For compact/cloud mode, skip enrichment if LLM is slow to respond
        # The direct prompt is already well-structured for Aristotle
        use_enriched = raw and not raw.startswith("[OLLAMA") and not "TIMEOUT" in raw
        if use_enriched:
            cleaned = self._strip_llm_preamble(raw)
            if cleaned and len(cleaned) > 200:
                # The LLM enriched the task section. Merge with catalog context.
                catalog_section = ""
                if "### Catalog Context" in direct_prompt:
                    idx = direct_prompt.find("### Catalog Context")
                    catalog_section = "\n\n" + direct_prompt[idx:]
                return cleaned + catalog_section
        # Fallback: use the direct prompt (never a meta-instruction)
        print(f"[Pi-Agent] Using direct prompt (enrichment {'failed' if raw and 'TIMEOUT' in raw else 'skipped'})")
        return direct_prompt

    @staticmethod
    def _strip_llm_preamble(text: str) -> str:
        """Strip common LLM preamble/echo patterns from enriched prompts.

        LLMs often echo instructions before the actual content. This removes:
        - "Here is the enriched prompt:" style headers
        - "Sure! Here's..." style acknowledgments
        - Markdown code fences wrapping the entire output
        - Leading instruction echoes like "Write a research brief..."
        - Blank lines between preamble and content
        """
        import re
        lines = text.strip().split('\n')

        # Preamble patterns that indicate a line is NOT real content
        preamble_patterns = [
            r"here\s+is\s+the", r"here'?s\s+the", r"^sure!?$", r"^certainly!?$",
            r"^of\s+course!?$", r"write\s+a\s+research\s+brief", r"i'?ll\s+write",
            r"below\s+is\s+the", r"the\s+enriched\s+prompt", r"^```markdown$",
            r"^```text$", r"^```\s*$",
        ]

        # Skip all leading preamble lines (including blank lines before content)
        content_start = 0
        for i, line in enumerate(lines):
            if i >= 10:  # Don't strip more than 10 lines of preamble
                break
            stripped = line.strip()
            stripped_lower = stripped.lower()
            is_preamble = any(re.search(p, stripped_lower) for p in preamble_patterns)
            is_blank = stripped == ""
            if is_preamble or is_blank:
                content_start = i + 1
            else:
                # Found the start of real content
                break

        result_lines = lines[content_start:]

        # Strip trailing code fence if present
        while result_lines and result_lines[-1].strip() == "```":
            result_lines = result_lines[:-1]

        result = '\n'.join(result_lines).strip()
        return result if len(result) > 100 else text.strip()

    # ------------------------------------------------------------------
    # Result quality evaluation
    # ------------------------------------------------------------------

    def evaluate_result_quality(
        self,
        result_lean: str,
        concept: ResearchConcept,
        prompt: str,
    ) -> Dict[str, Any]:
        """Pi-Agent evaluates the quality of an Aristotle result.

        Returns: {
            "quality": "trivial" | "partial" | "substantial",
            "should_retry": bool,
            "retry_strategy": str,
            "confidence": float,
            "analysis": str
        }
        """
        # Truncate very long results for the LLM
        lean_preview = result_lean[:3000] if len(result_lean) > 3000 else result_lean

        # Quick heuristic pre-check
        if self._is_trivially_obvious(lean_preview):
            return {
                "quality": "trivial",
                "should_retry": True,
                "retry_strategy": "Result is trivially obvious. Request a more specific, non-trivial theorem.",
                "confidence": 0.9,
                "analysis": "Heuristic: contains trivial proof patterns.",
            }

        user_prompt = textwrap.dedent(f"""\
            Evaluate this Lean 4 proof result.

            ## Original Concept
            - Title: {concept.title}
            - Domain: {concept.domain}
            - Research Mode: {concept.research_mode}
            - Description: {concept.concept_description[:500]}

            ## Lean 4 Result
            ```lean
            {lean_preview}
            ```

            Is this result trivial, partial, or substantial? Consider:
            - Does it prove something mathematically interesting and non-obvious?
            - Is the proof complete or does it have many sorries?
            - Does it contribute new mathematics or just restate known facts?

            Respond with JSON:
            {{
              "quality": "trivial|partial|substantial",
              "should_retry": true/false,
              "retry_strategy": "what to change if retrying",
              "confidence": 0.0-1.0,
              "analysis": "brief explanation"
            }}
        """)

        raw = self._call_ollama(_QUALITY_SYSTEM_PROMPT, user_prompt)
        parsed = self._parse_json_response(raw)

        if parsed:
            return {
                "quality": parsed.get("quality", "partial"),
                "should_retry": parsed.get("should_retry", True),
                "retry_strategy": parsed.get("retry_strategy", ""),
                "confidence": float(parsed.get("confidence", 0.5)),
                "analysis": parsed.get("analysis", ""),
            }

        # Fallback: heuristic evaluation
        sorry_count = lean_preview.count("sorry")
        theorem_count = lean_preview.count("theorem ") + lean_preview.count("lemma ")
        if sorry_count == 0 and theorem_count > 0:
            return {
                "quality": "substantial",
                "should_retry": False,
                "retry_strategy": "",
                "confidence": 0.6,
                "analysis": "Fallback heuristic: no sorries, has theorems.",
            }
        elif sorry_count > 0 and theorem_count > 0:
            return {
                "quality": "partial",
                "should_retry": True,
                "retry_strategy": "Fill remaining sorries or simplify theorem.",
                "confidence": 0.5,
                "analysis": "Fallback heuristic: has sorries and theorems.",
            }
        else:
            return {
                "quality": "trivial",
                "should_retry": True,
                "retry_strategy": "Generate a more specific concept.",
                "confidence": 0.4,
                "analysis": "Fallback heuristic: no theorems found.",
            }

    def _is_trivially_obvious(self, lean_source: str) -> bool:
        """Quick heuristic check for obviously trivial results.

        Catches results that are clearly tautological or use only trivial
        proof steps, which would score near-zero on mathematical depth.
        """
        lines = [l.strip() for l in lean_source.splitlines()
                 if l.strip() and not l.strip().startswith("--")]

        # Empty or near-empty files are trivial
        if len(lines) < 5:
            return True

        # Check for True-statements or tautologies
        obvious_patterns = [
            "True := by trivial",
            "True := by simp",
            "True := by decide",
            "True := by exact True.intro",
            "True := by rfl",
            "True := by aesop",
            "True := by native_decide",
        ]
        for pattern in obvious_patterns:
            if pattern in lean_source:
                return True

        # If ALL theorems just prove True, it's trivial
        theorem_count = lean_source.count("theorem ") + lean_source.count("lemma ")
        if theorem_count > 0 and "True :=" in lean_source and theorem_count == lean_source.count("True :="):
            return True

        # Check for proof files that ONLY use trivial tactics
        # (every proof step is trivial/simp/rfl with no setup)
        proof_sections = lean_source.split(":= by")
        if len(proof_sections) > 1:
            all_trivial = True
            trivial_only = {"trivial", "simp", "rfl", "decide", "native_decide", "exact rfl", "exact True.intro"}
            for i, section in enumerate(proof_sections[1:], 1):
                first_line = section.split("\n")[0].strip()
                if first_line and not any(t in first_line for t in trivial_only):
                    all_trivial = False
                    break
            if all_trivial and theorem_count <= 2:
                return True

        # File only has definitions with no theorems/lemmas
        has_theorems = ("theorem " in lean_source or "lemma " in lean_source)
        has_example = ("example " in lean_source)
        if not has_theorems and not has_example:
            # Just definitions, no proofs — this could be valuable or not
            # Let the LLM judge
            return False

        # CRITICAL: Check for the signature pattern of placeholder triviality
        # {X : Type*} [Inhabited X] : True := by trivial
        # This is the #1 indicator of garbage output from lazy LLMs
        import re as _re
        trivial_pattern = _re.compile(
            r'theorem\s+\w+[^:]*\{[^}]*Type\*?\}[^:]*\[Inhabited[^]]*\][^:]*:\s*True\s*:=\s*by\s*trivial'
        )
        if trivial_pattern.search(lean_source):
            # Count how many theorems match this pattern vs total
            trivial_matches = len(trivial_pattern.findall(lean_source))
            if trivial_matches >= theorem_count * 0.5:
                # More than half the theorems are this pattern — trivial output
                return True

        return False

