class PiAgentClient:
    """v3 Pi-Agent client: LLM provider via Pollinations or local Ollama.

    The brain of Aether v3. Handles:
    - Research direction selection
    - Dynamic prompt writing
    - Result quality evaluation
    - File classification and placement

    Set use_ollama=True to route all LLM calls through a local Ollama
    instance instead of the Pollinations cloud API. When using Ollama,
    the pollen gate (rate/budget tracking) is skipped.
    """

    OLLAMA_BASE_URL = "http://127.0.0.1:11434"

    def __init__(
        self,
        model: str = "openai-large",
        memory: Optional[ResearchMemory] = None,
        catalog_root: Optional[Path] = None,
        timeout: int = 300,
        compact: bool = False,
        pollinations: Optional[Dict[str, Any]] = None,
        use_ollama: bool = False,
        ollama_base_url: Optional[str] = None,
        ollama_model: Optional[str] = None,
        ollama_cloud: Optional[Dict[str, Any]] = None,
    ):
        self.model = model
        self.memory = memory
        self.catalog_root = Path(catalog_root) if catalog_root else None
        self.timeout = timeout
        self.compact = compact
        self.use_ollama = use_ollama
        self.ollama_base_url = ollama_base_url or self.OLLAMA_BASE_URL
        self.ollama_model = ollama_model  # None means auto-detect from local Ollama

        # Ollama Cloud fallback configuration
        _ocr = ollama_cloud or {}
        self.ollama_cloud_enabled: bool = bool(_ocr.get("enabled", False))
        # Load API key: env var > api_key_file > .env file
        _api_key_env = _ocr.get("api_key_env", "OLLAMA_API_KEY")
        self.ollama_cloud_api_key: str = os.getenv(_api_key_env, "")
        if not self.ollama_cloud_api_key:
            # Try reading from api_key_file
            _api_key_file = _ocr.get("api_key_file", "")
            if _api_key_file:
                try:
                    self.ollama_cloud_api_key = Path(_api_key_file).read_text().strip()
                    print(f"[Pi-Agent] Loaded Ollama Cloud API key from {_api_key_file}")
                except Exception:
                    pass
        if not self.ollama_cloud_api_key:
            # Try .env file in Aether directory
            _dotenv = Path(__file__).parent / ".env"
            if _dotenv.exists():
                try:
                    for line in _dotenv.read_text().splitlines():
                        line = line.strip()
                        if line.startswith(f"{_api_key_env}=") and not line.startswith("#"):
                            self.ollama_cloud_api_key = line.split("=", 1)[1].strip().strip("\"'")
                            break
                except Exception:
                    pass
        self.ollama_cloud_model: str = _ocr.get("model", "gpt-oss:120b-cloud")
        self.ollama_cloud_base_url: str = _ocr.get("base_url", "https://ollama.com").rstrip("/")
        self.ollama_cloud_timeout: int = int(_ocr.get("timeout", 300))
        # Use max timeout for client connection, use per-request timeouts for operations
        self.client = httpx.Client(timeout=httpx.Timeout(connect=30.0, read=300.0, write=30.0, pool=30.0))
        default_state_path = Path(__file__).parent / ".aether_workspace" / "pollinations_pollen_state.json"
        if self.catalog_root:
            default_state_path = self.catalog_root.parent / "Aether" / ".aether_workspace" / "pollinations_pollen_state.json"
        pollen_config = PollinationsPollenConfig.from_dict(
            pollinations,
            default_state_path=default_state_path,
        )
        if not pollen_config.api_key:
            pollen_config.api_key = os.getenv("POLLINATIONS_API_KEY") or os.getenv("OPENAI_API_KEY") or "pk_nxM10AP0L7y8AX1I"
        self.pollen_gate = PollinationsPollenGate(pollen_config, client=self.client)

        # CatalogAnalyzer for reference selection
        self.catalog_analyzer: Optional[CatalogAnalyzer] = None
        if self.catalog_root and self.catalog_root.exists():
            self.catalog_analyzer = CatalogAnalyzer(self.catalog_root)

    def _call_ollama(self, system: str, user: str, timeout: Optional[int] = None) -> str:
        """Dispatch LLM call through 3-tier fallback chain.

        Tier 1: Pollinations (cloud, free, pollen-limited)
        Tier 2: Ollama Cloud (paid, requires OLLAMA_API_KEY)
        Tier 3: Local Ollama (self-hosted, always available if running)

        When use_ollama=True, skip directly to Tier 3.
        When ollama_cloud is enabled, Pollinations 402/429 triggers immediate
        fallback instead of sleeping until reset.
        """
        # If user explicitly wants local Ollama, go straight there
        if self.use_ollama:
            return self._call_ollama_local(system, user, timeout=timeout)

        # Tier 1: Pollinations
        skip_wait = self.ollama_cloud_enabled
        result = self._call_pollinations(system, user, timeout=timeout,
                                         skip_wait_on_depletion=skip_wait)

        # If Pollinations succeeded, return immediately
        if not result.startswith(("[API_ERROR", "[API_TIMEOUT")):
            return result

        # Tier 2: Ollama Cloud (only if enabled and configured)
        if self.ollama_cloud_enabled and self.ollama_cloud_api_key:
            print(f"[Pi-Agent] Pollinations failed ({result[:80]}), falling back to Ollama Cloud")
            cloud_result = self._call_ollama_cloud(system, user, timeout=timeout)
            if not cloud_result.startswith(("[OLLAMA_CLOUD_ERROR", "[OLLAMA_CLOUD_TIMEOUT")):
                return cloud_result
            print(f"[Pi-Agent] Ollama Cloud also failed ({cloud_result[:80]})")
        elif self.ollama_cloud_enabled and not self.ollama_cloud_api_key:
            print("[Pi-Agent] Ollama Cloud enabled but no API key set — skipping to local Ollama")
        elif not self.ollama_cloud_enabled:
            # No fallback configured — return the Pollinations error as-is
            return result

        # Tier 3: Local Ollama
        print("[Pi-Agent] Falling back to local Ollama")
        return self._call_ollama_local(system, user, timeout=timeout)

    def _call_pollinations(self, system: str, user: str, timeout: Optional[int] = None, skip_wait_on_depletion: bool = False) -> str:
        """Call the Pollinations cloud API.

        On 402 (payment required / pollen depleted), waits until the next
        hourly reset then retries. Retries up to 3 times with increasing
        backoff for transient errors.
        """
        request_timeout = timeout or self.timeout
        print(f"[Pi-Agent] → calling Pollinations API (model={self.model}, timeout={request_timeout}s)")

        headers = {
            "Authorization": f"Bearer {self.pollen_gate.api_key}",
            "Content-Type": "application/json"
        }

        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user}
            ],
            "temperature": 0.85,
            "top_p": 0.92
        }
        input_chars = len(system) + len(user)

        # Truncate oversized prompts to avoid 400 Bad Request from Pollinations
        # This is a last-resort safety net — upstream budgeting should keep prompts well under this
        MAX_PROMPT_CHARS = 120000
        if input_chars > MAX_PROMPT_CHARS:
            print(f"[Pi-Agent] Prompt too large ({input_chars} chars), truncating to {MAX_PROMPT_CHARS}")
            user = user[:MAX_PROMPT_CHARS - len(system)] + "\n\n[... truncated for API limit ...]"
            payload["messages"] = [
                {"role": "system", "content": system},
                {"role": "user", "content": user}
            ]
            input_chars = MAX_PROMPT_CHARS
        max_retries = 3

        for attempt in range(max_retries):
            try:
                reservation = self.wait_for_pollinations_pollen(
                    "Pi-Agent LLM request",
                    kind="chat",
                    input_chars=input_chars,
                )
                response = self.client.post(
                    "https://gen.pollinations.ai/v1/chat/completions",
                    headers=headers,
                    json=payload,
                    timeout=request_timeout
                )
                response_json = None
                try:
                    response_json = response.json()
                except Exception:
                    response_json = None
                self.pollen_gate.record_response(
                    response,
                    kind="chat",
                    input_chars=input_chars,
                    reservation=reservation,
                    response_json=response_json,
                )

                if response.status_code in (402, 429):
                    # Pollen depleted — poll every 5 min until it's back
                    # Pollen resets at the top of the hour, we wait until :10
                    self.pollen_gate.mark_depleted_from_response(response)
                    if skip_wait_on_depletion:
                        print("[Pi-Agent] Pollen depleted (402) — skipping wait, falling through to fallback")
                        return "[API_ERROR: Pollen depleted (402) — fallback requested]"
                    wait_until = self.pollen_gate._next_hour_reset(time.time())
                    reset_at = time.strftime("%H:%M:%S", time.localtime(wait_until))
                    wait_minutes = (wait_until - time.time()) / 60
                    print(f"[Pi-Agent] Pollen depleted (402). Waiting {wait_minutes:.1f}min until reset ~{reset_at}, polling every 5min (attempt {attempt+1}/{max_retries})")
                    while time.time() < wait_until:
                        sleep_until = min(wait_until, time.time() + 300)
                        time.sleep(max(60, sleep_until - time.time()))
                        # Try a quick check — if pollen is back, break early
                        try:
                            check = self.client.get("https://pollinations.ai/api/v1/pollen_status",
                                                    headers={"Authorization": f"Bearer {self.pollen_gate.api_key}"},
                                                    timeout=10)
                            if check.status_code == 200:
                                print(f"[Pi-Agent] Pollen restored early!")
                                break
                        except Exception:
                            pass
                    continue  # Retry after waiting

                response.raise_for_status()
                data = response_json if response_json is not None else response.json()
                content = data["choices"][0]["message"]["content"]

                response_preview = content[:500].replace('\n', ' ')
                print(f"[Pi-Agent] ← response ({len(content)} chars)")
                print(f"[Pi-Agent]   {response_preview}...")

                return content

            except httpx.TimeoutException:
                print(f"[Pi-Agent] ← API TIMEOUT after {request_timeout}s (attempt {attempt+1}/{max_retries})")
                if attempt < max_retries - 1:
                    time.sleep(5 * (attempt + 1))
                    continue
                return f"[API_TIMEOUT: Request timed out after {request_timeout}s]"

            except httpx.HTTPStatusError as e:
                if e.response.status_code in (402, 429):
                    # Already handled above, but catch if raise_for_status hits first
                    self.pollen_gate.mark_depleted_from_response(e.response)
                    if skip_wait_on_depletion:
                        print("[Pi-Agent] Pollen depleted (402) — skipping wait, falling through to fallback")
                        return "[API_ERROR: Pollen depleted (402) — fallback requested]"
                    wait_until = self.pollen_gate._next_hour_reset(time.time())
                    reset_at = time.strftime("%H:%M:%S", time.localtime(wait_until))
                    wait_minutes = (wait_until - time.time()) / 60
                    print(f"[Pi-Agent] Pollen depleted (402). Waiting {wait_minutes:.1f}min until reset ~{reset_at}, polling every 5min (attempt {attempt+1}/{max_retries})")
                    while time.time() < wait_until:
                        sleep_until = min(wait_until, time.time() + 300)
                        time.sleep(max(60, sleep_until - time.time()))
                        try:
                            check = self.client.get("https://pollinations.ai/api/v1/pollen_status",
                                                    headers={"Authorization": f"Bearer {self.pollen_gate.api_key}"},
                                                    timeout=10)
                            if check.status_code == 200:
                                print(f"[Pi-Agent] Pollen restored early!")
                                break
                        except Exception:
                            pass
                    continue
                if e.response.status_code == 400:
                    # 400 Bad Request — log response body and retry with truncated prompt
                    resp_body = ""
                    try:
                        resp_body = e.response.text[:500]
                    except Exception:
                        pass
                    print(f"[Pi-Agent] ← 400 Bad Request: {resp_body}")
                    # If prompt is very large, truncate and retry
                    input_size = len(system) + len(user)
                    if input_size > 80000 and attempt < max_retries - 1:
                        truncation = max(40000, 80000 - attempt * 20000)
                        print(f"[Pi-Agent] Prompt too large ({input_size} chars), truncating to {truncation} and retrying")
                        user = user[:truncation] + "\n\n[... truncated for API limit ...]"
                        payload["messages"] = [
                            {"role": "system", "content": system},
                            {"role": "user", "content": user}
                        ]
                        time.sleep(2 * (attempt + 1))
                        continue
                    err_msg = f"400 Bad Request: {resp_body}"
                    print(f"[Pi-Agent] ← API exception: {err_msg}")
                    return f"[API_ERROR: {err_msg}]"
                if e.response.status_code >= 500 and attempt < max_retries - 1:
                    print(f"[Pi-Agent] ← Server error {e.response.status_code}, retrying ({attempt+1}/{max_retries})")
                    time.sleep(5 * (attempt + 1))
                    continue
                err_msg = str(e)
                print(f"[Pi-Agent] ← API exception: {err_msg}")
                return f"[API_ERROR: {err_msg}]"

            except Exception as e:
                err_msg = str(e)
                if hasattr(e, 'response') and e.response:
                    err_msg += f" - {e.response.text}"
                print(f"[Pi-Agent] ← API exception: {type(e).__name__}: {err_msg}")
                return f"[API_ERROR: {err_msg}]"

        return f"[API_ERROR: Max retries ({max_retries}) exhausted]"

    def _call_ollama_local(self, system: str, user: str, timeout: Optional[int] = None) -> str:
        """Call a local Ollama instance via its OpenAI-compatible API.

        If ollama_model is not explicitly set, auto-detects available models.
        Tries models in order: configured model -> cloud model -> first available.
        """
        request_timeout = timeout or self.timeout

        # Determine which model to use: explicit config > auto-detect
        if self.ollama_model:
            models_to_try = [self.ollama_model]
        else:
            # Auto-detect: try cloud model first, then discover local models
            models_to_try = []
            if self.model:
                models_to_try.append(self.model)
            # Try to discover available local models
            try:
                tags_resp = self.client.get(
                    f"{self.ollama_base_url}/api/tags",
                    timeout=10,
                )
                if tags_resp.status_code == 200:
                    tags_data = tags_resp.json()
                    local_models = [m["name"] for m in tags_data.get("models", [])]
                    for m in local_models:
                        if m not in models_to_try:
                            models_to_try.append(m)
            except Exception:
                pass
            if not models_to_try:
                models_to_try = [self.model or "llama3"]

        url = f"{self.ollama_base_url}/v1/chat/completions"

        for model in models_to_try:
            print(f"[Pi-Agent] → calling Ollama (model={model}, url={url}, timeout={request_timeout}s)")
            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user}
                ],
                "temperature": 0.85,
                "top_p": 0.92,
            }

            try:
                response = self.client.post(
                    url,
                    json=payload,
                    timeout=request_timeout,
                )
                # If model not found (404), try next model
                if response.status_code == 404:
                    print(f"[Pi-Agent] ← model '{model}' not found locally, trying next")
                    continue
                response.raise_for_status()
                data = response.json()
                content = data["choices"][0]["message"]["content"]

                # Remember which model worked for future calls
                self.ollama_model = model

                response_preview = content[:500].replace('\n', ' ')
                print(f"[Pi-Agent] ← Ollama response ({len(content)} chars, model={model})")
                print(f"[Pi-Agent]   {response_preview}...")

                return content
            except httpx.TimeoutException:
                print(f"[Pi-Agent] ← Ollama TIMEOUT with model={model} after {request_timeout}s")
                # Don't try other models on timeout — it's a connectivity issue
                return f"[OLLAMA_TIMEOUT: Request timed out after {request_timeout}s]"
            except httpx.HTTPStatusError as e:
                if e.response.status_code == 404:
                    print(f"[Pi-Agent] ← model '{model}' not found locally, trying next")
                    continue
                err_msg = str(e)
                if e.response:
                    err_msg += f" - {e.response.text[:200]}"
                print(f"[Pi-Agent] ← Ollama error: {err_msg}")
                return f"[OLLAMA_ERROR: {err_msg}]"
            except Exception as e:
                err_msg = str(e)
                if hasattr(e, 'response') and e.response:
                    err_msg += f" - {e.response.text}"
                print(f"[Pi-Agent] ← Ollama exception: {type(e).__name__}: {err_msg}")
                return f"[OLLAMA_ERROR: {err_msg}]"

        return f"[OLLAMA_ERROR: No available model found. Tried: {', '.join(models_to_try)}]"

    def _call_ollama_cloud(self, system: str, user: str, timeout: Optional[int] = None) -> str:
        """Call Ollama Cloud API as a fallback when Pollinations is depleted.

        Uses the same OpenAI-compatible /v1/chat/completions endpoint as local
        Ollama, but at the Ollama Cloud host with Bearer auth.
        """
        if not self.ollama_cloud_enabled or not self.ollama_cloud_api_key:
            return "[OLLAMA_CLOUD_ERROR: Ollama Cloud not configured or API key missing]"

        request_timeout = timeout or self.ollama_cloud_timeout
        model = self.ollama_cloud_model
        url = f"{self.ollama_cloud_base_url}/v1/chat/completions"
        print(f"[Pi-Agent] → calling Ollama Cloud (model={model}, timeout={request_timeout}s)")

        headers = {
            "Authorization": f"Bearer {self.ollama_cloud_api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": model,
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user}
            ],
            "temperature": 0.85,
            "top_p": 0.92,
        }

        try:
            response = self.client.post(
                url,
                headers=headers,
                json=payload,
                timeout=request_timeout,
            )
            response.raise_for_status()
            data = response.json()
            content = data["choices"][0]["message"]["content"]

            response_preview = content[:500].replace('\n', ' ')
            print(f"[Pi-Agent] ← Ollama Cloud response ({len(content)} chars)")
            print(f"[Pi-Agent]   {response_preview}...")
            return content
        except httpx.TimeoutException:
            print(f"[Pi-Agent] ← Ollama Cloud TIMEOUT after {request_timeout}s")
            return f"[OLLAMA_CLOUD_TIMEOUT: Request timed out after {request_timeout}s]"
        except Exception as e:
            err_msg = str(e)
            if hasattr(e, 'response') and e.response:
                err_msg += f" - {e.response.text}"
            print(f"[Pi-Agent] ← Ollama Cloud exception: {type(e).__name__}: {err_msg}")
            return f"[OLLAMA_CLOUD_ERROR: {err_msg}]"

