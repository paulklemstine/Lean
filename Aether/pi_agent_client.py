    # Class-level state to cycle through concepts (avoids always picking same one)
    _concept_cycle_index: int = 0

    def _generate_local_concept(
        self,
        domains: List[Dict[str, Any]],
        sorry_targets_list: Optional[List] = None,
        research_context: Optional[str] = None,
        forced_domain: Optional[str] = None,
    ) -> ResearchConcept:
        """Generate a research concept locally without LLM.

        Cycles through sorry_fill, cross-domain bridges, and research arcs
        in a round-robin fashion to maximize diversity.
        """
        from output_organizer import normalize_domain
        import random

        # Determine which type of concept to generate this cycle
        # Mode distribution: balanced across research modes
        # 5% sorry_fill, 25% bridge, 30% arc, 25% discovery, 15% future
        cycle = PiAgentClient._concept_cycle_index
        PiAgentClient._concept_cycle_index += 1
        mode_bucket = cycle % 20  # 0=sorry(1), 1-5=bridge(5), 6-11=arc(6), 12-15=discover(4), 16-19=future(4)

        if mode_bucket == 0:
            mode = "sorry_fill"
        elif mode_bucket <= 5:
            mode = "bridge"
        elif mode_bucket <= 11:
            mode = "arc"
        elif mode_bucket <= 15:
            mode = "discover"
        else:
            mode = "future"

        # sorry_fill is now domain-agnostic — any domain can fill sorry targets
        # Priority 1: sorry_fill on priority targets
        if mode == "sorry_fill" and self.catalog_analyzer:
            sorry_files = self.catalog_analyzer.get_priority_sorry_targets()
            if sorry_files:
                # Round-robin through sorry files instead of always picking [0]
                idx = (cycle // 2) % len(sorry_files)
                target = sorry_files[idx]
                domain = normalize_domain(target.domain or "Shared")

                concept_title = f"{target.declarations[0]}_proof" if target.declarations else f"fill_{Path(target.relative_path).stem}"
                concept_desc = (f"Fill the sorry in {target.relative_path} "
                               f"({target.sorry_count} sorries remaining). "
                               f"Key declarations: {', '.join(target.declarations[:5])}. "
                               f"This advances a known open problem in {domain}.")
                math_framing = f"Complete the proof of {target.declarations[0]} in {target.relative_path}."

                print(f"[Local] sorry_fill target {idx+1}/{len(sorry_files)}: {target.relative_path}")

                return ResearchConcept(
                    title=concept_title,
                    domain=domain,
                    concept_description=concept_desc,
                    mathematical_framing=math_framing,
                    lean_guess="",
                    catalog_references=[target.relative_path],
                    research_mode="sorry_fill",
                    novelty_estimate=0.85,
                    breakthrough_potential=0.90,
                    key_references=target.declarations[:3],
                )

        # Priority 2: Cross-domain bridges from catalog analysis
        # (VISIONARY_BRIDGES removed — bridge selection is now catalog-driven)
        if mode == "bridge" and self.catalog_analyzer:
            bridges = self.catalog_analyzer.find_missing_bridges(limit=20)
            if bridges:
                bridge_idx = cycle % len(bridges)
                b = bridges[bridge_idx]
                # find_missing_bridges returns (domain_a, domain_b, score)
                # tuples — the old dict indexing raised TypeError on every
                # bridge-mode concept generation (audit 2026-08-21).
                d_a, d_b, syn = (b + (0.0,))[:3] if isinstance(b, tuple) else (b.get('domain_a'), b.get('domain_b'), b.get('synonymy', 0.0))
                domain = normalize_domain(d_a)
                concept_title = f"{d_a.lower()}_{d_b.lower()}_bridge"
                concept_desc = f"Construct a bridge between {d_a} and {d_b} leveraging {syn:.1f} synonymy score."
                math_framing = f"Formalize the connection between {d_a} and {d_b} objects."

                # Find files from both domains for context
                refs = []
                all_files = self.catalog_analyzer.scan()
                d_a_files = [f for f in all_files if d_a.lower() in f.relative_path.lower()][:3]
                d_b_files = [f for f in all_files if d_b.lower() in f.relative_path.lower()][:3]
                refs = [f.relative_path for f in (d_a_files + d_b_files)[:6]]

                print(f"[Local] bridge target {bridge_idx+1}/{len(bridges)}: {d_a} -> {d_b} (syn={syn:.1f})")

                return ResearchConcept(
                    title=concept_title,
                    domain=domain,
                    concept_description=concept_desc,
                    mathematical_framing=math_framing,
                    lean_guess="",
                    catalog_references=refs,
                    research_mode="prove",
                    novelty_estimate=0.80 + min(syn/1000, 0.15),
                    breakthrough_potential=0.85 + min(syn/1000, 0.10),
                    key_references=[d_a, d_b],
                )

        # Priority 3: Discovery mode -- explore under-explored catalog territory
        if mode == "discover" and self.catalog_analyzer and hasattr(self.catalog_analyzer, 'find_under_explored_domains'):
            under_explored = self.catalog_analyzer.find_under_explored_domains()
            if under_explored:
                target = under_explored[cycle % len(under_explored)]
                domain = normalize_domain(target["domain"])
                structural = []
                if hasattr(self.catalog_analyzer, 'find_structural_opportunities'):
                    structural = self.catalog_analyzer.find_structural_opportunities()
                struct_for_domain = [s for s in structural if s.get("domain_a") == domain or s.get("domain_b") == domain]
                bridge_desc = ""
                if struct_for_domain:
                    s = struct_for_domain[0]
                    bridge_desc = f" This domain shares {', '.join(s.get('shared_structures', []))} structures with {s.get('domain_b', s.get('domain_a', '?'))} but no bridge exists."

                concept_title = f"{domain.lower()}_breakthrough_discovery"
                concept_desc = (f"Discover deep theorems in {domain} ({target['total_declarations']} declarations, "
                               f"exploration ratio {target.get('exploration_ratio', 0):.1f}). {bridge_desc} "
                               f"Find unexpected structure, prove non-trivial results, open new territory.")
                math_framing = (f"Survey {domain} for under-explored theorems. The catalog has "
                               f"{target['total_declarations']} declarations but few deep results. "
                               f"Look for: (1) structural theorems connecting existing definitions, "
                               f"(2) unexpected isomorphisms between objects in {domain}, "
                               f"(3) algorithmic results that leverage the existing infrastructure.")

                refs = [f.relative_path for f in self.catalog_analyzer.scan() if domain.lower() in f.relative_path.lower()][:4]

                print(f"[Local] discovery target: {domain} (exploration ratio {target.get('exploration_ratio', 0):.1f})")

                return ResearchConcept(
                    title=concept_title,
                    domain=domain,
                    concept_description=concept_desc,
                    mathematical_framing=math_framing,
                    lean_guess="",
                    catalog_references=refs,
                    research_mode="discover",
                    novelty_estimate=0.90,
                    breakthrough_potential=0.92,
                    key_references=refs[:3],
                )

        # Priority 4: Directions from Aristotle's FUTURE_DIRECTIONS reports
        # This is the self-improving feedback loop: Aristotle's own
        # recommendations from past cycles guide the next concept.
        if mode == "future" and self.catalog_analyzer:
            future_dirs_text = self.catalog_analyzer.collect_future_directions(limit=3)
            if future_dirs_text and "No previous future directions" not in future_dirs_text:
                # Extract concrete research directions from the reports
                extracted = self._extract_future_direction_concepts(future_dirs_text, cycle)
                if extracted:
                    print(f"[Local] Using Aristotle's future direction: {extracted.title}")
                    return extracted

        # Priority 5: Visionary research arcs — paradigm-opening mathematics
        # These are NOT incremental extensions. They are bold attempts to open
        # entirely new fields of mathematics.
        # VISIONARY_ARCS removed — research direction selection is now driven
        # entirely by the future directions pool (seed_directions.py + discovered
        # directions). When no future direction is available, fall back to a
        # random selection from the catalog.

        # Fallback: pick a random available direction from the future directions pool
        import random
        from research_memory import FutureDirectionsManager
        fd_manager = FutureDirectionsManager(self.workspace)
        available = [d for d in fd_manager._directions if d.status == "available"]
        if available:
            direction = random.choice(available)
            return ResearchConcept(
                title=direction.title,
                domain=normalize_domain(direction.domains[0] if direction.domains else "Bridges"),
                concept_description=direction.description,
                mathematical_framing=direction.proof_strategy or "",
                lean_guess="",
                catalog_references=[],
                research_mode="discover",
                novelty_estimate=direction.priority_score,
                breakthrough_potential=direction.priority_score,
                key_references=[],
            )
