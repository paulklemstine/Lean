    def classify_file_placement(
        self,
        lean_source: str,
        file_name: str,
        concept: ResearchConcept,
        timeout_override: int = 600,
    ) -> Dict[str, Any]:
        """Classify a Lean file into the correct Catalog location.

        Uses a shorter timeout than other calls since this is called
        per-file during organization and shouldn't block the pipeline.

        Returns dict with domain, subdirectory, target_path,
        is_complete_proof, confidence, reason.
        """
        source_preview = self._smart_truncate(lean_source, max_chars=3000)

        # Get domain files for context
        domain_files = ""
        if self.catalog_analyzer:
            self.catalog_analyzer.scan()
            domain_files = self.catalog_analyzer.get_domain_summary_for_prompt()

        user_prompt = textwrap.dedent(f"""\
            Classify this Lean 4 file into the correct domain in the catalog.

            ## File: {file_name}
            ```lean
            {source_preview}
            ```

            ## Concept Context
            - Domain: {concept.domain}
            - Research Mode: {concept.research_mode}

            ## Catalog Domains
            {domain_files if domain_files else "Algebra, Bridges, Computation, Cryptography, EML, Geometry, Logic, MachineLearning, Physics, Pythagorean, Shared, Speculative, Tropical"}

            Choose the most appropriate domain and subdirectory. The file should go
            where its mathematical content is most naturally at home.

            Respond with JSON:
            {{
              "domain": "DomainName",
              "subdirectory": "SubdirectoryName",
              "target_path": "DomainName/SubdirectoryName/FileName.lean",
              "is_complete_proof": true/false,
              "confidence": 0.0-1.0,
              "reason": "brief explanation"
            }}
        """)

        raw = self._call_ollama(_CLASSIFICATION_SYSTEM_PROMPT, user_prompt, timeout=timeout_override)
        parsed = self._parse_json_response(raw)

        if parsed:
            return {
                "domain": parsed.get("domain", concept.domain),
                "subdirectory": parsed.get("subdirectory", ""),
                "target_path": parsed.get("target_path", f"{concept.domain}/AutoResearch/{file_name}"),
                "is_complete_proof": parsed.get("is_complete_proof", "sorry" not in lean_source),
                "confidence": float(parsed.get("confidence", 0.5)),
                "reason": parsed.get("reason", ""),
            }

        # Fallback: use concept domain with heuristic
        sorry_count = lean_source.count("sorry")
        is_complete = sorry_count == 0
        # Normalize domain to PascalCase Catalog directory name
        from output_organizer import normalize_domain
        normalized_domain = normalize_domain(concept.domain)
        if is_complete:
            return {
                "domain": normalized_domain,
                "subdirectory": "",
                "target_path": f"{normalized_domain}/{file_name}",
                "is_complete_proof": True,
                "confidence": 0.4,
                "reason": f"Fallback: used concept domain ({concept.domain} -> {normalized_domain}), proof appears complete.",
            }
        else:
            return {
                "domain": "Speculative",
                "subdirectory": "AutoResearch",
                "target_path": f"Speculative/AutoResearch/{file_name}",
                "is_complete_proof": False,
                "confidence": 0.4,
                "reason": f"Fallback: proof has {sorry_count} sorries, placed in Speculative.",
            }

    def curate_similar_groups(
        self,
        groups_data: List[List[Dict[str, Any]]],
        timeout: int = 120,
    ) -> Optional[Dict[str, Any]]:
        """LLM curates semantically similar groups of Lean files.

        Returns a dict indicating which files to keep and which to remove.
        """
        system_prompt = (
            "You are a mathematical research curator for the Aether Lean 4 catalog.\n"
            "Your goal is to keep only the best of the best mathematics and shrink the catalog.\n"
            "You are presented with several groups of Lean 4 files. Each group contains semantically "
            "similar files (sharing theorem names, concepts, or name tokens).\n\n"
            "For each group:\n"
            "1. Compare the files. Identify duplicates, near-duplicates, or trivial variants.\n"
            "2. Select the single best/canonical file to KEEP. Prefer files that are sorry-free, "
            "have deeper proofs (using induction, rcases, linarith etc.), and are well-structured.\n"
            "3. Mark all other redundant or duplicate files in the group to REMOVE.\n"
            "4. If a file (even in a single-file group) is mathematically trivial, redundant, or "
            "represents low research value (e.g. basic algebraic/arithmetic identity wrappers), "
            "mark it to REMOVE.\n\n"
            "Output ONLY valid JSON:\n"
            "{\n"
            "  \"keep\": [\"path/to/keep1.lean\", ...],\n"
            "  \"remove\": [\"path/to/remove1.lean\", ...],\n"
            "  \"notes\": \"brief explanation of curation choices\"\n"
            "}"
        )

        user_parts = []
        for idx, group in enumerate(groups_data):
            user_parts.append(f"=== Group {idx + 1} (Size: {len(group)}) ===")
            for f in group:
                sorry_status = "has sorries" if f["sorries"] else "sorry-free"
                proof_style = "deep proofs" if f["deep_proof"] else ("trivial only" if f["trivial_only"] else "mixed")
                user_parts.append(
                    f"Path: {f['path']}\n"
                    f"Theorems: {f['theorems']} | Lines: {f['lines']} | {sorry_status} | Proofs: {proof_style}\n"
                    f"Declarations: {', '.join(f['declarations'][:10])}\n"
                    f"Preview:\n```lean\n{f['content_preview'][:400]}\n```\n"
                )
        user_prompt = "\n".join(user_parts)

        try:
            raw = self._call_ollama(system_prompt, user_prompt, timeout=timeout)
            return self._parse_json_response(raw)
        except Exception as e:
            print(f"[Curate] Pi-Agent curation call failed: {e}")
            return None


