    def select_research_direction(
        self,
        domains: List[Dict[str, Any]],
        recent_history: Optional[List[Dict]] = None,
        research_context: Optional[str] = None,
    ) -> ResearchConcept:
        """Pi-Agent analyzes the Catalog and picks a research direction.

        Args:
            domains: Available research domains with metadata
            recent_history: Recent experiment records
            research_context: Formatted discoveries from ResearchContext.build_discoveries_prompt()

        Returns a ResearchConcept with domain, concept details, catalog references,
        and research_mode chosen by the LLM.
        """
        # Build catalog summary
        catalog_summary = ""
        if self.catalog_analyzer:
            self.catalog_analyzer.scan()
            catalog_summary = self.catalog_analyzer.get_domain_summary_for_prompt()

        # Build exclusion prompt from memory
        exclusion = ""
        if self.memory:
            exclusion = self.memory.build_exclusion_prompt()

        # Build success patterns from memory
        success_patterns = ""
        if self.memory:
            success_patterns = self.memory.build_success_patterns()

        # Build priority sorry targets
        sorry_targets = ""
        if self.catalog_analyzer:
            priority_files = self.catalog_analyzer.get_priority_sorry_targets()
            if priority_files:
                sorry_targets = "\n".join(
                    f"  - {f.relative_path} ({f.sorry_count} sorries, "
                    f"domain: {f.domain}, declarations: {', '.join(f.declarations[:5])})"
                    for f in priority_files[:8]
                )

        # Build domain list for prompt
        domain_descriptions = []
        for d in domains:
            domain_descriptions.append(
                f"- {d.get('id', d.get('name', '?'))}: {d.get('description', d.get('name', '?'))} "
                f"(frontier: {d.get('frontier', 'open')}, "
                f"seed domains: {', '.join(str(x) for x in d.get('seed_domains', d.get('seed_concepts', []))[:3])})"
            )

        user_prompt = textwrap.dedent(f"""\
            Select ONE domain and ONE specific concept for mathematical research.

            Available domains:
            {chr(10).join(domain_descriptions[:8])}

            Sorry targets:
            {sorry_targets if sorry_targets else "None identified"}

            Recent history (avoid repeating):
            {exclusion if exclusion else "First cycle."}

            Context: {research_context[:500] if research_context else "Cold start."}

            IMPORTANT: Choose sorry_fill only for Pythagorean/Number Theory domains. Vary domains.
            Respond with JSON: {{"domain": "...", "concept_title": "...", "concept_description": "...", "mathematical_framing": "...", "lean_guess": "", "catalog_references": ["..."], "research_mode": "prove|sorry_fill", "novelty_estimate": 0.0-1.0, "breakthrough_potential": 0.0-1.0, "key_references": ["..."]}}
        """)

        # Concept generation: try LLM with short timeout, quick fallback to local
        # Cloud models often timeout on large prompts - local generator is faster
        if self.compact:
            # Cloud/compact mode: shorter timeout since we have local fallback
            concept_raw = self._call_ollama(_DIRECTION_SYSTEM_PROMPT, user_prompt, timeout=60)
            parsed = self._parse_json_response(concept_raw) if concept_raw and not concept_raw.startswith("[OLLAMA") else None
        else:
            # Local model: give more time
            concept_raw = self._call_ollama(_DIRECTION_SYSTEM_PROMPT, user_prompt, timeout=120)
            parsed = self._parse_json_response(concept_raw)

        if parsed:
            # If partial parse (from reasoning text), fill in missing fields
            domain = parsed.get("domain", "")
            if domain:
                from output_organizer import normalize_domain
                domain = normalize_domain(domain)
            else:
                domain = domains[0]["id"] if domains else "speculative"
            
            concept = ResearchConcept(
                title=parsed.get("concept_title", parsed.get("title", "unnamed_concept")),
                domain=domain,
                concept_description=parsed.get("concept_description", 
                    f"Research direction from LLM: {parsed.get('domain', 'unknown')} domain"),
                mathematical_framing=parsed.get("mathematical_framing", ""),
                lean_guess=parsed.get("lean_guess", ""),
                catalog_references=parsed.get("catalog_references", []),
                research_mode=parsed.get("research_mode", "prove" if not parsed.get("domain", "") else "sorry_fill" if any("sorry" in d.get("_priority_file","") for d in domains[:3]) else "prove"),
                novelty_estimate=float(parsed.get("novelty_estimate", 0.5) or 0.5),
                breakthrough_potential=float(parsed.get("breakthrough_potential", 0.5) or 0.5),
                key_references=parsed.get("key_references", []),
            )
            # Validate concept quality
            if concept.novelty_estimate >= 0.1 and concept.breakthrough_potential >= 0.1 and not concept.title.startswith("research_concept_"):
                return concept
            # LLM gave garbage — fall through to local generator
            print(f"[Pi-Agent] LLM returned low-quality concept: {concept.title} (n={concept.novelty_estimate:.2f}, b={concept.breakthrough_potential:.2f}). Using local fallback.")

        # LOCAL FALLBACK: Generate concept without LLM using catalog analysis
        # This avoids the 10-minute timeout when cloud models are slow
        print(f"[Pi-Agent] Using local concept generator (LLM unavailable/slow)")
        return self._generate_local_concept(domains, sorry_targets_list=None,
                                            research_context=research_context)

    def _generate_local_concept(
        self,
        domains: List[Dict[str, Any]],
        sorry_targets_list: Optional[List] = None,
        research_context: Optional[str] = None,
    ) -> ResearchConcept:
        """Generate a research concept locally without LLM.
        Uses catalog analysis, sorry targets, and Aristotle Loop
        recommendations to create high-quality concepts deterministically.
        """
