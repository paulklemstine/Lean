"""
R4 -- THE DECISIVE TEST, end to end.  Cost per COLLECTED RELATION, wall clock.

Everything so far compares SMOOTH-HIT RATES.  R4 says that is the wrong
quantity: a scheme that finds smoother candidates but costs more per candidate
is a LOSS.  This script runs the actual samplers end to end and divides WALL-CLOCK
SECONDS by RELATIONS ACTUALLY COLLECTED.

It also runs the ONE configuration that could still win -- conditioning on index
(x mod 2, x mod 4), which costs q = 1 -- as a full factored search rather than a
rate comparison.

Run: python3 r4_e2e.py
"""

from __future__ import annotations

import json
import math
import random
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, "/home/raver1975/lean/factor-scratch/r51exp/relcond")

from relcond_core import (  # noqa: E402
    gen_semiprime, pi, smooth_mask_batch, strata, wilson_lo,
)

OUT = Path(__file__).parent / "results"
OUT.mkdir(exist_ok=True)


def collect(n, g, b, want, rng, mode, k=200000):
    """Collect `want` FB-smooth candidates.  Returns (relations, seconds).

    The cost model here is the honest one for the Stange method: each candidate
    is generated by a modular exponentiation and tested by trial division over
    the whole factor base.  That is what `stange.py::find_relations` does.
    """
    FB = pi(b)
    t0 = time.time()
    found = 0
    seen = set()
    trials = 0
    # TEST COST: the smoothness test is |FB| modulo operations per candidate.
    # Generation cost differs by mode and is measured, not assumed.
    while found < want and trials < k:
        trials += 1
        if mode == "uniform":
            x = rng.randrange(1, n)
        elif mode == "odd_x":
            x = 2 * rng.randrange(0, n // 2) + 1
        elif mode == "even_x":
            x = 2 * rng.randrange(1, n // 2)
        elif mode == "x_mod4_0":
            x = 4 * rng.randrange(0, n // 4)
        else:
            raise ValueError(mode)
        if x in seen:
            continue
        r = pow(g, x, n)
        ok = bool(smooth_mask_batch(np.array([r], dtype=np.int64), b)[0])
        if ok:
            seen.add(x)
            found += 1
    return found, time.time() - t0, trials


def main() -> None:
    print("=" * 78)
    print("R4 -- COST PER COLLECTED RELATION (wall clock, end to end)")
    print("=" * 78)
    print("  Fresh moduli, fresh bases.  Each mode collects the SAME number of")
    print("  relations; the seconds-to-collect is the only fair comparison.")
    b = 2 ** 14
    want = 60
    print(f"\n  B = {b}, pi(B) = {pi(b)}, target = {want} relations per mode\n")
    print(f"  {'seed':>6} {'stratum':<18} {'mode':<12} {'rels':>5} {'sec':>8} "
          f"{'ms/rel':>8} {'trials':>7}")
    rows = []
    for sd in (3101, 3102, 3103):
        rng = random.Random(sd)
        n, p, q = gen_semiprime(40, rng)
        g = 2 + 2 * rng.randrange(0, 6)
        while math.gcd(g, n) != 1:
            g += 1
        st = strata(n, p, q, g)
        for mode in ("uniform", "odd_x", "even_x", "x_mod4_0"):
            f, sec, tr = collect(n, g, b, want, random.Random(sd + 1), mode)
            ms = 1000 * sec / max(f, 1)
            rows.append({"seed": sd, "stratum": st["cell"], "mode": mode,
                         "rels": f, "sec": sec, "ms_per_rel": ms, "trials": tr})
            print(f"  {sd:>6} {st['cell']:<18} {mode:<12} {f:>5} {sec:>8.2f} "
                  f"{ms:>8.1f} {tr:>7}")

    print("\n  COST PER RELATION, pooled by mode (ms/rel), and ratio vs uniform:")
    base = None
    for mode in ("uniform", "odd_x", "even_x", "x_mod4_0"):
        v = [r["ms_per_rel"] for r in rows if r["mode"] == mode]
        pooled = sum(v) / len(v)
        if base is None:
            base = pooled
        print(f"    {mode:<12} {pooled:8.1f} ms/rel   gain = {base/pooled:.4f}"
              f"   ({'baseline' if mode == 'uniform' else ''})")
    print("\n  A gain > 1.00 on `odd_x` / `even_x` / `x_mod4_0` would be the first")
    print("  real win in this round.  Anything <= 1.00 is a LOSS or a null.")

    # and the per-modulus detail, because pooling is forbidden on its own
    print("\n  PER-MODULUS (mandatory -- never pooled alone):")
    for sd in (3101, 3102, 3103):
        u = [r["ms_per_rel"] for r in rows if r["mode"] == "uniform" and r["seed"] == sd]
        line = f"    seed {sd}: "
        for mode in ("odd_x", "even_x", "x_mod4_0"):
            v = [r["ms_per_rel"] for r in rows if r["mode"] == mode and r["seed"] == sd]
            line += f"{mode}={u[0]/v[0]:.4f}  "
        print(line)

    (OUT / "r4_e2e.json").write_text(json.dumps(rows, indent=2, default=str))
    print(f"\nwrote {OUT / 'r4_e2e.json'}")


if __name__ == "__main__":
    main()