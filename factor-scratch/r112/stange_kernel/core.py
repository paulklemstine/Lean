#!/usr/bin/env python3
"""
Stange Q-kernel / linear-form factoring method -- MINIMAL SELF-CONTAINED core.

Method implemented (Stange, "Factoring using multiplicative relations modulo n",
arXiv:2211.06821, Algorithm 2.2, as read in factor-scratch/r48/notes/K_stange.md
and verified against the paper's own worked example in r48):

  1. Factor base FB = primes <= BB, |FB| = b.
  2. Pick g in (Z/N)*.
  3. Find b+c relations  g^{x_j} = prod_i p_i^{f_ij}  (mod N)  with x_j uniform
     in [1,N) -- the paper's own sampler.  Relation j contributes column j.
  4. M is the b x (b+c) integer matrix M[i][j] = f_ij.
  5. Take c independent vectors of the RIGHT KERNEL over Q.
  6. alpha_t = sum_j (b_t)_j * x_j ;  G = gcd(alpha_1..alpha_c).
     G is always a multiple of ord(g) (paper p.4).
  7. Strip prime factors off G to reach ord(g), then gcd -- the standard order
     trick.  A non-trivial gcd is a factor of N.

NOTE ON THE TASK BRIEF'S PARAPHRASE.  The brief describes "a linear form
l(m) = alpha*m + beta over a multiplicative subgroup generated by g, where
g^alpha*m mod N is small", i.e. a subgroup of order l obtained from an l-th
root of unity.  That is NOT Stange's method -- Stange takes NO l-th root of
unity, forms NO subgroup of prescribed order, and there is no "smallness" test
anywhere in Algorithm 2.2.  This file implements the actual published method
(the Q-kernel of the relation matrix), because that is what "the Stange
Q-kernel / linear-form method" names.

VERIFICATION DISCIPLINE (FANOUT_BRIEF.md):
  - ground truth: every reported factor is checked with f*(N//f) == N.
  - negative control: the paper's own example (N=62389=701*89, g=43, B=50,
    b=15, c=10) must fire; plus a planted-order control.
  - every count is seeded and run twice by the driver.

USAGE
    python3 core.py selftest        # negative + positive controls
    python3 core.py run --seed S    # full seeded trial battery, prints JSON
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
import sys
import time
from fractions import Fraction
from math import gcd

from sympy import Matrix, factorint, nextprime


# ---------------------------------------------------------------------------
# n, p, q  (ground truth generated here, never factored by a library)
# ---------------------------------------------------------------------------

def substream(seed: int, *parts) -> random.Random:
    """Deterministic RNG for (seed, parts...).

    DO NOT use `random.Random((seed, label).__hash__())` here: Python randomizes
    str/bytes hashing per process (PYTHONHASHSEED), so a tuple containing a
    string gets a DIFFERENT integer in every interpreter run.  That silently
    destroys reproducibility -- two "same-seed" passes of this battery disagreed
    28/40 vs 33/40 on the first config before this was fixed.  sha256 is stable.
    """
    h = hashlib.sha256()
    h.update(repr((seed,) + parts).encode())
    return random.Random(int.from_bytes(h.digest()[:8], "big"))


def gen_rsa(bits: int, rng: random.Random):
    """Balanced RSA-style modulus: p,q each `bits//2` bits, odd, distinct."""
    half = bits // 2

    def odd_prime() -> int:
        while True:
            v = rng.getrandbits(half) | (1 << (half - 1)) | 1
            q = int(nextprime(v))
            if q % 2 == 1 and q.bit_length() == half:
                return q

    p = odd_prime()
    q = odd_prime()
    while q == p:
        q = odd_prime()
    if p > q:
        p, q = q, p
    N = p * q
    # GROUND TRUTH ASSERTION -- never trust a library here.
    assert p * q == N and 1 < p < q < N
    return N, p, q


# ---------------------------------------------------------------------------
# factor base
# ---------------------------------------------------------------------------

_PRIMES: list[int] = []


def primes_upto(n: int) -> list[int]:
    global _PRIMES
    if _PRIMES and _PRIMES[-1] >= n:
        return [q for q in _PRIMES if q <= n]
    s = bytearray([1]) * (n + 1)
    s[0] = s[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    out = [i for i in range(n + 1) if s[i]]
    _PRIMES = out
    return out


def bbound_for_b(b: int) -> int:
    """b-th prime: the smallest bound whose factor base has exactly b elements."""
    ps = primes_upto(max(1000, 20 * b))
    assert len(ps) >= b
    return ps[b - 1]


def factor_base(bb: int, N: int) -> list[int]:
    """Factor base = primes <= bb that are coprime to N (in case 2 | N)."""
    return [q for q in primes_upto(bb) if gcd(q, N) == 1]


def fb_exponents(r: int, FB: list[int]) -> tuple[list[int], int]:
    exps = [0] * len(FB)
    for i, q in enumerate(FB):
        while r % q == 0:
            r //= q
            exps[i] += 1
        if r == 1:
            break
    return exps, r


# ---------------------------------------------------------------------------
# exact Q-kernel over the relation matrix
# ---------------------------------------------------------------------------

def _denominator(x) -> int:
    """Denominator of a rational entry.  `hasattr(x,'q')` alone is NOT enough:
    fractions.Fraction has no `.q`, so an hasattr check silently truncates
    1/2 -> 0 and destroys Mv = 0."""
    if isinstance(x, int):
        return 1
    if hasattr(x, "q"):          # sympy Rational
        return int(x.q)
    return int(getattr(x, "denominator", 1))


def primitive(v):
    """Algorithm 2.2 step 12: clear denominators, divide out the content,
    orient the first nonzero entry positive."""
    den = 1
    for x in v:
        d = _denominator(x)
        den = den * d // gcd(den, d)
    w = [int(x * den) for x in v]
    gg = 0
    for x in w:
        gg = gcd(gg, abs(x))
    if gg > 1:
        w = [x // gg for x in w]
    for i, x in enumerate(w):
        if x != 0:
            if x < 0:
                w = [-y for y in w]
            break
    return w


def kernel_basis_q(Mrows: list[list[int]]):
    """Right-kernel basis of M over Q, as lists of Fractions."""
    M = Matrix([[int(x) for x in row] for row in Mrows])
    basis = M.nullspace()
    out = [[basis[j][i, 0] for i in range(basis[j].rows)] for j in range(len(basis))]
    return out, int(M.rank())


def matvec_zero(rows, v) -> bool:
    """Independent check that M v == 0.  Guards the truncation trap."""
    for row in rows:
        s = sum(int(c) * Fraction(x) for c, x in zip(row, v))
        if s != 0:
            return False
    return True


# ---------------------------------------------------------------------------
# relation finding -- the paper's own uniform sampler
# ---------------------------------------------------------------------------

def find_relations(N: int, g: int, FB: list[int], need: int, rng: random.Random,
                   trial_cap: int = 20_000_000):
    """Relations g^x = prod p_i^{f_i} (mod N), x uniform in [1,N).

    NOTE: a sequential sampler x = 1,2,3,... is INVALID -- consecutive x
    satisfy exact finite-difference relations that manufacture a spurious
    kernel with G = 0.  Uniform random x is the paper's sampler; we use only it.
    """
    rels: list[tuple[list[int], int]] = []
    seen: set[int] = set()
    trials = 0
    while len(rels) < need:
        trials += 1
        if trials > trial_cap:
            raise RuntimeError("relation finding stalled")
        x = rng.randrange(1, N)
        if x in seen:
            continue
        r = pow(g, x, N)
        exps, rem = fb_exponents(r, FB)
        if rem == 1:
            seen.add(x)
            rels.append((exps, x))
    return rels, trials


def build_M(rels, b):
    """b x (b+c): row i is factor-base prime i's exponents across all relations."""
    return [[rels[j][0][i] for j in range(len(rels))] for i in range(b)]


# ---------------------------------------------------------------------------
# order strip + gcd
# ---------------------------------------------------------------------------

def factor_from_multiple(Mmult: int, g: int, N: int):
    """Mmult is a multiple of ord(g): strip prime factors down to ord(g), then
    take the standard gcd.  Returns a non-trivial factor of N or None."""
    M_ = abs(int(Mmult))
    if M_ == 0:
        return None
    for pp in _prime_factors(M_):
        while M_ % pp == 0:
            h = M_ // pp
            if pow(g, h, N) == 1:
                M_ = h
            else:
                break
    if M_ % 2 == 0:
        v = pow(g, M_ // 2, N)
        for cand in (v - 1, v + 1):
            f = gcd(cand, N)
            if 1 < f < N:
                return f
    return None


_PRIMEFACT_CACHE: dict[int, list[int]] = {}


def _prime_factors(n: int) -> list[int]:
    """Distinct prime factors.  sympy factorint is exact-proven (Pollard rho +
    deterministic Miller-Rabin bases), and at our sizes (<= ~10^3 bits) it is
    instant.  Cached: `run` strips the same G repeatedly."""
    if n in _PRIMEFACT_CACHE:
        return _PRIMEFACT_CACHE[n]
    if n <= 1:
        _PRIMEFACT_CACHE[n] = []
        return []
    out = sorted(int(q) for q in factorint(n))
    _PRIMEFACT_CACHE[n] = out
    return out


# ---------------------------------------------------------------------------
# ground-truth order helpers (used ONLY for diagnosis, never for factoring)
# ---------------------------------------------------------------------------

def _order(a: int, m: int) -> int:
    """ord_m(a) for PRIME m, by stripping factors of m-1.  Requires the truth
    (m prime) -- it is a diagnostic, never on the factoring path."""
    e = m - 1
    for q in _prime_factors(m - 1):
        while e % q == 0 and pow(a, e // q, m) == 1:
            e //= q
    return e


# ---------------------------------------------------------------------------
# one full trial
# ---------------------------------------------------------------------------

def one_trial(N: int, p: int, q: int, b: int, c: int, rng: random.Random,
              trial_cap: int = 20_000_000) -> dict:
    BB = bbound_for_b(b)
    FB = factor_base(BB, N)
    assert len(FB) == b, (len(FB), b)

    g = rng.randrange(2, N)
    while gcd(g, N) != 1:
        g = rng.randrange(2, N)

    t0 = time.time()
    rels, trials = find_relations(N, g, FB, b + c, rng, trial_cap)
    Mrows = build_M(rels, b)
    K, rank = kernel_basis_q(Mrows)

    alpha = []
    for v in K[:c]:
        pv = primitive(v)
        assert matvec_zero(Mrows, pv), "kernel vector does not annihilate M"
        alpha.append(sum(pv[j] * rels[j][1] for j in range(len(rels))))
    G = 0
    for a in alpha:
        G = gcd(G, abs(a))

    factor = factor_from_multiple(G, g, N) if G else None

    # ---- ground truth check: factor is verified by multiplying back to N ----
    verified = False
    if factor is not None and 1 < factor < N:
        verified = (factor * (N // factor) == N)

    # ---- diagnosis (uses p,q -- measurement only, NOT part of the method) ----
    op = _order(g % p, p)
    oq = _order(g % q, q)
    from math import lcm
    ordg = lcm(op, oq)
    v2p = (op & -op).bit_length() - 1
    v2q = (oq & -oq).bit_length() - 1
    h = (G // ordg) if (G and ordg and G % ordg == 0) else None

    return {
        "b": b, "c": c, "rank": rank, "dimK": len(K),
        "rel_trials": trials, "G": G, "ord_g": ordg,
        "h": h, "v2_op": v2p, "v2_oq": v2q,
        "v2_differ": bool(v2p != v2q),
        "alpha_zero": sum(1 for a in alpha if a == 0),
        "factor": factor, "verified": verified,
        "secs": round(time.time() - t0, 3),
    }


# ---------------------------------------------------------------------------
# self-test / negative control
# ---------------------------------------------------------------------------

def selftest() -> bool:
    ok = True

    def check(name, cond, detail=""):
        nonlocal ok
        if not cond:
            ok = False
        print(f"  [{'PASS' if cond else 'FAIL'}] {name} {detail}")

    print("T1 ground-truth generator: N == p*q, balanced")
    rng = random.Random(1)
    N, p, q = gen_rsa(40, rng)
    check("T1", p * q == N and 1 < p < q < N and abs(p.bit_length() - q.bit_length()) <= 1,
          f"(N={N})")

    print("T2 truncation trap: primitive() must preserve Mv == 0 on rational data")
    # M = [[0,5,1],[3,8,4]] has the kernel span(-4/5,-1/5,1) -- genuinely
    # rational, so a truncating primitive() would be caught.
    M2 = [[0, 5, 1], [3, 8, 4]]
    K2, _ = kernel_basis_q(M2)
    check("T2a", len(K2) == 1, f"dim={len(K2)}")
    any_frac = any(_denominator(x) > 1 for v in K2 for x in v)
    check("T2b", any_frac, "(rational entries present -> test is not vacuous)")
    check("T2c", all(matvec_zero(M2, primitive(v)) for v in K2), "(all annihilate M)")
    naive = [int(x) for x in K2[0]]
    check("T2d", not matvec_zero(M2, naive),
          f"(naive int() truncation DOES break Mv=0: naive={naive})")

    print("T3 fb_exponents round-trips")
    FB = factor_base(60, 10 ** 9 + 7)
    e, rem = fb_exponents(2 ** 5 * 3 ** 2 * 5, FB)
    check("T3", rem == 1 and e[:3] == [5, 2, 1], f"(rem={rem})")

    print("T4 POSITIVE CONTROL -- the paper's own worked example")
    # Stange p.5-7: N = 62389 = 701*89, g = 43, B = 50, b = 15, c = 10,
    # multiple 15400 -> gcd(51174-1, 62389) = 701.
    f = factor_from_multiple(15400, 43, 62389)
    check("T4a", f == 701, f"(got {f}, want 701)")
    check("T4b", f is not None and f * (62389 // f) == 62389, "(multiplies back to N)")

    print("T5 NEGATIVE CONTROL -- the harness must fire on the paper's own config")
    # N = 62389 = 701*89, g = 43, B = 50, b = 15, c = 10 (Stange p.5-7).
    # NOTE: the expected rate here is NOT 1.0.  Per r48 (U_stange_improve.md)
    # any method ending "strip to ord(g), gcd" scores 20/27 = 0.7407, the
    # classical order-finding constant, because success is exactly
    # P(v2(ord_p g) != v2(ord_q g)).  So the control asserts the harness FIRES
    # (a clear majority), and separately checks the rate against 20/27.
    fired = 0
    T = 40
    v2law = 0
    for s in range(T):
        rr = random.Random(1000 + s)
        r = one_trial(62389, 701, 89, b=15, c=10, rng=rr)
        fired += bool(r["verified"])
        v2law += (r["verified"] == r["v2_differ"])
    rate = fired / T
    check("T5a harness fires", fired >= int(0.6 * T), f"({fired}/{T} = {rate:.3f})")
    z = (fired - T * 20 / 27) / math.sqrt(T * (20 / 27) * (7 / 27))
    check("T5b rate matches 20/27", abs(z) < 3.0, f"(z={z:+.2f} vs P=20/27)")
    check("T5c success == v2-law", v2law == T, f"({v2law}/{T})")

    print("T6 NEGATIVE CONTROL -- must NOT invent a factor from a random N")
    bogus = 0
    for s in range(200):
        rr = random.Random(9000 + s)
        Nn, _, _ = gen_rsa(40, rr)
        ff = factor_from_multiple(rr.randrange(1, Nn), rr.randrange(2, Nn), Nn)
        if ff is not None and not (1 < ff < Nn and ff * (Nn // ff) == Nn):
            bogus += 1
    check("T6", bogus == 0, f"({bogus}/200 unverified factors reported)")

    print("T7 factor_from_multiple(2*ord) fires iff v2(ord_p) != v2(ord_q)  [the 20/27 law]")
    rr = random.Random(77)
    agree = dis = 0
    for s in range(120):
        Nn, pp, qq = gen_rsa(60, rr)
        gg = rr.randrange(2, Nn)
        while gcd(gg, Nn) != 1:
            gg = rr.randrange(2, Nn)
        op, oq = _order(gg % pp, pp), _order(gg % qq, qq)
        from math import lcm
        og = lcm(op, oq)
        ff = factor_from_multiple(2 * og, gg, Nn)
        got = ff is not None and ff * (Nn // ff) == Nn
        pred = ((op & -op) != (oq & -oq))
        agree += got == pred
        dis += got != pred
    check("T7", dis == 0, f"({agree} agree / {dis} disagree with the v2 law)")

    print("T8 _prime_factors is exact (reconstructs its input)")
    for m in (15400, 62388, 1, 2**61 - 1, 999983 * 1000003):
        got = _prime_factors(m)
        prod = 1
        for q in got:
            while prod * q <= m and m % (prod * q) == 0:
                prod *= q
        check(f"T8[{m}]", prod == m, f"(factors={got[:4]})")

    print("T9 DETERMINISM: the same seed must give the same RNG stream")
    ra, rb = substream(20261004, "x"), substream(20261004, "x")
    a_ = [ra.randrange(10 ** 9) for _ in range(5)]
    b_ = [rb.randrange(10 ** 9) for _ in range(5)]
    check("T9", a_ == b_ and len(set(a_)) == 5, f"(stream {a_})")
    # different labels must NOT collide (else the battery is self-correlated)
    s1 = substream(7, "cfgA").random()
    s2 = substream(7, "cfgB").random()
    check("T9b", s1 != s2, "(distinct labels -> distinct substreams)")

    print("\nSELFTEST", "ALL PASS" if ok else "FAILURES PRESENT")
    return ok


