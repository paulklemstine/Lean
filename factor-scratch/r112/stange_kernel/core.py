CONFIGS = [
    # (label, N bits, b, c, trials)
    ("2^20_b15_c10", 20, 15, 10, 40),
    ("2^26_b8_c5",   26,  8,  5, 40),
    ("2^30_b12_c10", 30, 12, 10, 30),
    ("2^40_b20_c10", 40, 20, 10, 25),
]


def run(seed: int, configs=None, out=None) -> dict:
    configs = configs or CONFIGS
    results = {"seed": seed, "configs": []}
    tot_ver = tot_trials = 0
    for label, bits, b, c, T in configs:
        rng = substream(seed, label)
        recs = []
        for _ in range(T):
            N, p, q = gen_rsa(bits, rng)
            try:
                recs.append(one_trial(N, p, q, b, c, rng))
            except RuntimeError as e:
                recs.append({"error": str(e), "b": b, "c": c})
        good = [r for r in recs if r.get("verified")]
        bad = [r for r in recs if not r.get("verified")]
        tot_ver += len(good)
        tot_trials += len(recs)
        hs = [r["h"] for r in good if r.get("h") is not None]
        agree = sum(1 for r in recs if r.get("verified") == r.get("v2_differ")
                    and r.get("h") is not None)
        cmp_n = sum(1 for r in recs if r.get("h") is not None)
        summary = {
            "label": label, "bits": bits, "b": b, "c": c,
            "trials": len(recs), "verified": len(good),
            "rate": round(len(good) / max(1, len(recs)), 4),
            "h_eq_1": sum(1 for x in hs if x == 1),
            "h_max": max(hs) if hs else None,
            "median_secs": sorted(r["secs"] for r in recs if "secs" in r)[len(recs) // 2]
            if recs else None,
            "total_secs": round(sum(r.get("secs", 0) for r in recs), 1),
            "verified_iff_v2differ": f"{agree}/{cmp_n}",
            "alpha_zero_events": sum(r.get("alpha_zero", 0) for r in recs),
        }
        results["configs"].append(summary)
        print(f"{label:16s} verified {len(good):3d}/{len(recs):3d} = {summary['rate']:.3f}"
              f"  h=1: {summary['h_eq_1']}  max_h: {summary['h_max']}"
              f"  v2-law {summary['verified_iff_v2differ']}"
              f"  {summary['total_secs']}s", flush=True)
    results["total_verified"] = tot_ver
    results["total_trials"] = tot_trials
    results["total_rate"] = round(tot_ver / max(1, tot_trials), 4)
    print(f"TOTAL verified {tot_ver}/{tot_trials} = {results['total_rate']:.4f}")
    if out:
        with open(out, "w") as f:
            json.dump(results, f, indent=2)
    return results


def diagnose(seed: int, bits: int, b: int, c: int, T: int) -> dict:
    """What separates success from failure?

    The r48 correction says the Q-kernel is ALGEBRAICALLY ERASED before the gcd:
    the stripper lands exactly on ord(g), so success reduces to the classical
    order-finding law  P(v2(ord_p g) != v2(ord_q g)) = 20/27, independent of the
    relation set, b, c and n.  This measures whether that is what we see.
    """
    rng = substream(seed, "diag", bits, b, c)
    rows = []
    for _ in range(T):
        N, p, q = gen_rsa(bits, rng)
        rows.append(one_trial(N, p, q, b, c, rng))
    ver = sum(r["verified"] for r in rows)
    v2match = sum(r["verified"] == r["v2_differ"] for r in rows)
    h1 = sum(r["h"] == 1 for r in rows)
    # is h (the Q-kernel index) predictive of anything at all?
    tab = {}
    for r in rows:
        k = r["h"] if r["h"] is not None else "None"
        tab.setdefault(k, [0, 0])
        tab[k][0] += r["verified"]
        tab[k][1] += 1
    out = {
        "seed": seed, "bits": bits, "b": b, "c": c, "trials": T,
        "verified": ver, "rate": round(ver / T, 4),
        "h_eq_1": h1, "h_eq_1_rate": round(h1 / T, 4),
        "verified_iff_v2differ": f"{v2match}/{T}",
        "p_v2_by_verified": {
            "verified": sorted(r["v2_op"] for r in rows if r["verified"]),
            "failed": sorted(r["v2_op"] for r in rows if not r["verified"]),
        },
        "success_rate_by_h": {str(k): f"{v[0]}/{v[1]}" for k, v in sorted(tab.items())},
    }
    print(json.dumps(out, indent=2))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["selftest", "run", "diagnose"])
    ap.add_argument("--seed", type=int, default=20261004)
    ap.add_argument("--out", default=None)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--bits", type=int, default=26)
    ap.add_argument("--b", type=int, default=8)
    ap.add_argument("--c", type=int, default=5)
    ap.add_argument("--trials", type=int, default=200)
    a = ap.parse_args()
    if a.cmd == "selftest":
        sys.exit(0 if selftest() else 1)
    if a.cmd == "diagnose":
        diagnose(a.seed, a.bits, a.b, a.c, a.trials)
        return
    cfgs = [(l, b, bb, c, max(4, t // 4)) for (l, b, bb, c, t) in CONFIGS] if a.quick else None
    run(a.seed, cfgs, a.out)


if __name__ == "__main__":
    main()