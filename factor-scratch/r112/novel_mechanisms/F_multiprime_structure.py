"""
CANDIDATE F -- "N has extra algebraic structure" constructions: is a random
RSA modulus accidentally of a special form that factors by a NON-general
method (Cunningham-style algebraic factorisation, Aurifeuilian, etc.)?

THE MECHANISM (different from every axis in the closed corpus).  Every closed
axis attacks a GENERIC semiprime.  But a large fraction of real RSA moduli
are generated by constrained prime generation (p,q close, special residues,
p-1 smooth, etc.) and are factorable by a formula rather than an algorithm.
Claim: at a measurable rate, N = pq with random-looking p,q nonetheless has
a polynomial-time non-generic factorisation.

FALSIFIER (cheapest possible): if the algebraic-formula attacks succeed at
the rate predicted by the SIZE of the special set -- which for a 2048-bit
modulus is ~2^{-64} or smaller -- the direction is closed as a factoring
method and is only a note about key hygiene.

This is the "kill in 30 seconds" candidate: it either finds a rate far above
prediction (interesting) or confirms the prediction (closed).
"""
import json, random, itertools
from math import gcd
from sympy import factorint, isprime, nextprime
from common112 import gen_semiprime, verified_factor


def try_algebraic(N, p, q):
    """Non-generic factorisation routes, all polynomial-time formulas."""
    routes = {}
    # 1. Cunningham / perfect-power: N = d^k
    for k in range(2, 40):
        r = round(N ** (1.0 / k))
        for cand in (r - 1, r, r + 1):
            if cand > 1 and cand ** k == N:
                routes["perfect_power_k%d" % k] = cand
    # 2. |p - q| small (Fermat) -> measured, closed as < N^(1/4)
    # 3. p-1 or q-1 smooth enough for Pollard p-1 at tiny bound
    for pr in (p, q):
        m = pr - 1
        for pp in (2, 3, 5, 7, 11, 13):
            while m % pp == 0:
                m //= pp
        if m == 1:
            routes["smooth_m1_p"] = pr
    # 4. Aurifeuilian: N = a^4 + 4b^4 factors as (a^2-2ab+2b^2)(a^2+2ab+2b^2)
    r = round(N ** 0.25)
    for a in range(max(1, r - 3), r + 4):
        for b in range(1, 6):
            if a ** 4 + 4 * b ** 4 == N:
                routes["aurifeuilian"] = a
    # 5. quadratic-field: N = x^2 + D y^2 with tiny D  (Cornacchia input)
    for D in range(1, 20):
        y = round((N / D) ** 0.5)
        for yy in range(max(1, y - 2), y + 3):
            r2 = N - D * yy * yy
            if r2 > 0:
                x = round(r2 ** 0.5)
                for xx in range(max(0, x - 2), x + 3):
                    if xx * xx + D * yy * yy == N:
                        g = gcd(xx, N)
                        if 1 < g < N:
                            routes["cornacchia_D%d" % D] = g
    return routes


def main():
    out = dict(cells=[])
    ntrials = 300
    hits = 0
    for seed in range(1, ntrials + 1):
        p, q, N = gen_semiprime(256, seed, beta=0.5)
        r = try_algebraic(N, p, q)
        if r:
            hits += 1
            out["cells"].append(dict(seed=seed, routes=r))
    out["ntrials"] = ntrials
    out["hits"] = hits
    # Stated prediction BEFORE the count: special forms at 256 bits have
    # density <= 2^-64; observing 0 is the predicted outcome.
