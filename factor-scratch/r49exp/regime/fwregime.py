# ---------------------------------------------------------------------------
# zeta
# ---------------------------------------------------------------------------
def zeta(k: int) -> float:
    """Riemann zeta at integer k >= 2, as a float."""
    if k <= 1:
        raise ValueError("zeta(k) needs k > 1")
    if k == 2:
        return math.pi ** 2 / 6.0
    if k <= 200:
        return float(mp.zeta(k))
    return 1.0 + 2.0 ** -k + 3.0 ** -k + 4.0 ** -k


def zeta_hat(K: int = 4000) -> float:
    """zhat = prod_{i=2}^{inf} zeta(i)^{-1}  (F&W Proposition 2.5). >= 0.434."""
    p = 1.0
    for i in range(2, K + 1):
        p /= zeta(i)
    return p


# ---------------------------------------------------------------------------
# EXACT regime arithmetic.  n >= 8 b^{b/2}  <=>  n^2 >= 64 b^b
# ---------------------------------------------------------------------------
def in_stange_regime(b: int, n: int) -> bool:
    """Stange p.4: n >= 8 b^{b/2}.   EXACT, integer only, no floats.

    b^{b/2} may be irrational (odd b), so we square both sides:
        n >= 8 b^{b/2}  <=>  n^2 >= 64 b^b     (n > 0, b > 0).
    Using floats here is exactly the `int(n**(1/3))` family of bugs.
    """
    assert b >= 1 and n >= 1
    return n * n >= 64 * (b ** b)


def threshold_int(b: int, two_window: bool = False) -> int:
    """Smallest integer n admitted at base size b -- EXACT.

    two_window=False : n >= 8 b^{b/2}                      -> n^2 >= 64 b^b
    two_window=True  : n >= 64 b^2 (b+1) b^{b/2}          -> n^2 >= (64 b^2(b+1))^2 b^b
    """
    assert b >= 1
    v = 64 * (b ** b)
    if two_window:
        w = 64 * b * b * (b + 1)
        v = w * w * (b ** b)
    r = math.isqrt(v)
    return r if r * r >= v else r + 1


def in_two_window_regime(b: int, n: int) -> bool:
    """Honest SINGLE-window version: all 2b+1 relations from one window."""
    assert b >= 1 and n >= 1
    w = 64 * b * b * (b + 1)
    return n * n >= (w * w) * (b ** b)


def b_max(n: int, regime: str = "stange") -> int:
    """Largest b admitted at modulus n.  EXACT integer binary search."""
    if regime not in ("stange", "two-window"):
        raise ValueError(f"unknown regime {regime!r}")
    check = in_stange_regime if regime == "stange" else in_two_window_regime
    lo, hi = 1, 2
    while check(hi, n):
        lo = hi
        hi *= 2
        if hi > 1 << 24:
            raise RuntimeError("b_max did not bracket; n too large?")
    while lo + 1 < hi:                       # invariant: check(lo), not check(hi)
        mid = (lo + hi) // 2
        if check(mid, n):
            lo = mid
        else:
            hi = mid
    return lo


def b_max_table(ns, regime: str = "stange"):
    return [(n, b_max(n, regime), b_max(n, regime) + 1) for n in ns]


