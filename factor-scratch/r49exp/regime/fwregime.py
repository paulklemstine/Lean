# F&W Theorem 1.1 lower bound alpha_n
# ---------------------------------------------------------------------------
def alpha_n(ndim: int) -> float:
    """alpha_n from F&W Theorem 1.1 (p.2), image-verified formula.

        alpha_n = ( prod_{i=2}^{n+1} zeta(i)^{-1} - 1/4 )
                * prod_{k=0}^{n-1} ( 1 - n^{k/2}(4 n^{n/2}+1)^k / (4 n^{n/2}-1)^n )

    n^{n/2} is irrational for odd ndim, so this is evaluated in 60-digit
    mpmath arithmetic.  That is far tighter than the paper's own printed
    values, and selftest T1 checks the result against those values -- which
    is what validates my reading of the mangled pdftotext of this formula.
    """
    assert ndim >= 1
    # factor 1: the finite-quotient step, needs ndim+1 samples.
    # (prod_{i=2}^{ndim+1} zeta(i)^{-1} - 1/4); the 1/4 is the total-variation
    # slack of Lemma 2.6.  The partial product >= zhat (factors are < 1).
    p1 = mp.one
    for i in range(2, ndim + 2):
        p1 /= mp.zeta(i)
    f1 = p1 - mp.mpf(1) / 4

    # factor 2: the full-rank-sublattice step -- the one carrying 8 n^{n/2}.
    NN = mp.power(ndim, mp.mpf(ndim) / 2)
    den = mp.power(4 * NN - 1, ndim)
    f2 = mp.one
    for k in range(ndim):
        num = mp.power(ndim, mp.mpf(k) / 2) * mp.power(4 * NN + 1, k)
        f2 *= 1 - num / den
    return float(f1 * f2)


def cor23_factor_exact(ndim: int) -> Fraction:
    """EXACT rational factor-2 of alpha_n for even ndim, returned as a pair.

    Returned as ((a, b), meaning a + b*sqrt(ndim)) so that the odd-k terms
    n^{k/2} = n^{(k-1)/2} sqrt(n) stay exact.  Selftest T1b uses this to
    confirm the 60-digit mpmath evaluation rather than trusting it.
    """
    assert ndim >= 1 and ndim % 2 == 0, "exact path is for EVEN ndim"
    NN = ndim ** (ndim // 2)                    # n^{n/2}, an integer
    den = Fraction((4 * NN - 1) ** ndim)
    a, bb = Fraction(1), Fraction(0)             # factor 2 = a + bb*sqrt(ndim)
    for k in range(ndim):
        c = Fraction((4 * NN + 1) ** k) / den    # (4n^{n/2}+1)^k / (4n^{n/2}-1)^n
        if k % 2 == 0:
            num = (Fraction(ndim ** (k // 2)) * c, Fraction(0))
        else:
            num = (Fraction(0), Fraction(ndim ** (k // 2)) * c)
        # (a + b r)(1 - (u + v r)) with r^2 = ndim
        #   real part: a(1-u) - b*v*ndim
        #   sqrt part: a*(-v) + b(1-u)
        # NOTE the -b*v*ndim term: dropping it silently loses a factor of
        # ndim and made this path disagree with mpmath by 1e-6 at n=4.
        a, bb = (a * (1 - num[0]) - bb * num[1] * ndim,
                 a * (-num[1]) + bb * (1 - num[0]))
    return (a, bb)


