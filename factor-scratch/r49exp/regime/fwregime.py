def b_needed(logN: float) -> float:
    """b = L_n(1/2,1) = exp( (log n)^{1/2} (log log n)^{1/2} )   (beta = 1).

    Stange p.4 sets Lx(alpha,beta) = exp((beta+o(1)) (log x)^alpha (log log x)^{1-alpha}).
    logN = log(n).
    """
    return math.exp(math.sqrt(logN) * math.sqrt(math.log(logN)))


# ---------------------------------------------------------------------------
# exact integer roots (the `int(n**(1/3))` hazard, made explicit)
# ---------------------------------------------------------------------------
def iroot(n: int, k: int) -> int:
    """EXACT floor(n^{1/k}).  n >= 0, k >= 1."""
    if n < 0:
        raise ValueError("iroot needs n >= 0")
    if k == 1:
        return n
    if n < 2:
        return n
    hi = 1 << ((n.bit_length() + k - 1) // k + 1)
    lo = 1
    while lo + 1 < hi:
        mid = (lo + hi) // 2
        if mid ** k <= n:
            lo = mid
        else:
            hi = mid
    return lo


