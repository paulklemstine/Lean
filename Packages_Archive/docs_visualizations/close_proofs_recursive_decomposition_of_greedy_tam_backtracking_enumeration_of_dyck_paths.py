from typing import List, Tuple


def enumerate_dyck_paths(n: int) -> List[Tuple[int, ...]]:
    """Enumerate all Dyck paths of semilength n.

    A path is a sequence of +1 (up) and -1 (down) steps with n of each whose
    partial sums never go negative. Generated by depth-first backtracking that
    prunes any prefix violating the boundary constraint.
    The number of paths returned is the Catalan number C_n.
    Complexity: O(C_n * n) time to materialize all paths.
    """
    results: List[Tuple[int, ...]] = []

    def backtrack(prefix: Tuple[int, ...], ups: int, downs: int) -> None:
        if ups == n and downs == n:
            results.append(prefix)
            return
        if ups < n:                       # extend by an up-step
            backtrack(prefix + (1,), ups + 1, downs)
        if downs < ups:                   # a down-step keeps height >= 0
            backtrack(prefix + (-1,), ups, downs + 1)

    backtrack((), 0, 0)
    return results
