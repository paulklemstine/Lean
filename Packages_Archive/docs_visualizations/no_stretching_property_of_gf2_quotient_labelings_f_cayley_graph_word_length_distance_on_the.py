from collections import deque
from typing import Dict, List, Tuple

BitVec = Tuple[int, ...]


def cayley_distances(k: int, generators: List[BitVec]) -> Dict[BitVec, int]:
    """Word-length distances from the identity in the Cayley graph on (Z/2)^k
    generated by `generators`, computed by BFS over the 2^k group elements."""
    gens = [g for g in generators if any(g)]
    start: BitVec = tuple(0 for _ in range(k))
    dist: Dict[BitVec, int] = {start: 0}
    q: deque[BitVec] = deque([start])
    while q:
        x = q.popleft()
        for g in gens:
            y = tuple(a ^ b for a, b in zip(x, g))
            if y not in dist:
                dist[y] = dist[x] + 1
                q.append(y)
    return dist


def cayley_distance(a: BitVec, b: BitVec, cayley_from_id: Dict[BitVec, int]) -> int:
    """Distance between two group elements = word length of their difference."""
    return cayley_from_id[tuple(x ^ y for x, y in zip(a, b))]
