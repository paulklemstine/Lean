class PatternOracle:
    """
    The Pattern Oracle: discovers regularities in numerical sequences.
    O² = O — patterns of patterns are just patterns (idempotent).
    """

    @staticmethod
    def find_gcd_pattern(sequence: List[int]) -> Dict[str, Any]:
        """Analyze GCD structure of a sequence."""
        gcds = []
        for i in range(len(sequence)):
            for j in range(i + 1, len(sequence)):
                gcds.append(math.gcd(sequence[i], sequence[j]))
        if not gcds:
            return {"pattern": "trivial", "data": sequence}
        return {
            "pattern": "gcd_structure",
            "max_gcd": max(gcds),
            "min_gcd": min(gcds),
            "coprime_fraction": sum(1 for g in gcds if g == 1) / len(gcds),
            "gcd_frequencies": {g: gcds.count(g) for g in set(gcds)},
        }

    @staticmethod
    def find_modular_pattern(sequence: List[int], moduli: List[int] = None) -> Dict:
        """Analyze residue patterns mod various bases."""
        if moduli is None:
            moduli = [2, 3, 4, 5, 6, 7, 8, 9, 10, 12]
        patterns = {}
        for m in moduli:
            residues = [x % m for x in sequence]
            unique_residues = sorted(set(residues))
            patterns[m] = {
                "residues": unique_residues,
                "missing": sorted(set(range(m)) - set(residues)),
                "counts": {r: residues.count(r) for r in unique_residues},
                "uniform": max(residues.count(r) for r in unique_residues) -
                           min(residues.count(r) for r in unique_residues) <= 1,
            }
        return patterns

    @staticmethod
    def find_growth_pattern(sequence: List[int]) -> Dict[str, Any]:
        """Analyze the growth rate of a sequence."""
        if len(sequence) < 3:
            return {"growth": "insufficient_data"}
        ratios = [sequence[i+1] / sequence[i] for i in range(len(sequence)-1)
                  if sequence[i] != 0]
        diffs = [sequence[i+1] - sequence[i] for i in range(len(sequence)-1)]
        second_diffs = [diffs[i+1] - diffs[i] for i in range(len(diffs)-1)]
        result = {
            "first_differences": diffs,
            "second_differences": second_diffs,
        }
        if ratios:
            result["ratio_mean"] = np.mean(ratios)
            result["ratio_std"] = np.std(ratios)
            if np.std(ratios) < 0.01:
                result["growth_type"] = "geometric"
                result["common_ratio"] = np.mean(ratios)
            elif np.std(second_diffs) < 0.01 and len(second_diffs) > 0:
                result["growth_type"] = "polynomial"
                result["degree"] = 2 if abs(np.mean(second_diffs)) > 0.01 else 1
            else:
                result["growth_type"] = "irregular"
        return result


