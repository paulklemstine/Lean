#  THE NUMBER THEORY ORACLE — Knows Primes and Divisibility
# ═══════════════════════════════════════════════════════════════════════════════

class NumberTheoryOracle:
    """
    The Number Theory Oracle: consults on primes, divisibility, and arithmetic.
    Its truth set = {n : the oracle's prediction about n is correct}.
    """

    @staticmethod
    @lru_cache(maxsize=10000)
    def is_prime(n: int) -> bool:
        if n < 2: return False
        if n < 4: return True
        if n % 2 == 0 or n % 3 == 0: return False
        i = 5
        while i * i <= n:
            if n % i == 0 or n % (i + 2) == 0: return False
            i += 6
        return True

    @staticmethod
    def prime_factorization(n: int) -> Dict[int, int]:
        if n <= 1: return {}
        factors = {}
        d = 2
        while d * d <= n:
            while n % d == 0:
                factors[d] = factors.get(d, 0) + 1
                n //= d
            d += 1
        if n > 1:
            factors[n] = factors.get(n, 0) + 1
        return factors

    @staticmethod
    def euler_totient(n: int) -> int:
        result = n
        p = 2
        temp_n = n
        while p * p <= temp_n:
            if temp_n % p == 0:
                while temp_n % p == 0:
                    temp_n //= p
                result -= result // p
            p += 1
        if temp_n > 1:
            result -= result // temp_n
        return result

    @staticmethod
    def sum_of_divisors(n: int) -> int:
        total = 0
        for d in range(1, int(math.isqrt(n)) + 1):
            if n % d == 0:
                total += d
                if d != n // d:
                    total += n // d
        return total

    @staticmethod
    def is_perfect(n: int) -> bool:
        return n > 1 and NumberTheoryOracle.sum_of_divisors(n) == 2 * n

    @staticmethod
    def pythagorean_triples(limit: int) -> List[Tuple[int, int, int]]:
        """Generate primitive Pythagorean triples via the stereographic parametrization."""
        triples = []
        for m in range(2, limit):
            for n in range(1, m):
                if math.gcd(m, n) == 1 and (m - n) % 2 == 1:
                    a = m*m - n*n
                    b = 2*m*n
                    c = m*m + n*n
                    triples.append(tuple(sorted([a, b, c])))
        return sorted(set(triples))

    @classmethod
    def goldbach_check(cls, n: int) -> Optional[Tuple[int, int]]:
        """Check Goldbach's conjecture for even n: find p, q prime with p + q = n."""
        if n < 4 or n % 2 != 0:
            return None
        for p in range(2, n // 2 + 1):
            if cls.is_prime(p) and cls.is_prime(n - p):
                return (p, n - p)
        return None


