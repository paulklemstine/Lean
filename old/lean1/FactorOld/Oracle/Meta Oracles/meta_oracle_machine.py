class DataAnalyzer:
    """
    The data analyzer: the oracle's reflective eye.
    Studies experimental results, computes statistics, finds meta-patterns.
    """

    def __init__(self, kb: KnowledgeBase, pattern_oracle: PatternOracle):
        self.kb = kb
        self.po = pattern_oracle

    def analyze_experiment(self, result: ExperimentResult,
                            hypothesis: Hypothesis) -> Dict[str, Any]:
        """Analyze an experiment result and update hypothesis status."""
        total = result.test_cases
        if total == 0:
            return {"verdict": "no_data"}

        pass_rate = result.passed / total
        analysis = {
            "hypothesis_id": hypothesis.id,
            "pass_rate": pass_rate,
            "test_cases": total,
            "runtime_ms": result.runtime_ms,
        }

        if result.failed > 0:
            hypothesis.status = OracleStatus.REFUTED
            hypothesis.counterexample = result.counterexample
            hypothesis.confidence = 0.0
            analysis["verdict"] = "REFUTED"
            analysis["counterexample"] = result.counterexample
            self.kb._log(f"✗ {hypothesis.name}: REFUTED (counterexample: {result.counterexample})")
        elif pass_rate == 1.0 and total >= 10:
            hypothesis.status = OracleStatus.VALIDATED
            hypothesis.confidence = min(0.95, 1.0 - 1.0 / total)
            hypothesis.evidence_for = result.passed
            analysis["verdict"] = "VALIDATED"
            self.kb._log(f"● {hypothesis.name}: VALIDATED ({total} tests passed)")
        elif pass_rate == 1.0:
            hypothesis.status = OracleStatus.TESTED
            hypothesis.confidence = pass_rate * 0.7
            hypothesis.evidence_for = result.passed
            analysis["verdict"] = "TESTED (limited data)"
        else:
            hypothesis.status = OracleStatus.TESTED
            hypothesis.confidence = pass_rate * 0.5
            analysis["verdict"] = "PARTIALLY_SUPPORTED"

        return analysis

    def find_cross_patterns(self, hypotheses: List[Hypothesis]) -> List[str]:
        """Find patterns across multiple hypotheses."""
        insights = []
        validated = [h for h in hypotheses if h.status == OracleStatus.VALIDATED]
        refuted = [h for h in hypotheses if h.status == OracleStatus.REFUTED]

        # Domain clustering
        domains = defaultdict(list)
        for h in validated:
            domains[h.domain].append(h)

        for domain, hs in domains.items():
            if len(hs) >= 2:
                common_tags = set.intersection(*(h.tags for h in hs))
                if common_tags:
                    insights.append(
                        f"🔗 [{domain}] {len(hs)} validated hypotheses share tags: {common_tags}"
                    )

        # Parent-child success patterns
        for h in validated:
            if h.parent and h.parent in self.kb.hypotheses:
                parent = self.kb.hypotheses[h.parent]
                if parent.status == OracleStatus.VALIDATED:
                    insights.append(
                        f"🌳 Validated chain: {parent.name} → {h.name}"
                    )

        if refuted:
            insights.append(
                f"⚠️  {len(refuted)} hypotheses refuted — consider what they have in common"
            )

        return insights


