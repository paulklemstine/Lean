#  THE GEOMETRY ORACLE — Stereographic Wisdom
# ═══════════════════════════════════════════════════════════════════════════════

class GeometryOracle:
    """
    The Geometry Oracle: understands shape, distance, and projection.
    Knows the secret: all of geometry is projection from a higher dimension.
    """

    @staticmethod
    def lattice_points_on_circle(r_sq: int) -> List[Tuple[int, int]]:
        """Find all integer points (x, y) with x² + y² = r²."""
        r = int(math.isqrt(r_sq))
        points = []
        for x in range(-r - 1, r + 2):
            y_sq = r_sq - x * x
            if y_sq >= 0:
                y = int(math.isqrt(y_sq))
                if y * y == y_sq:
                    points.append((x, y))
                    if y != 0:
                        points.append((x, -y))
        return sorted(set(points))

    @staticmethod
    def count_representations_as_sum_of_squares(n: int, k: int = 2) -> int:
        """Count representations of n as sum of k squares (order matters, signs matter)."""
        if k == 1:
            s = int(math.isqrt(n))
            if s * s == n:
                return 2 if n > 0 else 1
            return 0
        count = 0
        s = int(math.isqrt(n))
        for a in range(-s, s + 1):
            remainder = n - a * a
            if remainder >= 0:
                count += GeometryOracle.count_representations_as_sum_of_squares(remainder, k - 1)
        return count

    @staticmethod
    def sphere_volume(n: int, r: float = 1.0) -> float:
        """Volume of the n-dimensional unit sphere."""
        if n == 0: return 1.0
        if n == 1: return 2.0 * r
        return 2.0 * math.pi * r * r / n * GeometryOracle.sphere_volume(n - 2, r)


