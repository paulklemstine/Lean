class ExperimentEngine:
    """
    The experiment engine: the oracle's empirical arm.
    Tests hypotheses against computational evidence.
    """

    def __init__(self, kb: KnowledgeBase):
        self.kb = kb
        self.results: List[ExperimentResult] = []

    def run_experiment(self, hypothesis: Hypothesis,
                       test_inputs: List[Any] = None) -> ExperimentResult:
        """Run a hypothesis through its predicate on test inputs."""
        if hypothesis.predicate is None:
            return ExperimentResult(
                hypothesis_id=hypothesis.id,
                test_cases=0, passed=0, failed=0,
                counterexample=None, runtime_ms=0,
                data={"error": "No predicate defined"}
            )

        if test_inputs is None:
            test_inputs = self._generate_test_inputs(hypothesis)

        start = time.time()
        passed = 0
        failed = 0
        counterexample = None

        for inp in test_inputs:
            try:
                result = hypothesis.predicate(inp)
                if result:
                    passed += 1
                else:
                    failed += 1
                    if counterexample is None:
                        counterexample = inp
            except Exception as e:
                failed += 1
                if counterexample is None:
                    counterexample = (inp, str(e))

        elapsed = (time.time() - start) * 1000

        exp_result = ExperimentResult(
            hypothesis_id=hypothesis.id,
            test_cases=len(test_inputs),
            passed=passed,
            failed=failed,
            counterexample=counterexample,
            runtime_ms=elapsed,
        )
        self.results.append(exp_result)
        return exp_result

    def _generate_test_inputs(self, hypothesis: Hypothesis) -> List[Any]:
        """Generate appropriate test inputs based on hypothesis domain."""
        # Scale up test size for re-tested hypotheses
        scale = 2 if hypothesis.status == OracleStatus.TESTED else 1

        if hypothesis.domain == "number_theory":
            if "goldbach" in hypothesis.tags and "weak" not in hypothesis.tags:
                return list(range(4, 502 * scale, 2))  # Even numbers
            elif "primes" in hypothesis.tags:
                return [100, 500, 1000, 5000]
            elif "totient" in hypothesis.tags or "mobius" in hypothesis.tags:
                return list(range(1, 201 * scale))
            elif "perfect" in hypothesis.tags:
                return [1000, 10000, 50000]
            elif "squares" in hypothesis.tags:
                return list(range(0, 201 * scale))
            elif "mersenne" in hypothesis.tags:
                return [20, 40]
            elif "mertens" in hypothesis.tags:
                return list(range(2, 201 * scale))
            elif "divisor" in hypothesis.tags:
                return [50, 100, 500, 1000]
            elif "weak" in hypothesis.tags:
                return list(range(7, 200 * scale, 2))  # odd numbers
            else:
                return list(range(1, 101 * scale))
        elif hypothesis.domain == "geometry":
            if "lattice" in hypothesis.tags and "circle" in hypothesis.tags:
                return list(range(1, 101 * scale))
            elif "gauss" in hypothesis.tags:
                return list(range(5, 50 * scale, 2))
            elif "stereographic" in hypothesis.tags:
                return list(range(2, 15 * scale))
            elif "three" in hypothesis.tags:
                return list(range(0, 201 * scale))
            else:
                return list(range(1, 51 * scale))
        elif hypothesis.domain == "algebra":
            return list(range(5, 20 * scale))
        else:
            return list(range(1, 51 * scale))


