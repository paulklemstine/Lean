# ═══════════════════════════════════════════════════════════════════════════════

class StereographicLens:
    """
    The oracle's stereographic lens: maps between flat space ℝⁿ and the sphere Sⁿ.

    The key insight: problems in ℝⁿ become rotations on Sⁿ.
    The composition of lift → rotate → project is a Möbius transformation,
    which is a single matrix multiplication in projective coordinates.
    """

    @staticmethod
    def lift_to_sphere(t: np.ndarray) -> np.ndarray:
        """Inverse stereographic projection: ℝⁿ → Sⁿ (from south pole)."""
        t = np.atleast_1d(t).astype(float)
        norm_sq = np.sum(t ** 2)
        denom = 1.0 + norm_sq
        sphere_coords = np.append(2.0 * t / denom, (norm_sq - 1.0) / denom)
        return sphere_coords

    @staticmethod
    def project_to_flat(p: np.ndarray) -> np.ndarray:
        """Stereographic projection: Sⁿ → ℝⁿ (from north pole)."""
        n = len(p) - 1
        if abs(1.0 - p[-1]) < 1e-15:
            return np.full(n, np.inf)  # North pole maps to infinity
        return p[:n] / (1.0 - p[-1])

    @staticmethod
    def oracle_transform(p: np.ndarray, axis: int = 0) -> np.ndarray:
        """
        Oracle consultation on the sphere: reflection through an axis.
        This is the "mirror" that reveals hidden structure.
        """
        result = p.copy()
        result[axis] = -result[axis]
        return result

    @classmethod
    def consult(cls, query: np.ndarray, transform=None) -> np.ndarray:
        """Full oracle consultation: lift → transform → project."""
        on_sphere = cls.lift_to_sphere(query)
        if transform is None:
            transform = cls.oracle_transform
        transformed = transform(on_sphere)
        return cls.project_to_flat(transformed)


