def fig8_approximation():
    """Sigmoid approximation by Sheffer expressions."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    x = np.linspace(-8, 8, 500)

    # Sheffer approximations to sigmoid
    ax = axes[0]
    ax.plot(x, sigmoid(x), 'k-', linewidth=3, label='S(x) = sigmoid')

    # Simple Sheffer approximations
    # S(x) ≈ (σ(x+c) - σ(x-c))/(2c) for large c (differences approximate derivative)
    for c in [0.5, 1, 2, 4]:
        approx = (softplus(x + c) - softplus(x - c)) / (2 * c)
        ax.plot(x, approx, '--', linewidth=1.5, alpha=0.7,
                label=f'(σ(x+{c})-σ(x-{c}))/{2*c}')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Approximating Sigmoid with Sheffer Expressions')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Error analysis
    ax = axes[1]
    for c in [0.5, 1, 2, 4]:
        approx = (softplus(x + c) - softplus(x - c)) / (2 * c)
        error = np.abs(approx - sigmoid(x))
        ax.semilogy(x, error + 1e-16, linewidth=1.5, label=f'c = {c}')
    ax.set_xlabel('x'); ax.set_ylabel('|Approximation - S(x)|')
    ax.set_title('Approximation Error (log scale)')
    ax.legend(); ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('fig8_approximation.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Figure 8: Approximation saved")


def superscript(n):
    """Unicode superscript for small integers."""
    sups = {0: '⁰', 1: '¹', 2: '²', 3: '³', 4: '⁴', 5: '⁵'}
    return sups.get(n, f'^{n}')


