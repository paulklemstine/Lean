import numpy as np
import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec

# Core functions
def softplus(x):
    """σ(x) = log(1 + eˣ), numerically stable."""
    return np.where(x > 20, x, np.log1p(np.exp(np.clip(x, -500, 20))))

def sigmoid(x):
    """S(x) = eˣ/(1+eˣ) = 1/(1+e⁻ˣ), numerically stable."""
    return np.where(x > 0, 1 / (1 + np.exp(-x)), np.exp(x) / (1 + np.exp(x)))

def softplus_iter(n, x):
    """σⁿ(x) = log(n + eˣ) (closed form)."""
    return np.log(n + np.exp(x))

def sheffer_pair(a, b, x):
    """f(x) = (a-b)·σ(x) + b·x — achieves derivative limits (a, b)."""
    return (a - b) * softplus(x) + b * x

def sheffer_pair_deriv(a, b, x):
    """f'(x) = (a-b)·S(x) + b."""
    return (a - b) * sigmoid(x) + b


def fig1_fundamentals():
    """Softplus and sigmoid fundamentals."""
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))

    x = np.linspace(-6, 6, 500)

    # Softplus
    ax = axes[0]
    ax.plot(x, softplus(x), 'b-', linewidth=2, label='σ(x) = log(1+eˣ)')
    ax.plot(x, np.maximum(x, 0), 'r--', linewidth=1.5, alpha=0.6, label='ReLU = max(x,0)')
    ax.plot(x, x, 'g:', linewidth=1.5, alpha=0.6, label='y = x')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Softplus: Smooth Approximation to ReLU')
    ax.legend(); ax.grid(True, alpha=0.3)
    ax.set_ylim(-1, 7)

    # Sigmoid
    ax = axes[1]
    ax.plot(x, sigmoid(x), 'b-', linewidth=2, label='S(x) = σ\'(x)')
    ax.axhline(y=1, color='r', linestyle='--', alpha=0.5, label='y = 1')
    ax.axhline(y=0, color='g', linestyle='--', alpha=0.5, label='y = 0')
    ax.axhline(y=0.5, color='purple', linestyle=':', alpha=0.5, label='y = 1/2')
    ax.set_xlabel('x'); ax.set_ylabel('S(x)')
    ax.set_title('Logistic Sigmoid (Derivative of Softplus)')
    ax.legend(); ax.grid(True, alpha=0.3)

    # Identity decomposition
    ax = axes[2]
    ax.plot(x, softplus(x), 'b-', linewidth=2, label='σ(x)')
    ax.plot(x, softplus(-x), 'r-', linewidth=2, label='σ(-x)')
    ax.plot(x, softplus(x) - softplus(-x), 'g-', linewidth=2.5, label='σ(x) - σ(-x) = x')
    ax.plot(x, x, 'k--', linewidth=1, alpha=0.5, label='y = x')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Identity Decomposition: x = σ(x) - σ(-x)')
    ax.legend(); ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('fig1_fundamentals.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Figure 1: Fundamentals saved")


def fig2_barriers():
    """The four-barrier system."""
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))

    x = np.linspace(-5, 10, 500)

    # Barrier 1: Lipschitz
    ax = axes[0, 0]
    ax.plot(x, softplus(x), 'b-', linewidth=2, label='σ(x) — Lipschitz(1)')
    ax.plot(x, np.exp(x), 'r-', linewidth=2, label='eˣ — NOT Lipschitz')
    ax.plot(x, x**2, 'g-', linewidth=2, label='x² — NOT Lipschitz')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Barrier 1: Lipschitz Continuity')
    ax.legend(); ax.grid(True, alpha=0.3)
    ax.set_ylim(-5, 30)

    # Barrier 2: Analyticity
    ax = axes[0, 1]
    ax.plot(x, softplus(x), 'b-', linewidth=2, label='σ(x) — real analytic')
    ax.plot(x, np.maximum(x, 0), 'r--', linewidth=2, label='ReLU — NOT analytic at 0')
    ax.plot(x, np.abs(x), 'g--', linewidth=2, label='|x| — NOT analytic at 0')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Barrier 2: Real Analyticity')
    ax.legend(); ax.grid(True, alpha=0.3)

    # Barrier 3: Derivative convergence
    ax = axes[1, 0]
    ax.plot(x, sigmoid(x), 'b-', linewidth=2, label="σ'(x) = S(x) → 1 at +∞")
    ax.plot(x, np.cos(x), 'r-', linewidth=2, label="sin'(x) = cos(x) — oscillates")
    ax.axhline(y=1, color='b', linestyle='--', alpha=0.3)
    ax.axhline(y=0, color='b', linestyle='--', alpha=0.3)
    ax.set_xlabel('x'); ax.set_ylabel("f'(x)")
    ax.set_title('Barrier 3: Derivative Convergence at ±∞')
    ax.legend(); ax.grid(True, alpha=0.3)

    # Barrier 4: Asymptotic linear structure
    ax = axes[1, 1]
    ax.plot(x, softplus(x) - x, 'b-', linewidth=2, label='σ(x) - x → 0')
    sp2 = softplus_iter(2, x)
    ax.plot(x, sp2 - x, 'r-', linewidth=2, label='σ²(x) - x → log(2)')
    ax.axhline(y=0, color='b', linestyle='--', alpha=0.3)
    ax.axhline(y=np.log(2), color='r', linestyle='--', alpha=0.3)
    ax.set_xlabel('x'); ax.set_ylabel('f(x) - x')
    ax.set_title('Barrier 4: Asymptotic Linear Structure')
    ax.legend(); ax.grid(True, alpha=0.3)

    plt.suptitle('The Four-Barrier System: ShefferAlg ⊆ Cω ∩ Lip ∩ DerivConv ∩ AsympLin',
                 fontsize=14, fontweight='bold', y=1.02)
    plt.tight_layout()
    plt.savefig('fig2_barriers.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Figure 2: Barriers saved")


def fig3_orbits():
    """Iterated softplus orbits."""
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))

    x = np.linspace(-3, 5, 500)

    # Orbit trajectories
    ax = axes[0]
    for n in range(6):
        y = softplus_iter(n, x) if n > 0 else x
        ax.plot(x, y, linewidth=2, label=f'σ{superscript(n)}(x)')
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Iterated Softplus Orbits')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Orbit merging
    ax = axes[1]
    starts = [-5, -2, 0, 2, 5]
    ns = range(20)
    for x0 in starts:
        vals = [softplus_iter(n, x0) if n > 0 else x0 for n in ns]
        ax.plot(ns, vals, 'o-', markersize=3, label=f'x₀ = {x0}')
    ax.plot(ns, [np.log(n+1) for n in ns], 'k--', linewidth=1.5,
            alpha=0.5, label='log(n+1)')
    ax.set_xlabel('Iteration n'); ax.set_ylabel('σⁿ(x₀)')
    ax.set_title('Orbit Merging: All Orbits → log(n)')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Orbit addition theorem
    ax = axes[2]
    ks = [1, 2, 3, 5, 10]
    ns = np.arange(0, 15)
    for k in ks:
        vals = [np.log(n + k) for n in ns]
        ax.plot(ns, vals, 'o-', markersize=4, label=f'σⁿ(log {k}) = log(n+{k})')
    ax.set_xlabel('n'); ax.set_ylabel('σⁿ(log k)')
    ax.set_title('Orbit Addition: σⁿ(log k) = log(n + k)')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('fig3_orbits.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Figure 3: Orbits saved")


def fig4_derivative_pairs():
    """Q39 resolution: derivative limit pairs."""
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))

    x = np.linspace(-8, 8, 500)

    # Example functions
    ax = axes[0]
    pairs = [(2, -1), (1, 0), (0.5, 0.5), (-1, 2), (3, 3)]
    for a, b in pairs:
        ax.plot(x, sheffer_pair(a, b, x), linewidth=2, label=f'(a,b)=({a},{b})')
    ax.set_xlabel('x'); ax.set_ylabel('f(x)')
    ax.set_title('Sheffer Functions with Prescribed Slopes')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Their derivatives
    ax = axes[1]
    for a, b in pairs:
        ax.plot(x, sheffer_pair_deriv(a, b, x), linewidth=2, label=f'→ ({a},{b})')
    ax.set_xlabel('x'); ax.set_ylabel("f'(x)")
    ax.set_title('Derivatives: f\'(x) → a at +∞, b at -∞')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Coverage of R²
    ax = axes[2]
    a_vals = np.linspace(-3, 3, 15)
    b_vals = np.linspace(-3, 3, 15)
    A, B = np.meshgrid(a_vals, b_vals)
    ax.scatter(A.flatten(), B.flatten(), c='blue', s=20, alpha=0.6)
    ax.set_xlabel('L₊ (limit at +∞)'); ax.set_ylabel('L₋ (limit at -∞)')
    ax.set_title('Q39 Resolved: All (L₊, L₋) ∈ ℝ² Achievable')
    ax.set_aspect('equal')
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('fig4_derivative_pairs.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Figure 4: Derivative pairs saved")


