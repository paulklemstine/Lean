def fig6_growth_decomposition():
    """Orbit dynamics: derivative formula and growth decomposition."""
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))

    x = np.linspace(-5, 5, 500)

    # Derivative formula
    ax = axes[0]
    for n in [1, 2, 3, 5, 10]:
        deriv = np.exp(x) / (n + np.exp(x))
        ax.plot(x, deriv, linewidth=2, label=f"(σ{superscript(n)})'(x) = eˣ/(n+eˣ)")
    ax.axhline(y=1, color='k', linestyle='--', alpha=0.3)
    ax.axhline(y=0, color='k', linestyle='--', alpha=0.3)
    ax.set_xlabel('x'); ax.set_ylabel("(σⁿ)'(x)")
    ax.set_title('Derivative of Iterated Softplus')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Growth decomposition
    ax = axes[1]
    ns = np.arange(1, 50)
    x0 = 0
    total = np.log(ns + np.exp(x0))
    dominant = np.log(ns)
    correction = np.log(1 + np.exp(x0) / ns)
    ax.plot(ns, total, 'b-', linewidth=2, label='σⁿ(0) = log(n+1)')
    ax.plot(ns, dominant, 'r--', linewidth=1.5, label='log(n) — dominant')
    ax.plot(ns, correction, 'g--', linewidth=1.5, label='log(1+1/n) — correction')
    ax.set_xlabel('n'); ax.set_ylabel('Value')
    ax.set_title('Growth Decomposition: σⁿ(x) = log(n) + log(1+eˣ/n)')
    ax.legend(fontsize=8); ax.grid(True, alpha=0.3)

    # Convexity
    ax = axes[2]
    ax.plot(x, softplus(x), 'b-', linewidth=2, label='σ(x) — convex')
    # Show convexity with tangent lines
    for x0 in [-3, 0, 3]:
        y0 = softplus(x0)
        slope = sigmoid(x0)
        tangent = y0 + slope * (x - x0)
        ax.plot(x, tangent, '--', linewidth=1, alpha=0.5)
    ax.set_xlabel('x'); ax.set_ylabel('y')
    ax.set_title('Softplus is Convex (σ" > 0)')
    ax.legend(); ax.grid(True, alpha=0.3)
    ax.set_ylim(-1, 8)

    plt.tight_layout()
    plt.savefig('fig6_dynamics.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Figure 6: Dynamics saved")


