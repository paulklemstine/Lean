def modular_sieve(N, max_d=None):
    """Use modular arithmetic to navigate efficiently.
    
    Key insight: We want a² + b² + c² ≡ 0 (mod N) or (mod p) for factor p.
    This constrains which quadruples can reveal factors.
    """
    if max_d is None:
        max_d = 3 * N
    
    print(f"\n{'='*60}")
    print(f"Modular Sieve Factoring for N = {N}")
    print(f"{'='*60}")
    
    factors = set()
    
    # Precompute quadratic residues mod N
    qr_N = set()
    for x in range(N):
        qr_N.add((x * x) % N)
    
    print(f"  Quadratic residues mod {N}: {sorted(qr_N)}")
    print(f"  Number of QRs: {len(qr_N)} out of {N}")
    
    # Find triples (r_a, r_b, r_c) mod N such that r_a² + r_b² + r_c² ≡ 0 (mod N)
    target_triples = []
    for ra in range(N):
        for rb in range(ra, N):
            for rc in range(rb, N):
                if (ra*ra + rb*rb + rc*rc) % N == 0:
                    target_triples.append((ra, rb, rc))
    
    print(f"  Target residue triples: {len(target_triples)}")
    if len(target_triples) <= 20:
        for t in target_triples[:10]:
            print(f"    {t}")
    
    # For each target residue triple, search for actual quadruples
    for ra, rb, rc in target_triples[:50]:  # Limit search
        for ka in range(max(1, ra), min(max_d, N * 5), N):
            a = ka if ka % N == ra else ra
            if a == 0 and ra == 0:
                a = 0
            elif a % N != ra:
                a = ra
            for kb_mult in range(0, 5):
                b = rb + kb_mult * N
                for kc_mult in range(0, 5):
                    c = rc + kc_mult * N
                    d_sq = a*a + b*b + c*c
                    d = int(math.isqrt(d_sq))
                    if d > 0 and d*d == d_sq:
                        channels = peel_channels(a, b, c, d, N)
                        for name, g in channels:
                            if 1 < g < N:
                                factors.add(g)
                                print(f"  ✓ Factor {g} via ({a},{b},{c},{d}), channel {name}")
                                return factors
    
    return factors

