def factoring_energy(a, b, c, d, N):
    """The factoring energy: how far from factoring N.
    
    E = min over all peel channels of (distance to nontrivial GCD).
    Lower energy = closer to factoring.
    """
    channels = peel_channels(a, b, c, d, N)
    max_g = max(g for _, g in channels)
    if max_g == N:
        return float('inf')  # Trivial
    if max_g > 1:
        return 0  # Found a factor!
    # Energy based on how close GCDs are to being nontrivial
    return min(abs(d - leg) % N for leg in [a, b, c] if abs(d - leg) > 0)

def gravitational_descent(N, max_steps=10000):
    """Navigate the quadruple tree using energy minimization.
    
    Start from quadruples near N and descend toward lower energy states.
    """
    print(f"\n{'='*60}")
    print(f"Gravitational Descent for N = {N}")
    print(f"{'='*60}")
    
    # Start with quadruples whose hypotenuse is near N
    best_energy = float('inf')
    best_quad = None
    factors = set()
    
    # Generate starting quadruples around N
    for offset in range(-int(math.sqrt(N)), int(math.sqrt(N)) + 1):
        d = N + offset
        if d <= 0:
            continue
        for a in range(0, d):
            if a*a > d*d:
                break
            for b in range(a, d):
                rem = d*d - a*a - b*b
                if rem < 0:
                    break
                c = int(math.isqrt(rem))
                if c >= b and c*c == rem:
                    E = factoring_energy(a, b, c, d, N)
                    if E == 0:
                        channels = peel_channels(a, b, c, d, N)
                        for name, g in channels:
                            if 1 < g < N:
                                factors.add(g)
                        print(f"  ✓ Factor found via ({a},{b},{c},{d}): {factors}")
                        return factors
                    if E < best_energy:
                        best_energy = E
                        best_quad = (a, b, c, d)
    
    if best_quad:
        print(f"  Best quadruple: {best_quad}, energy = {best_energy}")
    
    return factors

