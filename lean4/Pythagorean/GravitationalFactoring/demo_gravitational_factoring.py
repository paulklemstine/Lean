def ktuple_factor(N, k=4, max_hyp=None):
    """Factor N using k-dimensional Pythagorean tuples.
    
    A k-tuple: x₁² + x₂² + ... + xₖ = d²
    Gives k peel channels and C(k,2) cross-collision pairs.
    """
    if max_hyp is None:
        max_hyp = 2 * N
    
    print(f"\n{'='*60}")
    print(f"{k}-Tuple Factoring for N = {N}")
    print(f"Channels: {k} peel + {k*(k-1)//2} cross = {k + k*(k-1)//2} total")
    print(f"{'='*60}")
    
    factors = set()
    
    # For k=4: use Lagrange four-square theorem
    if k == 4:
        # Every N has a representation as sum of 4 squares
        decomp = four_square_decomposition(N)
        if decomp:
            a, b, c, d_val = decomp
            # N = a² + b² + c² + d²
            # This IS a Pythagorean 5-tuple with hypotenuse √N... 
            # but we need integer hypotenuse.
            # Instead, use N² = (Na)² + ... trick or direct quadruple search
            pass
    
    # Direct search for k-tuples with hypotenuse d related to N
    # For efficiency, search with d = N (the target itself)
    d = N
    d_sq = d * d
    
    # Try random k-tuples summing to d²
    for trial in range(min(10000, N * 10)):
        legs = []
        remaining = d_sq
        for i in range(k - 1):
            max_val = int(math.isqrt(remaining))
            if max_val == 0:
                break
            val = random.randint(0, max_val)
            legs.append(val)
            remaining -= val * val
        
        if remaining >= 0:
            last = int(math.isqrt(remaining))
            if last * last == remaining:
                legs.append(last)
                if len(legs) == k:
                    # Found a valid k-tuple! Extract factors
                    for j, leg in enumerate(legs):
                        g_minus = math.gcd(abs(d - leg), N)
                        g_plus = math.gcd(abs(d + leg), N)
                        if 1 < g_minus < N:
                            factors.add(g_minus)
                            print(f"  ✓ Factor {g_minus} via leg[{j}]={leg}, d-leg={d-leg}")
                            return factors
                        if 1 < g_plus < N:
                            factors.add(g_plus)
                            print(f"  ✓ Factor {g_plus} via leg[{j}]={leg}, d+leg={d+leg}")
                            return factors
    
    return factors

