def four_square_decomposition(n):
    """Find a representation n = a² + b² + c² + d² using greedy + backtracking."""
    if n == 0:
        return (0, 0, 0, 0)
    
    for a in range(int(math.isqrt(n)), -1, -1):
        rem_a = n - a*a
        if rem_a < 0:
            continue
        for b in range(min(a, int(math.isqrt(rem_a))), -1, -1):
            rem_b = rem_a - b*b
            if rem_b < 0:
                continue
            for c in range(min(b, int(math.isqrt(rem_b))), -1, -1):
                rem_c = rem_b - c*c
                d = int(math.isqrt(rem_c))
                if d*d == rem_c and d <= c:
                    return (a, b, c, d)
    return None

def quaternion_multiply(q1, q2):
    """Multiply two quaternions (a,b,c,d) representing a + bi + cj + dk."""
    a1, b1, c1, d1 = q1
    a2, b2, c2, d2 = q2
    return (
        a1*a2 - b1*b2 - c1*c2 - d1*d2,
        a1*b2 + b1*a2 + c1*d2 - d1*c2,
        a1*c2 - b1*d2 + c1*a2 + d1*b2,
        a1*d2 + b1*c2 - c1*b2 + d1*a2
    )

def quaternion_norm(q):
    """Norm of quaternion = a² + b² + c² + d²."""
    return sum(x*x for x in q)

def quaternion_factor_attempt(N):
    """Attempt to factor N using quaternion norm decomposition.
    
    Strategy:
    1. Find N = a² + b² + c² + d² (Lagrange)
    2. Try to split the quaternion q = (a,b,c,d) into q₁·q₂
       with norm(q₁) = p, norm(q₂) = q, p*q = N
    3. GCD-based extraction from quaternion coordinates
    """
    decomp = four_square_decomposition(N)
    if decomp is None:
        return None
    
    a, b, c, d = decomp
    print(f"  Lagrange decomposition: {N} = {a}² + {b}² + {c}² + {d}²")
    
    # Try GCD extraction from quaternion components
    factors = set()
    for x in [a, b, c, d]:
        if x > 0:
            g = math.gcd(x, N)
            if 1 < g < N:
                factors.add(g)
    
    # Try sums and differences of squares
    for x, y in itertools.combinations([a, b, c, d], 2):
        for val in [x*x + y*y, abs(x*x - y*y), x+y, abs(x-y)]:
            if val > 0:
                g = math.gcd(val, N)
                if 1 < g < N:
                    factors.add(g)
    
    return factors

