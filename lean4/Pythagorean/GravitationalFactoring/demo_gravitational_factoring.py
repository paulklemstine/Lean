def is_pythagorean_quadruple(a, b, c, d):
    """Check if a² + b² + c² = d²."""
    return a*a + b*b + c*c == d*d

def generate_quadruples_up_to(D):
    """Generate all Pythagorean quadruples with hypotenuse ≤ D."""
    quads = []
    for d in range(1, D + 1):
        for a in range(0, d):
            for b in range(a, d):
                rem = d*d - a*a - b*b
                if rem < 0:
                    break
                c = int(math.isqrt(rem))
                if c >= b and c*c == rem:
                    quads.append((a, b, c, d))
    return quads

def generate_quadruples_parametric(max_param=20):
    """Generate quadruples using the parametric formula:
    (a, b, c, d) = (m²+n²-p²-q², 2(mq+np), 2(nq-mp), m²+n²+p²+q²)
    """
    quads = set()
    for m in range(0, max_param):
        for n in range(0, max_param):
            for p in range(0, max_param):
                for q in range(0, max_param):
                    if m == 0 and n == 0 and p == 0 and q == 0:
                        continue
                    a = m*m + n*n - p*p - q*q
                    b = 2*(m*q + n*p)
                    c = 2*(n*q - m*p)
                    d = m*m + n*n + p*p + q*q
                    if a >= 0 and b >= 0 and c >= 0:
                        triple = tuple(sorted([a, b, c]))
                        quads.add((triple[0], triple[1], triple[2], d))
    return sorted(quads, key=lambda x: x[3])

