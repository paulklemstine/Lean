def peel_channels(a, b, c, d, N):
    """Extract candidate factors from all peel channels of a quadruple.
    
    Peel channel j: gcd(d - leg_j, N)
    
    Returns list of (channel_name, gcd_value).
    """
    legs = [('a', a), ('b', b), ('c', c)]
    results = []
    for name, leg in legs:
        g_minus = math.gcd(abs(d - leg), N)
        g_plus = math.gcd(abs(d + leg), N)
        results.append((f'd-{name}', g_minus))
        results.append((f'd+{name}', g_plus))
    return results

def cross_collision_channels(a1, b1, c1, a2, b2, c2, d, N):
    """Extract factors from cross-collision of two quadruples sharing hypotenuse d.
    
    Cross differences: a1² - a2² = (a1-a2)(a1+a2), etc.
    """
    results = []
    for (name1, v1, name2, v2) in [('a', a1, 'a', a2), ('b', b1, 'b', b2), ('c', c1, 'c', c2)]:
        diff_sq = v1*v1 - v2*v2
        g = math.gcd(abs(diff_sq), N)
        results.append((f'{name1}²-{name2}²', g))
        g_sum = math.gcd(abs(v1 + v2), N)
        g_diff = math.gcd(abs(v1 - v2), N)
        results.append((f'{name1}+{name2}', g_sum))
        results.append((f'{name1}-{name2}', g_diff))
    return results

def gcd_cascade_factor(N, quadruples):
    """Attempt to factor N using GCD cascade across multiple quadruples.
    
    Strategy: For each quadruple with hypotenuse related to N,
    compute GCD with all peel channels.
    """
    factors_found = set()
    for (a, b, c, d) in quadruples:
        channels = peel_channels(a, b, c, d, N)
        for name, g in channels:
            if 1 < g < N:
                factors_found.add(g)
                print(f"  Factor {g} found via channel {name} of ({a},{b},{c},{d})")
    return factors_found

