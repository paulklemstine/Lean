def quadruple_children(a, b, c, d, max_d=1000):
    """Generate children of a quadruple in the tree using transformations.
    
    For Pythagorean quadruples, children are generated by matrix actions
    that preserve the quadratic form x²+y²+z²=w².
    """
    children = []
    
    # Transformation matrices that map quadruples to quadruples
    # These are generators of the orthogonal group O(3,1) over integers
    transforms = [
        # Type 1: Scaling by coordinate
        lambda a,b,c,d: (2*d - a, b, c, 2*d + a - 2*b),  
        lambda a,b,c,d: (a, 2*d - b, c, 2*d - 2*a + b),
        lambda a,b,c,d: (a, b, 2*d - c, 2*d - 2*a - 2*b + c),
        # Type 2: Cross-additions
        lambda a,b,c,d: (a + 2*d, b + 2*d, c, 3*d + 2*a + 2*b),
        lambda a,b,c,d: (a + 2*d, b, c + 2*d, 3*d + 2*a + 2*c),
        lambda a,b,c,d: (a, b + 2*d, c + 2*d, 3*d + 2*b + 2*c),
    ]
    
    # Simple child generation: add multiples
    for m in range(1, 5):
        for n in range(0, 5):
            # (a + 2md, b + 2nd, c, ...) type constructions
            new_a = a + 2*m*d
            new_b = b + 2*n*d
            rem = new_a**2 + new_b**2 + c**2
            sqrt_rem = int(math.isqrt(rem))
            if sqrt_rem > 0 and sqrt_rem**2 == rem and sqrt_rem <= max_d:
                children.append((new_a, new_b, c, sqrt_rem))
    
    return children

