class SimpleNeuralNavigator:
    """A simple neural network-inspired heuristic for tree navigation.
    
    Uses a learned scoring function to decide which branch of the
    quadruple tree to explore next.
    
    Features for each quadruple (a,b,c,d):
    - Residues mod N of each component
    - GCD values with N
    - Parity pattern
    - "Energy" = factoring potential
    """
    
    def __init__(self, N):
        self.N = N
        self.weights = defaultdict(float)
        self.learning_rate = 0.1
        self.history = []
    
    def features(self, a, b, c, d):
        """Extract features from a quadruple."""
        N = self.N
        return {
            'gcd_d_N': math.gcd(d, N),
            'gcd_da_N': math.gcd(abs(d-a), N),
            'gcd_db_N': math.gcd(abs(d-b), N),
            'gcd_dc_N': math.gcd(abs(d-c), N),
            'mod_a': a % N if N > 0 else 0,
            'mod_b': b % N if N > 0 else 0,
            'mod_c': c % N if N > 0 else 0,
            'parity': (a%2, b%2, c%2, d%2),
            'd_ratio': d / N if N > 0 else 0,
        }
    
    def score(self, a, b, c, d):
        """Score a quadruple: higher = more promising for factoring."""
        feats = self.features(a, b, c, d)
        s = 0.0
        # GCD signals are strong
        for key in ['gcd_da_N', 'gcd_db_N', 'gcd_dc_N']:
            g = feats[key]
            if 1 < g < self.N:
                s += 1000  # Found a factor!
            elif g > 1:
                s += math.log(g)
        # Prefer hypotenuse near multiples of N
        d_mod = d % self.N if self.N > 0 else 0
        s -= min(d_mod, self.N - d_mod) / self.N * 10
        return s
    
    def navigate(self, max_steps=5000):
        """Navigate the tree using the scoring heuristic."""
        print(f"\n{'='*60}")
        print(f"Neural Navigation for N = {self.N}")
        print(f"{'='*60}")
        
        # Start from multiple root nodes
        frontier = list(ROOT_NODES)
        visited = set()
        best_score = -float('inf')
        best_quad = None
        
        for step in range(max_steps):
            if not frontier:
                break
            
            # Score all frontier nodes
            scored = [(self.score(a,b,c,d), (a,b,c,d)) for a,b,c,d in frontier]
            scored.sort(reverse=True)
            
            # Take the best
            s, (a,b,c,d) = scored[0]
            
            if s > best_score:
                best_score = s
                best_quad = (a,b,c,d)
            
            if s >= 1000:
                channels = peel_channels(a, b, c, d, self.N)
                factors = set()
                for name, g in channels:
                    if 1 < g < self.N:
                        factors.add(g)
                if factors:
                    print(f"  ✓ Factor found at step {step}: {best_quad} → {factors}")
                    return factors
            
            visited.add((a,b,c,d))
            
            # Generate children
            children = quadruple_children(a, b, c, d, max_d=self.N * 3)
            frontier = [child for child in children if child not in visited]
            
            # Also keep top candidates from previous frontier
            for _, q in scored[1:min(5, len(scored))]:
                if q not in visited:
                    frontier.append(q)
            
            if step % 500 == 0 and step > 0:
                print(f"  Step {step}: best_score={best_score:.2f}, best={best_quad}")
        
        if best_quad:
            print(f"  Final: best_score={best_score:.2f}, best={best_quad}")
        return set()

