"""
demo.py — Berggren Semigroup Walk: Pseudorandomness Demonstration

Demonstrates that random walks on the Berggren tree of primitive Pythagorean
triples produce outputs that are pseudorandom modulo small moduli. This is
the computational companion to the formal spectral-gap-to-fooling theorems.
"""

import numpy as np
from collections import Counter

# ─── Berggren Generator Matrices ─────────────────────────────────────────────

B1 = np.array([[ 1, -2,  2],
               [ 2, -1,  2],
               [ 2, -2,  3]], dtype=np.int64)

B2 = np.array([[ 1,  2,  2],
               [ 2,  1,  2],
               [ 2,  2,  3]], dtype=np.int64)

B3 = np.array([[-1,  2,  2],
               [-2,  1,  2],
               [-2,  2,  3]], dtype=np.int64)

GENERATORS = [B1, B2, B3]
ROOT = np.array([3, 4, 5], dtype=np.int64)


def berggren_walk(length: int, rng=None) -> np.ndarray:
    """Perform a random Berggren walk of given length starting from (3,4,5)."""
    if rng is None:
        rng = np.random.default_rng()
    triple = ROOT.copy()
    for _ in range(length):
        gen = GENERATORS[rng.integers(0, 3)]
        triple = gen @ triple
    return triple


def berggren_walk_mod(length: int, q: int, num_samples: int = 10000, seed: int = 42):
    """Sample Berggren walks and reduce modulo q. Returns list of (a mod q, b mod q)."""
    rng = np.random.default_rng(seed)
    samples = []
    for _ in range(num_samples):
        triple = berggren_walk(length, rng)
        samples.append((int(triple[0] % q), int(triple[1] % q)))
    return samples


def total_variation_distance(samples, q):
    """Compute TV distance between empirical distribution and uniform on (ZMod q)^2."""
    n = len(samples)
    counts = Counter(samples)
    total_states = q * q
    uniform_prob = 1.0 / total_states
    tv = 0.0
    for state in counts:
        tv += abs(counts[state] / n - uniform_prob)
    # Count states not seen
    tv += (total_states - len(counts)) * uniform_prob
    return tv / 2.0


