def plot_polynomial_fooling():
    """Plot polynomial fooling error decay."""
    fig, ax = plt.subplots(figsize=(10, 6))

    q = 11
    num_samples = 30000

    # Several polynomial tests of different degrees
    tests = {
        'deg 1: a+b': lambda a, b: (a + b) % q,
        'deg 2: a²+ab': lambda a, b: (a*a + a*b) % q,
        'deg 3: a³+b²': lambda a, b: (a**3 + b**2) % q,
    }

    lengths = [1, 2, 3, 5, 8, 10, 15, 20, 25, 30]

    for name, poly in tests.items():
        # Uniform distribution
        uniform_counts = Counter()
        for a in range(q):
            for b in range(q):
                uniform_counts[poly(a, b)] += 1

        biases = []
        for ell in lengths:
            rng = np.random.default_rng(42)
            walk_counts = Counter()
            for _ in range(num_samples):
                triple = ROOT.copy()
                for _ in range(ell):
                    triple = GENERATORS[rng.integers(0, 3)] @ triple
                a, b = int(triple[0]) % q, int(triple[1]) % q
                walk_counts[poly(a, b)] += 1

            max_bias = 0
            for v in range(q):
                wp = walk_counts.get(v, 0) / num_samples
                up = uniform_counts.get(v, 0) / (q * q)
                max_bias = max(max_bias, abs(wp - up))
            biases.append(max(max_bias, 1e-6))

        ax.semilogy(lengths, biases, 'o-', label=name, markersize=5)

    ax.set_xlabel('Walk Length ℓ', fontsize=14)
    ax.set_ylabel('Maximum Bias', fontsize=14)
    ax.set_title(f'Polynomial Test Fooling (q = {q})', fontsize=16)
    ax.legend(fontsize=12)
    ax.grid(True, alpha=0.3)

    fig.savefig('polynomial_fooling.png', dpi=150, bbox_inches='tight')
    b64 = fig_to_base64(fig)
    plt.close(fig)
    return b64


def plot_walk_distribution():
    """Plot the distribution of Berggren walk outputs modulo q."""
    fig, axes = plt.subplots(1, 3, figsize=(16, 5))

    q = 7
    num_samples = 50000

    for idx, ell in enumerate([1, 5, 20]):
        rng = np.random.default_rng(42)
        counts = np.zeros((q, q))
        for _ in range(num_samples):
            triple = ROOT.copy()
            for _ in range(ell):
                triple = GENERATORS[rng.integers(0, 3)] @ triple
            a, b = int(triple[0]) % q, int(triple[1]) % q
            counts[a, b] += 1

        counts /= num_samples
        im = axes[idx].imshow(counts, cmap='YlOrRd', vmin=0,
                              vmax=max(2.0/(q*q), counts.max()))
        axes[idx].set_title(f'Walk length ℓ = {ell}', fontsize=14)
        axes[idx].set_xlabel('b mod 7', fontsize=12)
        axes[idx].set_ylabel('a mod 7', fontsize=12)
        plt.colorbar(im, ax=axes[idx], fraction=0.046, pad=0.04)

    fig.suptitle('Berggren Walk Output Distribution (a mod 7, b mod 7)',
                 fontsize=16, y=1.02)
    fig.tight_layout()
    fig.savefig('walk_distribution.png', dpi=150, bbox_inches='tight')
    b64 = fig_to_base64(fig)
    plt.close(fig)
    return b64


