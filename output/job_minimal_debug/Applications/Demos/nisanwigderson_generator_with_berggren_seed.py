def transition_matrix_analysis():
    """Compute and analyze the Berggren transition matrix modulo small q."""
    print("=" * 70)
    print("EXPERIMENT 3: Spectral Gap of Berggren Action Mod q")
    print("=" * 70)
    print()

    for q in [3, 5, 7, 11, 13]:
        # Enumerate reachable states modulo q
        states = set()
        frontier = {(3 % q, 4 % q, 5 % q)}
        while frontier:
            state = frontier.pop()
            if state in states:
                continue
            states.add(state)
            for gen in GENERATORS:
                triple = np.array(state, dtype=np.int64)
                new_triple = gen @ triple
                new_state = tuple(int(x) % q for x in new_triple)
                if new_state not in states:
                    frontier.add(new_state)

        state_list = sorted(states)
        state_idx = {s: i for i, s in enumerate(state_list)}
        n = len(state_list)

        # Build transition matrix
        T = np.zeros((n, n))
        for s in state_list:
            for gen in GENERATORS:
                triple = np.array(s, dtype=np.int64)
                new_triple = gen @ triple
                new_state = tuple(int(x) % q for x in new_triple)
                j = state_idx[new_state]
                i = state_idx[s]
                T[j, i] += 1.0 / 3.0

        # Compute eigenvalues
        eigenvalues = np.sort(np.abs(np.linalg.eigvals(T)))[::-1]
        rho = eigenvalues[1] if n > 1 else 0.0

        print(f"q = {q:>3}: |states| = {n:>4}, "
              f"λ₁ = {eigenvalues[0]:.4f}, "
              f"λ₂ = {rho:.4f}, "
              f"spectral gap = {1 - rho:.4f}")

    print()
    print("The second eigenvalue ρ = λ₂ < 1 confirms expansion.")
    print("Smaller ρ means faster mixing and better pseudorandomness.")
    print()


