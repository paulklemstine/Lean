# Berggren matrices
B1 = np.array([[ 1, -2,  2], [ 2, -1,  2], [ 2, -2,  3]], dtype=np.int64)
B2 = np.array([[ 1,  2,  2], [ 2,  1,  2], [ 2,  2,  3]], dtype=np.int64)
B3 = np.array([[-1,  2,  2], [-2,  1,  2], [-2,  2,  3]], dtype=np.int64)
GENERATORS = [B1, B2, B3]
ROOT = np.array([3, 4, 5], dtype=np.int64)


def fig_to_base64(fig):
    buf = io.BytesIO()
    fig.savefig(buf, format='png', dpi=150, bbox_inches='tight')
    buf.seek(0)
    return "data:image/png;base64," + base64.b64encode(buf.read()).decode('utf-8')


def plot_tv_decay():
    """Plot TV distance decay vs walk length for multiple moduli."""
    fig, ax = plt.subplots(figsize=(10, 6))

    for q in [5, 7, 11]:
        # Enumerate states
        states = set()
        frontier = {tuple(int(x) % q for x in ROOT)}
        while frontier:
            s = frontier.pop()
            if s in states: continue
            states.add(s)
            for gen in GENERATORS:
                ns = tuple(int(x) % q for x in gen @ np.array(s))
                if ns not in states: frontier.add(ns)

        state_list = sorted(states)
        state_idx = {s: i for i, s in enumerate(state_list)}
        n = len(state_list)

        T = np.zeros((n, n))
        for s in state_list:
            for gen in GENERATORS:
                ns = tuple(int(x) % q for x in gen @ np.array(s))
                T[state_idx[ns], state_idx[s]] += 1.0 / 3.0

        # Initial distribution: delta at root
        root_state = tuple(int(x) % q for x in ROOT)
        mu = np.zeros(n)
        mu[state_idx[root_state]] = 1.0
        uniform = np.ones(n) / n

        tvs = []
        lengths = list(range(0, 31))
        current = mu.copy()
        for ell in lengths:
            tv = 0.5 * np.sum(np.abs(current - uniform))
            tvs.append(tv)
            current = T @ current

        ax.semilogy(lengths, tvs, 'o-', label=f'q = {q} ({n} states)', markersize=4)

    ax.set_xlabel('Walk Length ℓ', fontsize=14)
    ax.set_ylabel('Total Variation Distance', fontsize=14)
    ax.set_title('Berggren Walk: Exponential Convergence to Uniform', fontsize=16)
    ax.legend(fontsize=12)
    ax.grid(True, alpha=0.3)
    ax.set_ylim(bottom=1e-15)

    fig.savefig('tv_decay.png', dpi=150, bbox_inches='tight')
    b64 = fig_to_base64(fig)
    plt.close(fig)
    return b64


def plot_spectral_gap():
    """Plot spectral gap vs modulus q."""
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    moduli = list(range(3, 30))
    gaps = []
    rhos = []
    num_states_list = []

    for q in moduli:
        states = set()
        frontier = {tuple(int(x) % q for x in ROOT)}
        while frontier:
            s = frontier.pop()
            if s in states: continue
            states.add(s)
            for gen in GENERATORS:
                ns = tuple(int(x) % q for x in gen @ np.array(s))
                if ns not in states: frontier.add(ns)

        state_list = sorted(states)
        state_idx = {s: i for i, s in enumerate(state_list)}
        n = len(state_list)
        num_states_list.append(n)

        T = np.zeros((n, n))
        for s in state_list:
            for gen in GENERATORS:
                ns = tuple(int(x) % q for x in gen @ np.array(s))
                T[state_idx[ns], state_idx[s]] += 1.0 / 3.0

        eigs = np.sort(np.abs(np.linalg.eigvals(T)))[::-1]
        rho = eigs[1] if n > 1 else 0.0
        gaps.append(1 - rho)
        rhos.append(rho)

    ax1.bar(moduli, gaps, color='steelblue', alpha=0.8)
    ax1.set_xlabel('Modulus q', fontsize=14)
    ax1.set_ylabel('Spectral Gap (1 - ρ)', fontsize=14)
    ax1.set_title('Spectral Gap of Berggren Action', fontsize=16)
    ax1.axhline(y=0, color='red', linestyle='--', alpha=0.5)
    ax1.grid(True, alpha=0.3, axis='y')

    ax2.scatter(moduli, num_states_list, c=gaps, cmap='RdYlGn', s=60, edgecolors='black', linewidths=0.5)
    ax2.set_xlabel('Modulus q', fontsize=14)
    ax2.set_ylabel('Number of Reachable States', fontsize=14)
    ax2.set_title('State Space Size (color = spectral gap)', fontsize=16)
    ax2.grid(True, alpha=0.3)
    cb = plt.colorbar(ax2.collections[0], ax=ax2, label='Spectral Gap')

    fig.tight_layout()
    fig.savefig('spectral_gap.png', dpi=150, bbox_inches='tight')
    b64 = fig_to_base64(fig)
