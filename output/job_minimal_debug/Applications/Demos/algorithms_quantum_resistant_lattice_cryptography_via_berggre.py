#!/usr/bin/env python3
"""
Berggren Groupoid Orbit Cryptography — Algorithms

Implements the core algorithms for Berggren-based post-quantum cryptographic
key exchange and lattice extraction.
"""

import numpy as np
from math import gcd, log2
from typing import List, Tuple, Optional, Dict
import secrets
import hashlib

# ─── Core Matrix Definitions ────────────────────────────────────────

# Berggren generator matrices
BERGGREN_A = np.array([[1, -2, 2], [2, -1, 2], [2, -2, 3]], dtype=np.int64)
BERGGREN_B = np.array([[1, 2, 2], [2, 1, 2], [2, 2, 3]], dtype=np.int64)
BERGGREN_C = np.array([[-1, 2, 2], [-2, 1, 2], [-2, 2, 3]], dtype=np.int64)

# Integer inverses (det = ±1 guarantees integer entries)
BERGGREN_A_INV = np.array([[1, 2, -2], [-2, -1, 2], [-2, -2, 3]], dtype=np.int64)
BERGGREN_B_INV = np.array([[1, 2, -2], [2, 1, -2], [-2, -2, 3]], dtype=np.int64)
BERGGREN_C_INV = np.array([[-1, -2, 2], [2, 1, -2], [-2, -2, 3]], dtype=np.int64)

GENERATORS = [BERGGREN_A, BERGGREN_B, BERGGREN_C]
INVERSES = [BERGGREN_A_INV, BERGGREN_B_INV, BERGGREN_C_INV]
GEN_NAMES = ['A', 'B', 'C']
ROOT_TRIPLE = np.array([3, 4, 5], dtype=np.int64)


# ─── Algorithm 1: Berggren Word Evaluation ──────────────────────────

def evaluate_berggren_word(word: List[int]) -> np.ndarray:
    """
    Evaluate a Berggren word to a matrix product.

    Args:
        word: List of generator indices (0=A, 1=B, 2=C)

    Returns:
        Product matrix M_{w[0]} * M_{w[1]} * ... * M_{w[n-1]}

    Time: O(n) matrix multiplications = O(27n) integer multiplications
    Space: O(1) (single 3x3 matrix)
    """
    result = np.eye(3, dtype=np.int64)
    for gen_idx in word:
        result = GENERATORS[gen_idx] @ result
    return result


def compute_orbit_point(word: List[int]) -> np.ndarray:
    """
    Compute the orbit point of a word from root (3,4,5).

    Args:
        word: Berggren word as list of generator indices

    Returns:
        Primitive Pythagorean triple (a, b, c)

    Time: O(n) where n = len(word)
    Space: O(1)
    """
    v = ROOT_TRIPLE.copy()
    # Apply generators right-to-left for correct orbit semantics
    for gen_idx in reversed(word):
        v = GENERATORS[gen_idx] @ v
    return v


# ─── Algorithm 2: Key Generation ────────────────────────────────────

def generate_secret_key(depth: int) -> List[int]:
    """
    Generate a cryptographically random Berggren secret key.

    Args:
        depth: Word length (determines security level)

    Returns:
        Random word of given length over {A, B, C}

    Security: log2(3) * depth ≈ 1.585 * depth classical bits
              Half that under Grover's quantum search

    Time: O(depth)
    """
    return [secrets.randbelow(3) for _ in range(depth)]


def derive_public_key(secret_key: List[int]) -> np.ndarray:
    """
    Derive a public key (primitive Pythagorean triple) from a secret word.

    By the faithfulness theorem, distinct secret keys yield distinct public keys.

    Args:
        secret_key: Berggren word (list of generator indices)

    Returns:
        Public key as a primitive Pythagorean triple (a, b, c)

    Time: O(n) where n = len(secret_key)
    """
    return compute_orbit_point(secret_key)


def verify_public_key(pk: np.ndarray) -> bool:
    """
    Verify that a public key is a valid primitive Pythagorean triple.

    Args:
        pk: Candidate public key (a, b, c)

    Returns:
        True if pk is a primitive Pythagorean triple
    """
    a, b, c = int(pk[0]), int(pk[1]), int(pk[2])
    return (a*a + b*b == c*c and
            gcd(a, b) == 1 and gcd(a, c) == 1 and gcd(b, c) == 1 and
            a > 0 and b > 0 and c > 0)


# ─── Algorithm 3: Orbit Lattice Extraction ──────────────────────────

def extract_orbit_lattice(words: List[List[int]]) -> np.ndarray:
    """
    Extract the integer lattice generated by pairwise orbit differences.

    Given a set of Berggren words, computes the lattice basis from
    pairwise differences of their orbit points.

    Args:
        words: List of Berggren words

    Returns:
        Matrix whose rows form a basis for the orbit-difference lattice

    Time: O(n² · d) where n = len(words), d = max word length
    Space: O(n²) for difference vectors
    """
    points = [compute_orbit_point(w) for w in words]

    # Collect all pairwise differences
    diffs = []
    for i in range(len(points)):
        for j in range(i + 1, len(points)):
            diffs.append(points[i] - points[j])

    if not diffs:
        return np.zeros((0, 3), dtype=np.int64)

    # Stack into matrix and compute row echelon form (integer Hermite normal form)
    M = np.array(diffs, dtype=np.int64)
    return integer_row_reduce(M)


def integer_row_reduce(M: np.ndarray) -> np.ndarray:
    """
    Compute an integer row-reduced form of a matrix.

    Uses elementary row operations with integer arithmetic.

    Args:
        M: Integer matrix

    Returns:
        Row-reduced integer matrix (nonzero rows only)
    """
    M = M.copy()
    rows, cols = M.shape
    pivot_row = 0

    for col in range(cols):
        # Find row with smallest nonzero absolute value in this column
        candidates = [(abs(int(M[r, col])), r)
                       for r in range(pivot_row, rows)
                       if M[r, col] != 0]
        if not candidates:
            continue

        _, best = min(candidates)
        M[[pivot_row, best]] = M[[best, pivot_row]]

        # Eliminate below
        for r in range(pivot_row + 1, rows):
            if M[r, col] != 0:
                # Use integer division to reduce
                q = M[r, col] // M[pivot_row, col]
                M[r] -= q * M[pivot_row]

        pivot_row += 1

    # Remove zero rows
    nonzero = np.any(M != 0, axis=1)
    return M[nonzero]


def l1_norm(v: np.ndarray) -> int:
    """L1 norm of an integer vector."""
    return int(np.sum(np.abs(v)))


def find_shortest_lattice_vector(words: List[List[int]]) -> Tuple[np.ndarray, int]:
    """
    Find the shortest nonzero vector in the orbit-difference lattice.

    Args:
        words: List of Berggren words

    Returns:
        (shortest vector, its L1 norm)
    """
    points = [compute_orbit_point(w) for w in words]
    best_vec = None
    best_norm = float('inf')

    for i in range(len(points)):
        for j in range(i + 1, len(points)):
            diff = points[i] - points[j]
            norm = l1_norm(diff)
            if 0 < norm < best_norm:
                best_vec = diff
                best_norm = norm

    return best_vec, int(best_norm)


# ─── Algorithm 4: Security Parameter Estimation ─────────────────────

def security_parameters(depth: int) -> Dict[str, float]:
    """
    Compute security parameters for a Berggren key derivation scheme.

    Args:
        depth: Word length (secret key size)

    Returns:
        Dictionary with security metrics

    The key space is 3^depth. Classical brute-force requires 3^depth
    evaluations. Grover's quantum search requires ~3^(depth/2) queries.
    """
    key_space_log2 = log2(3) * depth
    classical_security = key_space_log2
    quantum_security = key_space_log2 / 2  # Grover's bound

    return {
        'depth': depth,
        'key_space_log2': key_space_log2,
        'classical_security_bits': classical_security,
        'quantum_security_bits': quantum_security,
        'key_space_size': f'3^{depth}',
        'public_key_size_bits': depth * 3 * 64,  # rough upper bound
    }


# ─── Algorithm 5: Berggren Path Recovery (Parent Map) ───────────────

def recover_parent(triple: np.ndarray) -> Tuple[Optional[int], np.ndarray]:
    """
    Recover the parent of a primitive Pythagorean triple in the Berggren tree.

    Applies each inverse matrix and checks which yields a valid primitive
    triple with smaller hypotenuse.

    Args:
        triple: A primitive Pythagorean triple (a, b, c) with c > 5

    Returns:
        (generator_index, parent_triple) or (None, triple) if at root
    """
    a, b, c = int(triple[0]), int(triple[1]), int(triple[2])

    if (a, b, c) == (3, 4, 5):
        return None, triple

    for idx, inv_mat in enumerate(INVERSES):
        parent = inv_mat @ triple
        pa, pb, pc = int(parent[0]), int(parent[1]), int(parent[2])
        if pa > 0 and pb > 0 and pc > 0 and pc < c:
            if pa*pa + pb*pb == pc*pc and gcd(pa, pb) == 1:
                return idx, parent

    return None, triple  # Should not happen for valid primitive triples


def recover_word(triple: np.ndarray) -> List[int]:
    """
    Recover the unique Berggren word that generates a given primitive triple.

    Uses the parent map to trace back from the triple to root (3,4,5).

    Args:
        triple: A primitive Pythagorean triple in the Berggren tree

    Returns:
        The unique word [g₁, g₂, ..., gₙ] such that
        M_{g₁}·M_{g₂}·...·M_{gₙ}·(3,4,5) = triple

    Time: O(log c) where c is the hypotenuse (each step reduces c)
    """
    word = []
    current = triple.copy()

    while not np.array_equal(current, ROOT_TRIPLE):
        gen_idx, parent = recover_parent(current)
        if gen_idx is None:
            break
        word.append(gen_idx)
        current = parent

    return word  # Already in correct order (outermost generator first)


