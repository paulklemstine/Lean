#!/usr/bin/env python3
"""
EML-KA Algorithms: Core implementations with type hints.

Provides:
1. EMLChain evaluation and depth computation
2. EML-KA monomial and polynomial decomposition
3. Fenchel-Young gap computation and optimization
4. Bregman divergence computation
5. EML-KA approximation fitting
"""

from __future__ import annotations
from dataclasses import dataclass
from enum import Enum, auto
from typing import Callable, List, Tuple
import math


class OpType(Enum):
    """EML chain operation type."""
    EXP = auto()
    LOG = auto()
    AFFINE = auto()


@dataclass
class EMLOp:
    """A single operation in an EML chain."""
    op_type: OpType
    a: float = 0.0  # affine coefficient
    b: float = 0.0  # affine offset

    def eval(self, x: float) -> float:
        if self.op_type == OpType.EXP:
            return math.exp(x)
        elif self.op_type == OpType.LOG:
            return math.log(x) if x > 0 else float('-inf')
        else:  # AFFINE
            return self.a * x + self.b

    def is_transcendental(self) -> bool:
        return self.op_type != OpType.AFFINE


class EMLChain:
    """A chain of EML operations, evaluated left to right."""

    def __init__(self, ops: List[EMLOp]):
        self.ops = ops

    def eval(self, x: float) -> float:
        result = x
        for op in self.ops:
            result = op.eval(result)
        return result

    def depth(self) -> int:
        """Count of non-affine (transcendental) operations."""
        return sum(1 for op in self.ops if op.is_transcendental())

    @staticmethod
    def power_chain(a: float) -> 'EMLChain':
        """Chain for x^a: log → scale by a → exp."""
        return EMLChain([
            EMLOp(OpType.LOG),
            EMLOp(OpType.AFFINE, a=a, b=0.0),
            EMLOp(OpType.EXP),
        ])


@dataclass
class MonomialTerm:
    """A monomial term c * x^a * y^b."""
    coeff: float
    exp_x: float
    exp_y: float

    def eval(self, x: float, y: float) -> float:
        return self.coeff * (x ** self.exp_x) * (y ** self.exp_y)


class EMLKADecomp:
    """EML-KA decomposition with Q terms for bivariate functions.

    f(x,y) = sum_q outer_q(chain1_q(x) + chain2_q(y))
    """

    def __init__(self, chains1: List[EMLChain], chains2: List[EMLChain],
                 outer_chains: List[EMLChain]):
        assert len(chains1) == len(chains2) == len(outer_chains)
        self.chains1 = chains1
        self.chains2 = chains2
        self.outer_chains = outer_chains
        self.Q = len(chains1)

    def eval(self, x: float, y: float) -> float:
        total = 0.0
        for q in range(self.Q):
            inner = self.chains1[q].eval(x) + self.chains2[q].eval(y)
            total += self.outer_chains[q].eval(inner)
        return total

    def max_depth(self) -> int:
        depths = []
        for q in range(self.Q):
            depths.append(max(
                self.chains1[q].depth(),
                self.chains2[q].depth(),
                self.outer_chains[q].depth()
            ))
        return max(depths) if depths else 0

    @staticmethod
    def from_monomial(a: float, b: float) -> 'EMLKADecomp':
        """Construct decomposition for x^a * y^b."""
        chain1 = EMLChain([EMLOp(OpType.LOG), EMLOp(OpType.AFFINE, a=a, b=0.0)])
        chain2 = EMLChain([EMLOp(OpType.LOG), EMLOp(OpType.AFFINE, a=b, b=0.0)])
        outer = EMLChain([EMLOp(OpType.EXP)])
        return EMLKADecomp([chain1], [chain2], [outer])

    @staticmethod
    def from_polynomial(terms: List[MonomialTerm]) -> 'EMLKADecomp':
        """Construct decomposition for a polynomial (sum of monomials)."""
        chains1, chains2, outers = [], [], []
        for t in terms:
            chains1.append(EMLChain([
                EMLOp(OpType.LOG), EMLOp(OpType.AFFINE, a=t.exp_x, b=0.0)
            ]))
            chains2.append(EMLChain([
                EMLOp(OpType.LOG), EMLOp(OpType.AFFINE, a=t.exp_y, b=0.0)
            ]))
            outers.append(EMLChain([
                EMLOp(OpType.EXP), EMLOp(OpType.AFFINE, a=t.coeff, b=0.0)
            ]))
        return EMLKADecomp(chains1, chains2, outers)


def fenchel_young_gap(x: float, s: float) -> float:
    """Compute the Fenchel-Young gap: exp(x) + s*log(s) - s - x*s.

    Properties (proved in Lean):
    - Always ≥ 0 for s > 0
    - Equals 0 iff s = exp(x)
    """
    if s <= 0:
        raise ValueError("s must be positive")
    return math.exp(x) + s * math.log(s) - s - x * s


def bregman_exp_div(p: float, q: float) -> float:
    """Bregman divergence generated by exp: exp(p) - exp(q) - exp(q)(p-q)."""
    return math.exp(p) - math.exp(q) - math.exp(q) * (p - q)


def bregman_neglog_div(p: float, q: float) -> float:
    """Bregman divergence generated by -log: -log(p) + log(q) + (1/q)(p-q)."""
    if p <= 0 or q <= 0:
        raise ValueError("p and q must be positive")
    return -math.log(p) + math.log(q) + (1/q) * (p - q)


def kl_bregman(p: float, q: float) -> float:
    """KL divergence as Bregman: p*log(p/q) - (p-q).

    Properties (proved in Lean):
    - Always ≥ 0 (Gibbs' inequality)
    - Equals 0 iff p = q
    """
    if p <= 0 or q <= 0:
        raise ValueError("p and q must be positive")
    return p * math.log(p / q) - (p - q)


def eml_ka_approximate(
    f: Callable[[float, float], float],
    x_range: Tuple[float, float],
    y_range: Tuple[float, float],
    M: int,
    grid_size: int = 20,
) -> Tuple[EMLKADecomp, float]:
    """Fit an M-term EML-KA decomposition to f on a grid.

    Uses least-squares fitting of monomial terms.
    Returns (decomposition, max_error).

    Algorithm:
    1. Generate grid points on (x_range) × (y_range)
    2. For each of M terms, find best (coeff, exp_x, exp_y) by gradient descent
    3. Return the decomposition and its approximation error
    """
    import numpy as np

    xs = np.linspace(x_range[0], x_range[1], grid_size)
    ys = np.linspace(y_range[0], y_range[1], grid_size)
    X, Y = np.meshgrid(xs, ys)
    target = np.vectorize(f)(X, Y)

    residual = target.copy()
    terms = []

    for _ in range(M):
        # Greedy: find best single monomial term for residual
        best_err = float('inf')
        best_term = MonomialTerm(0, 0, 0)

        for ea in np.linspace(-2, 5, 15):
            for eb in np.linspace(-2, 5, 15):
                basis = (X ** ea) * (Y ** eb)
                if np.any(~np.isfinite(basis)):
                    continue
                denom = np.sum(basis ** 2)
                if denom < 1e-12:
                    continue
                c = np.sum(residual * basis) / denom
                err = np.max(np.abs(residual - c * basis))
                if err < best_err:
                    best_err = err
                    best_term = MonomialTerm(c, ea, eb)

        terms.append(best_term)
        residual -= best_term.coeff * (X ** best_term.exp_x) * (Y ** best_term.exp_y)

    decomp = EMLKADecomp.from_polynomial(terms)
    max_error = float(np.max(np.abs(residual)))
    return decomp, max_error


