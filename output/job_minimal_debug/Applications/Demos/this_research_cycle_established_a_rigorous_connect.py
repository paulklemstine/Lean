#!/usr/bin/env python3
"""
EML-KA Depth Theory: Numerical Demonstrations

Demonstrates the depth-independence phenomenon for monomials and the
Fenchel-Young duality bridge between EML and convex optimization.
"""

import numpy as np

def eml(x: float, y: float) -> float:
    """The EML operation: eml(x,y) = exp(x) - log(y)."""
    return np.exp(x) - np.log(y)

def eml_ka_monomial(a: float, b: float, x: float, y: float) -> float:
    """EML-KA decomposition of x^a * y^b = exp(a*log(x) + b*log(y))."""
    return np.exp(a * np.log(x) + b * np.log(y))

def fenchel_young_gap(x: float, s: float) -> float:
    """FYGap(x,s) = exp(x) + s*log(s) - s - x*s."""
    return np.exp(x) + s * np.log(s) - s - x * s

def bregman_exp(p: float, q: float) -> float:
    """Bregman divergence generated by exp."""
    return np.exp(p) - np.exp(q) - np.exp(q) * (p - q)

def bregman_neglog(p: float, q: float) -> float:
    """Bregman divergence generated by -log."""
    return -np.log(p) + np.log(q) + (1/q) * (p - q)

def kl_bregman(p: float, q: float) -> float:
    """KL divergence as Bregman of neg-entropy."""
    return p * np.log(p / q) - (p - q)


print("=" * 60)
print("EML-KA Depth Theory: Numerical Demonstrations")
print("=" * 60)

# Demo 1: Monomial decomposition correctness
print("\n--- Demo 1: Monomial Decomposition Correctness ---")
print("Verifying exp(a*log(x) + b*log(y)) = x^a * y^b")
test_cases = [
    (2, 3, 1.5, 2.0),
    (0.5, 0.5, 4.0, 9.0),  # sqrt(x)*sqrt(y)
    (100, 200, 1.01, 1.02),  # large exponents, small base
    (-1, 1, 2.0, 3.0),  # x^(-1) * y
]

for a, b, x, y in test_cases:
    eml_result = eml_ka_monomial(a, b, x, y)
    direct = x**a * y**b
    error = abs(eml_result - direct)
    print(f"  a={a:>4}, b={b:>4}, x={x:.2f}, y={y:.2f}: "
          f"EML-KA={eml_result:.8f}, direct={direct:.8f}, error={error:.2e}")

# Demo 2: Depth independence
print("\n--- Demo 2: Depth Independence ---")
print("All monomials use exactly the same chain structure (depth 1)")
print("regardless of exponent magnitude:")
for a, b in [(1,1), (10,10), (100,100), (1000,1000), (-5, 7.3)]:
    x, y = 1.1, 1.2
    result = eml_ka_monomial(a, b, x, y)
    expected = x**a * y**b
    print(f"  x^{a}*y^{b}: depth=1, result={result:.6e}, match={np.isclose(result, expected)}")

# Demo 3: Fenchel-Young gap
print("\n--- Demo 3: Fenchel-Young Gap ---")
print("FYGap(x, s) ≥ 0, with equality iff s = exp(x)")
for x in [-1.0, 0.0, 1.0, 2.0]:
    s_opt = np.exp(x)
    gap_opt = fenchel_young_gap(x, s_opt)
    gap_off = fenchel_young_gap(x, s_opt + 0.5)
    print(f"  x={x:>5.1f}: gap(x, exp(x))={gap_opt:.2e}, "
          f"gap(x, exp(x)+0.5)={gap_off:.6f}")

# Demo 4: Bregman divergences
print("\n--- Demo 4: Bregman Divergences (nonneg) ---")
for p, q in [(1.0, 2.0), (0.5, 3.0), (5.0, 0.1), (1.0, 1.0)]:
    be = bregman_exp(p, q)
    bnl = bregman_neglog(p, q)
    kl = kl_bregman(p, q)
    print(f"  p={p:.1f}, q={q:.1f}: B_exp={be:.6f}, B_neglog={bnl:.6f}, "
          f"KL={kl:.6f}, all≥0: {be>=0 and bnl>=0 and kl>=0}")

# Demo 5: Polynomial decomposition
print("\n--- Demo 5: Polynomial Decomposition ---")
print("f(x,y) = 3x²y + 2xy³ - x⁰·⁵y⁰·⁵")
def poly_direct(x, y):
    return 3*x**2*y + 2*x*y**3 - x**0.5*y**0.5

def poly_eml_ka(x, y):
    """3-term EML-KA decomposition."""
    t1 = 3 * np.exp(2*np.log(x) + 1*np.log(y))
    t2 = 2 * np.exp(1*np.log(x) + 3*np.log(y))
    t3 = -1 * np.exp(0.5*np.log(x) + 0.5*np.log(y))
    return t1 + t2 + t3

for x, y in [(1.5, 2.0), (3.0, 0.5), (10.0, 10.0)]:
    d = poly_direct(x, y)
    e = poly_eml_ka(x, y)
    print(f"  x={x:.1f}, y={y:.1f}: direct={d:.6f}, EML-KA={e:.6f}, "
          f"error={abs(d-e):.2e}")

# Demo 6: Approximation rate test (conjecture)
print("\n--- Demo 6: EML-KA Approximation of sin(x*y) ---")
print("Testing conjecture: error ∝ 1/M for M-term approximations")

def fit_eml_ka_sin(M, x_grid, y_grid):
    """Approximate sin(x*y) with M-term EML-KA on grid."""
    # Use Taylor-like expansion: sin(t) ≈ sum of t^k terms
    # sin(xy) ≈ xy - (xy)^3/6 + (xy)^5/120 - ...
    # Each (xy)^k = x^k * y^k has a 1-term EML-KA decomp
    target = np.sin(np.outer(x_grid, y_grid))
    approx = np.zeros_like(target)
    for k in range(M):
        n = 2*k + 1
        sign = (-1)**k
        coeff = sign / np.math.factorial(n)
        term = coeff * np.outer(x_grid**n, y_grid**n)
        approx += term
    return np.max(np.abs(target - approx))

x_grid = np.linspace(1.0, 2.0, 50)
y_grid = np.linspace(1.0, 2.0, 50)
for M in [1, 2, 3, 4, 5, 6]:
    err = fit_eml_ka_sin(M, x_grid, y_grid)
    print(f"  M={M}: max_error={err:.6e}")

print("\n" + "=" * 60)
print("All demonstrations complete.")


