"""
Visualization: EML-KA Depth Independence for Monomials

Shows that the decomposition depth remains constant (=1) regardless
of the exponent magnitude, while the direct computation grows.
"""

import numpy as np
import matplotlib.pyplot as plt

def eml_ka_depth(a: float, b: float) -> int:
    """EML-KA decomposition depth for x^a * y^b (always 1)."""
    return 1

def naive_depth(a: float, b: float) -> float:
    """Naive chain depth: proportional to |a| + |b| for integer exponents."""
    return abs(a) + abs(b)

fig, axes = plt.subplots(1, 3, figsize=(15, 5))

# Panel 1: Depth vs exponent magnitude
exponents = np.arange(1, 51)
eml_depths = [eml_ka_depth(n, n) for n in exponents]
naive_depths = [naive_depth(n, n) for n in exponents]

axes[0].plot(exponents, naive_depths, 'r-o', markersize=3, label='Naive (repeated multiply)')
axes[0].plot(exponents, eml_depths, 'b-s', markersize=4, label='EML-KA decomposition')
axes[0].set_xlabel('Exponent n (for x^n · y^n)')
axes[0].set_ylabel('Decomposition depth')
axes[0].set_title('Depth Independence Phenomenon')
axes[0].legend()
axes[0].set_yscale('log')
axes[0].grid(True, alpha=0.3)

# Panel 2: Fenchel-Young gap landscape
x_vals = np.linspace(-2, 3, 200)
s_vals = np.linspace(0.1, 10, 200)
X, S = np.meshgrid(x_vals, s_vals)
FY = np.exp(X) + S * np.log(S) - S - X * S
FY = np.clip(FY, 0, 20)

im = axes[1].contourf(X, S, FY, levels=20, cmap='viridis')
plt.colorbar(im, ax=axes[1], label='FY Gap')
# Plot the zero curve: s = exp(x)
x_curve = np.linspace(-2, 2.3, 100)
axes[1].plot(x_curve, np.exp(x_curve), 'r-', linewidth=2, label='s = exp(x) (gap = 0)')
axes[1].set_xlabel('x')
axes[1].set_ylabel('s')
axes[1].set_title('Fenchel-Young Gap Landscape')
axes[1].legend(fontsize=8)

# Panel 3: Bregman divergences
p_vals = np.linspace(0.1, 5, 200)
q_fixed = 2.0
B_exp = np.exp(p_vals) - np.exp(q_fixed) - np.exp(q_fixed) * (p_vals - q_fixed)
B_neglog = -np.log(p_vals) + np.log(q_fixed) + (1/q_fixed) * (p_vals - q_fixed)
KL = p_vals * np.log(p_vals / q_fixed) - (p_vals - q_fixed)

axes[2].plot(p_vals, B_exp, 'r-', label='Bregman(exp)', linewidth=2)
axes[2].plot(p_vals, B_neglog, 'b-', label='Bregman(-log)', linewidth=2)
axes[2].plot(p_vals, KL, 'g--', label='KL divergence', linewidth=2)
axes[2].axhline(y=0, color='k', linewidth=0.5)
axes[2].axvline(x=q_fixed, color='k', linewidth=0.5, linestyle='--', alpha=0.3)
axes[2].set_xlabel('p')
axes[2].set_ylabel('Divergence value')
axes[2].set_title(f'EML Divergences (q={q_fixed})')
axes[2].legend(fontsize=8)
axes[2].set_ylim(-1, 15)
axes[2].grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('eml_ka_depth_theory.png', dpi=150, bbox_inches='tight')
plt.close()
print("Saved: eml_ka_depth_theory.png")


