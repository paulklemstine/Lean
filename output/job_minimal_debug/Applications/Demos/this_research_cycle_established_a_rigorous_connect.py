"""
Visualization: Fenchel-Young Duality Bridge

Shows the connection between exp/log as convex conjugates and
the EML operation through the Fenchel-Young inequality.
"""

import numpy as np
import matplotlib.pyplot as plt

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

# Panel 1: Convex conjugate duality
x = np.linspace(-2, 3, 300)
axes[0].plot(x, np.exp(x), 'b-', linewidth=2, label='exp(x)')
axes[0].plot(x, x * np.log(np.maximum(x, 1e-10)) - x + 1, 'r-', linewidth=2,
             label='x·log(x) - x + 1 (shifted neg-entropy)')

# Show the tangent line at x=1
axes[0].plot(x, np.e * (x - 1) + np.e, 'g--', linewidth=1, alpha=0.7,
             label='Tangent at x=1')
axes[0].set_xlabel('x')
axes[0].set_ylabel('f(x)')
axes[0].set_title('Exp and Neg-Entropy: Convex Conjugates')
axes[0].legend()
axes[0].set_ylim(-2, 15)
axes[0].grid(True, alpha=0.3)

# Panel 2: KL divergence nonnegativity
p_vals = np.linspace(0.01, 5, 300)
for q in [0.5, 1.0, 2.0, 3.0]:
    kl = p_vals * np.log(p_vals / q) - (p_vals - q)
    axes[1].plot(p_vals, kl, linewidth=2, label=f'KL Bregman (q={q})')

axes[1].axhline(y=0, color='k', linewidth=0.5)
axes[1].set_xlabel('p')
axes[1].set_ylabel('KL Bregman divergence')
axes[1].set_title('Gibbs\' Inequality: KL ≥ 0, = 0 iff p = q')
axes[1].legend()
axes[1].set_ylim(-0.5, 5)
axes[1].grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('fenchel_young_bridge.png', dpi=150, bbox_inches='tight')
plt.close()
print("Saved: fenchel_young_bridge.png")
