#!/usr/bin/env python3
"""
Algorithms for Cyclotomic Subfield Extraction

Implements the core mathematical algorithms:
- Primitive root computation
- Subgroup enumeration in cyclic groups
- Euler's totient function
- Cyclotomic subfield lattice construction
- Divisor enumeration
"""

from typing import Dict, List, Set


def is_prime(n: int) -> bool:
    """Test if n is prime.

    >>> is_prime(13)
    True
    >>> is_prime(15)
    False
    """
    if n < 2:
        return False
    if n < 4:
        return True
    if n % 2 == 0 or n % 3 == 0:
        return False
    i = 5
    while i * i <= n:
        if n % i == 0 or n % (i + 2) == 0:
            return False
        i += 6
    return True


def euler_totient(n: int) -> int:
    """Compute Euler's totient function φ(n).

    φ(n) = number of integers in [1, n] coprime to n.
    For prime p, φ(p) = p - 1.

    >>> euler_totient(12)
    4
    >>> euler_totient(13)
    12
    """
    result = n
    p = 2
    temp = n
    while p * p <= temp:
        if temp % p == 0:
            while temp % p == 0:
                temp //= p
            result -= result // p
        p += 1
    if temp > 1:
        result -= result // temp
    return result


def divisors(n: int) -> List[int]:
    """Return sorted list of positive divisors of n.

    >>> divisors(12)
    [1, 2, 3, 4, 6, 12]
    """
    if n <= 0:
        return []
    divs = []
    for i in range(1, int(n**0.5) + 1):
        if n % i == 0:
            divs.append(i)
            if i != n // i:
                divs.append(n // i)
    return sorted(divs)


def multiplicative_order(a: int, n: int) -> int:
    """Compute the multiplicative order of a modulo n.

    The smallest positive k such that a^k ≡ 1 (mod n).

    >>> multiplicative_order(2, 7)
    3
    >>> multiplicative_order(3, 7)
    6
    """
    if n <= 1:
        return 1
    a = a % n
    if a == 0:
        raise ValueError(f"{a} is not coprime to {n}")
    k = 1
    current = a
    while current != 1:
        current = (current * a) % n
        k += 1
        if k > n:
            raise ValueError(f"{a} is not coprime to {n}")
    return k


def primitive_root(p: int) -> int:
    """Find the smallest primitive root modulo prime p.

    A primitive root g has multiplicative order p-1 in (Z/pZ)*.

    >>> primitive_root(7)
    3
    >>> primitive_root(13)
    2

    Args:
        p: A prime number.

    Returns:
        The smallest primitive root modulo p.
    """
    if p == 2:
        return 1
    phi = p - 1
    prime_factors = set()
    temp = phi
    for f in range(2, int(temp**0.5) + 1):
        if temp % f == 0:
            prime_factors.add(f)
            while temp % f == 0:
                temp //= f
    if temp > 1:
        prime_factors.add(temp)

    for g in range(2, p):
        is_root = True
        for q in prime_factors:
            if pow(g, phi // q, p) == 1:
                is_root = False
                break
        if is_root:
            return g
    raise ValueError(f"No primitive root found for {p}")


def subgroups_of_cyclic_group(n: int) -> Dict[int, Set[int]]:
    """Enumerate all subgroups of the cyclic group Z/nZ (additively).

    For each divisor d of n, returns the unique subgroup of order d.
    The subgroup of order d is generated by n/d and consists of
    {0, n/d, 2(n/d), ..., (d-1)(n/d)} mod n.

    >>> subgroups_of_cyclic_group(6)
    {1: {0}, 2: {0, 3}, 3: {0, 2, 4}, 6: {0, 1, 2, 3, 4, 5}}

    Args:
        n: The order of the cyclic group.

    Returns:
        Dictionary mapping divisor d to the set of elements in the unique
        subgroup of order d.
    """
    result = {}
    for d in divisors(n):
        gen = n // d  # generator of the subgroup of order d
        subgroup = set()
        for k in range(d):
            subgroup.add((k * gen) % n)
        result[d] = subgroup
    return result


def subgroups_of_units_mod_p(p: int) -> Dict[int, Set[int]]:
    """Enumerate all subgroups of (Z/pZ)* for prime p.

    Uses a primitive root to identify (Z/pZ)* with Z/(p-1)Z,
    then enumerates subgroups via the cyclic structure.

    >>> sorted(subgroups_of_units_mod_p(7).keys())
    [1, 2, 3, 6]

    Args:
        p: A prime number.

    Returns:
        Dictionary mapping divisor d of p-1 to the set of elements
        in the unique subgroup of (Z/pZ)* of order d.
    """
    g = primitive_root(p)
    n = p - 1

    # Build the isomorphism: k -> g^k mod p
    powers = {}
    current = 1
    for k in range(n):
        powers[k] = current
        current = (current * g) % p

    result = {}
    for d in divisors(n):
        # Subgroup of order d in Z/(p-1)Z is generated by (p-1)/d
        gen_index = n // d
        subgroup = set()
        for k in range(d):
            subgroup.add(powers[(k * gen_index) % n])
        result[d] = subgroup

    return result


def cyclotomic_subfield_lattice(p: int) -> List[Dict]:
    """Compute the complete subfield lattice of Q(ζ_p)/Q.

    For each divisor d of p-1, produces:
    - The subgroup of (Z/pZ)* of order (p-1)/d (corresponding to the
      Galois group of Q(ζ_p) over the degree-d subfield)
    - The generator of that subgroup
    - The degree d of the corresponding intermediate field

    >>> lattice = cyclotomic_subfield_lattice(7)
    >>> [e['degree'] for e in lattice]
    [1, 2, 3, 6]

    Args:
        p: An odd prime number.

    Returns:
        List of dictionaries, each describing an intermediate field.
    """
    g = primitive_root(p)
    n = p - 1
    subgroups = subgroups_of_units_mod_p(p)

    lattice = []
    for d in sorted(divisors(n)):
        # Degree-d subfield corresponds to subgroup of order (p-1)/d
        subgroup_order = n // d
        subgroup = subgroups[subgroup_order]

        # Find generator of the subgroup
        gen = pow(g, d, p)  # g^d generates the subgroup of order (p-1)/d

        lattice.append(
            {
                "degree": d,
                "subgroup_order": subgroup_order,
                "generator": gen,
                "subgroup_elements": subgroup,
                "field_description": _field_description(p, d),
            }
        )

    return lattice


def _field_description(p: int, d: int) -> str:
    """Generate a human-readable description of the degree-d subfield."""
    if d == 1:
        return "Q (rationals)"
    elif d == p - 1:
        return f"Q(ζ_{p}) (full cyclotomic field)"
    elif d == 2:
        p_star = p if (p - 1) // 2 % 2 == 0 else -p
        return f"Q(√({p_star}))"
    elif d == (p - 1) // 2:
        return f"Q(ζ_{p} + ζ_{p}⁻¹) (maximal real subfield)"
    else:
        return f"Unique degree-{d} subfield of Q(ζ_{p})"


def factorize(n: int) -> Dict[int, int]:
    """Return prime factorization of n as {prime: exponent}.

    >>> factorize(12)
    {2: 2, 3: 1}
    >>> factorize(30)
    {2: 1, 3: 1, 5: 1}
    """
    factors = {}
    d = 2
    while d * d <= n:
        while n % d == 0:
            factors[d] = factors.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        factors[n] = factors.get(n, 0) + 1
    return factors


def num_divisors(n: int) -> int:
    """Compute the number of positive divisors of n.

    >>> num_divisors(12)
    6
    """
    factors = factorize(n)
    result = 1
    for e in factors.values():
        result *= e + 1
    return result


