def demo_frobenius_speedup():
    """
    Demonstrate how the Freshman's Dream enables fast computation.

    To compute (a₁ + a₂ + ... + aₖ)^p mod p, we can use:
    (a₁ + ... + aₖ)^p ≡ a₁^p + ... + aₖ^p ≡ a₁ + ... + aₖ (mod p)

    This reduces an O(log p) exponentiation to an O(1) operation!
    """
    print("\n╔══════════════════════════════════════════════════════════╗")
    print("║  APPLICATION 2: Fast Computation via Freshman's Dream   ║")
    print("╚══════════════════════════════════════════════════════════╝")

    import time

    primes = [7, 101, 1009, 10007, 100003, 1000003]

    print(f"\n  Computing (sum of k random elements)^p mod p:")
    print(f"  {'p':>10}  {'k':>6}  {'Naive (μs)':>12}  {'Frobenius (μs)':>15}  {'Speedup':>8}  {'Match':>5}")
    print(f"  {'─'*60}")

    for p in primes:
        k = 1000
        values = [i % p for i in range(k)]
        total = sum(values) % p

        # Naive: compute pow(total, p, p)
        t0 = time.perf_counter()
        for _ in range(100):
            naive_result = pow(total, p, p)
        t_naive = (time.perf_counter() - t0) * 10000  # μs per iteration

        # Frobenius: (a₁+...+aₖ)^p = a₁+...+aₖ mod p
        t0 = time.perf_counter()
        for _ in range(100):
            frob_result = total  # Identity! By Fermat's Little Theorem
        t_frob = (time.perf_counter() - t0) * 10000

        match = naive_result == frob_result
        speedup = t_naive / t_frob if t_frob > 0 else float('inf')

        print(f"  {p:>10}  {k:>6}  {t_naive:>12.2f}  {t_frob:>15.2f}  "
              f"{speedup:>7.1f}x  {'✓' if match else '✗':>5}")


