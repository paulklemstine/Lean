"""
The Freshman's Dream Theorem: Interactive Demonstrations
========================================================

This module provides visualizations and computational demonstrations of the
Freshman's Dream theorem and the Frobenius endomorphism in characteristic p rings.

The "Freshman's Dream" states that in a ring of prime characteristic p:
    (a + b)^p = a^p + b^p

This seemingly "freshman mistake" is actually TRUE in these rings, because all
the intermediate binomial coefficients C(p,k) for 0 < k < p are divisible by p.

We also demonstrate the algebra of idempotent elements, which connects to the
Frobenius endomorphism through the result that Frobenius fixes all idempotents.
"""

import numpy as np
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors
from matplotlib.patches import Patch
import random


def mod_binomial(n, k, p):
    """Compute C(n, k) mod p using Lucas' theorem."""
    if k < 0 or k > n:
        return 0
    result = 1
    while n > 0 or k > 0:
        ni, ki = n % p, k % p
        if ki > ni:
            return 0
        c = 1
        for j in range(ki):
            c = (c * (ni - j)) % p
            c = (c * pow(j + 1, p - 2, p)) % p
        result = (result * c) % p
        n //= p
        k //= p
    return result


def demo_pascals_triangle_mod_p(p=5, rows=50):
    """
    Visualize Pascal's triangle modulo p.

    The Freshman's Dream is visible as the pattern: row p has only
    the entries at positions 0 and p nonzero (both equal to 1).
    The resulting fractal pattern reveals the deep structure of
    binomial coefficients in characteristic p.
    """
    triangle = np.zeros((rows, rows))
    for n in range(rows):
        for k in range(n + 1):
            triangle[n][k] = mod_binomial(n, k, p)

    fig, ax = plt.subplots(1, 1, figsize=(12, 10))
    colors = ['white'] + [plt.cm.viridis(i / (p - 1)) for i in range(p)]
    cmap = mcolors.ListedColormap(colors[:p + 1])

    im = ax.imshow(triangle[:, :rows], cmap=cmap, aspect='equal',
                   interpolation='nearest', vmin=0, vmax=p - 1)
    ax.set_title(f"Pascal's Triangle mod {p} (first {rows} rows)", fontsize=16)
    ax.set_xlabel("Column k", fontsize=12)
    ax.set_ylabel("Row n", fontsize=12)

    ax.axhline(y=p, color='red', linewidth=2, linestyle='--', alpha=0.7)
    ax.text(rows + 1, p, f'← Row {p}: only 0s and 1s\n   (Freshman\'s Dream!)',
            fontsize=10, color='red', va='center')

    plt.colorbar(im, ax=ax, label=f'Value mod {p}', ticks=range(p))
    plt.tight_layout()
    plt.savefig('demos/pascals_triangle_mod_p.png', dpi=150, bbox_inches='tight')
    plt.close()
    print(f"✓ Pascal's triangle mod {p} saved to demos/pascals_triangle_mod_p.png")

    print(f"\nRow {p} of Pascal's triangle mod {p}:")
    row_p = [mod_binomial(p, k, p) for k in range(p + 1)]
    print(f"  C({p},k) mod {p} for k = 0..{p}: {row_p}")
    print(f"  → Only C({p},0) = 1 and C({p},{p}) = 1 are nonzero")
    print(f"  → This proves: (a+b)^{p} = a^{p} + b^{p} in characteristic {p}")


def demo_freshman_dream_verification(p=7):
    """
    Verify the Freshman's Dream computationally in Z/pZ.
    """
    print(f"\n{'='*60}")
    print(f"Freshman's Dream Verification in Z/{p}Z")
    print(f"{'='*60}")

    # Binary version
    violations = 0
    for a in range(p):
        for b in range(p):
            lhs = pow(a + b, p, p)
            rhs = (pow(a, p, p) + pow(b, p, p)) % p
            if lhs != rhs:
                violations += 1
    print(f"\nBinary (a+b)^{p} = a^{p} + b^{p}:")
    print(f"  Tested all {p*p} pairs (a,b) in Z/{p}Z")
    print(f"  Violations: {violations} {'✓ THEOREM VERIFIED' if violations == 0 else '✗ ERROR'}")

    # Fermat's Little Theorem
    print(f"\nFermat's Little Theorem: a^{p} = a in Z/{p}Z")
    for a in range(p):
        ap = pow(a, p, p)
        print(f"  {a}^{p} ≡ {ap} (mod {p}) {'✓' if ap == a else '✗'}")

    # Multinomial version (triples)
    violations = 0
    for a in range(p):
        for b in range(p):
            for c in range(p):
                lhs = pow(a + b + c, p, p)
                rhs = (pow(a, p, p) + pow(b, p, p) + pow(c, p, p)) % p
                if lhs != rhs:
                    violations += 1
    print(f"\nMultinomial (a+b+c)^{p} = a^{p} + b^{p} + c^{p}:")
    print(f"  Tested all {p**3} triples (a,b,c) in Z/{p}Z")
    print(f"  Violations: {violations} {'✓ THEOREM VERIFIED' if violations == 0 else '✗ ERROR'}")


