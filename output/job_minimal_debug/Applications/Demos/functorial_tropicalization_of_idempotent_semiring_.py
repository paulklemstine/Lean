def demo_ring_decomposition():
    """
    Demonstrate ring decomposition via idempotents.

    For n = p₁·p₂·...·pₖ (squarefree), the Chinese Remainder Theorem gives:
      Z/nZ ≅ Z/p₁Z × Z/p₂Z × ... × Z/pₖZ

    Each idempotent e corresponds to a "projection" onto a subset of factors.
    """
    print("\n╔══════════════════════════════════════════════════════════╗")
    print("║  APPLICATION 3: Ring Decomposition via Idempotents      ║")
    print("╚══════════════════════════════════════════════════════════╝")

    n = 30  # 2 × 3 × 5
    factors = [2, 3, 5]

    print(f"\n  Z/{n}Z ≅ Z/2Z × Z/3Z × Z/5Z (Chinese Remainder Theorem)")

    # Find idempotents
    idempotents = sorted([a for a in range(n) if (a * a) % n == a])
    print(f"  Idempotents: {idempotents}")

    # Map each idempotent to its CRT decomposition
    print(f"\n  {'Idempotent e':>14}  {'e mod 2':>8}  {'e mod 3':>8}  {'e mod 5':>8}  {'Interpretation':>20}")
    print(f"  {'─'*65}")

    for e in idempotents:
        residues = tuple(e % p for p in factors)
        # Interpret which factors are "selected"
        selected = [str(p) for p, r in zip(factors, residues) if r == 1]
        interp = "proj onto " + "×".join(selected) if selected else "zero map"
        print(f"  {e:>14}  {residues[0]:>8}  {residues[1]:>8}  {residues[2]:>8}  {interp:>20}")

    # Visualize the Boolean lattice
    fig, ax = plt.subplots(figsize=(10, 8))

    # Hasse diagram of the Boolean algebra
    levels = {0: [], 1: [], 2: [], 3: []}
    for e in idempotents:
        residues = tuple(e % p for p in factors)
        level = sum(residues)
        levels[level].append((e, residues))

    # Position nodes
    positions = {}
    for level, items in levels.items():
        y = level
        n_items = len(items)
        for i, (e, res) in enumerate(items):
            x = (i - (n_items - 1) / 2) * 2
            positions[e] = (x, y)

    # Draw edges (e covers f if e·f = f and level(e) = level(f) + 1)
    for e in idempotents:
        for f in idempotents:
            if (e * f) % n == f and e != f:
                re = tuple(e % p for p in factors)
                rf = tuple(f % p for p in factors)
                if sum(re) == sum(rf) + 1:
                    x1, y1 = positions[e]
                    x2, y2 = positions[f]
                    ax.plot([x1, x2], [y1, y2], 'b-', alpha=0.3, linewidth=2)

    # Draw nodes
    for e, (x, y) in positions.items():
        residues = tuple(e % p for p in factors)
        color = '#4CAF50' if sum(residues) > 0 else '#9E9E9E'
        if sum(residues) == len(factors):
            color = '#FF5722'
        ax.plot(x, y, 'o', markersize=25, color=color, zorder=5)
        ax.text(x, y, str(e), ha='center', va='center',
                fontsize=12, fontweight='bold', color='white', zorder=6)

        # Label with CRT decomposition
        label = f"({','.join(str(r) for r in residues)})"
        ax.text(x, y - 0.35, label, ha='center', va='center',
                fontsize=8, color='gray', zorder=6)

    ax.set_xlim(-4, 4)
    ax.set_ylim(-0.5, 3.5)
    ax.set_title('Boolean Lattice of Idempotents in Z/30Z\n'
                 '(labels show CRT decomposition mod 2,3,5)',
                 fontsize=14)
    ax.set_ylabel('Level (number of active components)', fontsize=12)
    ax.set_aspect('equal')
    ax.axis('off')

    plt.tight_layout()
    plt.savefig('demos/idempotent_lattice.png', dpi=150, bbox_inches='tight')
    plt.close()
    print(f"\n  ✓ Boolean lattice diagram saved to demos/idempotent_lattice.png")


