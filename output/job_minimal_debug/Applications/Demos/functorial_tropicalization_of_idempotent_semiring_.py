def demo_idempotents_in_zn(max_n=30):
    """
    Find and count idempotent elements in Z/nZ for various n.

    The number of idempotents equals 2^ω(n) where ω(n) is the number of
    distinct prime factors of n.
    """
    print(f"\n{'='*60}")
    print(f"Idempotent Elements in Z/nZ")
    print(f"{'='*60}")

    def count_prime_factors(n):
        if n <= 1:
            return 0
        count = 0
        d = 2
        while d * d <= n:
            if n % d == 0:
                count += 1
                while n % d == 0:
                    n //= d
            d += 1
        if n > 1:
            count += 1
        return count

    print(f"\n  {'n':>4}  {'Idempotents':>30}  {'Count':>6}  {'2^ω(n)':>6}  {'Match':>5}")
    print(f"  {'─'*60}")

    data_n = []
    data_count = []

    for n in range(2, max_n + 1):
        idempotents = [a for a in range(n) if (a * a) % n == a]
        omega = count_prime_factors(n)
        expected = 2 ** omega
        match = len(idempotents) == expected

        idemp_str = (str(idempotents) if len(idempotents) <= 8
                     else f"{idempotents[:4]}...({len(idempotents)} total)")
        print(f"  {n:>4}  {idemp_str:>30}  {len(idempotents):>6}  {expected:>6}  {'✓' if match else '✗':>5}")

        data_n.append(n)
        data_count.append(len(idempotents))

    # Visualization
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    colors = ['#2196F3' if count_prime_factors(n) <= 1 else
              '#FF9800' if count_prime_factors(n) == 2 else
              '#F44336' if count_prime_factors(n) == 3 else '#9C27B0'
              for n in data_n]

    ax1.bar(data_n, data_count, color=colors, alpha=0.8)
    ax1.set_xlabel('n', fontsize=12)
    ax1.set_ylabel('Number of idempotents in Z/nZ', fontsize=12)
    ax1.set_title('Idempotent Count = 2^ω(n)', fontsize=14)

    legend_elements = [
        Patch(facecolor='#2196F3', label='ω(n) ≤ 1 (prime or prime power)'),
        Patch(facecolor='#FF9800', label='ω(n) = 2'),
        Patch(facecolor='#F44336', label='ω(n) = 3'),
        Patch(facecolor='#9C27B0', label='ω(n) ≥ 4'),
    ]
    ax1.legend(handles=legend_elements, fontsize=9)

    # Idempotent matrix
    max_vis = 20
    matrix = np.zeros((max_vis - 1, max_vis))
    for n in range(2, max_vis + 1):
        for a in range(n):
            if (a * a) % n == a:
                matrix[n - 2][a] = 1

    ax2.imshow(matrix, cmap='Blues', aspect='auto', interpolation='nearest')
    ax2.set_xlabel('Element a', fontsize=12)
    ax2.set_ylabel('Ring Z/nZ', fontsize=12)
    ax2.set_yticks(range(max_vis - 1))
    ax2.set_yticklabels(range(2, max_vis + 1))
    ax2.set_title('Idempotent Elements (blue = idempotent)', fontsize=14)

    plt.tight_layout()
    plt.savefig('demos/idempotents_in_zn.png', dpi=150, bbox_inches='tight')
    plt.close()
    print(f"\n✓ Idempotent visualization saved to demos/idempotents_in_zn.png")


def demo_idempotent_boolean_algebra():
    """
    Demonstrate the Boolean algebra structure on idempotents.
    """
    print(f"\n{'='*60}")
    print(f"Boolean Algebra of Idempotents in Z/30Z")
    print(f"{'='*60}")

    n = 30
    idempotents = sorted([a for a in range(n) if (a * a) % n == a])

    print(f"\n  Z/30Z has {len(idempotents)} idempotents: {idempotents}")
    print(f"  (30 = 2 × 3 × 5, so 2^3 = 8 idempotents)")

    print(f"\n  Boolean operations on idempotents:")
    print(f"  {'e':>4} {'f':>4} │ {'e∧f=ef':>8} {'e∨f=e+f-ef':>12} {'¬e=1-e':>8}")
    print(f"  {'─'*4} {'─'*4} │ {'─'*8} {'─'*12} {'─'*8}")

    for e in idempotents[:4]:
        for f in idempotents[:4]:
            meet = (e * f) % n
            join = (e + f - e * f) % n
            complement_e = (1 - e) % n
            print(f"  {e:>4} {f:>4} │ {meet:>8} {join:>12} {complement_e:>8}")

    print(f"\n  Complement table:")
    for e in idempotents:
        comp = (1 - e) % n
        print(f"    ¬{e} = {comp}")

    # Verify Boolean algebra axioms
    print(f"\n  Verification of Boolean algebra axioms:")
    all_ok = True
    for e in idempotents:
        comp_e = (1 - e) % n
        if (comp_e * comp_e) % n != comp_e:
            print(f"  ✗ Complement of {e} is not idempotent")
            all_ok = False
        if (e * comp_e) % n != 0:
            print(f"  ✗ e ∧ ¬e ≠ 0 for e={e}")
            all_ok = False
        join_comp = (e + comp_e - e * comp_e) % n
        if join_comp != 1 % n:
            print(f"  ✗ e ∨ ¬e ≠ 1 for e={e}")
            all_ok = False

    if all_ok:
        print(f"  ✓ All Boolean algebra axioms verified!")


def demo_multinomial_freshman_dream(p=5, k=4):
    """
    Demonstrate the multinomial Freshman's Dream for k-tuples.
    """
    print(f"\n{'='*60}")
    print(f"Multinomial Freshman's Dream (p={p}, {k} variables)")
    print(f"{'='*60}")

    random.seed(42)
    violations = 0
    n_tests = 10000

    for _ in range(n_tests):
        values = [random.randint(0, p - 1) for _ in range(k)]
        lhs = pow(sum(values), p, p)
        rhs = sum(pow(v, p, p) for v in values) % p
        if lhs != rhs:
            violations += 1

    print(f"\n  Tested {n_tests} random {k}-tuples in Z/{p}Z")
    print(f"  (a₁+...+a{k})^{p} = a₁^{p}+...+a{k}^{p}: ", end="")
    print(f"{'✓ ALL VERIFIED' if violations == 0 else f'✗ {violations} violations'}")

