# Algorithm 2: Euclidean Shadow Computation
# ============================================================

class EuclideanShadow:
    """
    The 2×2 Euclidean parameter shadow of the Berggren tree.

    Every primitive Pythagorean triple (a, b, c) with a odd comes from
    coprime parameters (m, n) via a = m²-n², b = 2mn, c = m²+n².

    The Berggren generators act on (m, n) by 2×2 integer matrices:
      A: (m, n) → (2m - n, m)
      B: (m, n) → (2m + n, m)
      C: (m, n) → (m + 2n, n)

    This shadow is functorial: it commutes with triple generation
    through the Euclid parametrization.
    """

    EUCLID_GENS = {
        'A': np.array([[ 2, -1], [ 1,  0]]),
        'B': np.array([[ 2,  1], [ 1,  0]]),
        'C': np.array([[ 1,  2], [ 0,  1]])
    }

    ROOT_PARAMS = np.array([2, 1])  # (3,4,5) = euclid(2, 1)

    @staticmethod
    def euclid_param(m: int, n: int) -> np.ndarray:
        """Map Euclid parameters to a Pythagorean triple."""
        return np.array([m*m - n*n, 2*m*n, m*m + n*n])

    def shadow_word(self, word: str) -> np.ndarray:
        """
        Evaluate a word in the Euclidean shadow.

        Returns (M, N) parameters after applying the shadow word.

        Time: O(|word|)
        """
        params = self.ROOT_PARAMS.copy()
        for ch in word:
            params = self.EUCLID_GENS[ch] @ params
        return params

    def verify_functoriality(self, word: str) -> bool:
        """
        Verify that the shadow commutes with triple generation.

        Checks: berggren_word(root) == euclid(shadow_word(root_params))
        """
        tree = BerggrenTree()
        triple_direct = tree.eval_word(word)
        params = self.shadow_word(word)
        triple_shadow = self.euclid_param(int(params[0]), int(params[1]))
        return np.array_equal(triple_direct, triple_shadow)


