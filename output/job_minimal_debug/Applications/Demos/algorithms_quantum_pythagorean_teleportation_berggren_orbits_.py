#!/usr/bin/env python3
"""
Algorithms for Berggren Orbit Dynamics and Quantum Shadow Computation

This module implements the core algorithms from the research paper:
1. Berggren tree traversal and word evaluation
2. Euclidean parameter shadow computation
3. SL(2, F_3) orbit enumeration
4. Circuit cost analysis via hypotenuse growth
"""

import numpy as np
from typing import List, Tuple, Dict, Optional, Set
from collections import deque
from math import gcd


# ============================================================
# Algorithm 1: Berggren Word Evaluation
# ============================================================

class BerggrenTree:
    """
    The Berggren ternary tree of primitive Pythagorean triples.

    The tree is rooted at (3, 4, 5) and generated by three integer
    matrix transformations A, B, C that preserve the Pythagorean
    condition a² + b² = c² and the primitiveness condition gcd(a,b) = 1.

    Time complexity: O(k) per word of length k
    Space complexity: O(1) per evaluation
    """

    GENERATORS = {
        'A': np.array([[ 1, -2,  2], [ 2, -1,  2], [ 2, -2,  3]]),
        'B': np.array([[ 1,  2,  2], [ 2,  1,  2], [ 2,  2,  3]]),
        'C': np.array([[-1,  2,  2], [-2,  1,  2], [-2,  2,  3]])
    }

    INVERSES = {
        'A': np.array([[ 1,  2, -2], [-2, -1,  2], [-2, -2,  3]]),
        'B': np.array([[ 1,  2, -2], [ 2,  1, -2], [-2, -2,  3]]),
        'C': np.array([[-1, -2,  2], [ 2,  1, -2], [-2, -2,  3]])
    }

    ROOT = np.array([3, 4, 5])

    def eval_word(self, word: str) -> np.ndarray:
        """
        Evaluate a Berggren word on the root triple.

        Args:
            word: String of characters from {A, B, C}

        Returns:
            Resulting Pythagorean triple as numpy array

        Time: O(|word|)
        Space: O(1)

        >>> tree = BerggrenTree()
        >>> tree.eval_word('A')
        array([ 5, 12, 13])
        >>> tree.eval_word('B')
        array([21, 20, 29])
        """
        t = self.ROOT.copy()
        for ch in word:
            t = self.GENERATORS[ch] @ t
        return t

    def find_word(self, triple: np.ndarray) -> Optional[str]:
        """
        Find the unique Berggren word generating a given primitive triple.

        Uses the descent algorithm: repeatedly apply inverse transforms
        until reaching the root (3, 4, 5).

        Args:
            triple: A primitive Pythagorean triple [a, b, c]

        Returns:
            The Berggren word, or None if the triple is not primitive

        Time: O(log c) where c is the hypotenuse
        Space: O(log c) for the word
        """
        t = triple.copy()
        word_reversed = []

        while not np.array_equal(t, self.ROOT):
            if t[2] <= 5:
                return None  # Not reachable

            # Try each inverse
            found = False
            for name, inv in self.INVERSES.items():
                candidate = inv @ t
                if all(candidate > 0):
                    word_reversed.append(name)
                    t = candidate
                    found = True
                    break

            if not found:
                return None

        return ''.join(reversed(word_reversed))

    def generate_level(self, depth: int) -> List[Tuple[str, np.ndarray]]:
        """
        Generate all triples at a given depth in the Berggren tree.

        Args:
            depth: Tree depth (0 = root)

        Returns:
            List of (word, triple) pairs

        Time: O(3^depth)
        Space: O(3^depth)
        """
        if depth == 0:
            return [("", self.ROOT)]

        result = []
        prev = self.generate_level(depth - 1)
        for word, triple in prev:
            for g in 'ABC':
                new_triple = self.GENERATORS[g] @ triple
                result.append((word + g, new_triple))
        return result


