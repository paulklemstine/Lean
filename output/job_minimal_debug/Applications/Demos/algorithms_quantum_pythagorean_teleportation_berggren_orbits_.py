# Algorithm 3: SL(2, F_3) Closure Computation
# ============================================================

class SL2F3Generator:
    """
    Compute and verify that Berggren Euclidean shadows generate SL(2, F_3).

    The mod-3 reductions of E_A = [[2,-1],[1,0]] and E_C = [[1,2],[0,1]]
    generate all 24 elements of SL(2, F_3) ≅ Sp(2, F_3), the qutrit
    symplectic group.
    """

    def __init__(self, p: int = 3):
        self.p = p
        self.EA = np.array([[2, -1], [1, 0]]) % p
        self.EC = np.array([[1, 2], [0, 1]]) % p

    def compute_closure(self) -> Set[Tuple[int, ...]]:
        """
        Compute the multiplicative closure of {E_A, E_C} mod p.

        Returns:
            Set of matrix tuples (flattened)

        Time: O(|closure|²) worst case
        """
        def key(M):
            return tuple(M.flatten())

        closure = {key(np.eye(2, dtype=int) % self.p)}
        queue = deque([np.eye(2, dtype=int) % self.p])

        while queue:
            M = queue.popleft()
            for gen in [self.EA, self.EC]:
                prod = (M @ gen) % self.p
                k = key(prod)
                if k not in closure:
                    closure.add(k)
                    queue.append(prod)

        return closure

    def verify_sl2(self) -> Dict:
        """
        Verify SL(2, F_p) generation.

        Returns:
            Dictionary with closure size, SL2 count, and verification status
        """
        closure = self.compute_closure()

        # Count elements with det ≡ 1 (mod p)
        det1_count = 0
        for k in closure:
            M = np.array(k).reshape(2, 2)
            det = int(round(np.linalg.det(M))) % self.p
            if det == 1:
                det1_count += 1

        # |SL(2, F_p)| = p(p²-1) = p³ - p
        expected = self.p * (self.p**2 - 1)

        return {
            'closure_size': len(closure),
            'det1_count': det1_count,
            'expected_sl2_size': expected,
            'is_sl2': det1_count == expected
        }


