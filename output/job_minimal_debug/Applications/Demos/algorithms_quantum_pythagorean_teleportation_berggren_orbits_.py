# Algorithm 4: Circuit Cost Analysis
# ============================================================

class CircuitCostAnalyzer:
    """
    Analyze the relationship between Berggren word length (circuit depth)
    and Pythagorean triple complexity (hypotenuse size).

    The formal theorem proves: hyp ≥ 5 + word_length for all words.
    Empirically, the growth is exponential.
    """

    def __init__(self):
        self.tree = BerggrenTree()

    def cost_statistics(self, max_depth: int) -> List[Dict]:
        """
        Compute hypotenuse statistics at each depth level.

        Args:
            max_depth: Maximum tree depth to analyze

        Returns:
            List of dicts with depth, min/max/mean hypotenuse, count
        """
        stats = []
        for depth in range(max_depth + 1):
            level = self.tree.generate_level(depth)
            hyps = [int(t[2]) for _, t in level]
            stats.append({
                'depth': depth,
                'count': len(hyps),
                'min_hyp': min(hyps),
                'max_hyp': max(hyps),
                'mean_hyp': np.mean(hyps),
                'formal_bound': 5 + depth,
                'bound_satisfied': all(h >= 5 + depth for h in hyps)
            })
        return stats

    def growth_ratio(self, gen: str, max_depth: int = 10) -> List[float]:
        """
        Compute the hypotenuse growth ratio along a single-generator branch.

        For generator B, this converges to 3 + 2√2 ≈ 5.828.

        Args:
            gen: Generator name ('A', 'B', or 'C')
            max_depth: Number of iterations

        Returns:
            List of successive ratios c_{n+1}/c_n
        """
        t = self.tree.ROOT.copy()
        ratios = []
        for _ in range(max_depth):
            old_hyp = t[2]
            t = BerggrenTree.GENERATORS[gen] @ t
            ratios.append(t[2] / old_hyp)
        return ratios


