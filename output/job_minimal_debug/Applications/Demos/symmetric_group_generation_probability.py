"""
Demo: Generation Probability of Symmetric Groups

Computes exact P_n values for small n, estimates via Monte Carlo for larger n,
and visualizes the convergence P_n → 1 as n → ∞ (Dixon's phenomenon).

Keywords: random generation, permutation statistics, probabilistic combinatorics,
          finite group sieve, transitivity certificates
"""

import itertools
import random
import math
from typing import List, Tuple, Optional


def all_permutations(n: int) -> List[Tuple[int, ...]]:
    """Generate all permutations of {0, 1, ..., n-1}."""
    return list(itertools.permutations(range(n)))


def compose(p: Tuple[int, ...], q: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compose two permutations: (p ∘ q)(i) = p(q(i))."""
    return tuple(p[q[i]] for i in range(len(p)))


def inverse(p: Tuple[int, ...]) -> Tuple[int, ...]:
    """Compute the inverse of a permutation."""
    inv = [0] * len(p)
    for i, v in enumerate(p):
        inv[v] = i
    return tuple(inv)


def closure(generators: List[Tuple[int, ...]], n: int) -> set:
    """Compute the subgroup closure of a set of generators via BFS."""
    identity = tuple(range(n))
    seen = {identity}
    queue = [identity]
    for g in generators:
        if g not in seen:
            seen.add(g)
            queue.append(g)
    
    idx = 0
    while idx < len(queue):
        current = queue[idx]
        idx += 1
        for g in generators:
            for new in [compose(current, g), compose(g, current),
                        compose(current, inverse(g)), compose(inverse(g), current)]:
                if new not in seen:
                    seen.add(new)
                    queue.append(new)
    return seen


def is_generating_pair(sigma: Tuple[int, ...], tau: Tuple[int, ...], n: int) -> bool:
    """Check if (σ, τ) generates the full symmetric group S_n."""
    return len(closure([sigma, tau], n)) == math.factorial(n)


def exact_generation_probability(n: int) -> float:
    """Compute the exact generation probability P_n for S_n by brute force."""
    if n <= 1:
        return 1.0
    perms = all_permutations(n)
    total = len(perms) ** 2
    count = 0
    for sigma in perms:
        for tau in perms:
            if is_generating_pair(sigma, tau, n):
                count += 1
    return count / total


def monte_carlo_generation_probability(n: int, samples: int = 10000) -> float:
    """Estimate P_n via Monte Carlo sampling."""
    count = 0
    elements = list(range(n))
    for _ in range(samples):
        sigma = tuple(random.sample(elements, n))
        tau = tuple(random.sample(elements, n))
        if is_generating_pair(sigma, tau, n):
            count += 1
    return count / samples


def is_n_cycle(perm: Tuple[int, ...]) -> bool:
    """Check if a permutation is a single n-cycle."""
    n = len(perm)
    if n <= 1:
        return True
    visited = [False] * n
    start = 0
    visited[start] = True
    current = perm[start]
    cycle_len = 1
    while current != start:
        visited[current] = True
        current = perm[current]
        cycle_len += 1
    return cycle_len == n


def sign(perm: Tuple[int, ...]) -> int:
    """Compute the sign of a permutation (+1 or -1)."""
    n = len(perm)
    visited = [False] * n
    num_cycles = 0
    for i in range(n):
        if not visited[i]:
            num_cycles += 1
            j = i
            while not visited[j]:
                visited[j] = True
                j = perm[j]
    return (-1) ** (n - num_cycles)


def has_mixing_property(tau: Tuple[int, ...], n: int) -> bool:
    """Check if τ has the mixing property: no nonempty proper subset is τ-invariant."""
    for size in range(1, n):
        for subset in itertools.combinations(range(n), size):
            s = set(subset)
            if all(tau[x] in s for x in s):
                return False
    return True


def check_certificate(sigma: Tuple[int, ...], tau: Tuple[int, ...], n: int) -> bool:
    """Check the SymmGenerationCertificate:
    1. σ is an n-cycle
    2. the pair acts transitively (implied by σ being an n-cycle)
    3. at least one permutation has sign -1
    """
    if not is_n_cycle(sigma):
        return False
    if sign(sigma) != -1 and sign(tau) != -1:
        return False
    return True


def certificate_density(n: int, samples: int = 10000) -> float:
    """Estimate the density of certificate-satisfying pairs."""
    count = 0
    elements = list(range(n))
    for _ in range(samples):
        sigma = tuple(random.sample(elements, n))
        tau = tuple(random.sample(elements, n))
        if check_certificate(sigma, tau, n):
            count += 1
    return count / samples


def dixon_bound(n: int) -> float:
    """Dixon's conjectured lower bound: 1 - 1/n - 2/n²."""
    if n == 0:
        return 0.0
    return 1.0 - 1.0/n - 2.0/(n*n)


def point_stabilizer_bound(n: int) -> float:
    """Upper bound on nongeneration from point stabilizers: 1/n."""
    if n == 0:
        return 1.0
    return 1.0 / n


def main():
    print("=" * 70)
    print("GENERATION PROBABILITY OF SYMMETRIC GROUPS")
    print("P_n = Pr[two random permutations generate S_n]")
