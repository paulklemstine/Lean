def random_transposition(n: int) -> Tuple[int, ...]:
    """Generate a random transposition in S_n."""
    perm = list(range(n))
    i, j = random.sample(range(n), 2)
    perm[i], perm[j] = perm[j], perm[i]
    return tuple(perm)


def random_circuit_reachability(n: int, num_gates: int, trials: int = 500) -> float:
    """
    Simulate a random reversible circuit with `num_gates` transposition gates.
    
    In reversible computing, a circuit of transposition gates on n bits
    generates a subgroup of S_n. The generation probability theory tells us
    how many gates suffice to generate the full group with high probability.
    
    Returns the fraction of trials where the full S_n is generated.
    """
    nfact = math.factorial(n)
    success = 0
    
    for _ in range(trials):
        gates = [random_transposition(n) for _ in range(num_gates)]
        if len(subgroup_closure(gates, n)) == nfact:
            success += 1
    
    return success / trials


