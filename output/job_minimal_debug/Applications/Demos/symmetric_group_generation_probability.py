def puzzle_solvability(n: int, num_moves: int = 2, trials: int = 500) -> Dict:
    """
    Many combinatorial puzzles (15-puzzle, Rubik's cube variants) are
    defined by a small set of allowed moves (permutations). The puzzle 
    is solvable iff the moves generate the full symmetric (or alternating) group.
    
    This simulates random puzzle design: given n positions and num_moves
    random allowed moves, what fraction of puzzles are fully solvable?
    """
    nfact = math.factorial(n)
    solvable = 0
    half_solvable = 0  # generates A_n but not S_n
    
    for _ in range(trials):
        moves = [tuple(random.sample(range(n), n)) for _ in range(num_moves)]
        cl = subgroup_closure(moves, n)
        cl_size = len(cl)
        
        if cl_size == nfact:
            solvable += 1
        elif cl_size == nfact // 2:
            half_solvable += 1
    
    return {
        "n": n,
        "num_moves": num_moves,
        "fully_solvable_rate": solvable / trials,
        "half_solvable_rate": half_solvable / trials,
        "unsolvable_rate": 1 - (solvable + half_solvable) / trials,
    }


