def assess_key_generation(n: int, trials: int = 1000) -> Dict:
    """
    In some symmetric-key schemes, the key defines a permutation.
    Two independent keys define a pair; if they generate S_n,
    the combined cipher can reach any permutation.
    
    This function estimates the probability that two random keys
    produce a cryptographically complete system.
    """
    nfact = math.factorial(n)
    generating = 0
    transitive_only = 0
    
    for _ in range(trials):
        key1 = tuple(random.sample(range(n), n))
        key2 = tuple(random.sample(range(n), n))
        
        cl = subgroup_closure([key1, key2], n)
        if len(cl) == nfact:
            generating += 1
        
        # Check transitivity: can we reach every element from 0?
        orbit = {0}
        changed = True
        while changed:
            changed = False
            new_orbit = set(orbit)
            for x in orbit:
                for perm in [key1, key2, inverse(key1), inverse(key2)]:
                    if perm[x] not in new_orbit:
                        new_orbit.add(perm[x])
                        changed = True
            orbit = new_orbit
        
        if len(orbit) == n:
            transitive_only += 1
    
    return {
        "n": n,
        "generation_rate": generating / trials,
        "transitivity_rate": transitive_only / trials,
        "security_assessment": "GOOD" if generating / trials > 0.9 else "WEAK",
    }


