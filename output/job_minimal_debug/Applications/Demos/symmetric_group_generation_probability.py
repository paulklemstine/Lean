def riffle_shuffle(deck: List[int]) -> List[int]:
    """Simulate a single riffle shuffle (Gilbert-Shannon-Reeds model)."""
    n = len(deck)
    # Cut position ~ Binomial(n, 1/2)
    cut = sum(1 for _ in range(n) if random.random() < 0.5)
    left = deck[:cut]
    right = deck[cut:]
    result = []
    while left or right:
        if not right or (left and random.random() < len(left) / (len(left) + len(right))):
            result.append(left.pop(0))
        else:
            result.append(right.pop(0))
    return result


def deck_to_perm(deck: List[int]) -> Tuple[int, ...]:
    """Convert deck state to permutation tuple."""
    return tuple(deck)


def compose(p: Tuple[int, ...], q: Tuple[int, ...]) -> Tuple[int, ...]:
    return tuple(p[q[i]] for i in range(len(p)))


def inverse(p: Tuple[int, ...]) -> Tuple[int, ...]:
    inv = [0] * len(p)
    for i, v in enumerate(p):
        inv[v] = i
    return tuple(inv)


def subgroup_closure(generators: List[Tuple[int, ...]], n: int) -> set:
    """Compute the subgroup generated by the given permutations."""
    from collections import deque
    e = tuple(range(n))
    seen = {e}
    queue = deque([e])
    all_gens = generators + [inverse(g) for g in generators]
    for g in all_gens:
        if g not in seen:
            seen.add(g)
            queue.append(g)
    while queue:
        current = queue.popleft()
        for g in all_gens:
            for new in [compose(current, g), compose(g, current)]:
                if new not in seen:
                    seen.add(new)
                    queue.append(new)
    return seen


def analyze_shuffle_generation(n: int, num_shuffles: int = 2, trials: int = 1000) -> Dict:
    """
    Analyze whether applying num_shuffles independent riffle shuffles to a deck
    of size n typically generates the full symmetric group.
    
    This connects to the generation probability: if two random shuffles 
    generate S_n, then any sequence achievable by those shuffles can be reached.
    """
    full_generation_count = 0
    nfact = math.factorial(n)
    
    for _ in range(trials):
        deck = list(range(n))
        shuffles = []
        for _ in range(num_shuffles):
            deck_copy = list(range(n))
            shuffled = riffle_shuffle(deck_copy)
            shuffles.append(deck_to_perm(shuffled))
        
        # Check if the shuffles generate S_n
        closure_size = len(subgroup_closure(shuffles, n))
        if closure_size == nfact:
            full_generation_count += 1
    
    return {
        "n": n,
        "num_shuffles": num_shuffles,
        "trials": trials,
        "full_generation_rate": full_generation_count / trials,
        "expected_by_dixon": 1.0 - 1.0/n if n > 1 else 1.0,
    }


