#!/usr/bin/env python3
"""
Pell Sequence and B₂-Branch Demo

The B₂ branch of the Berggren tree produces the remarkable sequence:
  (3,4,5) → (21,20,29) → (119,120,169) → (697,696,985) → ...

The hypotenuses satisfy the Pell recurrence: c_{n+1} = 6c_n - c_{n-1}
with characteristic roots 3 ± 2√2.

This demo explores the deep connections between:
1. The B₂-branch Pell recurrence
2. The continued fraction expansion of √2
3. The Pell equation x² - 2y² = ±1
4. Chebyshev polynomials of the first kind
"""

from math import sqrt, gcd
import sys


def b2_branch(n_terms=20):
    """Generate the first n_terms of the B₂ branch."""
    a, b, c = 3, 4, 5
    triples = [(a, b, c)]
    for _ in range(n_terms - 1):
        a, b, c = a + 2*b + 2*c, 2*a + b + 2*c, 2*a + 2*b + 3*c
        triples.append((a, b, c))
    return triples


def pell_equation_connection():
    """Show the connection between B₂ hypotenuses and Pell numbers."""
    print("=" * 70)
    print("  PELL EQUATION CONNECTION")
    print("=" * 70)
    print()
    print("  The Pell equation x² - 2y² = 1 has solutions (xₙ, yₙ)")
    print("  generated by (x + y√2)ⁿ = (1 + √2)ⁿ:")
    print()

    # Pell solutions
    x, y = 1, 0
    pell_solutions = [(x, y)]
    for _ in range(15):
        x, y = x + 2*y, x + y  # multiply by (1+√2)
        pell_solutions.append((x, y))

    # B₂ hypotenuses
    triples = b2_branch(10)
    hyps = [c for _, _, c in triples]
    legs = [(a, b) for a, b, _ in triples]

    print(f"  {'n':>3}  {'Pell (x,y)':>20}  {'x²-2y²':>8}  {'B₂ hyp':>10}  {'B₂ legs':>20}")
    print("  " + "-" * 65)
    for i in range(10):
        px, py = pell_solutions[i]
        pell_val = px*px - 2*py*py
        hyp = hyps[i] if i < len(hyps) else "—"
        leg = f"({legs[i][0]}, {legs[i][1]})" if i < len(legs) else "—"
        print(f"  {i:>3}  ({px:>8}, {py:>8})  {pell_val:>8}  {hyp:>10}  {leg:>20}")

    print()
    print("  Connection: The B₂ hypotenuses c_n satisfy")
    print("  c_{n+1} = 6c_n - c_{n-1}")
    print()
    print("  The Pell numbers x_n satisfy the SAME recurrence:")
    print("  x_{n+1} = 2x_n + x_{n-1} (but different initial conditions)")
    print()
    print("  Both sequences are governed by the same characteristic")
    print(f"  polynomial: λ² - 6λ + 1 = 0, with roots 3 ± 2√2")
    print(f"  3 + 2√2 = {3 + 2*sqrt(2):.10f}")
    print(f"  3 - 2√2 = {3 - 2*sqrt(2):.10f}")
    print()


def continued_fraction_sqrt2():
    """Show the continued fraction expansion of √2 and its relation to B₂."""
    print("=" * 70)
    print("  CONTINUED FRACTION CONNECTION")
    print("=" * 70)
    print()
    print("  √2 = [1; 2, 2, 2, 2, ...] (periodic continued fraction)")
    print()
    print("  Convergents p_n/q_n of √2:")
    print()

    p_prev, p_curr = 1, 1
    q_prev, q_curr = 0, 1
    convergents = [(p_curr, q_curr)]

    for i in range(15):
        a_i = 2  # all partial quotients are 2
        p_next = a_i * p_curr + p_prev
        q_next = a_i * q_curr + q_prev
        convergents.append((p_next, q_next))
        p_prev, p_curr = p_curr, p_next
        q_prev, q_curr = q_curr, q_next

    print(f"  {'n':>3}  {'p_n':>10}  {'q_n':>10}  {'p_n/q_n':>15}  {'|p²-2q²|':>10}")
    for i, (p, q) in enumerate(convergents[:12]):
        ratio = p / q if q > 0 else float('inf')
        diff = abs(p*p - 2*q*q)
        print(f"  {i:>3}  {p:>10}  {q:>10}  {ratio:>15.10f}  {diff:>10}")

    print(f"\n  √2 = {sqrt(2):.10f}")
    print()
    print("  The ratio a_n/b_n of the B₂-branch legs converges to 1,")
    print("  and the ratio (a_n+b_n)/c_n converges to √2.")
    print()

    triples = b2_branch(10)
    print(f"  {'n':>3}  {'(a+b)/c':>15}  {'|a-b|':>6}  {'a/b':>15}")
    for i, (a, b, c) in enumerate(triples):
        print(f"  {i:>3}  {(a+b)/c:>15.10f}  {abs(a-b):>6}  {a/b:>15.10f}")
    print(f"\n  √2 = {sqrt(2):.10f}")
    print()


def near_isosceles_property():
    """The B₂ branch produces 'almost isosceles' right triangles."""
    print("=" * 70)
    print("  NEAR-ISOSCELES RIGHT TRIANGLES")
    print("=" * 70)
    print()
    print("  The B₂ branch produces PPTs where |a - b| = 1 always!")
    print("  These are the closest a PPT can get to being isosceles.")
    print()

    triples = b2_branch(12)
    print(f"  {'n':>3}  {'a':>15}  {'b':>15}  {'c':>15}  {'a-b':>4}  {'c²=a²+b²':>5}")
    for i, (a, b, c) in enumerate(triples):
        check = "✓" if a*a + b*b == c*c else "✗"
        print(f"  {i:>3}  {a:>15}  {b:>15}  {c:>15}  {a-b:>4}  {check:>5}")

    print()
    print("  This is the sequence of 'almost-isosceles Pythagorean triples'")
    print("  (OEIS A001652, A001653, A002315)")
    print()
    print("  The legs alternate: a > b, then b > a, then a > b, ...")
    print("  The eigenvector (1,-1,0) of B₂ with eigenvalue -1 controls")
    print("  this alternation: it adds an oscillating ±1 to the leg difference.")
    print()


def fibonacci_overlap():
    """Find Fibonacci numbers that appear as B₂ hypotenuses."""
    print("=" * 70)
    print("  FIBONACCI-PELL OVERLAP")
    print("=" * 70)
    print()

    # Generate Fibonacci numbers
    fibs = set()
    a, b = 1, 1
    for _ in range(50):
        fibs.add(a)
        a, b = b, a + b

    # B₂ hypotenuses
    triples = b2_branch(15)
    hyps = [c for _, _, c in triples]

    print("  B₂ hypotenuses that are also Fibonacci numbers:")
    for c in hyps:
        if c in fibs:
            print(f"    c = {c} ✓ (Fibonacci)")
        else:
            print(f"    c = {c}")
        if c > 10**12:
            break

    print()
    print("  The overlap is finite: only c = 5 is both a B₂ hypotenuse")
    print("  and a Fibonacci number (in the range we checked).")
    print("  This is because Fibonacci numbers grow as φⁿ ≈ 1.618ⁿ,")
    print("  while B₂ hypotenuses grow as (3+2√2)ⁿ ≈ 5.828ⁿ.")
    print()


