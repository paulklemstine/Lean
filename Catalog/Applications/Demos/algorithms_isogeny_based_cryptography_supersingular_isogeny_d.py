# Algorithm 4: Random Walk on Isogeny Graph
# ============================================================

def isogeny_random_walk(num_vertices: int, degree: int,
                        start: int, length: int) -> List[int]:
    """
    Simulate a random walk on a regular graph (modeling isogeny graph).

    In the supersingular ℓ-isogeny graph:
    - Each vertex has ℓ+1 neighbors
    - The graph is Ramanujan (optimal expansion)
    - Mixing time is O(log |V|)
    """
    path = [start]
    current = start

    for _ in range(length):
        # In a (degree)-regular graph, pick a random neighbor
        # Simplified: use hash-like function to simulate regularity
        neighbors = [(current * (i + 2) + i * i + 7) % num_vertices
                     for i in range(degree)]
        current = random.choice(neighbors)
        path.append(current)

    return path


def estimate_mixing_time(num_vertices: int) -> int:
    """
    Estimate mixing time for Ramanujan graph.
    For a Ramanujan graph, mixing time is O(log |V|).
    """
    import math
    return int(math.log2(num_vertices)) + 1


# ============================================================
# Algorithm 5: CGL Hash Function
# ============================================================

def cgl_hash(message: bytes, num_vertices: int, start: int) -> int:
    """
    Charles-Goren-Lauter hash function (simplified).

    Walk on the supersingular 2-isogeny graph according to message bits.
    Each bit determines which of the 3 neighbors to visit
    (the 2-isogeny graph is 3-regular).
    """
    current = start

    for byte in message:
        for bit_pos in range(8):
            bit = (byte >> bit_pos) & 1
            # In the real CGL hash, the bit determines the isogeny direction
            # Here we simulate with a deterministic function
            if bit == 0:
                current = (current * 2 + 1) % num_vertices
            else:
                current = (current * 2 + current + 3) % num_vertices

    return current


