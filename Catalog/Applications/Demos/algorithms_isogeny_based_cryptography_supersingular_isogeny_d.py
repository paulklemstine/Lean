# ============================================================
# Algorithm 1: SIDH Key Exchange
# ============================================================

@dataclass
class SIDHPublicParams:
    """Public parameters for SIDH."""
    eA: int  # Alice's exponent (2^eA-isogenies)
    eB: int  # Bob's exponent (3^eB-isogenies)
    p: int   # Prime: p = 2^eA * 3^eB - 1

    @property
    def nA(self) -> int:
        return 2 ** self.eA

    @property
    def nB(self) -> int:
        return 3 ** self.eB


@dataclass
class SIDHKeyPair:
    """A key pair for SIDH."""
    secret: int
    public_curve: int  # j-invariant of public curve
    torsion_images: List[int]  # Images of partner's torsion points


def sidh_keygen_alice(params: SIDHPublicParams, j0: int,
                       secret: int) -> SIDHKeyPair:
    """
    Alice's key generation.

    Pseudocode:
        1. Compute φ_A : E₀ → E_A (kernel generated by secret)
        2. Publish j(E_A) and φ_A(P_B), φ_A(Q_B)
    """
    N = params.nA * params.nB
    public = (j0 + secret * params.nB) % N

    # Torsion images (simplified model)
    torsion = []
    for b in range(min(3, params.nB)):
        img = (j0 + b * params.nA + secret * params.nB) % N
        torsion.append(img)

    return SIDHKeyPair(secret=secret, public_curve=public, torsion_images=torsion)


def sidh_keygen_bob(params: SIDHPublicParams, j0: int,
                     secret: int) -> SIDHKeyPair:
    """Bob's key generation (analogous to Alice's)."""
    N = params.nA * params.nB
    public = (j0 + secret * params.nA) % N

    torsion = []
    for a in range(min(3, params.nA)):
        img = (j0 + a * params.nB + secret * params.nA) % N
        torsion.append(img)

    return SIDHKeyPair(secret=secret, public_curve=public, torsion_images=torsion)


def sidh_shared_secret(params: SIDHPublicParams, my_secret: int,
                        partner_public: int, is_alice: bool) -> int:
    """
    Compute shared secret.

    Both parties apply their secret isogeny to the partner's public curve.
    The commutativity theorem guarantees they get the same result.
    """
    N = params.nA * params.nB
    if is_alice:
        return (partner_public + my_secret * params.nB) % N
    else:
        return (partner_public + my_secret * params.nA) % N


# ============================================================
# Algorithm 2: Euler's Four-Square Identity
# ============================================================

def quaternion_norm(a: int, b: int, c: int, d: int) -> int:
    """Compute the Hamilton quaternion norm: a² + b² + c² + d²."""
    return a**2 + b**2 + c**2 + d**2


def quaternion_multiply(q1: Tuple[int, int, int, int],
                        q2: Tuple[int, int, int, int]) -> Tuple[int, int, int, int]:
    """
    Multiply two quaternions q1 * q2.

    Hamilton's formula:
        (a₁ + b₁i + c₁j + d₁k)(a₂ + b₂i + c₂j + d₂k)
    """
    a1, b1, c1, d1 = q1
    a2, b2, c2, d2 = q2

    return (
        a1*a2 - b1*b2 - c1*c2 - d1*d2,
        a1*b2 + b1*a2 + c1*d2 - d1*c2,
        a1*c2 - b1*d2 + c1*a2 + d1*b2,
        a1*d2 + b1*c2 - c1*b2 + d1*a2
    )


def verify_euler_identity(q1: Tuple[int, int, int, int],
                          q2: Tuple[int, int, int, int]) -> bool:
    """
    Verify Euler's four-square identity: N(q1)·N(q2) = N(q1·q2).

    This is the algebraic foundation of:
    - Quaternion norm multiplicativity
    - Isogeny degree multiplicativity: deg(φψ) = deg(φ)·deg(ψ)
    - The Deuring correspondence
    """
    n1 = quaternion_norm(*q1)
    n2 = quaternion_norm(*q2)
    product = quaternion_multiply(q1, q2)
    n_product = quaternion_norm(*product)

    return n1 * n2 == n_product


