# Algorithm 3: Castryck-Decru Attack (Simplified)
# ============================================================

@dataclass
class TorsionData:
    """Auxiliary torsion point data published in SIDH."""
    public_curve: int
    torsion_images: List[int]


def castryck_decru_attack(params: SIDHPublicParams, j0: int,
                          torsion_data: TorsionData) -> Optional[int]:
    """
    Simplified Castryck-Decru attack.

    Pseudocode:
        1. Use torsion images to construct Kani decomposition
        2. Factor the (2,2)-isogeny via Richelot isogenies
        3. After eA steps, recover Alice's secret

    In our simplified model, we directly solve the linear equation.
    """
    N = params.nA * params.nB

    if len(torsion_data.torsion_images) < 2:
        return None

    # The torsion image at index 1 gives us:
    # torsion_images[1] = (j0 + nA + secret * nB) mod N
    target = torsion_data.torsion_images[1]
    base = (j0 + params.nA) % N

    # Solve: target = base + secret * nB mod N
    diff = (target - base) % N

    # Since gcd(nB, N) = nB (not coprime to N), we solve mod nA
    # diff = secret * nB mod N
    # diff / nB mod nA = secret mod nA
    if diff % params.nB != 0:
        return None

    recovered = (diff // params.nB) % params.nA
    return recovered


