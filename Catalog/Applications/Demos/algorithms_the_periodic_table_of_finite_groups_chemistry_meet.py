"""
Algorithms for the Periodic Table of Finite Groups.

Implements group classification, derived depth computation, valence calculation,
and the big omega function. All algorithms operate on groups represented as
permutation groups or multiplication tables.

Author: Research Team
"""

from typing import List, Set, Tuple, Dict, Optional
from itertools import product as cartprod
from math import gcd, log2
from collections import Counter


def big_omega(n: int) -> int:
    """Count prime factors of n with multiplicity (Ω function).

    Args:
        n: A non-negative integer.

    Returns:
        The number of prime factors counted with multiplicity.
        Ω(0) = Ω(1) = 0.

    Examples:
        >>> big_omega(12)  # 12 = 2^2 * 3
        3
        >>> big_omega(7)   # prime
        1
    """
    if n <= 1:
        return 0
    count = 0
    d = 2
    while d * d <= n:
        while n % d == 0:
            count += 1
            n //= d
        d += 1
    if n > 1:
        count += 1
    return count


def prime_factorization(n: int) -> Dict[int, int]:
    """Return the prime factorization of n as {prime: exponent}.

    Args:
        n: A positive integer.

    Returns:
        Dictionary mapping primes to their exponents.
    """
    factors: Dict[int, int] = {}
    d = 2
    while d * d <= n:
        while n % d == 0:
            factors[d] = factors.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        factors[n] = factors.get(n, 0) + 1
    return factors


class FiniteGroup:
    """Represents a finite group via its multiplication table.

    Attributes:
        n: Order of the group.
        table: n×n multiplication table where table[i][j] = i*j.
        identity: Index of the identity element.
    """

    def __init__(self, table: List[List[int]]):
        self.n = len(table)
        self.table = table
        self.identity = self._find_identity()

    def _find_identity(self) -> int:
        for e in range(self.n):
            if all(self.table[e][j] == j for j in range(self.n)):
                if all(self.table[j][e] == j for j in range(self.n)):
                    return e
        raise ValueError("No identity element found — not a valid group table")

    def mul(self, a: int, b: int) -> int:
        return self.table[a][b]

    def inverse(self, a: int) -> int:
        for b in range(self.n):
            if self.mul(a, b) == self.identity:
                return b
        raise ValueError(f"No inverse for element {a}")

    def commutator(self, a: int, b: int) -> int:
        """Compute [a,b] = a*b*a^{-1}*b^{-1}."""
        return self.mul(self.mul(self.mul(a, b), self.inverse(a)), self.inverse(b))

    def is_abelian(self) -> bool:
        return all(
            self.table[i][j] == self.table[j][i]
            for i in range(self.n)
            for j in range(self.n)
        )

    def subgroup_generated_by(self, generators: Set[int]) -> Set[int]:
        """Compute the subgroup generated by a set of elements."""
        sub = set(generators)
        sub.add(self.identity)
        changed = True
        while changed:
            changed = False
            new = set()
            for a in sub:
                for b in sub:
                    p = self.mul(a, b)
                    if p not in sub:
                        new.add(p)
                inv_a = self.inverse(a)
                if inv_a not in sub:
                    new.add(inv_a)
            if new:
                sub |= new
                changed = True
        return sub

    def commutator_subgroup(self, subgroup: Set[int]) -> Set[int]:
        """Compute [H, H] for a subgroup H."""
        commutators = set()
        for a in subgroup:
            for b in subgroup:
                commutators.add(self.commutator(a, b))
        return self.subgroup_generated_by(commutators)

    def derived_series(self) -> List[Set[int]]:
        """Compute the derived series G = G^(0) ⊇ G^(1) ⊇ ..."""
        series = [set(range(self.n))]
        while True:
            next_sub = self.commutator_subgroup(series[-1])
            if next_sub == series[-1]:
                break
            series.append(next_sub)
            if next_sub == {self.identity}:
                break
        return series

    def derived_depth(self) -> Optional[int]:
        """Compute the derived depth (None if not solvable)."""
        series = self.derived_series()
        if series[-1] == {self.identity}:
            return len(series) - 1
        return None

    def is_solvable(self) -> bool:
        return self.derived_depth() is not None

    def is_normal(self, subgroup: Set[int]) -> bool:
        """Check if a subgroup is normal."""
        return all(
            self.mul(self.mul(g, h), self.inverse(g)) in subgroup
            for g in range(self.n)
            for h in subgroup
        )

    def all_subgroups(self) -> List[Set[int]]:
        """Find all subgroups (brute force for small groups)."""
        subgroups = [{self.identity}, set(range(self.n))]
        for size in range(2, self.n):
            if self.n % size != 0:
                continue
            from itertools import combinations
            for combo in combinations(range(self.n), size):
                s = set(combo)
                if self.identity in s:
                    gen = self.subgroup_generated_by(s)
                    if gen == s and gen not in subgroups:
                        subgroups.append(gen)
        return subgroups

    def normal_subgroups(self) -> List[Set[int]]:
        """Find all normal subgroups."""
        return [s for s in self.all_subgroups() if self.is_normal(s)]

    def minimal_normal_subgroups(self) -> List[Set[int]]:
        """Find all minimal normal subgroups.

        A minimal normal subgroup is a nontrivial normal subgroup containing
        no proper nontrivial normal subgroup. For simple groups, the whole
        group is the unique minimal normal subgroup.
        """
        normals = self.normal_subgroups()
        trivial = {self.identity}
        nontrivial_normals = [n for n in normals if n != trivial]

        minimals = []
        for n in nontrivial_normals:
            is_minimal = True
            for m in nontrivial_normals:
                if m != n and m.issubset(n) and len(m) < len(n):
                    is_minimal = False
                    break
            if is_minimal:
                minimals.append(n)
        return minimals

    def valence(self) -> int:
        """Compute the group valence (number of minimal normal subgroups)."""
        return len(self.minimal_normal_subgroups())

    def classify_chemical_series(self) -> str:
        """Classify the group into a chemical series."""
        if self.is_cyclic():
            return "Noble Gas"
        if self.is_abelian():
            return "Alkaline Earth"
        if self.is_nilpotent():
            return "Alkali Metal"
        if self.is_solvable():
            return "Halogen"
        return "Transition Metal"

    def is_cyclic(self) -> bool:
        for g in range(self.n):
            if len(self.subgroup_generated_by({g})) == self.n:
                return True
        return False

    def is_nilpotent(self) -> bool:
        """Check nilpotency via lower central series."""
        lcs = [set(range(self.n))]
        while True:
            commutators = set()
            for a in lcs[-1]:
                for b in range(self.n):
                    commutators.add(self.commutator(a, b))
            next_sub = self.subgroup_generated_by(commutators)
            if next_sub == lcs[-1]:
                return False
            lcs.append(next_sub)
            if next_sub == {self.identity}:
                return True

    def nilpotency_class(self) -> Optional[int]:
        """Compute nilpotency class (None if not nilpotent)."""
        lcs = [set(range(self.n))]
        while True:
            commutators = set()
            for a in lcs[-1]:
                for b in range(self.n):
                    commutators.add(self.commutator(a, b))
            next_sub = self.subgroup_generated_by(commutators)
            if next_sub == lcs[-1]:
                return None
            lcs.append(next_sub)
            if next_sub == {self.identity}:
                return len(lcs) - 1


def make_cyclic_group(n: int) -> FiniteGroup:
    """Construct the cyclic group Z/nZ."""
    table = [[(i + j) % n for j in range(n)] for i in range(n)]
    return FiniteGroup(table)


def make_symmetric_group(n: int) -> FiniteGroup:
    """Construct S_n as a permutation group (with multiplication table).

    Warning: This is O(n!^2) in time and space. Only feasible for n ≤ 5.
    """
    from itertools import permutations

    perms = list(permutations(range(n)))
    perm_to_idx = {p: i for i, p in enumerate(perms)}

    def compose(p: tuple, q: tuple) -> tuple:
        return tuple(p[q[i]] for i in range(n))

    order = len(perms)
    table = [[perm_to_idx[compose(perms[i], perms[j])]
              for j in range(order)]
             for i in range(order)]
    return FiniteGroup(table)


def make_dihedral_group(n: int) -> FiniteGroup:
    """Construct the dihedral group D_{2n} of order 2n.

    Elements: (k, 0) for rotation by k, (k, 1) for reflection.
    Multiplication: (a, s) * (b, t) = ((a + (-1)^s * b) mod n, s XOR t)
    """
    order = 2 * n
    elements = [(k, s) for s in range(2) for k in range(n)]
    elem_to_idx = {e: i for i, e in enumerate(elements)}

    def mul_elem(e1: tuple, e2: tuple) -> tuple:
        a, s = e1
        b, t = e2
        if s == 0:
            return ((a + b) % n, t)
        else:
            return ((a - b) % n, 1 - t)

    table = [[elem_to_idx[mul_elem(elements[i], elements[j])]
              for j in range(order)]
             for i in range(order)]
    return FiniteGroup(table)


def periodic_table_analysis(max_order: int = 20) -> Dict[str, list]:
    """Analyze groups of small order and classify into chemical series.

    Args:
        max_order: Maximum group order to analyze.

    Returns:
        Dictionary with classification results.
    """
    results: Dict[str, list] = {
        "Noble Gas": [],
        "Alkaline Earth": [],
        "Alkali Metal": [],
        "Halogen": [],
        "Transition Metal": [],
    }

    for n in range(1, max_order + 1):
        # Cyclic group always exists
        g = make_cyclic_group(n)
        series = g.classify_chemical_series()
        results[series].append(f"Z_{n}")

        # Dihedral group for n >= 3
        if n >= 3:
            d = make_dihedral_group(n)
            series = d.classify_chemical_series()
            results[series].append(f"D_{2*n}")

    return results


def verify_periodic_law_conjecture(max_order: int = 30) -> List[Dict]:
    """Verify the Refined Periodic Law conjecture for small groups.

    Tests: derivedDepth(G) ≤ Ω(|G|) for cyclic and dihedral groups.

    Returns:
        List of test results.
    """
    results = []
    for n in range(2, max_order + 1):
        # Cyclic group
        g = make_cyclic_group(n)
        dd = g.derived_depth()
        omega = big_omega(n)
        results.append({
            "group": f"Z_{n}",
            "order": n,
            "derived_depth": dd,
            "big_omega": omega,
            "conjecture_holds": dd is not None and dd <= omega,
            "chemical_series": g.classify_chemical_series(),
        })

        # Dihedral group
        if n >= 3:
            d = make_dihedral_group(n)
            dd = d.derived_depth()
            omega_val = big_omega(2 * n)
            results.append({
                "group": f"D_{2*n}",
                "order": 2 * n,
                "derived_depth": dd,
                "big_omega": omega_val,
                "conjecture_holds": dd is not None and dd <= omega_val,
                "chemical_series": d.classify_chemical_series(),
            })

    return results


