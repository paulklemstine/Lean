#!/usr/bin/env python3
"""
demo.py — The Periodic Table of Finite Groups

Demonstrates the chemical classification of finite groups by computing
structural invariants (center size, derived length, nilpotency class)
for all groups of small order.

Uses GAP-like computations implemented from scratch in Python.
"""

from itertools import product as cart_product
from math import gcd, log2
from collections import defaultdict


# === Group implementations ===

def cyclic_group(n):
    """Return the multiplication table of Z/nZ."""
    return [[( i + j) % n for j in range(n)] for i in range(n)]

def dihedral_group(n):
    """Return the multiplication table of D_n (order 2n).
    Elements: rotations r^i (0..n-1) and reflections s*r^i (n..2n-1)."""
    order = 2 * n
    table = [[0]*order for _ in range(order)]
    for a in range(order):
        for b in range(order):
            a_rot, a_ref = a < n, a >= n
            b_rot, b_ref = b < n, b >= n
            ai = a if a < n else a - n
            bi = b if b < n else b - n
            if a_rot and b_rot:
                table[a][b] = (ai + bi) % n
            elif a_rot and b_ref:
                table[a][b] = n + (ai + bi) % n
            elif a_ref and b_rot:
                table[a][b] = n + (ai - bi) % n
            else:  # both reflections
                table[a][b] = (ai - bi) % n
    return table

def direct_product(table1, table2):
    """Direct product of two groups given by multiplication tables."""
    n1, n2 = len(table1), len(table2)
    order = n1 * n2
    table = [[0]*order for _ in range(order)]
    for a in range(order):
        for b in range(order):
            a1, a2 = a // n2, a % n2
            b1, b2 = b // n2, b % n2
            table[a][b] = table1[a1][b1] * n2 + table2[a2][b2]
    return table


# === Group invariant computations ===

def compute_center(table):
    """Compute the center Z(G) as a list of element indices."""
    n = len(table)
    center = []
    for g in range(n):
        if all(table[g][h] == table[h][g] for h in range(n)):
            center.append(g)
    return center

def is_abelian(table):
    """Check if the group is abelian."""
    return len(compute_center(table)) == len(table)

def compute_commutator_subgroup(table):
    """Compute [G,G] = subgroup generated by all commutators [a,b] = a*b*a^{-1}*b^{-1}."""
    n = len(table)
    # Find inverses
    inv = [0]*n
    for i in range(n):
        for j in range(n):
            if table[i][j] == 0:
                inv[i] = j
                break

    # Compute all commutators
    commutators = set()
    for a in range(n):
        for b in range(n):
            # [a,b] = a*b*a^{-1}*b^{-1}
            ab = table[a][b]
            ainv_binv = table[inv[a]][inv[b]]
            comm = table[ab][ainv_binv]
            commutators.add(comm)

    # Generate the subgroup from commutators
    return generate_subgroup(table, commutators)

def generate_subgroup(table, generators):
    """Generate subgroup from a set of generators."""
    subgroup = set(generators)
    subgroup.add(0)  # identity
    changed = True
    while changed:
        changed = False
        new_elts = set()
        for a in subgroup:
            for b in subgroup:
                prod = table[a][b]
                if prod not in subgroup:
                    new_elts.add(prod)
                    changed = True
        subgroup.update(new_elts)
    return sorted(subgroup)

def compute_derived_series(table, max_depth=20):
    """Compute the derived series G = G^(0) ⊇ G^(1) ⊇ G^(2) ⊇ ..."""
    n = len(table)
    current = list(range(n))
    series = [current]

    for _ in range(max_depth):
        # Build restricted table for current subgroup
        sub_table = restriction_table(table, current)
        if sub_table is None:
            break
        comm = compute_commutator_subgroup(sub_table)
        # Map back to original indices
        next_sub = [current[i] for i in comm]
        if len(next_sub) == len(current):
            break  # stabilized
        current = next_sub
        series.append(current)
        if len(current) == 1:
            break
    return series

def restriction_table(table, elements):
    """Restrict multiplication table to a subset (must be a subgroup)."""
    idx_map = {e: i for i, e in enumerate(elements)}
    n = len(elements)
    sub_table = [[0]*n for _ in range(n)]
    for i, a in enumerate(elements):
        for j, b in enumerate(elements):
            prod = table[a][b]
            if prod not in idx_map:
                return None  # not closed
            sub_table[i][j] = idx_map[prod]
    return sub_table

def derived_length(table):
    """Compute the derived length of a solvable group."""
    series = compute_derived_series(table)
    if len(series[-1]) > 1:
        return None  # not solvable
    return len(series) - 1

def is_nilpotent_check(table, max_depth=20):
    """Check nilpotency by computing the lower central series."""
    n = len(table)
    current = list(range(n))

    for depth in range(max_depth):
        # Compute [G, current]
        inv = [0]*n
        for i in range(n):
            for j in range(n):
                if table[i][j] == 0:
                    inv[i] = j
                    break

        commutators = set()
        for a in range(n):
            for b in current:
                ab = table[a][b]
                ainv_binv = table[inv[a]][inv[b]]
                comm = table[ab][ainv_binv]
                commutators.add(comm)

        next_sub = generate_subgroup(table, commutators)
        if len(next_sub) == 1:
            return depth + 1  # nilpotency class
        if len(next_sub) == len(current):
            return None  # not nilpotent (stabilized without reaching trivial)
        current = next_sub

    return None

def classify_group(table):
    """Classify a group into its chemical series."""
    n = len(table)
    center = compute_center(table)
    ab = is_abelian(table)
    dl = derived_length(table)
    nilp = is_nilpotent_check(table)

    if n == 1:
        return "Vacuum"
    elif ab and is_cyclic(table):
        from sympy import isprime
        if isprime(n):
            return "Prime Element"
        return "Noble Gas"
    elif ab:
        return "Alkaline Earth"
    elif nilp is not None:
        return "Alkali Metal"
    elif dl is not None:
        return "Compound"
    else:
        return "Radioactive"

def is_cyclic(table):
    """Check if a group is cyclic."""
    n = len(table)
    for g in range(n):
        # Check if g generates the group
        seen = {0}
        current = g
        for _ in range(n):
            seen.add(current)
            current = table[current][g]
        if len(seen) == n:
            return True
    return False


