"""
Applications of Schanuel's Conjecture Framework

This module demonstrates real-world applications of the formal
transcendence theory infrastructure built around Schanuel's conjecture.
"""

import math
import cmath
from typing import List, Tuple, Dict, Optional
from fractions import Fraction


class TranscendenceCertificate:
    """
    A certificate that a complex number is transcendental over Q,
    conditional on Schanuel's conjecture.

    This implements the formal argument:
    1. Find a nonzero algebraic z such that exp(z) = target
       (or target is in the field generated by z and exp(z))
    2. Apply the Schanuel consequence: exp(nonzero algebraic) is transcendental
    """

    def __init__(self, target: complex, z: complex, description: str):
        """
        Args:
            target: The number claimed to be transcendental
            z: The algebraic number such that target relates to exp(z)
            description: Human-readable description of the argument
        """
        self.target = target
        self.z = z
        self.description = description
        self.exp_z = cmath.exp(z)

    def verify_numerically(self, tolerance: float = 1e-10) -> bool:
        """Check that exp(z) matches the target numerically."""
        return abs(self.exp_z - self.target) < tolerance

    def __repr__(self) -> str:
        return (f"TranscendenceCertificate(\n"
                f"  target = {self.target},\n"
                f"  z = {self.z},\n"
                f"  exp(z) = {self.exp_z},\n"
                f"  verified = {self.verify_numerically()},\n"
                f"  argument: {self.description}\n)")


def certify_e_transcendental() -> TranscendenceCertificate:
    """
    Produce a transcendence certificate for e, conditional on Schanuel.

    Argument: z = 1 is algebraic and nonzero.
    By Schanuel (n=1), trdeg(Q(1, e)) ≥ 1.
    Since 1 is algebraic, e must be transcendental.

    Returns:
        TranscendenceCertificate for e

    >>> cert = certify_e_transcendental()
    >>> cert.verify_numerically()
    True
    """
    return TranscendenceCertificate(
        target=math.e,
        z=1.0,
        description=(
            "z = 1 is algebraic and nonzero. "
            "Schanuel (n=1) gives trdeg(Q(1, e)) ≥ 1. "
            "Since 1 ∈ Q, we need trdeg contributed by e, "
            "so e is transcendental."
        )
    )


def certify_exp_sqrt2_transcendental() -> TranscendenceCertificate:
    """
    Produce a certificate that e^√2 is transcendental (conditional on Schanuel).

    Returns:
        TranscendenceCertificate for e^√2
    """
    z = math.sqrt(2)
    return TranscendenceCertificate(
        target=math.exp(z),
        z=z,
        description=(
            f"z = √2 is algebraic and nonzero. "
            f"Schanuel (n=1) gives trdeg(Q(√2, e^√2)) ≥ 1. "
            f"Since √2 is algebraic, e^√2 must be transcendental."
        )
    )


def certify_exp_algebraic_transcendental(
    alpha: complex,
    alpha_name: str = "α"
) -> Optional[TranscendenceCertificate]:
    """
    Produce a certificate that exp(α) is transcendental for nonzero algebraic α.

    This is the general n=1 Schanuel consequence.

    Args:
        alpha: A nonzero algebraic number
        alpha_name: Human-readable name for α

    Returns:
        TranscendenceCertificate, or None if α = 0

    >>> cert = certify_exp_algebraic_transcendental(1, "1")
    >>> cert.verify_numerically()
    True
    """
    if abs(alpha) < 1e-15:
        return None  # z = 0 is excluded

    return TranscendenceCertificate(
        target=cmath.exp(alpha),
        z=alpha,
        description=(
            f"z = {alpha_name} is algebraic and nonzero. "
            f"Schanuel (n=1) gives trdeg(Q({alpha_name}, exp({alpha_name}))) ≥ 1. "
            f"Since {alpha_name} is algebraic, exp({alpha_name}) is transcendental."
        )
    )


class ExponentialFieldChecker:
    """
    A checker for properties of exponential fields, inspired by the
    abstract algebraic structure underlying Schanuel's conjecture.

    An exponential field is a field F with a homomorphism
    exp: (F, +) → (F×, ·) satisfying certain axioms.
    """

    def __init__(self, field_elements: List[complex]):
        """
        Args:
            field_elements: A finite set of complex numbers generating the field
        """
        self.generators = field_elements
        self.exp_generators = [cmath.exp(z) for z in field_elements]

    def check_exponential_homomorphism(self, tolerance: float = 1e-10) -> bool:
        """
        Verify exp(a + b) = exp(a) · exp(b) for all pairs of generators.

        Returns:
            True if the homomorphism property holds numerically
        """
        for a in self.generators:
            for b in self.generators:
                lhs = cmath.exp(a + b)
                rhs = cmath.exp(a) * cmath.exp(b)
                if abs(lhs - rhs) > tolerance:
                    return False
        return True

    def schanuel_data(self) -> Dict:
        """
        Compute the Schanuel-relevant data for this exponential field.

        Returns:
            Dictionary with:
            - n: number of generators
            - generators: the field generators
            - exp_generators: their exponentials
            - all_generators: combined list
            - q_lin_rank: Q-linear rank of generators
        """
        from algorithms import q_linear_rank
        return {
            'n': len(self.generators),
            'generators': self.generators,
            'exp_generators': self.exp_generators,
            'all_generators': self.generators + self.exp_generators,
            'q_lin_rank': q_linear_rank(self.generators),
        }


