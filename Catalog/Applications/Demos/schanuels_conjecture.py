def application_constant_recognition():
    """
    Application: Constant recognition in numerical computation.

    Given a computed numerical value, determine if it could be
    a "simple" expression involving known constants.

    Schanuel's conjecture constrains which identities are possible:
    - exp(algebraic nonzero) cannot equal an algebraic number
    - This rules out many potential identifications
    """
    print("=" * 70)
    print("APPLICATION 2: Constant Recognition")
    print("=" * 70)
    print()

    # Test cases: given a numerical value, is it algebraic?
    test_values = [
        (math.e, "e"),
        (math.pi, "π"),
        (math.exp(math.sqrt(2)), "e^√2"),
        (math.sqrt(2) + math.sqrt(3), "√2 + √3"),
        (math.exp(1) + math.exp(2), "e + e²"),
        (1.0, "1"),
        (0.5, "1/2"),
    ]

    print("Can these constants be algebraic over Q?\n")
    for value, name in test_values:
        # Check if value satisfies a low-degree polynomial with small coefficients
        is_likely_algebraic = False
        for degree in range(1, 5):
            # Check if value is a root of a polynomial of this degree
            # with coefficients up to 10 in absolute value
            for coeffs in _generate_polynomial_coeffs(degree, max_coeff=10):
                if abs(_eval_polynomial(coeffs, value)) < 1e-8:
                    is_likely_algebraic = True
                    break
            if is_likely_algebraic:
                break

        schanuel_constraint = ""
        if name in ["e", "e^√2"]:
            schanuel_constraint = " [Schanuel: must be transcendental]"

        status = "likely algebraic" if is_likely_algebraic else "likely transcendental"
        print(f"  {name} = {value:.8f}: {status}{schanuel_constraint}")

    print()


def _generate_polynomial_coeffs(degree: int, max_coeff: int = 10):
    """Generate polynomial coefficient tuples for root testing."""
    import itertools
    for coeffs in itertools.product(range(-max_coeff, max_coeff + 1), repeat=degree + 1):
        if coeffs[-1] != 0 and coeffs[0] != 0:  # nonzero leading and constant
            yield coeffs


def _eval_polynomial(coeffs: tuple, x: float) -> float:
    """Evaluate polynomial with given coefficients at x."""
    return sum(c * x**i for i, c in enumerate(coeffs))


