"""
Schanuel's Conjecture: Interactive Demonstrations

This module provides concrete numerical explorations of the mathematical
structures underlying Schanuel's conjecture and its consequences.
"""

import math
import cmath
from fractions import Fraction
from typing import List, Tuple, Optional
import itertools


def is_q_linearly_independent(values: List[complex], tolerance: float = 1e-12) -> bool:
    """
    Heuristically test if complex numbers are Q-linearly independent.

    Uses LLL-style lattice reduction heuristic: if there exists a short
    integer relation among the values, they are likely Q-linearly dependent.

    Args:
        values: List of complex numbers to test
        tolerance: Numerical tolerance for zero detection

    Returns:
        True if no short rational relation is found (heuristically independent)

    >>> is_q_linearly_independent([1.0, math.sqrt(2)])
    True
    >>> is_q_linearly_independent([1.0, 2.0])
    False
    """
    n = len(values)
    if n == 0:
        return True
    if n == 1:
        return abs(values[0]) > tolerance

    # Try all integer coefficient vectors with small entries
    max_coeff = 20
    for total in range(1, max_coeff + 1):
        for coeffs in itertools.product(range(-total, total + 1), repeat=n):
            if all(c == 0 for c in coeffs):
                continue
            if max(abs(c) for c in coeffs) > total:
                continue
            linear_combo = sum(c * v for c, v in zip(coeffs, values))
            if abs(linear_combo) < tolerance:
                return False
    return True


def transcendence_degree_lower_bound(
    generators: List[complex],
    tolerance: float = 1e-10,
    max_degree: int = 4
) -> int:
    """
    Heuristically estimate a lower bound on the transcendence degree
    of Q(generators) by testing algebraic relations of bounded degree.

    This tests whether there exist polynomial relations of degree ≤ max_degree
    with small integer coefficients among the generators.

    Args:
        generators: List of complex numbers generating the field extension
        tolerance: Numerical tolerance
        max_degree: Maximum polynomial degree to test

    Returns:
        Lower bound on transcendence degree

    >>> transcendence_degree_lower_bound([math.e])
    1
    >>> transcendence_degree_lower_bound([1.0])
    0
    """
    n = len(generators)
    if n == 0:
        return 0

    # Generate monomials up to given degree
    def monomials(degree):
        """Generate all monomials in n variables up to given total degree."""
        if n == 0:
            return [1.0]
        result = []
        for exp_tuple in itertools.product(range(degree + 1), repeat=n):
            if sum(exp_tuple) <= degree:
                val = 1.0
                for g, e in zip(generators, exp_tuple):
                    val *= g ** e
                result.append((exp_tuple, val))
        return result

    monos = monomials(max_degree)
    mono_values = [v for _, v in monos]

    # Count how many are "algebraically independent" by checking linear
    # independence of monomials (as a proxy)
    independent_count = 0
    selected = []
    for val in mono_values:
        test = selected + [val]
        if is_q_linearly_independent(test, tolerance):
            selected.append(val)
            independent_count += 1

    # The transcendence degree is related to the growth rate of
    # linearly independent monomials
    # For a single transcendental, monomials 1, x, x^2, ... are all independent
    # For algebraic numbers, they eventually become dependent

    # Simple heuristic: count algebraically independent generators
    indep_gens = 0
    for i in range(n):
        powers = [generators[i] ** k for k in range(max_degree + 1)]
        if is_q_linearly_independent(powers, tolerance):
            indep_gens += 1

    return indep_gens


def demo_schanuel_n1():
    """
    Demonstrate the n=1 case of Schanuel's conjecture.

    For z algebraic and nonzero, Schanuel predicts trdeg(Q(z, exp(z))) >= 1.
    Since z is algebraic, this means exp(z) must be transcendental.

    Examples:
    - z = 1 (algebraic): exp(1) = e should be transcendental ✓
    - z = sqrt(2) (algebraic): exp(sqrt(2)) should be transcendental ✓
    - z = 0 (algebraic but zero!): exp(0) = 1 is algebraic ← needs z ≠ 0
    """
    print("=" * 70)
    print("DEMO 1: Schanuel's Conjecture (n = 1)")
    print("=" * 70)
    print()
    print("Schanuel's conjecture (n=1): If z ≠ 0, then")
    print("  trdeg_Q(Q(z, exp(z))) ≥ 1")
    print()

    cases = [
        ("z = 1", 1.0, True),
        ("z = √2", math.sqrt(2), True),
        ("z = 1/3", 1/3, True),
        ("z = π (transcendental)", math.pi, True),
        ("z = 0 (EXCLUDED)", 0.0, False),
    ]

    for name, z, nonzero in cases:
        exp_z = math.exp(z) if z != 0 else 1.0
        generators = [z, exp_z] if z != 0 else [0.0, 1.0]

        print(f"  {name}:")
        print(f"    z = {z:.6f}")
        print(f"    exp(z) = {exp_z:.6f}")

        if nonzero and z != 0:
            td = transcendence_degree_lower_bound(generators)
            print(f"    Estimated trdeg(Q(z, exp(z))) ≥ {td}")
            # Check if z is "algebraic" (heuristic: small height)
            z_alg = not is_q_linearly_independent([1.0, z])  # crude test
            if z_alg or abs(z - round(z)) < 1e-10 or abs(z * z - round(z * z)) < 1e-10:
                print(f"    z appears algebraic → exp(z) should be transcendental")
                exp_trans = is_q_linearly_independent(
                    [exp_z ** k for k in range(5)]
                )
                print(f"    exp(z) appears transcendental: {exp_trans}")
        else:
            print(f"    EXCLUDED: z = 0, exp(0) = 1 is algebraic!")
        print()


def demo_weak_lindemann_weierstrass():
    """
    Demonstrate the weak Lindemann-Weierstrass consequence of Schanuel:
    If α₁, ..., αₙ are Q-linearly independent algebraic numbers,
    then each exp(αᵢ) is transcendental.
    """
    print("=" * 70)
    print("DEMO 2: Weak Lindemann-Weierstrass (from Schanuel)")
    print("=" * 70)
    print()
    print("If α₁, ..., αₙ are Q-linearly independent algebraic numbers,")
    print("then each exp(αᵢ) is transcendental over Q.")
    print()

    # Example: α₁ = 1, α₂ = √2 (Q-linearly independent algebraic numbers)
    alphas = [1.0, math.sqrt(2), math.sqrt(3)]
    names = ["1", "√2", "√3"]

    print(f"  Family: {', '.join(names)}")
    print(f"  Q-linearly independent: {is_q_linearly_independent(alphas)}")
    print()

    for name, alpha in zip(names, alphas):
        exp_alpha = math.exp(alpha)
        # Test transcendence heuristically
        powers = [exp_alpha ** k for k in range(6)]
        appears_trans = is_q_linearly_independent(powers)
        print(f"  exp({name}) = {exp_alpha:.6f}")
        print(f"    Appears transcendental: {appears_trans}")
    print()


def demo_algebraic_obstruction():
    """
    Demonstrate the algebraic-dependence obstruction:
    Under Schanuel, if ALL of z_i and exp(z_i) are algebraic,
    then the z_i CANNOT be Q-linearly independent.
    """
    print("=" * 70)
    print("DEMO 3: Algebraic Dependence Obstruction")
    print("=" * 70)
    print()
    print("Under Schanuel: if z_i AND exp(z_i) are all algebraic,")
    print("then the z_i cannot be Q-linearly independent.")
    print()

    # Example: z_i = 0 for all i — trivially Q-linearly dependent
    print("  Case 1: z₁ = z₂ = 0")
    print("    All z_i algebraic: True (they're 0)")
    print("    All exp(z_i) algebraic: True (exp(0) = 1)")
    print("    Q-linearly independent: False ✓ (consistent with Schanuel)")
    print()

    # Example: z₁ = log(2), z₂ = log(3)
    # exp(z_i) = 2, 3 are algebraic
    # But log(2), log(3) are transcendental, not algebraic!
    # So the hypothesis "z_i algebraic" fails
    print("  Case 2: z₁ = log(2), z₂ = log(3)")
    print(f"    z₁ = {math.log(2):.6f}, z₂ = {math.log(3):.6f}")
    print(f"    exp(z₁) = 2, exp(z₂) = 3 — both algebraic")
    print(f"    But z₁, z₂ are NOT algebraic (they're transcendental)")
    print(f"    → Hypothesis fails, no contradiction with Schanuel")
    print()

    # The point: you can't have BOTH z_i algebraic AND exp(z_i) algebraic
    # AND z_i Q-linearly independent (for n ≥ 1 with z_i ≠ 0)
    print("  Key insight: Having both z_i and exp(z_i) algebraic")
    print("  while maintaining Q-linear independence is impossible")
    print("  under Schanuel's conjecture (for nonzero z_i).")
    print()


