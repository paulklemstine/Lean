def quantum_commuting_observables():
    """
    Demonstrate that commuting quantum observables preserve compact spectral sectors.
    
    In quantum mechanics, if a Hamiltonian H commutes with a compact observable K
    (e.g., a density operator or resolvent approximation), then the energy eigenspaces
    of K are preserved by the time evolution generated by H.
    
    This is a direct application of eigenspace_map_of_commuting.
    """
    print("=" * 70)
    print("APPLICATION 1: Quantum Mechanics - Commuting Observables")
    print("=" * 70)
    
    n = 20  # Truncated Hilbert space dimension
    
    # Create a "compact observable" K (density operator-like: positive, trace-class)
    # Eigenvalues decay like Boltzmann distribution
    beta = 1.0  # inverse temperature
    energies = np.array([k**2 for k in range(1, n+1)], dtype=float)
    boltzmann_weights = np.exp(-beta * energies)
    boltzmann_weights /= np.sum(boltzmann_weights)  # normalize
    
    # K is diagonal in energy basis
    K = np.diag(boltzmann_weights.astype(complex))
    
    # Hamiltonian that commutes with K (diagonal in same basis)
    H = np.diag(energies.astype(complex))
    
    # Time evolution operator U = exp(-iHt)
    t = 0.5
    U = np.diag(np.exp(-1j * energies * t))
    
    print(f"\nHilbert space dimension (truncated): {n}")
    print(f"Compact observable K (Boltzmann density operator):")
    print(f"  Top 5 eigenvalues: {boltzmann_weights[:5].round(6)}")
    print(f"  Trace: {np.trace(K).real:.6f}")
    
    # Check commutation
    comm_HK = np.linalg.norm(H @ K - K @ H)
    comm_UK = np.linalg.norm(U @ K - K @ U)
    print(f"\n‖[H, K]‖ = {comm_HK:.2e}")
    print(f"‖[U(t), K]‖ = {comm_UK:.2e}")
    
    # Verify eigenspace preservation
    print(f"\nEnergy shell preservation under time evolution:")
    for i in range(min(5, n)):
        v = np.zeros(n, dtype=complex)
        v[i] = 1.0  # i-th energy eigenstate
        
        Uv = U @ v  # evolved state
        # Check if Uv is still in eigenspace of K for same eigenvalue
        Kv = K @ v
        KUv = K @ Uv
        
        # K(Uv) should equal λ * Uv where λ = boltzmann_weights[i]
        expected = boltzmann_weights[i] * Uv
        error = np.linalg.norm(KUv - expected)
        
        print(f"  State |{i+1}⟩: K eigenvalue = {boltzmann_weights[i]:.6f}, "
              f"preservation error = {error:.2e} ✓" if error < 1e-10 else "✗")
    
    print("\n→ Time evolution preserves each energy shell (eigenspace of K)")
    print("→ This is the quantum manifestation of eigenspace_map_of_commuting")


