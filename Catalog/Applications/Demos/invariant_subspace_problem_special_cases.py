def model_reduction():
    """
    Demonstrate model reduction using compact operator invariant subspaces.
    
    Given a high-dimensional dynamical system, we use compact operator eigenspaces
    as invariant coordinate systems for reduced-order modeling.
    """
    print("\n" + "=" * 70)
    print("APPLICATION 4: Model Reduction via Invariant Subspaces")
    print("=" * 70)
    
    n = 100  # Full system dimension
    r = 5    # Target reduced dimension
    
    # Create a dynamical system matrix A with compact structure
    # A = S + K where S is simple (diagonal) and K is compact (low-rank perturbation)
    S_eigenvalues = -np.sort(np.random.exponential(1.0, n))[::-1]
    S = np.diag(S_eigenvalues.astype(complex))
    
    # Compact perturbation (rank r)
    U_pert = np.random.randn(n, r) * 0.1
    V_pert = np.random.randn(r, n) * 0.1
    K_pert = (U_pert @ V_pert).astype(complex)
    
    A = S + K_pert
    
    # Find invariant subspaces using eigendecomposition
    eigenvalues, eigenvectors = np.linalg.eig(A)
    
    # Sort by magnitude of eigenvalue
    order = np.argsort(-np.abs(eigenvalues))
    eigenvalues = eigenvalues[order]
    eigenvectors = eigenvectors[:, order]
    
    # Take top r modes as reduced basis
    V_r = eigenvectors[:, :r]
    
    # Reduced system: A_r = V_r^H A V_r
    A_r = V_r.conj().T @ A @ V_r
    
    print(f"\nFull system dimension: {n}")
    print(f"Reduced system dimension: {r}")
    
    print(f"\nFull system eigenvalues (top {r}):")
    for i in range(r):
        print(f"  λ_{i} = {eigenvalues[i]:.6f}")
    
    print(f"\nReduced system eigenvalues:")
    red_evals = np.linalg.eigvals(A_r)
    red_evals = red_evals[np.argsort(-np.abs(red_evals))]
    for i in range(r):
        error = min(abs(red_evals[i] - eigenvalues[j]) for j in range(r))
        print(f"  λ_r_{i} = {red_evals[i]:.6f} (error: {error:.2e})")
    
    # Simulate dynamics and compare
    x0 = np.random.randn(n).astype(complex)
    x0 /= np.linalg.norm(x0)
    
    # Project initial condition
    x0_r = V_r.conj().T @ x0
    
    # Time evolution
    dt = 0.01
    steps = 100
    
    full_trajectory = np.zeros((steps, n), dtype=complex)
    reduced_trajectory = np.zeros((steps, r), dtype=complex)
    
    x_full = x0.copy()
    x_red = x0_r.copy()
    
    for t in range(steps):
        full_trajectory[t] = x_full
        reduced_trajectory[t] = x_red
        
        x_full = x_full + dt * (A @ x_full)  # Euler step
        x_red = x_red + dt * (A_r @ x_red)
    
    # Compare trajectories (project full onto reduced basis)
    errors = np.array([
        np.linalg.norm(V_r.conj().T @ full_trajectory[t] - reduced_trajectory[t])
        for t in range(steps)
    ])
    
    print(f"\nTrajectory comparison ({steps} time steps, dt={dt}):")
    print(f"  Mean projection error: {np.mean(errors):.6e}")
    print(f"  Max projection error: {np.max(errors):.6e}")
    print(f"  Compression ratio: {n}/{r} = {n/r:.1f}x")
    print(f"\n→ Invariant subspaces enable faithful model reduction")
    print(f"→ The reduced model captures the dominant dynamics")


