    pres_errors = []
    for _ in range(50):
        T = np.diag(np.random.randn(n) + 1j * np.random.randn(n))
        noise = 0.0  # Perfect commutation
        T_noisy = T + noise * np.random.randn(n, n)
        ce = np.linalg.norm(T_noisy @ K - K @ T_noisy)
        
        # Check eigenspace preservation for dominant eigenvalue
        v = np.zeros(n, dtype=complex); v[0] = 1.0
        Tv = T_noisy @ v
        pe = abs(np.linalg.norm(Tv - (Tv[0] / v[0]) * v))
        
        comm_errors.append(ce)
        pres_errors.append(pe)
    
    # Non-commuting
    for _ in range(50):
        T_bad = np.random.randn(n, n) + 1j * np.random.randn(n, n)
        ce = np.linalg.norm(T_bad @ K - K @ T_bad)
