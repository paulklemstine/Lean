def invariant_spectral_filtering():
    """
    Demonstrate invariant spectral filtering using compact operator theory.
    
    A compact filter K (e.g., Gaussian blur) commutes with translation-invariant
    operators. The eigenspaces of K provide invariant frequency bands that are
    preserved by any translation-invariant processing.
    """
    print("\n" + "=" * 70)
    print("APPLICATION 3: Signal Processing - Invariant Spectral Filtering")
    print("=" * 70)
    
    n = 64  # Signal length
    
    # Compact filter K: Gaussian blur (circulant matrix)
    sigma = 3.0
    kernel = np.exp(-np.arange(n)**2 / (2 * sigma**2))
    kernel = kernel + np.exp(-(np.arange(n) - n)**2 / (2 * sigma**2))  # wrap around
    kernel = kernel / np.sum(kernel)
    
    # Circulant matrix
    K = np.zeros((n, n))
    for i in range(n):
        K[i] = np.roll(kernel, i)
    K = K.astype(complex)
    
    # Translation operator T (circular shift by 1)
    T = np.zeros((n, n), dtype=complex)
    for i in range(n):
        T[(i+1) % n, i] = 1.0
    
    # Check commutation (circulant matrices commute)
    comm = np.linalg.norm(T @ K - K @ T)
    print(f"\nSignal length: {n}")
    print(f"Gaussian blur kernel (σ = {sigma})")
    print(f"‖[T_shift, K_blur]‖ = {comm:.2e}")
    
    # Eigenspaces are Fourier modes (since both are circulant)
    K_eigenvalues = np.fft.fft(kernel)
    
    print(f"\nFilter frequency response (eigenvalues of K):")
    print(f"{'Frequency':>10} {'|K eigenvalue|':>16} {'Phase':>10}")
    for k in range(min(10, n)):
        print(f"  {k:>8} {abs(K_eigenvalues[k]):>16.6f} {np.angle(K_eigenvalues[k]):>10.4f}")
    
    # Demonstrate invariant filtering
    # Create a signal with known frequency content
    signal = np.zeros(n)
    signal += 1.0 * np.cos(2 * np.pi * 2 * np.arange(n) / n)  # frequency 2
    signal += 0.5 * np.cos(2 * np.pi * 10 * np.arange(n) / n)  # frequency 10
    signal += 0.3 * np.random.randn(n)  # noise
    
    filtered = K @ signal
    shifted_filtered = T @ filtered
    filtered_shifted = K @ (T @ signal)
    
    commutation_error = np.linalg.norm(shifted_filtered - filtered_shifted)
    print(f"\nSignal processing commutation test:")
    print(f"  ‖T(K·x) - K(T·x)‖ = {commutation_error:.2e}")
    print(f"  → Filtering and shifting commute (invariant spectral bands)")
    
    # Show that each Fourier mode is preserved
    print(f"\nFourier mode preservation:")
    for k in [0, 1, 2, 5, 10, 20]:
        fourier_mode = np.exp(2j * np.pi * k * np.arange(n) / n)
        Kf = K @ fourier_mode
        expected = K_eigenvalues[k] * fourier_mode
        error = np.linalg.norm(Kf - expected)
        print(f"  Mode k={k:>3}: preservation error = {error:.2e}, "
              f"filter gain = {abs(K_eigenvalues[k]):.4f}")


