def koopman_spectral_modes():
    """
    Demonstrate invariant spectral modes in Koopman operator analysis.
    
    For a dynamical system x_{n+1} = f(x_n), the Koopman operator U acts on
    observables: (Ug)(x) = g(f(x)). If a compact operator K commutes with U,
    then eigenspaces of K are invariant under U — these are "spectral modes"
    of the dynamics.
    
    This is a direct application of selfAdjoint_compact_mode_preservation.
    """
    print("\n" + "=" * 70)
    print("APPLICATION 2: Dynamical Systems - Koopman Spectral Modes")
    print("=" * 70)
    
    # Simple linear dynamical system: rotation + contraction
    n = 30  # Observable space dimension
    
    # Koopman operator for a rotation by angle theta with contraction
    theta = 0.3
    contraction = 0.95
    
    # In Fourier basis, the Koopman operator acts diagonally
    koopman_eigenvalues = np.array([
        contraction**k * np.exp(1j * k * theta) for k in range(n)
    ])
    U_koopman = np.diag(koopman_eigenvalues)
    
    # Compact "resolution operator" K that commutes with U
    # (smoothing/averaging operator — compact because it has decaying singular values)
    resolution_decay = 0.7
    K_eigenvalues = np.array([resolution_decay**k for k in range(n)])
    K = np.diag(K_eigenvalues.astype(complex))
    
    print(f"\nObservable space dimension: {n}")
    print(f"Dynamical system: rotation (θ={theta:.2f}) + contraction (r={contraction})")
    print(f"\nKoopman operator U (top 5 eigenvalues):")
