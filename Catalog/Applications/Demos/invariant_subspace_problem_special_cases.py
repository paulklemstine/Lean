def make_compact_operator(n: int, rank: int = 5, decay: float = 0.5) -> np.ndarray:
    """
    Construct an n×n matrix approximating a compact operator.
    
    A compact operator on an infinite-dimensional space can be approximated
    by operators whose singular values decay to zero. We simulate this with
    a low-rank-plus-decaying-tail structure.
    
    Args:
        n: Matrix dimension
        rank: Number of dominant singular values
        decay: Exponential decay rate for singular values
    
    Returns:
        n×n complex matrix with rapidly decaying singular values
    """
    U, _ = np.linalg.qr(np.random.randn(n, n) + 1j * np.random.randn(n, n))
    V, _ = np.linalg.qr(np.random.randn(n, n) + 1j * np.random.randn(n, n))
    sigmas = np.array([np.exp(-decay * k) for k in range(n)])
    return U @ np.diag(sigmas) @ V.conj().T


def compute_eigenspaces(K: np.ndarray, tol: float = 1e-10) -> dict:
    """
    Compute eigenvalues and eigenspaces of matrix K.
    
    Returns a dictionary mapping eigenvalues to their eigenspaces
    (as lists of eigenvectors).
    """
    eigenvalues, eigenvectors = np.linalg.eig(K)
    
    # Group by eigenvalue (up to tolerance)
    spaces = {}
    used = set()
    for i, ev in enumerate(eigenvalues):
        if i in used:
            continue
        # Find all eigenvalues close to this one
        cluster = [j for j in range(len(eigenvalues)) 
                   if j not in used and abs(eigenvalues[j] - ev) < tol]
        if cluster:
            key = np.mean(eigenvalues[cluster])
            spaces[key] = eigenvectors[:, cluster]
            used.update(cluster)
    
    return spaces


def verify_commutant_preserves_eigenspace(
    T: np.ndarray, K: np.ndarray, tol: float = 1e-8
) -> dict:
    """
    Verify that T preserves each eigenspace of K when T and K commute.
    
    This demonstrates Theorem B: eigenspace_map_of_commuting.
    
    Returns:
        Dictionary with eigenvalue -> preservation_error
    """
    # Check commutation
    commutator_norm = np.linalg.norm(T @ K - K @ T)
    
    eigenvalues, eigenvectors = np.linalg.eig(K)
    
    results = {}
    # Group eigenvalues
    used = set()
    for i, ev in enumerate(eigenvalues):
        if i in used or abs(ev) < tol:
            continue
        cluster = [j for j in range(len(eigenvalues))
                   if j not in used and abs(eigenvalues[j] - ev) < tol]
        if not cluster:
            continue
        used.update(cluster)
        
        # Get eigenspace basis
        V_space = eigenvectors[:, cluster]
        
        # Project T*v onto eigenspace for each basis vector v
        errors = []
        for j in range(V_space.shape[1]):
            v = V_space[:, j]
            Tv = T @ v
            # Project Tv onto the eigenspace
            proj = V_space @ (V_space.conj().T @ Tv)
            error = np.linalg.norm(Tv - proj)
            errors.append(error)
        
        results[ev] = {
            'dimension': len(cluster),
            'max_error': max(errors),
            'preserved': max(errors) < tol
        }
    
    return {'commutator_norm': commutator_norm, 'eigenspaces': results}


