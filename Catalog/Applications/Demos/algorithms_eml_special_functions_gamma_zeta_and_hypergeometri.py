from __future__ import annotations
from typing import Callable, List, Optional, Tuple
from enum import Enum
from dataclasses import dataclass
import math


# ============================================================
# 1. Rising Factorial
# ============================================================

def pochhammer(a: float, n: int) -> float:
    """Compute the rising factorial (a)_n = a(a+1)...(a+n-1).
    
    Args:
        a: Base parameter (real number)
        n: Number of factors (non-negative integer)
    
    Returns:
        The rising factorial value
    """
    result = 1.0
    for k in range(n):
        result *= (a + k)
    return result


def pochhammer_via_gamma(a: float, n: int) -> float:
    """Compute (a)_n = Γ(a+n)/Γ(a) using the Gamma function.
    
    Requires a > 0.
    """
    return math.gamma(a + n) / math.gamma(a)


# ============================================================
# 2. Hypergeometric Coefficient and Series
# ============================================================

def hypergeom_coeff(a: float, b: float, c: float, n: int) -> float:
    """Compute the n-th coefficient of 2F1(a,b;c;z).
    
    hypergeomCoeff(a, b, c, n) = (a)_n * (b)_n / ((c)_n * n!)
    """
    return pochhammer(a, n) * pochhammer(b, n) / (pochhammer(c, n) * math.factorial(n))


def hypergeom_coeff_via_recurrence(a: float, b: float, c: float, n: int) -> float:
    """Compute the n-th coefficient using the recurrence relation.
    
    a_{n+1} = a_n * (a+n)(b+n) / ((c+n)(n+1))
    """
    result = 1.0
    for k in range(n):
        result *= (a + k) * (b + k) / ((c + k) * (k + 1))
    return result


def hypergeom_partial_sum(a: float, b: float, c: float, z: float, N: int) -> float:
    """Compute the partial sum Σ_{k=0}^{N-1} a_k * z^k of 2F1(a,b;c;z).
    
    Uses the recurrence relation for efficiency (O(N) multiplications).
    """
    total = 0.0
    coeff = 1.0
    z_power = 1.0
    for k in range(N):
        total += coeff * z_power
        coeff *= (a + k) * (b + k) / ((c + k) * (k + 1))
        z_power *= z
    return total


def hypergeom_ratio(a: float, b: float, c: float, n: int) -> float:
    """Compute the ratio a_{n+1}/a_n = (a+n)(b+n)/((c+n)(n+1))."""
    return (a + n) * (b + n) / ((c + n) * (n + 1))


# ============================================================
# 3. EML Differential Operator Algebra
# ============================================================

class EMLDiffOp:
    """Abstract base class for EML differential operators.
    
    An EML differential operator acts on coefficient sequences (ℕ → ℝ).
    The algebra is generated by:
    - Identity: f(n) ↦ f(n)
    - Shift: f(n) ↦ f(n-1) (with f(-1) = 0)
    - Euler(k): f(n) ↦ (n+k) * f(n)
    """
    
    def act(self, f: Callable[[int], float], n: int) -> float:
        """Apply this operator to sequence f at index n."""
        raise NotImplementedError


class IdentityOp(EMLDiffOp):
    """Identity operator: f(n) ↦ f(n)."""
    
    def act(self, f: Callable[[int], float], n: int) -> float:
        return f(n)
    
    def __repr__(self) -> str:
        return "Id"


class ShiftOp(EMLDiffOp):
    """Shift operator (multiplication by z): f(n) ↦ f(n-1)."""
    
    def act(self, f: Callable[[int], float], n: int) -> float:
        if n == 0:
            return 0.0
        return f(n - 1)
    
    def __repr__(self) -> str:
        return "z"


class EulerOp(EMLDiffOp):
    """Euler operator θ + k: f(n) ↦ (n + k) * f(n).
    
    When k=0, this is the Euler operator θ = z·d/dz.
    The connection to EML: θ = d/d(log z), the logarithmic derivative.
    """
    
    def __init__(self, k: float = 0.0):
        self.k = k
    
    def act(self, f: Callable[[int], float], n: int) -> float:
        return (n + self.k) * f(n)
    
    def __repr__(self) -> str:
        if self.k == 0:
            return "θ"
        return f"(θ+{self.k})"


class ComposeOp(EMLDiffOp):
    """Composition of two operators: (op1 ∘ op2)(f) = op1(op2(f))."""
    
    def __init__(self, op1: EMLDiffOp, op2: EMLDiffOp):
        self.op1 = op1
        self.op2 = op2
    
    def act(self, f: Callable[[int], float], n: int) -> float:
        inner = lambda m: self.op2.act(f, m)
        return self.op1.act(inner, n)
    
    def __repr__(self) -> str:
        return f"({self.op1} ∘ {self.op2})"


class AddOp(EMLDiffOp):
    """Sum of two operators: (op1 + op2)(f)(n) = op1(f)(n) + op2(f)(n)."""
    
    def __init__(self, op1: EMLDiffOp, op2: EMLDiffOp):
        self.op1 = op1
        self.op2 = op2
    
    def act(self, f: Callable[[int], float], n: int) -> float:
        return self.op1.act(f, n) + self.op2.act(f, n)
    
    def __repr__(self) -> str:
        return f"({self.op1} + {self.op2})"


def gauss_lhs(c: float) -> EMLDiffOp:
    """The LHS of the Gauss hypergeometric equation: θ(θ+c-1)."""
    return ComposeOp(EulerOp(0), EulerOp(c - 1))


def gauss_rhs(a: float, b: float) -> EMLDiffOp:
    """The RHS of the Gauss hypergeometric equation: z·(θ+a)(θ+b)."""
    return ComposeOp(ShiftOp(), ComposeOp(EulerOp(a), EulerOp(b)))


def verify_operator_factorization(a: float, b: float, c: float,
                                   max_n: int = 20) -> List[float]:
    """Verify that gaussLHS(c) and gaussRHS(a,b) agree on hypergeometric coefficients.
    
    Returns list of |LHS - RHS| values for n = 1, ..., max_n.
    """
    lhs_op = gauss_lhs(c)
    rhs_op = gauss_rhs(a, b)
    f = lambda n: hypergeom_coeff(a, b, c, n)
    
    diffs = []
    for n in range(1, max_n + 1):
        lhs_val = lhs_op.act(f, n)
        rhs_val = rhs_op.act(f, n)
        diffs.append(abs(lhs_val - rhs_val))
    return diffs


