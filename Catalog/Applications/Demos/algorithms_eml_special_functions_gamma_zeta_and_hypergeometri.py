# 4. Singularity Classification
# ============================================================

class SingularityType(Enum):
    REMOVABLE = "removable"
    POLE = "pole"
    ESSENTIAL = "essential"
    BRANCH_POINT = "branch_point"


@dataclass
class Singularity:
    """A singularity of a function at a given point."""
    point: float
    stype: SingularityType
    order: Optional[int] = None  # For poles


@dataclass
class MeromorphicEMLFunction:
    """A meromorphic function in the EML framework."""
    name: str
    f: Callable[[float], float]
    singularities: List[Singularity]
    
    def is_meromorphic(self) -> bool:
        """Check if all singularities are poles (meromorphic)."""
        return all(s.stype == SingularityType.POLE for s in self.singularities)
    
    def is_entire(self) -> bool:
        """Check if there are no singularities."""
        return len(self.singularities) == 0


# Example: Gamma function (meromorphic with poles at 0, -1, -2, ...)
gamma_function = MeromorphicEMLFunction(
    name="Gamma",
    f=math.gamma,
    singularities=[Singularity(point=-n, stype=SingularityType.POLE, order=1)
                   for n in range(20)]  # Simple poles at 0, -1, ..., -19
)


# ============================================================
# 5. EML-Hypergeometric Bridge
# ============================================================

def log_series_partial_sum(z: float, N: int) -> float:
    """Compute Σ_{k=0}^{N-1} (-1)^k/(k+1) * z^k = partial sum of log(1+z)/z."""
    total = 0.0
    for k in range(N):
        total += (-1)**k / (k + 1) * z**k
    return total


def verify_eml_bridge(z: float, N: int = 100) -> Tuple[float, float, float]:
    """Verify 2F1(1,1;2;-z) ≈ log(1+z)/z.
    
    Returns (hypergeom_value, log_series_value, exact_value).
    """
    hyper = hypergeom_partial_sum(1, 1, 2, -z, N)
    log_series = log_series_partial_sum(z, N)
    exact = math.log(1 + z) / z if z != 0 else 1.0
    return hyper, log_series, exact


