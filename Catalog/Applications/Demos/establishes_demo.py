    verify_invertibility()

    # ── Step 2: Generate Berggren tree ─────────────────────────────────
    print("━━ Step 2: Berggren Tree (depth 3) ━━")
    depth = 3
    triples = generate_berggren_tree([3, 4, 5], depth)
