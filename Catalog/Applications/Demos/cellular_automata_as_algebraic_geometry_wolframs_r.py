def cryptographic_nonlinearity(r):
    """Compute the nonlinearity of an ECA rule.
    
    Nonlinearity = min Hamming distance to all affine functions over GF(2).
    Higher nonlinearity = better resistance to linear cryptanalysis.
    """
    truth_table = [(r >> i) & 1 for i in range(8)]
    
    # All affine functions on 3 variables
    min_dist = 8
    for mask in range(16):  # 2^(3+1) = 16 affine functions
        const = (mask >> 3) & 1
        for i in range(8):
            bits = [(i >> b) & 1 for b in range(3)]
            affine_val = const
            for b in range(3):
                if (mask >> b) & 1:
                    affine_val ^= bits[b]
            dist = sum(1 for j in range(8) if truth_table[j] != 
                      (const ^ sum(bits[b] * ((mask >> b) & 1) for b in range(3) 
                                   for bits in [[(j >> bb) & 1 for bb in range(3)]]) % 2))
        # Simplified: just use Walsh transform
        pass
    
    # Direct computation via Walsh-Hadamard transform
    wht = [0] * 8
    for w in range(8):
        for x in range(8):
            # (-1)^(f(x) + w·x)
            wx = sum(((w >> b) & 1) * ((x >> b) & 1) for b in range(3)) % 2
            wht[w] += (-1) ** (truth_table[x] ^ wx)
    
    max_wht = max(abs(v) for v in wht)
    nonlinearity = (8 - max_wht) // 2
    return nonlinearity


def stream_cipher_analysis():
    """Analyze all 256 rules for cryptographic suitability."""
    print("=" * 60)
    print("APPLICATION 1: Cryptographic Stream Cipher Analysis")
    print("=" * 60)
    
    results = []
    for r in range(256):
        anf = rule_to_anf(r)
        deg = anf_degree(anf)
        nl = cryptographic_nonlinearity(r)
        results.append((r, deg, nl))
    
    # Group by nonlinearity
    nl_groups = {}
    for r, deg, nl in results:
        nl_groups.setdefault(nl, []).append((r, deg))
    
    for nl in sorted(nl_groups.keys(), reverse=True):
        rules = nl_groups[nl]
        print(f"\n  Nonlinearity {nl}: {len(rules)} rules")
        if nl >= 2:
            for r, deg in rules[:10]:
                print(f"    Rule {r:3d} (degree {deg})")
    
    print("\n  Best cryptographic candidates (nonlinearity ≥ 2):")
    best = [(r, deg, nl) for r, deg, nl in results if nl >= 2]
    for r, deg, nl in best[:10]:
        print(f"    Rule {r:3d}: degree={deg}, nonlinearity={nl}")
    
    return results


