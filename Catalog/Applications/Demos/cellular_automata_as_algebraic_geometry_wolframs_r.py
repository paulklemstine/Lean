def find_linear_codes():
    """Find linear codes generated by linear ECA fixed-point varieties."""
    print("\n" + "=" * 60)
    print("APPLICATION 2: Error-Correcting Codes from ECA Fixed Points")
    print("=" * 60)
    
    linear_rules = [r for r in range(256) 
                    if rule_to_anf(r)[0] == 0 and 
                    all(rule_to_anf(r)[i] == 0 for i in range(8) if bin(i).count('1') > 1)]
    
    print(f"\n  Linear rules: {linear_rules}")
    
    for r in linear_rules:
        if r == 0:
            continue
        print(f"\n  Rule {r}:")
        for n in [4, 6, 8, 10]:
            fps = []
            for bits in product([0, 1], repeat=n):
                state = list(bits)
                if is_fixed_point(r, state):
                    fps.append(state)
            
            if len(fps) > 1:
                # This is a linear code
                k = round(log2(len(fps))) if len(fps) > 0 else 0
                # Minimum weight (distance) of nonzero codewords
                min_weight = min(sum(fp) for fp in fps if any(fp))
                print(f"    n={n:2d}: [{n},{k}] code, |C|={len(fps)}, d_min={min_weight}")
            else:
                print(f"    n={n:2d}: trivial (only {len(fps)} fixed point)")


