import numpy as np
from itertools import product


def eca_local_rule(r: int, left: int, center: int, right: int) -> int:
    """Local update function for ECA rule r.
    
    Maps neighborhood (left, center, right) ∈ {0,1}³ to output bit.
    The rule number r encodes the truth table: bit (4*left + 2*center + right)
    of r gives the output.
    """
    idx = 4 * left + 2 * center + right
    return (r >> idx) & 1


def eca_step(r: int, state: np.ndarray) -> np.ndarray:
    """Apply one step of ECA rule r to a cyclic state array."""
    n = len(state)
    new_state = np.zeros(n, dtype=int)
    for i in range(n):
        left = state[(i - 1) % n]
        center = state[i]
        right = state[(i + 1) % n]
        new_state[i] = eca_local_rule(r, left, center, right)
    return new_state


def is_fixed_point(r: int, state: np.ndarray) -> bool:
    """Check if state is a fixed point of rule r."""
    return np.array_equal(eca_step(r, state), state)


def count_fixed_points(r: int, n: int) -> int:
    """Count fixed points of rule r on n cells (brute force)."""
    count = 0
    for bits in product([0, 1], repeat=n):
        state = np.array(bits, dtype=int)
        if is_fixed_point(r, state):
            count += 1
    return count


def fixed_point_dimension(r: int, n: int) -> float:
    """Compute log₂ of the number of fixed points (variety dimension)."""
    fp_count = count_fixed_points(r, n)
    if fp_count == 0:
        return -1  # No fixed points
    return np.log2(fp_count)


class GF2Polynomial3:
    """Polynomial over GF(2) in three variables (l, c, r) of degree ≤ 3.
    
    f(l,c,r) = a₀ + a₁l + a₂c + a₃r + a₄lc + a₅lr + a₆cr + a₇lcr
    """
    
    def __init__(self, coeffs: list[int]):
        """coeffs = [const, l, c, r, lc, lr, cr, lcr]"""
        assert len(coeffs) == 8
        self.coeffs = [c % 2 for c in coeffs]
    
    def eval(self, l: int, c: int, r: int) -> int:
        """Evaluate polynomial at (l, c, r) over GF(2)."""
        monomials = [1, l, c, r, l*c, l*r, c*r, l*c*r]
        return sum(a * m for a, m in zip(self.coeffs, monomials)) % 2
    
    @property
    def degree(self) -> int:
        if self.coeffs[7]:
            return 3
        if any(self.coeffs[4:7]):
            return 2
        if any(self.coeffs[1:4]):
            return 1
        if self.coeffs[0]:
            return 0
        return 0  # zero polynomial
    
    @property
    def is_linear(self) -> bool:
        return self.coeffs[0] == 0 and all(c == 0 for c in self.coeffs[4:])
    
    def __repr__(self):
        terms = []
        names = ['1', 'l', 'c', 'r', 'lc', 'lr', 'cr', 'lcr']
        for coeff, name in zip(self.coeffs, names):
            if coeff:
                terms.append(name)
        return ' + '.join(terms) if terms else '0'


def rule_to_polynomial(r: int) -> GF2Polynomial3:
    """Convert rule number to its algebraic normal form polynomial over GF(2).
    
    Uses Möbius inversion on the truth table to find ANF coefficients.
    """
    # Get truth table
    table = [eca_local_rule(r, l, c, ri) for l, c, ri in product([0, 1], repeat=3)]
    
    # Möbius transform to get ANF coefficients
    # ANF: f(x) = ⊕_{S ⊆ {0,1,2}} a_S * ∏_{i∈S} x_i
    anf = table.copy()
    for i in range(3):
        step = 1 << i
        for j in range(8):
            if j & step:
                anf[j] ^= anf[j ^ step]
    
    # Map from bit-index ordering to our coefficient ordering
    # Index 0 = (0,0,0) → const
    # Index 1 = (0,0,1) → r
    # Index 2 = (0,1,0) → c
    # Index 3 = (0,1,1) → cr
    # Index 4 = (1,0,0) → l
    # Index 5 = (1,0,1) → lr
    # Index 6 = (1,1,0) → lc
    # Index 7 = (1,1,1) → lcr
    return GF2Polynomial3([anf[0], anf[4], anf[2], anf[1], anf[6], anf[5], anf[3], anf[7]])


def transfer_matrix(r: int) -> np.ndarray:
    """Compute the 4×4 transfer matrix for fixed-point counting.
    
    States (s_i, s_{i+1}) are indexed by 2*s_i + s_{i+1}.
    Transition (s_i, s_j) → (s_j, s_k) is valid if localRule(s_i, s_j, s_k) = s_j.
    """
    T = np.zeros((4, 4), dtype=int)
    for row in range(4):
        si = (row >> 1) & 1
        sj = row & 1
        for sk in range(2):
            col = 2 * sj + sk
            if eca_local_rule(r, si, sj, sk) == sj:
                T[row, col] = 1
    return T


def count_fixed_points_transfer(r: int, n: int) -> int:
    """Count fixed points using transfer matrix method (trace of T^n over GF(2)-ish).
    
    For cyclic boundary conditions, the number of fixed points equals Tr(T^n)
    where T is the transfer matrix and the trace counts closed walks of length n.
    """
    T = transfer_matrix(r)
    Tn = np.linalg.matrix_power(T, n)
    return int(np.trace(Tn))


