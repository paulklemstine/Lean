"""
Applications: Cellular Automata as Algebraic Geometry
=====================================================

Real-world applications of the ECA algebraic geometry framework:

1. **Cryptographic stream cipher analysis**: Linear rules over GF(2) produce
   predictable patterns (linear recurrences), while nonlinear rules resist
   linear cryptanalysis. The polynomial degree measures cryptographic strength.

2. **Error-correcting codes**: Fixed-point varieties of linear ECAs are
   linear codes over GF(2). The transfer matrix eigenvalues determine
   the code's minimum distance and error-correction capability.

3. **Pattern classification**: The fixed-point variety dimension serves as
   a complexity measure that distinguishes Wolfram's four classes.
"""

from itertools import product
from math import log2, gcd


def eca_local_rule(r, left, center, right):
    idx = 4 * left + 2 * center + right
    return (r >> idx) & 1


def eca_step(r, state):
    n = len(state)
    return [eca_local_rule(r, state[(i-1) % n], state[i], state[(i+1) % n]) for i in range(n)]


def is_fixed_point(r, state):
    return eca_step(r, state) == state


def count_fixed_points(r, n):
    count = 0
    for bits in product([0, 1], repeat=n):
        if is_fixed_point(r, list(bits)):
            count += 1
    return count


def rule_to_anf(r):
    table = [(r >> i) & 1 for i in range(8)]
    anf = table.copy()
    for bit in range(3):
        step = 1 << bit
        for j in range(8):
            if j & step:
                anf[j] ^= anf[j ^ step]
    return anf


def anf_degree(anf):
    max_deg = 0
    for i in range(8):
        if anf[i]:
            max_deg = max(max_deg, bin(i).count('1'))
    return max_deg


