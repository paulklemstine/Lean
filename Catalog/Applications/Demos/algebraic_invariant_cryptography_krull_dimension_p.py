@dataclass
class IdealZ:
    """An ideal in Z, represented by its generator (Z is a PID)."""
    generator: int  # (n) for generator n, 0 for (0), -1 for Z

    def __contains__(self, x: int) -> bool:
        if self.generator == -1:
            return True
        if self.generator == 0:
            return x == 0
        return x % self.generator == 0

    def __le__(self, other: 'IdealZ') -> bool:
        if other.generator == -1:
            return True
        if self.generator == -1:
            return False
        if self.generator == 0:
            return True
        if other.generator == 0:
            return self.generator == 0
        return other.generator % self.generator == 0 or self.generator % other.generator == 0

    def __lt__(self, other: 'IdealZ') -> bool:
        return self <= other and self.generator != other.generator

    def __repr__(self):
        if self.generator == -1:
            return "Z"
        if self.generator == 0:
            return "(0)"
        return f"({abs(self.generator)})"

    @property
    def height(self) -> int:
        """Height of a prime ideal in Z.
        (0) has height 0, (p) for prime p has height 1."""
        if self.generator == 0:
            return 0
        return 1


def analyze_protocol_chain(chain: List[IdealZ]) -> Dict:
    """
    Analyze a protocol chain of ideals in Z.

    Algorithm complexity: O(n) where n = chain length.

    Returns:
        Dictionary with chain analysis results including
        length, validity, height bounds, and security parameters.
    """
    result = {
        'chain': chain,
        'length': len(chain) - 1,
        'valid': True,
        'heights': [],
        'security_depth': 0,
    }

    for i in range(len(chain) - 1):
        if not chain[i] < chain[i + 1]:
            result['valid'] = False
            result['error'] = f"Chain not strictly ascending at index {i}"
            return result

    result['heights'] = [ideal.height for ideal in chain
                         if ideal.generator >= 0]
    result['security_depth'] = max(result['heights']) if result['heights'] else 0

    return result


