# Application 3: Homomorphic Encryption Modulus Switching
# ============================================================================

def analyze_modulus_switching(
    initial_modulus: int,
    switching_chain: List[int]
) -> Dict:
    """
    Analyze modulus switching in homomorphic encryption using
    quotient dimension monotonicity.

    By our theorem: dim(R/I) ≤ dim(R)
    Each modulus switch reduces dimension, bounding noise growth.

    Args:
        initial_modulus: Starting modulus q₀
        switching_chain: List of moduli [q₁, q₂, ..., qₖ]

    Returns:
        Analysis of the switching chain
    """
    chain = [initial_modulus] + switching_chain
    results = []

    for i in range(len(chain) - 1):
        q_before = chain[i]
        q_after = chain[i + 1]
        # Dimension reduction is at most 1 per switch
        # (by the quotient dimension monotonicity theorem)
        results.append({
            'step': i + 1,
            'modulus_before': q_before,
            'modulus_after': q_after,
            'dimension_reduction': 'at most 1',
            'security_maintained': q_after > 1,
        })

    return {
        'initial_modulus': initial_modulus,
        'final_modulus': chain[-1],
        'n_switches': len(chain) - 1,
        'steps': results,
        'termination_guaranteed': True,  # By ACC theorem
        'security_monotone': all(r['security_maintained'] for r in results),
    }


