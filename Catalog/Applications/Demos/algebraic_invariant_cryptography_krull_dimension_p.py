@dataclass
class SecurityCertificate:
    """
    A machine-checkable security certificate.

    Carries:
    - The ideal and its generators
    - Height bound (minimum key dimension)
    - Krull dimension (global security parameter)
    - SpanFinrank (key generation complexity)
    - Proof that ht(I) ≤ spanFinrank(I) ≤ dim(R)
    """
    generators: List[int]
    height: int
    krull_dim: int
    span_finrank: int

    def verify_cascade(self) -> bool:
        """Verify the dimension-height-generator cascade."""
        return self.height <= self.span_finrank <= self.krull_dim

    def security_level(self) -> str:
        """Return the security level classification."""
        if self.height == 0:
            return "TRIVIAL (height 0: generic point)"
        elif self.height == 1:
            return f"LEVEL-1 (Hauptidealsatz bound)"
        else:
            return f"LEVEL-{self.height} (height {self.height})"


def generate_security_certificate(
    generators: List[int],
    ring_dim: int = 1
) -> SecurityCertificate:
    """
    Generate a security certificate for an ideal in Z or Z[X].

    Algorithm:
    1. Compute the ideal generated by the given elements
    2. Determine the height using prime factorization
    3. Verify the cascade ht ≤ spanFinrank ≤ dim

    Complexity: O(n log max(generators)) where n = |generators|.

    Args:
        generators: List of generators for the ideal
        ring_dim: Krull dimension of the ambient ring (1 for Z, 2 for Z[X])

    Returns:
        SecurityCertificate with verified bounds
    """
    if not generators:
        return SecurityCertificate([], 0, ring_dim, 0)

    # In Z, the ideal (a₁, ..., aₙ) = (gcd(a₁, ..., aₙ))
    g = reduce(gcd, generators)
    height = 0 if g == 0 else 1  # In Z, nonzero primes have height 1
    span_finrank = 1 if g != 0 else 0  # Z is a PID

    return SecurityCertificate(
        generators=generators,
        height=height,
        krull_dim=ring_dim,
        span_finrank=span_finrank
    )


# ============================================================================
# Algorithm 3: Height Computation
# ============================================================================

def compute_height_bound(generators: List[int], ring_dim: int = 1) -> int:
    """
    Compute an upper bound on the height of the ideal generated by
    the given elements, using Krull's height theorem.

    By Krull's Height Theorem:
        ht(I) ≤ |generators| for minimal primes over I

    Complexity: O(1) — just returns |generators| as the bound.

    Args:
        generators: Generators of the ideal
        ring_dim: Krull dimension of the ambient ring

    Returns:
        Upper bound on height (min of |generators| and ring_dim)
    """
    return min(len(generators), ring_dim)


def is_prime_ideal_z(n: int) -> bool:
    """Check if (n) is a prime ideal in Z."""
    if n == 0:
        return True  # (0) is prime in Z (Z is a domain)
    n = abs(n)
    if n < 2:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % i == 0:
            return False
    return True


