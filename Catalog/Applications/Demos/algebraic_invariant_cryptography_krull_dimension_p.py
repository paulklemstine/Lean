# Algorithm 5: Protocol Composition
# ============================================================================

def compose_protocols(
    protocol_a_rounds: int,
    protocol_b_rounds: int,
    dim: int
) -> Dict:
    """
    Analyze the composition of two protocols.

    By the Protocol Composition Stabilization theorem,
    both sub-protocols stabilize, so the composition terminates.

    Total rounds ≤ rounds_a + rounds_b ≤ 2 · dim.

    Args:
        protocol_a_rounds: Rounds in protocol A
        protocol_b_rounds: Rounds in protocol B
        dim: Krull dimension bound

    Returns:
        Composition analysis
    """
    return {
        'protocol_a_rounds': protocol_a_rounds,
        'protocol_b_rounds': protocol_b_rounds,
        'total_rounds': protocol_a_rounds + protocol_b_rounds,
        'krull_dim_bound': dim,
        'terminates': True,
        'complexity': f"O({protocol_a_rounds + protocol_b_rounds})",
    }


