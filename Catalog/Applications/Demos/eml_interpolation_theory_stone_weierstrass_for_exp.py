#!/usr/bin/env python3
"""
EML Stone-Weierstrass Demo

Demonstrates that the algebra generated by exp(x) can approximate
any continuous function on [0,1]. We construct explicit exponential
polynomial approximations and measure their accuracy.
"""

import numpy as np
from typing import Callable

def exp_polynomial_approximation(
    f: Callable[[np.ndarray], np.ndarray],
    degree: int,
    n_points: int = 1000
) -> tuple[np.ndarray, float]:
    """
    Approximate f on [0,1] by a polynomial in exp(x):
        g(x) = c_0 + c_1*exp(x) + c_2*exp(2x) + ... + c_d*exp(d*x)

    Returns coefficients and sup-norm error.
    """
    x = np.linspace(0, 1, n_points)
    # Build Vandermonde-like matrix with exponential monomials
    V = np.column_stack([np.exp(k * x) for k in range(degree + 1)])
    y = f(x)
    # Least squares fit
    coeffs, _, _, _ = np.linalg.lstsq(V, y, rcond=None)

    # Compute approximation and error
    approx = V @ coeffs
    error = np.max(np.abs(approx - y))

    return coeffs, error


def demo_approximation():
    """Demonstrate EML approximation of various functions."""
    print("=" * 60)
    print("EML Stone-Weierstrass: Exponential Polynomial Approximation")
    print("=" * 60)

    # Target functions
    targets = {
        "x^2": lambda x: x**2,
        "sin(2πx)": lambda x: np.sin(2 * np.pi * x),
        "|x - 0.5|": lambda x: np.abs(x - 0.5),
        "x^3 - x": lambda x: x**3 - x,
        "sqrt(x+0.1)": lambda x: np.sqrt(x + 0.1),
    }

    for name, f in targets.items():
        print(f"\nTarget: f(x) = {name}")
        print(f"  {'Degree':>8}  {'Sup-norm error':>15}")
        print(f"  {'------':>8}  {'-------------':>15}")
        for d in [1, 2, 3, 5, 8, 12, 20]:
            _, err = exp_polynomial_approximation(f, d)
            print(f"  {d:>8}  {err:>15.2e}")


def demo_separation():
    """Demonstrate the separation property: exp(x) != exp(y) for x != y."""
    print("\n" + "=" * 60)
    print("Separation Property: exp distinguishes distinct points")
    print("=" * 60)

    pairs = [(0.0, 1.0), (0.3, 0.7), (0.49, 0.51), (0.499, 0.501)]
    for x, y in pairs:
        sep = abs(np.exp(x) - np.exp(y))
        print(f"  |exp({x}) - exp({y})| = {sep:.6e}")


def demo_exp_not_polynomial():
    """Show exp is not a polynomial by comparing derivatives."""
    print("\n" + "=" * 60)
    print("exp is NOT a polynomial: derivative comparison")
    print("=" * 60)

    x0 = 0.5
    exp_val = np.exp(x0)
    print(f"\n  At x = {x0}:")
    print(f"  All derivatives of exp equal exp(x) = {exp_val:.6f}")
    print(f"  But polynomial of degree d has (d+1)-th derivative = 0")
    print(f"  Contradiction for any finite d!")

    # Best polynomial approximation
    for d in [2, 5, 10, 20]:
        x = np.linspace(0, 1, 1000)
        coeffs = np.polyfit(x, np.exp(x), d)
        p = np.poly1d(coeffs)
        err = np.max(np.abs(np.exp(x) - p(x)))
        print(f"  Best poly degree {d:>2}: max error = {err:.2e}")


def demo_exponential_monomials():
    """Compare approximation by exp monomials vs standard monomials."""
    print("\n" + "=" * 60)
    print("Exponential Monomials vs Standard Polynomials")
    print("=" * 60)

    f = lambda x: np.sin(2 * np.pi * x)
    x = np.linspace(0, 1, 1000)

    for d in [3, 5, 8, 12]:
        # Standard polynomial
        V_poly = np.column_stack([x**k for k in range(d + 1)])
        c_poly, _, _, _ = np.linalg.lstsq(V_poly, f(x), rcond=None)
        err_poly = np.max(np.abs(V_poly @ c_poly - f(x)))

        # Exponential polynomial
        V_exp = np.column_stack([np.exp(k * x) for k in range(d + 1)])
        c_exp, _, _, _ = np.linalg.lstsq(V_exp, f(x), rcond=None)
        err_exp = np.max(np.abs(V_exp @ c_exp - f(x)))

        cond_poly = np.linalg.cond(V_poly)
        cond_exp = np.linalg.cond(V_exp)

        print(f"  Degree {d:>2}: poly err={err_poly:.2e} (cond={cond_poly:.1e})"
              f"  exp err={err_exp:.2e} (cond={cond_exp:.1e})")


if __name__ == "__main__":
    demo_approximation()
    demo_separation()
    demo_exp_not_polynomial()
    demo_exponential_monomials()


#!/usr/bin/env python3
"""
Visualization: EML Approximation Convergence

Shows how exponential polynomial approximations converge to
target functions as degree increases.
"""

import numpy as np
import matplotlib.pyplot as plt


def build_exp_vandermonde(x, degree):
    return np.column_stack([np.exp(k * x) for k in range(degree + 1)])


def eml_fit(x, y, degree):
    V = build_exp_vandermonde(x, degree)
    coeffs, _, _, _ = np.linalg.lstsq(V, y, rcond=None)
    return V @ coeffs, coeffs


def main():
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))
    fig.suptitle("EML Stone-Weierstrass: Convergence of Exponential Polynomials",
                 fontsize=14, fontweight='bold')

    x = np.linspace(0, 1, 500)
    targets = {
        "f(x) = sin(2πx)": np.sin(2 * np.pi * x),
        "f(x) = |x - 0.5|": np.abs(x - 0.5),
        "f(x) = x² - x + 0.3": x**2 - x + 0.3,
        "f(x) = √(x + 0.1)": np.sqrt(x + 0.1),
    }

    degrees = [1, 3, 5, 10, 20]
    colors = plt.cm.viridis(np.linspace(0.2, 0.9, len(degrees)))

    for ax, (name, y_target) in zip(axes.flat, targets.items()):
        ax.plot(x, y_target, 'k-', linewidth=2, label='Target', zorder=10)

        for d, color in zip(degrees, colors):
            y_approx, _ = eml_fit(x, y_target, d)
            err = np.max(np.abs(y_approx - y_target))
            ax.plot(x, y_approx, '--', color=color, linewidth=1,
                   label=f'deg {d} (err={err:.1e})')

        ax.set_title(name, fontsize=11)
        ax.set_xlabel('x')
        ax.set_ylabel('y')
        ax.legend(fontsize=7, loc='best')
        ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('eml_approximation_convergence.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("Saved: eml_approximation_convergence.png")


if __name__ == "__main__":
    main()


#!/usr/bin/env python3
"""
Visualization: Error Decay Rate for EML Approximation

Plots how the approximation error decreases as the degree of the
exponential polynomial increases, for various target functions.
"""

import numpy as np
import matplotlib.pyplot as plt


def build_exp_vandermonde(x, degree):
    return np.column_stack([np.exp(k * x) for k in range(degree + 1)])


def compute_error(f_values, x, degree):
    V = build_exp_vandermonde(x, degree)
    coeffs, _, _, _ = np.linalg.lstsq(V, f_values, rcond=None)
    approx = V @ coeffs
    return np.max(np.abs(approx - f_values))


def main():
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))
    fig.suptitle("EML Approximation: Error Decay Rates", fontsize=14, fontweight='bold')

    x = np.linspace(0, 1, 2000)
    degrees = list(range(1, 30))

    targets = {
        "sin(2πx)": np.sin(2 * np.pi * x),
        "|x - 0.5|": np.abs(x - 0.5),
        "x² - x + 0.3": x**2 - x + 0.3,
        "√(x+0.1)": np.sqrt(x + 0.1),
        "x·sin(10πx)": x * np.sin(10 * np.pi * x),
    }

    # Left: Error vs degree (log scale)
    for name, y in targets.items():
        errors = []
        for d in degrees:
            try:
                err = compute_error(y, x, d)
                errors.append(max(err, 1e-16))
            except Exception:
                errors.append(errors[-1] if errors else 1.0)
        ax1.semilogy(degrees, errors, 'o-', markersize=3, label=name)

    ax1.set_xlabel('Degree of exponential polynomial')
    ax1.set_ylabel('Sup-norm error')
    ax1.set_title('Convergence Rate')
    ax1.legend(fontsize=8)
    ax1.grid(True, alpha=0.3)
    ax1.set_ylim(1e-16, 10)

    # Right: Condition number comparison
    activations = {
        "exp": np.exp,
        "tanh": np.tanh,
        "sigmoid": lambda t: 1 / (1 + np.exp(-t)),
        "id (polynomial)": lambda t: t,
    }

    sizes = list(range(3, 25))
    for name, sigma in activations.items():
        conds = []
        x_grid = np.linspace(0.01, 0.99, 50)
        for n in sizes:
            try:
                V = np.column_stack([sigma(x_grid)**j for j in range(n)])
                c = np.linalg.cond(V)
                conds.append(min(c, 1e20))
            except Exception:
                conds.append(1e20)
        ax2.semilogy(sizes, conds, 'o-', markersize=3, label=name)

    ax2.set_xlabel('Matrix size n')
    ax2.set_ylabel('Condition number')
    ax2.set_title('Numerical Stability: Activation Vandermonde Matrices')
    ax2.legend(fontsize=8)
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('eml_error_decay.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("Saved: eml_error_decay.png")


if __name__ == "__main__":
    main()
