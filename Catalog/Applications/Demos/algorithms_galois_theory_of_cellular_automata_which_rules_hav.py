#!/usr/bin/env python3
"""
Type-hinted implementations of the core algorithms for CA reversibility theory.

Algorithms:
1. compute_dynamical_core — Compute the dynamical core of an endomorphism
2. compute_reversibility_group — Compute the reversibility group for a given n
3. check_rule_reversibility — Determine if an elementary CA rule is reversible
4. compute_image_tower — Compute the full image tower with depth tracking
5. rule150_circulant_det — Compute Rule 150's circulant determinant over GF(2)
"""

from typing import (
    TypeVar, Callable, Set, List, Tuple, Dict, FrozenSet, Optional
)
from itertools import product, permutations
from functools import reduce

T = TypeVar('T')
Config = Tuple[int, ...]


def compute_dynamical_core(
    f: Callable[[T], T],
    universe: Set[T]
) -> Tuple[Set[T], int]:
    """
    Compute the dynamical core and core depth of an endomorphism.
    
    The dynamical core is the largest f-invariant subset on which f acts
    bijectively. The core depth is the number of iterations until the
    image tower stabilizes.
    
    Args:
        f: An endomorphism of a finite set.
        universe: The full finite set (domain and codomain of f).
    
    Returns:
        (core, depth) where core is the dynamical core and depth is
        the stabilization depth.
    
    Time complexity: O(|universe|^2) worst case.
    """
    current: Set[T] = set(universe)
    depth: int = 0
    
    while True:
        next_image: Set[T] = {f(x) for x in current}
        if next_image == current:
            return current, depth
        current = next_image
        depth += 1


def compute_image_tower(
    f: Callable[[T], T],
    universe: Set[T]
) -> List[Tuple[Set[T], int]]:
    """
    Compute the full image tower with cardinalities at each level.
    
    Returns a list of (image_set, cardinality) pairs from Im^0 to stabilization.
    """
    tower: List[Tuple[Set[T], int]] = []
    current: Set[T] = set(universe)
    
    while True:
        tower.append((set(current), len(current)))
        next_image: Set[T] = {f(x) for x in current}
        if next_image == current:
            break
        current = next_image
    
    return tower


def check_rule_reversibility(
    rule_number: int,
    n: int
) -> Tuple[bool, int, int]:
    """
    Check if an elementary CA rule is reversible on Z/nZ.
    
    Returns:
        (is_reversible, image_size, config_count)
    """
    configs: List[Config] = list(product([0, 1], repeat=n))
    rule_bits: List[int] = [(rule_number >> i) & 1 for i in range(8)]
    
    def apply_rule(c: Config) -> Config:
        return tuple(
            rule_bits[c[(i-1) % n] * 4 + c[i] * 2 + c[(i+1) % n]]
            for i in range(n)
        )
    
    images: Set[Config] = {apply_rule(c) for c in configs}
    return len(images) == len(configs), len(images), len(configs)


def compute_reversibility_group_generators(
    n: int
) -> Dict[str, Callable[[Config], Config]]:
    """
    Return the generators of the reversibility group for binary CAs on Z/nZ.
    
    The group is generated by the shift σ and the complement ν.
    """
    def shift(c: Config) -> Config:
        return tuple(c[(i + 1) % n] for i in range(n))
    
    def complement(c: Config) -> Config:
        return tuple(1 - x for x in c)
    
    return {"shift": shift, "complement": complement}


def enumerate_reversibility_group(
    n: int
) -> List[Dict[Config, Config]]:
    """
    Enumerate all elements of the reversibility group ⟨σ, ν⟩ for binary CAs.
    
    The group has order 2n (n shifts × 2 complement choices).
    Returns each element as a dictionary mapping configs to configs.
    """
    configs: List[Config] = list(product([0, 1], repeat=n))
    gens = compute_reversibility_group_generators(n)
    shift = gens["shift"]
    complement = gens["complement"]
    
    group_elements: List[Dict[Config, Config]] = []
    
    for k in range(n):
        for use_complement in [False, True]:
            perm: Dict[Config, Config] = {}
            for c in configs:
                # Apply shift k times
                result: Config = c
                for _ in range(k):
                    result = shift(result)
                # Optionally apply complement
                if use_complement:
                    result = complement(result)
                perm[c] = result
            group_elements.append(perm)
    
    return group_elements


def rule150_circulant_det_gf2(n: int) -> int:
    """
    Compute the determinant of the Rule 150 circulant matrix over GF(2).
    
    Rule 150's global map on Z/nZ is linear over GF(2), represented by
    the circulant matrix C with first row (1, 1, 0, ..., 0, 1).
    The determinant over GF(2) is 0 iff Rule 150 is irreversible.
    
    Uses Gaussian elimination over GF(2).
    
    Returns: 0 or 1 (the determinant mod 2).
    """
    # Build the circulant matrix
    matrix: List[List[int]] = []
    for i in range(n):
        row: List[int] = [0] * n
        row[i] = 1                    # self
        row[(i - 1) % n] ^= 1        # left neighbor
        row[(i + 1) % n] ^= 1        # right neighbor
        matrix.append(row)
    
    # Gaussian elimination over GF(2)
    det: int = 1
    for col in range(n):
        # Find pivot
        pivot_row: Optional[int] = None
        for row in range(col, n):
            if matrix[row][col] == 1:
                pivot_row = row
                break
        
        if pivot_row is None:
            return 0
        
        # Swap rows
        if pivot_row != col:
            matrix[col], matrix[pivot_row] = matrix[pivot_row], matrix[col]
        
        # Eliminate
        for row in range(n):
            if row != col and matrix[row][col] == 1:
                matrix[row] = [
                    matrix[row][j] ^ matrix[col][j] for j in range(n)
                ]
    
    return det


def information_loss(
    f: Callable[[T], T],
    universe: Set[T]
) -> int:
    """
    Compute the information loss: |universe| - |core(f)|.
    
    Returns 0 iff f is bijective.
    """
    core, _ = compute_dynamical_core(f, universe)
    return len(universe) - len(core)


