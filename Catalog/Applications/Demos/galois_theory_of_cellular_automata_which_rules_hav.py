    print("DEMO 1: Identifying Reversible Elementary CA Rules")
    print("=" * 60)

    # Check which rules are reversible for various periods
    results = {}
    for period in range(3, 8):
        rev = find_reversible_rules(period)
        results[period] = rev
        print(f"\nPeriod {period}: {len(rev)} reversible rules")
        print(f"  Rules: {rev}")

    # Find rules that are reversible for ALL tested periods
    common = set(results[3])
    for period in range(4, 8):
        common &= set(results[period])
    print(f"\nRules reversible for all periods 3-7: {sorted(common)}")
    print("These are the 'universally reversible' elementary CAs.")

    # Analyze the universally reversible rules
    print("\nAnalysis of universally reversible rules:")
    for rule_num in sorted(common):
        rule = wolfram_rule(rule_num)
        table = [rule((a, b, c)) for a in [0, 1] for b in [0, 1] for c in [0, 1]]
        print(f"  Rule {rule_num}: truth table = {table}")
        # Check if it's a simple transformation
        if rule_num == 204:
            print("    → Identity rule: f(a,b,c) = b")
        elif rule_num == 170:
            print("    → Left-shift rule: f(a,b,c) = a")
        elif rule_num == 240:
            print("    → Right-shift rule: f(a,b,c) = c... wait")
            # Actually check
            is_right = all(rule((a, b, c)) == c for a in [0,1] for b in [0,1] for c in [0,1])
            is_left = all(rule((a, b, c)) == a for a in [0,1] for b in [0,1] for c in [0,1])
            if is_right:
                print("    → Confirmed: right neighbor rule f(a,b,c) = c")
            elif is_left:
                print("    → Actually: left neighbor rule f(a,b,c) = a")
        elif rule_num == 51:
            print("    → Complement rule: f(a,b,c) = 1-b")
        elif rule_num == 15:
            print("    → Complement of right: f(a,b,c) = 1-c... check")
