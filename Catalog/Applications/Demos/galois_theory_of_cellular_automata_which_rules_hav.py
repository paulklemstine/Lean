def demo_group_structure():
    """Compute the group generated by reversible CA rules."""
    print("\n" + "=" * 60)
    print("DEMO 2: Reversibility Group Structure")
    print("=" * 60)

    period = 3  # Work with period 3 for tractability
    configs = list(cartesian_product([0, 1], repeat=period))

    # Get the universally reversible rules
    rev_rules = [15, 51, 85, 170, 204, 240]

    print(f"\nComputing group generated by rules {rev_rules} on period {period}...")

    # Compute the permutations for each rule
    generators = []
    for rule_num in rev_rules:
        perm = compute_permutation(rule_num, period)
        generators.append(perm)
        cycles = permutation_to_cycles(perm)
        print(f"  Rule {rule_num}: {len(cycles)} non-trivial cycles")
        for cycle in cycles:
            print(f"    {cycle}")

    # Generate the full group
    group = generate_group(generators, configs)
    print(f"\nGroup order: {len(group)}")

    # Compare with centralizer of shift
    shift = shift_permutation(period)
    cycle_type = compute_shift_cycle_type(period)
    centralizer_order = centralizer_size_from_cycle_type(cycle_type, 2**period)
    print(f"Shift cycle type: {cycle_type}")
    print(f"Centralizer of shift in S_{2**period}: order {centralizer_order}")
    print(f"Ratio group/centralizer: {len(group)}/{centralizer_order} = {len(group)/centralizer_order:.4f}")

    if len(group) == centralizer_order:
        print("✓ The reversibility group equals the centralizer of the shift!")
    elif len(group) < centralizer_order:
        print("The reversibility group is a PROPER SUBGROUP of the centralizer.")
    else:
        print("⚠ Something unexpected: group is larger than centralizer?!")


def demo_centralizer_analysis():
    """Analyze the centralizer structure for various periods."""
    print("\n" + "=" * 60)
    print("DEMO 3: Centralizer Analysis Across Periods")
    print("=" * 60)

    print(f"\n{'Period':>6} {'|Config|':>8} {'|S_n|':>15} {'|Centralizer|':>15} {'Ratio':>12}")
    print("-" * 60)

    for period in range(2, 8):
        n = 2 ** period
        sn_order = math.factorial(n)
        cycle_type = compute_shift_cycle_type(period)
        cent_order = centralizer_size_from_cycle_type(cycle_type, n)
        ratio = cent_order / sn_order

        print(f"{period:>6} {n:>8} {sn_order:>15} {cent_order:>15} {ratio:>12.2e}")

    print("\nObservation: The centralizer fraction decreases super-exponentially,")
    print("confirming that shift-equivariant permutations are extremely rare")
    print("among all permutations.")


def demo_necklace_connection():
    """Connect the centralizer to necklace counting (Burnside's lemma)."""
    print("\n" + "=" * 60)
    print("DEMO 4: Connection to Necklace Theory")
    print("=" * 60)

    print("\nThe orbits of the shift on {0,1}^n are binary necklaces.")
    print("The centralizer structure is determined by orbit sizes.\n")

    for period in range(2, 8):
        cycle_type = compute_shift_cycle_type(period)
        total_configs = 2 ** period
        num_orbits = sum(cycle_type.values())

        # Count necklaces using Burnside's lemma
        # Number of binary necklaces of length n = (1/n) * sum_{d|n} phi(n/d) * 2^d
        def euler_phi(n):
            result = n
            p = 2
            temp = n
            while p * p <= temp:
                if temp % p == 0:
                    while temp % p == 0:
                        temp //= p
                    result -= result // p
                p += 1
            if temp > 1:
                result -= result // temp
            return result

        necklaces = sum(euler_phi(period // d) * (2 ** d)
                        for d in range(1, period + 1) if period % d == 0) // period

        print(f"Period {period}:")
        print(f"  Cycle type of shift: {cycle_type}")
        print(f"  Number of orbits (= necklaces): {necklaces}")
        print(f"  Orbit sizes: {dict(sorted(cycle_type.items()))}")
        print(f"  Centralizer order: {centralizer_size_from_cycle_type(cycle_type, total_configs)}")


def demo_composition_closure():
    """Verify that reversible rules are closed under composition."""
    print("\n" + "=" * 60)
    print("DEMO 5: Composition Closure of Reversible CAs")
    print("=" * 60)

    period = 5
    rev_rules = find_reversible_rules(period)
    print(f"\nReversible rules for period {period}: {rev_rules}")

    # Check that composing any two reversible rules gives a bijection
    all_configs = list(cartesian_product([0, 1], repeat=period))
    print(f"\nChecking all {len(rev_rules)}² = {len(rev_rules)**2} pairwise compositions...")

    all_bijective = True
    for r1 in rev_rules:
        for r2 in rev_rules:
            rule1 = wolfram_rule(r1)
            rule2 = wolfram_rule(r2)
            # Apply rule2 then rule1
            images = set()
            is_bij = True
            for config in all_configs:
                intermediate = apply_ca_periodic(rule2, list(config))
                result = tuple(apply_ca_periodic(rule1, intermediate))
                if result in images:
                    is_bij = False
                    break
                images.add(result)
            if not is_bij:
                print(f"  ⚠ Rule {r1} ∘ Rule {r2} is NOT bijective!")
                all_bijective = False

    if all_bijective:
        print("✓ All pairwise compositions are bijective!")
        print("  This confirms the group structure of reversible CAs.")


