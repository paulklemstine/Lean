def demo_group_structure():
    """Demo 3: Group structure of reversible CA compositions."""
    print("=" * 60)
    print("DEMO 3: Reversibility Group Structure")
    print("=" * 60)
    print()
    
    # For small n, compute the group generated by the 6 reversible rules
    reversible_rules = [wolfram_rule(r) for r in [15, 51, 85, 170, 204, 240]]
    
    for n in [3, 4, 5, 6]:
        order = composition_group_order(reversible_rules, n)
        print(f"  n = {n}: |G| = {order} (expected: 2n = {2*n})")
    
    print()
    print("The group is Z/nZ × Z/2Z (cyclic shifts × complement)")
    print("  - Z/nZ generated by the left shift (Rule 170)")
    print("  - Z/2Z generated by the complement (Rule 51)")
    print("  - These commute: shift ∘ complement = complement ∘ shift")
    
    print()
    
    # Verify commutativity
    n = 5
    rule_170 = wolfram_rule(170)
    rule_51 = wolfram_rule(51)
    
    print(f"Verifying commutativity (n={n}):")
    all_configs = list(product([False, True], repeat=n))
    commutes = all(
        global_map(rule_170, global_map(rule_51, c)) ==
        global_map(rule_51, global_map(rule_170, c))
        for c in all_configs
    )
    print(f"  shift ∘ complement = complement ∘ shift: {commutes}")
    
    print()


