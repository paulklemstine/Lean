"""
Visualization: Reversibility Landscape of Elementary Cellular Automata

Produces a heatmap showing which of the 256 elementary CA rules are reversible
for each period, plus a diagram of the reversibility group structure.
"""

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from algorithms import is_reversible_on_period, compute_shift_cycle_type, centralizer_size_from_cycle_type
import math


def plot_reversibility_heatmap():
    """Create a heatmap of reversibility across rules and periods."""
    periods = list(range(3, 10))
    rules = list(range(256))

    data = np.zeros((len(periods), len(rules)))
    for pi, period in enumerate(periods):
        for ri, rule in enumerate(rules):
            if is_reversible_on_period(rule, period):
                data[pi, ri] = 1

    fig, ax = plt.subplots(figsize=(16, 4))
    im = ax.imshow(data, aspect='auto', cmap='RdYlGn', interpolation='nearest')
    ax.set_xlabel('Rule Number (0-255)', fontsize=12)
    ax.set_ylabel('Period', fontsize=12)
    ax.set_yticks(range(len(periods)))
    ax.set_yticklabels(periods)
    ax.set_title('Reversibility of Elementary CA Rules by Period\n'
                 '(Green = Reversible, Red = Irreversible)', fontsize=14)

    # Mark the universally reversible rules
    universal = [15, 51, 85, 170, 204, 240]
    for r in universal:
        ax.axvline(x=r, color='blue', alpha=0.3, linewidth=0.5)

    plt.colorbar(im, ax=ax, label='Reversible')
    plt.tight_layout()
    plt.savefig('reversibility_heatmap.png', dpi=150)
    plt.close()
    print("Saved: reversibility_heatmap.png")


def plot_centralizer_decay():
    """Plot the super-exponential decay of the centralizer fraction."""
    periods = list(range(2, 9))
    fractions = []

    for period in periods:
        n = 2 ** period
        log_sn = sum(math.log10(i) for i in range(1, n + 1))
        ct = compute_shift_cycle_type(period)
        cent = centralizer_size_from_cycle_type(ct, n)
        log_cent = math.log10(cent)
        fractions.append(log_cent - log_sn)

    fig, ax = plt.subplots(figsize=(8, 6))
    ax.plot(periods, fractions, 'bo-', markersize=8, linewidth=2)
    ax.set_xlabel('Period n', fontsize=14)
    ax.set_ylabel('log₁₀(|Centralizer| / |Sₙ|)', fontsize=14)
    ax.set_title('Fraction of Shift-Equivariant Permutations\n'
                 '(Super-Exponential Decay)', fontsize=14)
    ax.grid(True, alpha=0.3)

    # Add annotations
    for i, (p, f) in enumerate(zip(periods, fractions)):
        ax.annotate(f'n={p}', (p, f), textcoords="offset points",
                    xytext=(10, 5), fontsize=9)

    plt.tight_layout()
    plt.savefig('centralizer_decay.png', dpi=150)
    plt.close()
    print("Saved: centralizer_decay.png")


