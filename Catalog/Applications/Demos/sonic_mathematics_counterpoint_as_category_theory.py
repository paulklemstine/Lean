print()
print(f"{'Interval':<25} {'Semitones':<10} {'Order':<8} {'Subgroup':<20} {'Type':<12}")
print("-" * 75)

for i in sorted(CONSONANT):
    order = additive_order(i)
    subgrp = sorted(cyclic_subgroup(i))
    is_perfect = i in PERFECT
    typename = "PERFECT" if is_perfect else "imperfect"
    name = INTERVAL_NAMES[i]
    print(f"{name:<25} {i:<10} {order:<8} {str(subgrp):<20} {typename:<12}")

print()
print("Key insight: Perfect consonances have order 1 (trivial) or 12 (full group).")
print("Imperfect consonances have intermediate orders (3 or 4).")

# === Demonstration 2: The Complement Involution ===

print()
print("=" * 70)
print("THEOREM: Complement Preserves Imperfect Consonances")
print("=" * 70)
print()

for i in sorted(CONSONANT):
    comp = complement(i)
    name_i = INTERVAL_NAMES[i]
    name_c = INTERVAL_NAMES[comp]
    in_consonant = comp in CONSONANT
    status = "✓ consonant" if in_consonant else "✗ DISSONANT"
    print(f"  -{i} mod 12 = {comp}: {name_i} → {name_c}  [{status}]")

print()
print("The perfect fifth (7) is the UNIQUE consonant interval whose complement")
print("is dissonant. This explains the 'problem of the fourth' in music theory.")

# === Demonstration 3: The Transition Graph ===

print()
print("=" * 70)
print("THEOREM: Valid Transition Count = 34")
print("=" * 70)
print()

valid_count = 0
cross_count = 0
self_count = 0
forbidden = []

for src in sorted(CONSONANT):
    for tgt in sorted(CONSONANT):
        if src == tgt:
            if src not in PERFECT:
                valid_count += 1
                self_count += 1
            else:
                forbidden.append((src, tgt))
        else:
            valid_count += 1
            cross_count += 1

print(f"Cross-transitions (i ≠ j): {cross_count}")
print(f"Self-loops (parallel motion on imperfect): {self_count}")
print(f"Forbidden (parallel motion on perfect): {len(forbidden)} → {forbidden}")
print(f"Total valid transitions: {valid_count}")

