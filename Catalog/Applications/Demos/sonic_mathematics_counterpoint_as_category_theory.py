from math import gcd

# === Core Definitions ===

INTERVAL_NAMES = {
    0: "P1 (unison)", 1: "m2", 2: "M2", 3: "m3 (minor third)",
    4: "M3 (major third)", 5: "P4 (perfect fourth)", 6: "TT (tritone)",
    7: "P5 (perfect fifth)", 8: "m6 (minor sixth)", 9: "M6 (major sixth)",
    10: "m7", 11: "M7"
}

CONSONANT = {0, 3, 4, 7, 8, 9}
PERFECT = {0, 7}
IMPERFECT = {3, 4, 8, 9}

def additive_order(k: int, n: int = 12) -> int:
    """Additive order of k in Z/nZ: smallest positive m with m*k ≡ 0 (mod n)."""
    if k % n == 0:
        return 1
    return n // gcd(n, k % n)

def cyclic_subgroup(k: int, n: int = 12) -> set[int]:
    """The cyclic subgroup generated by k in Z/nZ."""
    return {(m * k) % n for m in range(n)}

def complement(k: int, n: int = 12) -> int:
    """Intervallic complement: -k mod n."""
    return (-k) % n

# === Demonstration 1: The Perfect Consonance Characterization ===

print("=" * 70)
print("THEOREM: Perfect Consonance ↔ Extreme Additive Order")
