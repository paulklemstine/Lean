#!/usr/bin/env python3
"""
Algorithms for Complexity-Optimal Quotient Sections

This module implements the core algorithms from the research paper:
1. Run-deduplication (optimal section for idempotent quotient)
2. Inversion counting and cocycle computation
3. Sorting section with defect analysis
4. Band equivalence checking

All algorithms include complexity analysis and docstrings.
"""

from typing import List, Tuple, TypeVar, Callable
from functools import lru_cache

T = TypeVar('T')


# ─────────────────────────────────────────────────────────────────────
# Algorithm 1: Run Deduplication — O(n) time, O(n) space
# ─────────────────────────────────────────────────────────────────────

def run_dedup(word: List[T]) -> List[T]:
    """Collapse consecutive duplicate elements in a word.

    This is the unique minimum-length representative of the idempotent
    equivalence class containing `word`, where idempotent equivalence
    is generated by the relation xx ~ x for each letter x.

    Time complexity: O(n) where n = len(word)
    Space complexity: O(n) for the output

    Formally verified properties (see QuotientSections.lean):
    - runDedup_minimal_length: len(run_dedup(w)) ≤ len(w') for all w' ~ w
    - runDedup_unique_min_length: unique minimum-length representative
    - runDedup_invariant: run_dedup(w) = run_dedup(w') whenever w ~ w'

    Examples:
        >>> run_dedup([1, 1, 2, 2, 3, 1, 1])
        [1, 2, 3, 1]
        >>> run_dedup([1, 1, 1])
        [1]
        >>> run_dedup([])
        []
    """
    if not word:
        return []
    result = [word[0]]
    for i in range(1, len(word)):
        if word[i] != result[-1]:
            result.append(word[i])
    return result


def is_run_deduplicated(word: List[T]) -> bool:
    """Check if a word has no adjacent duplicates.

    A word is run-deduplicated iff it equals its own run_dedup.

    Time complexity: O(n)
    """
    for i in range(1, len(word)):
        if word[i] == word[i - 1]:
            return False
    return True


# ─────────────────────────────────────────────────────────────────────
# Algorithm 2: Inversion Count — O(n log n) via merge sort
# ─────────────────────────────────────────────────────────────────────

def inversion_count_naive(word: List) -> int:
    """Count inversions using the naive O(n²) algorithm.

    An inversion is a pair (i, j) with i < j and word[i] > word[j].
    """
    count = 0
    n = len(word)
    for i in range(n):
        for j in range(i + 1, n):
            if word[i] > word[j]:
                count += 1
    return count


def inversion_count(word: List) -> Tuple[int, List]:
    """Count inversions using merge sort in O(n log n) time.

    Returns (count, sorted_word).

    The inversion count of a permutation equals the Bruhat length
    in the symmetric group, which equals the minimum number of
    adjacent transpositions needed to sort the sequence.
    """
    if len(word) <= 1:
        return 0, list(word)

    mid = len(word) // 2
    left_inv, left_sorted = inversion_count(word[:mid])
    right_inv, right_sorted = inversion_count(word[mid:])

    merged = []
    cross_inv = 0
    i = j = 0

    while i < len(left_sorted) and j < len(right_sorted):
        if left_sorted[i] <= right_sorted[j]:
            merged.append(left_sorted[i])
            i += 1
        else:
            merged.append(right_sorted[j])
            cross_inv += len(left_sorted) - i
            j += 1

    merged.extend(left_sorted[i:])
    merged.extend(right_sorted[j:])

    return left_inv + right_inv + cross_inv, merged


def cross_inversions(u: List, v: List) -> int:
    """Count cross-inversions between sorted sequences u and v.

    A cross-inversion is a pair (i, j) with u[i] > v[j].
    For sorted u and v, this can be computed in O(|u| + |v|) time
    using a merge-like scan.

    Time complexity: O(|u| + |v|) for sorted inputs
    """
    count = 0
    j = 0
    for x in u:
        while j < len(v) and v[j] < x:
            j += 1
        count += j  # All v[0..j-1] are less than x
    return count


# ─────────────────────────────────────────────────────────────────────
# Algorithm 3: Sorting Section with Defect Analysis
# ─────────────────────────────────────────────────────────────────────

def sort_section(word: List) -> List:
    """The sorting section for the commutative quotient.

    Returns the lexicographically sorted representative.
    This is the canonical section of the free commutative monoid quotient.

    Time complexity: O(n log n)
    """
    return sorted(word)


def cocycle_defect(u: List, v: List) -> int:
    """Compute the 2-cocycle defect of the sorting section.

    For the sorting section σ, the defect is measured by:
        f(u, v) = cross_inversions(σ(u), σ(v))

    This counts how many pairs need to be swapped when merging
    two sorted sequences, which equals the inversion count of
    the permutation relating σ(u)·σ(v) to σ(u·v).

    The defect satisfies the 2-cocycle condition:
        f(u, v) + f(u·v, w) = f(u, v·w) + f(v, w)
    (when measured in the appropriate quotient).

    Time complexity: O(|u| + |v|) for sorted inputs
    """
    su = sort_section(u)
    sv = sort_section(v)
    return cross_inversions(su, sv)


def verify_cocycle_condition(u: List, v: List, w: List) -> dict:
    """Verify the 2-cocycle condition for the sorting section defect.

    The cocycle condition is:
        f(u,v) + f(uv,w) = f(u,vw) + f(v,w)

    where f is the cross-inversion count of sorted representatives.
    """
    f_uv = cocycle_defect(u, v)
    f_uv_w = cocycle_defect(u + v, w)
    f_u_vw = cocycle_defect(u, v + w)
    f_vw = cocycle_defect(v, w)

    lhs = f_uv + f_uv_w
    rhs = f_u_vw + f_vw

    return {
        'u': u, 'v': v, 'w': w,
        'f(u,v)': f_uv,
        'f(uv,w)': f_uv_w,
        'f(u,vw)': f_u_vw,
        'f(v,w)': f_vw,
        'LHS': lhs, 'RHS': rhs,
        'cocycle_holds': lhs == rhs,
    }


# ─────────────────────────────────────────────────────────────────────
# Algorithm 4: Idempotent Equivalence Checking — O(n)
# ─────────────────────────────────────────────────────────────────────

def are_idempotent_equivalent(u: List[T], v: List[T]) -> bool:
    """Check if two words are idempotent-equivalent.

    Two words are idempotent-equivalent iff they have the same
    run-deduplicated form. This is the key invariant.

    Time complexity: O(|u| + |v|)
    """
    return run_dedup(u) == run_dedup(v)


def idempotent_normal_form(word: List[T]) -> List[T]:
    """Compute the unique normal form under idempotent equivalence.

    This is just run_dedup, but named for clarity.
    """
    return run_dedup(word)


# ─────────────────────────────────────────────────────────────────────
# Algorithm 5: Tropical R-Matrix
# ─────────────────────────────────────────────────────────────────────

def tropical_r_matrix(n: int) -> List[List[int]]:
    """Compute the tropical R-matrix at q=0 for GL_n.

    The (i,j)-entry is the tropical eigenvalue of the R-matrix
    acting on the tensor product basis vector e_i ⊗ e_j.

    R(e_i ⊗ e_j) has eigenvalue 1 if i > j (transposition needed)
    R(e_i ⊗ e_j) has eigenvalue 0 if i ≤ j (no transposition)

    Time complexity: O(n²)
    """
    return [[1 if i > j else 0 for j in range(n)] for i in range(n)]


def print_tropical_r_matrix(n: int) -> None:
    """Print the tropical R-matrix in a readable format."""
    matrix = tropical_r_matrix(n)
    print(f"Tropical R-matrix for GL_{n} at q=0:")
    for i, row in enumerate(matrix):
        print(f"  e_{i}: {row}")


