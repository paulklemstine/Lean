# APPLICATION 1: Which primes are represented by x² + ny²?
# ──────────────────────────────────────────────────────────────

def primes_represented_by_form(n: int, bound: int) -> dict:
    """
    Determine which primes p ≤ bound can be written as x² + n·y².

    This is equivalent to asking: does the prime ideal above p in ℤ[√(-n)]
    lie in the principal class of the class group?

    By class field theory, p = x² + ny² iff p splits completely in the
    Hilbert class field of ℚ(√(-n)).

    Returns dict mapping primes to their representations (or None).
    """
    results = {}
    for p in range(2, bound + 1):
        if not is_prime_simple(p):
            continue
        # Try to represent p = x² + n*y²
        rep = None
        y_max = int(math.sqrt(p / n)) + 1
        for y in range(0, y_max + 1):
            x_sq = p - n * y * y
            if x_sq < 0:
                break
            if x_sq >= 0:
                x = int(math.sqrt(x_sq))
                if x * x == x_sq:
                    rep = (x, y)
                    break
        results[p] = rep
    return results


def is_prime_simple(n: int) -> bool:
    if n < 2:
        return False
    if n < 4:
        return True
    if n % 2 == 0 or n % 3 == 0:
        return False
    i = 5
    while i * i <= n:
        if n % i == 0 or n % (i + 2) == 0:
            return False
        i += 6
    return True


