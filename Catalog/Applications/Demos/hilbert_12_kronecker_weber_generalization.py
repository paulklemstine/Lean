def hilbert_class_polynomial_degree(d: int) -> int:
    """
    The degree of the Hilbert class polynomial H_D(x) equals the
    class number h(D). This polynomial's roots are j-invariants of
    CM elliptic curves with endomorphism ring ℤ[√d] (or the full
    ring of integers).

    This connects directly to Hilbert's 12th problem: the roots
    of H_D generate the Hilbert class field of ℚ(√d).
    """
    D = compute_discriminant(d)
    return class_number(D)


