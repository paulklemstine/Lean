def legendre_symbol(a: int, p: int) -> int:
    """Compute the Legendre symbol (a/p) for odd prime p."""
    if a % p == 0:
        return 0
    result = pow(a, (p - 1) // 2, p)
    return result if result == 1 else -1


def minkowski_bound(d: int) -> float:
    """
    Compute the Minkowski bound for Q(sqrt(d)).
    For imaginary quadratic fields (d < 0), this is (2/pi) * sqrt(|disc|).
    For real quadratic fields (d > 0), this is sqrt(|disc|) / 2.
    """
    # Compute discriminant
    if d % 4 == 1:
        disc = d
    else:
        disc = 4 * d
    abs_disc = abs(disc)

    if d < 0:
        return (2.0 / math.pi) * math.sqrt(abs_disc)
    else:
        return math.sqrt(abs_disc) / 2.0


def is_prime(n: int) -> bool:
    """Simple primality test."""
    if n < 2:
        return False
    if n < 4:
        return True
    if n % 2 == 0 or n % 3 == 0:
        return False
    i = 5
    while i * i <= n:
        if n % i == 0 or n % (i + 2) == 0:
            return False
        i += 6
    return True


def primes_up_to(n: int) -> List[int]:
    """Return all primes up to n."""
    return [p for p in range(2, n + 1) if is_prime(p)]


def class_number_imaginary_quadratic(d: int) -> int:
    """
    Compute the class number of Q(sqrt(d)) for d < 0 squarefree
    using the Minkowski bound approach.

    We find all reduced binary quadratic forms of discriminant D,
    which is equivalent to computing the class group.
    """
    assert d < 0, "d must be negative for imaginary quadratic fields"

    # Compute discriminant
    if d % 4 == 1:
        D = d
    else:
        D = 4 * d
    abs_D = abs(D)

    # Count reduced forms: |a| <= sqrt(|D|/3), -a < b <= a, a^2 - D = 4ac
    # A reduced form (a, b, c) satisfies: -a < b <= a, a <= c, and b >= 0 if a == c
    count = 0
    a_max = int(math.sqrt(abs_D / 3.0)) + 1

    for a in range(1, a_max + 1):
        for b in range(-a + 1, a + 1):
            # Check if b ≡ D (mod 2)
            if (b * b - D) % (4 * a) != 0:
                continue
            c = (b * b - D) // (4 * a)
            if c < a:
                continue
            if c == a and b < 0:
                continue
            if c >= 1:
                count += 1

    return count


