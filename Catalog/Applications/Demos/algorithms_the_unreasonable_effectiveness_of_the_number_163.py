#!/usr/bin/env python3
"""
Algorithms for Heegner Number Theory
=====================================

Type-hinted implementations of the core algorithms used in
the study of Heegner numbers, Rabinowitz polynomials, and
near-integer phenomena.
"""

from typing import List, Tuple, Optional, Set
import math


# --- Heegner Number Constants ---

HEEGNER_NUMBERS: List[int] = [1, 2, 3, 7, 11, 19, 43, 67, 163]
HEEGNER_ODD: List[int] = [3, 7, 11, 19, 43, 67, 163]  # ≡ 3 mod 4
RABINOWITZ_CONSTANTS: List[int] = [1, 2, 3, 5, 11, 17, 41]
EULER_LUCKY_PRIMES: List[int] = [2, 3, 5, 11, 17, 41]
J_CUBE_ROOTS: dict[int, int] = {43: 960, 67: 5280, 163: 640320}


def is_prime(n: int) -> bool:
    """Optimized primality test for moderate-sized integers."""
    if n < 2:
        return False
    if n < 4:
        return True
    if n % 2 == 0 or n % 3 == 0:
        return False
    i = 5
    while i * i <= n:
        if n % i == 0 or n % (i + 2) == 0:
            return False
        i += 6
    return True


def disc_to_rab(d: int) -> int:
    """Map Heegner discriminant d to Rabinowitz constant c = (d+1)/4.

    Requires d ≡ 3 (mod 4).
    """
    assert d % 4 == 3, f"d = {d} is not ≡ 3 mod 4"
    return (d + 1) // 4


def rab_to_disc(c: int) -> int:
    """Map Rabinowitz constant c to Heegner discriminant d = 4c - 1."""
    return 4 * c - 1


def rabinowitz_eval(c: int, x: int) -> int:
    """Evaluate the Rabinowitz polynomial R_c(x) = x² + x + c."""
    return x * x + x + c


def heegner_form(x: int, y: int, c: int = 41) -> int:
    """Evaluate the Heegner quadratic form Q(x,y) = x² + xy + cy²."""
    return x * x + x * y + c * y * y


def complete_square_check(x: int, y: int, d: int = 163) -> Tuple[int, int, int]:
    """Verify 4Q(x,y) = (2x+y)² + d·y² for Heegner form.

    Returns (4Q, lhs_sq, d_y_sq) where 4Q = lhs_sq + d_y_sq.
    """
    c = (d + 1) // 4
    four_q = 4 * heegner_form(x, y, c)
    sq_term = (2 * x + y) ** 2
    disc_term = d * y * y
    assert four_q == sq_term + disc_term, "Complete square identity failed!"
    return four_q, sq_term, disc_term


def prime_streak(c: int) -> int:
    """Count consecutive primes generated by x²+x+c starting at x=0."""
    x = 0
    while is_prime(rabinowitz_eval(c, x)):
        x += 1
    return x


def is_euler_lucky(p: int) -> bool:
    """Test if p is an Euler lucky prime.

    p is Euler-lucky if p is prime and x²+x+p is prime for x=0,...,p-2.
    """
    if not is_prime(p):
        return False
    return all(is_prime(rabinowitz_eval(p, x)) for x in range(p - 1))


def quadratic_residues(p: int) -> Set[int]:
    """Compute the set of quadratic residues modulo p."""
    return {(x * x) % p for x in range(p)}


def is_qnr(a: int, p: int) -> bool:
    """Test if a is a quadratic non-residue modulo p."""
    return (a % p) not in quadratic_residues(p)


def verify_qnr_property(d: int = 163) -> List[Tuple[int, bool]]:
    """Verify that -d is a QNR mod every odd prime < sqrt(d+1).

    Returns list of (prime, is_QNR) pairs.
    """
    bound = int(math.sqrt(d + 1)) + 1
    results = []
    for p in range(3, bound):
        if is_prime(p):
            results.append((p, is_qnr(-d, p)))
    return results


def near_integer_quality(d: int) -> Tuple[float, float, int]:
    """Compute e^(π√d) and its distance from the nearest integer.

    Returns (value, error, nearest_integer).
    """
    val = math.exp(math.pi * math.sqrt(d))
    nearest = round(val)
    error = abs(val - nearest)
    return val, error, nearest


def ramanujan_target(d: int) -> Optional[int]:
    """Compute A_d³ + 744 for known j-invariant cube roots.

    Returns None if d is not in the known table.
    """
    if d not in J_CUBE_ROOTS:
        return None
    A = J_CUBE_ROOTS[d]
    return A ** 3 + 744


def form_representations(n: int, c: int = 41, bound: int = 1000) -> List[Tuple[int, int]]:
    """Find all representations of n by Q(x,y) = x² + xy + cy² with |x|,|y| < bound.

    Returns list of (x, y) pairs with Q(x,y) = n.
    """
    reps = []
    for y in range(-bound, bound + 1):
        for x in range(-bound, bound + 1):
            if heegner_form(x, y, c) == n:
                reps.append((x, y))
    return reps


def class_number_bound(d: int) -> float:
    """Compute the Minkowski bound for class number of Q(√(-d)).

    For fundamental discriminant -d (d ≡ 3 mod 4), the bound is (2/π)√d.
    All forms with norm ≤ this bound generate the class group.
    """
    return (2.0 / math.pi) * math.sqrt(d)


# --- Main algorithm demonstration ---

if __name__ == "__main__":
    print("Heegner Number Algorithms")
    print("=" * 50)

    # Verify all Rabinowitz polynomials
    print("\nRabinowitz polynomial prime streaks:")
    for d in HEEGNER_ODD:
        c = disc_to_rab(d)
        streak = prime_streak(c)
        expected = c - 1
        status = "✓" if streak == expected else "✗"
        print(f"  d={d:3d}, c={c:2d}: streak={streak:2d} (expected {expected:2d}) {status}")

    # Verify Euler lucky primes
    print("\nEuler lucky primes (up to 50):")
    for p in range(2, 50):
        if is_prime(p):
            lucky = is_euler_lucky(p)
            if lucky:
                print(f"  p={p:2d}: LUCKY")

    # QNR property
    print("\nQNR property of -163:")
    for p, qnr in verify_qnr_property(163):
        print(f"  p={p:2d}: {'QNR' if qnr else 'QR'}")

    # Near-integer quality
    print("\nNear-integer quality:")
    for d in HEEGNER_NUMBERS:
        val, error, nearest = near_integer_quality(d)
        print(f"  d={d:3d}: error = {error:.2e}")

    # Representations by Heegner form
    print("\nRepresentations of small primes by Q(x,y) = x² + xy + 41y²:")
    for p in [2, 3, 5, 7, 41, 43, 47, 53, 59, 61]:
        reps = form_representations(p, 41, 10)
        print(f"  {p:3d}: {reps if reps else 'none'}")
