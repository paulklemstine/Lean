if __name__ == "__main__":
    print("=== Rabinowitz Polynomial Analysis ===")
    for d, p, count in analyze_rabinowitz_polynomials():
        print(f"  d={d:>3}, p={p:>2}: {count} consecutive primes "
              f"(x² + x + {p}, x=0..{count-1})")

    print("\n=== Class Number Verification ===")
    for d, h in verify_heegner_class_numbers():
        status = "✓" if h == 1 else "✗"
        print(f"  {status} h(-{d}) = {h}")

    print("\n=== Near-Integer Quality (top 15) ===")
    for d, dist in rank_near_integer_quality(100)[:15]:
        marker = " ← HEEGNER" if d in HEEGNER_NUMBERS else ""
        print(f"  d={d:>3}: distance = {dist:.6e}{marker}")

    print("\n=== j-Invariant Connection ===")
    for d in HEEGNER_MOD3:
        exp_val, theory = j_invariant_approximation(d)
        print(f"  d={d:>3}: e^(π√d) ≈ {exp_val:.2f}, "
              f"|j| + 744 = {theory:.0f}")
