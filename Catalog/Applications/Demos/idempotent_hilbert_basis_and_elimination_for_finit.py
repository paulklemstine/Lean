def demo_elimination():
    """Demonstrate variable elimination."""
    print("\n" + "=" * 70)
    print("DEMO 3: Variable Elimination (elimination_fg)")
    print("=" * 70)
    print()
    print("Theorem (elimination_fg): If ι : τ → σ is surjective and")
    print("C is a finitely presented congruence on MvPolynomial σ S,")
    print("then eliminateCongruence(ι, C) is finitely presented.")
    print()
    print("─── Construction ───")
    print()
    print("Given: ι : {a,b,c} → {x,y}, ι(a)=x, ι(b)=x, ι(c)=y")
    print("       C generated by R = {(x², y), (x+y, x)} on k[x,y]")
    print()
    print("Step 1: Fiber collapse")
    print("  surjSection: x ↦ a, y ↦ c")
    print("  fiberCollapse = surjSection ∘ ι:")
    print("    a ↦ a, b ↦ a, c ↦ c")
    print()
    print("Step 2: Kernel generators (kernelGenerators)")
    print("  For each variable t, pair (X_t, X_collapse(t)):")
    print("  {(a,a), (b,a), (c,c)} → non-trivial: {(b,a)}")
    print()
    print("Step 3: Preimage generators (preimageGenerators)")
    print("  For (x², y) ∈ R: choose preimages a² and c")
    print("    → (a², c)")
    print("  For (x+y, x) ∈ R: choose preimages a+c and a")
    print("    → (a+c, a)")
    print()
    print("Step 4: Combine")
    print("  eliminationGenerators = {(a², c), (a+c, a)} ∪ {(b, a)}")
    print()
    print("Result: The elimination congruence on k[a,b,c] is generated")
    print("by these 3 pairs. This is a finite presentation!")


def demo_kernel():
    """Demonstrate kernel of rename."""
    print("\n" + "=" * 70)
    print("DEMO 4: Kernel of rename (kernel_rename_finitely_generated)")
    print("=" * 70)
    print()
    print("Theorem: If ι : τ → σ is surjective, the kernel of rename(ι)")
    print("(i.e., the relation rename(ι)(f) = rename(ι)(g)) is generated")
    print("by pairs {(X_t, X_collapse(t)) | t ∈ τ}.")
    print()
    print("─── Proof idea ───")
    print()
    print("Key lemma (poly_congr_collapsed):")
    print("  For any polynomial f, f ≡ rename(collapse)(f) mod K")
    print()
    print("  Proof by induction on f:")
    print("  • f = c (constant): rename(collapse)(c) = c, so c ≡ c by .refl")
    print("  • f = f₁ + f₂: by IH and .add")
    print("  • f = f₁ · X_t: by IH, .mul, and var_congr_collapsed")
    print()
    print("Main proof:")
    print("  rename(ι)(f) = rename(ι)(g)")
    print("  ⟹ rename(collapse)(f) = rename(collapse)(g)")
    print("     [since collapse = surjSection ∘ ι, apply rename(surjSection)]")
    print("  ⟹ f ≡ rename(collapse)(f) = rename(collapse)(g) ≡ g")
    print("     [by poly_congr_collapsed on both sides + transitivity]")


def demo_pullback():
    """Demonstrate pullback lemma."""
    print("\n" + "=" * 70)
    print("DEMO 5: Pullback Lemma (pullback_RingConGen_of_surjective)")
    print("=" * 70)
    print()
    print("Theorem: If φ : A →+* B is surjective and")
    print("RingConGen.Rel r (φ(a)) (φ(b)), then")
    print("RingConGen.Rel (r ∘ φ ∨ ker φ) a b.")
    print()
    print("The proof generalizes from φ(a), φ(b) to arbitrary x, y ∈ B:")
    print()
    print("  Key insight for .add case:")
    print("  Given w+y ≡ x+z, φ(a) = w+y, φ(b) = x+z:")
    print("  • Choose preimages: w = φ(w'), x = φ(x'), y = φ(y'), z = φ(z')")
    print("  • Then a ≡_ker w'+y' (since φ(a) = φ(w'+y'))")
    print("  • By IH: w' ≡ x' and y' ≡ z'")
    print("  • By .add: w'+y' ≡ x'+z'")
    print("  • And b ≡_ker x'+z'")
    print("  • Chaining: a ≡ w'+y' ≡ x'+z' ≡ b")
    print()
    print("This is proved axiom-free (no Classical.choice needed)!")


def demo_visualization():
    """Create visualizations."""
    print("\n" + "=" * 70)
    print("DEMO 6: Visualizations")
    print("=" * 70)
    
    fig, axes = plt.subplots(1, 3, figsize=(16, 5))
    
    x = np.linspace(-3, 3, 300)
    y = np.linspace(-3, 3, 300)
    X, Y = np.meshgrid(x, y)
    
    # Plot 1: f = max(x, y)
    Z1 = np.maximum(X, Y)
    ax = axes[0]
    im = ax.contourf(X, Y, Z1, levels=20, cmap='viridis')
    ax.set_title('f(x,y) = x ⊕ y = max(x,y)', fontsize=11)
    ax.set_xlabel('x'); ax.set_ylabel('y')
    plt.colorbar(im, ax=ax, shrink=0.8)
    
    # Plot 2: g = max(x+y, 2)
    Z2 = np.maximum(X + Y, 2)
    ax = axes[1]
    im = ax.contourf(X, Y, Z2, levels=20, cmap='viridis')
    ax.set_title('g(x,y) = (x⊙y) ⊕ 2 = max(x+y, 2)', fontsize=11)
    ax.set_xlabel('x'); ax.set_ylabel('y')
    plt.colorbar(im, ax=ax, shrink=0.8)
    
    # Plot 3: Difference |f - g|
    Z3 = np.abs(Z1 - Z2)
    ax = axes[2]
    im = ax.contourf(X, Y, Z3, levels=20, cmap='RdYlGn_r')
    ax.contour(X, Y, Z3, levels=[0.01], colors='red', linewidths=2)
    ax.set_title('|f − g|: equality locus (red)', fontsize=11)
    ax.set_xlabel('x'); ax.set_ylabel('y')
    plt.colorbar(im, ax=ax, shrink=0.8)
    
    plt.suptitle('Tropical Polynomial Congruences', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig('demos/tropical_congruences.png', dpi=150, bbox_inches='tight')
    print("\nSaved: demos/tropical_congruences.png")
    
    # Elimination visualization
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))
    
    # 3D congruence: rename ι sends (a,b,c) → (x,y) with ι(a)=ι(b)=x, ι(c)=y
    # Before elimination: points where f(x,y) = g(x,y)
    ax = axes[0]
    ax.contourf(X, Y, Z3, levels=20, cmap='coolwarm')
    ax.contour(X, Y, Z3, levels=[0.05], colors='black', linewidths=2)
    ax.set_title('Original congruence\nf(x,y) ≡ g(x,y)', fontsize=12)
    ax.set_xlabel('x'); ax.set_ylabel('y')
    
    # After elimination: fiber collapse identifies some variables
    ax = axes[1]
    t = np.linspace(-3, 3, 300)
    # After collapsing a↦a, b↦a, c↦c:
    # f becomes max(a, c), g becomes max(2a, 2)
    f_collapsed = np.maximum(t, 0)  # slice at c=0
    g_collapsed = np.maximum(t + t, 2)  # 2a vs 2
    ax.fill_between(t, f_collapsed, g_collapsed, alpha=0.3, color='orange',
                     label='Congruence gap')
    ax.plot(t, f_collapsed, 'b-', linewidth=2, label='f after collapse (c=0)')
    ax.plot(t, g_collapsed, 'r-', linewidth=2, label='g after collapse (c=0)')
    intersections = np.where(np.abs(f_collapsed - g_collapsed) < 0.05)[0]
    if len(intersections) > 0:
        for idx in [intersections[0], intersections[-1]]:
            ax.axvline(x=t[idx], color='green', linestyle='--', alpha=0.7)
    ax.set_title('After elimination\n(projected to collapsed variables)', fontsize=12)
    ax.set_xlabel('collapsed variable a')
    ax.legend(fontsize=9)
    
    plt.suptitle('Variable Elimination for Congruences', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig('demos/elimination_visualization.png', dpi=150, bbox_inches='tight')
    print("Saved: demos/elimination_visualization.png")


