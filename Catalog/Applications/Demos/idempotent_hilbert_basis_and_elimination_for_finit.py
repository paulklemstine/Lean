def demo_tropical_polynomials():
    """Demonstrate tropical polynomial arithmetic."""
    print("=" * 70)
    print("DEMO 1: Tropical Polynomial Arithmetic")
    print("=" * 70)
    print()
    print("In the tropical semiring (R ∪ {-∞}, max, +):")
    print("  'addition' is max  (idempotent: a ⊕ a = a)")
    print("  'multiplication' is ordinary +")
    print()
    
    # f(x,y) = x ⊕ y = max(x, y)
    # g(x,y) = x ⊙ y = x + y
    vals = [(3, 5), (2, 2), (-1, 4), (0, 0)]
    
    print("  f(x,y) = x ⊕ y = max(x,y)")
    print("  g(x,y) = x ⊙ y = x + y")
    print()
    for x, y in vals:
        f = trop_add(x, y)
        g = trop_mul(x, y)
        print(f"  f({x},{y}) = max({x},{y}) = {f}")
        print(f"  g({x},{y}) = {x}+{y} = {g}")
        print()
    
    # Idempotency
    print("Idempotency: a ⊕ a = max(a, a) = a for all a")
    for a in [3, -2, 0]:
        print(f"  {a} ⊕ {a} = max({a},{a}) = {trop_add(a,a)}")


