def trop_add(a, b):
    """Tropical addition = max."""
    return max(a, b)

def trop_mul(a, b):
    """Tropical multiplication = ordinary +."""
    if a == float('-inf') or b == float('-inf'):
        return float('-inf')
    return a + b

TROP_ZERO = float('-inf')
TROP_ONE = 0


