#!/usr/bin/env python3
"""
algorithms.py — Core Algorithms for Metric Graph Tropical Jacobians

Implements the computational backbone for the metric canonical kernel
correspondence:

1. Weighted Laplacian construction
2. Effective resistance computation
3. Canonical kernel generator extraction
4. Smith normal form for Jacobian invariant factors
5. Subdivision for approximation

All algorithms include docstrings, type hints, and complexity analysis.
"""

import numpy as np
from typing import List, Tuple, Optional
from dataclasses import dataclass


@dataclass
class MetricGraph:
    """A metric graph: a connected simple graph with positive edge lengths.

    Attributes:
        n_vertices: Number of vertices.
        edges: List of (i, j) pairs (undirected edges).
        lengths: List of positive real edge lengths, parallel to edges.
    """
    n_vertices: int
    edges: List[Tuple[int, int]]
    lengths: List[float]

    def __post_init__(self):
        assert len(self.edges) == len(self.lengths)
        assert all(l > 0 for l in self.lengths)

    @property
    def genus(self) -> int:
        """First Betti number: g = |E| - |V| + 1."""
        return len(self.edges) - self.n_vertices + 1

    def adjacency_dict(self) -> dict:
        """Return adjacency dict: vertex -> list of (neighbor, edge_index)."""
        adj = {i: [] for i in range(self.n_vertices)}
        for idx, (i, j) in enumerate(self.edges):
            adj[i].append((j, idx))
            adj[j].append((i, idx))
        return adj


def weighted_laplacian(G: MetricGraph) -> np.ndarray:
    """Compute the weighted Laplacian matrix of a metric graph.

    The weighted Laplacian L has entries:
        L[i,i] = Σ_{j ~ i} 1/ℓ(i,j)  (sum of conductances)
        L[i,j] = -1/ℓ(i,j)            if i ~ j
        L[i,j] = 0                     otherwise

    Time complexity: O(|V|² + |E|)
    Space complexity: O(|V|²)

    Args:
        G: A metric graph with positive edge lengths.

    Returns:
        L: The |V| × |V| weighted Laplacian matrix.
    """
    n = G.n_vertices
    L = np.zeros((n, n))

    for (i, j), length in zip(G.edges, G.lengths):
        conductance = 1.0 / length
        L[i, j] -= conductance
        L[j, i] -= conductance
        L[i, i] += conductance
        L[j, j] += conductance

    return L


def reduced_laplacian(G: MetricGraph, remove_vertex: int = 0) -> np.ndarray:
    """Compute the reduced Laplacian by removing one row and column.

    The reduced Laplacian is invertible for connected graphs.

    Time complexity: O(|V|² + |E|)

    Args:
        G: A metric graph.
        remove_vertex: Vertex to remove (default: 0).

    Returns:
        L_red: The (|V|-1) × (|V|-1) reduced Laplacian.
    """
    L = weighted_laplacian(G)
    indices = [i for i in range(G.n_vertices) if i != remove_vertex]
    return L[np.ix_(indices, indices)]


def effective_resistance_matrix(G: MetricGraph) -> np.ndarray:
    """Compute the effective resistance matrix of a metric graph.

    R[i,j] = (e_i - e_j)^T L^+ (e_i - e_j)

    where L^+ is the Moore-Penrose pseudoinverse of L.

    For connected graphs, R[i,j] is the resistance distance between i and j
    in the electrical network with conductances c_e = 1/ℓ_e.

    Time complexity: O(|V|³) (dominated by pseudoinverse)
    Space complexity: O(|V|²)

    Args:
        G: A connected metric graph.

    Returns:
        R: The |V| × |V| effective resistance matrix.
    """
    L = weighted_laplacian(G)
    n = G.n_vertices

    # Moore-Penrose pseudoinverse
    L_pinv = np.linalg.pinv(L)

    # Effective resistance: R[i,j] = L^+[i,i] + L^+[j,j] - 2*L^+[i,j]
    R = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            R[i, j] = L_pinv[i, i] + L_pinv[j, j] - 2 * L_pinv[i, j]

    return R


def canonical_kernel_generators(
    G: MetricGraph, S: List[int], base_vertex: Optional[int] = None
) -> np.ndarray:
    """Compute canonical kernel generators for the metric graph.

    Given a vertex subset S (containing all branch points), compute the
    columns of the reduced resistance matrix that generate the canonical
    kernel lattice.

    The canonical kernel lattice Λ_S is generated by the columns of the
    matrix R_S restricted to S (with one vertex removed for normalization).

    Time complexity: O(|V|³)
    Space complexity: O(|V|²)

    Args:
        G: A connected metric graph.
        S: Subset of vertices (indices).
        base_vertex: Vertex to remove for normalization (default: S[0]).

    Returns:
        generators: (|S|-1) × (|S|-1) matrix whose columns generate Λ_S.
    """
    if base_vertex is None:
        base_vertex = S[0]

    R = effective_resistance_matrix(G)

    # Restrict to S, remove base_vertex
    S_reduced = [v for v in S if v != base_vertex]
    k = len(S_reduced)

    if k == 0:
        return np.array([[]])

    # The generator matrix: normalized resistance columns
    # G[i,j] = R[S_reduced[i], S_reduced[j]] - R[S_reduced[i], base_vertex]
    #         - R[base_vertex, S_reduced[j]] + R[base_vertex, base_vertex]
    # This is the "centered" resistance matrix.
    gen = np.zeros((k, k))
    for i in range(k):
        for j in range(k):
            vi, vj = S_reduced[i], S_reduced[j]
            gen[i, j] = (R[vi, vj] - R[vi, base_vertex]
                         - R[base_vertex, vj] + R[base_vertex, base_vertex])

    return gen


def smith_normal_form_diagonal(M: np.ndarray, tol: float = 1e-8) -> List[float]:
    """Compute the Smith normal form diagonal of a real matrix.

    Uses SVD as a numerical approximation. For exact integer matrices,
    this gives the invariant factors.

    Time complexity: O(n³) for SVD

    Args:
        M: Square matrix.
        tol: Tolerance for zero detection.

    Returns:
        Sorted list of non-zero singular values.
    """
    U, s, Vt = np.linalg.svd(M)
    return sorted([x for x in s if abs(x) > tol])


def tropical_jacobian_invariant_factors(
    G: MetricGraph, S: List[int]
) -> List[float]:
    """Compute the invariant factors of the S-supported tropical Jacobian.

    The tropical Jacobian J_S(Γ) ≅ ℝ^(|S|-1) / Λ_S, and the invariant
    factors are the diagonal entries of the Smith normal form of the
    generator matrix of Λ_S.

    For genus-1 graphs (cycles), this gives a single factor equal to the
    total perimeter.

    Time complexity: O(|V|³)

    Args:
        G: A connected metric graph.
        S: Subset of vertices.

    Returns:
        List of invariant factors (positive reals).
    """
    gens = canonical_kernel_generators(G, S)
    if gens.size == 0:
        return []
    return smith_normal_form_diagonal(gens)


def subdivide_graph(G: MetricGraph, n: int) -> MetricGraph:
    """Subdivide each edge of a metric graph into n equal segments.

    Each edge of length ℓ is replaced by n edges of length ℓ/n,
    connected by n-1 new intermediate vertices.

    The subdivision preserves the metric structure and the tropical
    Jacobian (up to isomorphism).

    Time complexity: O(n · |E|)

    Args:
        G: A metric graph.
        n: Number of subdivisions per edge.

    Returns:
        G_n: The n-fold subdivision of G.
    """
    if n <= 1:
        return G

    new_n = G.n_vertices
    new_edges = []
    new_lengths = []

    next_vertex = G.n_vertices

    for (i, j), length in zip(G.edges, G.lengths):
        sub_length = length / n
        prev = i
        for k in range(n - 1):
            new_vertex = next_vertex
            next_vertex += 1
            new_edges.append((prev, new_vertex))
            new_lengths.append(sub_length)
            prev = new_vertex
        new_edges.append((prev, j))
        new_lengths.append(sub_length)

    return MetricGraph(next_vertex, new_edges, new_lengths)


def metric_canonical_kernel(
    G: MetricGraph,
    S: List[int],
    subdivision_level: int = 1,
) -> Tuple[np.ndarray, List[float]]:
    """Compute the canonical kernel generators with optional subdivision.

    This is the main algorithm combining subdivision refinement with
    canonical kernel extraction.

    Args:
        G: A connected metric graph.
        S: Subset of vertices (must include all branch points).
        subdivision_level: Number of subdivisions (1 = no subdivision).

    Returns:
        Tuple of (generator_matrix, invariant_factors).
    """
    G_sub = subdivide_graph(G, subdivision_level)
    gens = canonical_kernel_generators(G_sub, S)
    factors = smith_normal_form_diagonal(gens) if gens.size > 0 else []
    return gens, factors


def verify_laplacian_properties(G: MetricGraph) -> dict:
    """Verify the fundamental properties of the weighted Laplacian.

    Checks:
    1. Row-sum-zero
    2. Symmetry
    3. Positive semi-definiteness
    4. Nullity = number of connected components (should be 1)

    Args:
        G: A metric graph.

    Returns:
        Dictionary of property verification results.
    """
    L = weighted_laplacian(G)
    eigenvalues = np.linalg.eigvalsh(L)

    results = {
        "row_sum_zero": np.allclose(L.sum(axis=1), 0, atol=1e-12),
        "symmetric": np.allclose(L, L.T, atol=1e-12),
        "psd": all(e >= -1e-10 for e in eigenvalues),
        "eigenvalues": sorted(eigenvalues),
        "nullity": sum(1 for e in eigenvalues if abs(e) < 1e-10),
        "min_nonzero_eigenvalue": min(e for e in eigenvalues if e > 1e-10)
            if any(e > 1e-10 for e in eigenvalues) else None,
    }

    return results


