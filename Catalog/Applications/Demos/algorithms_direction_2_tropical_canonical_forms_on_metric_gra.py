    # Cycle graph C_3 with unit lengths
    G = MetricGraph(3, [(0, 1), (1, 2), (2, 0)], [1.0, 1.0, 1.0])

    print("Cycle graph C_3 with unit edge lengths:")
    print(f"  Genus: {G.genus}")

    L = weighted_laplacian(G)
    print(f"  Weighted Laplacian:\n{L}")

    props = verify_laplacian_properties(G)
    for k, v in props.items():
        print(f"  {k}: {v}")

    R = effective_resistance_matrix(G)
    print(f"  Effective resistance matrix:\n{R}")

    factors = tropical_jacobian_invariant_factors(G, [0, 1, 2])
    print(f"  Jacobian invariant factors: {factors}")
    print(f"  Perimeter: {sum(G.lengths)}")
