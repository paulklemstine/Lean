"""
Algorithms for k-Automatic Sequences

Type-hinted implementations of the core algorithms from our formalization:
1. DFAO evaluation
2. k-Kernel computation
3. Zero-in-sequence decidability
4. Kernel orbit graph construction
"""

from dataclasses import dataclass
from typing import Any, Callable


def to_digits_lsf(n: int, k: int) -> list[int]:
    """Base-k LSF digit representation."""
    if n == 0:
        return []
    digits = []
    while n > 0:
        digits.append(n % k)
        n //= k
    return digits


@dataclass
class DFAO:
    """Deterministic Finite Automaton with Output."""
    num_states: int
    k: int
    delta: Callable[[int, int], int]  # (state, digit) -> state
    q0: int
    tau: Callable[[int], Any]  # state -> output

    def state_at(self, n: int) -> int:
        """State reached after reading n in base k (LSF)."""
        q = self.q0
        for d in to_digits_lsf(n, self.k):
            q = self.delta(q, d)
        return q

    def gen_seq(self, n: int) -> Any:
        """Generate the n-th term of the automatic sequence."""
        return self.tau(self.state_at(n))

    def gen_seq_from(self, q: int, n: int) -> Any:
        """Generate from starting state q."""
        state = q
        for d in to_digits_lsf(n, self.k):
            state = self.delta(state, d)
        return self.tau(state)


def reachable_states(dfao: DFAO) -> set[int]:
    """BFS to find all reachable states."""
    visited = {dfao.q0}
    queue = [dfao.q0]
    while queue:
        q = queue.pop(0)
        for d in range(dfao.k):
            nq = dfao.delta(q, d)
            if nq not in visited:
                visited.add(nq)
                queue.append(nq)
    return visited


def decide_value_exists(dfao: DFAO, target: Any) -> tuple[bool, int | None]:
    """Decide if target appears in the sequence generated by dfao.

    Algorithm: Compute reachable states, check if any has tau(q) = target.
    If yes, find a minimal witness by BFS over the digit tree.

    Time: O(|Q| * k)
    Space: O(|Q|)
    """
    reachable = reachable_states(dfao)
    target_states = {q for q in reachable if dfao.tau(q) == target}
    if not target_states:
        return False, None

    # BFS to find minimal n with gen_seq(n) = target
    from collections import deque
    # Each node: (state, digit_list_LSF)
    queue: deque[tuple[int, list[int]]] = deque([(dfao.q0, [])])
    visited_states: set[int] = {dfao.q0}

    # Check n = 0
    if dfao.tau(dfao.q0) == target:
        return True, 0

    while queue:
        state, digits = queue.popleft()
        for d in range(dfao.k):
            new_state = dfao.delta(state, d)
            new_digits = digits + [d]
            n = sum(dig * dfao.k**i for i, dig in enumerate(new_digits))
            if dfao.tau(new_state) == target:
                return True, n
            if new_state not in visited_states:
                visited_states.add(new_state)
                queue.append((new_state, new_digits))

    return False, None  # Should not reach here if reachability analysis was correct


def compute_k_kernel(
    seq: Callable[[int], Any], k: int, max_e: int = 5, num_terms: int = 20
) -> dict[tuple, tuple[int, int]]:
    """Compute the k-kernel of a sequence.

    Returns dict mapping value-tuples to (e, r) pairs.
    The kernel has at most |Q|² elements for a DFAO-generated sequence.
    """
    kernel: dict[tuple, tuple[int, int]] = {}
    for e in range(max_e + 1):
        for r in range(k**e):
            values = tuple(seq(k**e * n + r) for n in range(num_terms))
            if values not in kernel:
                kernel[values] = (e, r)
    return kernel


@dataclass
class KernelOrbit:
    """The kernel orbit graph: vertices = kernel elements, edges = digit transitions."""
    vertices: list[tuple]  # Each is a tuple of (first num_terms values)
    transitions: dict[tuple[int, int], int]  # (vertex_idx, digit) -> vertex_idx
    outputs: list[Any]  # output[i] = vertex i evaluated at 0
    root: int  # Index of the original sequence


def build_kernel_orbit(
    seq: Callable[[int], Any], k: int, max_e: int = 5, num_terms: int = 20
) -> KernelOrbit:
    """Build the kernel orbit graph of a sequence.

    This is the novel KernelOrbit structure from our formalization.
    """
    kernel = compute_k_kernel(seq, k, max_e, num_terms)
    vertices = list(kernel.keys())
    vertex_idx = {v: i for i, v in enumerate(vertices)}

    transitions = {}
    for i, v in enumerate(vertices):
        e, r = kernel[v]
        for d in range(k):
            # kernel_step: n -> seq(k*n + d) applied to the subsequence at (e, r)
            step_values = tuple(
                seq(k**e * (k * n + d) + r) for n in range(num_terms)
            )
            # This should equal kernelSubseq with (e+1, k^e * d + r)
            if step_values in vertex_idx:
                transitions[(i, d)] = vertex_idx[step_values]

    outputs = [v[0] for v in vertices]  # value at n=0
    root_values = tuple(seq(n) for n in range(num_terms))
    root = vertex_idx.get(root_values, 0)

    return KernelOrbit(vertices, transitions, outputs, root)


# Example: Thue-Morse DFAO
def thue_morse_dfao() -> DFAO:
    """2-state DFAO for the Thue-Morse sequence."""
    return DFAO(
        num_states=2,
        k=2,
        delta=lambda q, d: q ^ d,  # XOR
        q0=0,
        tau=lambda q: q,
    )


