    Y = GroupAction(n, frozenset(range(3)),
                    {g: {y: (y + g) % 3 for y in range(3)} for g in range(6)})

    spectrum = compute_impossibility_spectrum(X, Y, subgroups)
    print(f"\nImpossibility spectrum for Z/6Z: {sorted(X.elements)} → {sorted(Y.elements)}")
    for H in subgroups:
        status = "IMPOSSIBLE" if frozenset(H) in spectrum.carrier else "POSSIBLE"
        print(f"  {str(sorted(H)):20s} : {status}")

    # Test spectral completeness for small groups
    test_spectral_completeness(4)
