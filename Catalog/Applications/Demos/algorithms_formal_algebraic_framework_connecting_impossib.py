#!/usr/bin/env python3
"""
Algorithms for Equivariant Impossibility Spectra

Type-hinted implementations of the core algorithms from the research paper.
"""

from itertools import product
from typing import Dict, FrozenSet, List, Optional, Set, Tuple
from dataclasses import dataclass


@dataclass(frozen=True)
class GroupAction:
    """A finite group action on a finite set.

    Attributes:
        group_order: Order of the group (elements are 0..group_order-1)
        elements: The set being acted upon
        action: action[g][x] = g·x
    """
    group_order: int
    elements: FrozenSet[int]
    action: Dict[int, Dict[int, int]]

    def fixed_points(self, subgroup: FrozenSet[int]) -> FrozenSet[int]:
        """Compute the set of fixed points under a subgroup."""
        return frozenset(
            x for x in self.elements
            if all(self.action[h][x] == x for h in subgroup)
        )

    def orbit(self, x: int) -> FrozenSet[int]:
        """Compute the orbit of x under the full group action."""
        return frozenset(self.action[g][x] for g in range(self.group_order))

    def orbits(self) -> List[FrozenSet[int]]:
        """Compute all orbits."""
        visited: Set[int] = set()
        result: List[FrozenSet[int]] = []
        for x in sorted(self.elements):
            if x not in visited:
                orb = self.orbit(x)
                result.append(orb)
                visited.update(orb)
        return result


@dataclass
class ObstructionFilter:
    """An obstruction filter on a group.

    Attributes:
        group_order: Order of the group
        carrier: Set of subgroups (as frozensets) in the filter
    """
    group_order: int
    carrier: Set[FrozenSet[int]]

    def is_valid(self, all_subgroups: List[FrozenSet[int]]) -> bool:
        """Check upward closure and bot ∉ carrier."""
        trivial = frozenset({0})
        if trivial in self.carrier:
            return False
        for H in self.carrier:
            for K in all_subgroups:
                if H.issubset(K) and K not in self.carrier:
                    return False
        return True


def subgroups_of_cyclic(n: int) -> List[FrozenSet[int]]:
    """Enumerate all subgroups of Z/nZ.

    Each subgroup of Z/nZ has order d dividing n, generated by n/d.

    Returns:
        List of subgroups as frozensets of group elements.
    """
    result: List[FrozenSet[int]] = []
    for d in range(1, n + 1):
        if n % d == 0:
            step = n // d
            result.append(frozenset((k * step) % n for k in range(d)))
    return result


def is_equivariant(
    f: Dict[int, int],
    action_X: GroupAction,
    action_Y: GroupAction,
    subgroup: FrozenSet[int]
) -> bool:
    """Check if f : X → Y is H-equivariant.

    Algorithm:
        For each h ∈ H and x ∈ X, verify f(h·x) = h·f(x).

    Complexity: O(|H| · |X|)
    """
    return all(
        f[action_X.action[h][x]] == action_Y.action[h][f[x]]
        for h in subgroup
        for x in action_X.elements
    )


def fixed_point_obstruction(
    action_X: GroupAction,
    action_Y: GroupAction,
    subgroup: FrozenSet[int]
) -> bool:
    """Check if the fixed-point obstruction applies.

    Algorithm:
        Compute X^H and Y^H. If X^H ≠ ∅ and Y^H = ∅, return True.

    Complexity: O(|H| · (|X| + |Y|))

    Returns:
        True if the fixed-point obstruction proves impossibility.
    """
    fp_X = action_X.fixed_points(subgroup)
    fp_Y = action_Y.fixed_points(subgroup)
    return len(fp_X) > 0 and len(fp_Y) == 0


def compute_impossibility_spectrum(
    action_X: GroupAction,
    action_Y: GroupAction,
    subgroups: List[FrozenSet[int]]
) -> ObstructionFilter:
    """Compute the impossibility spectrum of (X, Y).

    Algorithm:
        1. For each subgroup H (bottom-up in the lattice):
           a. Check fixed-point obstruction (fast).
           b. If not obstructed, try to construct an H-equivariant map (brute force).
           c. Use upward closure to propagate impossibilities.

    Pseudocode:
        spectrum ← ∅
        for H in subgroups sorted by order:
            if any K ⊆ H with K ∈ spectrum:
                spectrum ← spectrum ∪ {H}  // upward closure
            elif fixed_point_obstruction(X, Y, H):
                spectrum ← spectrum ∪ {H}
            elif not exists_equivariant_map(X, Y, H):
                spectrum ← spectrum ∪ {H}

    Complexity: O(|Sub(G)|² + |Sub(G)| · |Y|^|X| · |H| · |X|) worst case.
    """
    spectrum: Set[FrozenSet[int]] = set()

    # Sort subgroups by order (bottom-up)
    sorted_subs = sorted(subgroups, key=len)

    for H in sorted_subs:
        # Check upward closure
        if any(K.issubset(H) and K in spectrum for K in spectrum):
            spectrum.add(H)
            continue

        # Check fixed-point obstruction (fast)
        if fixed_point_obstruction(action_X, action_Y, H):
            spectrum.add(H)
            continue

        # Brute force: try all maps
        X_list = sorted(action_X.elements)
        Y_list = sorted(action_Y.elements)
        found = False
        for assignment in product(Y_list, repeat=len(X_list)):
            f = dict(zip(X_list, assignment))
            if is_equivariant(f, action_X, action_Y, H):
                found = True
                break

        if not found:
            spectrum.add(H)

    return ObstructionFilter(
        group_order=action_X.group_order,
        carrier=spectrum
    )


def enumerate_upper_sets(
    subgroups: List[FrozenSet[int]]
) -> List[Set[FrozenSet[int]]]:
    """Enumerate all upper sets in the subgroup lattice not containing ⊥.

    Used for testing the Spectral Completeness Conjecture.

    Algorithm:
        Generate all subsets of subgroups (excluding the trivial subgroup),
        then filter to those that are upward closed.
    """
    trivial = min(subgroups, key=len)  # ⊥ = smallest subgroup
    non_trivial = [H for H in subgroups if H != trivial]

    upper_sets: List[Set[FrozenSet[int]]] = []

    for size in range(len(non_trivial) + 1):
        for combo in _combinations(non_trivial, size):
            candidate = set(combo)
            # Check upward closure
            is_upper = True
            for H in candidate:
                for K in subgroups:
                    if H.issubset(K) and K not in candidate:
                        is_upper = False
                        break
                if not is_upper:
                    break
            if is_upper:
                upper_sets.append(candidate)

    return upper_sets


def _combinations(lst: list, k: int) -> list:
    """Generate all k-element combinations of lst."""
    if k == 0:
        return [()]
    if not lst:
        return []
    first, rest = lst[0], lst[1:]
    with_first = [(first,) + c for c in _combinations(rest, k - 1)]
    without_first = _combinations(rest, k)
    return with_first + without_first


def test_spectral_completeness(n: int) -> None:
    """Test the Spectral Completeness Conjecture for Z/nZ.

    For each upper set S in Sub(Z/nZ) with ⊥ ∉ S,
    search for finite Z/nZ-sets X, Y with ImpSpec(X, Y) = S.
    """
    subgroups = subgroups_of_cyclic(n)
    upper_sets = enumerate_upper_sets(subgroups)

    print(f"\nSpectral Completeness Test for Z/{n}Z")
    print(f"Number of subgroups: {len(subgroups)}")
    print(f"Number of upper sets (excl. ⊥): {len(upper_sets)}")

    for us in upper_sets:
        us_str = "{" + ", ".join(str(sorted(H)) for H in us) + "}"
        print(f"\n  Target spectrum: {us_str}")
        # Try various X, Y sizes
        realized = False
        for x_size in range(1, 2 * n + 1):
            for y_size in range(1, 2 * n + 1):
                X_elems = frozenset(range(x_size))
                Y_elems = frozenset(range(y_size))
                action_X_dict = {g: {x: (x + g) % x_size for x in range(x_size)}
                                 for g in range(n)}
                action_Y_dict = {g: {y: (y + g) % y_size for y in range(y_size)}
                                 for g in range(n)}
                action_X = GroupAction(n, X_elems, action_X_dict)
                action_Y = GroupAction(n, Y_elems, action_Y_dict)
                spectrum = compute_impossibility_spectrum(action_X, action_Y, subgroups)
                if spectrum.carrier == us:
                    print(f"    Realized: |X|={x_size}, |Y|={y_size}")
                    realized = True
                    break
            if realized:
                break
        if not realized:
            print(f"    NOT realized with cyclic actions up to size {2*n}")


