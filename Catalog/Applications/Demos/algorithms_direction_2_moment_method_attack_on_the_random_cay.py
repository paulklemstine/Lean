#!/usr/bin/env python3
"""
algorithms.py — Core algorithms for the moment method on Cayley graphs.

Implements:
1. Word evaluation in permutation groups
2. Closed-word counting (exact and sampling-based)
3. Backtrack-free word enumeration
4. Moment kernel computation
5. Adjacency matrix construction and trace computation

Complexity analysis:
- Exact closed-word count: O(4^m * m * n) time, O(n) space
- Backtrack-free count: O(1) via formula 4 * 3^(m-1)
- Adjacency matrix: O(n!^2 * 4) space, O(n!^2 * 4) time
- Matrix trace via power: O(n!^3 * m) time (impractical for large n)
"""

import itertools
import random
from math import factorial, comb
from typing import List, Tuple, Optional, Dict


# ──────────────────────────────────────────────
# Permutation arithmetic
# ──────────────────────────────────────────────

def compose_perm(p: List[int], q: List[int]) -> List[int]:
    """Compose permutations: (p ∘ q)(i) = p[q[i]].
    Time: O(n), Space: O(n)."""
    return [p[q[i]] for i in range(len(p))]


def inverse_perm(p: List[int]) -> List[int]:
    """Inverse permutation.
    Time: O(n), Space: O(n)."""
    n = len(p)
    inv = [0] * n
    for i in range(n):
        inv[p[i]] = i
    return inv


def identity_perm(n: int) -> List[int]:
    """Identity permutation of {0,...,n-1}."""
    return list(range(n))


def is_identity_perm(p: List[int]) -> bool:
    """Check if permutation is the identity.
    Time: O(n)."""
    return all(p[i] == i for i in range(len(p)))


def random_perm(n: int) -> List[int]:
    """Uniformly random permutation via Fisher-Yates shuffle.
    Time: O(n)."""
    p = list(range(n))
    random.shuffle(p)
    return p


def generates_sn(sigma: List[int], tau: List[int], n: int) -> bool:
    """Check if σ, τ generate S_n by BFS on the Cayley graph.
    Time: O(n! * n), Space: O(n! * n).
    Returns True iff the group generated by {σ,τ} is all of S_n."""
    if n <= 1:
        return True
    target = factorial(n)
    gens = [sigma, tau, inverse_perm(sigma), inverse_perm(tau)]
    reached = {tuple(identity_perm(n))}
    frontier = [identity_perm(n)]
    while frontier:
        next_frontier = []
        for g in frontier:
            for s in gens:
                h = compose_perm(s, g)
                th = tuple(h)
                if th not in reached:
                    reached.add(th)
                    next_frontier.append(h)
                    if len(reached) == target:
                        return True
        frontier = next_frontier
    return len(reached) == target


# ──────────────────────────────────────────────
# Word evaluation
# ──────────────────────────────────────────────

# Alphabet: 0=σ, 1=σ⁻¹, 2=τ, 3=τ⁻¹
ALPHABET = [0, 1, 2, 3]
FORMAL_INV = {0: 1, 1: 0, 2: 3, 3: 2}


def eval_word(word: Tuple[int, ...], sigma: List[int], tau: List[int],
              n: int) -> List[int]:
    """Evaluate a word in the generators {σ, σ⁻¹, τ, τ⁻¹}.
    Time: O(m * n) where m = len(word)."""
    sigma_inv = inverse_perm(sigma)
    tau_inv = inverse_perm(tau)
    gen_map = {0: sigma, 1: sigma_inv, 2: tau, 3: tau_inv}
    result = identity_perm(n)
    for letter in word:
        result = compose_perm(gen_map[letter], result)
    return result


# ──────────────────────────────────────────────
# Closed-word counting
# ──────────────────────────────────────────────

def closed_word_count_exact(sigma: List[int], tau: List[int],
                            n: int, m: int) -> int:
    """Exact count of length-m words evaluating to identity.
    Time: O(4^m * m * n), Space: O(n).

    This is the brute-force algorithm: enumerate all 4^m words
    and check each one. Practical for m ≤ 8 and small n."""
    count = 0
    for word in itertools.product(ALPHABET, repeat=m):
        if is_identity_perm(eval_word(word, sigma, tau, n)):
            count += 1
    return count


def closed_word_count_sampling(sigma: List[int], tau: List[int],
                               n: int, m: int,
                               num_samples: int = 10000) -> float:
    """Estimate closed-word count via random sampling.
    Time: O(num_samples * m * n), Space: O(n).

    Returns estimated count (not normalized). For large m where
    exact enumeration is infeasible."""
    if m == 0:
        return 1.0
    hits = 0
    for _ in range(num_samples):
        word = tuple(random.choice(ALPHABET) for _ in range(m))
        if is_identity_perm(eval_word(word, sigma, tau, n)):
            hits += 1
    return hits * (4 ** m) / num_samples


# ──────────────────────────────────────────────
# Moment kernel
# ──────────────────────────────────────────────

def moment_kernel_exact(sigma: List[int], tau: List[int],
                        n: int, m: int) -> float:
    """Exact moment kernel: closedWordCount / 4^m.
    This is the return probability of the random walk at time m."""
    return closed_word_count_exact(sigma, tau, n, m) / (4 ** m)


def moment_kernel_sampling(sigma: List[int], tau: List[int],
                           n: int, m: int,
                           num_samples: int = 10000) -> float:
    """Estimated moment kernel via sampling."""
    if m == 0:
        return 1.0
    hits = 0
    for _ in range(num_samples):
        word = tuple(random.choice(ALPHABET) for _ in range(m))
        if is_identity_perm(eval_word(word, sigma, tau, n)):
            hits += 1
    return hits / num_samples


# ──────────────────────────────────────────────
# Backtrack-free words
# ──────────────────────────────────────────────

def is_backtrack_free(word: Tuple[int, ...]) -> bool:
    """Check if a word has no immediate backtracking.
    Time: O(m)."""
    for i in range(len(word) - 1):
        if word[i + 1] == FORMAL_INV[word[i]]:
            return False
    return True


def count_backtrack_free_exact(m: int) -> int:
    """Exact count of backtrack-free words of length m.
    Formula: 4 * 3^(m-1) for m ≥ 1, and 1 for m = 0.
    Time: O(1)."""
    if m == 0:
        return 1
    return 4 * (3 ** (m - 1))


def count_backtrack_free_brute(m: int) -> int:
    """Brute-force count for verification.
    Time: O(4^m * m)."""
    return sum(1 for w in itertools.product(ALPHABET, repeat=m)
               if is_backtrack_free(w))


# ──────────────────────────────────────────────
# Decomposition: tree-like vs relation-driven
# ──────────────────────────────────────────────

def decompose_closed_words(sigma: List[int], tau: List[int],
                           n: int, m: int) -> Dict[str, int]:
    """Decompose closed words into backtrack-free and non-backtrack-free.
    Returns counts of each type.

    - tree_like: closed words that are not backtrack-free
      (these arise from immediate cancellations)
    - relation_driven: closed words that are backtrack-free
      (these arise from genuine group relations)
    """
    bf_closed = 0
    non_bf_closed = 0
    total_closed = 0
    for word in itertools.product(ALPHABET, repeat=m):
        if is_identity_perm(eval_word(word, sigma, tau, n)):
            total_closed += 1
            if is_backtrack_free(word):
                bf_closed += 1
            else:
                non_bf_closed += 1
    return {
        "total_closed": total_closed,
        "backtrack_free_closed": bf_closed,
        "non_backtrack_free_closed": non_bf_closed,
        "total_backtrack_free": count_backtrack_free_exact(m),
        "relation_density": bf_closed / max(1, count_backtrack_free_exact(m))
    }


# ──────────────────────────────────────────────
# Adjacency matrix (for small groups)
# ──────────────────────────────────────────────

def build_cayley_adj_matrix(sigma: List[int], tau: List[int],
                            n: int) -> List[List[int]]:
    """Build the adjacency matrix of Cay(S_n, {σ,σ⁻¹,τ,τ⁻¹}).
    Time: O(|G|^2 * 4), Space: O(|G|^2) where |G| = n!.

    Only practical for n ≤ 5."""
    from itertools import permutations
    perms = [list(p) for p in permutations(range(n))]
    perm_to_idx = {tuple(p): i for i, p in enumerate(perms)}
    N = len(perms)

    gens = [sigma, inverse_perm(sigma), tau, inverse_perm(tau)]
    A = [[0] * N for _ in range(N)]

    for i, g in enumerate(perms):
        for s in gens:
            h = compose_perm(s, g)
            j = perm_to_idx[tuple(h)]
            A[j][i] += 1

    return A


def matrix_trace_power(A: List[List[int]], m: int) -> int:
    """Compute tr(A^m) by matrix multiplication.
    Time: O(N^3 * m), Space: O(N^2)."""
    N = len(A)
    # Start with identity
    result = [[1 if i == j else 0 for j in range(N)] for i in range(N)]
    for _ in range(m):
        new = [[0] * N for _ in range(N)]
        for i in range(N):
            for j in range(N):
                for k in range(N):
                    new[i][j] += result[i][k] * A[k][j]
        result = new
    return sum(result[i][i] for i in range(N))


