def build_weighted_laplacian(M):
    n = M.n_vertices
    L = np.zeros((n, n))
    for i, j, length in M.edges:
        c = 1.0 / length
        L[i, j] = -c
        L[j, i] = -c
        L[i, i] += c
        L[j, j] += c
