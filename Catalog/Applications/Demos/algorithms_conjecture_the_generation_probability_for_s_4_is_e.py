#!/usr/bin/env python3
"""
Algorithms for Symmetric Group Generation Probability

This module implements algorithms for computing and bounding the probability
that random permutations generate the symmetric group, following the
subgroup-obstruction framework.

Algorithms:
1. Exact generation probability via exhaustive enumeration
2. Intransitive obstruction bound computation
3. Point-stabilizer dominance analysis
4. Asymptotic generation probability estimation
"""

from itertools import permutations
from fractions import Fraction
from math import factorial, comb
from typing import List, Tuple, Set, Optional


# ──────────────────────────────────────────────────────────────
# Algorithm 1: Subgroup closure computation
# ──────────────────────────────────────────────────────────────

def closure_bfs(generators: List[Tuple[int, ...]], n: int) -> Set[Tuple[int, ...]]:
    """
    Compute the subgroup generated by a list of permutations using BFS.

    Algorithm:
        1. Initialize queue with identity and generators
        2. For each element g in queue, multiply by all known elements
        3. Add new products to queue
        4. Repeat until no new elements found

    Time complexity: O(|H|² · n) where H is the generated subgroup
    Space complexity: O(|H| · n)

    Args:
        generators: List of permutations as tuples
        n: Degree of the symmetric group

    Returns:
        Set of all permutations in the generated subgroup
    """
    identity = tuple(range(n))
    seen: Set[Tuple[int, ...]] = {identity}
    queue: List[Tuple[int, ...]] = [identity]

    # Add generators and their inverses
    for g in generators:
        inv_g = tuple(0 for _ in range(n))
        inv_list = list(inv_g)
        for i, v in enumerate(g):
            inv_list[v] = i
        inv_g = tuple(inv_list)

        for elem in [g, inv_g]:
            if elem not in seen:
                seen.add(elem)
                queue.append(elem)

    # BFS closure
    idx = 0
    while idx < len(queue):
        g = queue[idx]
        current_size = len(queue)
        for j in range(current_size):
            h = queue[j]
            prod = tuple(g[h[i]] for i in range(n))
            if prod not in seen:
                seen.add(prod)
                queue.append(prod)
                if len(seen) == factorial(n):
                    return seen  # Early termination
        idx += 1

    return seen


def generates_symmetric_group(sigma: Tuple[int, ...], tau: Tuple[int, ...],
                               n: int) -> bool:
    """
    Check whether two permutations generate the full symmetric group S_n.

    Args:
        sigma, tau: Permutations as tuples
        n: Degree

    Returns:
        True if ⟨σ, τ⟩ = S_n
    """
    subgroup = closure_bfs([sigma, tau], n)
    return len(subgroup) == factorial(n)


# ──────────────────────────────────────────────────────────────
# Algorithm 2: Exact generation probability
# ──────────────────────────────────────────────────────────────

def exact_generation_probability(n: int) -> Tuple[int, int, Fraction]:
    """
    Compute the exact generation probability for S_n.

    Pseudocode:
        count ← 0
        for each σ ∈ S_n:
            for each τ ∈ S_n:
                if ⟨σ, τ⟩ = S_n:
                    count ← count + 1
        return count / (n!)²

    Time complexity: O((n!)² · n! · n) — cubic in group order
    Space complexity: O(n! · n)

    Args:
        n: Degree of symmetric group

    Returns:
        (count, total, probability) where probability = count/total
    """
    all_perms = list(permutations(range(n)))
    target = factorial(n)
    count = 0

    for sigma in all_perms:
        for tau in all_perms:
            if generates_symmetric_group(sigma, tau, n):
                count += 1

    total = target ** 2
    return count, total, Fraction(count, total)


# ──────────────────────────────────────────────────────────────
# Algorithm 3: Intransitive obstruction bound
# ──────────────────────────────────────────────────────────────

def intransitive_obstruction_term(n: int, k: int) -> Fraction:
    """
    Compute the obstruction term for k-subset stabilizers.

    The probability that two random permutations both preserve
    a common k-element subset, summed over all C(n,k) such subsets:

        C(n,k) · (k!(n-k)!/n!)² = 1/C(n,k)

    This remarkable simplification is the heart of the obstruction calculus.

    Args:
        n: Degree of symmetric group
        k: Size of preserved subset (1 ≤ k ≤ n-1)

    Returns:
        The obstruction term as an exact fraction
    """
    assert 1 <= k <= n - 1, f"Need 1 ≤ k ≤ n-1, got k={k}, n={n}"
    return Fraction(1, comb(n, k))


def intransitive_obstruction_sum(n: int) -> Fraction:
    """
    Compute the total intransitive obstruction bound.

    Σ_{k=1}^{⌊n/2⌋} 1/C(n,k)

    By symmetry C(n,k) = C(n,n-k), we only sum up to n/2
    (each intransitive partition {k, n-k} is counted once).

    Args:
        n: Degree of symmetric group

    Returns:
        Upper bound on non-generation probability from intransitive subgroups
    """
    return sum(Fraction(1, comb(n, k)) for k in range(1, n // 2 + 1))


def intransitive_tail_sum(n: int) -> Fraction:
    """
    Compute the tail of the obstruction sum from k=2.

    Σ_{k=2}^{⌊n/2⌋} 1/C(n,k)

    This is the portion NOT contributed by point stabilizers.

    Args:
        n: Degree

    Returns:
        Tail contribution as exact fraction
    """
    return sum(Fraction(1, comb(n, k)) for k in range(2, n // 2 + 1))


# ──────────────────────────────────────────────────────────────
# Algorithm 4: Point-stabilizer dominance analysis
# ──────────────────────────────────────────────────────────────

def point_stabilizer_dominance_ratio(n: int) -> float:
    """
    Compute the ratio (1/n) / Σ_{k=1}^{⌊n/2⌋} 1/C(n,k).

    This ratio tends to 1 as n → ∞, showing that point stabilizers
    dominate the intransitive obstruction.

    Args:
        n: Degree (n ≥ 2)

    Returns:
        The dominance ratio as a float
    """
    k1_term = Fraction(1, n)
    total = intransitive_obstruction_sum(n)
    if total == 0:
        return float('inf')
    return float(k1_term / total)


# ──────────────────────────────────────────────────────────────
# Algorithm 5: Asymptotic generation probability estimator
# ──────────────────────────────────────────────────────────────

def dixon_asymptotic_estimate(n: int) -> Fraction:
    """
    Estimate the generation probability using the obstruction bound.

    Lower bound: 1 - Σ_{k=1}^{⌊n/2⌋} 1/C(n,k)

    This is a certified lower bound on the probability that two
    random permutations generate S_n (or A_n, which by itself is
    also a generating pair for these purposes).

    For large n, this approaches 1 - 1/n.

    Args:
        n: Degree

    Returns:
        Lower bound on generation probability
    """
    return 1 - intransitive_obstruction_sum(n)


def verify_four_over_n_bound(n_max: int = 100) -> List[Tuple[int, bool, Fraction, Fraction]]:
    """
    Verify the bound Σ 1/C(n,k) ≤ 4/n for 5 ≤ n ≤ n_max.

    Returns:
        List of (n, satisfies_bound, sum, bound) tuples
    """
    results = []
    for n in range(5, n_max + 1):
        s = intransitive_obstruction_sum(n)
        bound = Fraction(4, n)
        results.append((n, s <= bound, s, bound))
    return results


# ──────────────────────────────────────────────────────────────
# Algorithm 6: Subgroup structure analysis
# ──────────────────────────────────────────────────────────────

def classify_non_generating_pair(sigma: Tuple[int, ...], tau: Tuple[int, ...],
                                  n: int) -> str:
    """
    Classify why a pair fails to generate S_n.

    Categories:
    - "generates": pair generates S_n
    - "identity": at least one is identity
    - "common_fixed_point": both fix a common point
    - "intransitive": generated group acts intransitively
    - "imprimitive": generated group preserves a block system
    - "alternating": generated group is A_n
    - "other": other proper subgroup

    Args:
        sigma, tau: Permutations as tuples
        n: Degree

    Returns:
        Classification string
    """
    subgroup = closure_bfs([sigma, tau], n)
    size = len(subgroup)

    if size == factorial(n):
        return "generates"

    # Check for common fixed point
    for i in range(n):
        if sigma[i] == i and tau[i] == i:
            return "common_fixed_point"

    # Check transitivity: compute orbit of 0
    orbit = {0}
    queue = [0]
    while queue:
        pt = queue.pop()
        for perm in subgroup:
            img = perm[pt]
            if img not in orbit:
                orbit.add(img)
                queue.append(img)
    if len(orbit) < n:
        return "intransitive"

    # Check if it's A_n
    if size == factorial(n) // 2:
        return "alternating"

    return "other"


def obstruction_census(n: int) -> dict:
    """
    Classify all non-generating pairs in S_n × S_n.

    Args:
        n: Degree

    Returns:
        Dictionary mapping classification to count
    """
    census: dict = {}
    all_perms = list(permutations(range(n)))

    for sigma in all_perms:
        for tau in all_perms:
            cat = classify_non_generating_pair(sigma, tau, n)
            census[cat] = census.get(cat, 0) + 1

    return census


