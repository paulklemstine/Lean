"""Visualization: apparition support as a principal arithmetic progression.

Draws, for several primes p, the indices n at which p | F(n) (Fibonacci) and
p | 2^n - 1 (Mersenne), highlighting that they form a single arithmetic
progression generated by the entry point. Requires matplotlib.
"""
from __future__ import annotations
import matplotlib.pyplot as plt


def fib(n: int) -> int:
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def main() -> None:
    primes = [3, 5, 7, 11, 13]
    N = 40
    fig, axes = plt.subplots(2, 1, figsize=(11, 6), sharex=True)

    for row, (title, divides) in enumerate([
        ("Fibonacci  F(n):  positions where p | F(n)", lambda p, n: fib(n) % p == 0),
        ("Mersenne  2^n - 1:  positions where p | 2^n - 1",
         lambda p, n: (2 ** n - 1) % p == 0),
    ]):
        ax = axes[row]
        for i, p in enumerate(primes):
            xs = [n for n in range(1, N + 1) if divides(p, n)]
            ax.scatter(xs, [i] * len(xs), s=60)
            if xs:
                ax.axhline(i, color="gray", lw=0.3, alpha=0.5)
                ax.annotate(f"e={xs[0]}", (xs[0], i), textcoords="offset points",
                            xytext=(0, 8), fontsize=8)
        ax.set_yticks(range(len(primes)))
        ax.set_yticklabels([f"p={p}" for p in primes])
        ax.set_title(title)
        ax.set_xlim(0, N + 1)
    axes[-1].set_xlabel("index n")
    fig.suptitle("Apparition support is a principal progression "
                 "(equally spaced by the entry point)")
    fig.tight_layout()
    fig.savefig("apparition_support.png", dpi=140)
    print("saved apparition_support.png")


if __name__ == "__main__":
    main()
