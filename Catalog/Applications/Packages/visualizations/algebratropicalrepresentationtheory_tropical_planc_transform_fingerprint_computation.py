    # Quick self-test
    x0 = TropPoly.gen(0)
    x1 = TropPoly.gen(1)
    
    # p = x0 ⊕ (x0 ⊙ x1)
    p = TropPoly.tadd(x0, TropPoly.tmul(x0, x1))
    
    # Character with x0 -> 3, x1 -> 5
    chi = TropicalCharacter({0: 3.0, 1: 5.0})
    
    # χ(p) = min(3, 3+5) = min(3, 8) = 3
    result = chi(p)
    print(f"χ({p}) = {result}")  # Should be 3.0
    assert result == 3.0
    
    # Monomials of p: [[0], [0, 1]]
    mons = p.to_monomials()
    print(f"Monomials of {p}: {mons}")
    assert mons == [[0], [0, 1]]
    
    # Lower envelope
    env = lower_envelope_at(mons, {0: 3.0, 1: 5.0})
    print(f"Lower envelope at (3, 5): {env}")  # Should be 3.0
    assert env == 3.0
    
    # Fingerprint
    spectrum = grid_spectrum(2, [-1, 0, 1, 2])
    fp = spectrum.transform_fingerprint(p)
    print(f"Fingerprint ({len(fp)} entries): {fp[:5]}...")
    
    # Equality check
    q = TropPoly.tadd(x0, TropPoly.tmul(x0, x1))  # same as p
    r = TropPoly.tmul(x0, x1)  # different from p
    
    print(f"p == q via fingerprint: {spectrum.decide_equality(p, q)}")
    print(f"p == r via fingerprint: {spectrum.decide_equality(p, r)}")
    
    print("\nAll self-tests passed!")
