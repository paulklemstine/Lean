"""
Tropical Plancherel Reconstruction: Core Algorithms

Implements the tropical spherical transform, fingerprint computation,
equality decision, and lower-envelope reconstruction for commutative
idempotent semirings.

All algorithms operate over the min-plus tropical semiring:
  - Addition = min
  - Multiplication = +
  - Zero = +∞
  - One = 0
"""

from __future__ import annotations
import math
from typing import List, Tuple, Callable, Optional, Dict
from dataclasses import dataclass
from enum import Enum, auto


# ──────────────────────────────────────────────────────
# Tropical Semiring
# ──────────────────────────────────────────────────────

INF = float('inf')

def trop_add(a: float, b: float) -> float:
    """Tropical addition: min(a, b)."""
    return min(a, b)

def trop_mul(a: float, b: float) -> float:
    """Tropical multiplication: a + b."""
    return a + b

def trop_zero() -> float:
    """Tropical additive identity: +∞."""
    return INF

def trop_one() -> float:
    """Tropical multiplicative identity: 0."""
    return 0.0


# ──────────────────────────────────────────────────────
# Tropical Polynomial Expressions
# ──────────────────────────────────────────────────────

class PolyType(Enum):
    GEN = auto()
    ONE = auto()
    TADD = auto()
    TMUL = auto()

@dataclass
class TropPoly:
    """A tropical polynomial expression over generators.
    
    Represents elements of a free idempotent semiring built from:
    - Generators: Gen(i)
    - Unit: One
    - Tropical addition (min): TAdd(p, q)
    - Tropical multiplication (+): TMul(p, q)
    """
    kind: PolyType
    gen_index: Optional[int] = None
    left: Optional['TropPoly'] = None
    right: Optional['TropPoly'] = None
    
    @staticmethod
    def gen(i: int) -> 'TropPoly':
        return TropPoly(PolyType.GEN, gen_index=i)
    
    @staticmethod
    def one() -> 'TropPoly':
        return TropPoly(PolyType.ONE)
    
    @staticmethod
    def tadd(p: 'TropPoly', q: 'TropPoly') -> 'TropPoly':
        return TropPoly(PolyType.TADD, left=p, right=q)
    
    @staticmethod
    def tmul(p: 'TropPoly', q: 'TropPoly') -> 'TropPoly':
        return TropPoly(PolyType.TMUL, left=p, right=q)
    
    def eval_tropical(self, vals: Dict[int, float]) -> float:
        """Evaluate tropically given generator values.
        
        Args:
            vals: Map from generator index to tropical value.
        
        Returns:
            Tropical evaluation result.
        """
        if self.kind == PolyType.GEN:
            return vals.get(self.gen_index, INF)
        elif self.kind == PolyType.ONE:
            return 0.0
        elif self.kind == PolyType.TADD:
            return trop_add(self.left.eval_tropical(vals), 
                          self.right.eval_tropical(vals))
        elif self.kind == PolyType.TMUL:
            return trop_mul(self.left.eval_tropical(vals), 
                          self.right.eval_tropical(vals))
    
    def to_monomials(self) -> List[List[int]]:
        """Expand into a list of monomials (lists of generator indices).
        
        Each monomial is a list of generator indices whose tropical product
        (sum of values) gives one term. The polynomial's value is the
        tropical sum (min) over all monomials.
        
        Returns:
            List of monomials, where each monomial is a list of generator indices.
        """
        if self.kind == PolyType.GEN:
            return [[self.gen_index]]
        elif self.kind == PolyType.ONE:
            return [[]]  # empty product = 1
        elif self.kind == PolyType.TADD:
            return self.left.to_monomials() + self.right.to_monomials()
        elif self.kind == PolyType.TMUL:
            left_mons = self.left.to_monomials()
            right_mons = self.right.to_monomials()
            return [ml + mr for ml in left_mons for mr in right_mons]
    
    def __repr__(self) -> str:
        if self.kind == PolyType.GEN:
            return f"x{self.gen_index}"
        elif self.kind == PolyType.ONE:
            return "1"
        elif self.kind == PolyType.TADD:
            return f"({self.left} ⊕ {self.right})"
        elif self.kind == PolyType.TMUL:
            return f"({self.left} ⊙ {self.right})"


# ──────────────────────────────────────────────────────
# Tropical Characters
# ──────────────────────────────────────────────────────

@dataclass
class TropicalCharacter:
    """A tropical character defined by generator values.
    
    For a semiring generated by {g₁, ..., gₙ}, a tropical character
    is determined by the values χ(gᵢ) = vals[i].
    
    The character extends to arbitrary tropical polynomial expressions
    via the structural recursion:
      χ(a ⊕ b) = min(χ(a), χ(b))
      χ(a ⊙ b) = χ(a) + χ(b)
      χ(1) = 0
    """
    gen_values: Dict[int, float]
    
    def __call__(self, poly: TropPoly) -> float:
        """Evaluate the character on a tropical polynomial."""
        return poly.eval_tropical(self.gen_values)
    
    def fingerprint_entry(self, poly: TropPoly) -> float:
        """Compute the fingerprint entry for this character on a polynomial."""
        return self(poly)


# ──────────────────────────────────────────────────────
# Finite Extremal Spectrum
# ──────────────────────────────────────────────────────

@dataclass
class FiniteExtremalSpectrum:
    """A finite collection of tropical characters forming a spectrum.
    
    Attributes:
        characters: List of tropical characters.
    """
    characters: List[TropicalCharacter]
    
    @property
    def size(self) -> int:
        return len(self.characters)
    
    def transform_fingerprint(self, poly: TropPoly) -> List[float]:
        """Compute the transform fingerprint of a polynomial.
        
        The fingerprint is the vector (χ₁(p), χ₂(p), ..., χₙ(p))
        where χᵢ are the characters in the spectrum.
        
        Args:
            poly: Tropical polynomial to fingerprint.
            
        Returns:
            List of tropical values, one per character.
        """
        return [chi(poly) for chi in self.characters]
    
    def decide_equality(self, p: TropPoly, q: TropPoly) -> bool:
        """Decide equality of two polynomials via fingerprint comparison.
        
        Sound and complete when the spectrum is complete.
        
        Args:
            p, q: Tropical polynomials to compare.
            
        Returns:
            True iff fingerprints are identical.
        """
        fp_p = self.transform_fingerprint(p)
        fp_q = self.transform_fingerprint(q)
        return fp_p == fp_q


# ──────────────────────────────────────────────────────
# Lower Envelope Computation
# ──────────────────────────────────────────────────────

def lower_envelope_at(monomials: List[List[int]], 
                       gen_values: Dict[int, float]) -> float:
    """Compute the lower envelope value at given generator coordinates.
    
    For a tropical polynomial expanded into monomials, the value at
    generator coordinates (s₁, ..., sₙ) is:
      min over monomials m of (∑_{i ∈ m} sᵢ)
    
    This is the piecewise-linear lower envelope function.
    
    Args:
        monomials: List of monomials, each a list of generator indices.
        gen_values: Map from generator index to value.
        
    Returns:
        The lower envelope value (minimum over affine forms).
    """
    if not monomials:
        return INF
    
    values = []
    for mon in monomials:
        if not mon:
            values.append(0.0)  # empty monomial = 1, evaluates to 0
        else:
            val = sum(gen_values.get(i, INF) for i in mon)
            values.append(val)
    
    return min(values)


def monomial_affine_form(monomial: List[int], 
                          num_generators: int) -> List[int]:
    """Convert a monomial to an affine coefficient vector.
    
    The monomial [i₁, i₂, ..., iₖ] corresponds to the affine form
    s_{i₁} + s_{i₂} + ... + s_{iₖ}, represented as the coefficient
    vector (a₁, ..., aₙ) where aⱼ = #{j appears in monomial}.
    
    Args:
        monomial: List of generator indices.
        num_generators: Total number of generators.
        
    Returns:
        Coefficient vector of length num_generators.
    """
    coeffs = [0] * num_generators
    for i in monomial:
        if 0 <= i < num_generators:
            coeffs[i] += 1
    return coeffs


# ──────────────────────────────────────────────────────
# Grid-based Spectrum Construction
# ──────────────────────────────────────────────────────

def grid_spectrum(num_generators: int, 
                   grid_values: List[float]) -> FiniteExtremalSpectrum:
    """Construct a finite spectrum by gridding generator value space.
    
    Creates one character for each point on a grid in generator-value space.
    For 2 generators with grid_values = [-2, -1, 0, 1, 2], this creates
    25 characters.
    
    Args:
        num_generators: Number of generators.
        grid_values: Values to assign to each generator coordinate.
        
    Returns:
        FiniteExtremalSpectrum with grid-based characters.
    """
    import itertools
    
    characters = []
    for combo in itertools.product(grid_values, repeat=num_generators):
        gen_vals = {i: v for i, v in enumerate(combo)}
        characters.append(TropicalCharacter(gen_vals))
    
    return FiniteExtremalSpectrum(characters)


