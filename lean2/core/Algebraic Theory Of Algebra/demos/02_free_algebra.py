class Term:
    """A term in an algebraic signature."""

    def __init__(self, symbol, children=None):
        self.symbol = symbol          # operation symbol or variable name
        self.children = children or []  # sub-terms (empty for variables)

    @property
    def is_variable(self):
        return len(self.children) == 0

    @property
    def depth(self):
        if self.is_variable:
            return 0
        return 1 + max(c.depth for c in self.children)

    @property
    def size(self):
        if self.is_variable:
            return 1
        return 1 + sum(c.size for c in self.children)

    def __repr__(self):
        if self.is_variable:
            return self.symbol
        if len(self.children) == 2:
            return f"({self.children[0]}·{self.children[1]})"
        return f"{self.symbol}({','.join(str(c) for c in self.children)})"

    def __eq__(self, other):
        return (self.symbol == other.symbol and
                len(self.children) == len(other.children) and
                all(a == b for a, b in zip(self.children, other.children)))

    def __hash__(self):
        return hash((self.symbol, tuple(hash(c) for c in self.children)))

    def substitute(self, mapping):
        """Apply a substitution mapping variables to terms."""
        if self.is_variable:
            return mapping.get(self.symbol, self)
        return Term(self.symbol, [c.substitute(mapping) for c in self.children])


def generate_terms(variables, op_symbol, max_depth):
    """Generate all terms up to a given depth."""
    terms_by_depth = {0: [Term(v) for v in variables]}

    for d in range(1, max_depth + 1):
        new_terms = []
        # All terms of depth exactly d: op applied to terms of depth < d
        # where at least one argument has depth d-1
        prev_terms = []
        for dd in range(d):
            prev_terms.extend(terms_by_depth[dd])

        for t1 in prev_terms:
            for t2 in prev_terms:
                if t1.depth == d - 1 or t2.depth == d - 1:
                    new_terms.append(Term(op_symbol, [t1, t2]))

        terms_by_depth[d] = new_terms

    all_terms = []
    for d in range(max_depth + 1):
        all_terms.extend(terms_by_depth[d])
    return all_terms


