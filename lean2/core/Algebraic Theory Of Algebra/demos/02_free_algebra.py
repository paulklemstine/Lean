# Part 2: Equational Reasoning — Quotienting by Axioms
# ============================================================

class UnionFind:
    """Union-Find data structure for computing equivalence classes."""

    def __init__(self, elements):
        self.parent = {e: e for e in elements}
        self.rank = {e: 0 for e in elements}

    def find(self, x):
        if self.parent[x] != x:
            self.parent[x] = self.find(self.parent[x])
        return self.parent[x]

    def union(self, x, y):
        rx, ry = self.find(x), self.find(y)
        if rx == ry:
            return False
        if self.rank[rx] < self.rank[ry]:
            rx, ry = ry, rx
        self.parent[ry] = rx
        if self.rank[rx] == self.rank[ry]:
            self.rank[rx] += 1
        return True

    def classes(self):
        result = defaultdict(list)
        for e in self.parent:
            result[self.find(e)].append(e)
        return dict(result)


def build_free_commutative_semigroup(generators, max_depth=2):
    """
    Build the free commutative semigroup on the given generators.

    This is T(Σ,X)/≡ where ≡ is generated by:
      - Associativity: (x·y)·z = x·(y·z)
      - Commutativity: x·y = y·x
    """
    # Generate all terms
    terms = generate_terms(generators, "·", max_depth)
    term_list = list(set(terms))  # deduplicate

    print(f"\n  Raw terms (up to depth {max_depth}): {len(term_list)}")

    # Build equivalence relation using union-find
    uf = UnionFind(range(len(term_list)))

    # Apply axioms: for all substitutions, identify equal terms
    def normalize(term):
        """
        Normalize a term in a commutative semigroup.
        The normal form is a sorted multiset of generators.
        """
        if term.is_variable:
            return [term.symbol]
        left_norm = normalize(term.children[0])
        right_norm = normalize(term.children[1])
        return sorted(left_norm + right_norm)

    # Group terms by their normal form
    normal_forms = defaultdict(list)
    for i, t in enumerate(term_list):
        nf = tuple(normalize(t))
        normal_forms[nf].append(i)

    # Union terms with the same normal form
    for nf, indices in normal_forms.items():
        for idx in indices[1:]:
            uf.union(indices[0], idx)

    classes = uf.classes()
    print(f"  Equivalence classes (= elements of free algebra): {len(classes)}")
    print(f"\n  Elements of the free commutative semigroup on {{{', '.join(generators)}}}:")

    for rep, members in sorted(classes.items(), key=lambda x: len(x[1])):
        member_terms = [term_list[i] for i in members]
        # Pick shortest representative
        shortest = min(member_terms, key=lambda t: t.size)
        nf = normalize(shortest)
        multiset_repr = " + ".join(nf)
        print(f"    [{multiset_repr}] = {{{', '.join(str(t) for t in member_terms[:4])}"
              f"{'...' if len(member_terms) > 4 else ''}}}")

    return classes, term_list


def build_free_semigroup(generators, max_depth=2):
    """
    Build the free semigroup on the given generators.
    Axiom: associativity only.
    Elements are finite non-empty strings over the generators.
    """
    terms = generate_terms(generators, "·", max_depth)
    term_list = list(set(terms))

    print(f"\n  Raw terms (up to depth {max_depth}): {len(term_list)}")

    def flatten(term):
        """Flatten to a string (free semigroup = non-empty words)."""
        if term.is_variable:
            return term.symbol
        return flatten(term.children[0]) + flatten(term.children[1])

    # Group by flattened form
    uf = UnionFind(range(len(term_list)))
    by_word = defaultdict(list)
    for i, t in enumerate(term_list):
        by_word[flatten(t)].append(i)

    for word, indices in by_word.items():
        for idx in indices[1:]:
            uf.union(indices[0], idx)

    classes = uf.classes()
    print(f"  Equivalence classes: {len(classes)}")
    print(f"\n  Elements of the free semigroup on {{{', '.join(generators)}}}:")

    for rep, members in sorted(classes.items(), key=lambda x: len(x[1])):
        member_terms = [term_list[i] for i in members]
        shortest = min(member_terms, key=lambda t: t.size)
        word = flatten(shortest)
        print(f"    [{word}] ← {len(member_terms)} equivalent term(s)")

    return classes, term_list


