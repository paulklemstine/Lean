    for q in [5, 7]:
        result = certified_expander_search(q)
        print(f"\nq = {q}: |GL₂| = {result['gl2_order']}")
        print(f"  Found {len(result['pairs'])} certified pairs")
        print(f"  Min spectral gap: {result['min_gap']:.6f}")
        print(f"  Min q·γ: {result['min_q_gap']:.6f}")
