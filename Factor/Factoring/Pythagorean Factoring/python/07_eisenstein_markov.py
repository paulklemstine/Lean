def experiment_markov():
    """
    The Markov equation x² + y² + z² = 3xyz has infinitely many solutions
    organized in a TERNARY TREE, just like Pythagorean triples!
    
    Root: (1, 1, 1)
    
    Mutations: from (x, y, z), the three children are obtained by 
    replacing one variable: x → 3yz - x (and permuting to maintain order).
    
    The Markov numbers (values appearing in Markov triples) are:
    1, 2, 5, 13, 29, 34, 89, 169, 194, 233, 433, 610, ...
    
    CONJECTURE (Markov Uniqueness): Each Markov number appears in exactly
    one Markov triple (up to permutation). STILL OPEN!
    
    NEW HYPOTHESIS: The Markov tree and the Berggren tree are 
    "dual" in a precise sense — the Markov tree encodes ADDITIVE 
    structure while the Berggren tree encodes MULTIPLICATIVE structure.
    """
    print("\n" + "=" * 80)
    print("THE MARKOV TREE: x² + y² + z² = 3xyz")
    print("=" * 80)
    
    def markov_mutation(triple, index):
        """Replace triple[index] with 3*y*z - x (where x = triple[index])."""
        x, y, z = triple
        if index == 0:
            new_x = 3*y*z - x
            return tuple(sorted([new_x, y, z]))
        elif index == 1:
            new_y = 3*x*z - y
            return tuple(sorted([x, new_y, z]))
        else:
            new_z = 3*x*y - z
            return tuple(sorted([x, y, new_z]))
    
    def verify_markov(triple):
        x, y, z = triple
        return x*x + y*y + z*z == 3*x*y*z
    
    # Generate Markov tree BFS
    root = (1, 1, 1)
    seen = {root}
    queue = [root]
    all_triples = [root]
    
    for _ in range(6):  # 6 levels
        next_queue = []
        for triple in queue:
            for i in range(3):
                child = markov_mutation(triple, i)
                if child not in seen and all(c > 0 for c in child):
                    seen.add(child)
                    all_triples.append(child)
                    next_queue.append(child)
        queue = next_queue
    
    print(f"\nMarkov triples (first {min(len(all_triples), 25)}):")
    for t in all_triples[:25]:
        x, y, z = t
        verified = verify_markov(t)
        print(f"  ({x:6d},{y:6d},{z:6d})  {x}²+{y}²+{z}² = {x*x+y*y+z*z}, 3×{x}×{y}×{z} = {3*x*y*z}  {'✓' if verified else '✗'}")
    
    # Markov numbers
    markov_numbers = sorted(set(v for t in all_triples for v in t))
    print(f"\n  Markov numbers: {markov_numbers[:20]}")
    
    # Connection to Pythagorean triples?
    print("\n  Seeking connections between Markov and Pythagorean numbers...")
    pyth_hypotenuses = set()
    for a in range(1, 100):
        for b in range(a+1, 200):
            c_sq = a*a + b*b
            c = int(math.isqrt(c_sq))
            if c*c == c_sq:
                pyth_hypotenuses.add(c)
    
    overlap = set(markov_numbers[:30]) & pyth_hypotenuses
    print(f"  Markov numbers that are also Pythagorean hypotenuses: {sorted(overlap)}")
    
    # Check if Markov numbers have special divisibility properties
    print("\n  Markov numbers modulo small primes:")
    for p in [3, 5, 7, 11, 13]:
        residues = sorted(set(m % p for m in markov_numbers[:30]))
        print(f"    mod {p:2d}: {residues}")
    
    # Key structural comparison
    print("\n  STRUCTURAL COMPARISON:")
    print("  ┌──────────────────┬────────────────────┬────────────────────┐")
    print("  │ Property         │ Berggren Tree      │ Markov Tree        │")
    print("  ├──────────────────┼────────────────────┼────────────────────┤")
    print("  │ Equation         │ a²+b²=c²           │ x²+y²+z²=3xyz     │")
    print("  │ Root             │ (3,4,5)            │ (1,1,1)            │")
    print("  │ Branching        │ 3 matrices         │ 3 mutations        │")
    print("  │ Preserved form   │ a²+b²-c²=0         │ x²+y²+z²-3xyz=0   │")
    print("  │ Uniqueness       │ Yes (proven)       │ Open conjecture!   │")
    print("  │ Group            │ SO(2,1;Z)          │ Aut(F₂)            │")
    print("  │ Connection       │ Factoring integers │ Geodesics on torus │")
    print("  └──────────────────┴────────────────────┴────────────────────┘")


