def experiment_eisenstein():
    """
    The Eisenstein integers Z[ω] = {a + bω : a, b ∈ Z} where ω = e^{2πi/3}.
    
    The norm is N(a + bω) = a² + ab + b² = a² - a(-b) + (-b)² 
    (related to the hexagonal lattice).
    
    A "Loeschian triple" is (a, b, c) with a² + ab + b² = c².
    
    QUESTION: Is there a "Berggren-like" tree for Loeschian triples?
    If so, does it carry factoring information?
    """
    print("=" * 80)
    print("THE EISENSTEIN TREE: Triples from the Hexagonal Lattice")
    print("=" * 80)
    
    def loeschian_norm(a, b):
        """Compute a² + ab + b²."""
        return a*a + a*b + b*b
    
    def find_loeschian_triples(c_max):
        """Find all triples (a, b, c) with a² + ab + b² = c², c ≤ c_max."""
        triples = []
        for c in range(1, c_max + 1):
            c_sq = c * c
            for a in range(0, c + 1):
                for b in range(a, c + 1):
                    if loeschian_norm(a, b) == c_sq:
                        if a > 0 and b > 0:
                            triples.append((a, b, c))
        return triples
    
    print("\nLoeschian triples (a² + ab + b² = c²) with c ≤ 30:")
    triples = find_loeschian_triples(30)
    
    print(f"{'(a, b, c)':>15s} | {'a²+ab+b²':>10s} | {'c²':>10s} | {'gcd(a,b)':>8s} | {'primitive':>10s}")
    print("-" * 60)
    
    primitive_triples = []
    for a, b, c in triples:
        g = math.gcd(math.gcd(a, b), c)
        is_prim = (g == 1)
        if is_prim:
            primitive_triples.append((a, b, c))
        print(f"  ({a:3d},{b:3d},{c:3d}) | {loeschian_norm(a,b):>10d} | {c*c:>10d} | {g:>8d} | {'✓' if is_prim else ''}")
    
    print(f"\n  Found {len(triples)} total triples, {len(primitive_triples)} primitive")
    
    # Try to find tree structure
    print("\n  Looking for tree-generating matrices...")
    print("  The quadratic form a² + ab + b² is preserved by rotations of 60°.")
    print("  In matrix form: Q = [[1, 1/2], [1/2, 1]] and M^T Q M = Q")
    
    # The symmetry group of a² + ab + b² includes:
    # R = [[0, -1], [1, 1]] (rotation by 60° in the hex lattice)
    # S = [[1, 0], [1, -1]] (reflection)
    
    # For a 3D generalization (a² + ab + b² = c²), we need 3×3 matrices
    # preserving the form a² + ab + b² - c² = 0
    
    # This is the quadratic form with matrix Q3 = [[1, 1/2, 0], [1/2, 1, 0], [0, 0, -1]]
    
    # NEW: Search for integer matrices M with M^T Q3 M = Q3
    print("\n  Searching for integer isometries of a² + ab + b² - c² = 0...")
    
    # We can parameterize: a = m² - n², b = 2mn + n², c = m² + mn + n²
    # (Eisenstein analogue of the Pythagorean parametrization)
    # Verify:
    print("\n  Eisenstein parametrization: a = m²-n², b = 2mn+n², c = m²+mn+n²")
    for m in range(1, 8):
        for n in range(1, m+1):
            if math.gcd(m, n) != 1:
                continue
            a = m*m - n*n
            b = 2*m*n + n*n
            c = m*m + m*n + n*n
            if a > 0 and b > 0:
                check = a*a + a*b + b*b
                print(f"    (m,n)=({m},{n}): (a,b,c)=({a},{b},{c}), a²+ab+b²={check}, c²={c*c}, match={'✓' if check==c*c else '✗'}")


