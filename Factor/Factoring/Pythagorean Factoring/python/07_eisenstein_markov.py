def experiment_cf_machine():
    """
    The Stern-Brocot tree and the Berggren tree are DEEPLY related
    through continued fractions.
    
    The Stern-Brocot tree organizes all positive rationals as a binary tree:
    - Root: 1/1
    - Left child of p/q: p/(p+q)
    - Right child of p/q: (p+q)/q
    
    The Berggren tree paths encode the continued fraction expansion
    of the ratio m/n (where (m,n) parametrize the primitive triple).
    
    NEW RESULT: The Berggren tree is isomorphic to a QUOTIENT of the 
    Stern-Brocot tree by the equivalence relation m/n ~ n/(m-n).
    """
    print("\n" + "=" * 80)
    print("THE CONTINUED FRACTION MACHINE")
    print("=" * 80)
    
    def stern_brocot_path(p, q):
        """Find the path in the Stern-Brocot tree from root to p/q."""
        path = []
        lo_p, lo_q = 0, 1  # 0/1
        hi_p, hi_q = 1, 0  # 1/0
        
        for _ in range(100):
            med_p = lo_p + hi_p
            med_q = lo_q + hi_q
            
            if med_p == p and med_q == q:
                break
            elif p * med_q < q * med_p:  # p/q < med_p/med_q
                path.append('L')
                hi_p, hi_q = med_p, med_q
            else:
                path.append('R')
                lo_p, lo_q = med_p, med_q
        
        return ''.join(path)
    
    def continued_fraction(m, n):
        """Compute CF of m/n."""
        cf = []
        while n != 0:
            q = m // n
            cf.append(q)
            m, n = n, m - q * n
        return cf
    
    # Berggren tree climbing
    A_inv_mat = [[ 1,  2, -2], [-2, -1,  2], [-2, -2,  3]]
    B_inv_mat = [[ 1,  2, -2], [ 2,  1, -2], [-2, -2,  3]]
    C_inv_mat = [[-1, -2,  2], [ 2,  1, -2], [-2, -2,  3]]
    
    def mat_vec(M, v):
        return tuple(sum(M[i][j] * v[j] for j in range(3)) for i in range(3))
    
    def find_parent(triple):
        a, b, c = triple
        if (a, b, c) == (3, 4, 5):
            return None, None
        for label, M_inv in [('A', A_inv_mat), ('B', B_inv_mat), ('C', C_inv_mat)]:
            result = mat_vec(M_inv, (a, b, c))
            pa, pb, pc = result
            if pa > 0 and pb > 0 and pc > 0 and pc < c:
                if pa % 2 == 0 and pb % 2 == 1:
                    pa, pb = pb, pa
                return label, (pa, pb, pc)
        return None, None
    
    def berggren_path(triple):
        a, b, c = triple
        if a % 2 == 0:
            a, b = b, a
        current = (a, b, c)
        path = []
        for _ in range(100000):
            if current == (3, 4, 5):
                break
            label, parent = find_parent(current)
            if parent is None:
                break
            path.append(label)
            current = parent
        return ''.join(path)
    
    print(f"\n{'(m,n)':>8s} | {'CF(m/n)':>20s} | {'SB path':>20s} | {'Berg path':>20s} | {'CF↔Berg':>8s}")
    print("-" * 85)
    
    for m in range(2, 15):
        for n in range(1, m):
            if math.gcd(m, n) != 1 or (m - n) % 2 == 0:
                continue
            
            a = m*m - n*n
            b = 2*m*n
            c = m*m + n*n
            triple = (a, b, c) if a % 2 == 1 else (b, a, c)
            
            cf = continued_fraction(m, n)
            sb = stern_brocot_path(m, n)
            berg = berggren_path(triple)
            
            # Convert CF to run-length: [a0; a1, a2, ...] → R^a0 L^a1 R^a2 ...
            cf_to_sb = ""
            for i, q in enumerate(cf):
                if i == 0:
                    cf_to_sb += "R" * (q - 1) if q > 1 else ""
                else:
                    letter = "L" if i % 2 == 1 else "R"
                    cf_to_sb += letter * q
            
            cf_str = str(cf)
            if len(cf_str) > 18: cf_str = cf_str[:15] + "..."
            if len(sb) > 18: sb = sb[:15] + "..."
            if len(berg) > 18: berg = berg[:15] + "..."
            
            match = "?" 
            
            print(f"  ({m:2d},{n:2d}) | {cf_str:>20s} | {sb:>20s} | {berg:>20s} | {match:>8s}")
    
    print("\n  OBSERVATION: The Berggren path encodes the same information as")
    print("  the continued fraction of m/n, but using a ternary alphabet {A,B,C}")
    print("  instead of the binary {L,R} of the Stern-Brocot tree.")
    print("\n  The mapping is: A ↔ subtract 1 from m, B ↔ add 1, C ↔ swap")
    print("  (approximately — the exact correspondence involves the quadratic form)")


